// 每行 = JD 硬性要求原文 × 我方证据原文,AI 只做连线,零自创文案。
//
// 三态(2026-08-31 定稿):
//   有证据 —— 简历里有对应事实,证据行给原文拼接;
//   未提及 —— 简历里查无此词/核不动。不是「不满足」:没写 ≠ 不会,灰圈不打叉;
//   不满足 —— 只有经验/学历这类硬字段的确定性比较才配得上,灰叉。
//
// 条目来源(2026-08-31 定稿):JD 写明的硬性要求 —— 硬字段(经验/学历)+ JD 必须项,
// 有几条列几条,不设人为上限;加分项不进表,城市/薪资在进市场前已过滤、不进表。
//
// 分从行来(2026-08-31 定稿):适配分由这些行加权算出(硬字段权重 2、必须项 1),
// 数字与行永不矛盾;任一硬字段不满足则封顶。求职端所有分数展示点统一走 算适配分。
//
// 招聘端仍是 2026-08-26 定稿的「圆点行式」两态卡,本文件的招聘侧生成器保持原口径。

