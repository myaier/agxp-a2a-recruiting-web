// 匹配对齐(2026-08-26 用户定稿「甲-圆点行式」)——匹配度分析的新数据形态:
// 每行 = 对方要求原文 × 我方证据原文,AI 只做连线,零自创文案。
// 未命中行置顶;证据一律由既有数据字段裁剪/拼接,不写解释句。
//
// 两端各一个生成器:求职端(JD 要求 × 我的简历),招聘端(岗位硬性条件 × 候选简历档)。
// 旗舰岗位可在 手工对齐表 里放语义级连线(JD 原文整句),没有手工条目的走字段级生成。

import type { 简历经历段, 简历教育段 } from './类型';
import type { 匿名简历档 } from './企业端模拟数据';

export interface 对齐行 {
  /** 对方的要求(原文或原文裁剪) */
  要求: string;
  /** 我方命中的证据(原文/字段拼接);null = 未命中 */
  证据: string | null;
}

/** 学历排序:核对「X及以上」用 */
function 学历阶(值: string): number {
  return 值.includes('博士') ? 3 : 值.includes('硕士') ? 2 : 值.includes('本科') ? 1 : 0;
}

/** 未命中置顶(用户定稿版式:差距先入眼),组内保持原顺序 */
function 未命中置顶(行们: 对齐行[]): 对齐行[] {
  return [...行们.filter((行) => !行.证据), ...行们.filter((行) => 行.证据)];
}

/** 旗舰岗位的语义级连线:JD 原文整句 × 简历原文裁剪(2026-08-26 效果图定稿内容) */
const 手工对齐表: Record<string, 对齐行[]> = {
  'M-11': [
    { 要求: '订单簿、撮合、清算的基本模型', 证据: null },
    { 要求: '5 年以上后端经验，Go 或 C++ 主栈', 证据: '字节跳动 · 交易中台 · Go · 9 年' },
    { 要求: '做过高并发低延迟系统', 证据: '峰值 32 万 QPS 全链路治理' },
  ],
};

/** 求职端:JD 的要求 × 我的简历。证据 = 简历字段拼接(公司·职位 / 学校·学历 / 命中技能) */
export function 求职侧对齐行(
  源: { 编号?: string; 经验要求?: string; 学历要求?: string; 技能要求?: string[] },
  简历: { 经历: 简历经历段[]; 教育: 简历教育段[]; 技能: string[] }
): 对齐行[] {
  if (源.编号 && 手工对齐表[源.编号]) return 手工对齐表[源.编号];

  const 行们: 对齐行[] = [];
  if (源.经验要求) {
    const 需 = parseInt(源.经验要求, 10);
    // 与原 硬性行们 同一口径:演示简历 9 年
    const 过 = !Number.isFinite(需) || 需 <= 9;
    const 首段 = (简历.经历 ?? [])[0];
    行们.push({
      要求: `经验 ${源.经验要求}`,
      证据: 过 && 首段 ? `${首段.公司} · ${首段.职位}` : null,
    });
  }
  if (源.学历要求) {
    const 过 = 学历阶(源.学历要求) <= 2;
    const 首段 = (简历.教育 ?? [])[0];
    行们.push({
      要求: `学历 ${源.学历要求}`,
      证据: 过 && 首段 ? `${首段.学校} · ${首段.学历}` : null,
    });
  }
  for (const 技 of 源.技能要求 ?? []) {
    const 命中 = (简历.技能 ?? []).find((有) => 有.includes(技) || 技.includes(有));
    行们.push({ 要求: 技, 证据: 命中 ?? null });
  }
  return 未命中置顶(行们);
}

/** 招聘端:岗位硬性条件 × 候选简历档。逐条按内容认类(经验/学历/技能词) */
export function 招聘侧对齐行(硬性条件: string[], 档: 匿名简历档): 对齐行[] {
  const 行们: 对齐行[] = 硬性条件.map((条) => {
    if (/经验|年以上/.test(条)) {
      const 需 = parseInt(条, 10);
      const 有 = parseInt(档.经验, 10);
      const 过 = !Number.isFinite(需) || (Number.isFinite(有) && 需 <= 有);
      const 首段 = (档.经历 ?? [])[0];
      return { 要求: 条, 证据: 过 && 首段 ? `${首段.公司} · ${首段.职位} · ${档.经验}` : null };
    }
    if (/及以上/.test(条) && 学历阶(条) > 0) {
      const 过 = 学历阶(档.学历) >= 学历阶(条);
      return { 要求: 条, 证据: 过 ? `${档.教育行} · ${档.学历}` : null };
    }
    const 命中 = (档.技能 ?? []).find((有) => 有.includes(条) || 条.includes(有));
    return { 要求: 条, 证据: 命中 ?? null };
  });
  return 未命中置顶(行们);
}
