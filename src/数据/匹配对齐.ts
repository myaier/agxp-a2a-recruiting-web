/**
 * Backend(P4) 核对输入:命中判定必须来自用户自己的真实事实,不许吃演示常量。
 * 不传 = Mock/演示路径,保持原「演示简历 9 年 / 硕士」口径逐字不变。
 */
export interface 求职侧核对 {
  /** 折算工作年限(年);null = 开始工作年 缺失,核不动 → 那一行记未提及 */
  工作年限: number | null;
}

/** 开始工作年 → 折算工作年限;空/非法一律 null（核不动,绝不当 0 或演示常量用） */
export function 折算工作年限(开始工作年: string): number | null {
  const 年 = Number(开始工作年);
  if (!开始工作年 || !Number.isFinite(年) || 年 <= 0) return null;
  return Math.max(0, new Date().getFullYear() - 年);
}

/** 求职端:JD 的硬性要求 × 我的简历。硬字段行恒在前,必须项按 JD 原顺序,不做重排 */
export function 求职侧对齐行(
  源: { 编号?: string; 经验要求?: string; 学历要求?: string; 技能要求?: string[] },
  简历: { 经历: 简历经历段[]; 教育: 简历教育段[]; 技能: string[] },
  /** Backend 权威路径的核对事实;缺省(Mock/直聊会话调用方)走原演示口径 */
  核对?: 求职侧核对
): 对齐行[] {
  const 行们: 对齐行[] = [];
  if (源.经验要求) {
    const 需 = parseInt(源.经验要求, 10);
    const 首段 = (简历.经历 ?? [])[0];
    // Backend:门槛来自用户真实工作年限(要求无数字 = 「不限」,本来就没门槛);
    // 核不动(未填开始工作年)= 未提及 —— 绝不用演示常量替真人断言命中或不满足。
    // Mock:与原口径一致,演示简历 9 年。
    const 核不动 = 核对 !== undefined && 核对.工作年限 === null && Number.isFinite(需);
    const 过 = 核对
      ? !Number.isFinite(需) || (核对.工作年限 !== null && 需 <= 核对.工作年限)
      : !Number.isFinite(需) || 需 <= 9;
    行们.push({
      要求: `经验 ${源.经验要求}`,
      证据: 过 && 首段 ? `${首段.公司} · ${首段.职位}` : null,
      态: 过 && 首段 ? '有证据' : 核不动 || !首段 ? '未提及' : '不满足',
      类: '硬性',
    });
  }
  if (源.学历要求) {
    const 首段 = (简历.教育 ?? [])[0];
    // Backend:拿用户真实学历比(与招聘侧对齐行同一比法);Mock:演示简历 硕士
    const 过 = 核对
      ? 首段 !== undefined && 学历阶(首段.学历) >= 学历阶(源.学历要求)
      : 学历阶(源.学历要求) <= 2;
    行们.push({
      要求: `学历 ${源.学历要求}`,
      证据: 过 && 首段 ? `${首段.学校} · ${首段.学历}` : null,
      态: 过 && 首段 ? '有证据' : !首段 ? '未提及' : '不满足',
      类: '硬性',
    });
  }
  if (源.编号 && 手工对齐表[源.编号]) return [...行们, ...手工对齐表[源.编号]];
  for (const 技 of 源.技能要求 ?? []) {
    const 命中 = (简历.技能 ?? []).find((有) => 有.includes(技) || 技.includes(有));
    // 词表搜不到只能说明简历没写,不能说明不会 —— 永远是未提及,不是不满足
    行们.push({ 要求: 技, 证据: 命中 ?? null, 态: 命中 ? '有证据' : '未提及', 类: '必须' });
  }
  return 行们;
}

/** 分从行来:硬字段权重 2、必须项 1,分 = 有证据权重占比;任一硬字段不满足封顶 45。
    行为空(JD 没写任何硬性要求)回落调用方给的种子分 —— 没有行就没有可算的依据 */
export function 算适配分(行们: 对齐行[], 种子分: number): number {
  if (行们.length === 0) return 种子分;
  const 权 = (行: 对齐行) => (行.类 === '硬性' ? 2 : 1);
  const 总 = 行们.reduce((和, 行) => 和 + 权(行), 0);
  const 得 = 行们.filter((行) => 行.态 === '有证据').reduce((和, 行) => 和 + 权(行), 0);
  const 分 = Math.round((100 * 得) / 总);
  const 硬性不满足 = 行们.some((行) => 行.类 === '硬性' && 行.态 === '不满足');
  return 硬性不满足 ? Math.min(分, 45) : 分;
}

/** 分析段(2026-08-31 定稿):墨句讲强项、灰句讲缺口。旗舰岗位用手写句,其余按行模板拼 */
export function 求职匹配分析(
  行们: 对齐行[],
  源编号?: string
): { 墨句: string; 灰句: string } | null {
  if (行们.length === 0) return null;
  if (源编号 && 手工分析表[源编号]) return 手工分析表[源编号];

  const 硬性们 = 行们.filter((行) => 行.类 === '硬性');
  const 硬性全过 = 硬性们.length > 0 && 硬性们.every((行) => 行.态 === '有证据');
  const 命中必须 = 行们.filter((行) => 行.类 === '必须' && 行.态 === '有证据').map((行) => 行.要求);
  const 未提及们 = 行们.filter((行) => 行.态 === '未提及').map((行) => 行.要求);
  const 不满足们 = 行们.filter((行) => 行.态 === '不满足').map((行) => 行.要求);

  const 墨段们: string[] = [];
  if (硬性全过) 墨段们.push('经验与学历满足岗位要求');
  if (命中必须.length) 墨段们.push(`${命中必须.slice(0, 4).join('、')}均有简历证据`);
  const 墨句 = 墨段们.length ? `${墨段们.join('，')}。` : '';

  const 灰段们: string[] = [];
  if (不满足们.length) 灰段们.push(`${不满足们.join('、')}未达到岗位要求`);
  if (未提及们.length) 灰段们.push(`${未提及们.join('、')}简历未提及——在下方告诉代理即可补上`);
  const 灰句 = 灰段们.length ? `${灰段们.join('；')}。` : '';

  if (!墨句 && !灰句) return null;
  return { 墨句, 灰句 };
}

/** 招聘端:岗位硬性条件 × 候选简历档。逐条按内容认类(经验/学历/技能词) */
export function 招聘侧对齐行(硬性条件: string[], 档: 匿名简历档): 对齐行[] {
  const 行们: 对齐行[] = 硬性条件.map((条) => {
    if (/经验|年以上/.test(条)) {
      const 需 = parseInt(条, 10);
      const 有 = parseInt(档.经验, 10);
      const 过 = !Number.isFinite(需) || (Number.isFinite(有) && 需 <= 有);
      const 首段 = (档.经历 ?? [])[0];
      return {
        要求: 条,
        证据: 过 && 首段 ? `${首段.公司} · ${首段.职位} · ${档.经验}` : null,
        态: (过 && 首段 ? '有证据' : '不满足') as 对齐行['态'],
        类: '硬性' as const,
      };
    }
    if (/及以上/.test(条) && 学历阶(条) > 0) {
      const 过 = 学历阶(档.学历) >= 学历阶(条);
      return {
        要求: 条,
        证据: 过 ? `${档.教育行} · ${档.学历}` : null,
        态: (过 ? '有证据' : '不满足') as 对齐行['态'],
        类: '硬性' as const,
      };
    }
    const 命中 = (档.技能 ?? []).find((有) => 有.includes(条) || 条.includes(有));
    return {
      要求: 条,
      证据: 命中 ?? null,
      态: (命中 ? '有证据' : '未提及') as 对齐行['态'],
      类: '必须' as const,
    };
  });
  return 未命中置顶(行们);
}
