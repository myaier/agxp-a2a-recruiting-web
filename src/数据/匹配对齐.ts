export interface 对齐行 {
  /** 对方的要求(原文或原文裁剪) */
  要求: string;
  /** 我方命中的证据(原文/字段拼接);null = 无 */
  证据: string | null;
  /** 三态。旧两态调用方(招聘端卡)只看 证据 真值,不受影响 */
  态: '有证据' | '未提及' | '不满足';
  /** 硬字段(经验/学历)权重 2,JD 必须项权重 1 —— 算适配分用 */
  类: '硬性' | '必须';
}

/** 学历排序:核对「X及以上」用 */
function 学历阶(值: string): number {
  return 值.includes('博士') ? 3 : 值.includes('硕士') ? 2 : 值.includes('本科') ? 1 : 0;
}

/** 未命中置顶(招聘端 2026-08-26 定稿版式:差距先入眼),组内保持原顺序 */
function 未命中置顶(行们: 对齐行[]): 对齐行[] {
  return [...行们.filter((行) => !行.证据), ...行们.filter((行) => 行.证据)];
}

