import { describe, expect, it } from 'vitest';
import { 解析薪资区间, 薪资初筛, 薪资初筛文案 } from './薪资初筛';

describe('薪资初筛', () => {
  it('兼容两种常见的月薪区间写法', () => {
    expect(解析薪资区间('25K-35K')).toEqual({ 下限: 25, 上限: 35, 单位: '月薪K' });
    expect(解析薪资区间('25-35K')).toEqual({ 下限: 25, 上限: 35, 单位: '月薪K' });
  });

  it('只返回薪资带是否相交，不泄露候选人的具体预期', () => {
    const 结果 = 薪资初筛('25K-35K', '30K-45K');
    expect(结果).toBe('有交集');
    expect(薪资初筛文案(结果)).toBe('薪资带有交集');
  });

  it('识别没有交集的薪资带', () => {
    expect(薪资初筛('45K-55K', '25K-35K')).toBe('无交集');
  });

  it('不同计薪周期和无法解析的输入交由人工核对', () => {
    expect(薪资初筛('1000元/天', '25K-35K')).toBe('待核对');
    expect(薪资初筛('面议', '25K-35K')).toBe('待核对');
  });
});
