// 列表卡片映射：纯函数投影，不插占位文本（占位由组件按同一规则渲染，Spec §4）。
import { describe, expect, it } from 'vitest';
import { 从Mock推荐到卡信息, 从招聘摘要到卡信息, 求职状态文案 } from './列表卡片映射';
import type { 招聘候选摘要视图 } from './招聘候选摘要映射';
import type { 推荐候选 } from './类型';

const Mock人: 推荐候选 = {
  编号: 'R-11',
  岗位编号: 'P-01',
  代号: '江叙白',
  头像字: '江',
  性别: '男',
  画像: '7 年 · Go / 交易网关 · 华泰证券',
  匹配分: 91,
  亮点: ['交易域直接对口', '短通勤'],
  评语: '硬性五项全过',
  经验年: 7,
  学历: '本科',
  学校: '上海交通大学',
  专业: '计算机科学与技术',
  求职状态: '在职',
  活跃度: '今天活跃',
};

const 摘要视图: 招聘候选摘要视图 = {
  性别: '女',
  年限: '5 年',
  学历: '本科',
  求职状态: '在职看机会',
  工作: '示例公司 · 软件工程师',
  教育: '示例大学 · 计算机科学',
  个人亮点: ['带领5人团队交付'],
};

describe('从招聘摘要到卡信息', () => {
  it('摘要缺省（显式 null）：全字段 null、亮点空数组，不造半已知卡', () => {
    expect(从招聘摘要到卡信息(null)).toEqual({
      性别: null, 年限: null, 学历: null, 求职状态: null, 工作: null, 教育: null, 亮点: [],
    });
  });

  it('摘要视图逐字段透传，不改写业务文案算法（0 年「不满 1 年」原样）；亮点改名并保持顺序', () => {
    expect(从招聘摘要到卡信息({ ...摘要视图, 年限: '不满 1 年' })).toEqual({
      性别: '女',
      年限: '不满 1 年',
      学历: '本科',
      求职状态: '在职看机会',
      工作: '示例公司 · 软件工程师',
      教育: '示例大学 · 计算机科学',
      亮点: ['带领5人团队交付'],
    });
  });

  it('摘要没给性别（键缺席）：性别为 null，不猜', () => {
    const 无性别: 招聘候选摘要视图 = { ...摘要视图, 性别: undefined };
    expect(从招聘摘要到卡信息(无性别).性别).toBeNull();
  });
});

describe('从Mock推荐到卡信息', () => {
  it('画像拆成「现职类型 · 方向」工作行 + 学校专业教育行；年限/学历/求职状态按 Mock 现有口径', () => {
    // 求职状态走 2026-09-08 定稿的显示层口径（数据枚举不改）：在职 → 在职看机会
    expect(从Mock推荐到卡信息(Mock人)).toEqual({
      性别: '男',
      年限: '7 年',
      学历: '本科',
      求职状态: '在职看机会',
      工作: '华泰证券 · Go / 交易网关',
      教育: '上海交通大学 · 计算机科学与技术',
      亮点: ['交易域直接对口', '短通勤'],
    });
  });

  it('画像只给部分段：复合行显示已知部分（空白段丢弃，不为空段补内容）', () => {
    const 卡信息 = 从Mock推荐到卡信息({ ...Mock人, 画像: '5 年 · 前端工程师', 学校: ' ' });
    expect(卡信息.工作).toBe('前端工程师');
    expect(卡信息.教育).toBe('计算机科学与技术');
  });

  it('画像只有年限段、学校专业全空：工作与教育为 null（整行占位交给组件）', () => {
    const 卡信息 = 从Mock推荐到卡信息({ ...Mock人, 画像: '5 年', 学校: '', 专业: '' });
    expect(卡信息.工作).toBeNull();
    expect(卡信息.教育).toBeNull();
  });

  it('性别缺省（undefined）：映射成 null，不给默认性别', () => {
    expect(从Mock推荐到卡信息({ ...Mock人, 性别: undefined }).性别).toBeNull();
  });

  it('亮点原样带出：不去重、不排序、不过滤', () => {
    expect(从Mock推荐到卡信息({ ...Mock人, 亮点: ['b', 'b', 'a', ' '] }).亮点).toEqual([
      'b', 'b', 'a', ' ',
    ]);
  });
});

describe('求职状态文案', () => {
  it.each([
    ['在职', '在职看机会'],
    ['离职', '离职可到岗'],
    ['在校', '在校'],
  ] as const)('%s → %s', (状态, 文案) => {
    expect(求职状态文案(状态)).toBe(文案);
  });
});
