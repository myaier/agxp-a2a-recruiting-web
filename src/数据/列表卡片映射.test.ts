describe('从P5到阶段', () => {
  /** P5 列表正常视图的最小样本（招聘 open 行） */
  function P5视图(覆盖: Partial<P5列表正常视图> = {}): P5列表正常视图 {
    return {
      kind: '正常',
      caseId: 'mc_1',
      role: 'recruiter',
      职位: {
        jobId: 'job_1', 职位名: 'AI 产品实习生', 城市: '上海', 薪资带: '300-500 元/天', 技能: ['Python'],
      },
      intentionId: null,
      candidateAlias: 'candidate-0123456789ab',
      阶段标题: '匿名初筛',
      状态文案: '进行中',
      待办: false,
      终局: false,
      更新于: '2026-08-29T02:00:00Z',
      注意说明: null,
      ...覆盖,
    };
  }

  it.each([
    ['匿名初筛', '匿名初筛'],
    ['简历提交', '递交简历'],
    ['差异协同', '需要协调'],
    ['意向确认', '意向确认'],
  ] as const)('阶段标题 %s 保留 P5 原文，色系按语义闭表映射 %s', (标题, 色系) => {
    expect(从P5到阶段(P5视图({ 阶段标题: 标题 }))).toMatchObject({ 标题, 色系 });
  });

  it('徽标优先级保留：需要你 > 需注意 > 代理处理中；待办恒 false（不新增 Mock 呼吸点）', () => {
    const 注意 = 'AI 服务暂时不可用，本 Case 尚未继续';
    expect(从P5到阶段(P5视图({ 待办: true, 注意说明: 注意 })).徽标).toBe('需要你');
    expect(从P5到阶段(P5视图({ 待办: false, 注意说明: 注意 })).徽标).toBe('需注意');
    expect(从P5到阶段(P5视图({ 待办: false, 注意说明: null })).徽标).toBe('代理处理中');
    expect(从P5到阶段(P5视图({ 待办: true })).待办).toBe(false);
  });

  it('状态文本用既有 P5 状态文案原样带出（不是「下一步未知」），注意说明透传', () => {
    const 阶段 = 从P5到阶段(P5视图({
      阶段标题: '简历提交',
      状态文案: '等待中',
      注意说明: 'AI 服务暂时不可用，本 Case 尚未继续',
    }));
    expect(阶段.文本).toBe('等待中');
    expect(阶段.注意说明).toBe('AI 服务暂时不可用，本 Case 尚未继续');
  });
});
