/** 按岗位取「看市场 → 职位详情」的详情。
 *  查不到编号时**不回落到别的岗**（那正是这次要修的穿帮点），而是用这张岗位卡
 *  自己的字段合成一份「待补充」空态：公司名、发布人、简介仍然是这个岗真实的，
 *  只有 JD 正文缺失。口径与 公司档案.取公司档案 的兜底一致。 */
export function 取市场岗位详情(岗: 市场职位): 市场岗位详情 {
  const 命中 = 市场职位详情表[岗.编号];
  if (命中) return 命中;

  // 卡片上的发布人是 '姓名 · 机构'（猎头）或 '公司 · 企业直招'（直招）一整串，按分隔符拆开
  const [前段, 后段] = 岗.发布人.split(' · ');
  return {
    标签: 岗.学历要求 ? [岗.学历要求] : [],
    发布人: {
      首字: 岗.发布人首字,
      姓名: 前段,
      公司: 后段 ?? 岗.公司,
      职务: '',
      备注: '',
    },
    职位详情: ['职位详情待补充'],
    职位要求: ['职位要求待补充'],
    公司: { 首字: 岗.公司首字, 名称: 岗.公司, 简介: 岗.公司简介 },
    公司正文: '',
    公司标签: [],
  };
}

/** 按在谈单取职位详情 Tab 的数据。三级取数：
 *  ① 剧本单 J-01…J-05，各自一份；
 *  ② 与看市场同岗的单 —— 剧本里的 J-21/J-22/J-23 走镜像表，
 *     用户从看市场委托进来的单则编号本身就是 M-xx（见 应用状态.委托入谈 原样搬编号），
 *     两种都借市场表那一份，是同一个岗，JD 本来就该一样；
 *  ③ 都查不到 → 用在谈单自己的字段合成空态，对接人为 null（整张卡不渲染），
 *     绝不回落到别家公司的 JD。 */
export function 取在谈岗位详情(单: 在谈单): 在谈岗位详情 {
  const 命中 = 在谈职位详情表[单.编号];
  if (命中) return 命中;

  const 市场份 = 市场职位详情表[在谈单对应市场岗[单.编号] ?? 单.编号];
  if (市场份) {
    return {
      职位详情: 市场份.职位详情,
      职位要求: 市场份.职位要求,
      对接人: {
        首字: 市场份.发布人.首字,
        姓名: 市场份.发布人.姓名,
        职务: 市场份.发布人.职务,
        备注: 市场份.发布人.备注,
      },
      公司: { 正文: 市场份.公司正文, 标签: 市场份.公司标签 },
    };
  }

  return {
    职位详情: ['职位详情待补充'],
    职位要求: ['职位要求待补充'],
    对接人: null,
    公司: { 正文: '', 标签: [] },
  };
}

/** 按岗位编号取直聊对象。编号缺失（消息 Tab 那条无参进来的直聊）或查不到时，
 *  回落到市场列表第一条 —— 消息列表 X-02 那条直聊本来就是这个岗的对接人，
 *  回落到它比回落到空态更贴近真实入口。 */
export function 取直聊对象(编号?: string): 直聊对象 {
  const 岗 = 市场列表.find((条) => 条.编号 === 编号) ?? 市场列表[0];
  const 详 = 取市场岗位详情(岗);
  return {
    首字: 详.发布人.首字,
    姓名: 详.发布人.姓名,
    机构: 详.发布人.公司,
    职务: 详.发布人.职务,
    岗位公司: 岗.公司,
    // 原型统一给一套对接人联系方式（换电话的系统消息里那个尾号 2046 就是它）
    联系方式: { 电话: '138 0013 2046', 微信: 'hr_quanheng' },
    消息: 直聊开场白[岗.编号] ?? 直聊开场白[市场列表[0].编号],
  };
}
