import { describe, expect, it } from 'vitest';
import { 客户端校验错误 } from './HTTP客户端';
import { 构造登录手机号, 规范化登录区号 } from './登录手机号';

describe('规范化登录区号', () => {
  it.each([
    [' 999 ', '+999'],
    ['+86', '+86'],
    ['  1  ', '+1'],
  ])('将 %j 规范为 %s', (raw, expected) => {
    expect(规范化登录区号(raw)).toBe(expected);
  });

  it.each(['', '0', '++86', '1234', '8x6', '+ 86'])('拒绝非法区号 %j', (raw) => {
    expect(() => 规范化登录区号(raw)).toThrow(
      expect.objectContaining<Partial<客户端校验错误>>({
        name: '客户端校验错误',
        field: 'dialCode',
      }),
    );
  });
});

describe('构造登录手机号', () => {
  it('省略区号时保持旧 +86 单参数合同', () => {
    expect(构造登录手机号('13800000000')).toBe('+8613800000000');
  });

  it('只清理允许的普通分隔符', () => {
    expect(构造登录手机号('(138) 0000-0000', '+86')).toBe('+8613800000000');
  });

  it('保留 +999 的 12 位本地号码并只拼接一次', () => {
    expect(构造登录手机号('123456789012', '+999')).toBe('+999123456789012');
  });

  it.each([
    ['', '+86'],
    ['1380000000', '+86'],
    ['138000000000', '+86'],
    ['138x0000000', '+86'],
    ['+8613800000000', '+86'],
    ['1234', '+999'],
    ['1234567890123', '+999'],
  ])('拒绝不符当前区号合同的本地号码 %j / %s', (phone, dialCode) => {
    expect(() => 构造登录手机号(phone, dialCode)).toThrow(
      expect.objectContaining<Partial<客户端校验错误>>({
        name: '客户端校验错误',
        field: 'phone',
      }),
    );
  });
});
