import { describe, expect, it } from 'vitest';
import { 打码微信号, 打码手机号 } from './隐私展示';

describe('隐私展示', () => {
  it('手机号与账号安全页共用前三后四的展示口径', () => {
    expect(打码手机号('138 0217 6021')).toBe('138 **** 6021');
    expect(打码手机号('13802176021')).toBe('138 **** 6021');
  });

  it('带国码或分隔符的手机号仍能安全打码', () => {
    expect(打码手机号('+86 138-0217-6021')).toBe('138 **** 6021');
  });

  it('无法识别的联系方式 fail-closed，不回显完整原值', () => {
    expect(打码手机号('123456')).toBe('****56');
    expect(打码微信号('wx123')).toBe('***23');
  });

  it('微信号保留前三后二', () => {
    expect(打码微信号('shenyizhou_88')).toBe('she***88');
  });
});
