//   · 已知空（[]）与缺失（null）分别保持，不互换；
//   · Mock 归一语义逐段对比原正文内 从匿名档归一 的口径（视觉红线：字段与非空分支逐字一致），
//     真名对公司字段的合法恢复在本适配执行 —— renderer 不做实名决定。

