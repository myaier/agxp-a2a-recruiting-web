/** 与 Mock档 展示事实等价的安全资料（同一批共享事实；批注/一致性/项目日期是 Mock 独有演示事实） */
const 等价资料: 在线简历展示资料 = {
  画像: { 性别: '女', 年限: '5 年', 学历: '本科', 求职状态: '在职看机会', 职位行: '示例公司 · 软件工程师' },
  个人优势: '四年全栈经验',
  期望: { 标题: '社招全职 · 产品经理', 薪资关系: '薪资带有交集', 副行: '上海 · 混合' },
  工作: [{ 公司: '云衢', 起止: '2021.01—至今', 职位: '工程师', 说明: '平台研发' }],
  项目: [{ 名称: '推荐引擎', 角色: '负责人', 结果: '转化提升 12%' }],
  教育: [{ 行: '复旦大学 · 计算机科学 · 本科', 起止: '2017—2021' }],
  技能: ['TypeScript', 'React'],
};

function Mock内容(覆盖: Partial<Parameters<typeof 从Mock到简历正文>[0]> = {}): 在线简历正文内容 {
  const 内容 = 从Mock到简历正文({
    档: Mock档,
    真名: null,
    求职状态: '在职看机会',
    薪资结论: '薪资带待核对',
    ...覆盖,
  });
  if (内容 === null) throw new Error('非空档必须归一出正文内容');
  return 内容;
}

function 安全内容(资料: 在线简历展示资料 | null): 在线简历正文内容 {
  const 内容 = 从安全资料到简历正文(资料);
  if (内容 === null) throw new Error('非空资料必须归一出正文内容');
  return 内容;
}

describe('从Mock到简历正文 / 从安全资料到简历正文 · 整份缺源', () => {
  it('两来源 null 入 null 出：不造空资料，缺失归展示层原位显示', () => {
    expect(从Mock到简历正文({ 档: null, 真名: null, 求职状态: null, 薪资结论: 'x' })).toBeNull();
    expect(从安全资料到简历正文(null)).toBeNull();
  });
});

describe('从Mock到简历正文 / 从安全资料到简历正文 · 等价输入同内容', () => {
  it('共享槽位逐段一致：头区（含摘要求职状态）/自述/工作/项目/教育/技能', () => {
    const Mock出 = Mock内容();
    const 安全出 = 安全内容(等价资料);
    expect(Mock出.头区).toEqual(安全出.头区);
    expect(Mock出.自述).toBe(安全出.自述);
    expect(Mock出.经历![0]).toMatchObject({ 公司: '云衢', 起止: '2021.01—至今', 职位: '工程师', 说明: '平台研发' });
    expect(安全出.经历![0]).toMatchObject({ 公司: '云衢', 起止: '2021.01—至今', 职位: '工程师', 说明: '平台研发' });
    expect(Mock出.项目![0]).toMatchObject({ 名称: '推荐引擎', 角色: '负责人', 说明: '转化提升 12%' });
    expect(安全出.项目![0]).toMatchObject({ 名称: '推荐引擎', 角色: '负责人', 说明: '转化提升 12%' });
    expect(Mock出.教育).toEqual(安全出.教育);
    expect(Mock出.技能).toEqual(安全出.技能);
  });

  it('来源独有事实各归各位：批注/一致性/项目日期只属于 Mock，安全槽恒空且不设页尾说明', () => {
    const Mock出 = Mock内容();
    const 安全出 = 安全内容(等价资料);
    expect(Mock出.经历![0].批注).toBe('与岗位硬性条件吻合');
    expect(安全出.经历![0].批注).toBeNull();
    expect(Mock出.项目![0].起止).toBe('2022.03—2022.09');
    expect(安全出.项目![0].起止).toBeNull();
    expect(Mock出.期望!.一致性).toBe('薪资带与岗位一致');
    expect(安全出.期望!.一致性).toBeNull();
    expect(安全出.期望!.偏好).toBeNull();
    expect('页尾说明' in 安全出).toBe(false);
  });
});

describe('从安全资料到简历正文 · Backend 隐私红线', () => {
  it('遮蔽公司保持「未披露」：适配层没有 identity/公司目录输入，无实名恢复通道', () => {
    const 出 = 安全内容({
      ...等价资料,
      工作: [{ 公司: '未披露', 起止: '日期未知', 职位: null, 说明: null }],
    });
    expect(出.经历![0].公司).toBe('未披露');
    expect(出.经历![0].起止).toBe('日期未知');
  });

  it('项目不借工作日期：工作有起止，项目起止仍为 null，不添虚假批注', () => {
    const 出 = 安全内容(等价资料);
    expect(出.项目).toHaveLength(1);
    expect(出.项目![0].起止).toBeNull();
    expect(出.项目![0].批注).toBeNull();
  });

  it('薪资只认既有关系文案，无候选薪资数字；期望全无证据收口 null', () => {
    const 出 = 安全内容(等价资料);
    expect(出.期望!.薪资结论).toBe('薪资带有交集');
    expect(JSON.stringify(出)).not.toMatch(/\d+-\d+K/); // 不合成任何候选期望数字
    expect(
      安全内容({ ...等价资料, 期望: null }).期望,
    ).toBeNull();
  });

  it('区级 null / [] 分别保持：全 null 给缺失、合法空数组原样带出（不互换）', () => {
    const 全缺 = 安全内容({
      画像: null, 个人优势: null, 期望: null, 工作: null, 项目: null, 教育: null, 技能: null,
    });
    expect(全缺.头区).toBeNull();
    expect(全缺.自述).toBeNull();
    expect(全缺.期望).toBeNull();
    expect(全缺.经历).toBeNull();
    expect(全缺.项目).toBeNull();
    expect(全缺.教育).toBeNull();
    expect(全缺.技能).toBeNull();
    const 全空 = 安全内容({ ...等价资料, 工作: [], 项目: [], 教育: [], 技能: [] });
    expect(全空.经历).toEqual([]);
    expect(全空.项目).toEqual([]);
    expect(全空.教育).toEqual([]);
    expect(全空.技能).toEqual([]);
  });
});

describe('从Mock到简历正文 · 原 Mock 归一语义逐段保持', () => {
  it('头区：经验去「经验」后缀、性别/学历/职位行原样、求职状态取调用方事实', () => {
    expect(Mock内容().头区).toEqual({
      性别: '女',
      年限: '5 年',
      学历: '本科',
      求职状态: '在职看机会',
      职位行: '示例公司 · 软件工程师',
    });
    expect(Mock内容({ 求职状态: null }).头区!.求职状态).toBeNull();
  });

  it('期望：带宽行/偏好/一致性空串收口 null；薪资结论取调用方传入（不用档内期望薪资）', () => {
    expect(Mock内容().期望).toEqual({
      标题: '社招全职 · 产品经理',
      薪资结论: '薪资带待核对',
      带宽行: '上海 · 混合',
      偏好: '接受弹性办公',
      一致性: '薪资带与岗位一致',
    });
    expect(Mock内容({
      档: { ...Mock档, 期望: { ...Mock档.期望, 带宽行: '', 偏好: '', 一致性: '' } },
    }).期望).toEqual({
      标题: '社招全职 · 产品经理',
      薪资结论: '薪资带待核对',
      带宽行: null,
      偏好: null,
      一致性: null,
    });
  });

  it('真名只恢复公司实名（S1 既有口径）：非空才恢复，空串/缺省保持遮蔽公司', () => {
    expect(Mock内容({ 真名: '测某真名' }).经历![0].公司).toBe('云衢科技有限公司');
    expect(Mock内容({ 真名: null }).经历![0].公司).toBe('云衢');
    expect(Mock内容({ 真名: '' }).经历![0].公司).toBe('云衢');
    // 无 公司实名 的段不凭空造实名
    expect(Mock内容({
      档: { ...Mock档, 经历: [{ ...Mock档.经历[0]!, 公司实名: undefined }] },
      真名: '测某真名',
    }).经历![0].公司).toBe('云衢');
  });

  it('页尾说明是 Mock 演示事实：已披露给 S1 披露说明，未披露给双向核验声明；安全来源永不携带', () => {
    expect(Mock内容({ 真名: null }).页尾说明).toBe(
      '这份简历由候选人的AI代理生成 · 内容真实性经双向核验 · 不可转发',
    );
    expect(Mock内容({ 真名: '测某真名' }).页尾说明).toBe(
      '候选人身份已随 S1 原件披露 · 意向确认后进入真人沟通 · 内容不可转发',
    );
  });

  it('技能/数组是拷贝：改副本不动档；教育按 Mock 单条适配成一条', () => {
    const 出 = Mock内容();
    expect(出.技能).toEqual(['TypeScript', 'React']);
    expect(出.技能).not.toBe(Mock档.技能);
    expect(出.教育).toEqual([{ 行: '复旦大学 · 计算机科学 · 本科', 起止: '2017—2021' }]);
  });
});
