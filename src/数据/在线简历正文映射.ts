// 在线简历正文映射（S0–S3 展示统一 Task 6，Spec §7.1/§7.2）：两种来源 → 唯一正文模型
// 在线简历正文内容 的纯函数适配。正文 JSX 只吃这一个模型，不再识别数据源。
//
//   · 从Mock到简历正文：Mock 简历档（演示事实：批注/一致性/项目日期/期望偏好）
//     归一出模型。真名对公司字段的合法恢复（S1 原件披露的既有口径）在这里执行完毕 ——
//     renderer 不做实名决定；页尾的披露/核验说明也由本适配按演示事实提供（Spec §7.3）。
//   · 从安全资料到简历正文：Backend 安全展示资料（数据/在线简历展示映射 的产出）归一出
//     模型。不读 Mock 表；null/[]、遮蔽公司「未披露」、日期未知/有开始才至今、项目无独立
//     日期、批注/一致性/偏好 null、未知薪资关系 null 全部沿用安全资料的冻结语义；
//     不设页尾说明 —— Backend 没有核验/披露证据，展示层回退到无承诺的生成声明。
//
// 两条映射都不做身份/薪资/日期的恢复或合成：模型里没有候选薪资数字，也没有公司实名
// 恢复字段 —— Backend 永不读 identity 恢复实名。

import type {
  在线简历正文内容,
  在线简历展示资料,
} from '../组件/在谈详情/类型';
import type { 匿名简历档 } from './企业端模拟数据';

/** Mock 期望薪资槽的既有默认结论（旧正文 props 默认值原样搬来；独立页/详情按岗位初筛覆盖） */
export const Mock默认薪资结论 = '薪资带已进入初筛';

/** Mock 真名恢复后的页尾披露说明 / 未披露时的双向核验声明（既有页尾文案逐字保留） */
const Mock已披露页尾说明 = '候选人身份已随 S1 原件披露 · 意向确认后进入真人沟通 · 内容不可转发';
const Mock默认页尾说明 = '这份简历由候选人的AI代理生成 · 内容真实性经双向核验 · 不可转发';

/**
 * Mock 简历档 → 正文内容：字段名与非空分支与原正文内 从匿名档归一 逐字一致（视觉红线）。
 * 真名非空（S1 原件递交后）即还原有 公司实名 的经历段公司名，并把披露/核验说明装入
 * 页尾说明 —— 两处都是 Mock 演示事实，Backend 链路不经过本函数。
 */
export function 从Mock到简历正文(输入: {
  档: 匿名简历档 | null;
  真名: string | null;
  求职状态: string | null;
  薪资结论: string;
}): 在线简历正文内容 | null {
  const 档 = 输入.档;
  if (档 === null) return null;
  const 已披露 = 输入.真名 !== null && 输入.真名 !== undefined && 输入.真名 !== '';
  return {
    头区: {
      性别: 档.性别 ?? null,
      年限: 档.经验.replace(/经验$/, ''),
      学历: 档.学历,
      求职状态: 输入.求职状态,
      职位行: 档.职位行,
    },
    自述: 档.自述,
    期望: {
      标题: 档.期望.标题,
      薪资结论: 输入.薪资结论,
      带宽行: 档.期望.带宽行 === '' ? null : 档.期望.带宽行,
      偏好: 档.期望.偏好 === '' ? null : 档.期望.偏好,
      一致性: 档.期望.一致性 === '' ? null : 档.期望.一致性,
    },
    经历: 档.经历.map((段) => ({
      公司: 已披露 && 段.公司实名 ? 段.公司实名 : 段.公司,
      起止: 段.起止,
      职位: 段.职位,
      说明: 段.说明,
      批注: 段.批注,
    })),
    项目: 档.项目.map((项) => ({
      名称: 项.名称,
      起止: 项.起止,
      角色: 项.角色,
      说明: 项.说明,
      批注: 项.批注,
    })),
    教育: [{ 行: 档.教育行, 起止: 档.教育起止 }],
    技能: [...档.技能],
    页尾说明: 已披露 ? Mock已披露页尾说明 : Mock默认页尾说明,
  };
}

/**
 * Backend 安全展示资料 → 正文内容：真名恢复 / 公司实名 / 批注 / 一致性条在安全槽不存在，
 * 本映射也无从合成 —— 遮蔽公司原样带出「未披露」，项目起止恒 null，页尾说明恒不设。
 * 不读 Mock 表、不读 identity：候选薪资数字与项目日期在模型上就不存在。
 */
export function 从安全资料到简历正文(
  资料: 在线简历展示资料 | null,
): 在线简历正文内容 | null {
  if (资料 === null) return null;
  return {
    头区: 资料.画像 === null ? null : { ...资料.画像 },
    自述: 资料.个人优势,
    期望: 资料.期望 === null
      ? null
      : {
          标题: 资料.期望.标题,
          薪资结论: 资料.期望.薪资关系,
          带宽行: 资料.期望.副行,
          偏好: null,
          一致性: null,
        },
    经历: 资料.工作 === null
      ? null
      : 资料.工作.map((段) => ({
          公司: 段.公司,
          起止: 段.起止,
          职位: 段.职位,
          说明: 段.说明,
          批注: null,
        })),
    项目: 资料.项目 === null
      ? null
      : 资料.项目.map((项) => ({
          名称: 项.名称,
          起止: null,
          角色: 项.角色,
          说明: 项.结果,
          批注: null,
        })),
    教育: 资料.教育 === null ? null : 资料.教育.map((条) => ({ 行: 条.行, 起止: 条.起止 })),
    技能: 资料.技能 === null ? null : [...资料.技能],
  };
}
