/** 静态档的 规模行 是「C 轮 · 500-1000 人 · 金融科技」这一串，按 ' · ' 拆成三个档位 */
function 拆规模行(规模行: string): { 融资阶段: string; 规模: string; 行业: string } {
  const 段 = 规模行.split('·').map((条) => 条.trim());
  return { 融资阶段: 段[0] ?? '', 规模: 段[1] ?? '', 行业: 段[2] ?? '' };
}

/** 静态档的 作息 是「上午 09:30 – 下午 07:00 · 双休 · 大小周已取消」，
 *  把两个钟点抠出来换成 24 小时制。本屏不编辑它们，但保存时要原样合成回去 */
export function 拆时间段(作息文: string): { 上班: string; 下班: string } {
  const 命中 = [...作息文.matchAll(/(上午|下午|晚上)?\s*(\d{1,2}):(\d{2})/g)];
  const 换算 = (段: RegExpMatchArray) => {
    let 时 = Number(段[2]);
    if ((段[1] === '下午' || 段[1] === '晚上') && 时 < 12) 时 += 12;
    return `${String(时).padStart(2, '0')}:${段[3]}`;
  };
  return {
    上班: 命中[0] ? 换算(命中[0]) : '09:30',
    下班: 命中[1] ? 换算(命中[1]) : '19:00',
  };
}

/** 作息档：'双休 · 大小周已取消' 里 双休 在前，按池子顺序取第一个命中的即可 */
function 拆作息档(作息文: string): string {
  return 作息池.find((档) => 作息文.includes(档)) ?? 作息池[0];
}

/** 全局覆盖 + 静态档 → 一份可编辑的扁平资料。改过的用改过的，没改过的用静态档 */
export function 读资料(静态档: 公司档案, 覆盖: 公司自述覆盖 | null): 资料形 {
  const 档 = 覆盖 ? { ...静态档, ...覆盖 } : 静态档;
  const 静态规模 = 拆规模行(静态档.规模行);
  return {
    公司全称: 档.名称,
    行业: 覆盖?.行业 ?? 静态规模.行业,
    规模: 覆盖?.规模 ?? 静态规模.规模,
    融资阶段: 覆盖?.融资阶段 ?? 静态规模.融资阶段,
    办公地址: 档.地址,
    福利标签:
      覆盖?.公司标签 ??
      静态档.福利.map((项) => 项.名称).filter((名) => 福利标签池.includes(名)),
    作息档: 覆盖?.作息档 ?? 拆作息档(静态档.作息),
    // 三段自述在数据层是数组，编辑时摊成多行文本，一行一条
    公司介绍: 档.简介.join('\n'),
    主营业务: (覆盖?.主营业务 ?? 静态档.主营业务).join('\n'),
    实景照片: 覆盖?.公司相册?.实景照片 ?? [],
    公司照片: 覆盖?.公司相册?.公司照片 ?? [],
    产品介绍: 覆盖?.产品介绍 ?? '',
    团队介绍: 覆盖?.团队介绍 ?? [],
  };
}

/** 清单行右侧的摘要：一行放不下就截断，不改写用户原话 */
function 截断(文: string, 上限 = 12): string {
  const 单行 = 文.replace(/\s+/g, ' ').trim();
  return 单行.length > 上限 ? `${单行.slice(0, 上限)}…` : 单行;
}

export interface 分区状态 {
  已填: number;
  总数: number;
  摘要: string;
}

/** 每个分区填了几项 + 摘要。LOGO 存在独立切片里，所以要单独传进来 */
export function 算分区状态(资料: 资料形, LOGO: string | null): Record<分区键, 分区状态> {
  return {
    基本信息: {
      已填: [资料.公司全称, LOGO ?? '', 资料.行业, 资料.规模, 资料.融资阶段, 资料.办公地址].filter(
        (值) => 值.trim() !== ''
      ).length,
      总数: 6,
      摘要: '',
    },
    公司福利: {
      已填: (资料.福利标签.length > 0 ? 1 : 0) + (资料.作息档 ? 1 : 0),
      总数: 2,
      摘要: '',
    },
    公司介绍: { 已填: 资料.公司介绍.trim() ? 1 : 0, 总数: 1, 摘要: 截断(资料.公司介绍) },
    主营业务: {
      已填: 资料.主营业务.trim() ? 1 : 0,
      总数: 1,
      摘要: 截断(资料.主营业务.split('\n').filter(Boolean).join(' · ')),
    },
    公司相册: {
      已填: (资料.实景照片.length > 0 ? 1 : 0) + (资料.公司照片.length > 0 ? 1 : 0),
      总数: 2,
      摘要: '',
    },
    产品介绍: { 已填: 资料.产品介绍.trim() ? 1 : 0, 总数: 1, 摘要: 截断(资料.产品介绍) },
    团队介绍: {
      已填: 资料.团队介绍.length > 0 ? 1 : 0,
      总数: 1,
      摘要: 截断(资料.团队介绍.map((位) => 位.姓名 || 位.职务).filter(Boolean).join('、')),
    },
  };
}

/** 一份资料 → 完整的 公司自述覆盖。合成字段与本屏不编辑的字段都在这里补齐 */
export function 合成覆盖(
  资料: 资料形,
  静态档: 公司档案,
  覆盖: 公司自述覆盖 | null
): 公司自述覆盖 {
  const 档 = 覆盖 ? { ...静态档, ...覆盖 } : 静态档;
  const 时间段 = 拆时间段(覆盖?.作息 ?? 静态档.作息);
  const 上班时间 = 覆盖?.上班时间 ?? 时间段.上班;
  const 下班时间 = 覆盖?.下班时间 ?? 时间段.下班;
  // 全称留空就退回原值：候选端 企业详情 拿 名称 当页面标题、拿 首字 画字标，
  // 存进一个空串会让那一屏顶部整块塌掉（空标题 + 空字标）
  const 落库全称 = 资料.公司全称.trim() || 档.名称;

  return {
    简介: 资料.公司介绍.split('\n').map((行) => 行.trim()).filter(Boolean),
    // 企业文化 / 发展历程 / 地址补充 本屏没有分区，原样带过去
    企业文化: 档.企业文化,
    发展历程: 档.发展历程,
    地址补充: 档.地址补充,
    // 候选端读的合成字段：作息 = 上班时间段 + 作息档，规模行 = 融资 · 规模 · 行业
    作息: `${上班时间} – ${下班时间} · ${资料.作息档}`,
    // 地址清空就是真清空（清单上那一项也随之变回未填）
    地址: 资料.办公地址.trim(),
    名称: 落库全称,
    首字: 落库全称.charAt(0),
    一句话简介: 覆盖?.一句话简介,
    行业: 资料.行业,
    规模: 资料.规模,
    融资阶段: 资料.融资阶段,
    规模行: [资料.融资阶段, 资料.规模, 资料.行业].filter(Boolean).join(' · '),
    上班时间,
    下班时间,
    作息档: 资料.作息档,
    公司标签: 资料.福利标签,
    主营业务: 资料.主营业务.split('\n').map((行) => 行.trim()).filter(Boolean),
    公司相册: { 实景照片: 资料.实景照片, 公司照片: 资料.公司照片 },
    产品介绍: 资料.产品介绍.trim(),
    // 三格全空的行是用户加了没写的空壳，不落库
    团队介绍: 资料.团队介绍.filter((位) => 位.姓名 || 位.职务 || 位.简介),
  };
}
