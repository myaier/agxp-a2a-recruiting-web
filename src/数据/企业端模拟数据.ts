// 结构对齐 BOSS直聘 的牛人简历页（状态行 → 个人优势 → 工作经历 → 作品 →
// 教育 → 技能），但按不对称双盲逐段脱敏：
//   · 公司名按候选人的披露偏好写成「同赛道头部公司」；确认意向后还原实名
