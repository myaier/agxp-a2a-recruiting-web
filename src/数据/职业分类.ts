/** 扁平结构（大类 + 小类[]）：发布岗位的职业分类层仍按这个渲染 */
export interface 职业大类扁平 {
  大类: string;
  小类: string[];
}

export const 职业分类表: 职业大类扁平[] = 职业分类树.map((组) => ({
  大类: 组.大类,
  小类: 组.分组.flatMap((分) => 分.岗位),
}));

/** 从岗位反查它所属的大类；查不到回退第一个大类 */
export function 查大类(小类: string): string {
  return 职业分类表.find((组) => 组.小类.includes(小类))?.大类 ?? 职业分类表[0].大类;
}
