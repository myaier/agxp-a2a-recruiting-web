// 薪资展示（Task 8 / Spec §8A / Plan C4）：一个小型薪资格式化函数 + 有限输入适配。
//
// 只统一已有结构化薪资的显示表示（§8A.1 合同表）；不建立金额引擎、不解析自然语言、
// 不新增请求/配置/缓存，也不导出任何金额换算能力。内部输入结构不持久化 ——
// 调用方各自的数值字段（草稿/DTO/模型）仍是唯一真相，显示统一只发生在读取边界。
//
// 显示合同（§8A.1）：区间用 en dash `–`；月薪数字与 `K` 无空格；日/时薪数字与单位
// 之间一个空格；后缀是小写 ASCII ` x N`（不带「薪」字）；只有月薪且明确填写非 12
// 的合法年薪月数才追加（未填/12 都是省略，不代表已确认 12 薪，也不按 12 补写数据）；
// 同值折单值；「面议」与「薪资未知」是两回事 —— 前者是来源明确的协议值，后者是
// 缺失/空白/无法安全判明单位的降级显示（不造 0、不推断面议）。

/** §8A.1 缺失/非法的统一降级显示 */
export const 薪资未知 = '薪资未知';

export interface 薪资输入 {
  下限: number | null;
  上限: number | null;
  周期: 'month' | 'day' | 'hour';
  /** 仅月薪有意义；未填/12 省略，日/时不追加 */
  年薪月数?: number | null;
  /** 来源明确为面议（如补偿协议的 negotiable 档）：直接显示 面议，不追加年薪月数 */
  面议?: boolean;
}

/** 合法金额：有限且非负。null/undefined/NaN/负数都不算合法值。 */
function 是合法金额(值: number | null | undefined): 值 is number {
  return typeof 值 === 'number' && Number.isFinite(值) && 值 >= 0;
}

/** 可作后缀的年薪月数：明确填写的正整数且 ≠12；否则视为省略（非法月数不毁掉合法区间）。 */
function 后缀月数(值: number | null | undefined): number | null {
  if (typeof 值 !== 'number' || !Number.isInteger(值) || 值 < 1 || 值 === 12) return null;
  return 值;
}

/** 结构化薪资 → §8A.1 显示文本；非法/缺失返回 薪资未知。 */
export function 格式化薪资({ 下限, 上限, 周期, 年薪月数, 面议 }: 薪资输入): string {
  if (面议 === true) return '面议';
  if (!是合法金额(下限) || !是合法金额(上限) || 下限 > 上限) return 薪资未知;
  const 区间 = 下限 === 上限 ? `${下限}` : `${下限}–${上限}`;
  if (周期 === 'day') return `${区间} 元/天`;
  if (周期 === 'hour') return `${区间} 元/时`;
  const 月数 = 后缀月数(年薪月数);
  return 月数 === null ? `${区间}K` : `${区间}K x ${月数}`;
}

// §8A.3 有限识别清单：紧凑带（ASCII 连字符或 en dash）、本函数自身输出（含 x N 后缀）、
// 后端 `K/month x N薪`、Mock `K · N 薪`。清单之外的表示（含 `K/day`/`K/hour` 这类
// 单位矛盾串、自然语言、旧 `/天` 形式）一律降级 薪资未知，不猜单位、不改写数值。
const 紧凑带式 = /^(\d+)(?:[-–](\d+))?\s*(K|元\/天|元\/时)(?:\s*x\s*(\d+))?$/;
const 月薪月数式 = /^(\d+)(?:[-–](\d+))?\s*K(?:\/month\s*x\s*|\s*·\s*)(\d+)\s*薪$/;

/**
 * 已核对的有限薪资显示串 → §8A.1 统一显示（幂等）；不可识别返回 薪资未知。
 * 年薪月数参数来自同一记录的结构化字段：与串内自带的月数一致只保留一个后缀，
 * 冲突则不择一（薪资未知）；日/时薪永不追加。
 */
export function 规范薪资文本(文本: string | null | undefined, 年薪月数?: number | null): string {
  const 原 = 文本?.trim();
  if (!原) return 薪资未知;
  if (原 === '面议' || 原 === 薪资未知) return 原;
  const 参数月数 = 后缀月数(年薪月数);
  const 月数式 = 月薪月数式.exec(原);
  if (月数式) {
    const 串月数 = Number(月数式[3]);
    if (参数月数 !== null && 参数月数 !== 串月数) return 薪资未知;
    return 格式化薪资({
      下限: Number(月数式[1]),
      上限: Number(月数式[2] ?? 月数式[1]),
      周期: 'month',
      年薪月数: 串月数,
    });
  }
  const 紧凑 = 紧凑带式.exec(原);
  if (!紧凑) return 薪资未知;
  const 单位 = 紧凑[3];
  const 串月数 = 紧凑[4] !== undefined ? Number(紧凑[4]) : null;
  // 「元/天/时 x N」不是任何已识别来源会产出的表示，无法安全表达 → 降级
  if (单位 !== 'K' && 串月数 !== null) return 薪资未知;
  if (参数月数 !== null && 串月数 !== null && 参数月数 !== 串月数) return 薪资未知;
  return 格式化薪资({
    下限: Number(紧凑[1]),
    上限: Number(紧凑[2] ?? 紧凑[1]),
    周期: 单位 === 'K' ? 'month' : 单位 === '元/天' ? 'day' : 'hour',
    年薪月数: 串月数 ?? 参数月数,
  });
}
