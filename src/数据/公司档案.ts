// 公司档案。入口：职位详情 / 在谈详情的职位详情 Tab 里点公司卡。
//
// 信息架构的立场：这不是公司的宣传册，而是「你的代理对这家公司的档案」。
// 所以每一段信息都要标明可信来源 —— 代理核过的、公司自述的、第三方核验的，三者分开。
// 常规招聘 App 的公司页把这三者混成一锅「公司介绍」，用户没法判断哪句话能当真。
//
// 两条硬约束：
//   1. 核对结论只能定性（覆盖 / 一致 / 偏窄），不出现任何薪资数字，也不出现
//      竞争者人数、百分位这类可反推他人的数字；
//   2. 核对项只列硬性条件与软性要求 —— 到岗时间不在代理谈判范围内
//      （产品边界 2026-08-18：薪资与到岗由候选人和 HR 在真人聊天里自己谈）。
// 招聘方实名可见（不对称双盲，见 数据/类型.ts 顶部），所以公司信息这一页是实名的。

export interface 福利项 {
  名称: string;
  说明: string;
  /** 已核 = 代理在往来里确认过；自述 = 公司单方面写的，还没核 */
  核对: '已核' | '自述';
}

export interface 历程节点 {
  年份: string;
  事件: string;
}

export interface 感受项 {
  标签: string;
  条数: number;
}

export interface 工商项 {
  项: string;
  值: string;
}

/**
 * 代理对这家公司的硬性条件核对结果。这是本页与普通招聘 App 的根本差别：
 * 不是公司自我介绍，而是「你的代理替你核过什么」。
 * 双盲约束：结论只能是定性的（是否覆盖 / 是否一致），不得出现任何薪资数字。
 */
export interface 核对项 {
  项: string;
  结论: string;
  状态: '通过' | '待核' | '有分歧';
}

export interface 公司档案 {
  /** URL slug，必须 ASCII（中文参数在 react-router 里匹配不上）*/
  键: string;
  名称: string;
  首字: string;
  /** 融资 · 规模 · 行业 */
  规模行: string;
  作息: string;
  地址: string;
  地址补充: string;
  简介: string[];
  企业文化: string;
  发展历程: 历程节点[];
  主营业务: string[];
  福利: 福利项[];
  在职感受: 感受项[];
  工商信息: 工商项[];
  在招岗位数: number;
  /** 这家公司的代理在本轮谈判里的画风，给用户一个预期 */
  代理风格: string;
  核对: 核对项[];
}

