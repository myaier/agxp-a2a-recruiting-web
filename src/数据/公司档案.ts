/** 名称 → 路由用的 slug。没档案的公司退回 URL 编码后的名称，保证链接一定能点开 */
export function 公司路由键(名称: string): string {
  return 公司档案表.find((条) => 条.名称 === 名称)?.键 ?? encodeURIComponent(名称);
}

