import type { 候选卡信息, 在谈阶段信息 } from '../组件/列表卡片/类型';
import type { P5列表正常视图 } from './MatchCase展示映射';
import type { 连续列表视图 } from './连续代谈展示映射';
import type { 招聘候选摘要视图 } from './招聘候选摘要映射';
import type { 阶段, 候选, 推荐候选, 在谈单 } from './类型';

/** Mock 推荐卡头行的求职状态口径（2026-09-08 产品负责人定稿）：数据枚举不改，只在显示层
 *  映射成与在谈卡「在找」后半段同一套词。表从 屏幕/候选推荐.tsx 挪到数据层：映射要在
 *  这里用到它，保持 屏幕 → 数据 单向依赖（页面保留同名导出，匿名在线简历等消费者不变）。 */
const 求职状态文案表: Record<推荐候选['求职状态'], string> = {
  在职: '在职看机会',
  离职: '离职可到岗',
  在校: '在校',
};

export function 求职状态文案(状态: 推荐候选['求职状态']): string {
  return 求职状态文案表[状态];
}

/** 招聘摘要缺省（键缺席 / 显式 null）：统一传 null，占位交给组件，不造半已知卡。 */
export function 从招聘摘要到卡信息(v: 招聘候选摘要视图 | null): 候选卡信息 {
  if (v === null) {
    return { 性别: null, 年限: null, 学历: null, 求职状态: null, 工作: null, 教育: null, 亮点: [] };
  }
  return {
    性别: v.性别 ?? null,
    年限: v.年限,
    学历: v.学历,
    求职状态: v.求职状态,
    工作: v.工作,
    教育: v.教育,
    亮点: v.个人亮点,
  };
}

/** trim 后无有效字符的段不算已知内容（Spec §4.1：展示文本 trim 后为空按缺失处理）。 */
function 非空段(段: string): string | null {
  const 值 = 段.trim();
  return 值 === '' ? null : 值;
}

/** Mock 画像/学校专业的复合行：丢掉空白段、只留已知部分（Spec §4.2），全空才为 null。 */
function 复合行(...段们: string[]): string | null {
  const 们 = 段们.map((段) => 非空段(段)).filter((段): 段 is string => 段 !== null);
  return 们.length > 0 ? 们.join(' · ') : null;
}

export function 从Mock推荐到卡信息(v: 推荐候选): 候选卡信息 {
  // 画像 = 「年限 · 方向 · 现职类型」三段；Mock 卡原有工作行显示「现职类型 · 方向」
  const [, 方向 = '', 现职类型 = ''] = v.画像.split(' · ');
  return {
    性别: v.性别 ?? null,
    年限: `${v.经验年} 年`,
    学历: v.学历,
    求职状态: 求职状态文案(v.求职状态),
    工作: 复合行(现职类型, 方向),
    教育: 复合行(v.学校, v.专业),
    亮点: v.亮点,
  };
}

export function 从Mock候选到卡信息(v: 候选, 标签: readonly string[]): 候选卡信息 {
  // 画像 = 「年限 · 方向 · 现职类型」三段：头行年限取首段，工作行显示「现职类型 · 方向」
  //（与原 Mock 候选卡同一拆法）；求职状态只取 在找「·」后半段（2026-09-08 定稿，数据已是文案）。
  const [年限 = '', 方向 = '', 现职类型 = ''] = v.画像.split(' · ');
  const [, 在找状态 = ''] = v.在找?.split(' · ') ?? [];
  return {
    性别: v.性别 ?? null,
    年限: 非空段(年限),
    学历: 非空段(v.学历 ?? ''),
    求职状态: 非空段(在找状态),
    工作: 复合行(现职类型, 方向),
    教育: 复合行(v.学校 ?? '', v.专业 ?? ''),
    // 亮点 = 连接层回查推荐库的标签（查不到为空数组），原样透传：不去重、不排序、不过滤
    亮点: 标签,
  };
}

/** Mock 在谈阶段：标题与色系都是原阶段枚举（保留原阶段名称与颜色），呼吸点跟 需要你 走，
 *  文本 = 下一步；Mock 不新增归属徽标、没有 attention 说明（Spec §5.4）。 */
export function 从Mock在谈到阶段(v: Pick<在谈单, '阶段' | '需要你' | '下一步'>): 在谈阶段信息 {
  return {
    标题: v.阶段,
    色系: v.阶段,
    待办: v.需要你,
    徽标: null,
    文本: v.下一步,
    注意说明: null,
  };
}

/** P5 阶段标题 → Mock 四阶段色系闭表（Spec §5.4）：标题保留 P5 原文，色系按四阶段语义
 *  对齐 Mock 配色；键就是 映射P5列表项 阶段标题表 的四个原文字。 */
const P5标题色系表: Record<string, 阶段> = {
  匿名初筛: '匿名初筛',
  简历提交: '递交简历',
  差异协同: '需要协调',
  意向确认: '意向确认',
};

export function 从P5到阶段(v: P5列表正常视图): 在谈阶段信息 {
  const 色系 = P5标题色系表[v.阶段标题];
  if (色系 === undefined) {
    // 阶段标题 是闭表的产物，四词之外就是契约漂移：不兜底配色遮掩（Plan：输入必须是现有
    // 合法映射的正常分支），也不把这一行画成未知阶段的正常卡（错误路径在列表层）。
    throw new Error(`未知 P5 阶段标题：${v.阶段标题}`);
  }
  return {
    标题: v.阶段标题,
    色系,
    // Backend 只保留原徽标，不新增 Mock 的待办呼吸点（Plan：待办恒 false）
    待办: false,
    // 原 P5 徽标优先级原样保留，只从头行搬进阶段区（Spec §5.4）：
    // 需要你 > 需注意（有 attention 说明）> 代理处理中
    徽标: v.待办 ? '需要你' : v.注意说明 !== null ? '需注意' : '代理处理中',
    // 状态文本继续用既有 P5 状态文案 —— 它是已知状态，不能抹成「下一步未知」
    文本: v.状态文案,
    注意说明: v.注意说明,
  };
}

/** 连续卡阶段 → 阶段区信息（J-PILOT-01 Task 4）：case_started 的阶段标题复用既有
 *  P5 标题闭表；pre-Case 阶段标题（已受理/初评中/初评失败/已拒绝/已开案）归初评色系。
 *  徽标/文本/注意说明由 映射连续列表项 权威投影，这里只补配色 —— 徽标原样透传，
 *  待办恒 false（同 从P5到阶段：Backend 只保留徽标，不新增 Mock 的待办呼吸点）。 */
export function 从连续到阶段(v: 连续列表视图): 在谈阶段信息 {
  return {
    标题: v.阶段标题,
    色系: P5标题色系表[v.阶段标题] ?? '匿名初筛',
    待办: false,
    徽标: v.徽标,
    文本: v.状态文案,
    注意说明: v.注意说明,
  };
}
