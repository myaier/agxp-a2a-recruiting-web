// 列表卡片映射：把页面既有视图投影成 src/组件/列表卡片 的展示数据。
// 纯函数、只转换数据、不插入占位文本 —— 占位由 候选信息主体 / 卡片分数 按同一规则渲染
// （Spec §4）；输入必须是现有合法映射的正常分支。类型引用一律 type-only，
// 零 React / fixture / HTTP 运行时依赖。
import type { 候选卡信息 } from '../组件/列表卡片/类型';
import type { 招聘候选摘要视图 } from './招聘候选摘要映射';
import type { 推荐候选 } from './类型';

/** Mock 推荐卡头行的求职状态口径（2026-09-08 产品负责人定稿）：数据枚举不改，只在显示层
 *  映射成与在谈卡「在找」后半段同一套词。表从 屏幕/候选推荐.tsx 挪到数据层：映射要在
 *  这里用到它，保持 屏幕 → 数据 单向依赖（页面保留同名导出，匿名在线简历等消费者不变）。 */
const 求职状态文案表: Record<推荐候选['求职状态'], string> = {
  在职: '在职看机会',
  离职: '离职可到岗',
  在校: '在校',
};

export function 求职状态文案(状态: 推荐候选['求职状态']): string {
  return 求职状态文案表[状态];
}

/** 招聘摘要缺省（键缺席 / 显式 null）：统一传 null，占位交给组件，不造半已知卡。 */
export function 从招聘摘要到卡信息(v: 招聘候选摘要视图 | null): 候选卡信息 {
  if (v === null) {
    return { 性别: null, 年限: null, 学历: null, 求职状态: null, 工作: null, 教育: null, 亮点: [] };
  }
  return {
    性别: v.性别 ?? null,
    年限: v.年限,
    学历: v.学历,
    求职状态: v.求职状态,
    工作: v.工作,
    教育: v.教育,
    亮点: v.个人亮点,
  };
}

/** Mock 画像/学校专业的复合行：丢掉空白段、只留已知部分（Spec §4.2），全空才为 null。 */
function 复合行(...段们: string[]): string | null {
  const 们 = 段们.map((段) => 段.trim()).filter((段) => 段 !== '');
  return 们.length > 0 ? 们.join(' · ') : null;
}

export function 从Mock推荐到卡信息(v: 推荐候选): 候选卡信息 {
  // 画像 = 「年限 · 方向 · 现职类型」三段；Mock 卡原有工作行显示「现职类型 · 方向」
  const [, 方向 = '', 现职类型 = ''] = v.画像.split(' · ');
  return {
    性别: v.性别 ?? null,
    年限: `${v.经验年} 年`,
    学历: v.学历,
    求职状态: 求职状态文案(v.求职状态),
    工作: 复合行(现职类型, 方向),
    教育: 复合行(v.学校, v.专业),
    亮点: v.亮点,
  };
}
