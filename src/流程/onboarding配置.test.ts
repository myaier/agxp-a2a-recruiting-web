import { describe, expect, it } from 'vitest';
import { 路径 } from '../路由/路径表';
import {
  Onboarding流程,
  初筛字段矩阵,
  判断求职薪资单位,
  向导出口,
  向导段参数名,
  向导题序,
  读向导段,
  规范化作品集链接,
  校验作品集链接,
  校验起止年月,
  校验预计毕业时间,
  求职初筛缺失项,
  身份首次入口,
  默认求职初筛偏好,
  迁移主要求职类型,
} from './onboarding配置';

describe('多角色 onboarding 合同', () => {
  it('招聘方首次注册直接进招聘名片，注册流程里不含实名认证', () => {
    // 标注 2026-08-20 13:32 定、2026-08-22 再次确认：企业端先不做实名认证。
    // 这条守的是「实名认证不能被重新排回注册流程」，所以除了首屏还要显式断言它不在合同里 ——
    // 只断言首屏的话，把认证插在名片之后仍然能蒙混过关
    expect(身份首次入口('企业')).toBe(路径.招聘名片);
    expect(Onboarding流程.招聘方).toEqual([路径.招聘名片, 路径.发布岗位, 路径.企业主壳]);
    expect(Onboarding流程.招聘方).not.toContain(路径.企业实名认证);
  });

  it('学生路径不会跳过实习经历、技能与证书所在页', () => {
    const 流程 = Onboarding流程.学生求职;
    expect(流程.indexOf(路径.工作经历)).toBeGreaterThan(流程.indexOf(路径.就读时间段));
    expect(流程.indexOf(路径.工作经历)).toBeLessThan(流程.indexOf(路径.求职状态));
  });

  it('学生和社招的配置顺序明确不同', () => {
    expect(Onboarding流程.学生求职).not.toEqual(Onboarding流程.社招求职);
    expect(Onboarding流程.学生求职.indexOf(路径.基本信息)).toBeLessThan(Onboarding流程.学生求职.indexOf(路径.引导问答));
    expect(Onboarding流程.社招求职.indexOf(路径.引导问答薪资段)).toBeLessThan(Onboarding流程.社招求职.indexOf(路径.基本信息));
  });

  it('求职端首屏是完善资料（引导说明页已删）', () => {
    expect(身份首次入口('求职者')).toBe(路径.学生分流);
    expect(Onboarding流程.学生求职[0]).toBe(路径.学生分流);
    expect(Onboarding流程.社招求职[0]).toBe(路径.学生分流);
  });

  it('社招两次进向导登记成两个不同的地址，屏幕才分得清自己是第几次', () => {
    const 流程 = Onboarding流程.社招求职;
    expect(流程.filter((屏) => 屏 === 路径.引导问答薪资段)).toHaveLength(1);
    expect(流程.filter((屏) => 屏 === 路径.引导问答)).toHaveLength(1);
    // 薪资段在补档案之前，偏好段在工作经历之后 —— 顺序反了就说明合同被改坏了
    expect(流程.indexOf(路径.引导问答薪资段)).toBeLessThan(流程.indexOf(路径.工作经历));
    expect(流程.indexOf(路径.引导问答)).toBeGreaterThan(流程.indexOf(路径.工作经历));
    // 学生只进一次向导，且只走偏好段
    expect(Onboarding流程.学生求职).not.toContain(路径.引导问答薪资段);
  });

  it('选择实习时必须补齐时长和每周到岗天数', () => {
    // 断言从三项收到两项：最早可开始实习日期 2026-08-22 已删（它比对的招聘端
    // 「最晚可接受实习开始日期」被产品负责人标注删掉后就没有对面了）。
    // 这条用例守的是「实习方向的必填闸门不能塌」，路径本身还在，所以改断言不删用例
    expect(求职初筛缺失项({ 求职类型: ['实习生'], 办公方式: ['混合'] }, '2026-08-21')).toEqual([
      '可实习月数',
      '每周可到岗天数',
    ]);
    expect(求职初筛缺失项({ 求职类型: ['实习生'], 办公方式: ['混合'], 实习月数: 3, 每周到岗天数: 4 }, '2026-08-21')).toEqual([]);
  });

  it('校招主要方向必须采集预计毕业时间', () => {
    expect(求职初筛缺失项({ 求职类型: ['校园招聘'], 办公方式: ['现场'] }, '2026-08-21')).toContain('预计毕业时间');
    expect(求职初筛缺失项({ 求职类型: ['校园招聘'], 办公方式: ['现场'], 毕业时间: '2027-06' }, '2026-08-21')).toEqual([]);
  });

  it('首次配置只保留一个主要求职类型', () => {
    expect(默认求职初筛偏好(true).求职类型).toEqual(['实习生']);
    expect(默认求职初筛偏好(false).求职类型).toEqual(['社招全职']);
    expect(求职初筛缺失项({ 求职类型: ['校园招聘', '实习生'], 办公方式: ['混合'], 实习月数: 3, 每周到岗天数: 4 })).toContain(
      '一个主要求职类型',
    );
  });

  it('自动迁移旧的多类型缓存，避免月薪与日薪共用一个区间', () => {
    const 旧偏好 = { 求职类型: ['校园招聘', '实习生'] as const, 办公方式: ['混合'] as const };
    expect(迁移主要求职类型({ 求职类型: [...旧偏好.求职类型], 办公方式: [...旧偏好.办公方式] }, '元/天').求职类型).toEqual(['实习生']);
    expect(迁移主要求职类型({ 求职类型: [...旧偏好.求职类型], 办公方式: [...旧偏好.办公方式] }, '月薪K').求职类型).toEqual(['校园招聘']);
  });

  it('初筛合同同时覆盖通用、社招、学生与实习字段', () => {
    expect(Object.keys(初筛字段矩阵)).toEqual(['通用', '社招', '学生', '实习']);
    // 实习档在 2026-08-22 去掉「最早可开始实习日期」，剩下的两项必须还在
    expect(初筛字段矩阵.实习).toEqual(['可实习月数', '每周可到岗天数']);
  });

  it('实习主要方向按日薪采集，其他类型保持月薪', () => {
    expect(判断求职薪资单位({ 求职类型: ['实习生'], 办公方式: ['混合'] })).toBe('元/天');
    expect(判断求职薪资单位({ 求职类型: ['社招全职'], 办公方式: ['现场'] })).toBe('月薪K');
  });

  it('拒绝过期的预计毕业时间，并允许当月', () => {
    // 原来这条还断言 校验未过期日期()。那个函数只有两个调用点（招聘端最晚开始日期 /
    // 求职端最早开始日期），两个字段 2026-08-22 都按产品负责人标注删了，函数随之删除，
    // 相关三行断言一并去掉。预计毕业时间的校验与那两个字段无关，原样守住
    expect(校验预计毕业时间('2026-07', '2026-08-21')).toBe('预计毕业时间不能早于本月');
    expect(校验预计毕业时间('2026-08', '2026-08-21')).toBeNull();
  });

  it('拦住结束早于开始的起止年月，但不误伤「至今」和同月起止', () => {
    // 截图里的教育卡就是这一条：2020.09 入学，2018.06 毕业
    expect(校验起止年月('2020-09', '2018-06', '入学时间', '毕业时间')).toBe(
      '毕业时间不能早于入学时间',
    );
    expect(校验起止年月('2018-06', '2020-09', '入学时间', '毕业时间')).toBeNull();
    // 至今（null）/ 还没填（空串）都是合法状态，不能报错
    expect(校验起止年月('2019-06', null, '入职时间', '离职时间')).toBeNull();
    expect(校验起止年月('2019-06', '', '入职时间', '离职时间')).toBeNull();
    expect(校验起止年月('', '2019-06', '入职时间', '离职时间')).toBeNull();
    // 同月起止合法（只做了一个月的实习）
    expect(校验起止年月('2026-07', '2026-07')).toBeNull();
    // 跨年边界：只差一个月也要判出来
    expect(校验起止年月('2021-01', '2020-12')).toBe('结束时间不能早于开始时间');
    expect(校验起止年月('2020-12', '2021-01')).toBeNull();
    // 格式不对时先报格式，不去做无意义的字符串比较
    expect(校验起止年月('2020-13', '2021-01')).toBe('开始时间格式不正确');
    expect(校验起止年月('2020-01', '2021/01')).toBe('结束时间格式不正确');
  });

  it('作品集链接不再是求职偏好字段，缺失项里不含它', () => {
    // 它已经搬到简历（工作经历屏）。留在这里会变成用户在完善资料屏看不见、
    // 却把「下一步」锁死的隐形门槛
    expect(求职初筛缺失项({ 求职类型: ['社招全职'], 办公方式: ['现场'] }, '2026-08-21')).toEqual([]);
  });

  it('统一并校验作品集链接', () => {
    expect(规范化作品集链接(' github.com/example/project ')).toBe('https://github.com/example/project');
    expect(校验作品集链接('github.com/example/project')).toBeNull();
    expect(校验作品集链接('not-a-link')).toBe('请输入有效的作品集或项目链接');
    expect(校验作品集链接('')).toBeNull();
  });

  it('向导段从地址上读，缺省是偏好段', () => {
    expect(读向导段('salary')).toBe('薪资段');
    expect(读向导段(null)).toBe('偏好段');
    expect(读向导段('')).toBe('偏好段');
    // 路径表登记的薪资段地址必须真能被解析成薪资段，两边不能各写各的
    const 查询 = 路径.引导问答薪资段.split('?')[1] ?? '';
    expect(读向导段(new URLSearchParams(查询).get(向导段参数名))).toBe('薪资段');
  });

  it('向导题序：薪资段只问薪资，偏好段问排除项和个人优势', () => {
    expect(向导题序({ 段: '薪资段', 已有引导预填: true, 在校: false })).toEqual(['期望薪资']);
    expect(向导题序({ 段: '偏好段', 已有引导预填: true, 在校: false })).toEqual(['硬性排除', '个人优势']);
    // 学生只进一次向导，薪资题必须跟着偏好段一起问，否则永远采不到
    expect(向导题序({ 段: '偏好段', 已有引导预填: true, 在校: true })).toEqual([
      '期望薪资',
      '硬性排除',
      '个人优势',
    ]);
  });

  it('没有引导预填时才在向导里补问期望职位与工作城市', () => {
    expect(向导题序({ 段: '薪资段', 已有引导预填: false, 在校: false })).toEqual([
      '期望职位',
      '工作城市',
      '期望薪资',
    ]);
    expect(向导题序({ 段: '偏好段', 已有引导预填: false, 在校: false })).toEqual([
      '期望职位',
      '工作城市',
      '硬性排除',
      '个人优势',
    ]);
  });

  it('题序在任何组合下都非空 —— 游标取不到「没有题」这种状态', () => {
    for (const 段 of ['薪资段', '偏好段'] as const) {
      for (const 已有引导预填 of [true, false]) {
        for (const 在校 of [true, false]) {
          expect(向导题序({ 段, 已有引导预填, 在校 }).length).toBeGreaterThan(0);
        }
      }
    }
  });

  it('向导出口按段分开：薪资段回主干补档案，偏好段才去披露说明', () => {
    // 两段共用一个出口正是「社招第一次进向导两步冲到披露页、跳过 7 屏」的根因
    expect(向导出口('薪资段')).toBe(路径.基本信息);
    expect(向导出口('偏好段')).toBe(路径.披露说明);
  });
});
