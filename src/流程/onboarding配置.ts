/** 段写在 query 上；URL 是对外地址，走 ASCII slug（同 路径表 的既有约定）。 */
export const 向导段参数名 = 'stage';
const 薪资段标记 = 'salary';

export type 向导段 = '薪资段' | '偏好段';
export type 向导题名 = '期望职位' | '工作城市' | '期望薪资' | '硬性排除' | '个人优势';

/** 把 URL 上的 ?stage= 读成段。除薪资段外一律偏好段（含缺省的 #/wizard）。 */
export function 读向导段(查询值: string | null): 向导段 {
  return 查询值 === 薪资段标记 ? '薪资段' : '偏好段';
}

/**
 * 向导这一段要问哪几题，按什么顺序问。
 *
 * 调用方必须在**进屏那一刻算一次然后冻结**：这里的两个入参（已有引导预填 / 在校）
 * 都会被「答题」这个动作本身改写，每次 render 重算就等于用户答一题、题目集合当场变一次，
 * 游标必然对不上（原来的白屏根因）。
 *
 * - 薪资段：社招第一次进向导，只采期望薪资，答完去 基本信息 补档案；
 * - 偏好段：社招第二次进（档案填完回来）/ 学生唯一一次进，问硬性排除 + 个人优势。
 *   学生一次走完全程，所以偏好段对学生要把薪资题一起带上。
 * - 期望职位 / 工作城市 在 完善资料 屏已采过（引导预填非空即代表采过），只有直接
 *   打开 #/wizard、本地没有任何缓存时才需要在向导里补问。
 */
export function 向导题序(参数: {
  段: 向导段;
  已有引导预填: boolean;
  在校: boolean;
}): 向导题名[] {
  const 补问前两题: 向导题名[] = 参数.已有引导预填 ? [] : ['期望职位', '工作城市'];
  if (参数.段 === '薪资段') return [...补问前两题, '期望薪资'];
  // 硬性排除与个人优势两题永远在，所以题序永远非空 —— 游标不会取到「没有题」这种状态
  return [...补问前两题, ...(参数.在校 ? (['期望薪资'] as 向导题名[]) : []), '硬性排除', '个人优势'];
}

/** 这一段答完去哪。薪资段回合同的主干（基本信息），偏好段是注册流最后一段（披露说明）。 */
export function 向导出口(段: 向导段): string {
  return 段 === '薪资段' ? 路径.基本信息 : 路径.披露说明;
}

