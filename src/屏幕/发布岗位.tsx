// ── D0c 第三步：职位要求 + 硬性条件（可增可删，不再是写死的四个片）──
function 职位要求步({
  文本,
  设文本,
  硬性条件: 已选条件,
  添加,
  删除,
  草稿,
  设草稿,
}: {
  文本: string;
  设文本: (值: string) => void;
  硬性条件: string[];
  添加: (项: string) => void;
  删除: (项: string) => void;
  草稿: string;
  设草稿: (值: string) => void;
}) {
  // 已经写进合同的不再出现在备选行里，避免同一条出现两次
  const 可选通用条件 = 通用硬性条件.filter((项) => !已选条件.includes(项));
  const 可添加 = 草稿.trim() !== '' && !已选条件.includes(草稿.trim());

  return (
    <滚动区 样式覆盖={{ paddingBottom: 12 }}>
      <页面大标题
        标题="职位要求"
        说明="要求写给人看，硬性条件交给 AI 代理执行。"
      />

      <div className={样式.描述卡}>
        <textarea
          className={样式.描述输入}
          value={文本}
          onChange={(事件) => 设文本(事件.target.value)}
          maxLength={500}
          aria-label="职位要求"
        />
        <div className={样式.描述底}>
          <span className={`${样式.描述计数} 等宽数字`}>{文本.length} / 500</span>
        </div>
      </div>

      <div className={样式.硬性区}>
        <div className={样式.条目标签}>硬性条件</div>

        {/* 已写进合同的条件：点 ✕ 删掉 */}
        {已选条件.length > 0 ? (
          <div className={样式.已选片行}>
            {已选条件.map((项) => (
              <button
                key={项}
                className={`${样式.已选片} 可点`}
                onClick={() => 删除(项)}
                aria-label={`删除硬性条件 ${项}`}
              >
                {项}
                <span className={样式.已选片删}>✕</span>
              </button>
            ))}
          </div>
        ) : (
          <div className={样式.条件空提示}>
            还没有硬性条件。代理会只按上面的职位要求做软性判断，不做逐条核对。
          </div>
        )}

        {/* 通用备选：点一下加进去 */}
        {可选通用条件.length > 0 ? (
          <>
            <div className={样式.备选标}>常用条件</div>
            <div className={样式.快捷片行}>
              {可选通用条件.map((项) => (
                <button
                  key={项}
                  className={`${样式.快捷片} 可点`}
                  onClick={() => 添加(项)}
                >
                  ＋ {项}
                </button>
              ))}
            </div>
          </>
        ) : null}

        {/* 自定义一条：行业专有条件（Go 主栈、有清结算实战…）都从这里进来 */}
        <div className={样式.自定义行}>
          <input
            className={样式.自定义输入}
            value={草稿}
            placeholder="自定义一条，如：有清结算系统实战"
            maxLength={20}
            onChange={(事件) => 设草稿(事件.target.value)}
            onKeyDown={(事件) => {
              // isComposing 挡住中文输入法「回车上屏候选词」那一下被当成添加
              if (事件.key === 'Enter' && !事件.nativeEvent.isComposing && 可添加) {
                添加(草稿);
                设草稿('');
              }
            }}
            enterKeyHint="done"
          />
          <button
            className={`${样式.自定义键} ${可添加 ? '' : 样式.自定义键禁用} 可点`}
            disabled={!可添加}
            onClick={() => {
              添加(草稿);
              设草稿('');
            }}
          >
            添加
          </button>
        </div>

        <div className={样式.硬性说明}>
          这几条就是 AI 代理在匿名初筛逐条核对的合同 —— 不满足的候选人不会进入下一阶段。
          核对只回「满足 / 不满足」，双方的数值都不披露。
        </div>
      </div>
    </滚动区>
  );
}
