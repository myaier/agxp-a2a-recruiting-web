// R9 招聘名片 · 招聘方注册第二步（实名认证 → 名片 → 发岗）。
//
// 同构源：添加意向.tsx（表单条目版式 + 底部编辑抽屉）。
//
// 业务口径：这张名片是「候选人在谈判里看到的你」—— 双盲的不对称面：
// 候选人在意向确认前只有代号，招聘方从一开始就实名示人。
// 「公司」是上一步实名认证核验过的结果，带「已认证」徽标，
// 本屏不可修改（要改得重新走认证），点它给轻提示而不是死按钮。
//
// 交互：姓名 / 职务点开升起底部编辑抽屉（镜像 A21）；
// 「对候选人的一句话」是页面内直接编辑的多行输入。

import { useState } from 'react';
import 样式 from './招聘名片.module.css';
import {
  次级页外壳,
  返回栏,
  页面大标题,
  滚动区,
  表单条目,
  主按钮,
} from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 企业信息 } from '../数据/企业端模拟数据';

/** 可在抽屉里编辑的两个字段（公司已认证锁死，不入此表） */
type 表单键 = '姓名' | '职务';

const 表单字段表: { 键: 表单键; 标签: string }[] = [
  { 键: '姓名', 标签: '姓名' },
  { 键: '职务', 标签: '职务' },
];

/** 表单初值：姓名取企业模拟数据（邵铭），职务为设计稿 R9 预填值 */
const 表单初值: Record<表单键, string> = {
  姓名: 企业信息.认证人,
  职务: '技术 VP',
};

/** 设计稿 R9 预填的一句话 */
const 一句话初值 = '交易网关 0→1，团队 8 人，直接向我汇报。';

export default function 招聘名片() {
  const { 跳转, 返回 } = use导航();

  const [表单值, 设表单值] = useState<Record<表单键, string>>(表单初值);
  const [一句话, 设一句话] = useState(一句话初值);
  // 正在编辑哪个字段（null = 抽屉关着）
  const [编辑中, 设编辑中] = useState<表单键 | null>(null);
  // 抽屉草稿：确认前不写回表单，取消就丢掉
  const [草稿, 设草稿] = useState('');

  const 编辑中字段 = 表单字段表.find((字段) => 字段.键 === 编辑中);

  // 打开抽屉时把现值灌进草稿，用户看到的是「改」而不是「重填」
  function 打开编辑(键: 表单键) {
    设编辑中(键);
    设草稿(表单值[键]);
  }

  // 确认：空白视作没改（不允许把字段清空成空串，否则表单条目会塌成空行）
  function 确认编辑() {
    if (编辑中 === null) return;
    const 新值 = 草稿.trim();
    if (新值) 设表单值((旧) => ({ ...旧, [编辑中]: 新值 }));
    设编辑中(null);
  }

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题 标题="招聘名片" 说明="候选人在谈判里看到的你。" />

      <滚动区 样式覆盖={{ padding: '6px 22px 0' }}>
        {/* ── 姓名 / 职务：点开升起编辑抽屉 ── */}
        {表单字段表.map((字段) => (
          <表单条目
            key={字段.键}
            标签={字段.标签}
            值={表单值[字段.键]}
            按下={() => 打开编辑(字段.键)}
          />
        ))}

        {/* ── 公司：实名认证核验结果，带徽标、本屏不可改 ── */}
        <表单条目
          标签="公司"
          值={企业信息.公司}
          徽标="已认证"
          按下={() => 轻提示('公司已实名核验，如需变更请重新认证')}
        />

        {/* ── 对候选人的一句话：页面内直接编辑的多行输入 ── */}
        <div className={样式.一句话区}>
          <span className={样式.一句话标签}>对候选人的一句话</span>
          <textarea
            className={样式.一句话输入}
            value={一句话}
            rows={3}
            onChange={(事件) => 设一句话(事件.target.value)}
            placeholder="一句话说清这个岗位为什么值得来"
          />
        </div>
      </滚动区>

      <主按钮 文字="保存 · 去发岗位" 按下={() => 跳转(路径.发布岗位)} />

      {/* ── 编辑抽屉（镜像 添加意向）：点遮罩或确认都关掉 ── */}
      {编辑中字段 ? (
        <>
          <div className={样式.遮罩} onClick={() => 设编辑中(null)} />
          <div className={样式.抽屉}>
            <div className={样式.抽屉头}>
              <span className={样式.抽屉标题}>{编辑中字段.标签}</span>
            </div>
            <input
              className={样式.抽屉输入}
              value={草稿}
              autoFocus
              onChange={(事件) => 设草稿(事件.target.value)}
              onKeyDown={(事件) => {
                // isComposing 挡住中文输入法「回车上屏候选词」那一下被误当确认
                if (事件.key === 'Enter' && !事件.nativeEvent.isComposing) 确认编辑();
              }}
              enterKeyHint="done"
            />
            <主按钮 文字="确定" 按下={确认编辑} />
          </div>
        </>
      ) : null}
    </次级页外壳>
  );
}
