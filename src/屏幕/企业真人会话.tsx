// D12·A 会话详情 · 真人接管（企业端）—— 同构镜像求职端 A19 真人会话。
// 意向确认后 AI 代理退场，招聘方与候选人（沈亦舟）直聊面试落地。候选人真名与联系方式
// 在 S1 简历原件递交时已对招聘方可见，意向确认只表示双方同意进入真人沟通。
//
// 结构：返回栏（居中标题 + ⋯）→ 顶部操作排（看简历 / 电话 / 微信）→
// 已确认意向的职位摘要卡 → 消息流（含代理提醒与日期分隔）→ 真输入条（深绿边 + ◈）。
//
// 气泡、联系卡与自动滚到底都复用 直聊会话.tsx 导出的共用件，
// 样式同样引 直聊会话.module.css —— 与求职端的消息流必须像素一致，所以不另写一份。
//
// 顶部操作排与求职端 A19 互为镜像：那边主项是「看职位」，这边是「看简历」。

import { useState } from 'react';
import { useParams } from 'react-router-dom';
import 样式 from './企业真人会话.module.css';
import 共用样式 from './直聊会话.module.css';
import { 消息条, use自动滚到底 } from './直聊会话';
import { 简历纸身 } from '../组件/简历预览层';
import 真人会话操作栏 from './真人会话操作栏';
import { 次级页外壳, 返回栏, 滚动区, 真输入条 } from '../组件/通用';
import { 简历图标 } from '../组件/图标';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';
import { 企业真人会话 as 会话数据, 候选简历原件表 } from '../数据/企业端模拟数据';
import Backend真人会话, { 会话不可用 } from './P7/Backend真人会话';
import type { 会话条 } from '../数据/类型';

// 标注 2026-08-20 09:36/09:42：电话/微信/简历在 S1 原件递交后即对招聘方可见；面试邀约先不做。
// 2026-08-22：原先钉在消息流顶部的两张联系卡整块挪进顶部操作排的展开区 ——
// 组件与复制逻辑没换，只换了位置。留在流里会和顶部那排讲同一件事两遍，
// 而它本来就钉在流顶（在日期分隔条之前），已经不在时间轴上、不带任何时间信息；
// 「联系方式在 S1 原件递交时已可见」由职位卡归档行（15:22 意向确认）继续承担。

/**
 * P7 Task 4：模式/参数双开关（镜像求职端 真人会话.tsx）—— Backend 且带
 * conversationId 时交给 P7 Backend 真人会话（recruiter）；Backend 访问无参路由
 * fail closed 成「会话不可用」，绝不读默认 A-01；Mock 保留真名/联系方式剧情。
 */
export default function 企业真人会话() {
  const { 数据源模式 } = use应用状态();
  const { conversationId } = useParams();
  if (数据源模式 === 'backend') {
    if (conversationId === undefined) return <会话不可用 />;
    // review-r3：按会话坐标 key 重挂（镜像求职端 真人会话.tsx）。
    return <Backend真人会话 key={conversationId} role="recruiter" conversationId={conversationId} />;
  }
  return <Mock企业真人会话 />;
}

function Mock企业真人会话() {
  // 双盲门控：对方名从全局状态派生 —— A-01 未确认意向时显示代号，确认后显示真名
  const { 状态 } = use应用状态();
  const A01 = 状态.企业候选列表.find((条) => 条.编号 === 'A-01');
  const 对方显示名 = A01?.真名 ?? A01?.代号 ?? 会话数据.对方名;
  const { 返回, 跳转 } = use导航();
  const [消息, 设消息] = useState<会话条[]>(会话数据.消息);
  const [草稿, 设草稿] = useState('');
  const 底部锚 = use自动滚到底(消息);

  // 发送：草稿去空后追加到本地消息流（真人页的消息不带时间戳，与同构源一致）
  const 发送 = () => {
    const 内容 = 草稿.trim();
    if (!内容) return;
    const 新条: 会话条 = { 编号: Date.now(), 角色: '我', 内容 };
    设消息((旧) => [...旧, 新条]);
    设草稿('');
  };

  return (
    <次级页外壳 对话底 白底>
      <返回栏
        返回={返回}
        标题={对方显示名}
        副标题={会话数据.对方描述}
        居中标题
        右侧={<span className={共用样式.更多}>⋯</span>}
      />

      {/* 顶部操作排：主项「看简历」盖一层全屏，路由不动、返回栈不加深，
          「继续沟通」关掉层就回到聊天。
          层里铺的是**简历原件**（候选专属投影 = 该候选人自己的真名 / 联系方式 / 履历）——
          标注 2026-08-23：「这个点击看简历指的是用户的正式简历，一般都是 PDF 那种正式简历。
          不是这个」。之前铺的是 app 内生成的在线简历页，接错了对象。
          真名在 S1 原件递交时已写入，这里读取候选专属投影而不是求职端全局简历，
          避免所有候选的 PDF 都渲染成沈亦舟。未披露时传代号走打码分支。 */}
      {(() => {
        const A01原件 = A01?.真名 ? 候选简历原件表['A-01'] : undefined;
        return (
          <真人会话操作栏
            主项名="看简历"
            主项图标={<简历图标 尺寸={18} 色="#3f7a1f" />}
            主项内容={
              <简历纸身
                候选原件={A01原件}
                原件={A01原件 !== undefined}
                代号={A01?.代号 ?? ''}
              />
            }
            联系方式={会话数据.联系方式}
          />
        );
      })()}

      <滚动区>
        <div className={`${共用样式.消息流} ${共用样式.消息流上留白}`}>
          {/* 沈亦舟 = A-01 陈屿（意向已确认），「查看 ›」回到该候选的详情页 */}
          <职位卡 查看={() => 跳转(路径.候选详情('A-01'))} />

          {消息.map((条) => (
            <消息条 key={条.编号} 条={条} 对方首字="沈" />
          ))}

          <div ref={底部锚} />
        </div>
      </滚动区>

      <真输入条
        占位="输入消息…"
        值={草稿}
        改变={设草稿}
        发送={发送}
        右侧图标={<span className={样式.代理符}>◈</span>}
      />
    </次级页外壳>
  );
}

// ── 顶部职位摘要卡：意向已确认，谈判档案归档，「查看 ›」回到该候选的详情 ──
// 薪资一栏是岗位自己的带（50-65K · 15 薪），不是报价 —— 双盲不谈薪。
function 职位卡({ 查看 }: { 查看: () => void }) {
  const 卡 = 会话数据.职位卡;
  return (
    <div className={样式.职位卡}>
      <div className={样式.职位卡头行}>
        <div className={`${样式.职位卡标题} 单行`}>{卡.职位}</div>
        <span className={`${样式.职位卡薪资} 等宽数字`}>{卡.薪资}</span>
      </div>
      <div className={样式.职位卡条件}>{卡.条件行}</div>
      <div className={样式.职位卡底}>
        <div className={`${样式.职位卡归档} 单行`}>{卡.归档行}</div>
        <button className={`${样式.职位卡链接} 可点`} onClick={查看}>
          查看 ›
        </button>
      </div>
    </div>
  );
}
