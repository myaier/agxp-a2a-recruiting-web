// A4 披露偏好 · 完成即就绪 —— 「谈判怎么推进？」
//
// 核心信息是「分阶段披露」：AI 代理按四个阶段替你推进，
// 每进一步才多亮一层信息，所以每行徽标用对应阶段的主题色，跟在谈卡的阶段标签同色系。
//
// 2026-08-20 按 BOSS 截图顺序重排：本屏不再是注册流末屏，继续键改跳
// /onboard/avatar 添加头像 —— 清注册流历史的 replace 跳转挪去头像屏做。

import 样式 from './披露说明.module.css';
import { 次级页外壳, 返回栏, 主按钮, 滚动区, 阶段配色 } from '../组件/通用';
import 代理标 from '../组件/代理标';
import { 披露四阶段 } from '../数据/模拟数据';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

export default function 披露说明() {
  const { 返回, 跳转 } = use导航();

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <div className={样式.头部}>
        <h1 className={样式.大标题}>AI代理如何帮你找工作</h1>
        <p className={样式.说明}>
          条件先对，对上了才多给一层 —— 不用一开始就交底，也不用把时间花在聊不成的岗位上。
        </p>
      </div>

      {/* 只有这一段允许滚动：标题、就绪条、主按钮都固定，
          阶段数以后变多也只是这一块变长，底部结论区不会被顶出屏幕。 */}
      <滚动区 样式覆盖={{ padding: '12px 18px 0' }}>
        <div className={样式.卡}>
          {披露四阶段.map((段) => {
            // 徽标底色/字色统一取自 阶段配色，不在本屏另起一套颜色
            const 配色 = 阶段配色[段.编号];
            return (
              <div key={段.编号} className={样式.阶段行}>
                <span
                  className={样式.阶段徽标}
                  style={{ background: 配色.底, color: 配色.文字 }}
                >
                  {段.编号}
                </span>
                <div className={样式.阶段文字组}>
                  <div className={样式.阶段名}>{段.名称}</div>
                  <div className={样式.阶段说明}>{段.说明}</div>
                </div>
              </div>
            );
          })}
        </div>
      </滚动区>

      {/* 就绪条：把「点下面这颗按钮就生效」这件事说在按钮上方，而不是塞进按钮文案 */}
      <div className={样式.就绪条}>
        <span className={样式.盾牌底}>
          <代理标 尺寸={30} 脸色="#ffffff" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
        </span>
        <div className={样式.就绪文字}>完成后，AI代理将按这些条件开始匹配和初筛</div>
      </div>

      <主按钮 文字="完成设置，开始匹配" 按下={() => 跳转(路径.添加头像)} />
    </次级页外壳>
  );
}
