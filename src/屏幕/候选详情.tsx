// ── 弹层文案：必须带这一单的真实上下文（代号 + 卡点项 + 差值），不能用写死的示例句 ──
function 算决策文案(候: 候选, 类型: '接受' | '终止'): { 决定文案: string; 规则草案: string } {
  // 卡点项名从「对方要每周 2 天远程…」「主栈 Java 非 Go…」这类下一步文案里抠关键词。
  // 关键词只覆盖软性要求与硬性资历 —— 薪资与到岗不在代理谈判范围内（产品边界 2026-08-18）
  const 卡点项名 =
    /(远程|办公|作息|双休|大小周|加班|出差|团队|汇报|主栈|技术栈|年限|学历)/.exec(候.下一步)?.[1] ??
    '这一项';
  // '差 15 天' → '15 天'；「域对口」这类非数字差值不做净值拼接
  const 差值净 =
    候.分歧 && /^差\s*/.test(候.分歧.差值) ? 候.分歧.差值.replace(/^差\s*/, '') : null;
  // 差值末尾是英文单位（2K）时后面补一个空格，中文单位（15 天）时不补 —— 中英混排间距
  const 差值短语 = 差值净 ? (/[a-zA-Z]$/.test(差值净) ? `${差值净} ` : 差值净) : '';
  const 卡点描述 = 差值净 ? `在「${卡点项名}」上差 ${差值净}` : `在「${卡点项名}」这一项有分歧`;

  return 类型 === '终止'
    ? {
        // 代号已是中文昵称（陈屿），直接与后文相接，不再需要中英混排空格
        决定文案: `${候.代号}${卡点描述}，你选择不放宽 —— AI代理已终止接触并归档，不再消耗接触额度。`,
        规则草案: 差值净
          ? `${卡点项名}差超过 ${差值短语}的候选，直接终止，不用先问我`
          : `触到${卡点项名}这条线的候选，直接终止，不用先问我`,
      }
    : {
        决定文案: `${候.代号}${卡点描述}，你同意放宽 —— AI代理会立刻回报对方，等候选人确认意向。`,
        规则草案: 差值净
          ? `${卡点项名}差 ${差值短语}以内的候选，可以直接替我放宽`
          : `${卡点项名}这类域对口的分歧，可以直接替我放宽`,
      };
}

export default function 候选详情() {
  const { id: 编号 = '' } = useParams<{ id: string }>();
  const { 状态, 派发 } = use应用状态();
  const { 跳转, 返回 } = use导航();

  const [当前Tab, 设当前Tab] = useState<页内Tab>('谈判进度');
  const [弹层可见, 设弹层可见] = useState(false);
  // 递交简历段的 PDF 附件（标注 09:23）：看的是收到的匿名版原件
  const [看简历, 设看简历] = useState(false);
  const [决策快照, 设决策快照] = useState<决策快照内容 | null>(null);

  // 进入页面自动定位到当前需要行动的阶段段（与求职端同构）
  const 当前节点引用 = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const 定时 = window.setTimeout(() => {
      当前节点引用.current?.scrollIntoView({ block: 'start', behavior: 'smooth' });
    }, 120);
    return () => window.clearTimeout(定时);
  }, []);

  // 「终止」会把这位候选从在谈列表里移除（归档），页面必须留一份快照，
  // 否则用户点完「不合适 · 终止」整屏会瞬间跳成已归档提示，看不到决策回执。
  const 列表内候选 = 状态.企业候选列表.find((条) => 条.编号 === 编号);
  const [快照候选, 设快照候选] = useState<候选 | null>(列表内候选 ?? null);
  useEffect(() => {
    if (列表内候选) 设快照候选(列表内候选);
  }, [列表内候选]);
  const 候 = 列表内候选 ?? 快照候选;

  // 协调阶段的决策来自全局状态，跨屏可见（人才页那张卡会跟着变）
  const 协调决策: '接受' | '终止' | null = 状态.候选决策[编号] ?? null;

  // 叮嘱：就地输入，落全局 叮嘱表（按候选编号归档），产物接在写下它的那个阶段流末尾
  const [叮嘱草稿, 设叮嘱草稿] = useState('');
  const 本候叮嘱 = 状态.叮嘱表[编号] ?? [];
  const 发叮嘱 = () => {
    const 内容 = 叮嘱草稿.trim();
    if (内容 === '' || !候) return;
    // 带上写下这句话时所处的阶段：之后推进到下一阶段，这条话仍留在原来那一段流里
    派发({ 型: '加叮嘱', 归属: 编号, 文本: 内容, 序号: 本候叮嘱.length + 1, 写于阶段: 候.阶段 });
    设叮嘱草稿('');
  };

  // 直接进 URL 但这位候选从来不存在（或刷新后状态已丢）时的兜底
  if (!候) {
    return (
      <次级页外壳>
        <返回栏 返回={返回} 标题="这位候选已归档" />
        <div className={样式.已归档区}>
          这位候选已不在「在谈」列表里。
          <br />
          可能你选择了终止，AI代理已停止接触并归档，不再消耗接触额度。
        </div>
      </次级页外壳>
    );
  }

  const 已完成阶段 = 候选阶段小结[编号] ?? [];
  const 当前阶段序 = 阶段顺序.indexOf(候.阶段);

  // 「候选确认意向」后 reducer 会写入真名（A-01 → 沈亦舟）并把辅助文案改成
  // 「去消息页私聊」，用这两个信号判断意向节点是「等你确认」还是「已互换」
  const 意向已确认 =
    候.阶段 === '意向确认' && (候.真名 !== null || 候.辅助文案 === '去消息页私聊');

  // 协调节点在两种情况下要渲染：① 还卡着等你拍板；② 已经拍了（要显示回执，不能凭空消失）
  const 显示协调节点 = (候.阶段 === '需要协调' && 候.需要你) || 协调决策 !== null;


  // 决策落地：先把卡点上下文冻结成快照，再写全局状态（人才页那张卡同步变），最后升起
  // 「要我记住这个判断吗」弹层。顺序不能颠倒 —— reducer 的「候选接受方案」会清掉 分歧、
  // 改写 下一步，派发之后再算文案就只剩空壳（会出现「这一项差 以内的」这种残句）。
  const 做协调决策 = (类型: '接受' | '终止') => {
    设决策快照({ 分歧: 候.分歧, ...算决策文案(候, 类型) });
    派发(类型 === '接受' ? { 型: '候选接受方案', 编号 } : { 型: '候选终止', 编号 });
    设弹层可见(true);
  };

  // ── 谈判进度：把四个阶段摊成一条对话流的分段数据（与求职端同构）──────────
  const 小结表 = new Map<阶段, 阶段小结>(已完成阶段.map((段) => [段.阶段, 段]));
  const 本候对话 = 各候选阶段对话[编号] ?? {};

  const 分段们: 分段项[] = 阶段顺序.map((名, 序) => {
    const 段小结 = 小结表.get(名);
    const 对话 = 本候对话[名];
    const 态: 分段项['态'] =
      序 < 当前阶段序 ? '已完成' : 序 === 当前阶段序 ? '当前' : '未到达';

    // 状态胶囊：协调阶段拍过板就说结果，其余走小结自带的状态
    const 状态文 =
      名 === '需要协调' && 协调决策
        ? 协调决策 === '接受'
          ? '已放宽'
          : '已终止'
        : 名 === '需要协调' && 态 === '当前'
          ? '需要你'
          : 名 === '意向确认' && 态 === '当前'
            ? 意向已确认
              ? '已确认'
              : '需要你'
            : (段小结?.状态 ?? (态 === '已完成' ? '通过' : '进行中'));

    return {
      阶段: 名,
      态,
      状态文: 态 === '未到达' ? null : 状态文,
      // 当前阶段没有剧本小结时，退回卡片上的下一步文案，段内不至于空着
      // 代理小结只属于「已经聊完、推进到下一阶段」的段（用户 2026-08-20）：
      // 进行中的阶段还没有结论，不摆小结块；卡住的阶段结论由决策卡自己带一行
      小结: 态 === '已完成' ? (段小结?.小结 ?? null) : null,
      核对清单: 态 === '已完成' ? 段小结?.核对清单 : undefined,
      // 递交简历段没有对话数据时，仍要给出收到的那份匿名简历原件
      附件:
        名 === '递交简历' && !对话?.length && 态 !== '未到达'
          ? { 文件名: `${候.代号}_简历.pdf` }
          : null,
      对话,
      // 进往来记录的那类链接在本次重构里去掉了（对话已经在流里），只留就地切 Tab 的
      小链接: 段小结?.链接 && !段小结.链接.includes('往来') ? 段小结.链接 : null,
      // 按「写下时所在的阶段」归段，不按当前阶段 —— 否则谈判一推进，旧话会整批跳到新段
      用户气泡: 本候叮嘱.filter((条) => 条.写于阶段 === 名),
      待推进说明:
        名 === '意向确认'
          ? '双方确认即互换联系方式，直接进入私聊'
          : '前一阶段通过后 AI 代理自动推进',
      空说明: '已通过 · AI代理自动推进',
      默认展开: 名 === '需要协调' && 协调决策 !== null ? true : undefined,
      尾部:
        名 === '需要协调' && 显示协调节点 ? (
          <协调决策卡
            候={候}
            分歧={候.分歧 ?? 决策快照?.分歧 ?? 状态.候选决策快照[编号] ?? null}
            决策={协调决策}
            接受={() => 做协调决策('接受')}
            终止={() => 做协调决策('终止')}
          />
        ) : 名 === '意向确认' && 候.阶段 === '意向确认' ? (
          <意向确认卡
            已确认={意向已确认}
            真名行={`已互换：候选人是 ${候.真名 ?? 候.代号}`}
            确认={() => {
              // 标注 18:44：确认即直达私聊，不让用户再点一次
              派发({ 型: '候选确认意向', 编号 });
              跳转(路径.企业真人会话);
            }}
            去私聊={() => 跳转(路径.企业真人会话)}
          />
        ) : undefined,
    };
  });

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        标题={候.真名 ?? 候.代号}
        副标题={候.画像}
        右侧={
          <span className={样式.匹配组}>
            <span className={样式.匹配标}>匹配</span>
            <span
              className={`${样式.匹配分} ${候.匹配分 < 80 ? 样式.匹配分警示 : ''} 等宽数字`}
            >
              {候.匹配分}
            </span>
          </span>
        }
      />

      {/* 两个 Tab：本地状态切换，不走路由（同一屏的两种视图，返回键不该退到上一个 Tab）*/}
      <div className={样式.Tab行}>
        {(['谈判进度', '在线简历'] as 页内Tab[]).map((名) => (
          <button
            key={名}
            className={`${样式.Tab} ${当前Tab === 名 ? 样式.Tab选中 : 样式.Tab未选} 可点`}
            onClick={() => 设当前Tab(名)}
          >
            {名}
          </button>
        ))}
      </div>

      {当前Tab === '谈判进度' ? (
        <滚动区>
          {/* 一条流：阶段分节条 → 该阶段双方代理对话 → 你的话 → 决策卡 */}
          <阶段对话流
            分段们={分段们}
            当前段引用={当前节点引用}
            点附件={() => 设看简历(true)}
            点链接={() => 设当前Tab('在线简历')}
          />
        </滚动区>
      ) : (
        <在线简历Tab 候={候} />
      )}

      {/* 底部就地输入（与求职端在谈详情同构）：写下的话挂到当前阶段节点下 */}
      <真输入条
        占位={
          候.阶段 === '需要协调' && 候.需要你
            ? '你的条件是什么？直接告诉代理'
            : '有想法就告诉你的AI代理'
        }
        值={叮嘱草稿}
        改变={设叮嘱草稿}
        发送={发叮嘱}
      />

      {/* 拿不准 → 记成规则：只在协调决策后升起；意向确认没有可沉淀的分歧项。
          弹层组件的决策类型只认求职端的 '退出'，企业侧的 '终止' 映射过去 */}
      <拿不准弹层
        可见={弹层可见}
        关闭={() => 设弹层可见(false)}
        决策类型={协调决策 === '终止' ? '退出' : 协调决策}
        决定文案={决策快照?.决定文案}
        规则草案={决策快照?.规则草案}
        记成规则={(内容: string) => {
          派发({
            型: '企业新增规则',
            内容: 内容 || 决策快照?.规则草案 || 候.下一步,
            来源: `来自「${候.代号}」单的决策`,
          });
          设弹层可见(false);
          跳转(路径.企业代理设置);
        }}
      />
      {看简历 ? (
        <简历预览层
          文件名={`${候.代号}_简历.pdf`}
          匿名代号={候.代号}
          关闭={() => 设看简历(false)}
        />
      ) : null}
    </次级页外壳>
  );
}

// ── D5·C 需要协调 · 卡点决策卡：小结 + 数字对比 + 方案条 + 不接受 / 接受双按钮 ──
// 位置在「需要协调」这一段对话流的末尾 —— 代理聊到哪儿卡住，卡片就长在哪儿。
function 协调决策卡({
  候,
  分歧: 差额,
  决策,
  接受,
  终止,
}: {
  候: 候选;
  /** 由调用方给：当前分歧，接受后退回决策前的快照 */
  分歧: 分歧 | null;
  决策: '接受' | '终止' | null;
  接受: () => void;
  终止: () => void;
}) {
  return (
    <>
      <小结托盘 标签="">
        <div className={样式.小结正文}>
          {/* A-01（沈亦舟）用设计稿定稿小结；其余候选退回卡片上的辅助文案 */}
          {候.编号 === 'A-01' ? 卡点小结A01 : 候.辅助文案 ?? 候.下一步}
        </div>
      </小结托盘>

      {/* 数字对比：双方条件在这一阶段已可披露，直接把差额摊开给你看 */}
      {差额 ? (
        <div className={样式.数字对比}>
          <div className={样式.对比列}>
            <span className={样式.对比标}>岗位条件</span>
            <span className={`${样式.对比值} 等宽数字`}>{差额.我方}</span>
          </div>
          <div className={样式.对比差}>
            <span className={`${样式.对比差值} 等宽数字`}>{差额.差值}</span>
          </div>
          <div className={`${样式.对比列} ${样式.对比列右}`}>
            <span className={样式.对比标}>候选条件</span>
            <span className={`${样式.对比值} 等宽数字`}>{差额.对方}</span>
          </div>
        </div>
      ) : null}

      {决策 ? (
        <div className={样式.决策回执}>
          {决策 === '接受'
            ? '已告知AI代理：接受该方案，它会回报对方，等候选人确认意向。'
            : '已告知AI代理：终止这一单，不再消耗接触额度。'}
        </div>
      ) : (
        <>
          {/* 方案条（标注 00:12）：条款放上面说清，按钮只留动作 */}
          {候.方案 ? (
            <div className={样式.方案条}>
              <span className={样式.方案标}>方案</span>
              <span className={样式.方案值}>{候.方案}</span>
            </div>
          ) : null}
          <div className={样式.决策行}>
            <button className={`${样式.次按钮} 可点`} onClick={终止}>
              {企业卡点决策.退出按钮}
            </button>
            <button className={`${样式.主小按钮} 可点`} onClick={接受}>
              接受
            </button>
          </div>
          <div className={样式.决策尾注}>{企业卡点决策.尾部说明}</div>
        </>
      )}
    </>
  );
}

// ── D5·C 意向确认卡：确认后会发生什么（不可撤回，所以先把后果讲清）─────────
function 意向确认卡({
  已确认,
  真名行,
  确认,
  去私聊,
}: {
  已确认: boolean;
  /** 已互换后的揭晓行：「已互换：候选人是 沈亦舟」 */
  真名行: string;
  确认: () => void;
  去私聊: () => void;
}) {
  return (
    <>
      <div className={样式.节点说明}>
        {已确认 ? 真名行 : '条件已回报一致，等你先确认意向。'}
      </div>

      <小结托盘 标签="确 认 后 会 发 生 什 么">
        {企业意向确认说明.map((条) => (
          <div key={条} className={样式.要点行}>
            <span className={样式.要点符}>·</span>
            <span className={样式.要点文字}>{条}</span>
          </div>
        ))}
      </小结托盘>

      {已确认 ? (
        <button className={`${样式.主小按钮} ${样式.整宽} 可点`} onClick={去私聊}>
          继续私聊 ›
        </button>
      ) : (
        <button className={`${样式.主小按钮} ${样式.整宽} 可点`} onClick={确认}>
          确认意向 · 等候选人点头
        </button>
      )}
    </>
  );
}


// ── D11·A 在线简历 Tab：与独立屏（匿名在线简历）共用同一份简历正文组件 ──
// 确认意向后（候.真名 非空）脱敏段自动还原实名，与 A-01=沈亦舟 剧情闭环。
function 在线简历Tab({ 候 }: { 候: 候选 }) {
  const 档 = 匿名简历表[候.编号] ?? 匿名简历表[候.编号.split('@')[0]];
  if (!档) {
    return (
      <滚动区>
        <div className={样式.简历列}>
          <div className={样式.隐去条}>这位候选的简历还没同步过来，当前仅有画像：{候.画像}</div>
        </div>
      </滚动区>
    );
  }
  return (
    <滚动区>
      <简历正文 档={档} 已确认={候.真名 !== null} />
    </滚动区>
  );
}
