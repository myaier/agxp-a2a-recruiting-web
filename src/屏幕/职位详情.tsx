// 内容顺序：职位名 + 薪资 → 标签（含发布于）→ 匹配度分析 → JD → 公司(加厚) → 发布人。
// 2026-08-26 用户指定:发布人挪到公司之下(先认识公司,再认识人);公司区块参考
