/** 深链/导航写入 history.state 的有限来源标记（只认看市场这一种来路）。 */
type 候选职位来源状态 = { 来源?: 'candidate-market' };

/** Backend 分支（P4）：只吃候选岗位快照 / 详情缓存 / 单个 CandidateJob GET 的权威数据。 */
function Backend职位详情() {
  const { id: 编号 } = useParams<{ id: string }>();
  const { 状态, 派发, 后端状态, 操作 } = use应用状态();
  const { 返回, 跳转, 替换跳转 } = use导航();
  const 位置 = useLocation();
  // 来路只认显式标记的看市场：没有标记（直链/刷新）就绝不盲退栈
  const 来源 = (位置.state as 候选职位来源状态 | null)?.来源;

  // 安全返回：来路可信（来源标记 + 本会话内真的从看市场跳过来，内存证据随刷新归零，
  // 刷新残留的标记不能算数）且 history 确实有上一格才退栈；否则把主壳的「职位 → 看市场」
  // 状态摆好再原地替换进主壳 —— 直链/刷新链用户按返回永远落回市场列表，而不是退出一格
  // 空白（或被浏览器弹出站外）。不做 document.referrer、不做 navigate(-1) 猜测。
  const 安全返回 = () => {
    const 当前格 = (window.history.state as { idx?: number } | null)?.idx;
    if (
      来源 === 'candidate-market' && 有会话内看市场来路()
      && typeof 当前格 === 'number' && 当前格 > 0
    ) {
      // 退栈前先把主壳归一到「职位 → 看市场」：来源标记承诺的是回到市场，而用户可能
      // 返回→切在谈→前进 回到本详情，裸退栈会落在他后来选的子视图上。常规来路下
      // 这两次派发与现状相同，是幂等 no-op。
      派发({ 型: '切Tab', Tab: '职位' });
      派发({ 型: '切子视图', 子视图: '看市场' });
      返回();
      return;
    }
    派发({ 型: '切Tab', Tab: '职位' });
    派发({ 型: '切子视图', 子视图: '看市场' });
    替换跳转(路径.主壳);
  };

  // 「⋯」拉起的更多操作抽屉是否展开
  const [抽屉展开, 设抽屉展开] = useState(false);
  // 详情读取的非 404 错误文案（404 走统一不可用页，不进这里）
  const [读取错误, 设读取错误] = useState<string | null>(null);
  // 反馈/委托写进行中：并发写会被操作层单飞丢弃，动作键统一禁用防静默丢点击
  const [写中, 设写中] = useState(false);
  // P8 举报层（从更多操作抽屉里进；target 只认 视图.jobId 的权威 job_id）
  const [举报层开, 设举报层开] = useState(false);
  // 本次要委托的捕获（P5）：一份附件走 确认层 点名该文件；确认层只在它非空时挂载，
  // 取消即清、确认后立刻清 —— 上一次的披露授权绝不复用
  const [待确认视图, 设待确认视图] = useState<{ 视图: P4候选岗位页面; 选择: 附件简历选择值 } | null>(null);
  // 多份附件走 附件简历选择层：捕获待选的卡与权威库行，取消 / 确认即清
  const [待选择视图, 设待选择视图] = useState<{ 视图: P4候选岗位页面; 文件们: readonly BFF附件简历[] } | null>(null);

  // 进屏先注册可见范围（操作层栅栏要靠它对上），离开即清，别让别的屏背上旧范围
  useEffect(() => {
    if (!编号) return;
    操作.设置发现推荐范围('candidate', P4范围键.候选详情(编号));
    return () => 操作.设置发现推荐范围('candidate', null);
  }, [编号, 操作]);

  // 委托准备的代际栅栏（评审 R2）：权威附件库的读取是异步的，回来时用户可能已
  // 换岗位路由（编号）或离开详情 —— 每次卸载与 scope 变化都让代际 +1，迟到的结果
  //（含拒绝）对不上代际就整体静默作废，绝不跨 scope 弹层/提示/跳转。
  // 代际只在 effect 里动：StrictMode 的 setup→cleanup→setup 不会把它永久关死。
  const 准备代际引用 = useRef(0);
  useEffect(() => () => { 准备代际引用.current += 1; }, []);
  useEffect(() => {
    准备代际引用.current += 1;
    // scope 变化即作废已捕获的弹层状态：旧岗位的确认层/举报层绝不在新岗位下出现
    设待确认视图(null);
    设待选择视图(null);
    设举报层开(false);
  }, [编号]);

  // 推荐坐标只认当前意向那一份快照（编号载体，同 看市场）：同一 job_id 可能同时躺在
  // 多个意向的缓存 scope 里，扫全表会借到别的意向的 intention_id + recommendation_id。
  // 当前意向缺位或这份快照里没有该岗位 → 推荐卡 为 null，退回权威详情直取（反馈与委托
  // 在那条路径上本就禁用），绝不猜坐标。
  const 当前意向编号 = 状态.当前意向编号 ?? null;
  const 当前意向快照 = 当前意向编号 === null
    ? undefined
    : 后端状态.候选岗位推荐?.[当前意向编号];
  const 推荐卡 = useMemo(() => {
    if (!编号 || 当前意向编号 === null) return null;
    return 当前意向快照?.items.find((卡) => 卡.job.job_id === 编号) ?? null;
  }, [当前意向快照, 编号, 当前意向编号]);

  // 直链深链进详情时当前意向的快照可能还没进内存：只补加载当前意向这一份来恢复坐标。
  // 已结算（成功/失败）的快照绝不重发 —— 失败也不换 scope 自动重试；进行中的快照则
  // 仍交给 操作.加载候选岗位 的单飞/锁主接管：在途的那次可能早已被 scope 栅栏作废
  //（进屏即发、离开即弃），重进详情若不补发，主键会永远卡在「正在恢复推荐信息…」。
  // 单飞吞掉的重复请求不落任何状态，不会造成 effect 重发循环。编号载体缺位
  //（意向未水合）时同样不猜，等水合完成再有编号才发。
  useEffect(() => {
    if (!编号 || 后端状态.初始化 !== '完成' || 当前意向编号 === null) return;
    if (当前意向快照 !== undefined && (当前意向快照.阶段 === '成功' || 当前意向快照.阶段 === '失败')) return;
    void 操作.加载候选岗位(当前意向编号).catch(() => undefined);
  }, [编号, 后端状态.初始化, 当前意向编号, 当前意向快照, 操作]);

  // 权威 Job：快照卡自带完整 CandidateJob（详情优先复用卡），没有才靠缓存 / GET
  const 岗位 = 推荐卡?.job ?? (编号 ? 后端状态.候选岗位详情?.[编号] ?? null : null);
  const 不可用 = 编号 !== undefined && (后端状态.候选岗位不可用 ?? []).includes(编号);

  // 快照与缓存都没有：GET 单个 CandidateJob。404 已由操作层收口成不可用标记（不抛）；
  // 其余错误落到 读取错误，给明确重试。
  useEffect(() => {
    if (!编号 || 岗位 || 不可用) return;
    let 已失效 = false;
    void 操作.读取候选岗位详情(编号).catch((错误: unknown) => {
      if (!已失效) 设读取错误(P4错误文案(错误));
    });
    return () => {
      已失效 = true;
    };
  }, [编号, 岗位, 不可用, 操作]);

  // 推荐卡路径带真实匹配分与推荐坐标；详情直取路径 wire 上没有这些，置 null/0 不编造
  const 视图 = useMemo(
    () => (岗位 === null ? null : 推荐卡 !== null ? 从P4候选岗位(推荐卡) : 从P4CandidateJob(岗位)),
    [岗位, 推荐卡]
  );

  // 委托状态只认 映射P4委托展示 的闭合六态投影：摘要 + 权威回执（按 delegation_id 对上）；
  // 详情直取没有推荐坐标，摘要恒 null
  const 委托摘要 = 推荐卡?.delegation ?? null;
  const 委托回执 = 委托摘要 === null
    ? null
    : 后端状态.P4委托回执?.[委托摘要.delegation_id] ?? null;
  const 委托展示 = 映射P4委托展示(委托摘要, 委托回执);
  // 已开案且回执带非空服务端 case_id 才有「查看进展」；job_id / recommendation_id /
  // delegation_id 一律不作 Case 凭据，也绝不拿 P4真实Case引用 兜底
  const 进展Case编号 = 委托展示?.state === 'case_started' ? 委托展示.caseId : null;

  // 本页唯一可见的进行中委托（accepted/evaluating，即 inProgress === true 的那两个状态）
  const 进行中委托 = useMemo(() => (委托展示?.inProgress === true && 委托摘要 !== null
    ? [{
      role: 'candidate' as const,
      delegationId: 委托摘要.delegation_id,
      // inProgress === true 已闭合出 accepted/evaluating 两员
      state: 委托展示.state === 'accepted' ? ('accepted' as const) : ('evaluating' as const),
    }]
    : []), [委托展示, 委托摘要]);
  // terminal summary 单次权威补读：摘要已 refused/failed 而权威回执表缺这条 ID 时，
  // 钩子立即补读一次拿回拒绝/失败码 —— 页面摘要永远不给原因，回执来了才解释
  const 待恢复终态 = useMemo(() => {
    if (委托摘要 === null || 委托摘要.delegation_id === '') return [];
    if (委托摘要.state !== 'refused' && 委托摘要.state !== 'failed') return [];
    if (委托回执 !== null) return [];
    return [{
      role: 'candidate' as const,
      delegationId: 委托摘要.delegation_id,
      state: 委托摘要.state,
    }];
  }, [委托摘要, 委托回执]);
  const 进度未知 = use发现推荐委托轮询({
    开启: true,
    委托: 进行中委托,
    待恢复终态,
    刷新: 操作.刷新委托,
    // scope 变化即结束本轮询周期：换 Job 不带走上一条的连续失败计数（§8.3）
    范围键: 编号 ?? null,
  });
  // 轮询连败的委托：状态文案覆盖成中性「进度未知」，绝不伪造终态回执
  const 委托进度未知 = 委托展示?.inProgress === true && 委托摘要 !== null
    && 进度未知.has(委托摘要.delegation_id);

  const 重试读取 = () => {
    if (!编号) return;
    设读取错误(null);
    void 操作.读取候选岗位详情(编号, true)
      .catch((错误: unknown) => 设读取错误(P4错误文案(错误)));
  };

  // 委托第一跳（P5）：先拿权威附件库，再让用户显式选定这次提交的简历坐标。
  // 读失败 → P4 失败 toast（零导航零委托）；null（会话/角色换代）→ 静默返回，
  // 绝不当成空库走「去上传」的跳转分支。
  const 开始委托 = async (目标视图: P4候选岗位页面) => {
    if (!目标视图.recommendationId || !目标视图.intentionId) return;
    const 起始代际 = 准备代际引用.current;
    try {
      const 库 = await 操作.准备候选委托简历();
      // 迟到栅栏：scope 已变或屏幕已卸载 → 本次权威结果整体作废（静默返回）
      if (准备代际引用.current !== 起始代际) return;
      if (库 === null) return;
      if (库.items.length === 0) {
        轻提示('请先上传一份 PDF 简历');
        跳转(路径.我的简历);
        return;
      }
      if (库.items.length === 1) {
        const 唯一 = 库.items[0];
        if (唯一) 设待确认视图({ 视图: 目标视图, 选择: 从附件行取选择值(唯一) });
        return;
      }
      设待选择视图({ 视图: 目标视图, 文件们: 库.items });
    } catch (错误) {
      // 拒绝路径同样过栅栏：切了 scope / 离屏后的迟到失败不再 toast
      if (准备代际引用.current !== 起始代际) return;
      轻提示(P4错误文案(错误));
    }
  };

  // 确认层只在这里真正发起委托：先收层再 await —— 失败后下一次点击必须重新确认
  const 执行候选委托 = async (候选视图: P4候选岗位页面, 选择: 附件简历选择值) => {
    if (!候选视图.recommendationId || !候选视图.intentionId) return;
    设待确认视图(null);
    设写中(true);
    try {
      await 操作.委托候选岗位({
        intentionId: 候选视图.intentionId,
        recommendationId: 候选视图.recommendationId,
        jobId: 候选视图.jobId,
        resumeFileId: 选择.fileId,
        resumeFileVersionId: 选择.fileVersionId,
        disclosureAcknowledged: true,
      });
    } catch (错误) {
      轻提示(P4错误文案(错误));
    } finally {
      设写中(false);
    }
  };

  // 不感兴趣：服务端先行，PUT 成功（或 404 收口）才回列表；失败原地提示不移动。
  // 落点与返回栏同一套 安全返回 —— 直链/刷新链进来恢复出推荐坐标的详情页，
  // 成功剔除后同样不能盲退栈（idx 0 会卡死、外链前一格会退出应用）
  const 标记不感兴趣 = async () => {
    if (!推荐卡) return;
    设写中(true);
    try {
      await 操作.标记岗位不感兴趣(推荐卡.intention_id, 推荐卡.recommendation_id);
      安全返回();
    } catch (错误) {
      轻提示(P4错误文案(错误));
    } finally {
      设写中(false);
    }
  };

  // ── 加载 / 错误 / 安全不可用页：真实 DTO 到手前不给任何 Mock 内容 ──
  if (视图 === null) {
    const 不可用态 = 不可用;
    return (
      <次级页外壳>
        <返回栏 返回={安全返回} />
        <滚动区>
          <div className={样式.后端态}>
            <div className={样式.后端态标题}>
              {不可用态 ? '这个职位暂时看不了' : 读取错误 !== null ? '职位暂时加载不了' : '正在加载职位详情…'}
            </div>
            {不可用态 ? (
              <div className={样式.后端态说明}>该职位可能已下架，或已不在你的推荐范围内。</div>
            ) : 读取错误 !== null ? (
              <>
                <div className={样式.后端态说明}>{读取错误}</div>
                <button className={`${样式.后端态按钮} 可点`} onClick={重试读取}>
                  重试
                </button>
              </>
            ) : null}
          </div>
        </滚动区>
      </次级页外壳>
    );
  }

  const 已委托 = 委托摘要 !== null;
  // 推荐坐标恢复的三种非命中态（直链进详情时快照可能还在途）：
  //   · 当前意向缺位 / 快照未开始或进行中 → 恢复中，坐标回来前绝不给可点的委托键；
  //   · 快照失败 → 通用不可用文案，不换 scope 重试（反馈与委托照样禁用）；
  //   · 快照成功但没有这张卡 → 只读空态：当前意向确实没有这条推荐。
  const 恢复中 = 推荐卡 === null && 当前意向编号 !== null &&
    (当前意向快照 === undefined || 当前意向快照.阶段 === '未开始' || 当前意向快照.阶段 === '进行中');
  // 委托态的权威文案 = 闭合六态 copy（refused 附服务端拒绝原因）；轮询连败被「进度未知」覆盖
  const 委托文字 = 委托进度未知
    ? P4委托进度未知文案
    : 委托展示 === null
      ? '让AI代理去谈'
      : `${委托展示.copy}${委托展示.reason === null ? '' : `：${委托展示.reason}`}`;
  const 主键文字 = 已委托
    ? 委托文字
    : 推荐卡 !== null
      ? '让AI代理去谈'
      : 恢复中
        ? '正在恢复推荐信息…'
        : 当前意向快照?.阶段 === '失败'
          ? (当前意向快照.error ?? '服务暂时不可用，请稍后再试')
          : '当前求职意向暂无这条推荐';
  const 动作可用 = 推荐卡 !== null && !写中;

  return (
    <次级页外壳>
      <返回栏
        返回={安全返回}
        右侧={
          // P8：权威 CandidateJob 快照解码成功（视图在场）即可举报这个岗 —— 举报
          // target 用 job_id，与有没有推荐坐标无关；快照缺位/加载/失败/404 一律无 ⋯
          视图 !== null ? (
            <div className={样式.工具组}>
              <button
                className={`${样式.工具符} 可点`}
                onClick={() => 设抽屉展开(true)}
                aria-label="更多操作"
              >
                ⋯
              </button>
            </div>
          ) : undefined
        }
      />

      <滚动区>
        <职位正文 岗={视图.卡} P4视图={视图} />
      </滚动区>

      {/* 底部浮动胶囊条：🚫（不感兴趣）+ 主键（让AI代理去谈 / 已接手状态标） */}
      <div className={样式.浮动条}>
        <button
          className={`${样式.圆形次按钮} ${动作可用 ? '可点' : ''}`}
          aria-label="不感兴趣"
          disabled={!推荐卡 || 写中}
          onClick={() => void 标记不感兴趣()}
        >
          <禁止图标 尺寸={18} 色="var(--次要)" />
        </button>
        {进展Case编号 !== null ? (
          // 已开案且回执带服务端 case_id：主键换成「查看进展」（唯一导航凭据就是它）
          <button
            className={`${样式.主按钮} 可点`}
            onClick={() => 跳转(路径.在谈详情(进展Case编号))}
          >
            <span className={样式.主按钮文字}>查看进展</span>
          </button>
        ) : (
          <button
            className={`${样式.主按钮} ${已委托 ? 样式.已委托态 : 动作可用 ? '可点' : ''}`}
            disabled={!推荐卡 || 已委托 || 写中}
            onClick={() => void 开始委托(视图)}
          >
            <谈判图标 尺寸={15} 色={已委托 ? 'var(--深绿)' : undefined} />
            <span className={样式.主按钮文字}>{主键文字}</span>
          </button>
        )}
      </div>

      {/* 「⋯」更多操作抽屉：不感兴趣与浮动条同一动作（服务端先行，成功才回列表）；
          举报这个职位（P8）对推荐/详情直取两条路径都在 —— 推荐专属的不感兴趣只在
          有推荐坐标的路径出现，直取路径里举报是唯一非取消动作 */}
      {抽屉展开 ? (
        <弹层框架 标签="职位更多操作" 遮罩类名={样式.遮罩} 面板类名={样式.抽屉} 关闭={() => 设抽屉展开(false)}>
            {推荐卡 !== null ? (
              <button
                className={`${样式.抽屉项} 可点`}
                disabled={写中}
                onClick={() => {
                  设抽屉展开(false);
                  void 标记不感兴趣();
                }}
              >
                不感兴趣，别再推给我
              </button>
            ) : null}
            <button
              className={`${样式.抽屉项} 可点`}
              onClick={() => {
                设抽屉展开(false);
                设举报层开(true);
              }}
            >
              举报这个职位
            </button>
            <button
              className={`${样式.抽屉项} ${样式.抽屉取消} 可点`}
              onClick={() => 设抽屉展开(false)}
            >
              取消
            </button>
        </弹层框架>
      ) : null}

      {/* P8 举报层：target 只认 视图.jobId（成功解码的 CandidateJob job_id），
          绝不用路由参数 编号、更不用 P4 推荐 ID；target-not-found 由层统一关层，
          这里强制重读来源收掉过期的岗位页 */}
      {举报层开 && 视图 !== null ? (
        <举报层
          对象名={`${视图.卡.职位} · ${视图.公司.名称}`}
          屏蔽名称={视图.公司.名称}
          target={{ type: 'job', ref: 视图.jobId }}
          目标失效={() => {
            void 操作.读取候选岗位详情(视图.jobId, true)
              .catch((错误: unknown) => 设读取错误(P4错误文案(错误)));
          }}
          关闭={() => 设举报层开(false)}
        />
      ) : null}

      {待选择视图 ? (
        // 多份附件：必须单选一份才可确认；取消 / 遮罩 / Esc 都只清捕获零请求，
        // 确认值只来自所选行的当前 file/version，层内文案声明授权仅对这一次委托生效
        <附件简历选择层
          文件们={待选择视图.文件们}
          取消={() => 设待选择视图(null)}
          确认={(选择) => {
            const 捕获 = 待选择视图;
            设待选择视图(null); // 先收层再发委托：失败要求下一次重新选
            if (捕获) void 执行候选委托(捕获.视图, 选择);
          }}
        />
      ) : null}

      {待确认视图 ? (
        // 不可逆动作的披露确认：正文点名这次提交哪份 PDF、披露什么，且仅对这一次
        // 委托生效；取消 / 遮罩 / Esc 都是零请求零状态，确认后才发起委托
        <确认层
          标题="确认委托AI代理？"
          正文={`S0 通过后，本 Case 将提交「${待确认视图.选择.displayName}」这份 PDF，并向该招聘方披露姓名和联系方式。本次授权仅对这一次委托生效。`}
          执行文="确认委托"
          取消文="暂不委托"
          取消={() => 设待确认视图(null)}
          执行={() => void 执行候选委托(待确认视图.视图, 待确认视图.选择)}
        />
      ) : null}
    </次级页外壳>
  );
}

/** 四档条里每一块的配色。
 *  当前档用深绿实心；序号 1 那一块固定用中灰（RN 源里就是硬编码 序===1，
 *  不是「当前档减一」，这里保持一致以免像素对不上）；其余用更浅的灰。 */
/** 匹配维度：岗位字段 × 简历侧事实 → 逐行核对。
 *  值一律「你的值 → 岗位的值」或单值事实，不写解释句。 */
// ── 职位正文（共享）：职位名/薪资 → 发布人 → 匹配度分析 → JD → 公司 ──
// 2026-08-24 从本屏抽出：直聊会话顶部「看职位」层要铺同一份内容
// （产品负责人：「这私信的两个人点开后为什么还不一样」）。
// 藏直聊：在直聊会话的层里已经在和发布人聊天，「直接聊」按钮没有意义，藏掉。
// P4：Backend 传 P4视图 时整页改吃映射后的权威数据（JD/公司/发布人），
// 直聊入口同样隐藏 —— P4 没有建立直聊许可或会话坐标。
export function 职位正文({
  岗,
  藏直聊 = false,
  P4视图,
}: {
  岗: 市场职位;
  藏直聊?: boolean;
  /** Backend 候选岗位视图；缺省走 Mock 的 取市场岗位详情（直聊会话等调用方不变） */
  P4视图?: P4候选岗位页面;
}) {
  const { 状态, 数据源模式 } = use应用状态();
  const { 跳转 } = use导航();
  const 是后端 = 数据源模式 === 'backend';
  // 视图只在「Backend 且调用方给了 P4视图」时生效：Mock 调用方不传，行为不变
  const 视图 = 是后端 && P4视图 ? P4视图 : null;

  // Backend P4 路径不读 Mock 详情表（取市场岗位详情 是演示域数据），Mock/直聊会话
  // 路径保持原读取；两条路径收成同一份展示投影，下面的 JSX 不分叉。
  // P4：岗位硬事实（城市/办公方式/办公地点/年薪月数/经验/学历）以「标签：值」文本行
  // 前置进既有 JD 卡正文槽 —— 只渲染已投影的非空事实（办公地点 blank → null 不出空标签，
  // 年薪月数 null 不出 X 薪，绝不补 12 薪默认），JD 原文行跟在事实行之后。
  const 事实行 = 视图 === null ? [] : [
    `城市：${视图.岗位事实.城市}`,
    `办公方式：${视图.岗位事实.办公方式}`,
    ...(视图.岗位事实.办公地点 === null ? [] : [`办公地点：${视图.岗位事实.办公地点}`]),
    ...(视图.岗位事实.年薪月数 === null ? [] : [`年薪月数：${视图.岗位事实.年薪月数} 薪`]),
    `结构化经验要求：${视图.岗位事实.经验要求}`,
    `结构化学历要求：${视图.岗位事实.学历要求}`,
  ];
  const 内容 = 视图 !== null
    ? {
      标签: 视图.卡.学历要求 ? [视图.卡.学历要求] : [],
      职位详情: [...事实行, ...视图.职位详情],
      职位要求: 视图.职位要求,
      公司: {
        名称: 视图.公司.名称,
        首字: 视图.公司.首字,
        简介: 视图.公司.简介,
        organizationId: 视图.公司.organizationId,
      },
      发布人: 视图.发布人
        ? {
          首字: 视图.发布人.首字,
          姓名: 视图.发布人.姓名,
          公司: 视图.公司.名称,
          职务: 视图.发布人.职务,
          备注: '',
        }
        : null,
    }
    : (() => {
      const 详 = 取市场岗位详情(岗);
      return {
        标签: 详.标签,
        职位详情: 详.职位详情,
        职位要求: 详.职位要求,
        公司: { 名称: 详.公司.名称, 首字: 详.公司.首字, 简介: 详.公司.简介, organizationId: null },
        发布人: {
          首字: 详.发布人.首字,
          姓名: 详.发布人.姓名,
          公司: 详.发布人.公司,
          职务: 详.发布人.职务,
          备注: 详.发布人.备注,
        },
      };
    })();

  // 详情直取（recommendationId === null）wire 上没有匹配分：藏环不伪造 0 分
  const 藏匹配环 = 视图 !== null && 视图.recommendationId === null;

  // 公司槽落点：Backend 只认 hiring_organization_ref（claim 不是组织坐标）；
  // Mock 仍按原公司名 slug 进企业详情
  let 公司跳转: (() => void) | undefined;
  if (视图 !== null) {
    const 组织编号 = 内容.公司.organizationId;
    if (组织编号 !== null) 公司跳转 = () => 跳转(路径.企业详情(组织编号));
  } else if (!是后端) {
    公司跳转 = () => 跳转(路径.企业详情(公司路由键(内容.公司.名称)));
  }

  // 发布人：wire 缺席 → 整卡不渲染，绝不拿公司声明合成「某某 · 企业直招」
  const 发布人 = 内容.发布人;

  return (
    <div className={样式.内容}>
      {/* 职位名 + 薪资 + 标签：baseline 对齐，让 21px 的职位名和 16px 的薪资底线齐平 */}
      <div>
        <div className={样式.标题行}>
          <div className={样式.职位名}>{岗.职位}</div>
          <div className={`${样式.薪资} 薪资体`}>{岗.薪资}</div>
        </div>
        {/* 标签行(本科及以上/今天新发)已删(用户 2026-08-31:「所有的都不要加这种标签」),
            标题直接贴匹配度分析 */}
      </div>

      {/* 匹配度分析(2026-08-31 用户定稿「分从行来 + 三态行」):条目 = JD 硬性要求,
          分数由行加权算出,环下分析段讲原因 —— 数字与证据不再可能打架 */}
      <div className={样式.卡}>
        {视图 === null || 视图.匹配依据已确认 === true ? (
          (() => {
            const 对齐行们 = 求职侧对齐行(
              岗,
              { 经历: 状态.简历经历, 教育: 状态.简历教育, 技能: 状态.简历技能 },
              // Backend:权威 JD 要求只能核用户真实简历事实（工作年限 / 学历），
              // 核不动记未提及；Mock 不传，演示口径逐字不变
              视图 !== null
                ? { 工作年限: 折算工作年限(状态.基本信息.开始工作年) }
                : undefined,
            );
            // 分析段文案：Mock 逐字不变；Backend 的分析开头必须说明核对基准 ——
            // 这些行只按岗位设置的结构化要求核对（匹配分析块 的 分析 是 {墨句,灰句}，
            // 所以基准句并进墨句开头，不另造元素）
            const 原分析 = 求职匹配分析(对齐行们, 岗.编号);
            return (
              <匹配分析块
                // Backend:wire 匹配分是权威,本地不重算(P4);Mock:分从行来
                分={视图 !== null ? 岗.适配分 : 算适配分(对齐行们, 岗.适配分)}
                藏环={藏匹配环}
                行们={对齐行们}
                分析={视图 !== null && 原分析 !== null
                  ? { 墨句: `按岗位设置的结构化要求核对。${原分析.墨句}`, 灰句: 原分析.灰句 }
                  : 原分析}
              />
            );
          })()
        ) : (
          // Backend：历史依据未确认（false）或无推荐批次（详情直取 null）时，
          // 这条推荐/详情根本没核对过经验与学历 —— 确定性核对行与生成分析整组不出，
          // 只给中性交代与当前 Job 的结构化设置现状；推荐分本身是 wire 事实，照常保留
          <>
            <div className={样式.适配头}>
              <span className={样式.卡标题}>匹配度分析</span>
              {藏匹配环 ? null : <适配环 分={岗.适配分} 标={null} 尺寸={44} />}
            </div>
            {视图.匹配依据已确认 === false ? (
              <div className={样式.卡正文}>经验与学历尚未核对</div>
            ) : null}
            <div className={样式.卡正文}>
              {`结构化设置：${视图.岗位事实.结构化要求已确认 ? '已确认' : '尚未确认'}`}
            </div>
          </>
        )}
      </div>

      {/* JD：职位详情 + 职位要求两段合在一张卡里，中间用小标题分隔。
          Backend(P4)：标题与小标题改成如实口径 —— 事实行混在 JD 正文里，标题必须
          说明「岗位信息」；职位要求只是补充说明、不自动解析进匹配卡 */}
      <div className={样式.卡}>
        <div className={样式.卡标题}>
          {视图 !== null ? '岗位信息与职位详情' : '职位详情'}
        </div>
        {内容.职位详情.map((行, index) => (
          <div key={`${index}:${行}`} className={样式.卡正文}>
            {行}
          </div>
        ))}
        <div className={样式.卡小标题}>
          {视图 !== null ? '职位要求（补充说明，不自动解析）' : '职位要求'}
        </div>
        {内容.职位要求.map((行) => (
          <div key={行} className={样式.卡正文}>
            {行}
          </div>
        ))}
      </div>

      {/* 公司(加厚,2026-08-26 用户指定「所有页面都要改」):共用 公司区块 组件,
          介绍段 + 融资阶段/规模/行业/成立/地址。Backend(P4)公司名照常展示,
          介绍段不造(映射层只带 wire 事实);只有 hiring_organization_ref 在场才可点进公开企业页 */}
      <div className={样式.卡}>
        <公司区块
          名称={内容.公司.名称}
          首字={内容.公司.首字}
          一行简介={内容.公司.简介}
          资料={是后端 ? { 介绍段: null, 元行组: [] } : undefined}
          按下={公司跳转}
        />
      </div>

      {/* 发布人:是企业招聘负责人还是猎头,决定了用户愿不愿意直接聊。
          2026-08-26 用户指定:挪到公司区块之下——先认识公司,再认识对接的人。
          P4 发布人缺席(wire 无 publisher_profile)整卡不渲染 */}
      {发布人 !== null ? (
        <div className={`${样式.卡} ${样式.发布人卡}`}>
          <span className={样式.发布人头像}>{发布人.首字}</span>
          <div className={样式.发布人文字区}>
            <div className={样式.发布人名}>
              {发布人.姓名} · {发布人.公司}{' '}
              {发布人.职务 ? (
                <span className={样式.发布人职务}>{发布人.职务}</span>
              ) : null}
            </div>
            {发布人.备注 ? (
              <div className={样式.发布人备注}>{发布人.备注}</div>
            ) : null}
          </div>
          {/* 直接聊入口收进发布人卡:聊的对象就是这个人,按钮贴着人放。
              直聊层里本来就在和这个人聊,藏掉;Backend 无直聊坐标,同样藏掉 */}
          {藏直聊 || 是后端 ? null : (
            <button
              className={`${样式.发布人聊} 可点`}
              onClick={() => 跳转(路径.直聊会话岗位(岗.编号))}
            >
              直接聊
            </button>
          )}
        </div>
      ) : null}

    </div>
  );
}
