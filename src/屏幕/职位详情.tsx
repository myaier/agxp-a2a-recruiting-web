// A18 职位详情 —— 从「看市场」点职位卡进来，是用户做选择之前看到的岗位全貌页。
//
// 两条路径的入口（2026-08 重排后）：
//   · 直接聊      —— 发布人卡右侧小按钮：双方互相看到身份，AI代理退成旁听；
//   · 让AI代理去谈 —— 底部浮动胶囊条主键：走匿名初筛，委托后原地切到在谈详情。
// 浮动条左侧的 🚫 圆钮 = 不感兴趣：从看市场流里剔除这个岗并回列表。
//
// 内容顺序：职位名 + 薪资 → 标签（含发布于）→ 发布人 → 匹配度分析 → JD → 公司。

import { useState } from 'react';
import { useParams } from 'react-router-dom';
import 样式 from './职位详情.module.css';
import { 次级页外壳, 返回栏, 滚动区, 公司字标 } from '../组件/通用';
import 适配环 from '../组件/适配环';
import { 谈判图标, 禁止图标 } from '../组件/图标';
import 举报层 from '../组件/举报层';
import { 轻提示 } from '../组件/轻提示';
import { 市场列表, 取市场岗位详情 } from '../数据/模拟数据';
import type { 市场职位 } from '../数据/类型';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import 弹层框架 from '../组件/弹层框架';
import { 公司路由键 } from '../数据/公司档案';

/** 硬性要求核对行：JD 的 经验/学历/城市 逐条对我的简历事实（9 年 / 硕士 / 上海）。
    只render JD 里写了的项；到岗、薪资是双盲协商项，不进这张表。 */
export function 硬性行们(
  源: { 经验要求?: string; 学历要求?: string; 标签?: string[] },
  技能: string[]
): { 文: string; 过: boolean }[] {
  void 技能; // 技能对照已有独立 chips 区，这里不重复
  const 行: { 文: string; 过: boolean }[] = [];
  if (源.经验要求) {
    const 需 = parseInt(源.经验要求, 10);
    行.push({ 文: `经验 ${源.经验要求} · 我 9 年`, 过: !Number.isFinite(需) || 需 <= 9 });
  }
  if (源.学历要求) {
    const 阶 = (值: string) => (值.includes('硕士') ? 2 : 值.includes('本科') ? 1 : 0);
    行.push({ 文: `学历 ${源.学历要求} · 我 硕士`, 过: 阶(源.学历要求) <= 2 });
  }
  const 城 = 源.标签?.[0]?.split(' · ')[0];
  if (城) {
    // 全远程岗不卡城市：任一标签带「远程」即视为通过
    const 远程 = 源.标签?.some((签) => 签.includes('远程')) ?? false;
    行.push({
      文: 远程 ? `城市 ${城} · 全远程` : `城市 ${城} · 我 上海`,
      过: 城 === '上海' || 远程,
    });
  }
  return 行;
}

export default function 职位详情() {
  const { id: 编号 } = useParams<{ id: string }>();
  const { 状态, 派发 } = use应用状态();
  const { 跳转, 返回, 替换跳转 } = use导航();

  // 「⋯」拉起的更多操作抽屉是否展开
  const [抽屉展开, 设抽屉展开] = useState(false);
  // 举报层（从更多操作抽屉里进）
  const [举报层开, 设举报层开] = useState(false);

  // 按路由参数取岗位；直接输 URL 或参数丢失时退回第一条，
  // 保证这一屏永远有内容可渲染，不会白屏。
  const 岗 = 市场列表.find((条) => 条.编号 === 编号) ?? 市场列表[0];
  // JD / 发布人 / 公司卡都按这个岗的编号取。原来这里是一份单例常量，
  // 7 个岗点进去看到的是同一家公司 —— 点开第二个岗当场穿帮
  const 详 = 取市场岗位详情(岗);
  // 举报/屏蔽的对象是这个岗位所属的公司，取自岗位数据本身，
  // 不用下面公司卡里的静态 mock —— 用户屏蔽的是他刚才在列表里看到的那一家
  const 岗位公司名 = 岗.公司;
  // 已经委托过的岗位，主按钮换成「AI代理已接手」，和「看市场」卡片上的状态标口径一致
  const 已委托 = 状态.已委托.includes(岗.编号);

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        右侧={
          <div className={样式.工具组}>
            <button
              className={`${样式.工具符} 可点`}
              onClick={() => 设抽屉展开(true)}
              aria-label="更多操作"
            >
              ⋯
            </button>
          </div>
        }
      />

      <滚动区>
        <div className={样式.内容}>
          {/* 职位名 + 薪资 + 标签：baseline 对齐，让 21px 的职位名和 16px 的薪资底线齐平 */}
          <div>
            <div className={样式.标题行}>
              <div className={样式.职位名}>{岗.职位}</div>
              <div className={`${样式.薪资} 薪资体`}>{岗.薪资}</div>
            </div>
            <div className={样式.标签行}>
              {详.标签.map((标签) => (
                <span key={标签} className={样式.标签}>
                  {标签}
                </span>
              ))}
              {/* 发布时间 chip：淡绿一档，和灰标签区分出「新鲜度」这一维 */}
              {岗.发布于 ? <span className={样式.发布于标}>{岗.发布于}</span> : null}
            </div>
          </div>

          {/* 发布人：是企业招聘负责人还是猎头，决定了用户愿不愿意直接聊，所以排在 JD 之前 */}
          <div className={`${样式.卡} ${样式.发布人卡}`}>
            <span className={样式.发布人头像}>{详.发布人.首字}</span>
            <div className={样式.发布人文字区}>
              <div className={样式.发布人名}>
                {详.发布人.姓名} · {详.发布人.公司}{' '}
                {详.发布人.职务 ? (
                  <span className={样式.发布人职务}>{详.发布人.职务}</span>
                ) : null}
              </div>
              {详.发布人.备注 ? (
                <div className={样式.发布人备注}>{详.发布人.备注}</div>
              ) : null}
            </div>
            {/* 直接聊入口收进发布人卡：聊的对象就是这个人，按钮贴着人放 */}
            <button
              className={`${样式.发布人聊} 可点`}
              onClick={() => 跳转(路径.直聊会话岗位(岗.编号))}
            >
              直接聊
            </button>
          </div>

          {/* 匹配度分析（标注 00:38）：JD × 你的简历逐维核对。
              左列 维度 · 双方的值，右列 ✓/✗ —— 与在谈详情的初筛核对清单同一语言，
              分数不再是黑箱，每一维都能看到是拿什么比出来的 */}
          <div className={样式.卡}>
            <div className={样式.适配头}>
              <span className={样式.卡标题}>匹配度分析</span>
              <适配环 分={岗.适配分} 标={null} 尺寸={44} />
            </div>
            {取适配维度(岗).map((维) => (
              <div key={维.名} className={样式.适配行}>
                <span className={样式.适配维名}>{维.名}</span>
                <span className={`${样式.适配值} 单行`}>{维.值}</span>
                <span className={维.过 ? 样式.适配过 : 样式.适配差}>
                  {维.过 ? '✓' : '✗'}
                </span>
              </div>
            ))}

            {/* 硬性要求核对（标注 2026-08-20 09:39）：匹配分的依据 ——
                简历 vs JD 硬性要求逐条 ✓/✗，替代原「对得上」映射行 */}
            {硬性行们(岗, 状态.简历技能).length ? (
              <>
                <div className={样式.证据组标}>硬性要求</div>
                {硬性行们(岗, 状态.简历技能).map((行) => (
                  <div key={行.文} className={样式.证据行}>
                    <span className={行.过 ? 样式.适配过 : 样式.适配差}>
                      {行.过 ? '✓' : '✗'}
                    </span>
                    <span className={样式.证据文}>{行.文}</span>
                  </div>
                ))}
              </>
            ) : null}

            {/* 技能对照：JD 技能词 × 简历技能，子串互含即命中（'Go' 命中 'Go / 高并发'）。
                命中 → 绿 chip 带 ✓；未命中 → 灰 chip，一眼看出还缺哪几个词 */}
            {岗.技能要求?.length ? (
              <>
                <div className={样式.证据组标}>技能</div>
                <div className={样式.技能行}>
                  {岗.技能要求.map((技) => {
                    const 命中 = 状态.简历技能.some(
                      (有) => 有.includes(技) || 技.includes(有)
                    );
                    return (
                      <span key={技} className={命中 ? 样式.技能中 : 样式.技能缺}>
                        {命中 ? `✓ ${技}` : 技}
                      </span>
                    );
                  })}
                </div>
              </>
            ) : null}
          </div>

          {/* JD：职位详情 + 职位要求两段合在一张卡里，中间用小标题分隔 */}
          <div className={样式.卡}>
            <div className={样式.卡标题}>职位详情</div>
            {详.职位详情.map((行) => (
              <div key={行} className={样式.卡正文}>
                {行}
              </div>
            ))}
            <div className={样式.卡小标题}>职位要求</div>
            {详.职位要求.map((行) => (
              <div key={行} className={样式.卡正文}>
                {行}
              </div>
            ))}
          </div>

          {/* 公司：黑底橄榄字的字标是品牌向的定稿样式，不走 公司字标 的白底默认值。
              整卡可点，进公司主页（作息福利 / 地址 / 介绍 / 工商信息 / 在招岗位）*/}
          <button
            className={`${样式.卡} ${样式.公司卡} 可点`}
            onClick={() => 跳转(路径.企业详情(公司路由键(详.公司.名称)))}
          >
            <公司字标
              首字={详.公司.首字}
              尺寸={40}
              圆角={14}
              底色="var(--墨)"
              字色="var(--橄榄)"
              描边={false}
              字号={17}
            />
            <span className={样式.公司文字区}>
              <span className={样式.公司名}>{详.公司.名称}</span>
              <span className={样式.公司简介}>{详.公司.简介}</span>
            </span>
            <span className={样式.尖括号}>›</span>
          </button>

        </div>
      </滚动区>

      {/* 底部浮动胶囊条：悬浮在滚动内容之上，🚫（不感兴趣）+ 主键（让AI代理去谈） */}
      <div className={样式.浮动条}>
        <button
          className={`${样式.圆形次按钮} 可点`}
          aria-label="不感兴趣"
          onClick={() => {
            // 和「⋯ → 不感兴趣」同一动作：从看市场流剔除 + 代理负反馈样本，随后回列表
            派发({ 型: '不感兴趣', 编号: 岗.编号 });
            返回();
          }}
        >
          <禁止图标 尺寸={18} 色="var(--次要)" />
        </button>
        <button
          className={`${样式.主按钮} ${已委托 ? 样式.已委托态 : '可点'}`}
          disabled={已委托}
          onClick={() => {
            // 标注意见 #8：点了不是回列表，而是这个岗位当场变成一个在谈单 ——
            // 代理立刻主动打招呼，页面原地切到在谈详情（replace，后退不回本页），
            // 首页在谈列表里同时多出这张卡
            派发({ 型: '委托入谈', 岗 });
            替换跳转(路径.在谈详情(岗.编号));
          }}
        >
          <谈判图标 尺寸={15} 色={已委托 ? 'var(--深绿)' : undefined} />
          <span className={样式.主按钮文字}>{已委托 ? 'AI代理已接手' : '让AI代理去谈'}</span>
        </button>
      </div>

      {/* 「⋯」更多操作抽屉：点遮罩或「取消」关闭 */}
      {抽屉展开 ? (
        <弹层框架 标签="职位更多操作" 遮罩类名={样式.遮罩} 面板类名={样式.抽屉} 关闭={() => 设抽屉展开(false)}>
            <button
              className={`${样式.抽屉项} 可点`}
              onClick={() => {
                // 真的落到全局：这个岗从看市场的职位流里消失，同时是代理的负反馈样本，
                // 所以提示语说的是「代理会记住」而不是「已隐藏」
                派发({ 型: '不感兴趣', 编号: 岗.编号 });
                设抽屉展开(false);
                轻提示('已不再推荐，代理会记住这类岗位');
                返回();
              }}
            >
              不感兴趣，别再推给我
            </button>
            <button
              className={`${样式.抽屉项} 可点`}
              onClick={() => {
                设抽屉展开(false);
                设举报层开(true);
              }}
            >
              举报这个职位
            </button>
            <button
              className={`${样式.抽屉项} ${样式.抽屉取消} 可点`}
              onClick={() => 设抽屉展开(false)}
            >
              取消
            </button>
        </弹层框架>
      ) : null}

      {举报层开 ? (
        <举报层
          对象名={`${岗.职位} · ${岗位公司名}`}
          屏蔽名称={岗位公司名}
          关闭={() => 设举报层开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}

/** 四档条里每一块的配色。
 *  当前档用深绿实心；序号 1 那一块固定用中灰（RN 源里就是硬编码 序===1，
 *  不是「当前档减一」，这里保持一致以免像素对不上）；其余用更浅的灰。 */
/** 匹配维度：岗位字段 × 简历侧事实 → 逐行核对。
 *  值一律「你的值 → 岗位的值」或单值事实，不写解释句。 */
function 取适配维度(岗: 市场职位): { 名: string; 值: string; 过: boolean }[] {
  return [
    { 名: '方向', 值: `${岗.意向} · 9 年`, 过: true },
    {
      名: '城市',
      值: `上海 → ${岗.城市 ?? '—'}`,
      过: !岗.城市 || 岗.城市 === '上海' || 岗.城市 === '远程',
    },
    { 名: '办公', 值: 岗.办公方式 ?? '—', 过: 岗.办公方式 !== '现场' },
    { 名: '薪资带', 值: 岗.带有交集 ? '与期望有交集' : '未核出交集', 过: !!岗.带有交集 },
    {
      名: '到岗',
      值: `45 天内 → ${岗.标签.find((t) => t.includes('到岗')) ?? '未标注'}`,
      过: true,
    },
  ];
}
