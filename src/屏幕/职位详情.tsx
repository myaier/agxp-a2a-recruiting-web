/** 两条来源收拢成同一份 职位正文展示属性（无 hook：正常页两分支在条件返回后调用） */
function 职位正文属性({
  岗,
  藏直聊 = false,
  P4视图,
  简历,
  是后端,
  跳转,
  公开企业 = null,
}: {
  岗: 市场职位;
  藏直聊?: boolean;
  P4视图?: P4候选岗位页面;
  简历: 职位核对简历;
  是后端: boolean;
  跳转: (目标: string) => void;
  /** Spec §6.1：独立职位详情补读到的公开企业；缺省 null（Mock / 直聊层不受影响） */
  公开企业?: BFF公开企业 | null;
}): 职位正文展示属性 {
  // 视图只在「Backend 且调用方给了 P4视图」时生效：Mock 调用方不传，行为不变
  const 视图 = 是后端 && P4视图 ? P4视图 : null;

  // Backend P4 路径不读 Mock 详情表（取市场岗位详情 是演示域数据），Mock/直聊会话
  // 路径保持原读取；两条路径收成同一份展示数据，JSX 只有一份。
  const 数据 = 视图 !== null
    ? 准备Backend职位正文(视图, 简历, 公开企业)
    : 准备Mock职位正文(岗, 简历);

  // 公司槽落点：Backend 只认 hiring_organization_ref（claim 不是组织坐标）；
  // Mock 仍按原公司名 slug 进企业详情
  let 打开公司: (() => void) | undefined;
  if (视图 !== null) {
    const 组织编号 = 视图.公司.organizationId;
    if (组织编号 !== null) 打开公司 = () => 跳转(路径.企业详情(组织编号));
  } else if (!是后端) {
    打开公司 = () => 跳转(路径.企业详情(公司路由键(数据.公司.名称)));
  }

  // 直接聊能力：Mock 且非嵌入隐藏才有；Backend 无直聊坐标，不给回调即不渲染按钮
  const 直接聊 = !藏直聊 && !是后端
    ? () => 跳转(路径.直聊会话岗位(岗.编号))
    : undefined;

  return { 数据, 打开公司, 直接聊 };
}

