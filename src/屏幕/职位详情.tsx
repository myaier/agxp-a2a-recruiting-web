// A18 职位详情 —— 从「看市场」点职位卡进来，是用户做选择之前看到的岗位全貌页。
//
// 两条路径的入口（2026-08 重排后）：
//   · 直接聊      —— 发布人卡右侧小按钮：双方互相看到身份，AI代理退成旁听；
//   · 让AI代理去谈 —— 底部浮动胶囊条主键：走匿名初筛，委托后原地切到在谈详情。
// 浮动条左侧的 🚫 圆钮 = 不感兴趣：从看市场流里剔除这个岗并回列表。
//
// 内容顺序：职位名 + 薪资 → 标签（含发布于）→ 匹配度分析 → JD → 公司(加厚) → 发布人。
// 2026-08-26 用户指定:发布人挪到公司之下(先认识公司,再认识人);公司区块参考
// 海外求职 App 的公司卡加厚——介绍段 + 融资阶段/规模/行业/成立/地址,数据读 公司档案。
//
// P4 模式边界：Backend 路由只吃 P4 权威数据 —— 先在候选岗位快照里按 job_id 找卡
// （有推荐坐标，可反馈可委托），快照没有再读详情缓存 / GET 单个 CandidateJob；
// 绝不回退 市场列表[0]，未知/不可见 Job 给安全不可用页。详情直取（无推荐坐标）
// 渲染权威详情但禁用 不感兴趣 与 委托 —— 缺 recommendation_id 就绝不猜坐标；
// 举报（P8）例外：target 用 job_id 本身，两条路径都能举报（推荐 ID 绝不作 target）。
// 委托每次都过显式披露确认（P5：先拿权威附件库 —— 零份去上传、一份 确认层 点名、
// 多份 附件简历选择层 单选），提交后原地停留（不造本地 Case）。J-PILOT-01 Task 3（Spec §4）：
// 持久回执在手（delegation_id 非空，含正常运行/失败/已结束）主按钮是可点的「查看进展」，
// 受理后不自动跳页、点击才导航 路径.在谈详情(持久回执坐标)、只导航不再次 POST；
// 记录尚待核对且无可靠 ID 时主按钮是「核对提交结果」（核对该 intention-job 的原命令，
// 不重新选 PDF、不猜同岗位记录）；create-time 空 delegation_id 的明确业务拒绝保持
// 既有安全错误文案。直聊入口整体隐藏（P4 没有直聊许可/会话坐标）；公司槽只在
// hiring_organization_ref 在场时可进公开企业页。Mock 分支保持原型行为原样。

