// A14 职位Tab·看市场 —— 自己刷市场上的职位，每张卡上带「让AI代理去谈」。
//
// 与「在谈」共用顶栏（意向左右平铺切换 + 在谈/看市场子视图）和代理横幅，
// 所以这两屏切换时顶部不动，只有列表在换 —— 这是设计稿里的硬要求。
//
// 卡片版式（2026-08-18 参考 Jobright 岗位卡重排，用户指定）：
//   公司字标 + 公司名/规模行 + 右上适配环 → 大职位名 → 薪资行 → 标签行
//   → 分隔线 → 发布人 + 「让AI代理去谈」。
// 借它的骨架（公司身份先行、匹配分做环形进度、标题放大），但三处按我们的立场改：
//   · 薪资不进标签堆 —— 单独一行 薪资体，价格标地位不动摇；
//   · 适配环按分数换语义色（≥90 递简历绿 / 75-89 协调橙 / 更低灰），不是装饰绿；
//   · 底行不放收藏/屏蔽小图标，只放我们的差异点：让AI代理去谈。
//
// 搜索与筛选都长在这一屏（2026-08-18 补）：顶部意向栏的放大镜 / 筛选 ▾ 只负责打开它们，
// 状态是本页 UI 态、不进全局 store。列表最终 = 当前意向 → 去掉不感兴趣 → 过筛选 → 过搜索。

import { useEffect, useMemo, useRef, useState } from 'react';
import 样式 from './看市场.module.css';
import 顶部意向栏, { 取走市场工具请求 } from './顶部意向栏';
import { 主页外壳, 代理横幅, 滚动区, 白卡, 开关 } from '../组件/通用';
import 适配环 from '../组件/适配环';
import { 谈判图标, 放大镜图标 } from '../组件/图标';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 市场列表 } from '../数据/模拟数据';
import type { 市场职位 } from '../数据/类型';

type 办公方式 = NonNullable<市场职位['办公方式']>;

/** 办公方式是固定三档（数据里可能只出现其中两档，但选项不该跟着少）*/
const 办公方式选项: 办公方式[] = ['现场', '混合', '全远程'];

/**
 * 筛选维度只有四个，而且【刻意没有薪资数字滑杆】——
 * 薪资数字在本产品里双向不披露（产品口径 2），用户拖一根「30-60K」的杆子，
 * 等于把自己的心理价位交给平台和对方推断。能问的只有「两边区间有没有交集」，
 * 这一位布尔量由代理在初筛时替双方核对，用户只决定要不要只看有交集的。
 */
interface 筛选条件 {
  办公方式: 办公方式[];
  城市: string[];
  仅企业直招: boolean;
  仅有交集: boolean;
}

const 空筛选: 筛选条件 = { 办公方式: [], 城市: [], 仅企业直招: false, 仅有交集: false };

/** 已生效的维度个数：两个多选各算一维（不按选项个数累加），两个开关各算一维 */
function 数生效维度(条件: 筛选条件): number {
  return (
    (条件.办公方式.length > 0 ? 1 : 0) +
    (条件.城市.length > 0 ? 1 : 0) +
    (条件.仅企业直招 ? 1 : 0) +
    (条件.仅有交集 ? 1 : 0)
  );
}

function 过筛选(岗: 市场职位, 条件: 筛选条件): boolean {
  // 多选为空 = 不限；非空时字段缺失的岗一律排除（宁可少给，也不给用户「筛了等于没筛」）
  if (条件.办公方式.length > 0 && (!岗.办公方式 || !条件.办公方式.includes(岗.办公方式)))
    return false;
  if (条件.城市.length > 0 && (!岗.城市 || !条件.城市.includes(岗.城市))) return false;
  if (条件.仅企业直招 && !岗.企业直招) return false;
  if (条件.仅有交集 && !岗.带有交集) return false;
  return true;
}

/** 本地包含匹配：职位名、公司行、标签三处任一命中即可（原型层不做分词与拼音）*/
function 命中搜索(岗: 市场职位, 关键词: string): boolean {
  if (关键词 === '') return true;
  return [岗.职位, 岗.公司行, ...岗.标签].some((文本) => 文本.toLowerCase().includes(关键词));
}

/** 多选片的开关：有就去掉、没有就加上 */
function 切多选<项>(列表: 项[], 项目: 项): 项[] {
  return 列表.includes(项目) ? 列表.filter((条) => 条 !== 项目) : [...列表, 项目];
}

export default function 看市场() {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  const [搜索展开, 设搜索展开] = useState(false);
  const [搜索词, 设搜索词] = useState('');
  const [筛选层开, 设筛选层开] = useState(false);
  const [筛选, 设筛选] = useState<筛选条件>(空筛选);
  const 搜索框 = useRef<HTMLInputElement>(null);

  // 从「在谈」子视图点放大镜 / 筛选时本页还没挂载，顶部意向栏把意图存进模块级信号，
  // 这里挂载后取走并打开对应工具（取走即复位，下次进来不会自己弹开）
  useEffect(() => {
    const 待办 = 取走市场工具请求();
    if (待办 === '搜索') 设搜索展开(true);
    if (待办 === '筛选') 设筛选层开(true);
  }, []);

  // 搜索行展开就把光标送进输入框，省用户一次点击
  useEffect(() => {
    if (搜索展开) 搜索框.current?.focus();
  }, [搜索展开]);

  // 标注意见 #9：切意向后市场职位流跟着变；
  // 「不感兴趣」的岗在这一步就被剔除 —— 用户说过不想再看见，它不该再参与后面任何一步。
  // 被屏蔽的公司同样剔除：屏蔽在本产品里是双向的（你看不到它、它也匹配不到你），
  // 举报层里勾了「同时屏蔽」之后回到这一屏还能看见它的岗，那个承诺就是假的。
  const 屏蔽公司 = useMemo(
    () => new Set(状态.屏蔽名单.map((条) => 条.名称)),
    [状态.屏蔽名单]
  );
  const 本意向市场 = useMemo(
    () =>
      市场列表.filter(
        (岗) =>
          岗.意向 === 状态.当前意向 &&
          !状态.不感兴趣岗位.includes(岗.编号) &&
          !屏蔽公司.has(岗.公司行.split(' · ')[0])
      ),
    [状态.当前意向, 状态.不感兴趣岗位, 屏蔽公司]
  );

  // 城市选项从数据里动态生成：写死一张城市表，用户会看到一堆一个岗都没有的城市
  const 城市选项 = useMemo(
    () => [...new Set(本意向市场.map((岗) => 岗.城市).filter((城): 城 is string => !!城))],
    [本意向市场]
  );

  const 关键词 = 搜索词.trim().toLowerCase();
  const 显示列表 = useMemo(
    () => 本意向市场.filter((岗) => 过筛选(岗, 筛选) && 命中搜索(岗, 关键词)),
    [本意向市场, 筛选, 关键词]
  );

  const 筛选生效数 = 数生效维度(筛选);

  // 需要你协调的条数从在谈列表实时算，横幅文案与「在谈」子视图保持一致，
  // 免得同一句话在两个子视图里给出不同数字。
  const 待协调数 = 状态.在谈列表.filter((单) => 单.需要你).length;

  const 关闭搜索 = () => {
    设搜索展开(false);
    设搜索词('');
  };

  return (
    <主页外壳>
      <顶部意向栏
        打开搜索={() => 设搜索展开(true)}
        打开筛选={() => 设筛选层开(true)}
        筛选生效数={筛选生效数}
      />

      {搜索展开 ? (
        <div className={样式.搜索行}>
          <div className={样式.搜索框}>
            <放大镜图标 尺寸={16} 色="#a7aa9f" />
            <input
              ref={搜索框}
              className={样式.搜索输入}
              value={搜索词}
              placeholder="搜职位、公司或关键词"
              enterKeyHint="search"
              onChange={(事件) => 设搜索词(事件.target.value)}
            />
            {搜索词 ? (
              <button
                className={`${样式.搜索清空} 可点`}
                onClick={() => 设搜索词('')}
                aria-label="清空搜索"
              >
                ✕
              </button>
            ) : null}
          </div>
          <button className={`${样式.搜索取消} 可点`} onClick={关闭搜索}>
            取消
          </button>
        </div>
      ) : (
        // 搜索时把代理横幅让出去：这一刻用户是自己在找岗，屏幕该留给结果
        <代理横幅
          前文="初筛与前几轮我已谈完，"
          强调={待协调数 > 0 ? `${待协调数} 个职位需要你协调` : '暂时没有需要你介入的'}
          按下={() => 跳转(路径.问AI代理)}
        />
      )}

      {/* 横幅与列表之间的固定留白（RN 里是一个 height:10 的占位 View） */}
      <div style={{ height: 10, flex: 'none' }} />

      <滚动区>
        <div className={样式.列表}>
          {显示列表.length === 0 ? (
            <空结果
              搜索词={搜索词.trim()}
              筛选生效数={筛选生效数}
              问代理={() => 跳转(路径.问AI代理)}
              重置筛选={() => 设筛选(空筛选)}
            />
          ) : (
            显示列表.map((岗) => (
              <市场卡
                key={岗.编号}
                岗={岗}
                已委托={状态.已委托.includes(岗.编号)}
                委托={() => 派发({ 型: '委托入谈', 岗 })}
                按下={() => 跳转(路径.职位详情(岗.编号))}
              />
            ))
          )}
        </div>
      </滚动区>

      {筛选层开 ? (
        <筛选层
          条件={筛选}
          城市选项={城市选项}
          结果数={显示列表.length}
          改条件={设筛选}
          关闭={() => 设筛选层开(false)}
        />
      ) : null}
    </主页外壳>
  );
}

/** 空态：把「为什么没结果」和「下一步能干什么」一起给出来，
 *  搜不到时的出口是代理 —— 本地包含匹配搜不到，不代表市场上没有。 */
function 空结果({
  搜索词,
  筛选生效数,
  问代理,
  重置筛选,
}: {
  搜索词: string;
  筛选生效数: number;
  问代理: () => void;
  重置筛选: () => void;
}) {
  const 有搜索 = 搜索词 !== '';
  const 有筛选 = 筛选生效数 > 0;

  // 三种空法的文案分开写：用户要先知道是「搜没搜着」「筛太狠了」还是「本来就没有」，
  // 才知道该改哪一步
  let 标题 = '这个意向下暂时没有新职位';
  let 说明 = '代理还在替你筛，有合适的会推过来。';
  if (有搜索) {
    标题 = `没有匹配「${搜索词}」的职位`;
    说明 = '这里只在已推荐的岗位里找。市场上还有没推给你的，让代理去搜一轮。';
  } else if (有筛选) {
    标题 = '没有符合当前筛选的职位';
    说明 = '放宽一两个条件试试，或者让代理按你的条件去市场上找。';
  }

  return (
    <div className={样式.空态}>
      <div className={样式.空态标题}>{标题}</div>
      <div className={样式.空态说明}>{说明}</div>
      {有搜索 || !有筛选 ? (
        <button className={`${样式.空态主键} 可点`} onClick={问代理}>
          让AI代理帮我搜
        </button>
      ) : null}
      {有筛选 ? (
        <button className={`${样式.空态次键} 可点`} onClick={重置筛选}>
          清空筛选条件
        </button>
      ) : null}
    </div>
  );
}

/** 底部筛选抽屉。改动即时生效（背后的列表跟着变），底部「查看 N 个结果」只是收起层。 */
function 筛选层({
  条件,
  城市选项,
  结果数,
  改条件,
  关闭,
}: {
  条件: 筛选条件;
  城市选项: string[];
  结果数: number;
  改条件: (条件: 筛选条件) => void;
  关闭: () => void;
}) {
  return (
    <div className={样式.遮罩} onClick={关闭}>
      <div className={样式.筛选层} onClick={(事件) => 事件.stopPropagation()}>
        <div className={样式.抓手} />
        <div className={样式.筛选标题}>筛选</div>

        <div className={`${样式.筛选内容} 滚动区`}>
          <div className={样式.分组标}>办公方式</div>
          <div className={样式.片行}>
            {办公方式选项.map((项) => (
              <button
                key={项}
                className={`${样式.片} ${条件.办公方式.includes(项) ? 样式.片选中 : ''} 可点`}
                onClick={() => 改条件({ ...条件, 办公方式: 切多选(条件.办公方式, 项) })}
              >
                {项}
              </button>
            ))}
          </div>

          <div className={样式.分组标}>城市</div>
          <div className={样式.片行}>
            {城市选项.length === 0 ? (
              <span className={样式.无选项}>这个意向下还没有岗位可选城市</span>
            ) : (
              城市选项.map((城) => (
                <button
                  key={城}
                  className={`${样式.片} ${条件.城市.includes(城) ? 样式.片选中 : ''} 可点`}
                  onClick={() => 改条件({ ...条件, 城市: 切多选(条件.城市, 城) })}
                >
                  {城}
                </button>
              ))
            )}
          </div>

          <div className={样式.开关行}>
            <span className={样式.开关文字}>
              <span className={样式.开关标题}>只看企业直招</span>
              <span className={样式.开关说明}>由用人公司自己发布，不经猎头转手</span>
            </span>
            <开关
              开={条件.仅企业直招}
              切换={() => 改条件({ ...条件, 仅企业直招: !条件.仅企业直招 })}
            />
          </div>

          {/* 这一项替代了别家的「期望薪资滑杆」：双方数字都不出，只交换有没有交集 */}
          <div className={`${样式.开关行} ${样式.无线}`}>
            <span className={样式.开关文字}>
              <span className={样式.开关标题}>只看薪资带与我有交集</span>
              <span className={样式.开关说明}>不比数字，只看两边区间有没有重叠</span>
            </span>
            <开关 开={条件.仅有交集} 切换={() => 改条件({ ...条件, 仅有交集: !条件.仅有交集 })} />
          </div>
        </div>

        <div className={样式.筛选底行}>
          <button className={`${样式.重置键} 可点`} onClick={() => 改条件(空筛选)}>
            重置
          </button>
          <button className={`${样式.查看键} 可点`} onClick={关闭}>
            查看 {结果数} 个结果
          </button>
        </div>
      </div>
    </div>
  );
}

/** 单张市场职位卡。
 *  这里刻意不用「白卡 按下=…」整卡可点：卡内还有两个自己的按钮（› 和 去谈键），
 *  HTML 里 button 不能嵌套 button，所以外层用不可点的白卡，卡主体单独做一个按钮。 */
function 市场卡({
  岗,
  已委托,
  委托,
  按下,
}: {
  岗: 市场职位;
  已委托: boolean;
  委托: () => void;
  按下: () => void;
}) {
  // 公司行 = 「公司名 · 其余信息」，第一段拆出来配字标，其余当规模行
  const [公司名, ...规模段] = 岗.公司行.split(' · ');
  const 规模行 = 规模段.join(' · ');

  return (
    <白卡 类名={样式.卡}>
      {/* 卡主体整块点进职位详情 */}
      <button className={`${样式.卡主体} 可点`} onClick={按下}>
        {/* 公司身份行：右列 = 适配环 + 薪资（标注 2026-08-18：与在谈卡同构，卡压矮）*/}
        <div className={样式.头行}>
          <span className={样式.公司字标}>{公司名.charAt(0)}</span>
          <span className={样式.公司组}>
            <span className={`${样式.公司名} 单行`}>{公司名}</span>
            <span className={`${样式.规模行} 单行`}>{规模行}</span>
          </span>
          <span className={样式.右列}>
            <适配环 分={岗.适配分} 标={null} />
            <span className={`${样式.薪资} 薪资体`}>{岗.薪资}</span>
          </span>
        </div>

        {/* 大职位名：这张卡的主角 */}
        <div className={样式.职位名}>{岗.职位}</div>

        <div className={样式.标签行}>
          {岗.标签.map((标签) => (
            <span key={标签} className={样式.标签}>
              {标签}
            </span>
          ))}
        </div>
      </button>

      {/* 底行：发布人身份 + 委托按钮。公司名头行已交代过，
          发布人若以公司名开头就只留身份段（如「企业直招」），不重复 */}
      <div className={样式.底行}>
        <span
          className={样式.发布人头像}
          style={{ background: 岗.发布人底色, color: 岗.发布人字色 }}
        >
          {岗.发布人首字}
        </span>
        <span className={`${样式.发布人} 单行`}>
          {岗.发布人.startsWith(`${公司名} · `)
            ? 岗.发布人.slice(公司名.length + 3)
            : 岗.发布人}
        </span>

        <button className={`${样式.尖括号} 可点`} onClick={按下} aria-label="查看职位详情">
          ›
        </button>

        {已委托 ? (
          // 委托后按钮换成不可点的状态标（代理已接手，不需要再点第二次）
          <span className={样式.已委托}>
            <span className={样式.已委托文字}>AI代理已接手</span>
          </span>
        ) : (
          <button className={`${样式.去谈键} 可点`} onClick={委托}>
            <谈判图标 />
            <span className={样式.去谈文字}>让AI代理去谈</span>
          </button>
        )}
      </div>
    </白卡>
  );
}
