/** 本地包含匹配：职位名、公司名、公司简介、标签四处任一命中即可（原型层不做分词与拼音）*/
function 命中搜索(岗: 市场职位, 关键词: string): boolean {
  if (关键词 === '') return true;
  return [岗.职位, 岗.公司, 岗.公司简介, ...岗.标签].some((文本) =>
    文本.toLowerCase().includes(关键词)
  );
}

export default function 看市场() {
  const { 状态, 派发, 数据源模式, 后端状态, 操作 } = use应用状态();
  const { 跳转 } = use导航();

  const [搜索展开, 设搜索展开] = useState(false);
  const [搜索词, 设搜索词] = useState('');
  const [筛选层开, 设筛选层开] = useState(false);
  const 搜索框 = useRef<HTMLInputElement>(null);
  // 本次进屏内点过「让AI代理去谈」的岗：卡先留在原位显示「AI代理已接手」，
  // 让用户看到这一下点到了；离开这一屏再回来就不再出现（它已经是一张在谈单了）。
  // 与企业端 候选推荐 的 本次已接触 同一写法。
  const 本次已委托 = useRef<Set<string>>(new Set());

  // ── P4：Backend 候选发现 ──────────────────────────────────────
  const 是后端 = 数据源模式 === 'backend';
  // 本次要委托的捕获（P5）：一份附件走 确认层 点名该文件；捕获只在非空时挂载层，
  // 取消即清、确认后立刻清 —— 上一次的披露授权绝不复用
  const [待确认委托, 设待确认委托] = useState<{ 视图: P4候选岗位页面; 选择: 附件简历选择值 } | null>(null);
  // 多份附件走 附件简历选择层：捕获待选的卡与权威库行，取消 / 确认即清
  const [待选择委托, 设待选择委托] = useState<{ 视图: P4候选岗位页面; 文件们: readonly BFF附件简历[] } | null>(null);
  // 反馈/委托写进行中：并发写会被操作层单飞丢弃，禁用动作键防静默丢点击
  const [反馈中, 设反馈中] = useState(false);

  // Backend 的 scope 坐标 = 当前意向编号 载体（水合后端意向 / Backend 切意向 写入的
  // intention_id）；当前意向 本身仍是意向名（Mock 语义不动，名字不唯一不可反查）。
  // 只有服务端 active 的编号才 admits 进市场流，否则不发任何 P4 请求（宁空勿错）。
  const 意向编号 = 状态.当前意向编号 ?? null;
  const 活跃意向 = 是后端 && 意向编号 !== null &&
      状态.后端意向服务端?.[意向编号]?.status === 'active'
    ? 意向编号
    : null;
  // 只选当前意向自己的快照：键按意向隔离，切换时旧 scope 的数据天然进不来
  const 后端快照 = 活跃意向 !== null ? 后端状态.候选岗位推荐?.[活跃意向] : undefined;
  const 后端卡们 = useMemo(
    () => (后端快照 ? 后端快照.items.map((卡) => ({ 视图: 从P4候选岗位(卡), 卡 })) : []),
    [后端快照]
  );

  // 进屏 / 切意向：先注册可见范围再懒加载（操作层的栅栏要靠注册的可见范围对上）；
  // 离开本屏或换 scope 时把可见范围清成 null，别让详情页等屏背上旧范围。
  useEffect(() => {
    if (!是后端 || 活跃意向 === null) return;
    操作.设置发现推荐范围('candidate', P4范围键.候选列表(活跃意向));
    void 操作.加载候选岗位(活跃意向).catch(() => undefined);
    return () => 操作.设置发现推荐范围('candidate', null);
  }, [是后端, 活跃意向, 操作]);

  // 进行中委托（accepted/evaluating）交给页面域轮询钩子；暂停表里的委托把
  // 「AI代理已接手」覆盖成中性文案 —— 绝不伪造终态回执。Mock 不开节拍。
  const 进行中委托 = useMemo(
    () => 后端卡们.flatMap(({ 卡 }) => {
      const 委托 = 卡.delegation;
      return 委托 !== null && (委托.state === 'accepted' || 委托.state === 'evaluating')
        ? [{ role: 'candidate' as const, delegationId: 委托.delegation_id, state: 委托.state }]
        : [];
    }),
    [后端卡们]
  );
  const 进度未知 = use发现推荐委托轮询({
    开启: 是后端,
    委托: 进行中委托,
    刷新: 操作.刷新委托,
    // scope 变化即结束本轮询周期：换意向不带走上一意向的连续失败计数（§8.3）
    范围键: 活跃意向,
  });

  // 委托第一跳（P5）：先拿权威附件库，再让用户显式选定这次提交的简历坐标。
  // 读失败 → P4 失败 toast（零导航零委托）；null（会话/角色换代）→ 静默返回，
  // 绝不当成空库走「去上传」的跳转分支。
  const 开始委托 = async (视图: P4候选岗位页面) => {
    if (!视图.recommendationId || !视图.intentionId) return;
    try {
      const 库 = await 操作.准备候选委托简历();
      if (库 === null) return;
      if (库.items.length === 0) {
        轻提示('请先上传一份 PDF 简历');
        跳转(路径.我的简历);
        return;
      }
      if (库.items.length === 1) {
        const 唯一 = 库.items[0];
        if (唯一) 设待确认委托({ 视图, 选择: 从附件行取选择值(唯一) });
        return;
      }
      设待选择委托({ 视图, 文件们: 库.items });
    } catch (错误) {
      轻提示(P4错误文案(错误));
    }
  };

  // 确认层只在这里真正发起委托：先收层再 await —— 任何失败（含终态/拒绝回执）
  // 都要求下一次点击重新过确认，上一次的披露授权绝不复用。
  const 执行候选委托 = async (视图: P4候选岗位页面, 选择: 附件简历选择值) => {
    if (!视图.recommendationId || !视图.intentionId) return;
    设待确认委托(null);
    设反馈中(true);
    try {
      await 操作.委托候选岗位({
        intentionId: 视图.intentionId,
        recommendationId: 视图.recommendationId,
        jobId: 视图.jobId,
        resumeFileId: 选择.fileId,
        resumeFileVersionId: 选择.fileVersionId,
        disclosureAcknowledged: true,
      });
    } catch (错误) {
      轻提示(P4错误文案(错误));
    } finally {
      设反馈中(false);
    }
  };

  // 下拉只重读当前 scope（GET）；空态的「让AI代理帮我搜」才建新批次（POST+GET）。
  // 下拉把这个 Promise 交回 下拉刷新：转圈等真实 GET settle，不是干等最短动画。
  const 重读当前范围 = () => {
    if (活跃意向 === null) return;
    // 这里的静默不是漏提示：加载失败（含下拉重读）的文案由操作层落进快照 error，
    // 列表上方的错误/未决行负责呈现 —— 再 toast 一次就成了双重提示，别「修」它。
    return 操作.加载候选岗位(活跃意向, true).catch(() => undefined);
  };
  const 请代理再搜 = () => {
    if (活跃意向 === null) return;
    void 操作.刷新候选岗位(活跃意向).catch((错误: unknown) => 轻提示(P4错误文案(错误)));
  };

  // 从「在谈」子视图点放大镜 / 筛选时本页还没挂载，顶部意向栏把意图存进模块级信号，
  // 这里挂载后取走并打开对应工具（取走即复位，下次进来不会自己弹开）
  useEffect(() => {
    const 待办 = 取走市场工具请求();
    if (待办 === '搜索') 设搜索展开(true);
    if (待办 === '筛选') 设筛选层开(true);
  }, []);

  // 搜索行展开就把光标送进输入框，省用户一次点击
  useEffect(() => {
    if (搜索展开) 搜索框.current?.focus();
  }, [搜索展开]);

  // 标注意见 #9：切意向后市场职位流跟着变；
  // 「不感兴趣」的岗在这一步就被剔除 —— 用户说过不想再看见，它不该再参与后面任何一步。
  // 被屏蔽的公司同样剔除：屏蔽在本产品里是双向的（你看不到它、它也匹配不到你），
  // 举报层里勾了「同时屏蔽」之后回到这一屏还能看见它的岗，那个承诺就是假的。
  // P4：Backend 完全不读 市场列表（列表只来自候选岗位快照），Mock 原样保留这套过滤。
  const 屏蔽公司 = useMemo(
    () => new Set(状态.屏蔽名单.map((条) => 条.名称)),
    [状态.屏蔽名单]
  );
  const 本意向市场 = useMemo(
    () =>
      (是后端
        ? []
        : 市场列表.filter((岗) => {
          if (岗.意向 !== 状态.当前意向) return false;
          if (状态.不感兴趣岗位.includes(岗.编号)) return false;
          if (屏蔽公司.has(岗.公司)) return false;
          // 已委托代理去谈的岗要退出市场流：它已经变成一张在谈单，继续留在待选列表里
          // 就是一张点不动的死卡 —— 委托 8 个岗就永久堵 8 张，而且会让用户反过来怀疑
          // 「我到底委托成功没有」（还在待选列表 = 看起来像没委托上）。
          // 只有本次进屏里刚点的那张先留着显示「AI代理已接手」，把这一下的反馈给足，
          // 下次进来才移出 —— 企业端 候选推荐 的已接触推荐就是这个口径，照它写。
          if (状态.已委托.includes(岗.编号) && !本次已委托.current.has(岗.编号)) return false;
          return true;
        })),
    [是后端, 状态.当前意向, 状态.不感兴趣岗位, 屏蔽公司, 状态.已委托]
  );

  const 关键词 = 搜索词.trim().toLowerCase();
  const 显示列表 = useMemo(
    () => 本意向市场.filter((岗) => 命中搜索(岗, 关键词)),
    [本意向市场, 关键词]
  );
  const 后端显示 = useMemo(
    () => 后端卡们.filter(({ 视图 }) => 命中搜索(视图.卡, 关键词)),
    [后端卡们, 关键词]
  );

  // Backend 列表态：无活跃意向 / 首载进行中 / 首载失败（给明确重试）；
  // 已有卡的快照不管阶段（刷新失败保留旧卡，错误单独一行交代）都算「有卡」。
  const 后端列表态: '无活跃意向' | '载入中' | '失败' | '有卡' =
    活跃意向 === null
      ? '无活跃意向'
      : 后端快照 === undefined ||
          (后端快照.items.length === 0 &&
            (后端快照.阶段 === '未开始' || 后端快照.阶段 === '进行中'))
        ? '载入中'
        : 后端快照 !== undefined && 后端快照.items.length === 0 && 后端快照.阶段 === '失败'
          ? '失败'
          : '有卡';

  // 顶栏「筛选 ▾」右上角的数字 = 代理正在生效的规则条数（不再是本地档位维度数）。
  // P6：Backend 只认已水合的权威规则 —— candidate rules 未水合时不出角标数，
  // 宁可少显示一个数字，也不把 Mock 种子数当真（与 规则库 门控同一口径）。
  const 可显示候选规则数 = 数据源模式 === 'mock' || 后端状态.Agent规则水合.candidate.rules === '成功';
  const 生效规则数 = 可显示候选规则数
    ? [...状态.全局规则, ...状态.意向级规则].filter((条) => 条.生效).length
    : 0;

  // 需要你协调的条数从在谈列表实时算，横幅文案与「在谈」子视图保持一致，
  // 免得同一句话在两个子视图里给出不同数字。
  const 待协调数 = 状态.在谈列表.filter((单) => 单.需要你).length;

  const 关闭搜索 = () => {
    设搜索展开(false);
    设搜索词('');
  };

  return (
    <主页外壳>
      <顶部意向栏
        打开搜索={() => 设搜索展开(true)}
        打开筛选={() => 设筛选层开(true)}
        筛选生效数={生效规则数}
      />

      {搜索展开 ? (
        <div className={样式.搜索行}>
          <div className={样式.搜索框}>
            <放大镜图标 尺寸={16} 色="#a7aa9f" />
            <input
              ref={搜索框}
              className={样式.搜索输入}
              value={搜索词}
              placeholder="搜职位、公司或关键词"
              enterKeyHint="search"
              onChange={(事件) => 设搜索词(事件.target.value)}
            />
            {搜索词 ? (
              <button
                className={`${样式.搜索清空} 可点`}
                onClick={() => 设搜索词('')}
                aria-label="清空搜索"
              >
                ✕
              </button>
            ) : null}
          </div>
          <button className={`${样式.搜索取消} 可点`} onClick={关闭搜索}>
            取消
          </button>
        </div>
      ) : (
        // 搜索时把代理横幅让出去：这一刻用户是自己在找岗，屏幕该留给结果
        <代理横幅
          前文="初筛与前几轮我已谈完，"
          强调={待协调数 > 0 ? `${待协调数} 个职位需要你协调` : '暂时没有需要你介入的'}
          按下={() => 跳转(路径.问AI代理)}
        />
      )}

      {/* 横幅与列表之间的固定留白（RN 里是一个 height:10 的占位 View） */}
      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新 刷新={是后端 ? 重读当前范围 : undefined}>
      <滚动区>
        <div className={样式.列表}>
          {是后端 ? (
            <>
              {/* 刷新未决（POST 成功 / follow-up GET 失败）：旧卡保留，错误单独一行交代 */}
              {后端快照?.error && 后端卡们.length > 0 && !后端快照.刷新中 ? (
                <div className={样式.空态说明} style={{ padding: '0 4px 6px' }}>
                  {后端快照.error}
                </div>
              ) : null}
              {后端列表态 === '无活跃意向' ? (
                <div className={样式.空态}>
                  <div className={样式.空态标题}>还没有进行中的求职意向</div>
                  <div className={样式.空态说明}>代理只替进行中的意向看市场，先去补一条求职意向吧。</div>
                </div>
              ) : 后端列表态 === '载入中' ? (
                <div className={样式.空态}>
                  <div className={样式.空态标题}>正在为你挑岗位…</div>
                </div>
              ) : 后端列表态 === '失败' ? (
                <div className={样式.空态}>
                  <div className={样式.空态标题}>推荐暂时加载不了</div>
                  <div className={样式.空态说明}>{后端快照?.error}</div>
                  <button className={`${样式.空态主键} 可点`} onClick={重读当前范围}>
                    重试
                  </button>
                </div>
              ) : 后端显示.length === 0 ? (
                <空结果 搜索词={搜索词.trim()} 问代理={请代理再搜} />
              ) : (
                后端显示.map(({ 视图, 卡 }) => (
                  <市场卡
                    key={卡.recommendation_id}
                    岗={视图.卡}
                    已委托={卡.delegation !== null}
                    已委托文字={
                      卡.delegation !== null && 进度未知.has(卡.delegation.delegation_id)
                        ? P4委托进度未知文案
                        : 'AI代理已接手'
                    }
                    委托禁用={反馈中}
                    委托={() => void 开始委托(视图)}
                    按下={() => 跳转(路径.职位详情(视图.jobId))}
                  />
                ))
              )}
            </>
          ) : (
            <>
              {显示列表.length === 0 ? (
                <空结果 搜索词={搜索词.trim()} 问代理={() => 跳转(路径.问AI代理)} />
              ) : (
                显示列表.map((岗) => (
                  <市场卡
                    key={岗.编号}
                    岗={岗}
                    已委托={状态.已委托.includes(岗.编号)}
                    委托={() => {
                      // 先记本次，再派发：否则这一派发就把卡从列表里过滤掉，
                      // 用户看不到「AI代理已接手」那一下，只看到卡凭空消失
                      本次已委托.current.add(岗.编号);
                      派发({ 型: '委托入谈', 岗 });
                    }}
                    按下={() => 跳转(路径.职位详情(岗.编号))}
                  />
                ))
              )}
            </>
          )}
        </div>
      </滚动区>
      </下拉刷新>

      {筛选层开 ? <筛选层 关闭={() => 设筛选层开(false)} /> : null}

      {待选择委托 ? (
        // 多份附件：必须单选一份才可确认；取消 / 遮罩 / Esc 都只清捕获零请求，
        // 确认值只来自所选行的当前 file/version，层内文案声明授权仅对这一次委托生效
        <附件简历选择层
          文件们={待选择委托.文件们}
          取消={() => 设待选择委托(null)}
          确认={(选择) => {
            const 捕获 = 待选择委托;
            设待选择委托(null); // 先收层再发委托：失败要求下一次重新选
            if (捕获) void 执行候选委托(捕获.视图, 选择);
          }}
        />
      ) : null}

      {待确认委托 ? (
        // 不可逆动作的披露确认：正文点名这次提交哪份 PDF、披露什么，且仅对这一次
        // 委托生效；取消 / 遮罩 / Esc 都是零请求零状态，确认后才发起委托
        <确认层
          标题="确认委托AI代理？"
          正文={`S0 通过后，本 Case 将提交「${待确认委托.选择.displayName}」这份 PDF，并向该招聘方披露姓名和联系方式。本次授权仅对这一次委托生效。`}
          执行文="确认委托"
          取消文="暂不委托"
          取消={() => 设待确认委托(null)}
          执行={() => void 执行候选委托(待确认委托.视图, 待确认委托.选择)}
        />
      ) : null}
    </主页外壳>
  );
}

/** 空态：把「为什么没结果」和「下一步能干什么」一起给出来，
 *  搜不到时的出口是代理 —— 本地包含匹配搜不到，不代表市场上没有。
 *  本地档位筛选删掉之后就只剩两种空法：搜没搜着，和本来就没有。 */
function 空结果({ 搜索词, 问代理 }: { 搜索词: string; 问代理: () => void }) {
  const 有搜索 = 搜索词 !== '';

  const 标题 = 有搜索 ? `没有匹配「${搜索词}」的职位` : '这个意向下暂时没有新职位';
  const 说明 = 有搜索
    ? '这里只在已推荐的岗位里找。市场上还有没推给你的，让代理去搜一轮。'
    : '代理还在替你筛，有合适的会推过来。';

  return (
    <div className={样式.空态}>
      <div className={样式.空态标题}>{标题}</div>
      <div className={样式.空态说明}>{说明}</div>
      <button className={`${样式.空态主键} 可点`} onClick={问代理}>
        让AI代理帮我搜
      </button>
    </div>
  );
}

/**
 * 底部层：告诉AI代理你的硬性要求。
 *
 * 它不是过滤器 —— 这个产品里筛岗本来就是 AI 代理干的活，用户手工勾一遍档位条件、
 * 关掉就没了，等于白说。所以这一层是规则清单：全局规则 + 意向级规则一排一条，
 * 每行一个输入框，可改、可删、可新增，改完失焦当场落进规则库，下一轮代理照它筛。
 * 与企业端 候选筛选抽屉 同构，只换数据源与「管理规则」的去处。
 *
 * P6 模式边界：Backend 下这一层转只读 —— 权威规则按行展示为纯文本，无输入、无删除、
 * 无新增；rules 未水合前不出清单（宁缺勿错）。Mock 保持原型交互原样。
 */
function 筛选层({ 关闭 }: { 关闭: () => void }) {
  const { 状态, 派发, 数据源模式, 后端状态 } = use应用状态();
  const { 跳转 } = use导航();

  // P6：Backend 只读；权威规则展示同 规则库 门控 —— rules 成功前不出清单
  const 是Backend = 数据源模式 === 'backend';
  const 可显示规则 = 数据源模式 === 'mock' || 后端状态.Agent规则水合.candidate.rules === '成功';

  // 只存被改动过的那几行；没动过的行直接显示规则库里的原值，避免打开层就整份复制一遍
  const [编辑文本, 设编辑文本] = useState<Record<string, string>>({});
  // 新增行的内容；null = 当前没有在新增
  const [新行, 设新行] = useState<string | null>(null);

  // 规则库分全局与意向级两组，但这一层不做分组展示 —— 用户在这儿关心的是
  // 「代理现在按哪些话筛」，不是这条话挂在哪一层；改/删动作两组都能命中。
  const 规则清单 = [...状态.全局规则, ...状态.意向级规则];

  /** 已有行失焦即落库。清空视为放弃这次编辑（要删就点行尾 ✕，不靠清空来删） */
  const 提交编辑 = (编号: string, 原内容: string) => {
    const 内容 = (编辑文本[编号] ?? 原内容).trim();
    设编辑文本((旧) => {
      const 新 = { ...旧 };
      delete 新[编号];
      return 新;
    });
    if (内容 && 内容 !== 原内容) 派发({ 型: '改规则', 编号, 内容 });
  };

  /** 新增行失焦即落库；内容为空就当这一行没写过 */
  const 提交新行 = () => {
    const 内容 = (新行 ?? '').trim();
    设新行(null);
    if (内容) 派发({ 型: '新增规则', 内容, 来源: '筛选设定' });
  };

  /** 回车 = 写完这一行：交给失焦逻辑落库，手机上也顺手收起键盘 */
  const 回车即失焦 = (事件: KeyboardEvent<HTMLInputElement>) => {
    if (事件.key === 'Enter' && !事件.nativeEvent.isComposing) 事件.currentTarget.blur();
  };

  return (
    <弹层框架 标签="岗位筛选规则" 遮罩类名={样式.遮罩} 面板类名={样式.筛选层} 关闭={关闭}>
        <div className={样式.抓手} />

        <div className={样式.要求标题行}>
          <span className={样式.筛选标题}>告诉AI代理你的硬性要求</span>
          <button
            className={`${样式.管理规则} 可点`}
            onClick={() => {
              关闭();
              跳转(路径.规则库);
            }}
          >
            管理规则 ›
          </button>
        </div>

        <div className={`${样式.筛选内容} 滚动区`}>
          {是Backend ? (
            // Backend：权威规则按行展示为纯文本（版式借用 .规则输入 的行外观）——
            // 增改删一律去 规则库（右上 管理规则 ›），本层不提供任何写入口
            (可显示规则
              ? 规则清单.map((条) => (
                  <div key={条.编号} className={`${样式.规则行} ${样式.规则输入}`}>
                    {条.内容}
                  </div>
                ))
              : null)
          ) : (
            <>
              {规则清单.map((条) => (
                <div key={条.编号} className={样式.规则行}>
                  <input
                    className={样式.规则输入}
                    value={编辑文本[条.编号] ?? 条.内容}
                    enterKeyHint="done"
                    onChange={(事件) => 设编辑文本({ ...编辑文本, [条.编号]: 事件.target.value })}
                    onBlur={() => 提交编辑(条.编号, 条.内容)}
                    onKeyDown={回车即失焦}
                  />
                  <button
                    className={`${样式.删行} 可点`}
                    onClick={() => 派发({ 型: '删规则', 编号: 条.编号 })}
                    aria-label={`删除规则 ${条.内容}`}
                  >
                    ✕
                  </button>
                </div>
              ))}

              {新行 !== null ? (
                <div className={样式.规则行}>
                  <input
                    className={样式.规则输入}
                    value={新行}
                    autoFocus
                    enterKeyHint="done"
                    onChange={(事件) => 设新行(事件.target.value)}
                    onBlur={提交新行}
                    onKeyDown={回车即失焦}
                  />
                  {/* 按下就失焦会先触发 提交新行，那样点 ✕ 反而把这行存下来了；
                      拦掉 mousedown 的默认行为，保证 ✕ 的语义就是丢弃这一行 */}
                  <button
                    className={`${样式.删行} 可点`}
                    onMouseDown={(事件) => 事件.preventDefault()}
                    onClick={() => 设新行(null)}
                    aria-label="放弃这一条"
                  >
                    ✕
                  </button>
                </div>
              ) : null}

              <button className={`${样式.添加行} 可点`} onClick={() => 设新行('')}>
                ＋ 添加规则
              </button>
            </>
          )}
        </div>

        {/* 每一行都是即时落库，所以底部这一键只负责收起来 */}
        <button className={`${样式.完成键} 可点`} onClick={关闭}>
          完成
        </button>
    </弹层框架>
  );
}

/** 单张市场职位卡。
 *  骨架与「在谈卡」完全一致（公司头行 → 职位名 → 标签行），唯一的差别在最下面那一段：
 *  在谈卡是「阶段 + 需要你 + 下一步」，市场卡是「发布人 + 让AI代理去谈」。
 *  用户点了「让AI代理去谈」，这张卡就原样长出下半段搬到在谈列表里 —— 同一张卡的两个状态，
 *  所以两边不能长得不一样（用户口径 2026-08-18）。
 *
 *  这里刻意不用「白卡 按下=…」整卡可点：卡内还有两个自己的按钮（› 和 去谈键），
 *  HTML 里 button 不能嵌套 button，所以外层用不可点的白卡，卡主体单独做一个按钮。 */
function 市场卡({
  岗,
  已委托,
  委托,
  按下,
  已委托文字 = 'AI代理已接手',
  委托禁用 = false,
}: {
  岗: 市场职位;
  已委托: boolean;
  委托: () => void;
  按下: () => void;
  /** 状态标文字；Backend 轮询连败时被「进度未知」的中性文案覆盖 */
  已委托文字?: string;
  /** Backend 反馈/委托写进行中时禁用去谈键（并发写会被操作层单飞丢弃） */
  委托禁用?: boolean;
}) {
  return (
    <白卡 类名={样式.卡}>
      {/* 卡主体整块点进职位详情 */}
      <button className={`${样式.卡主体} 可点`} onClick={按下}>
        {/* 公司头行：字标 + 公司名/简介 + 右列[适配环 + 薪资]，与在谈卡一比一 */}
        <div className={样式.公司头行}>
          <公司字标 首字={岗.公司首字} 公司名={岗.公司} 尺寸={34} 圆角={10} 字号={14} />
          <div style={{ flex: 1, minWidth: 0 }}>
            <div className={`${样式.公司名} 单行`}>{岗.公司}</div>
            <div className={`${样式.公司简介} 单行`}>{岗.公司简介}</div>
          </div>
          <div className={样式.右列}>
            <适配环 分={岗.适配分} 标={null} />
            <span className={`${样式.薪资} 薪资体`}>{岗.薪资.replace('-', '–')}</span>
          </div>
        </div>

        {/* 职位名 */}
        <div className={`${样式.职位名} 单行`}>{岗.职位}</div>

        {/* 标签行：岗位属性，与在谈卡同一口径（城市 · 区 / N 薪 / 办公方式 / 到岗） */}
        <div className={样式.标签行}>
          {岗.标签.map((标签) => (
            <span key={标签} className={样式.标签}>
              {标签}
            </span>
          ))}
        </div>
      </button>

      {/* 底行 —— 在谈卡在这个位置是「阶段 + 下一步」，市场卡是「发布人 + 去谈」。
          公司名头行已交代过，发布人若以公司名开头就只留身份段（如「企业直招」），不重复 */}
      <div className={样式.底行}>
        <span
          className={样式.发布人头像}
          style={{ background: 岗.发布人底色, color: 岗.发布人字色 }}
        >
          {岗.发布人首字}
        </span>
        <span className={`${样式.发布人} 单行`}>
          {岗.发布人.startsWith(`${岗.公司} · `) ? 岗.发布人.slice(岗.公司.length + 3) : 岗.发布人}
        </span>

        <button className={`${样式.尖括号} 可点`} onClick={按下} aria-label="查看职位详情">
          ›
        </button>

        {已委托 ? (
          // 委托后按钮换成不可点的状态标（代理已接手，不需要再点第二次）
          <span className={样式.已委托}>
            <span className={样式.已委托文字}>{已委托文字}</span>
          </span>
        ) : (
          <button
            className={`${样式.去谈键} 可点`}
            disabled={委托禁用}
            onClick={委托}
          >
            <谈判图标 />
            <span className={样式.去谈文字}>让AI代理去谈</span>
          </button>
        )}
      </div>
    </白卡>
  );
}
