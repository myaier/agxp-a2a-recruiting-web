// A14 职位Tab·看市场 —— 自己刷市场上的职位，每张卡上带「让AI代理去谈」。
//
// 与「在谈」共用顶栏（意向左右平铺切换 + 在谈/看市场子视图）和代理横幅，
// 所以这两屏切换时顶部不动，只有列表在换 —— 这是设计稿里的硬要求。
//
// 卡片版式（2026-08-18 参考 Jobright 岗位卡重排，用户指定）：
//   公司字标 + 公司名/规模行 + 右上适配环 → 大职位名 → 薪资行 → 标签行
//   → 分隔线 → 发布人 + 「让AI代理去谈」。
// 借它的骨架（公司身份先行、匹配分做环形进度、标题放大），但三处按我们的立场改：
//   · 薪资不进标签堆 —— 单独一行 薪资体，价格标地位不动摇；
//   · 适配环按分数换语义色（≥80 翠绿 / 65-79 协调橙 / 更低灰），不是装饰绿；
//   · 底行不放收藏/屏蔽小图标，只放我们的差异点：让AI代理去谈。
//
// 搜索与筛选都长在这一屏（2026-08-18 补）：顶部意向栏的放大镜 / 筛选 ▾ 只负责打开它们。
// 列表 = 当前意向 → 去掉不感兴趣与被屏蔽的 → 过搜索。
//
// 筛选层已经彻底改成规则清单（2026-08-20）：过滤在本产品里是代理的活，
// 用户写下的是长期规则、不是一次性档位，所以这一屏不再做任何本地档位过滤 ——
// 城市 / 办公方式 / 公司类型 / 薪资带交集那一套连同 过筛选 都已删掉，
// 列表里的岗位就是代理按规则筛过之后的结果。
//
// P6 模式边界：写规则的入口收敛到 规则库（canonical，层内右上「管理规则 ›」）。
// Backend 下筛选层转只读 —— 权威规则按行展示为纯文本，无输入、无删除、无新增，
// 且与 规则库 同一口径：candidate rules 未水合前不出清单，角标数同样不出（宁缺勿错）。
// Mock 保持原型交互原样。
//
// P4 模式边界：Backend 列表只来自当前活跃意向（scope 坐标 = 当前意向编号 载体里的
// intention_id，且 服务端 status === 'active'）的候选岗位快照，经 从P4候选岗位 投影；
// 不读 市场列表、不做 Mock 屏蔽公司过滤（P4/P3 已在服务端收口）。搜索仍是本地包含
// 匹配；下拉只重读（GET），空态「让AI代理帮我搜」才建新批次（POST+GET）。
// 委托必过显式披露确认（P5：先拿权威附件库 —— 零份去上传、一份 确认层 点名、
// 多份 附件简历选择层 单选），确认不复用；委托后不写任何 Mock 在谈状态、不跳页，
// 进行中回执交给 use发现推荐委托轮询 按节拍刷新。

import { useEffect, useMemo, useRef, useState, type KeyboardEvent } from 'react';
import 弹层框架 from '../组件/弹层框架';
