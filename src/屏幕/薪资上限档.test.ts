// 锁住薪资上限档的两条规则（标注 2026-08-23）。
// 这两条是产品负责人用具体例子定的，规则本身没有别处记录，
// 只靠代码注释很容易在后续重构里被改坏 —— 所以钉住。
//
// bottom-drawer 统一 Task 5：算法正文原样迁到 组件/引导薪资档位（组件不依赖页面），
// 测试 import 指向新模块，期望值仍全部用字面常量，不调用生产算法生成期望。
import { describe, expect, it } from 'vitest';
import { 日薪档, 上限日薪档, 上限薪资档, 算上限档表, 薪资档 } from '../组件/引导薪资档位';

const 算 = (下限: number) => 算上限档表(下限, 上限薪资档, false);
const 算日 = (下限: number) => 算上限档表(下限, 上限日薪档, true);

describe('薪资上限档', () => {
  it('产品负责人给的两个例子必须精确命中', () => {
    // 「10K 最多滑到 15K，25K 最多可以滑到 50K」
    expect(算(10).at(-1)).toBe(15);
    expect(算(25).at(-1)).toBe(50);
  });

  it('下限附近按 1 步长加密，不跳档', () => {
    // 「我选 26k 的时候，右边最高应该是 27K，中间多跳过了一个」
    expect(算(26).slice(0, 5)).toEqual([27, 28, 29, 30, 31]);
    expect(算(1)[0]).toBe(2); // 「左边最低选择 1k，右边最高就应该是 2k 起步」
  });

  it('每一档都严格大于下限', () => {
    for (const 下限 of [1, 5, 10, 12, 20, 25, 40, 80, 150, 250]) {
      expect(算(下限).every((档) => 档 > 下限)).toBe(true);
    }
  });

  it('倍率平滑过渡，10K 与 12K 之间不突跳', () => {
    // 曾经在 10K 处从 1.5 倍硬切到 2 倍：10K 帽 15、12K 帽 24，
    // 差 2K 的两个人可选带宽差 9K。
    const 差 = 算(12).at(-1)! - 算(10).at(-1)!;
    expect(差).toBeLessThanOrEqual(6);
  });

  it('帽不超出档表自身上界', () => {
    // 250K × 2 = 500K，而档表最高 260K —— 不夹会把表外的数塞进滚轮
    expect(算(250).every((档) => 档 <= 260)).toBe(true);
  });

  it('面议（下限 0）没有上限档，右轮换成空位', () => {
    expect(算(0)).toEqual([]);
  });

  it('高段不被 1 步长占满', () => {
    // 年薪 150K 的人不在意 1K 差别；固定 10K 加密跨度会排成 151、152…160
    const 表 = 算(150);
    expect(表[1] - 表[0]).toBeGreaterThan(1);
  });

  // ── 日薪同口径反例（Task 5 迁移后一并钉住；分界 200 元/天 ≈ 月薪 10K 日均）──
  it('日薪下限最高 2000 仍有 2200 上限', () => {
    // 2000 × 2 = 4000，但档表上界 2200 —— 帽必须夹在表内
    expect(算日(2000).at(-1)).toBe(2200);
  });

  it('日薪面议没有上限档', () => {
    expect(算日(0)).toEqual([]);
  });

  it('日薪低段 1.5 倍：100 元/天帽 150（与月薪 10K→15K 同一规则）', () => {
    expect(算日(100).at(-1)).toBe(150);
  });

  it('迁移不改动档表正文：月薪含面议 0 与 260 上限档，日薪含 2200 上限档', () => {
    expect(薪资档[0]).toBe(0);
    expect(上限薪资档.at(-1)).toBe(260);
    expect(日薪档[0]).toBe(0);
    expect(上限日薪档.at(-1)).toBe(2200);
  });
});
