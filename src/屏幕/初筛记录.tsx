// 本周初筛记录 —— 企业端「AI代理动态 › 日报卡 › 硬性匹配」那一行点进来的一屏。
//
// 存在的理由：日报卡上「触达 23 → 硬性匹配 12」「替你挡掉 3 个硬性不符的」原来点不动，
// 代理到底怎么筛的、挡掉的是谁、按哪条硬性挡的，全都看不到。
// 与 屏幕/已筛候选 同一条口径：代理替你挡掉的人不能是一个静默的黑洞，必须可回看。
// 挡掉的那条不进在谈列表，只在这份记录里可见 —— 这正是这一屏存在的意义。
//
// 双盲不变：整屏只有代号与画像，没有真名；薪资只以「有交集」这类结论出现，不出任何数字。

import 样式 from './初筛记录.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import {
  在招岗位列表,
  本周初筛记录,
  type 初筛记录 as 初筛记录条,
} from '../数据/企业端模拟数据';

/**
 * 单条初筛对话的路径。路由注册与 路径表 条目由下一步补上，
 * 这里先按规格里的字面量走，注册完把这个常量换成 路径.初筛对话(编号) 即可。
 */
const 初筛对话路径 = (编号: string) => `/hr/screening-log/${编号}`;

/** 一个岗位分组：小节头（岗位名）+ 这个岗位下的初筛记录 */
interface 岗位分组 {
  岗位编号: string;
  岗位名: string;
  记录们: 初筛记录条[];
}

/**
 * 按岗位把记录分组。
 * 组序跟 在招岗位列表 走，保证每次进来顺序一样；
 * 记录里出现的岗位若已不在在招列表里（岗位被归档过），照样单独成组排在最后，
 * 不能因为查不到岗位名就把这条记录悄悄丢掉 —— 丢掉就又成了黑洞。
 */
function 按岗位分组(记录们: 初筛记录条[]): 岗位分组[] {
  const 组表 = new Map<string, 初筛记录条[]>();
  for (const 条 of 记录们) {
    const 已有 = 组表.get(条.岗位编号);
    if (已有) 已有.push(条);
    else 组表.set(条.岗位编号, [条]);
  }

  const 岗位序 = (岗位编号: string) => {
    const 序 = 在招岗位列表.findIndex((岗) => 岗.编号 === 岗位编号);
    return 序 === -1 ? 在招岗位列表.length : 序;
  };

  return [...组表.entries()]
    .sort(([甲], [乙]) => 岗位序(甲) - 岗位序(乙))
    .map(([岗位编号, 本组记录]) => ({
      岗位编号,
      // 查不到岗位档就退回岗位编号本身，不编一个名字出来
      岗位名: 在招岗位列表.find((岗) => 岗.编号 === 岗位编号)?.名称 ?? 岗位编号,
      记录们: 本组记录,
    }));
}

export default function 初筛记录() {
  const { 跳转, 返回 } = use导航();
  const 分组们 = 按岗位分组(本周初筛记录);

  return (
    <次级页外壳>
      <返回栏 返回={返回} 标题="本周初筛记录" />

      <滚动区>
        <div className={样式.列表}>
          {分组们.length === 0 ? (
            <div className={样式.空态}>本周还没有初筛记录</div>
          ) : (
            分组们.map((组) => (
              <div key={组.岗位编号} className={样式.分组}>
                <div className={`${样式.岗位名} 单行`}>{组.岗位名}</div>
                <div className={样式.卡}>
                  {组.记录们.map((条, 序) => (
                    <记录行
                      key={条.编号}
                      条={条}
                      末条={序 === 组.记录们.length - 1}
                      按下={() => 跳转(初筛对话路径(条.编号))}
                    />
                  ))}
                </div>
              </div>
            ))
          )}
        </div>
      </滚动区>
    </次级页外壳>
  );
}

/**
 * 一条初筛记录 = 一行。
 * 头像沿用双盲画法：头像字 + 灰绿底（var(--初筛)），不用真人照片、不用真名首字。
 * 右侧结果标只有「通过」「挡掉」两个词，不加任何解释；
 * 小字行是 硬性 N/5 与完成时间，两个都是记录自带的字段。
 */
function 记录行({
  条,
  末条,
  按下,
}: {
  条: 初筛记录条;
  末条: boolean;
  按下: () => void;
}) {
  const 通过 = 条.结果 === '通过';

  return (
    <button
      className={`${样式.记录行} ${末条 ? 样式.末条 : ''} 可点`}
      // 行内文字分散在三行嵌套 span 里，读屏拼不出一句完整的行名；
      // 这里把这一行本来就看得见的四项按阅读顺序拼一遍，不新增任何行上没有的信息
      aria-label={`${条.代号}，${条.画像}，${条.结果}，硬性 ${条.硬性通过}`}
      onClick={按下}
    >
      <span className={样式.头像}>
        <span className={样式.头像字}>{条.头像字}</span>
      </span>

      <span className={样式.文本组}>
        <span className={样式.名行}>
          <span className={`${样式.代号} 单行`}>{条.代号}</span>
          <span
            className={`${样式.结果标} ${通过 ? 样式.结果通过 : 样式.结果挡掉}`}
          >
            {条.结果}
          </span>
        </span>
        <span className={`${样式.画像} 单行`}>{条.画像}</span>
        <span className={样式.小字行}>
          硬性 <span className="等宽数字">{条.硬性通过}</span>
          <span className={样式.小字分}>·</span>
          <span className="等宽数字">{条.完成于}</span>
        </span>
      </span>
    </button>
  );
}
