// A19 会话详情 · 真人接管 —— 意向确认后 AI 代理退场，招聘顾问真人上场谈落地细节。
//
// 结构：返回栏（居中标题 + ⋯）→ 顶部操作排（看职位 / 电话 / 微信）→
// 已确认意向的职位摘要卡 → 消息流（含代理提醒灰条与日期分隔）→
// 真输入条（深绿边 + ◈ 代理符）。
//
// 气泡、系统条与自动滚到底都复用 直聊会话.tsx 导出的共用件，
// 样式同样引 直聊会话.module.css —— 两屏的消息流必须像素一致，所以不另写一份。
//
// 双盲：这一屏在意向确认之后，双盲已解除，对方真名与联系方式本来就互相可见，
// 所以顶部操作排是「看」不是「换」，没有申请-同意这一步（见 真人会话操作栏.tsx）。

import { useState } from 'react';
import 样式 from './真人会话.module.css';
import 共用样式 from './直聊会话.module.css';
import { 消息条, use自动滚到底 } from './直聊会话';
import 真人会话操作栏 from './真人会话操作栏';
import { 次级页外壳, 返回栏, 滚动区, 真输入条 } from '../组件/通用';
import { 公文包图标 } from '../组件/图标';
import 举报层 from '../组件/举报层';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 真人会话 as 真人会话数据 } from '../数据/模拟数据';
import type { 会话条 } from '../数据/类型';

export default function 真人会话() {
  const { 返回, 跳转 } = use导航();
  const [消息, 设消息] = useState<会话条[]>(真人会话数据.消息);
  const [草稿, 设草稿] = useState('');
  // 标注 2026-08-20 09:36 / 2026-08-21 10:14：意向确认即自动互换，只显示对方的。
  // 2026-08-22：原先那两张联系卡钉在消息流顶部，现在整块挪进顶部操作排的展开区 ——
  // 卡片组件与复制逻辑没换，只换了位置。留在流里会和顶部那排讲同一件事两遍，
  // 而它本来就钉在流顶（在日期分隔条之前），已经不在时间轴上、不带任何时间信息；
  // 「联系方式是这一刻互换的」这句话由职位卡的归档行（15:22 意向确认）继续承担。
  // 右上「⋯」拉起的举报层：这一屏对面是真人顾问，屏蔽指向他所属的机构
  const [举报层开, 设举报层开] = useState(false);
  const 底部锚 = use自动滚到底(消息);

  // 发送：草稿去空后追加到本地消息流（真人页的消息不带时间戳，与源一致）
  const 发送 = () => {
    const 内容 = 草稿.trim();
    if (!内容) return;
    const 新条: 会话条 = { 编号: Date.now(), 角色: '我', 内容 };
    设消息((旧) => [...旧, 新条]);
    设草稿('');
  };

  return (
    <次级页外壳 对话底>
      <返回栏
        返回={返回}
        标题="林筱"
        副标题="铨衡人才 · 招聘顾问"
        居中标题
        右侧={
          <button
            className={`${共用样式.更多} 可点`}
            onClick={() => 设举报层开(true)}
            aria-label="举报"
          >
            ⋯
          </button>
        }
      />

      {/* 顶部操作排（2026-08-22）：主项「看职位」跳的是这一单已确认的那个岗位，
          落点用 在谈详情看职位 —— 直接开在职位详情 Tab。
          岗位编号与下面职位卡的「查看 ›」同一个 J-01，两个入口不能指向不同的岗。 */}
      <真人会话操作栏
        主项名="看职位"
        主项图标={<公文包图标 尺寸={20} 色="#3f7a1f" />}
        主项打开={() => 跳转(路径.在谈详情看职位('J-01'))}
        联系方式={真人会话数据.联系方式}
      />

      <滚动区>
        <div className={`${共用样式.消息流} ${共用样式.消息流上留白}`}>
          <职位卡 查看={() => 跳转(路径.在谈详情('J-01'))} />

          {消息.map((条) => (
            <消息条 key={条.编号} 条={条} 对方首字="林" />
          ))}
          <div ref={底部锚} />
        </div>
      </滚动区>

      <真输入条
        占位="输入消息…"
        值={草稿}
        改变={设草稿}
        发送={发送}
        右侧图标={<span className={样式.代理符}>◈</span>}
      />

      {举报层开 ? (
        <举报层
          对象名="林筱 · 铨衡人才"
          屏蔽名称="铨衡人才"
          关闭={() => 设举报层开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}

// ── 顶部职位摘要卡：意向已确认，谈判档案归档，「查看 ›」回到该单的在谈详情 ──
function 职位卡({ 查看 }: { 查看: () => void }) {
  const 卡 = 真人会话数据.职位卡;
  return (
    <div className={样式.职位卡}>
      <div className={样式.职位卡头行}>
        <div className={`${样式.职位卡标题} 单行`}>{卡.职位}</div>
        <span className={`${样式.职位卡薪资} 等宽数字`}>{卡.薪资}</span>
      </div>
      <div className={样式.职位卡条件}>{卡.条件行}</div>
      <div className={样式.职位卡底}>
        <div className={`${样式.职位卡归档} 单行`}>{卡.归档行}</div>
        <button className={`${样式.职位卡链接} 可点`} onClick={查看}>
          查看 ›
        </button>
      </div>
    </div>
  );
}
