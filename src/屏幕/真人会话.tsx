/** 这一屏写死服务 J-01 这一单（顶部职位卡、看职位层、「查看 ›」都指同一个岗）。
 *  编号只在这里出现一次，避免三个入口哪天被改歪、指向不同的岗。 */
const 本单编号 = 'J-01';

/**
 * P7 Task 4：模式/参数双开关 —— Backend 且带 conversationId 时把坐标交给
 * P7 Backend 真人会话（详情 + 消息 + 发送 + 已读 + 上下文动作）；Backend 访问
 * 无参路由 fail closed 成「会话不可用」，绝不读默认 J-01；Mock 保留 J-01 剧情。
 */
export default function 真人会话() {
  const { 数据源模式 } = use应用状态();
  const { conversationId } = useParams();
  if (数据源模式 === 'backend') {
    if (conversationId === undefined) return <会话不可用 />;
    // review-r3：按会话坐标 key 重挂 —— 换会话即全新实例，旧会话的草稿/未知提示/
    // PDF 层不存在跨实例残留窗口（组件内另有 layout-effect 代际兜底）。
    return <Backend真人会话 key={conversationId} 角色="candidate" conversationId={conversationId} />;
  }
  return <Mock真人会话 />;
}

function Mock真人会话() {
  const { 返回, 跳转 } = use导航();
  const { 状态 } = use应用状态();
  const [消息, 设消息] = useState<会话条[]>(真人会话数据.消息);
  const [草稿, 设草稿] = useState('');
  // 标注 2026-08-20 09:36 / 2026-08-21 10:14：联系方式在 S1 原件递交时即对双方可见，只显示对方的。
  // 2026-08-22：原先那两张联系卡钉在消息流顶部，现在整块挪进顶部操作排的展开区 ——
  // 卡片组件与复制逻辑没换，只换了位置。留在流里会和顶部那排讲同一件事两遍，
  // 而它本来就钉在流顶（在日期分隔条之前），已经不在时间轴上、不带任何时间信息；
  // 「联系方式在 S1 原件递交时已可见」这句话由职位卡的归档行（15:22 意向确认）继续承担。
  // 右上「⋯」拉起的举报层：这一屏对面是真人顾问，屏蔽指向他所属的机构
  const [举报层开, 设举报层开] = useState(false);
  const 底部锚 = use自动滚到底(消息);

  // 「看职位」层要渲染的那一单。优先取全局在谈列表（用户可能在在谈详情里改过它），
  // 取不到再退回种子数据 —— 退出谈判会把这一单从全局列表里移除，但这一屏是
  // 意向确认之后的场景，职位本身还得看得见，不能因为归档就点开一片空白。
  const 本单 =
    状态.在谈列表.find((条) => 条.编号 === 本单编号) ??
    在谈种子列表.find((条) => 条.编号 === 本单编号) ??
    null;

  // 发送：草稿去空后追加到本地消息流（真人页的消息不带时间戳，与源一致）
  const 发送 = () => {
    const 内容 = 草稿.trim();
    if (!内容) return;
    const 新条: 会话条 = { 编号: Date.now(), 角色: '我', 内容 };
    设消息((旧) => [...旧, 新条]);
    设草稿('');
  };

  return (
    <次级页外壳 对话底 白底>
      <返回栏
        返回={返回}
        标题="林筱"
        副标题="铨衡人才 · 招聘顾问"
        居中标题
        右侧={
          <button
            className={`${共用样式.更多} 可点`}
            onClick={() => 设举报层开(true)}
            aria-label="举报"
          >
            ⋯
          </button>
        }
      />

      {/* 顶部操作排：主项「看职位」2026-08-22 由跳转改成盖一层全屏详情（产品负责人反馈：
          「点开后是一个和主页一样的页面，但是不要跳转」）。层里铺的就是在谈详情
          「职位详情」Tab 看到的那份内容，路由不动、返回栈不加深，
          「继续沟通」关掉层就回到聊天，滚动位置与草稿都还在。 */}
      <真人会话操作栏
        主项名="看职位"
        主项图标={<公文包图标 尺寸={18} 色="#3f7a1f" />}
        主项内容={本单 ? <职位内容 单={本单} /> : null}
        联系方式={真人会话数据.联系方式}
      />

      <滚动区>
        <div className={`${共用样式.消息流} ${共用样式.消息流上留白}`}>
          <职位卡 查看={() => 跳转(路径.在谈详情(本单编号))} />

          {消息.map((条) => (
            <消息条 key={条.编号} 条={条} 对方首字="林" />
          ))}
          <div ref={底部锚} />
        </div>
      </滚动区>

      <真输入条
        占位="输入消息…"
        值={草稿}
        改变={设草稿}
        发送={发送}
        右侧图标={<span className={样式.代理符}>◈</span>}
      />

      {举报层开 ? (
        <举报层
          对象名="林筱 · 铨衡人才"
          屏蔽名称="铨衡人才"
          关闭={() => 设举报层开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}

// ── 「看职位」全屏层的正文：对接人 → 匹配度分析 → JD / 职位要求 → 公司 ──
// 与 在谈详情.tsx 的「职位详情」Tab 是同一份内容、同一份取数（取在谈岗位详情）、
// 同一批样式类，所以两处看到的职位必然一样。
// 这里之所以重写了一遍 JSX 而不是复用：那个 Tab 是 在谈详情.tsx 内部的私有组件，
// 本轮的改动范围不含那个文件（并行改动，不越界动别人的文件）。后续应把它提成
// 共享组件，两边一起引 —— 在那之前，改 JD 版式时这两处必须一起改。
//
// 2026-08-23 就是「必须一起改」的一次：产品负责人在 #/deal/J-02 的职位详情 Tab 上要求
// 把对接人挪到最上面、备注归 JD（原话与理由见 在谈详情.tsx 职位详情Tab 的注释）。
// 这一层若不跟着挪，同一个岗从「在谈详情」和「真人会话·看职位」两个入口点进来会长得不一样。
function 职位内容({ 单 }: { 单: 在谈单 }) {
  const { 跳转 } = use导航();
  const { 状态: 全局, 数据源模式 } = use应用状态();
  const 详 = 取在谈岗位详情(单);
  // P1C Task 5：Backend 下本单来自未接线演示域，没有 CandidateJob/canonical ref。
  // 公司槽只读：不传 按下、不调 路径.企业详情、不把静态键当 opaque ID 请求；
  // Mock 仍按原 slug 导航。资料 走显式路径，Backend 不读静态公司档案。
  const 是后端 = 数据源模式 === 'backend';
  // 适配分的依据：委托进来的 M- 单直接借市场岗位上的证据，剧本 J- 单用自己的同名字段
  const 证据源 = 市场列表.find((岗) => 岗.编号 === 单.编号) ?? 单;

  return (
    <div className={谈详情样式.详情列}>
      {/* 匹配度分析(2026-08-31 定稿「分从行来 + 三态行」):与在谈详情同一个共用块,两入口必然一致 */}
      <div className={详析样式.卡}>
        {(() => {
          const 对齐行们 = 求职侧对齐行(证据源, {
            经历: 全局.简历经历,
            教育: 全局.简历教育,
            技能: 全局.简历技能,
          });
          return (
            <匹配分析块
              分={算适配分(对齐行们, 单.适配分)}
              行们={对齐行们}
              分析={求职匹配分析(对齐行们, 证据源.编号)}
            />
          );
        })()}
      </div>

      <div className={谈详情样式.详情卡}>
        <div className={谈详情样式.详情标题}>职位详情</div>
        {详.职位详情.map((行) => (
          <div key={行} className={谈详情样式.详情正文}>
            {行}
          </div>
        ))}
        <div className={谈详情样式.详情小标题}>职位要求</div>
        {详.职位要求.map((行) => (
          <div key={行} className={谈详情样式.详情正文}>
            {行}
          </div>
        ))}
        {/* 对接人备注行已删（用户 2026-08-31 标注）*/}
      </div>

      {/* 公司(2026-08-26「所有页面都要改」):共用 公司区块 组件。这一跳是用户主动
          要看另一个对象(公司),与「看职位不该跳走」不冲突:回来按返回键即可。
          Backend(P1C Task 5)公司槽只读:显式 资料,不传 按下 */}
      <div className={谈详情样式.详情卡}>
        <公司区块
          名称={单.公司}
          首字={单.公司首字}
          一行简介={单.公司简介}
          资料={是后端 ? { 介绍段: null, 元行组: [] } : undefined}
          按下={
            是后端
              ? undefined
              : () => 跳转(路径.企业详情(公司路由键(单.公司)))
          }
        >
          {详.公司.标签.length ? (
            <span className={谈详情样式.公司标签行}>
              {详.公司.标签.map((标签) => (
                <span key={标签} className={谈详情样式.公司标签}>
                  {标签}
                </span>
              ))}
            </span>
          ) : null}
        </公司区块>
      </div>

      {/* 对接人卡(2026-08-26 用户定:全站对接人一律放公司区块之下,与 在谈详情 同步挪动)。
          备注行仍归「职位详情」卡;取不到对接人时整张卡不渲染 */}
      {详.对接人 ? (
        <div className={`${谈详情样式.详情卡} ${谈详情样式.对接人卡}`}>
          <span className={谈详情样式.对接人头像}>
            <span className={谈详情样式.对接人首字}>{详.对接人.首字}</span>
          </span>
          <div className={谈详情样式.对接人文本}>
            <div className={谈详情样式.对接人名}>
              {详.对接人.姓名} · {单.公司}{' '}
              <span className={谈详情样式.对接人职务}>{详.对接人.职务}</span>
            </div>
          </div>
        </div>
      ) : null}
    </div>
  );
}

// ── 顶部职位摘要卡：意向已确认，谈判档案归档，「查看 ›」回到该单的在谈详情 ──
function 职位卡({ 查看 }: { 查看: () => void }) {
  const 卡 = 真人会话数据.职位卡;
  return (
    <div className={样式.职位卡}>
      <div className={样式.职位卡头行}>
        <div className={`${样式.职位卡标题} 单行`}>{卡.职位}</div>
        <span className={`${样式.职位卡薪资} 等宽数字`}>{卡.薪资}</span>
      </div>
      <div className={样式.职位卡条件}>{卡.条件行}</div>
      <div className={样式.职位卡底}>
        <div className={`${样式.职位卡归档} 单行`}>{卡.归档行}</div>
        <button className={`${样式.职位卡链接} 可点`} onClick={查看}>
          查看 ›
        </button>
      </div>
    </div>
  );
}
