// 单条初筛对话 —— 本周初筛记录点一条进来，整屏就是这一场初筛。
//
// 版式：返回栏（标题 = 代号，副标题 = 画像）→ 顶部结论卡（结果 + 硬性核对清单逐项）
// → 下方复用 组件/阶段对话流，只传一个分段，与在谈详情 / 候选详情里的对话是同一种版式。
// 没有底部输入条：这是回看一场已经聊完的初筛，不是进行中的单子，没有可叮嘱的对象。
//
// 双盲不变：整屏只有代号与画像，没有真名；薪资只以「有交集」这类结论出现，不出任何数字。

import { useParams } from 'react-router-dom';
import 样式 from './初筛对话.module.css';
import 阶段对话流, { type 分段项 } from '../组件/阶段对话流';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { 本周初筛记录, 初筛对话表, type 初筛记录 } from '../数据/企业端模拟数据';

export default function 初筛对话() {
  // 路由参数名必须 ASCII（同 路径表 的约定：react-router 的参数正则不认中文），
  // 所以取 id，落到本屏语义上是初筛记录的编号
  const { id: 编号 = '' } = useParams<{ id: string }>();
  const { 返回 } = use导航();

  const 记录 = 本周初筛记录.find((条) => 条.编号 === 编号);

  // 直接敲 URL 进来、编号却不在记录里：不白屏也不抛错，留返回栏 + 一行空态，
  // 用户还能退回上一屏
  if (!记录) {
    return (
      <次级页外壳>
        <返回栏 返回={返回} 标题="本周初筛记录" />
        <div className={样式.空态}>没有这条初筛记录</div>
      </次级页外壳>
    );
  }

  const 对话 = 初筛对话表[记录.编号] ?? [];

  // 只传一个分段：这一屏不是四阶段推进中的单子，是回看已经收束的那一场初筛，
  // 所以态固定「已完成」、默认展开，不给用户一个还要先点开才看得见对话的折叠条。
  //
  // 核对清单刻意不往这里传：顶部结论卡已经逐项列过一遍，传进来会在小结托盘里再列一遍；
  // 而且 阶段对话流 会给非「通过」的项追加「核对中」字样，
  // 用在挡掉这条上会显示成「主栈 · Java 非 Go 核对中」，与「已挡掉」自相矛盾。
  const 分段们: 分段项[] = [
    {
      阶段: '匿名初筛',
      态: '已完成',
      状态文: 记录.结果,
      小结: 记录.结论,
      对话,
      默认展开: true,
    },
  ];

  return (
    <次级页外壳>
      <返回栏 返回={返回} 标题={记录.代号} 副标题={记录.画像} />

      <滚动区>
        <结论卡 记录={记录} />
        <阶段对话流 分段们={分段们} />
      </滚动区>
    </次级页外壳>
  );
}

/**
 * 结论卡：结果标 + 硬性 N/5 + 核对清单逐项。
 *
 * 核对记号只有两态：通过打绿勾，其余打灰点，且不追加任何字样 ——
 * 数据层的 核对清单.结果 只有 '通过' | '核对中' 两个值，挡掉那两项的事实写在 项 文本里
 * （主栈 · Java 非 Go、城市 · 常驻杭州，不接受迁沪），
 * 这里若照字面渲染成「核对中」，会与卡上的「挡掉」互相打架。
 */
function 结论卡({ 记录 }: { 记录: 初筛记录 }) {
  const 通过 = 记录.结果 === '通过';

  return (
    <div className={样式.结论卡}>
      <div className={样式.结论头}>
        <span className={`${样式.结果标} ${通过 ? 样式.结果通过 : 样式.结果挡掉}`}>
          {记录.结果}
        </span>
        <span className={样式.硬性数}>
          硬性 <span className="等宽数字">{记录.硬性通过}</span>
        </span>
      </div>

      <div className={样式.核对列}>
        {记录.核对清单.map((条) => (
          <div key={条.项} className={样式.核对行}>
            <span
              className={`${样式.核对记} ${
                条.结果 === '通过' ? 样式.核对记过 : 样式.核对记未过
              }`}
            >
              {条.结果 === '通过' ? '✓' : '·'}
            </span>
            <span className={样式.核对项}>{条.项}</span>
          </div>
        ))}
      </div>
    </div>
  );
}
