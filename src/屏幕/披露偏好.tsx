// 披露偏好 —— 「我的 › 其他功能 › 披露偏好」。
//
// 逐项决定「代理在什么时机可以把这条信息交出去」，三档：不披露 / 意向确认后 / 一直允许。
// 其中两项是锁死的，且锁在数据层（归约里也挡了一次），不是 UI 上灰一下：
//   · 具体薪资数字 —— 双盲机制的地基，任何一方的数字都不出手，只交换「是否落在区间内」
//   · 并行接触数量 —— 披露会直接削弱用户的谈判位置
// 这两把锁是产品承诺，不能做成用户可开的开关。

import 样式 from './我的功能页.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 轻提示 } from '../组件/轻提示';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import type { 披露档 } from '../数据/类型';

const 全部档: 披露档[] = ['不披露', '意向确认后', '一直允许'];

export default function 披露偏好() {
  const { 返回 } = use导航();
  const { 状态, 派发, 操作, 数据源模式, 后端状态 } = use应用状态();

  // P3：Backend 隐私未水合（隐私快照 null）时不渲染任何档位行 ——
  // Mock 七行模板不能冒充服务端值；Mock 模式照旧直接用本地状态。
  const 隐私已水合 = 数据源模式 !== 'backend' || 后端状态.隐私快照 !== null;

  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：选择/填写屏页底一律白底
    <次级页外壳 白底>
      <返回栏 返回={返回} 标题="披露偏好" 副标题="代理按这里的设定决定何时交出信息" />

      <滚动区 样式覆盖={{ padding: '14px 18px 24px' }}>
        <div className={样式.说明条}>
          代理在匹配和初筛中只使用你允许的信息。
          <span className={样式.说明强调}>AI 不会自动披露你的薪资数字</span>
          —— 初筛时只判断「区间是否匹配」；意向确认后，由你决定是否在真人沟通中讨论具体金额。
        </div>

        {(隐私已水合 ? 状态.披露偏好 : []).map((项) => {
          const 锁了 = 项.锁定 !== null;
          return (
            <div key={项.编号} className={样式.披露卡}>
              <div className={样式.披露头}>
                <span className={样式.披露名}>{项.名称}</span>
                {锁了 ? <span className={样式.锁标}>🔒 机制锁定</span> : null}
              </div>
              <div className={样式.披露说明}>{项.说明}</div>

              <div className={样式.分段}>
                {全部档.map((档) => {
                  const 可选 = 项.可选档.includes(档);
                  const 选中 = 项.档 === 档;
                  // P3：可写 = 服务端授权（可修改）+ 无机制锁 + 档位合法。
                  // className 仍按 可选 计算 —— 固定行不新增视觉禁用样式（视觉边界由 UI 回归门冻结），
                  // 只有行为用 可改 收口；Backend 点档走 操作.设置披露偏好 单字段 patch，Mock 走本地归约。
                  const 可改 = 项.可修改 === true && 项.锁定 === null && 项.可选档.includes(档);
                  return (
                    <button
                      key={档}
                      className={`${样式.分段项} ${选中 ? 样式.分段项选中 : ''} ${
                        可选 ? '可点' : 样式.分段项禁用
                      }`}
                      // 这一屏有 7 行 × 最多 3 档，光看「不披露」听不出是哪一行 ——
                      // 可访问名称按字段限定，选中态用 aria-pressed 说，都是纯语义属性，不动一个像素。
                      aria-label={`${项.名称}：${档}`}
                      aria-pressed={选中}
                      onClick={async () => {
                        if (!可改) return;
                        if (数据源模式 === 'backend') {
                          // Backend 写档失败：复用现有轻提示与错误文案映射（Mock 本地归约不会拒绝，原样保留）
                          try {
                            await 操作.设置披露偏好(项.编号 as 'D-03' | 'D-04' | 'D-05', 档);
                          } catch (错误) {
                            轻提示(取后端错误文案(错误));
                          }
                        } else 派发({ 型: '设披露档', 编号: 项.编号, 档 });
                      }}
                      disabled={!可改}
                    >
                      {档}
                    </button>
                  );
                })}
              </div>

              {锁了 ? <div className={样式.锁条}>{项.锁定}</div> : null}
            </div>
          );
        })}

        <div className={样式.版本}>
          改动即时生效，对正在进行的匹配和代谈同样适用。
          <br />
          已经披露出去的信息无法收回。
        </div>
      </滚动区>
    </次级页外壳>
  );
}
