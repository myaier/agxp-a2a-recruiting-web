// 公司主页资料 · 企业端维护入口（/hr/company-profile）
//
// 这一屏改的，正是候选人在 企业详情（公司主页）里看到的「公司自述」那一块：
// 公司简介 / 企业文化 / 发展历程 / 作息 / 办公地 —— 字段与那一屏一一对应。
//
// 刻意不放进来的东西（与不对称双盲及「代理档案而非宣传册」的立场直接相关）：
//   · 工商信息 —— 第三方核验的结果，企业自己改了就没有可信度可言；
//   · 代理核对结果与在职者反馈 —— 那是平台与候选人侧产生的，企业不该有编辑权。
// 候选人那一屏会给自述段打上「未经核实」，所以这里写什么都不会被当成已核事实。
//
// 版式：说明条 + 白卡分节（多行自述三段 / 作息与办公地两个单行输入）+ 底部主按钮，
// 复用 我的功能页.module.css 的组标与说明条，输入控件在本屏 css 里。
//
// 保存落全局状态 + localStorage（回归发现原实现只弹「已保存」实则不落地，
// 属于会误导用户的假成功）。候选端 企业详情 读同一份覆盖值。

import { useState } from 'react';
import 公用 from './我的功能页.module.css';
import 样式 from './公司档案编辑.module.css';
import { 次级页外壳, 返回栏, 滚动区, 主按钮 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { 取公司档案 } from '../数据/公司档案';
import { use应用状态 } from '../状态/应用状态';

/** 原型阶段固定编辑云衢科技这一家（= 当前登录的招聘方）*/
const 本公司键 = 'yunqu';

export default function 公司档案编辑() {
  const { 返回 } = use导航();
  const { 状态, 派发 } = use应用状态();
  const 静态档 = 取公司档案(本公司键);
  // 改过就用改过的，没改过用静态档
  const 覆盖 = 状态.公司自述;
  const 档 = 覆盖
    ? { ...静态档, ...覆盖, 简介: 覆盖.简介, 发展历程: 覆盖.发展历程 }
    : 静态档;

  // 三段自述在数据层是数组 / 结构化节点，编辑时摊成多行文本，一行一条，够用且好改
  const [公司简介, 设公司简介] = useState(档.简介.join('\n'));
  const [企业文化, 设企业文化] = useState(档.企业文化);
  const [发展历程, 设发展历程] = useState(
    档.发展历程.map((节) => `${节.年份} ${节.事件}`).join('\n')
  );
  const [作息, 设作息] = useState(档.作息);
  const [办公地, 设办公地] = useState(档.地址);
  const [办公地补充, 设办公地补充] = useState(档.地址补充);

  const 保存 = () => {
    派发({
      型: '存公司自述',
      值: {
        简介: 公司简介.split('\n').map((行) => 行.trim()).filter(Boolean),
        企业文化,
        // 「2023 成立…」逐行拆回结构化节点；没有年份前缀的整行当事件
        发展历程: 发展历程
          .split('\n')
          .map((行) => 行.trim())
          .filter(Boolean)
          .map((行) => {
            const 命中 = /^(\d{4})\s+(.*)$/.exec(行);
            return 命中 ? { 年份: 命中[1], 事件: 命中[2] } : { 年份: '', 事件: 行 };
          }),
        作息,
        地址: 办公地,
        地址补充: 办公地补充,
      },
    });
    轻提示('已保存 · 候选人看到的公司主页同步更新');
    返回();
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} 标题="公司主页资料" 副标题={档.名称} />

      <滚动区 样式覆盖={{ padding: '12px 18px 20px' }}>
        <div className={公用.说明条}>
          这里改的是候选人在公司主页看到的
          <span className={公用.说明强调}>公司自述</span>
          部分。工商信息由第三方核验、代理核对结果由你的代理生成，都不在这里改。
        </div>

        <div className={公用.组标}>公司自述</div>
        <div className={样式.卡}>
          <多行字段
            标签="公司简介"
            提示="一段一行。写清楚业务是什么、技术团队什么背景、为什么现在招人"
            值={公司简介}
            改变={设公司简介}
            高度={132}
            上限={500}
          />
          <多行字段
            标签="企业文化"
            提示="一两句就够，写你们真正在意的判断标准"
            值={企业文化}
            改变={设企业文化}
            高度={84}
            上限={200}
          />
          <多行字段
            标签="发展历程"
            提示="一行一条，格式：年份 事件"
            值={发展历程}
            改变={设发展历程}
            高度={110}
            上限={400}
            末条
          />
        </div>

        <div className={`${公用.组标} ${公用.组标间距}`}>作息与办公地</div>
        <div className={样式.卡}>
          {/* 这三条都可能写得很长（完整地址、作息说明），一律用会换行的多行框，
              单行输入在窄屏上会把后半截截掉，用户看不见自己填了什么 */}
          <多行字段
            标签="作息"
            提示="如：上午 09:30 – 下午 07:00 · 双休"
            值={作息}
            改变={设作息}
            高度={62}
            上限={60}
            无计数
          />
          <多行字段
            标签="办公地"
            提示="楼宇级地址，候选人据此判断通勤"
            值={办公地}
            改变={设办公地}
            高度={62}
            上限={80}
            无计数
          />
          <多行字段
            标签="办公地补充"
            提示="如：地铁 2 号线世纪大道站 · 混合办公 3+2"
            值={办公地补充}
            改变={设办公地补充}
            高度={62}
            上限={60}
            无计数
            末条
          />
        </div>

        {/* 作息这一条会被代理拿去核对，所以要提醒它不是纯宣传文案 */}
        <div className={样式.尾注}>
          作息与办公方式是代理在谈判里会被问到的条款，写实一点 ——
          与实际不符会在「需要协调」阶段直接暴露成分歧。
        </div>
      </滚动区>

      <主按钮 文字="保存" 按下={保存} />
    </次级页外壳>
  );
}

/** 一条字段：小标签 + 会换行的多行输入 + 字数（短字段用 无计数 关掉计数，少一行小字）*/
function 多行字段({
  标签,
  提示,
  值,
  改变,
  高度,
  上限,
  无计数 = false,
  末条 = false,
}: {
  标签: string;
  提示: string;
  值: string;
  改变: (值: string) => void;
  高度: number;
  上限: number;
  无计数?: boolean;
  末条?: boolean;
}) {
  return (
    <div className={`${样式.字段} ${末条 ? 样式.末条 : ''}`}>
      <div className={样式.字段标签}>{标签}</div>
      <textarea
        className={样式.多行输入}
        style={{ height: 高度 }}
        value={值}
        placeholder={提示}
        maxLength={上限}
        onChange={(事件) => 改变(事件.target.value)}
        aria-label={标签}
      />
      {无计数 ? null : (
        <div className={`${样式.字数} 等宽数字`}>
          {值.length} / {上限}
        </div>
      )}
    </div>
  );
}
