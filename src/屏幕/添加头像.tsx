// 添加头像（/onboard/avatar）—— 2026-08-20 按 BOSS 截图顺序重排：注册流最后一屏。
// 大圆上传位（选图片压成 dataURL）。标注 2026-08-20 18:07：我们设计的虚拟头像删掉，只留用户自己上传。
// 头像落 全局.求职头像；Provider 统一按模式/环境/账号隔离缓存。
// 「完成注册」（标注 2026-08-24：原「开启求职之旅」营销腔，产品负责人终定）→ 替换跳转进主壳，后退不能回注册流。
// J-PILOT-02 Task 8：头像可选 —— 未选始终可完成；未知结果不伪成功：上传圆位/文件框
// 允许重选同一张图片按原命令重试，「完成注册」是用户明确放弃本次未确认上传的出口（Spec §6）。

import { useEffect, useRef, useState } from 'react';
import 样式 from './入职引导.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { 相机图标 } from '../组件/图标';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 压成头像 } from '../组件/头像处理';
import { 取后端错误文案 } from '../数据/HTTP客户端';

const 头像字节上限 = 10 * 1024 * 1024;

export default function 添加头像() {
  const { 返回, 进初始化 } = use导航();
  const { 状态: 全局, 派发, 数据源模式, 操作 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  const 文件框 = useRef<HTMLInputElement>(null);
  const [保存中, 设保存中] = useState(false);
  const [完成中, 设完成中] = useState(false);
  const 头像 = 全局.求职头像;
  // 只有注册旅程（引导预填 非 null，由 学生分流 的 启程引导 派发）才碰建档草稿 ——
  // 与 引导问答 同款纪律；本屏在日常语境不可达建档，Mock 模式零草稿操作。
  const 旅程中 = 是后端 && 全局.引导预填 !== null;
  const 建档 = 旅程中 ? 全局.引导预填?.建档 : undefined;
  const 头像待核对 = 建档?.待写入?.种类 === 'avatar';

  // 未知结果的头像写入用现有轻提示说明恢复所需操作（不添加新按钮/新错误组件）；
  // 提交在途时不提示（槽是发送前登记的，结果还没回来）。
  useEffect(() => {
    if (头像待核对 && !保存中) {
      轻提示('头像上传结果未确认：请重新选择同一张图片重试，或点「完成注册」放弃本次上传');
    }
  }, [头像待核对, 保存中]);

  /** 注册收尾：先核对本人真实资源（Task 9 / Spec §6），通过才进初始化页
      （2026-08-25 用户定稿的乙方案），播完由初始化页替换进主壳；落地回主页而不是
      上次停留的 Tab（2026-08-20）。核对失败留在本页，经既有轻提示指出缺项。 */
  const 开启 = async () => {
    if (保存中 || 完成中) return;
    // Task 8：头像可选 —— 「完成注册」也是用户明确跳过/放弃本次未确认头像上传的出口
    //（与 Task 6「继续手填」释放建档文件槽 同一纪律；命令在途时按钮禁用，点不到这里）。
    // 只释放 avatar 槽并记 头像状态 已放弃：不发请求、不删已传内容、不声称上传失败；
    // 放弃事实先落草稿、完成核对随后读它（Task 9）；其他域的未结算命令留给完成
    // 核对，本屏不越权释放。
    if (头像待核对 && 建档 !== undefined) {
      const { 待写入: _释放, ...无槽 } = 建档;
      操作.更新候选建档草稿({ ...无槽, 头像状态: '已放弃' });
    }
    // Task 9：完成注册先核对本轮真实资源 —— 失败留在本页（预填轮与草稿都不清），
    // 成功才沿原收尾编排（清预填轮 → 切 Tab → 进初始化）。切 Tab/子视图与清理都是
    // 成功侧收尾，不能在核对可能失败时先落下。
    if (旅程中) {
      设完成中(true);
      try {
        await 操作.完成候选Onboarding();
      } catch (错误) {
        轻提示(取后端错误文案(错误));
        return;
      } finally {
        设完成中(false);
      }
      // 注册完成（设计 §9 / Task 7）：作废候选 onboarding 预填轮与恢复元数据
      //（内存建议 + session 存储一起清；完成核对里已按归属清过一轮，这里是本屏
      // 既有收尾口，重复清理幂等无害），完成注册后旧建议绝不再残留。
      操作.清候选Onboarding预填();
    }
    派发({ 型: '切Tab', Tab: '职位' });
    派发({ 型: '切子视图', 子视图: '在谈' });
    进初始化();
  };

  async function 选了照片(事件: React.ChangeEvent<HTMLInputElement>) {
    const 文件 = 事件.target.files?.[0];
    事件.target.value = ''; // 允许再次选同一张
    if (!文件) return;
    if (文件.type !== 'image/png' && 文件.type !== 'image/jpeg') {
      轻提示('请选择 JPG 或 PNG 图片');
      return;
    }
    if (文件.size > 头像字节上限) {
      轻提示('图片不超过 10 MiB');
      return;
    }
    设保存中(true);
    try {
      if (数据源模式 === 'backend') await 操作.保存候选头像(文件);
      else 派发({ 型: '存求职头像', 图: await 压成头像(文件) });
      轻提示('头像已更新');
    } catch (错误) {
      轻提示(数据源模式 === 'backend' ? 取后端错误文案(错误) : '这张图片读不出来，换一张试试');
    } finally {
      设保存中(false);
    }
  }

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      <页面大标题 标题="添加头像" />

      <滚动区 样式覆盖={{ padding: '4px 22px 12px' }}>
        <div className={样式.头像区}>
          {/* 大圆 = 唯一的头像入口（标注 18:07：虚拟头像删掉，让用户自己上传）*/}
          <button
            className={`${样式.大圆} 可点`}
            onClick={() => 文件框.current?.click()}
            aria-label="上传头像照片"
            disabled={保存中}
          >
            {头像 ? (
              <img className={样式.头像图} src={头像} alt="" />
            ) : (
              <相机图标 尺寸={30} 色="var(--弱化)" />
            )}
          </button>
          <input
            ref={文件框}
            type="file"
            accept="image/*"
            className={样式.隐藏文件框}
            onChange={选了照片}
          />
        </div>
      </滚动区>

      <主按钮 文字="完成注册" 按下={开启} 禁用={保存中 || 完成中} />
    </次级页外壳>
  );
}
