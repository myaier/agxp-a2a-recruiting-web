// 真人会话顶部操作排 —— 求职端 A19（真人会话）与企业端 D12·A（企业真人会话）共用。
//
// ════ 双盲铁律：这一排（「看」模式）只允许出现在「意向确认之后」的两屏真人会话上 ════
// 意向确认前的直聊（直聊会话.tsx）不能挂它 —— 这一排是实值直陈，没有交换动作，
// 挂过去就是当场破盲。2026-08-24 边界收窄：直聊做了自己的顶部交换排
// （「换」语义：换电话/换微信点了才换、才展开），复用的只是本文件的 CSS 与联系卡，
// 组件本身仍然只属于确认后的两屏。配套的静态守卫见 真人会话操作栏.test.tsx。
//
// ════ 与 BOSS 那排的本质差别：这是「看」，不是「换」════
// BOSS 的「换电话 / 换微信 / 发简历」是**请求**：发申请 → 对方同意 → 才拿得到。
// 我们的机制是 S1 简历原件递交后真名与联系方式即对双方可见，意向确认只表示双方同意
// 进入真人沟通（见 数据/类型.ts 披露注释、真人会话.tsx 头部注释），中间没有申请-同意这一步。
// 所以这一排的三个名字只能是「看职位 / 看简历 / 电话 / 微信」这类直陈动作，
// 不许出现「换」「申请」「求」——那会凭空造出一个我们根本没有的授权环节。
//
// ════ 三项互斥：同时只开一个（标注 2026-08-24「这三个同时只能点击一个。
// 每个页面都是这样的」）════
// 电话 / 微信 展开成排下面的一小块联系卡，两张卡之间本就互斥；点主项开全屏层时
// 也把展开的联系卡收掉 —— 之前层与卡各管各的，层下压着一张开着的卡，
// 回来时排上同时亮着两项。展开区没有独立关闭键：再点一次同一格就收起。
//
// 主项（看职位 / 看简历）2026-08-22 从「跳转到详情页」改成「盖在聊天页上的全屏层」：
// 产品负责人原话是点开后该看到一个和详情页一样的页面、但不要跳转，底下放一个
// 「继续沟通」点了回聊天。跳转的毛病是整屏被换掉、返回栈多一层，回来时聊天要重新
// 挂载；盖一层则路由不动、聊天的滚动位置与草稿原样留在下面。层的壳用全应用统一的
// 组件/弹层框架（可聚焦遮罩 + 原生 dialog + Escape + 焦点恢复），不自己发明覆盖层。

import { useCallback, useRef, useState, type ReactNode } from 'react';
import 样式 from './真人会话操作栏.module.css';
import 共用样式 from './直聊会话.module.css';
import { 联系卡 } from './直聊会话';
import 弹层框架 from '../组件/弹层框架';
import { 电话图标, 微信图标 } from '../组件/图标';

/** 可展开的两个次项。用字面量联合而不是 string，避免以后往这排里塞别的东西 */
type 次项名 = '电话' | '微信';

/**
 * P7 展示增量（Spec §11.3/§11.4）：
 *   · 主项统一为「盖全屏层」形态（旧的 主项按下 导航分支已无生产调用方，删除）；
 *     层打开回调 主项打开（Backend 用它延迟取 PDF）、所有关闭路径（继续沟通 /
 *     Escape / 遮罩）回调 主项关闭（Backend 用它回收租约）—— 开关时机归调用方。
 *   · 主项禁用：Backend 缺授权坐标时的占位禁用，点击不开层。
 *   · 联系方式可缺席：Mock 传实值联系卡（复制行为原样）；Backend 传 联系方式占位
 *     出「电话暂未提供 / 微信暂未提供」纯说明行，无复制、无假号码。
 */
type 联系属性 =
  | {
      联系方式: { 电话: string; 微信: string };
      交换?: { 已换: 次项名[]; 换: (名: 次项名) => void };
      联系方式占位?: never;
    }
  | { 联系方式?: never; 交换?: never; 联系方式占位?: boolean };
type 属性 = 联系属性 & {
  /** 主项名：求职端 = 看职位，企业端 = 看简历。两端互为镜像，各只有一个主项 */
  主项名: string;
  /** 主项图标：求职端给公文包，企业端给简历本，都由调用方按本端语义传 */
  主项图标: ReactNode;
  /** 全屏层正文：Mock 盖卡片内容；Backend 盖 Case 职位资料 / 授权 PDF 正文 */
  主项内容: ReactNode;
  /** 主项禁用（缺授权坐标的占位禁用）：禁用时不开层、不触发 主项打开 */
  主项禁用?: boolean;
  /** 层打开时回调（延迟取件时机归调用方） */
  主项打开?: () => void;
  /** 层关闭回调（继续沟通 / Escape / 遮罩全都走到这里，回收时机归调用方） */
  主项关闭?: () => void;
};

export default function 真人会话操作栏({
  主项名, 主项图标, 主项内容, 主项禁用 = false, 主项打开, 主项关闭, 联系方式, 交换, 联系方式占位 = false,
}: 属性) {
  // null = 两个次项都收起。同时最多展开一个：两张联系卡一起铺开会把消息流挤到看不见
  const [展开项, 设展开项] = useState<次项名 | null>(null);
  // 主项的全屏详情层是否盖着。开层时顺手收掉联系卡（三项互斥，见头部注释）
  const [详情层开, 设详情层开] = useState(false);

  // 再点一次同一格就收起（这一格本身就是它的开关），点另一格则直接换过去。
  // 交换模式下首次点是「换」：先完成交换（调用方落系统消息），随即展开给看
  const 切换 = (名: 次项名) => {
    if (交换 && !交换.已换.includes(名)) {
      交换.换(名);
      设展开项(名);
      return;
    }
    设展开项((旧) => (旧 === 名 ? null : 名));
  };

  // 关闭回调走 ref：弹层框架的按键监听/焦点 effect 只在挂载时绑定一次，
  // 回调身份变化不得反复卸载重挂、把焦点重新拉回首控件。
  const 主项关闭引用 = useRef(主项关闭);
  主项关闭引用.current = 主项关闭;
  // 恒定引用：弹层框架的按键监听 useEffect 依赖 关闭，若每次渲染都换一个新函数，
  // 监听会被反复卸载重挂、并把焦点重新拉回首个控件
  const 关详情层 = useCallback(() => {
    设详情层开(false);
    主项关闭引用.current?.();
  }, []);

  // 次项三态：Mock 实值联系卡 / Backend 缺失占位（Spec §11.4：两入口都在，展开是
  // 「暂未提供」纯说明行，无复制动作、无假号码）。
  const 次项们: { 名: 次项名; 值: string | null; 画图标: (色: string) => ReactNode }[] =
    联系方式 !== undefined
      ? [
          { 名: '电话', 值: 联系方式.电话, 画图标: (色) => <电话图标 尺寸={18} 色={色} /> },
          { 名: '微信', 值: 联系方式.微信, 画图标: (色) => <微信图标 尺寸={18} 色={色} /> },
        ]
      : 联系方式占位
        ? [
            { 名: '电话', 值: null, 画图标: (色) => <电话图标 尺寸={18} 色={色} /> },
            { 名: '微信', 值: null, 画图标: (色) => <微信图标 尺寸={18} 色={色} /> },
          ]
        : [];

  return (
    <>
      <div className={样式.操作栏}>
        <button
          className={`${样式.项} 可点`}
          disabled={主项禁用}
          onClick={() => {
            if (主项禁用) return;
            设展开项(null);
            设详情层开(true);
            主项打开?.();
          }}
        >
          <span className={样式.项图}>{主项图标}</span>
          {/* 禁用时文字回中性灰：占位不伪装可用（Spec §11.3） */}
          <span className={主项禁用 ? 样式.项名 : `${样式.项名} ${样式.主项名}`}>{主项名}</span>
        </button>

        {次项们.map((次项) => {
          const 已展开 = 展开项 === 次项.名;
          return (
            <button
              key={次项.名}
              className={`${样式.项} ${已展开 ? 样式.项展开 : ''} 可点`}
              onClick={() => 切换(次项.名)}
              aria-expanded={已展开}
            >
              {/* 展开中的图标跟着文字上深绿，收起时是中性灰 */}
              <span className={样式.项图}>{次项.画图标(已展开 ? 'var(--深绿文字)' : '#6f7268')}</span>
              {/* 交换模式没换过时带「换」字前缀 —— 动作完成后落回名词 */}
              <span className={样式.项名}>
                {交换 && !交换.已换.includes(次项.名) ? `换${次项.名}` : 次项.名}
              </span>
            </button>
          );
        })}
      </div>

      {次项们.map((次项) =>
        展开项 === 次项.名 ? (
          <div key={次项.名} className={样式.展开区}>
            {次项.值 === null ? (
              // Backend 缺失占位（Spec §11.4）：纯说明行，不进联系卡（联系卡带复制）、
              // 不放假号码、不写剪贴板
              <div className={共用样式.联系条}>
                <span className={样式.缺失行}>{`${次项.名}暂未提供`}</span>
              </div>
            ) : (
              /* 直接复用直聊会话导出的联系卡：复制到剪贴板 + 轻提示 + execCommand 兜底
                 全在它里面，这里一行复制实现都不另写（产品负责人明确要求复用）*/
              <div className={共用样式.联系条}>
                <联系卡 名={次项.名} 对方={次项.值} />
              </div>
            )}
          </div>
        ) : null
      )}

      {详情层开 ? (
        <弹层框架
          标签={主项名}
          遮罩类名={样式.详情遮罩}
          面板类名={样式.详情层}
          关闭={关详情层}
        >
          {/* 「继续沟通」写在 DOM 首位、靠 CSS order 摆到底部：见 module.css 的说明。
              它做的事只有关层 —— 层没有改动过任何会话状态，退回来就是原样。 */}
          <div className={样式.详情底栏}>
            <button className={`${样式.继续沟通} 可点`} onClick={关详情层}>
              继续沟通
            </button>
          </div>
          <div className={样式.详情正文区}>{主项内容}</div>
        </弹层框架>
      ) : null}
    </>
  );
}
