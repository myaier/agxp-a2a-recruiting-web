// 选工作城市（/onboard/city）—— 全页城市选择（候选引导多选上限 10；?来源=意向 单选）。
//
// 版式：大标题「你理想的工作城市是」+ 右上 N/10 计数 → 搜索框 →
// 当前定位 / 国内热门城市 / 海外热门城市 / 行政区分组 → 底部「已选」chips（点 ✕ 删）+ 保存键。
// 选好的城市落 全局.引导预填.城市们（职位原样带上），保存后返回完善资料屏回显。
// 意向来源单选、写 意向草稿.工作城市（含引用），无 N/10 计数。
//
// picker 统一 Task 2：列表/搜索/已选/保存的版式与交互提取为共用正文
// `组件/工作城市选择正文`，本屏只做数据适配（Backend 目录 / Mock 字典）与业务派发。
// 城市临时选择归正文内部；保存时才按键取实际引用并一次性派发，中途退出不写脏数据。
//
// merge 调和（2026-09-14）：默认目录采用 origin/main 的四支分页模型 —— 热门区是 12+10
// 精选配置（国内/海外热门城市，无港澳台精选），分组按返回字段（CN 用 admin1、港澳台用三个
// 中文固定组标题）；Backend 定位仍是已批准的「暂未获取定位」缺失态，失败/重试走正文错误行。
// Mock 默认分组用 Mock默认城市字典，搜索读 Mock城市搜索字典（不发请求）。

import { useSearchParams } from 'react-router-dom';
import { 次级页外壳 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { Mock默认城市字典, Mock城市搜索结果 } from '../数据/城市与行业';
import { 国内精选城市, 海外精选城市, 精选城市显示名, 规范精选城市名称 } from '../数据/城市精选';
import type { BFFLocationItem } from '../数据/BFF契约';
import { use城市搜索, use城市默认页, 按行政区分组 } from './城市查询钩子';
import 工作城市选择正文, { type 城市列表状态, type 城市项 } from '../组件/工作城市选择正文';

/** 城市多选上限：与 BOSS 同档 */
const 城市上限 = 10;

export default function 选工作城市() {
  const { 返回 } = use导航();
  const { 状态: 全局, 派发, 数据源模式, 目录查询 } = use应用状态();
  const [查询参数] = useSearchParams();
  const 是后端 = 数据源模式 === 'backend';

  // 「添加求职期望」页的工作城市行点进来时带 ?来源=意向（规格：单选，写 意向草稿.工作城市）。
  // 不带这个参数就是注册引导的原路径 —— 那条路径的多选 + 写 引导预填 行为一个字都没动。
  const 来自意向 = 查询参数.get('来源') === '意向';

  // 进页初始已选取全局（Backend 用引用的 id/name，Mock 用城名）；
  // 之后只改正文内部的临时值 —— 中途退出不写脏数据。
  // Task 6：显示名经有限映射归一到目录规范名（ID 命中用规范名，Mock 城名走别名表），
  // 旧草稿「北京」与热门「北京市」同项；存储不重写，取消不派发。
  const 初始已选: 城市项[] = (() => {
    if (是后端) {
      if (来自意向) {
        const 引用 = 全局.意向草稿.工作城市引用;
        return 引用 ? [{ 键: 引用.id, 名称: 精选城市显示名(引用.id, 引用.display_name) }] : [];
      }
      return (全局.引导预填?.城市引用们 ?? []).map((条) => ({
        键: 条.id,
        名称: 精选城市显示名(条.id, 条.display_name),
      }));
    }
    if (来自意向) {
      const 名 = 规范精选城市名称(全局.意向草稿.工作城市);
      return 名 === '' ? [] : [{ 键: 名, 名称: 名 }];
    }
    return (全局.引导预填?.城市们 ?? ['上海']).map((城) => {
      const 名 = 规范精选城市名称(城);
      return { 键: 名, 名称: 名 };
    });
  })();

  // ── 搜索 / 默认目录页查询（Backend 分支）──
  const { 词, 设词, 结果: 搜索结果项, 搜索中, 错误: 搜索错误, 重试: 搜索重试, 下一页游标, 加载中: 搜索分页中, 加载更多: 搜索加载更多 } = use城市搜索(
    是后端 ? 目录查询?.查询Location : undefined,
  );
  // Task 4：不带 q 的四支默认目录页（CN/TW/HK/MO），分组见 城市查询钩子
  const { 项们: 默认项们, 加载中: 默认加载中, 还有, 错误: 默认错误, 重试: 默认重试, 加载更多: 默认加载更多 } = use城市默认页(
    是后端 ? 目录查询?.查询Location : undefined,
  );

  const 搜索态 = 词.trim() !== '';

  // ── 正文列表状态：Backend 用目录查询，Mock 用本地字典（键 = 规范名 / 目录 ID，不发请求）──
  // Task 6：Backend 目录项显示名经 精选城市显示名 归一（ID 命中用规范名），Mock 城名走
  // 规范精选城市名称 —— 热门与省内同名同键，选择比较统一到规范名。
  const 列表: 城市列表状态 = 搜索态
    ? {
        组: [{
          键: '搜索',
          名称: '搜 索 结 果',
          城市: 是后端
            ? 搜索结果项.map((项: BFFLocationItem) => ({
                键: 项.id,
                名称: 精选城市显示名(项.id, 项.display_name),
              }))
            : Mock城市搜索结果(词).map((城) => ({ 键: 城, 名称: 城 })),
        }],
        加载中: 是后端 ? 搜索中 || 搜索分页中 : false,
        错误: 是后端 ? 搜索错误 : null,
        可加载更多: 是后端 ? 下一页游标 !== null : false,
        加载更多: () => void 搜索加载更多(),
        重试: 搜索重试,
      }
    : {
        组: 是后端
          ? [
              // 当前定位：Backend 用已批准的缺失态，不假选上海
              { 键: '定位', 名称: '当 前 定 位', 城市: [{ 键: '定位缺失', 名称: '暂未获取定位', 禁用: true }] },
              // 热门区来自精选配置（12 大陆 + 10 海外，无港澳台精选），与默认目录返回无关
              { 键: '国内热门', 名称: '国内热门城市', 城市: 国内精选城市.map((项) => ({ 键: 项.id, 名称: 项.display_name })) },
              { 键: '海外热门', 名称: '海外热门城市', 城市: 海外精选城市.map((项) => ({ 键: 项.id, 名称: 项.display_name })) },
              ...按行政区分组(默认项们).map((组) => ({
                键: 组.键,
                名称: 组.键,
                城市: 组.城市们.map((项) => ({
                  键: 项.id,
                  名称: 精选城市显示名(项.id, 项.display_name),
                })),
              })),
            ]
          : [
              { 键: '定位', 名称: '当 前 定 位', 城市: [{ 键: 规范精选城市名称('上海'), 名称: 规范精选城市名称('上海') }] },
              // 精选区与 Backend 共用同一份产品顺序与规范名（无港澳台精选）
              { 键: '国内热门', 名称: '国内热门城市', 城市: 国内精选城市.map((项) => ({ 键: 项.display_name, 名称: 项.display_name })) },
              { 键: '海外热门', 名称: '海外热门城市', 城市: 海外精选城市.map((项) => ({ 键: 项.display_name, 名称: 项.display_name })) },
              ...Mock默认城市字典.map((组) => ({
                键: 组.省,
                名称: 组.省,
                城市: 组.城市.map((城) => {
                  const 名 = 规范精选城市名称(城);
                  return { 键: 名, 名称: 名 };
                }),
              })),
            ],
        加载中: 是后端 ? 默认加载中 : false,
        错误: 是后端 ? 默认错误 : null,
        可加载更多: 是后端 ? 还有 : false,
        加载更多: () => void 默认加载更多(),
        重试: 默认重试,
      };

  // 保存：正文把本次临时选择整体上交，这里按键取得实际引用并一次性派发
  //（键 = 目录稳定 ID / Mock 城名，不从名称重建）
  const 保存 = (已选: 城市项[]) => {
    if (来自意向) {
      if (是后端) {
        const 选 = 已选[0];
        派发({
          型: '改意向草稿',
          补丁: {
            工作城市: 选?.名称 ?? '',
            工作城市引用: 选 ? { id: 选.键, display_name: 选.名称 } : undefined,
          },
        });
      } else {
        派发({ 型: '改意向草稿', 补丁: { 工作城市: 已选[0]?.名称 ?? '' } });
      }
      返回();
      return;
    }
    if (是后端) {
      派发({
        型: '存引导预填',
        城市们: 已选.map((条) => 条.名称),
        职位: 全局.引导预填?.职位 ?? [],
        城市引用们: 已选.map((条) => ({ id: 条.键, display_name: 条.名称 })),
        // 本屏不选职位，保留原职位引用们（Task 4 R10：替换语义，原值带过）
        职位引用们: 全局.引导预填?.职位引用们 ?? [],
      });
    } else {
      派发({
        型: '存引导预填',
        城市们: 已选.map((条) => 条.名称),
        职位: 全局.引导预填?.职位 ?? [],
        // 没有 refs 时显式写空数组，禁止保留旧 refs
        城市引用们: [],
        职位引用们: [],
      });
    }
    返回();
  };

  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：页底改白底
    <次级页外壳 白底>
      <工作城市选择正文
        标题="你理想的工作城市是"
        上限={来自意向 ? 1 : 城市上限}
        初始已选={初始已选}
        搜索词={词}
        改搜索词={设词}
        列表={列表}
        返回={返回}
        保存={保存}
      />
    </次级页外壳>
  );
}