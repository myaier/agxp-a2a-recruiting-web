// 最高学历（/onboard/degree）—— 2026-08-20 按 BOSS 截图顺序重排：
// 方块单选七档。答案落 简历教育[0].学历（教育为空则先建一条空段，
// 后面的 毕业院校 / 选专业 / 就读时间段 三屏继续往同一段里填）。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';
import type { 简历教育段 } from '../数据/类型';

/** 学历七档（截图档位）*/
const 学历选项 = ['初中及以下', '中专中技', '高中', '大专', '本科', '硕士', '博士'];

export default function 最高学历() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  const 首段 = 全局.简历教育[0];

  const [当前, 设当前] = useState(
    首段 && 学历选项.includes(首段.学历) ? 首段.学历 : '本科'
  );

  const 下一步 = () => {
    // 教育为空则先建一条：后面三屏（院校 / 专业 / 时间段）都写这一段
    const 新教育: 简历教育段[] = 首段
      ? 全局.简历教育.map((条, 序) => (序 === 0 ? { ...条, 学历: 当前 } : 条))
      : [{ 编号: `edu${Date.now()}`, 学校: '', 学历: 当前, 专业: '', 开始: '', 结束: '' }];
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 新教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: 全局.基本信息,
    });
    跳转(路径.毕业院校);
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题 标题="最高学历" />

      <滚动区 样式覆盖={{ padding: '18px 18px 12px' }}>
        <div className={样式.方块网格}>
          {学历选项.map((项) => {
            const 选中 = 当前 === 项;
            return (
              <button
                key={项}
                className={`${样式.方块} ${选中 ? 样式.方块选中 : ''} 可点`}
                onClick={() => 设当前(项)}
                aria-pressed={选中}
              >
                <span className={样式.方块题}>{项}</span>
              </button>
            );
          })}
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
