// 最高学历（/onboard/degree）—— 2026-08-20 按 BOSS 截图顺序重排：
// 方块单选七档。答案落 简历教育[0].学历（教育为空则先建一条空段，
// 后面的 毕业院校 / 选专业 / 就读时间段 三屏继续往同一段里填）。
//
// 候选 onboarding 简历预填（Spec §8 /onboard/degree）：首挂载同步用 取最高学历预填
// 预选档位 —— eligible 且未确认的 degree 分区才建议，词表外（如 Bachelor）不翻译
// 不猜档、保留既有选择；确认 degree 分区只在既有保存成功后、跳转之前。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import { 取最高学历预填 } from '../流程/候选Onboarding简历预填';
import { 创建空候选预填状态 } from '../状态/后端/类型';
import { 轻提示 } from '../组件/轻提示';
import { 路径 } from '../路由/路径表';
import type { 简历教育段 } from '../数据/类型';

/** 学历档位：非学生 = 截图七档；学生 = 在读四档（分叉口两条路径不同档）*/
const 学历选项 = ['初中及以下', '中专/中技', '高中', '大专', '本科', '硕士', '博士'];
const 在读选项 = ['大专在读', '本科在读', '硕士在读', '博士在读'];

export default function 最高学历() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 操作, 数据源模式, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  const 首段 = 全局.简历教育[0];
  const 在校中 = 全局.基本信息.身份 === '在校';
  const 档表 = 在校中 ? 在读选项 : 学历选项;
  const 预填状态 = 后端状态.候选预填状态 ?? 创建空候选预填状态();

  // N：nullable selection —— 既有值取真实教育段/在读学历（词表外不算），
  // 建议只在无既有时预选；Backend 空教育不亮任何档，Mock 保留演示默认
  const [当前, 设当前] = useState<string | null>(() => {
    const 既有 = 在校中
      ? (全局.基本信息.在读学历 && 在读选项.includes(全局.基本信息.在读学历)
        ? 全局.基本信息.在读学历 : null)
      : (首段 && 学历选项.includes(首段.学历) ? 首段.学历 : null);
    const 建议 = 取最高学历预填(预填状态, 在校中, 既有 ?? '');
    return 建议 ?? 既有 ?? (是后端 ? null : (在校中 ? '本科在读' : '本科'));
  });

  const 下一步 = async () => {
    // N：未选择先给可见校验，不预创建教育记录（edu${Date.now()}）
    if (当前 === null) {
      轻提示(在校中 ? '请选择在读学历' : '请选择最高学历');
      return;
    }
    // 学生选的是「X在读」：教育段学历去掉「在读」二字，同时记 基本信息.在读学历
    const 落档学历 = 当前.replace('在读', '');
    // 教育为空则先建一条：后面三屏（院校 / 专业 / 时间段）都写这一段
    const 新教育: 简历教育段[] = 首段
      ? 全局.简历教育.map((条, 序) => (序 === 0 ? { ...条, 学历: 落档学历 } : 条))
      : [{ 编号: `edu${Date.now()}`, 学校: '', 学历: 落档学历, 专业: '', 开始: '', 结束: '' }];
    try {
      await 操作.保存简历({
        基本信息: 在校中 ? { ...全局.基本信息, 在读学历: 当前 } : 全局.基本信息,
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 新教育,
        证书: 全局.简历证书,
      });
      // 预填确认只在既有保存成功后（拒绝时分区不确认），且先于跳转
      操作.确认候选Onboarding预填分区('degree');
      跳转(路径.毕业院校);
    } catch (错误) {
      轻提示(取后端错误文案(错误));
    }
  };

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      <页面大标题 标题={在校中 ? '在读学历' : '最高学历'} />

      <滚动区 样式覆盖={{ padding: '18px 18px 12px' }}>
        <div className={样式.方块网格}>
          {档表.map((项) => {
            const 选中 = 当前 === 项;
            return (
              <button
                key={项}
                className={`${样式.方块} ${选中 ? 样式.方块选中 : ''} 可点`}
                onClick={() => 设当前(项)}
                aria-pressed={选中}
              >
                <span className={样式.方块题}>{项}</span>
              </button>
            );
          })}
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
