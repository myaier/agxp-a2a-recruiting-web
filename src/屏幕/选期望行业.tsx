// 选期望行业（/intentions/industries）—— 添加求职期望页的次级页 B（规格截图 5）。
//
// picker 统一 Task 1：两模式的目录展开/缓存/分页/重试/换代机制收敛到共用 屏幕行业目录钩子
// 与共用 行业分类列表（展示不读数据源模式/Context/raw DTO）。本页只保留数据适配与控制：
// Backend 注入 现有 查询Taxonomy('industries') 的 DTO 适配（创建目录行业查询，签名不变），
// Mock 沿本地 行业字典 的模拟适配（创建模拟行业查询，不发真实请求）；目录身份 = 模式+主体。
// 原页「推荐」chips 按 Plan 删除（伪推荐不再保留）；选择身份按稳定 ID
//（Backend = 目录 ID，Mock = 局部模拟键），点击按键取得原引用，不从名称重建 ID。
//
// 选择结果沿原业务直接写进 意向草稿.期望行业们 —— 主屏与本页共用同一份草稿，
// 所以右上「保存」和返回键做的是同一件事（都只是 返回()）：
// 不存在「不点保存就丢」的第二条路径，也就不会出现两个入口结果不一致。
// （与城市不同：本页不做取消回滚事务，保存负责返回。）
// Backend selectable 叶子原子保存 期望行业们+行业引用们（ID 去重，上限 3）。

import { useRef } from 'react';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import type { 行业项, 查询行业页 } from '../组件/行业分类列表';
import {
  use行业目录,
  创建模拟行业查询,
  创建目录行业查询,
  模拟行业名,
  模拟行业键们,
} from './行业目录钩子';
import type { 目录选择值 } from '../数据/招聘数据源类型';
import {
  期望行业选择正文,
} from '../组件/期望行业选择正文';

/** 期望行业上限（规格：最多 3 个）*/
const 行业上限 = 3;

export default function 选期望行业() {
  const { 返回 } = use导航();
  const { 状态: 全局, 派发, 数据源模式, 目录查询, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';

  // 草稿是唯一数据源：本页不留本地副本，每次点选立刻回写，
  // 这样返回键、保存键、手势返回三条出口拿到的结果必然一致。
  const 已选行业们 = 全局.意向草稿.期望行业们;
  const 已选引用 = 全局.意向草稿.行业引用们 ?? [];
  const 已选满 = 已选行业们.length >= 行业上限;

  // ── 目录查询适配注入（引用稳定，经 getter 读最新 目录查询；本文件不读 Context 内部）──
  const 取得查询方法 = useRef(() => 目录查询?.查询Taxonomy);
  取得查询方法.current = () => 目录查询?.查询Taxonomy;
  const 查询引用 = useRef<查询行业页 | null>(null);
  if (查询引用.current === null) {
    查询引用.current = 是后端 ? 创建目录行业查询(() => 取得查询方法.current()) : 创建模拟行业查询();
  }
  // 目录身份必须包含当前模式与主体身份：主体/模式变更作废旧缓存并重拉，不改已选业务值
  const 目录 = use行业目录({
    查询: 查询引用.current,
    目录身份: `${数据源模式}:${后端状态?.主体?.subject_id ?? ''}`,
  });

  /** 名称列表按值摘除首个同名条目：Backend 按 ID 取消时保持 名称↔引用 数量对齐 */
  const 摘除首个 = (们: string[], 名: string) => {
    const 下标 = 们.indexOf(名);
    return 下标 === -1 ? 们 : [...们.slice(0, 下标), ...们.slice(下标 + 1)];
  };

  /** 已选回显按稳定键：Backend 勾只落在已选引用的 ID 上（同名条目不互串）；
   *  Mock 沿名称草稿回显（模拟键与名称分离，同名细分各自成键） */
  const 已选键 = 是后端
    ? 已选引用.map((条) => 条.id)
    : 已选行业们.flatMap((名) => 模拟行业键们(名));

  /** 已选 → 再点取消；未选且没到上限 → 追加（满额拒绝，已选可取消、折叠不受限）*/
  const 选择 = (项: 行业项) => {
    if (是后端) {
      // 引用从稳定键取得（键 = 目录 ID），不从名称重建
      const 引用: 目录选择值 = { id: 项.键, display_name: 项.名称 };
      if (已选引用.some((条) => 条.id === 引用.id)) {
        // 按 ID 取消：引用去掉该 ID，名称列表只摘除一个同名条目（同名另一条保留）
        派发({
          型: '改意向草稿',
          补丁: {
            期望行业们: 摘除首个(已选行业们, 项.名称),
            行业引用们: 已选引用.filter((条) => 条.id !== 引用.id),
          },
        });
        return;
      }
      if (已选满) return;
      // ID 去重
      派发({
        型: '改意向草稿',
        补丁: {
          期望行业们: [...已选行业们, 项.名称],
          行业引用们: [...已选引用, 引用],
        },
      });
      return;
    }
    const 名 = 模拟行业名(项.键);
    if (名 === undefined) return;
    if (已选行业们.includes(名)) {
      派发({ 型: '改意向草稿', 补丁: { 期望行业们: 已选行业们.filter((条) => 条 !== 名) } });
      return;
    }
    if (已选满) return;
    派发({ 型: '改意向草稿', 补丁: { 期望行业们: [...已选行业们, 名] } });
  };

  return (
    <期望行业选择正文
      已选键={已选键}
      上限={行业上限}
      目录={目录}
      选择={选择}
      /* 选择即写意向草稿（原业务）：保存与返回同途，都只负责返回 */
      返回={返回}
      保存={返回}
    />
  );
}