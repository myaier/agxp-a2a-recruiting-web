// R2 选择身份 · 三端分流点。
// 两端可用：求职者 → 引导流程；招聘方 → 实名认证 → 招聘名片 → 发岗。
// 猎头端已按用户指令（2026-08-17）整个移除。原注释：
// 「该端本次未开放」并禁用 —— 让产品形态可见，同时明确走不通，避免用户以为是 bug。

import { useEffect, useRef, useState } from 'react';
import { useLocation } from 'react-router-dom';
import 样式 from './选身份.module.css';
import { 求职插画, 招人插画 } from '../组件/身份插画';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮 } from '../组件/通用';
import 代理标 from '../组件/代理标';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';
import { 身份首次入口 } from '../流程/onboarding配置';

/** 三端身份键：也直接用作主按钮文案里的身份名 */
type 身份键 = '求职者' | '企业';



export default function 选身份() {
  const { 跳转, 返回, 替换跳转 } = use导航();
  const { 派发 } = use应用状态();
  // 切换身份模式（#/identity?switch=1&from=app|hr）：老用户切端，
  // 不重走注册引导，直接进对应主壳（标注意见 2026-08-18）
  const 查询 = new URLSearchParams(useLocation().search);
  const 切换模式 = 查询.get('switch') === '1';
  const 来源 = 查询.get('from');
  // 切换模式只给「对面」一个选项（用户定 2026-08-18）：两个都摆着，用户可能
  // 选中当前身份又切回自己，等于「切不过去」。所以这里目标身份是算出来的，不给选。
  const 目标身份: 身份键 = 来源 === 'app' ? '企业' : '求职者';
  // ── 翻面切换（2026-08-18 用户：切换页太普通，要有创意）──
  // 我们的隐喻不借 BOSS 的插画，用产品自己的核心概念：不对称双盲 = 同一个人的两面。
  // 求职那面匿名（代号示人，荧光绿），招聘那面实名（名片示人，墨色）。
  // 点按钮卡片翻 180°，翻完才真正切端 —— 动画本身就在讲这个产品的规则。
  const [已翻面, 设已翻面] = useState(false);
  const 翻面计时 = useRef<number | null>(null);
  useEffect(() => {
    return () => {
      if (翻面计时.current !== null) window.clearTimeout(翻面计时.current);
    };
  }, []);

  const 切换身份 = () => {
    if (已翻面) return; // 动画进行中，别重复触发
    设已翻面(true);
    翻面计时.current = window.setTimeout(() => {
      // 落地视图也要切过去：求职者看「职位」，招聘方看「人才」（标注意见 2026-08-18）
      派发({ 型: '切身份', 到: 目标身份 === '企业' ? '招聘方' : '求职者' });
      // 用替换跳转：切身份不该在返回栈里留一层「另一端」
      替换跳转(目标身份 === '企业' ? 路径.企业主壳 : 路径.主壳);
    }, 950);
  };

  // 切换模式的两面：正面 = 当前身份，背面 = 目标身份
  const 当前身份: 身份键 = 目标身份 === '企业' ? '求职者' : '企业';

  return (
    <次级页外壳>
      {/* 补返回栏（直达标注意见 21:23）：后续每一屏都有它，缺了会让本屏标题
          比后面所有页面高一行（约 44px），视觉上「太靠上」。顺带也让用户能退回登录页。 */}
      <返回栏 返回={返回} />

      {/* 选身份的问题句按标注 2026-08-24 删除（参考 BOSS：插画讲故事，不用问句）；
          大标题只留给切换模式 */}
      {切换模式 ? (
        <页面大标题
          标题={目标身份 === '企业' ? '切换到招聘端' : '切换到求职端'}
          // 标注 22:57：切换模式的说明小字删掉，标题自己说得清
        />
      ) : null}

      {切换模式 ? (
        <div className={样式.翻面区}>
          <div className={样式.翻面浮}>
            <div className={`${样式.翻面卡} ${已翻面 ? 样式.已翻面 : ''}`}>
              <身份面 键={当前身份} 背面={false} />
              <身份面 键={目标身份} 背面 />
            </div>
          </div>
        </div>
      ) : (
<div className={样式.分屏列}>
        {/* 方案 C（2026-08-24，「我觉得C比B好」）：上下各半屏、一绿一蓝各染各的，
            点半屏即选。插画 = 场景化图标（组件/身份插画），不是 BOSS 的人物风 */}
        <button
          type="button"
          className={`${样式.半屏钮} ${样式.半屏求职} 可点`}
          onClick={() => 跳转(身份首次入口('求职者'))}
        >
          <求职插画 />
          <span className={样式.半屏名}>我要找工作</span>
        </button>
        <span className={样式.半屏线} aria-hidden />
        <button
          type="button"
          className={`${样式.半屏钮} ${样式.半屏招聘} 可点`}
          onClick={() => 跳转(身份首次入口('企业'))}
        >
          <招人插画 />
          <span className={样式.半屏名}>我要招人</span>
        </button>
      </div>
      )}

      {切换模式 ? (
        <主按钮
          文字={
            已翻面
              ? '正在切换…'
              : 目标身份 === '企业'
                ? '翻到「招聘方」那一面'
                : '翻到「求职者」那一面'
          }
          禁用={已翻面}
          按下={切换身份}
        />
      ) : null}
    </次级页外壳>
  );
}

/**
 * 翻面卡的一面。两面讲的就是不对称双盲：
 * 求职面 —— 荧光绿，匿名（代号示人，确认意向才露名）；
 * 招聘面 —— 墨色，实名（名片示人，候选人第一轮就看到你）。
 */
function 身份面({
  键,
  背面,
  静态 = false,
}: {
  键: 身份键;
  背面: boolean;
  /** true = 注册页的选项卡：不参与 3D 翻转，走文档流 */
  静态?: boolean;
}) {
  const 求职 = 键 === '求职者';
  return (
    <div
      className={`${样式.面} ${求职 ? 样式.面求职 : 样式.面招聘} ${背面 ? 样式.面背 : ''} ${
        静态 ? 样式.面静态 : ''
      }`}
    >
      {/* 右上角超大代理标水印：这一面归哪位代理管 */}
      <span className={样式.面水印} aria-hidden>
        <代理标
          尺寸={150}
          脸色="transparent"
          眼色={求职 ? 'rgba(26,26,26,0.16)' : 'rgba(255,255,255,0.15)'}
          描边色={求职 ? 'rgba(26,26,26,0.16)' : 'rgba(255,255,255,0.15)'}
          描边宽={2.2}
        />
      </span>

      <span className={样式.面章}>{求职 ? '匿名示人' : '实名示人'}</span>

      <span className={样式.面主}>
        <span className={样式.面身份}>{求职 ? '求职者' : '招聘方'}</span>
        {/* 标注 2026-08-20 13:21 / 17:00：两面都只留身份名，说明小字全删 */}
      </span>

    </div>
  );
}
