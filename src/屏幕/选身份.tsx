// R2 选择身份 · 三端分流点。
// 两端可用：求职者 → 引导流程；招聘方 → 实名认证 → 招聘名片 → 发岗。
// 猎头端已按用户指令（2026-08-17）整个移除。原注释：
// 「该端本次未开放」并禁用 —— 让产品形态可见，同时明确走不通，避免用户以为是 bug。

import { useState } from 'react';
import 样式 from './选身份.module.css';
import { 次级页外壳, 页面大标题, 主按钮, 单选点 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

/** 三端身份键：也直接用作主按钮文案里的身份名 */
type 身份键 = '求职者' | '企业';

interface 身份项 {
  键: 身份键;
  标题: string;
  /** 本次是否开放；false 的端可选中但不能继续 */
  可用: boolean;
}

const 身份列表: 身份项[] = [
  // 说明小字已按直达标注意见（2026-08-17 21:13）删除，卡片只留标题
  { 键: '求职者', 标题: '我要找工作', 可用: true },
  { 键: '企业', 标题: '我要招人', 可用: true },
];

export default function 选身份() {
  const { 跳转 } = use导航();
  const [选中, 设选中] = useState<身份键>('求职者');

  const 选中项 = 身份列表.find((项) => 项.键 === 选中) ?? 身份列表[0];

  return (
    <次级页外壳>
      <页面大标题 标题="你想用它做什么？" />

      <div className={样式.列表}>
        {身份列表.map((项) => {
          const 当前 = 选中 === 项.键;
          return (
            <button
              key={项.键}
              className={`${样式.身份卡} ${当前 ? 样式.选中 : ''} 可点`}
              onClick={() => 设选中(项.键)}
            >
              <span className={样式.图标底}>
                <身份图标 键={项.键} />
              </span>
              <span className={样式.身份文字}>
                <span className={样式.身份标题}>{项.标题}</span>
              </span>
              <单选点 选中={当前} />
            </button>
          );
        })}
      </div>

      {/* 尾注按用户标注意见（2026-08-17）从选项卡下方挪到底部按钮上方 */}
      <div className={样式.尾注}>求职者即选即用；招聘方需实名认证。</div>

      <主按钮
        文字={选中 === '企业' ? '以「招聘方」身份继续' : '以「求职者」身份继续'}
        禁用={!选中项.可用}
        按下={() => 跳转(选中 === '企业' ? 路径.企业实名认证 : 路径.引导说明)}
      />
    </次级页外壳>
  );
}

/**
 * 两个身份的彩绘极简图标（Robinhood 风，直达标注意见 2026-08-17 21:20）。
 *
 * 这套风格的三条要点，也是它和原来线性图标的根本差别：
 *   · 大色块填充，不靠描边勾轮廓 —— 远看是一个「形」，不是一堆线；
 *   · 圆润几何：只用圆、圆角矩形、粗圆头线段拼，不画写实细节；
 *   · 双色分层：主色（品牌荧光绿 / 深绿）+ 一层半透明同色做纵深。
 * 因为是填充色块，尺寸取 34（52px 圆底里留 9px 边距）才压得住，比线性图标大得多。
 */
function 身份图标({ 键 }: { 键: 身份键 }) {
  const 公共属性 = {
    width: 34,
    height: 34,
    viewBox: '0 0 32 32',
    'aria-hidden': true,
  };

  // 求职者：一枚圆润公文包 —— 深绿箱体 + 荧光绿提手与锁扣
  if (键 === '求职者') {
    return (
      <svg {...公共属性}>
        {/* 提手 */}
        <path
          d="M12 9V7.5A2.5 2.5 0 0 1 14.5 5h3A2.5 2.5 0 0 1 20 7.5V9"
          fill="none"
          stroke="var(--深绿)"
          strokeWidth={2.6}
          strokeLinecap="round"
        />
        {/* 箱体 */}
        <rect x="4" y="9" width="24" height="18" rx="5" fill="var(--深绿)" />
        {/* 中缝亮带：荧光绿横条，Robinhood 那种「一条高亮」的处理 */}
        <rect x="4" y="16" width="24" height="3.4" fill="var(--荧光绿)" />
        {/* 锁扣 */}
        <rect x="14.4" y="15" width="3.2" height="5.4" rx="1.6" fill="var(--荧光绿)" />
      </svg>
    );
  }

  // 招聘方：两栋圆角楼 —— 深绿主楼 + 荧光绿副楼，窗户用圆点
  return (
    <svg {...公共属性}>
      {/* 副楼（矮，荧光绿） */}
      <rect x="17" y="13" width="11" height="15" rx="3.4" fill="var(--荧光绿)" />
      {/* 主楼（高，深绿） */}
      <rect x="4" y="5" width="14" height="23" rx="4" fill="var(--深绿)" />
      {/* 主楼窗户：两列三行圆点，用荧光绿点亮 */}
      <g fill="var(--荧光绿)">
        <circle cx="8.4" cy="12" r="1.9" />
        <circle cx="13.6" cy="12" r="1.9" />
        <circle cx="8.4" cy="19" r="1.9" />
        <circle cx="13.6" cy="19" r="1.9" />
      </g>
      {/* 副楼一扇深绿窗，和主楼互为反色 */}
      <circle cx="22.5" cy="20" r="1.9" fill="var(--深绿)" />
    </svg>
  );
}
