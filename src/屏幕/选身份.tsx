// R2 选择身份 · 三端分流点。
// 两端可用：求职者 → 引导流程；招聘方 → 实名认证 → 招聘名片 → 发岗。
// 猎头端已按用户指令（2026-08-17）整个移除。原注释：
// 「该端本次未开放」并禁用 —— 让产品形态可见，同时明确走不通，避免用户以为是 bug。

import { useEffect, useRef, useState } from 'react';
import { useLocation } from 'react-router-dom';
import 样式 from './选身份.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 单选点 } from '../组件/通用';
import 代理标 from '../组件/代理标';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';

/** 三端身份键：也直接用作主按钮文案里的身份名 */
type 身份键 = '求职者' | '企业';

interface 身份项 {
  键: 身份键;
  标题: string;
  /** 本次是否开放；false 的端可选中但不能继续 */
  可用: boolean;
}

const 身份列表: 身份项[] = [
  // 说明小字已按直达标注意见（2026-08-17 21:13）删除，卡片只留标题
  { 键: '求职者', 标题: '我要找工作', 可用: true },
  { 键: '企业', 标题: '我要招人', 可用: true },
];

export default function 选身份() {
  const { 跳转, 返回, 替换跳转 } = use导航();
  const { 派发 } = use应用状态();
  // 切换身份模式（#/identity?switch=1&from=app|hr）：老用户切端，
  // 不重走注册引导，直接进对应主壳（标注意见 2026-08-18）
  const 查询 = new URLSearchParams(useLocation().search);
  const 切换模式 = 查询.get('switch') === '1';
  const 来源 = 查询.get('from');
  // 切换模式只给「对面」一个选项（用户定 2026-08-18）：两个都摆着，用户可能
  // 选中当前身份又切回自己，等于「切不过去」。所以这里目标身份是算出来的，不给选。
  const 目标身份: 身份键 = 来源 === 'app' ? '企业' : '求职者';
  const [选中, 设选中] = useState<身份键>(切换模式 ? 目标身份 : '求职者');

  const 选中项 = 身份列表.find((项) => 项.键 === 选中) ?? 身份列表[0];

  // ── 翻面切换（2026-08-18 用户：切换页太普通，要有创意）──
  // 我们的隐喻不借 BOSS 的插画，用产品自己的核心概念：不对称双盲 = 同一个人的两面。
  // 求职那面匿名（代号示人，荧光绿），招聘那面实名（名片示人，墨色）。
  // 点按钮卡片翻 180°，翻完才真正切端 —— 动画本身就在讲这个产品的规则。
  const [已翻面, 设已翻面] = useState(false);
  const 翻面计时 = useRef<number | null>(null);
  useEffect(() => {
    return () => {
      if (翻面计时.current !== null) window.clearTimeout(翻面计时.current);
    };
  }, []);

  const 继续 = () => {
    if (切换模式) {
      if (已翻面) return; // 动画进行中，别重复触发
      设已翻面(true);
      翻面计时.current = window.setTimeout(() => {
        // 落地视图也要切过去：求职者看「职位」，招聘方看「人才」（标注意见 2026-08-18）
        派发({ 型: '切身份', 到: 目标身份 === '企业' ? '招聘方' : '求职者' });
        // 用替换跳转：切身份不该在返回栈里留一层「另一端」
        替换跳转(目标身份 === '企业' ? 路径.企业主壳 : 路径.主壳);
      }, 950);
      return;
    }
    // 求职者先进学生分流（在校 / 有经验），后续三屏按分流结果分支
    // 标注 2026-08-20 13:32：企业端先不做实名认证，注册直接进招聘名片
    跳转(选中 === '企业' ? 路径.招聘名片 : 路径.引导说明);
  };

  // 切换模式的两面：正面 = 当前身份，背面 = 目标身份
  const 当前身份: 身份键 = 目标身份 === '企业' ? '求职者' : '企业';

  return (
    <次级页外壳>
      {/* 补返回栏（直达标注意见 21:23）：后续每一屏都有它，缺了会让本屏标题
          比后面所有页面高一行（约 44px），视觉上「太靠上」。顺带也让用户能退回登录页。 */}
      <返回栏 返回={返回} />

      <页面大标题
        标题={
          切换模式
            ? 目标身份 === '企业'
              ? '切换到招聘端'
              : '切换到求职端'
            : '你想用它做什么？'
        }
        // 标注 22:57：切换模式的说明小字删掉，标题自己说得清
      />

      {切换模式 ? (
        <div className={样式.翻面区}>
          <div className={样式.翻面浮}>
            <div className={`${样式.翻面卡} ${已翻面 ? 样式.已翻面 : ''}`}>
              <身份面 键={当前身份} 背面={false} />
              <身份面 键={目标身份} 背面 />
            </div>
          </div>
        </div>
      ) : (
<div className={样式.列表}>
        {身份列表.map((项) => {
          const 当前 = 选中 === 项.键;
          return (
            <div
              key={项.键}
              className={`${样式.身份卡} ${当前 ? 样式.选中 : ''} 可点`}
              onClick={() => 设选中(项.键)}
              role="button"
            >
              <span className={样式.图标底}>
                <身份图标 键={项.键} />
              </span>
              <span className={样式.身份文字}>
                <span className={样式.身份标题}>{项.标题}</span>
              </span>
              <单选点 选中={当前} />
            </div>
          );
        })}
      </div>
      )}

      <主按钮
        文字={
          切换模式
            ? 已翻面
              ? '正在切换…'
              : 目标身份 === '企业'
                ? '翻到「招聘方」那一面'
                : '翻到「求职者」那一面'
            : 选中 === '企业'
              ? '以「招聘方」身份继续'
              : '以「求职者」身份继续'
        }
        禁用={!选中项.可用 || (切换模式 && 已翻面)}
        按下={继续}
      />
    </次级页外壳>
  );
}

/**
 * 翻面卡的一面。两面讲的就是不对称双盲：
 * 求职面 —— 荧光绿，匿名（代号示人，确认意向才露名）；
 * 招聘面 —— 墨色，实名（名片示人，候选人第一轮就看到你）。
 */
function 身份面({
  键,
  背面,
  静态 = false,
}: {
  键: 身份键;
  背面: boolean;
  /** true = 注册页的选项卡：不参与 3D 翻转，走文档流 */
  静态?: boolean;
}) {
  const 求职 = 键 === '求职者';
  return (
    <div
      className={`${样式.面} ${求职 ? 样式.面求职 : 样式.面招聘} ${背面 ? 样式.面背 : ''} ${
        静态 ? 样式.面静态 : ''
      }`}
    >
      {/* 右上角超大代理标水印：这一面归哪位代理管 */}
      <span className={样式.面水印} aria-hidden>
        <代理标
          尺寸={150}
          脸色="transparent"
          眼色={求职 ? 'rgba(26,26,26,0.16)' : 'rgba(255,255,255,0.15)'}
          描边色={求职 ? 'rgba(26,26,26,0.16)' : 'rgba(255,255,255,0.15)'}
          描边宽={2.2}
        />
      </span>

      <span className={样式.面章}>{求职 ? '匿名示人' : '实名示人'}</span>

      <span className={样式.面主}>
        <span className={样式.面身份}>{求职 ? '求职者' : '招聘方'}</span>
        {/* 标注 2026-08-20 13:21 / 17:00：两面都只留身份名，说明小字全删 */}
      </span>

    </div>
  );
}

/**
 * 两个身份的彩绘极简图标（Robinhood 风，直达标注意见 2026-08-17 21:20）。
 *
 * 这套风格的三条要点，也是它和原来线性图标的根本差别：
 *   · 大色块填充，不靠描边勾轮廓 —— 远看是一个「形」，不是一堆线；
 *   · 圆润几何：只用圆、圆角矩形、粗圆头线段拼，不画写实细节；
 *   · 双色分层：主色（品牌荧光绿 / 深绿）+ 一层半透明同色做纵深。
 * 因为是填充色块，尺寸取 34（52px 圆底里留 9px 边距）才压得住，比线性图标大得多。
 */
function 身份图标({ 键 }: { 键: 身份键 }) {
  const 公共属性 = {
    width: 34,
    height: 34,
    viewBox: '0 0 32 32',
    'aria-hidden': true,
  };

  // 求职者：一枚圆润公文包 —— 深绿箱体 + 荧光绿提手与锁扣
  if (键 === '求职者') {
    return (
      <svg {...公共属性}>
        {/* 提手 */}
        <path
          d="M12 9V7.5A2.5 2.5 0 0 1 14.5 5h3A2.5 2.5 0 0 1 20 7.5V9"
          fill="none"
          stroke="var(--深绿)"
          strokeWidth={2.6}
          strokeLinecap="round"
        />
        {/* 箱体 */}
        <rect x="4" y="9" width="24" height="18" rx="5" fill="var(--深绿)" />
        {/* 中缝亮带：荧光绿横条，Robinhood 那种「一条高亮」的处理 */}
        <rect x="4" y="16" width="24" height="3.4" fill="var(--荧光绿)" />
        {/* 锁扣 */}
        <rect x="14.4" y="15" width="3.2" height="5.4" rx="1.6" fill="var(--荧光绿)" />
      </svg>
    );
  }

  // 招聘方：两栋圆角楼 —— 深绿主楼 + 荧光绿副楼，窗户用圆点
  return (
    <svg {...公共属性}>
      {/* 副楼（矮，荧光绿） */}
      <rect x="17" y="13" width="11" height="15" rx="3.4" fill="var(--荧光绿)" />
      {/* 主楼（高，深绿） */}
      <rect x="4" y="5" width="14" height="23" rx="4" fill="var(--深绿)" />
      {/* 主楼窗户：两列三行圆点，用荧光绿点亮 */}
      <g fill="var(--荧光绿)">
        <circle cx="8.4" cy="12" r="1.9" />
        <circle cx="13.6" cy="12" r="1.9" />
        <circle cx="8.4" cy="19" r="1.9" />
        <circle cx="13.6" cy="19" r="1.9" />
      </g>
      {/* 副楼一扇深绿窗，和主楼互为反色 */}
      <circle cx="22.5" cy="20" r="1.9" fill="var(--深绿)" />
    </svg>
  );
}
