// P7 Backend 收件箱（双角色共用）：只读 后端状态.P7收件箱[role] 的内存快照与
// 真人会话操作，绝不 import Mock 消息 fixture。结构与行 JSX 统一收进 消息列表展示
// （P1 Task 4），字段映射收进 消息行映射；Task 2 起行消费 use会话列表资料 的本轮
// 本地资料（available = 授权姓名 + 企业·岗位副标题 + 真实头像；unavailable = 会话
// 资料暂不可用；loading = P7 viewer-safe 标签），姓名/副标题/摘要同源进本地搜索。
// 本文件只剩连接层 —— 可见范围登记/注销、force 首读、分页、重试、本地过滤、资料
// 补读编排接线。context 不可用只降级展示；unread_count=0 无红点、>0 数字胶囊；点行
// 只走参数路由导航（Builder），已读由会话页 read-through 回执收敛 —— 绝不派发
// 读消息/企业读消息、绝不本地清零。「全部」「仅会话」展示同一已加载集合；「通知」=
// 固定 AI 动态入口行。固定 AI 入口行只在展示层组装（零快照/分页/未读写入），键
// agent-entry:* 与十进制 conversationId 空间不相交；受页签/搜索约束但不参与 P7 的
// 错误/读入提示与加载更多。搜索只过滤已加载项与该入口行，不声称搜全部。

import { useEffect, useMemo, useState } from 'react';
import { 从Backend消息行 } from '../消息列表展示/消息行映射';
import { 消息列表展示 } from '../消息列表展示/消息列表展示';
import type { 会话行数据, 消息页签 } from '../消息列表展示/类型';
import { use导航 } from '../../路由/导航钩子';
import { 路径 } from '../../路由/路径表';
import { use应用状态 } from '../../状态/应用状态';
import { use会话列表资料 } from './use会话列表资料';
import type { P7角色, P7会话项 } from '../../数据/招聘数据源/真人会话';

/** 搜索无匹配的既有文案（通知与全部/仅会话共用同一份，不另起说法）。 */
const 无匹配行们 = ['没有匹配的会话。', '换个关键词，或者切到「全部」看看。'];

export default function Backend会话列表({ 角色: role }: { 角色: P7角色 }) {
  const { 跳转 } = use导航();
  const { 后端状态, 操作 } = use应用状态();
  const 快照 = 后端状态.P7收件箱[role];
  const [当前页签, 设当前页签] = useState<消息页签>('全部');
  const [搜索词, 设搜索词] = useState('');
  const 通知页签 = 当前页签 === '通知';

  // Task 2：已加载 available 项的会话资料补读编排（去重 / ≤4 并发 / 翻页追加 /
  // 失败定向重试），行展示与本地搜索同源消费。
  const { 资料表, 有失败, 重试失败 } = use会话列表资料(role, 快照.items);

  // 进入消息 Tab：登记收件箱可见范围 + force 权威刷新（操作层单飞防重复）；
  // 卸载注销可见范围。事件层据此决定失效重拉的范围。
  useEffect(() => {
    操作.设置P7收件箱范围(role, true);
    void 操作.加载会话列表(role, true);
    return () => 操作.设置P7收件箱范围(role, false);
  }, [role, 操作]);

  // 固定 AI 动态入口行：不构造 P7 会话项（无假 human_handoff、不写快照），只在展示层
  // 组装；时间留空不伪造，未读无标记。点击直接去代理页参数路由，不经过真人会话。
  // 求职端助手聊天已开放（Spec §7）：摘要改为真实能力说明；招聘端仍未开放，原文案保持。
  const AI入口行: 会话行数据 = {
    键: role === 'candidate' ? 'agent-entry:candidate' : 'agent-entry:recruiter',
    标题: 'AI代理动态',
    副标题: role === 'candidate' ? '你的求职AI代理' : '你的招聘AI代理',
    时间: '',
    摘要: role === 'candidate' ? '查看岗位推荐和在谈进展' : '聊天暂未开放，可查看代理功能',
    头像: { 种类: '代理' },
    未读: { 种类: '无' },
    按下: () => 跳转(role === 'candidate' ? 路径.问AI代理 : 路径.企业问AI代理),
  };

  // 本地搜索只过滤已加载项；「全部」与「仅会话」是同一已加载集合（P7 只有真人会话）。
  // 过滤字段与行展示同源：都走 从Backend消息行（资料/角色反转/降级/摘要缺省一处说了
  // 算），姓名搜索随资料加载结果更新；AI 入口行同规则匹配 标题/副标题/摘要。
  const 关键词 = 搜索词.trim();
  const AI行命中 = 关键词 === ''
    || `${AI入口行.标题} ${AI入口行.副标题} ${AI入口行.摘要}`.includes(关键词);
  const 过滤后 = useMemo(() => {
    if (通知页签) return [];
    if (!关键词) return 快照.items;
    return 快照.items.filter((条) => {
      const 行 = 从Backend消息行(条, role, () => {}, 资料表[条.caseId]);
      return `${行.标题} ${行.副标题} ${行.摘要}`.includes(关键词);
    });
  }, [快照.items, 通知页签, 关键词, role, 资料表]);

  /** 点行只导航到参数路由；已读由会话页 read-through 回执权威收敛，不本地清零。 */
  const 打开会话 = (条: P7会话项) => {
    跳转(role === 'candidate'
      ? 路径.真人会话路径(条.conversationId)
      : 路径.企业真人会话路径(条.conversationId));
  };

  // AI 入口行受页签约束：全部/通知显示（搜索命中时），仅会话隐藏；入口只有这一条，
  // 不随分页追加 —— P7 行映射顺序原样保留，AI 行永远排第一。
  const 行们: 会话行数据[] = [
    ...(当前页签 !== '仅会话' && AI行命中 ? [AI入口行] : []),
    ...(通知页签 ? [] : 过滤后.map((条) => 从Backend消息行(条, role, () => 打开会话(条), 资料表[条.caseId]))),
  ];

  // 状态区沿用原互斥条件，错误与缓存行可共存：错误/读入中在前，成功空页/搜索无命中在后。
  // AI 入口行不参与这些提示：通知页签仍无错误/读入/加载更多，真实收件箱错误不被掩盖。
  // Task 2：资料补读局部失败给独立提示 + 定向重试（行本身仍可点）。
  const 前置提示 = 通知页签
    ? []
    : [
      ...(快照.error !== null
        ? [{
          键: '错误',
          行们: [快照.error],
          操作: { 文案: '重试', 按下: () => void 操作.加载会话列表(role, true) },
        }]
        : []),
      ...(快照.阶段 !== '成功' && 快照.items.length === 0 && 快照.error === null
        ? [{ 键: '读入中', 行们: ['正在读入会话…'] }]
        : []),
      ...(有失败
        ? [{ 键: '资料失败', 行们: ['部分会话资料暂不可用'], 操作: { 文案: '重试', 按下: 重试失败 } }]
        : []),
    ];
  const 后置提示 = 通知页签
    ? (AI行命中 ? [] : [{ 键: '无匹配', 行们: 无匹配行们 }])
    : [
      ...(快照.阶段 === '成功' && 快照.items.length === 0 && 关键词 === ''
        ? [{ 键: '空', 行们: ['还没有真人会话'] }]
        : []),
      // 无匹配只在「搜过了」的前提下成立：P7 成功（读入完成）或有缓存行可对照；
      // 首读未完成且无缓存只保留错误/读入提示，不宣称搜完。AI 行命中即不出。
      ...(关键词 !== '' && 行们.length === 0 && (快照.阶段 === '成功' || 快照.items.length > 0)
        ? [{ 键: '无匹配', 行们: 无匹配行们 }]
        : []),
    ];

  return (
    <消息列表展示
      页签={当前页签}
      改页签={设当前页签}
      搜索词={搜索词}
      改搜索词={设搜索词}
      搜索提示={role === 'candidate' ? '搜索会话 / 公司 / 职位' : '搜索会话 / 候选 / 岗位'}
      前置提示={前置提示}
      行们={行们}
      后置提示={后置提示}
      加载更多={!通知页签 && 快照.nextCursor !== null
        ? () => void 操作.追加会话列表(role)
        : undefined}
    />
  );
}