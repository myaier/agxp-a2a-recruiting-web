/**
 * Mock 公司五元行：档案规模行按内容认段（与 公司区块 的静态路径同判据，档案未补全时
 * 用在谈单的一行简介兜底），缺哪段补 null —— 五个元行位置固定，缺失由资料组件原位显示。
 * （公司区块 的 资料 合同表达不了「有标签但缺值」的行，这里在连接层投影同形。）
 */
function Mock公司元行(档案: 公司档案, 一行简介: string): 职位资料信息['公司']['元行'] {
  const 档案未补全 = 档案.规模行 === '规模与融资信息待补充';
  const 段们 = (档案未补全 ? 一行简介 : 档案.规模行).split(' · ').filter((段) => 段 !== '');
  const 认段 = (段: string): '融资阶段' | '规模' | '行业' =>
    /轮|上市/.test(段) ? '融资阶段' : /人/.test(段) ? '规模' : '行业';
  const 值 = (标签: '融资阶段' | '规模' | '行业') => 段们.find((段) => 认段(段) === 标签) ?? null;
  const 成立年 = 档案.工商信息.find((条) => 条.项 === '成立日期')?.值.slice(0, 4);
  return [
    { 标签: '融资阶段', 值: 值('融资阶段') },
    { 标签: '规模', 值: 值('规模') },
    { 标签: '行业', 值: 值('行业') },
    { 标签: '成立', 值: 成立年 !== undefined && !档案未补全 ? `${成立年} 年` : null },
    { 标签: '地址', 值: 档案未补全 ? null : 档案.地址 },
  ];
}

