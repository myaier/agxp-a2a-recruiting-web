/** 点决策那一刻冻结下来的卡点上下文（见 做协调决策 的注释） */
interface 决策快照内容 {
  分歧: 分歧 | null;
  决定文案: string;
  规则草案: string;
}

// ── 弹层文案：必须带这一单的真实上下文（公司 + 卡点项 + 差值），不能用写死的示例句 ──
function 算决策文案(单: 在谈单, 类型: '接受' | '退出'): { 决定文案: string; 规则草案: string } {
  // 卡点项名从「卡在作息，AI代理建议…」这类下一步文案里抠出来（作息 / 办公方式…）。
  // 需要协调只谈软性要求，薪资与到岗不在这里（产品边界 2026-08-18）
  const 卡点项名 = /卡在(.{1,6}?)[，,]/.exec(单.下一步)?.[1] ?? '这一项';
  // '差 2K' → '2K'，只留净差值，方便拼进规则草案
  const 差值净 = 单.分歧 ? 单.分歧.差值.replace(/^差\s*/, '') : null;
  // 差值末尾是英文单位（2K）时后面补一个空格，中文单位（15 天）时不补 —— 中英混排间距
  const 差值短语 = 差值净 ? (/[a-zA-Z]$/.test(差值净) ? `${差值净} ` : 差值净) : '';
  // 决定文案里差值后面直接跟逗号，用不带尾空格的净差值；规则草案后面跟「的 / 以内」，用带空格的
  const 卡点描述 = 差值净 ? `「${卡点项名}」上差 ${差值净}` : `「${卡点项名}」这一项`;

  return 类型 === '退出'
    ? {
        决定文案: `${单.公司}${卡点描述}，你选择了不让 —— AI代理已终止这一单，不再消耗你的匿名额度。`,
        规则草案: 差值净
          ? `${卡点项名}差超过 ${差值短语}的岗位，直接过滤，不用先问我`
          : `触到${卡点项名}这条线的岗位，直接过滤，不用先问我`,
      }
    : {
        决定文案: `${单.公司}${卡点描述}，你同意放宽 —— AI代理会立刻回报对方，把这一单推进到意向确认。`,
        规则草案: 差值净
          ? `${卡点项名}差 ${差值短语}以内的，可以直接替我放宽`
          : `${卡点项名}这类分歧不大的，可以直接替我放宽`,
      };
}

export default function 在谈详情() {
  const { id: 编号 = '' } = useParams<{ id: string }>();
  const { 状态, 派发 } = use应用状态();
  const { 跳转, 返回 } = use导航();

  const [当前Tab, 设当前Tab] = useState<页内Tab>('谈判进度');
  const [弹层可见, 设弹层可见] = useState(false);
  const [决策快照, 设决策快照] = useState<决策快照内容 | null>(null);
  // 顶部「在线简历」折叠卡：默认收起（标注意见 2026-08-18 23:51）。
  // 内容是脱敏的在线简历 —— 从匿名初筛起对方核对的就是它，所以每一单都显示
  const [简历卡展开, 设简历卡展开] = useState(false);
  // 点开的简历原件（null = 没开）：点阶段节点里的 PDF 附件行打开原件弹层
  const [看原件, 设看原件] = useState<{ 文件名: string } | null>(null);
  // 已完成阶段默认收起（标注 09:36：列太长）；点行展开
  const [展开阶段, 设展开阶段] = useState<Set<string>>(() => new Set());
  // 进入页面自动定位到当前需要行动的节点，不用手动划过整条时间线
  const 当前节点引用 = useRef<HTMLDivElement>(null);
  useEffect(() => {
    // 布局稳定后再滚（折叠卡/骨架挂载完），block:'start' 让决策区顶到视口上部
    const 定时 = window.setTimeout(() => {
      当前节点引用.current?.scrollIntoView({ block: 'start', behavior: 'smooth' });
    }, 120);
    return () => window.clearTimeout(定时);
  }, []);

  // 从一单切到另一单时（同路由只换参数，组件不重挂载），折叠卡收起、弹层关闭，
  // 否则上一单里的展开/弹层状态会残留到下一单
  useEffect(() => {
    设简历卡展开(false);
    设看原件(null);
  }, [编号]);

  // 「退出谈判」会把这一单从在谈列表里移除（归档），页面必须留一份快照，
  // 否则用户点完「不谈了 · 退出」整屏会瞬间跳成已归档提示，看不到决策回执。
  const 列表内单 = 状态.在谈列表.find((条) => 条.编号 === 编号);
  const [快照单, 设快照单] = useState<在谈单 | null>(列表内单 ?? null);
  useEffect(() => {
    if (列表内单) 设快照单(列表内单);
  }, [列表内单]);
  const 单 = 列表内单 ?? 快照单;

  // 协调阶段的决策来自全局状态，跨屏可见（首页那张卡会跟着变）
  const 协调决策: '接受' | '退出' | null = 状态.决策[编号] ?? null;

  // 直接进 URL 但这一单从来不存在（或刷新后状态已丢）时的兜底
  if (!单) {
    return (
      <次级页外壳>
        <返回栏 返回={返回} 标题="这一单已归档" />
        <div className={样式.已归档区}>
          这一单已不在「在谈」列表里。
          <br />
          可能你选择了退出，AI代理已终止并归档，不再消耗你的匿名额度。
        </div>
      </次级页外壳>
    );
  }

  // 新委托单没有剧本小结：兜底渲染一个「进行中」的匿名初筛节点，
  // 小结就是代理替你主动打招呼的内容（标注意见 #8）
  const 委托兜底小结: 阶段小结[] = [
    {
      阶段: '匿名初筛',
      状态: '进行中',
      时间: '刚刚',
      小结: `已按你的授权主动接触对方代理：匿名画像高度对口（适配 ${单.适配分}），请求核对城市 / 年限 / 薪资带交集，数值互不披露。等待对方响应。`,
      链接: '查看 3 条完整往来 ›',
    },
  ];
  const 已完成阶段: 阶段小结[] = 各单阶段小结[编号] ?? 委托兜底小结;
  const 当前阶段序 = 阶段顺序.indexOf(单.阶段);

  // 确认意向后 reducer 会把 需要你 置 false，用它判断意向节点是「等你点头」还是「已确认」
  const 意向已确认 = 单.阶段 === '意向确认' && !单.需要你;

  // 协调节点在两种情况下要渲染：① 还卡着等你定；② 已经定了（要显示回执，不能凭空消失）
  const 显示协调节点 = (单.阶段 === '需要协调' && 单.需要你) || 协调决策 !== null;


  // 决策落地：先把卡点上下文冻结成快照，再写全局状态（首页那张卡同步变），最后升起
  // 「要我记住这个判断吗」弹层。顺序不能颠倒 —— reducer 的「接受方案」会清掉 分歧、
  // 改写 下一步，派发之后再算文案就只剩空壳（会出现「这一项差 以内的」这种残句）。
  const 做协调决策 = (类型: '接受' | '退出') => {
    设决策快照({ 分歧: 单.分歧, ...算决策文案(单, 类型) });
    派发(类型 === '接受' ? { 型: '接受方案', 编号 } : { 型: '退出谈判', 编号 });
    设弹层可见(true);
  };

  // 小结里的链接：带「往来」的进往来记录，其余（查看岗位与公司详情）就地切到职位详情 Tab
  const 打开小结链接 = (链接: string) => {
    if (链接.includes('往来')) 跳转(路径.往来记录(编号));
    else 设当前Tab('职位详情');
  };

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        标题={单.阶段 === '意向确认' ? 单.职位 : `${单.职位} · ${单.公司}`}
        副标题={`${单.公司} · ${单.标签.slice(0, 2).join(' · ')}`}
        右侧={
          单.阶段 === '意向确认' ? (
            <span className={`${样式.顶部薪资} 薪资体`}>{单.薪资}</span>
          ) : (
            <span className={样式.适配组}>
              <span className={样式.适配标}>适配</span>
              <span
                className={`${样式.适配分} ${单.适配分 < 80 ? 样式.适配分警示 : ''} 等宽数字`}
              >
                {单.适配分}
              </span>
            </span>
          )
        }
      />

      {/* 两个 Tab：本地状态切换，不走路由（同一屏的两种视图，返回键不该退到上一个 Tab）*/}
      <div className={样式.Tab行}>
        {(['谈判进度', '职位详情'] as 页内Tab[]).map((名) => (
          <button
            key={名}
            className={`${样式.Tab} ${当前Tab === 名 ? 样式.Tab选中 : 样式.Tab未选} 可点`}
            onClick={() => 设当前Tab(名)}
          >
            {名}
          </button>
        ))}
      </div>

      {当前Tab === '谈判进度' ? (
        <滚动区>
          {/* 全部对话的唯一入口（标注 16:15，与企业端同款） */}
          <button
            className={`${样式.对话入口} 可点`}
            onClick={() => 跳转(路径.往来记录(编号))}
          >
            <span className={样式.对话入口标}>双方代理对话</span>
            <span className={样式.核对尖}>›</span>
          </button>

          <div className={样式.时间线}>
            {/* 在线简历 · 可折叠（标注意见 2026-08-18 23:51）：
                时间线最上方常驻用户的在线简历（脱敏版）—— 从匿名初筛起对方核对的
                就是它，所以每一单（含新委托的 M- 单）都显示，回看任何一单都从它开始。
                标题只有「在线简历」四个字，不加任何解释文案（用户硬规则）*/}
            <div className={样式.简历卡}>
              <button
                className={`${样式.简历卡头} 可点`}
                onClick={() => 设简历卡展开(!简历卡展开)}
                aria-expanded={简历卡展开}
              >
                <简历图标 尺寸={17} />
                <span className={样式.简历卡标题}>在线简历</span>
                <span
                  className={`${样式.简历卡箭头} ${简历卡展开 ? 样式.简历卡箭头开 : ''}`}
                  aria-hidden
                >
                  ›
                </span>
              </button>
              {简历卡展开 ? (
                <div className={样式.简历卡纸}>
                  {/* 对外统一用用户自己的匿名昵称，每一单核对的都是同一份脱敏简历 */}
                  <简历纸身 代号="陈屿" />
                </div>
              ) : null}
            </div>

            {/* 已完成 / 进行中的阶段：小结由代理生成，附件与完整往来入口挂在小结里 */}
            {已完成阶段.map((段) =>
              !展开阶段.has(段.阶段) ? (
                // 收起态：一行带走（标注 09:36 列太长）。点行展开看小结与核对
                <阶段节点
                  key={段.阶段}
                  标题={段.阶段}
                  状态={段.状态}
                  时间={段.时间}
                  已通过={段.状态 === '通过' || 段.状态 === '达成'}
                >
                  <button
                    className={`${样式.折行} 可点`}
                    onClick={() => 设展开阶段((旧) => new Set(旧).add(段.阶段))}
                  >
                    <span className={`${样式.折行摘要} 单行`}>{段.小结}</span>
                    <span className={样式.折行开}>⌄</span>
                  </button>
                </阶段节点>
              ) : (
              <阶段节点
                key={段.阶段}
                标题={段.阶段}
                状态={段.状态}
                时间={段.时间}
                已通过={段.状态 === '通过' || 段.状态 === '达成'}
                点头部={() =>
                  设展开阶段((旧) => {
                    const 新 = new Set(旧);
                    新.delete(段.阶段);
                    return 新;
                  })
                }
              >
                <小结托盘>
                  <div className={样式.小结正文}>{段.小结}</div>

                  {/* 结构化核对清单（标注 18:05）：逐项一行，不再挤成一句 */}
                  {段.核对清单 ? (
                    <div className={样式.核对列}>
                      {/* 每一项核对都来自两个代理的一段对话 —— 整行可点进完整对聊
                          （标注 16:14，与企业端候选详情同款） */}
                      {段.核对清单.map((条) => (
                        <button
                          key={条.项}
                          className={`${样式.核对行} 可点`}
                          onClick={() => 跳转(路径.往来记录(编号))}
                        >
                          <span
                            className={`${样式.核对记} ${
                              条.结果 === '通过' ? 样式.核对记过 : 样式.核对记中
                            }`}
                          >
                            {条.结果 === '通过' ? '✓' : '·'}
                          </span>
                          <span className={样式.核对项}>{条.项}</span>
                          {条.结果 === '核对中' ? (
                            <span className={样式.核对中字}>核对中</span>
                          ) : null}
                          <span className={样式.核对尖}>›</span>
                        </button>
                      ))}
                    </div>
                  ) : null}

                  {段.附件 ? (
                    <div className={样式.附件}>
                      {/* 标注意见 2026-08-18 23:51：点附件打开简历原件弹层（PDF 观感）——
                          自己看自己的文件，真名与联系方式不打码 */}
                      <button
                        className={`${样式.附件主体} 可点`}
                        onClick={() => 设看原件({ 文件名: 状态.简历文件名 || 段.附件!.文件名 })}
                      >
                        <span className={样式.PDF块}>
                          <span className={样式.PDF字}>PDF</span>
                        </span>
                        <span className={样式.附件文本}>
                          <span className={`${样式.附件名} 单行`}>{状态.简历文件名 || 段.附件.文件名}</span>
                          <span className={`${样式.附件说明} 单行`}>{段.附件.说明}</span>
                        </span>
                        <span className={样式.附件看}>查看 ›</span>
                      </button>
                    </div>
                  ) : null}

                  {段.链接 && !段.链接.includes('往来') ? (
                    <button
                      className={`${样式.小链接} ${样式.链接间距} 可点`}
                      onClick={() => 打开小结链接(段.链接 as string)}
                    >
                      {段.链接}
                    </button>
                  ) : null}
                </小结托盘>
              </阶段节点>
              )
            )}

            {/* 当前阶段 ①：需要协调卡住 → 数字对比 + 双按钮决策（A6a 卡点态）。
                分歧优先取当前值，接受后 reducer 会清空它，就退回决策前的快照，
                这样回执上方仍然摊着「52K / 差 2K / 50K」，不会突然少一块。 */}
            {显示协调节点 ? (
              <div ref={当前节点引用}>
              <协调决策节点
                单={单}
                分歧={单.分歧 ?? 决策快照?.分歧 ?? 状态.决策快照[编号] ?? null}
                决策={协调决策}
                接受={() => 做协调决策('接受')}
                退出={() => 做协调决策('退出')}
                看往来={() => 跳转(路径.往来记录(编号))}
              />
              </div>
            ) : null}

            {/* 当前阶段 ②：条件已一致 → 确认意向转真人（A6·C 顺利态）*/}
            {单.阶段 === '意向确认' ? (
              <div ref={单.需要你 ? 当前节点引用 : undefined}>
              <意向确认节点
                已确认={意向已确认}
                确认={() => {
                  // 与企业端同构（标注 18:44）：确认即直达私聊
                  派发({ 型: '确认意向', 编号 });
                  跳转(路径.真人会话);
                }}
                去私聊={() => 跳转(路径.真人会话)}
              />
              </div>
            ) : null}

            {/* 未到达的阶段：灰掉，只说下一步由谁推进 */}
            {阶段顺序.slice(当前阶段序 + 1).map((名) => (
              <div key={名} className={`${样式.节点行} ${样式.灰节点}`}>
                <div className={样式.节点轴}>
                  <span className={样式.空心点} />
                </div>
                <div className={样式.节点主体}>
                  <div className={样式.节点标题}>{名}</div>
                  <div className={样式.节点待办}>
                    {名 === '意向确认'
                      ? '双方确认即转真人，直接进入私聊'
                      : '前一阶段通过后 AI 代理自动推进'}
                  </div>
                </div>
              </div>
            ))}
          </div>
        </滚动区>
      ) : (
        <职位详情Tab 单={单} />
      )}

      <代理输入条 占位="对这单有想法？告诉你的AI代理…" 按下={() => 跳转(路径.问AI代理)} />

      {/* 拿不准 → 记成规则（A24）：只在协调决策后升起；意向确认没有可沉淀的分歧项 */}
      <拿不准弹层
        可见={弹层可见}
        关闭={() => 设弹层可见(false)}
        决策类型={协调决策}
        决定文案={决策快照?.决定文案}
        规则草案={决策快照?.规则草案}
        记成规则={(内容: string) => {
          派发({
            型: '新增规则',
            内容: 内容 || 决策快照?.规则草案 || 单.下一步,
            来源: `来自${单.公司}单的决策 · ${单.轮次}`,
          });
          设弹层可见(false);
          跳转(路径.规则库);
        }}
      />

      {/* 简历原件弹层：只有文件名 + 简历数据本身，没有任何说明文字（用户硬规则）*/}
      {看原件 ? (
        <简历原件层 文件名={看原件.文件名} 关闭={() => 设看原件(null)} />
      ) : null}
    </次级页外壳>
  );
}

// ── 时间线节点外壳：左侧圆点 + 竖连线，右侧标题 / 状态胶囊 / 时间 + 内容 ──────
function 阶段节点({
  标题,
  状态,
  时间,
  已通过,
  强调 = false,
  无连线 = false,
  点头部,
  children,
}: {
  /** 同时是阶段名：轴点、标题、胶囊的颜色都由它决定 */
  标题: 阶段;
  状态?: string;
  时间?: string;
  已通过: boolean;
  /** 强调 = 这一步在等你。只加脉冲，不再另换一套红色 */
  强调?: boolean;
  /** 时间线最后一个节点不画连线 */
  无连线?: boolean;
  /** 传了 = 头部可点（展开态点头部收起，标注 10:22）*/
  点头部?: () => void;
  children: ReactNode;
}) {
  // 标注意见 2026-08-18：时间线按 onboarding 最后一页（A4 披露说明）的阶段配色来。
  // 全站四阶段共用 阶段配色 这一张表，这里不另起颜色。
  const 配色 = 阶段配色[标题];

  return (
    <div className={样式.节点行}>
      <div className={样式.节点轴}>
        {已通过 ? (
          <span
            className={样式.实心点}
            style={{ background: 配色.文字, boxShadow: `0 0 0 3px ${配色.底}` }}
          >
            <对勾图标 尺寸={8} 线宽={3.6} />
          </span>
        ) : (
          <span
            className={`${样式.环点} ${强调 ? '脉冲点' : ''}`}
            style={{
              borderColor: 配色.文字,
              borderWidth: 强调 ? 4.5 : 3.5,
              boxShadow: 强调 ? `0 0 0 4px ${配色.底}` : `0 0 0 3px ${配色.底}`,
            }}
          />
        )}
        {无连线 ? null : (
          <span
            className={样式.连线}
            style={已通过 ? { background: 配色.底 } : undefined}
          />
        )}
      </div>

      <div className={`${样式.节点主体} ${样式.节点主体带底距}`}>
        <div
          className={`${样式.节点头} ${点头部 ? '可点' : ''}`}
          onClick={点头部}
          role={点头部 ? 'button' : undefined}
        >
          <span className={样式.节点标题} style={{ color: 配色.文字 }}>
            {标题}
          </span>
          {状态 ? (
            <span
              className={样式.状态胶囊}
              style={{ background: 配色.底, color: 配色.文字 }}
            >
              {状态}
            </span>
          ) : null}
          {时间 ? <span className={`${样式.节点时间} 等宽数字`}>{时间}</span> : null}
          {点头部 ? <span className={样式.收起符}>⌃</span> : null}
        </div>
        {children}
      </div>
    </div>
  );
}

