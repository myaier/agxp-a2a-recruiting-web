/** 点决策那一刻冻结下来的卡点上下文（见 做协调决策 的注释） */
interface 决策快照内容 {
  分歧: 分歧 | null;
  决定文案: string;
  规则草案: string;
}

// ── 弹层文案：必须带这一单的真实上下文（公司 + 卡点项 + 差值），不能用写死的示例句 ──
function 算决策文案(单: 在谈单, 类型: '接受' | '退出'): { 决定文案: string; 规则草案: string } {
  // 卡点项名从「卡在作息，AI代理建议…」这类下一步文案里抠出来（作息 / 办公方式…）。
  // 需要协调只谈软性要求，薪资与到岗不在这里（产品边界 2026-08-18）
  const 卡点项名 = /卡在(.{1,6}?)[，,]/.exec(单.下一步)?.[1] ?? '这一项';
  // '差 2K' → '2K'，只留净差值，方便拼进规则草案
  const 差值净 = 单.分歧 ? 单.分歧.差值.replace(/^差\s*/, '') : null;
  // 差值末尾是英文单位（2K）时后面补一个空格，中文单位（15 天）时不补 —— 中英混排间距
  const 差值短语 = 差值净 ? (/[a-zA-Z]$/.test(差值净) ? `${差值净} ` : 差值净) : '';
  // 决定文案里差值后面直接跟逗号，用不带尾空格的净差值；规则草案后面跟「的 / 以内」，用带空格的
  const 卡点描述 = 差值净 ? `「${卡点项名}」上差 ${差值净}` : `「${卡点项名}」这一项`;

  return 类型 === '退出'
    ? {
        决定文案: `${单.公司}${卡点描述}，你选择了不让 —— AI代理已终止这一单，不再消耗你的匿名额度。`,
        规则草案: 差值净
          ? `${卡点项名}差超过 ${差值短语}的岗位，直接过滤，不用先问我`
          : `触到${卡点项名}这条线的岗位，直接过滤，不用先问我`,
      }
    : {
        决定文案: `${单.公司}${卡点描述}，你同意放宽 —— AI代理会立刻回报对方，把这一单推进到意向确认。`,
        规则草案: 差值净
          ? `${卡点项名}差 ${差值短语}以内的，可以直接替我放宽`
          : `${卡点项名}这类分歧不大的，可以直接替我放宽`,
      };
}

export default function 在谈详情() {
  const { id: 编号 = '' } = useParams<{ id: string }>();
  const { 状态, 派发 } = use应用状态();
  const { 跳转, 返回 } = use导航();

  // 真人会话顶部「看职位」带 ?tab=job 进来，直接开在职位详情 Tab，不让用户再点一次。
  // 只在挂载时读一次（初始值形态）：读完就交给本地状态，用户随后手点 Tab 不会被地址栏拽回去。
  const [查询参数] = useSearchParams();
  const [当前Tab, 设当前Tab] = useState<页内Tab>(
    查询参数.get('tab') === 'job' ? '职位详情' : '代谈进度'
  );
  const [弹层可见, 设弹层可见] = useState(false);
  const [决策快照, 设决策快照] = useState<决策快照内容 | null>(null);
  // 退出是本屏唯一不可逆的动作，且与「接受」并排（小屏一滑就点错）——
  // 先过一道确认，与「删除岗位」「解除屏蔽」「关闭职位」同一套确认框（组件/确认层）
  const [待退出, 设待退出] = useState(false);
  // 点开的简历原件（null = 没开）：点阶段节点里的 PDF 附件行打开原件弹层
  const [看原件, 设看原件] = useState<{ 文件名: string } | null>(null);
  // 进入页面自动定位到当前需要行动的阶段段，不用手动划过整条流
  const 当前节点引用 = useRef<HTMLDivElement>(null);
  useEffect(() => {
    // 布局稳定后再滚（折叠卡/骨架挂载完），block:'start' 让决策区顶到视口上部
    const 定时 = window.setTimeout(() => {
      当前节点引用.current?.scrollIntoView({ block: 'start', behavior: 'smooth' });
    }, 120);
    return () => window.clearTimeout(定时);
  }, []);

  // 从一单切到另一单时（同路由只换参数，组件不重挂载），折叠卡收起、弹层关闭，
  // 否则上一单里的展开/弹层状态会残留到下一单
  useEffect(() => {
    设看原件(null);
  }, [编号]);

  // 「退出谈判」会把这一单从在谈列表里移除（归档），页面必须留一份快照，
  // 否则用户点完「不谈了 · 退出」整屏会瞬间跳成已归档提示，看不到决策回执。
  const 列表内单 = 状态.在谈列表.find((条) => 条.编号 === 编号);
  const [快照单, 设快照单] = useState<在谈单 | null>(列表内单 ?? null);
  useEffect(() => {
    if (列表内单) 设快照单(列表内单);
  }, [列表内单]);
  const 单 = 列表内单 ?? 快照单;

  // 协调阶段的决策来自全局状态，跨屏可见（首页那张卡会跟着变）
  const 协调决策: '接受' | '退出' | null = 状态.决策[编号] ?? null;

  // 直接进 URL 但这一单从来不存在（或刷新后状态已丢）时的兜底
  if (!单) {
    return (
      <次级页外壳>
        <返回栏 返回={返回} 标题="这一单已归档" />
        <div className={样式.已归档区}>
          这一单已不在「在谈」列表里。
          <br />
          可能你选择了退出，AI代理已终止并归档，不再消耗你的匿名额度。
        </div>
      </次级页外壳>
    );
  }

  // 新委托单没有剧本小结：兜底渲染一个「进行中」的匿名初筛节点，
  // 小结就是代理替你主动打招呼的内容（标注意见 #8）
  const 委托兜底小结: 阶段小结[] = [
    {
      阶段: '匿名初筛',
      状态: '进行中',
      时间: '刚刚',
      小结: `已按你的授权主动接触对方代理：匿名画像高度对口（适配 ${单.适配分}），请求核对城市 / 年限 / 薪资带交集，数值互不披露。等待对方响应。`,
      链接: '查看 3 条完整往来 ›',
    },
  ];
  const 已完成阶段: 阶段小结[] = 各单阶段小结[编号] ?? 委托兜底小结;
  const 当前阶段序 = 阶段顺序.indexOf(单.阶段);

  // 确认意向后 reducer 会把 需要你 置 false，用它判断意向节点是「等你点头」还是「已确认」
  const 意向已确认 = 单.阶段 === '意向确认' && !单.需要你;

  // 协调节点在两种情况下要渲染：① 还卡着等你定；② 已经定了（要显示回执，不能凭空消失）
  // 叮嘱草稿：就地输入，发出后落全局 叮嘱表（按单编号归档）
  const [叮嘱草稿, 设叮嘱草稿] = useState('');
  const 本单叮嘱 = 状态.叮嘱表[编号] ?? [];
  const 发叮嘱 = () => {
    const 内容 = 叮嘱草稿.trim();
    if (内容 === '') return;
    // 带上写下这句话时所处的阶段：之后推进到下一阶段，这条话仍留在原来那一段流里
    派发({ 型: '加叮嘱', 归属: 编号, 文本: 内容, 序号: 本单叮嘱.length + 1, 写于阶段: 单.阶段 });
    设叮嘱草稿('');
  };

  const 显示协调节点 = (单.阶段 === '需要协调' && 单.需要你) || 协调决策 !== null;

  // 决策落地：先把卡点上下文冻结成快照，再写全局状态（首页那张卡同步变），最后升起
  // 「要我记住这个判断吗」弹层。顺序不能颠倒 —— reducer 的「接受方案」会清掉 分歧、
  // 改写 下一步，派发之后再算文案就只剩空壳（会出现「这一项差 以内的」这种残句）。
  const 做协调决策 = (类型: '接受' | '退出') => {
    设决策快照({ 分歧: 单.分歧, ...算决策文案(单, 类型) });
    派发(类型 === '接受' ? { 型: '接受方案', 编号 } : { 型: '退出谈判', 编号 });
    设弹层可见(true);
  };

  // ── 谈判进度：把四个阶段摊成一条对话流的分段数据 ──────────────────────────
  // 小结（结论 + 核对清单 + 附件）与对话是两份数据源：老单只有小结，
  // 有剧本的单（J-01 / J-02 / J-21）两份都有 —— 缺哪一份都要能渲染，不能空白。
  const 小结表 = new Map<阶段, 阶段小结>(已完成阶段.map((段) => [段.阶段, 段]));
  // 剧本单读自己的对话；委托进来的 M- 单没有剧本，用它自己的字段拼一段兜底往来 ——
  // 每张卡点开都要看得见双方代理在交互（用户 2026-08-20）
  const 本单对话 = 各单阶段对话[编号] ?? 委托单兜底对话(单);

  const 分段们: 分段项[] = 阶段顺序.map((名, 序) => {
    const 段小结 = 小结表.get(名);
    const 对话 = 本单对话[名];
    const 态: 分段项['态'] =
      序 < 当前阶段序 ? '已完成' : 序 === 当前阶段序 ? '当前' : '未到达';

    // 状态胶囊：协调阶段拍过板就说结果，其余走小结自带的状态
    const 状态文 =
      名 === '需要协调' && 协调决策
        ? 协调决策 === '接受'
          ? '已放宽'
          : '已退出'
        : 名 === '需要协调' && 态 === '当前'
          ? '需要你'
          : 名 === '意向确认' && 态 === '当前'
            ? 意向已确认
              ? '已确认'
              : '需要你'
            : (段小结?.状态 ?? (态 === '已完成' ? '通过' : '进行中'));

    return {
      阶段: 名,
      态,
      状态文: 态 === '未到达' ? null : 状态文,
      // 当前阶段没有剧本小结时，退回卡片上的下一步文案，段内不至于空着
      // 代理小结只属于「已经聊完、推进到下一阶段」的段（用户 2026-08-20）：
      // 进行中的阶段还没有结论，不摆小结块；卡住的阶段结论由决策卡自己带一行
      小结: 态 === '已完成' ? (段小结?.小结 ?? null) : null,
      核对清单: 态 === '已完成' ? 段小结?.核对清单 : undefined,
      附件: 段小结?.附件 ?? null,
      对话,
      // 进往来记录的那类链接在本次重构里去掉了（对话已经在流里），只留就地切 Tab 的
      小链接: 段小结?.链接 && !段小结.链接.includes('往来') ? 段小结.链接 : null,
      // 按「写下时所在的阶段」归段，不按当前阶段 —— 否则谈判一推进，旧话会整批跳到新段
      用户气泡: 本单叮嘱.filter((条) => 条.写于阶段 === 名),
      待推进说明:
        名 === '意向确认'
          ? '双方确认即转真人，直接进入私聊'
          : '前一阶段通过后 AI 代理自动推进',
      // 段内一条对话一句小结都没有时的兜底行：聊完的段说「已通过」，
      // 还在跑的段退回卡片上的下一步，不能拿「已通过」去描述进行中的阶段
      空说明: 态 === '已完成' ? '已通过 · AI代理自动推进' : 单.下一步,
      默认展开: 名 === '需要协调' && 协调决策 !== null ? true : undefined,
      尾部:
        名 === '需要协调' && 显示协调节点 ? (
          <协调决策卡
            单={单}
            分歧={单.分歧 ?? 决策快照?.分歧 ?? 状态.决策快照[编号] ?? null}
            决策={协调决策}
            接受={() => 做协调决策('接受')}
            退出={() => 设待退出(true)}
          />
        ) : 名 === '意向确认' && 单.阶段 === '意向确认' ? (
          <意向确认卡
            已确认={意向已确认}
            小结={意向小结(已完成阶段)}
            确认={() => {
              // 与企业端同构（标注 18:44）：确认即直达私聊
              派发({ 型: '确认意向', 编号 });
              跳转(路径.真人会话);
            }}
            去私聊={() => 跳转(路径.真人会话)}
          />
        ) : undefined,
    };
  });

  return (
    <次级页外壳 白底>
      <返回栏
        返回={返回}
        标题={单.阶段 === '意向确认' ? 单.职位 : `${单.职位} · ${单.公司}`}
        副标题={`${单.公司} · ${单.标签.slice(0, 2).join(' · ')}`}
        右侧={
          单.阶段 === '意向确认' ? (
            <span className={`${样式.顶部薪资} 薪资体`}>{单.薪资}</span>
          ) : (
            <span className={样式.适配组}>
              <span className={样式.适配标}>适配</span>
              <span
                className={`${样式.适配分} ${单.适配分 < 80 ? 样式.适配分警示 : ''} 等宽数字`}
              >
                {单.适配分}
              </span>
            </span>
          )
        }
      />

      {/* 两个 Tab：本地状态切换，不走路由（同一屏的两种视图，返回键不该退到上一个 Tab）*/}
      <div className={样式.Tab行}>
        {(['代谈进度', '职位详情'] as 页内Tab[]).map((名) => (
          <button
            key={名}
            className={`${样式.Tab} ${当前Tab === 名 ? 样式.Tab选中 : 样式.Tab未选} 可点`}
            onClick={() => 设当前Tab(名)}
          >
            {名}
          </button>
        ))}
      </div>

      {当前Tab === '代谈进度' ? (
        <滚动区>
          {/* 一条流：阶段分节条 → 该阶段双方代理对话 → 你的话 → 决策卡 */}
          <阶段对话流
            分段们={分段们}
            当前段引用={当前节点引用}
            点附件={(文件名) => 设看原件({ 文件名: 状态.简历文件名 || 文件名 })}
            点链接={() => 设当前Tab('职位详情')}
          />
        </滚动区>
      ) : (
        <职位详情Tab 单={单} />
      )}

      {/* 底部就地输入（2026-08-20 谈判页介入设计）：不跳页，写下的话直接接进
          当前阶段的对话流末尾（荧光绿右气泡），代理紧跟一条执行回执 */}
      <真输入条
        占位={
          单.阶段 === '需要协调' && 单.需要你
            ? '你的条件是什么？直接告诉代理'
            : '有想法就告诉你的AI代理'
        }
        值={叮嘱草稿}
        改变={设叮嘱草稿}
        发送={发叮嘱}
      />

      {/* 拿不准 → 记成规则（A24）：只在协调决策后升起；意向确认没有可沉淀的分歧项 */}
      <拿不准弹层
        可见={弹层可见}
        关闭={() => 设弹层可见(false)}
        决策类型={协调决策}
        决定文案={决策快照?.决定文案}
        规则草案={决策快照?.规则草案}
        记成规则={(内容: string) => {
          派发({
            型: '新增规则',
            内容: 内容 || 决策快照?.规则草案 || 单.下一步,
            来源: `来自${单.公司}单的决策 · ${单.轮次}`,
          });
          设弹层可见(false);
          跳转(路径.规则库);
        }}
      />

      {/* 简历原件弹层：只有文件名 + 简历数据本身，没有任何说明文字（用户硬规则）*/}
      {看原件 ? (
        <简历原件层 文件名={看原件.文件名} 关闭={() => 设看原件(null)} />
      ) : null}

      {/* 退出二次确认：确认后这一单立刻移出在谈列表，只能去「历史代谈」回看。
          标题里的主体名与本屏返回栏同序（职位 · 公司），确认的是不是这一单一眼能对上 */}
      {待退出 ? (
        <确认层
          标题={`退出「${单.职位} · ${单.公司}」？`}
          正文={归档口径}
          执行文="退出"
          取消={() => 设待退出(false)}
          执行={() => {
            设待退出(false);
            做协调决策('退出');
          }}
        />
      ) : null}
    </次级页外壳>
  );
}

