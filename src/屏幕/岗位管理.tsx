// D17 岗位管理 · 次级页
//
// 版式：返回栏「岗位管理」→ 提示不设 → 分组清单（「在 招」「已 归 档」两组，
// 分组标风格镜像 规则库.tsx 的字距标题）→ 虚线「＋ 发布新岗位」→ 尾注。
// 数据读全局状态的 岗位列表（不用本地 useState），点在招岗派发「切当前岗位」并返回 ——
// 这样人才页的在谈 / 推荐会真的跟着切过去，原型的跨屏联动才立得住。
//
// 薪资只显示岗位自己的带（如 50-65K）：不做谈薪，无报价 UI —— 双盲语义硬约束。

import 样式 from './岗位管理.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 轻提示 } from '../组件/轻提示';
import type { 在招岗位 } from '../数据/类型';

export default function 岗位管理() {
  const { 状态, 派发 } = use应用状态();
  const { 返回, 跳转 } = use导航();

  const 在招组 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');
  const 归档组 = 状态.岗位列表.filter((岗) => 岗.状态 === '已归档');

  // 点在招岗 = 把它设为当前寻访岗位，随后回上一屏（人才页跟着切）
  const 选中在招岗 = (编号: string) => {
    派发({ 型: '切当前岗位', 编号 });
    返回();
  };

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        标题="岗位管理"
        右侧={<span className={`${样式.在招数} 等宽数字`}>{在招组.length} 个在招</span>}
      />

      <滚动区>
        <div className={样式.列表}>
          {在招组.length > 0 ? (
            <>
              <div className={样式.分组标}>在 招 · 点 击 切 换 当 前 岗 位</div>
              <div className={样式.卡}>
                {在招组.map((岗, 序) => (
                  <岗位行
                    key={岗.编号}
                    岗={岗}
                    当前={岗.编号 === 状态.当前岗位编号}
                    末条={序 === 在招组.length - 1}
                    按下={() => 选中在招岗(岗.编号)}
                  />
                ))}
              </div>
            </>
          ) : null}

          {归档组.length > 0 ? (
            <>
              <div className={样式.分组标}>已 归 档</div>
              <div className={样式.卡}>
                {归档组.map((岗, 序) => (
                  <岗位行
                    key={岗.编号}
                    岗={岗}
                    末条={序 === 归档组.length - 1}
                    // 归档岗只留档不寻访：给轻提示兜底，不做死按钮
                    按下={() => 轻提示('该岗位已归档，重新开放待接后端')}
                  />
                ))}
              </div>
            </>
          ) : null}

          <button className={`${样式.发布新岗位} 可点`} onClick={() => 跳转(路径.发布岗位)}>
            <span className={样式.添加圆}>＋</span>
            <span className={样式.添加文字}>发布新岗位</span>
          </button>

          <div className={样式.尾注}>
            切换当前岗位后，人才页的在谈与推荐都跟着这个岗位走；归档岗位保留全部谈判档案。
          </div>
        </div>
      </滚动区>
    </次级页外壳>
  );
}

// ── 单个岗位行：左侧「名称（+ 当前徽）+ 薪资带 · 在谈数」，右侧状态徽标 ──
function 岗位行({
  岗,
  当前 = false,
  末条,
  按下,
}: {
  岗: 在招岗位;
  当前?: boolean;
  末条: boolean;
  按下: () => void;
}) {
  const 在招中 = 岗.状态 === '在招';
  return (
    <button className={`${样式.岗位行} ${末条 ? 样式.末条 : ''} 可点`} onClick={按下}>
      <span className={样式.岗位主体}>
        <span className={样式.名称行}>
          <span className={`${样式.岗位名称} ${在招中 ? '' : 样式.已归档名} 单行`}>
            {岗.名称}
          </span>
          {当前 ? <span className={样式.当前徽}>当前</span> : null}
        </span>
        <span className={`${样式.条件行} 等宽数字`}>
          {在招中 ? `${岗.薪资带} · 在谈 ${岗.在谈数} 人` : 岗.薪资带}
        </span>
      </span>
      <span className={`${样式.状态徽} ${在招中 ? '' : 样式.归档徽}`}>{岗.状态}</span>
    </button>
  );
}
