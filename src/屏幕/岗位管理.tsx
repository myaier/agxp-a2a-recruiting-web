// D17 岗位管理 · 次级页
//
// 版式：返回栏「岗位管理」→ 提示不设 → 分组清单（「在招」「已归档」两组，
// 分组标风格镜像 规则库.tsx 的字距标题）→ 虚线「＋ 发布新岗位」（标注 15:03：尾注删）。
// 数据读全局状态的 岗位列表（不用本地 useState），点在招岗派发「切当前岗位」并返回 ——
// 这样人才页的在谈 / 推荐会真的跟着切过去，原型的跨屏联动才立得住。
//
// 薪资只显示岗位自己的带（如 50-65K）：不做谈薪，无报价 UI —— 双盲语义硬约束。

import { useEffect, useState } from 'react';
import 样式 from './岗位管理.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import 滑动行, { type 滑动操作 } from '../组件/滑动行';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import type { 在招岗位 } from '../数据/类型';
import 弹层框架 from '../组件/弹层框架';

export default function 岗位管理() {
  const { 状态, 派发 } = use应用状态();
  const { 返回, 跳转 } = use导航();
  // 同一时刻只允许一行滑开，存的是那一行的岗位编号
  const [滑开的, 设滑开的] = useState<string | null>(null);
  // 待确认的危险操作（删除）
  const [待删, 设待删] = useState<在招岗位 | null>(null);
  // 待确认的停止招聘。停止本身可逆，但岗位下还有在谈候选时要先说清后果：
  // 那几位候选会收到代理的终止通知，这一步对他们是不可逆的
  const [待停, 设待停] = useState<在招岗位 | null>(null);
  const [提示, 设提示] = useState<string | null>(null);

  useEffect(() => {
    if (!提示) return;
    const 定时 = window.setTimeout(() => 设提示(null), 1800);
    return () => window.clearTimeout(定时);
  }, [提示]);

  const 在招组 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');
  const 归档组 = 状态.岗位列表.filter((岗) => 岗.状态 === '已归档');

  /** 某个岗位下还在谈的候选人数 */
  const 数在谈 = (编号: string) =>
    状态.企业候选列表.filter((候) => 候.岗位编号 === 编号).length;

  const 执行停止 = (岗: 在招岗位) => {
    派发({ 型: '停止招聘', 编号: 岗.编号 });
    设提示(`「${岗.名称}」已停止招聘并归档`);
  };

  /** 一个岗位左滑后能做什么。删除只对「无在谈候选」的岗位开放 ——
   *  有人在谈就删岗，等于把对方晾在半路，谈判档案也一起没了 */
  const 取操作 = (岗: 在招岗位): 滑动操作[] => {
    const 在谈人数 = 数在谈(岗.编号);
    // 编辑对两种状态都开放：归档岗位改完条件再重新开放，是很自然的一条路
    const 编辑操作: 滑动操作 = {
      文字: '编辑',
      按下: () => 跳转(路径.编辑岗位(岗.编号)),
    };
    if (岗.状态 === '在招') {
      const 项: 滑动操作[] = [
        编辑操作,
        {
          文字: '停止招聘',
          // 有人在谈就先弹确认，把「对方会收到终止通知」讲清楚再动手
          按下: () => (在谈人数 > 0 ? 设待停(岗) : 执行停止(岗)),
        },
      ];
      if (在谈人数 === 0) 项.push({ 文字: '删除', 危险: true, 按下: () => 设待删(岗) });
      return 项;
    }
    return [
      编辑操作,
      { 文字: '重新开放', 按下: () => { 派发({ 型: '重开岗位', 编号: 岗.编号 }); 设提示(`「${岗.名称}」已重新开放`); } },
      ...(在谈人数 === 0
        ? [{ 文字: '删除', 危险: true, 按下: () => 设待删(岗) } as 滑动操作]
        : []),
    ];
  };

  // 点岗位行 = 进这个岗位的详情页。
  // 「设为当前岗位」以前挂在这一下点击上，现在挪进详情页当一个显式动作 ——
  // 点开一个岗位想看的是它长什么样，而不是顺手把人才页切走。
  const 进岗位详情 = (编号: string) => 跳转(路径.岗位详情(编号));

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        标题="岗位管理"
        右侧={<span className={`${样式.在招数} 等宽数字`}>{在招组.length} 个在招</span>}
      />

      <滚动区>
        <div className={样式.列表}>
          {在招组.length > 0 ? (
            <>
              <div className={样式.分组标}>在招</div>
              <div className={样式.卡}>
                {在招组.map((岗, 序) => (
                  <滑动行
                    key={岗.编号}
                    操作={取操作(岗)}
                    打开={滑开的 === 岗.编号}
                    请求打开={(开) => 设滑开的(开 ? 岗.编号 : null)}
                    按下={() => 进岗位详情(岗.编号)}
                  >
                    <岗位行
                      岗={岗}
                      在谈人数={数在谈(岗.编号)}
                      当前={岗.编号 === 状态.当前岗位编号}
                      末条={序 === 在招组.length - 1}
                    />
                  </滑动行>
                ))}
              </div>
            </>
          ) : null}

          {归档组.length > 0 ? (
            <>
              <div className={样式.分组标}>已归档</div>
              <div className={样式.卡}>
                {归档组.map((岗, 序) => (
                  <滑动行
                    key={岗.编号}
                    操作={取操作(岗)}
                    打开={滑开的 === 岗.编号}
                    请求打开={(开) => 设滑开的(开 ? 岗.编号 : null)}
                    按下={() => 进岗位详情(岗.编号)}
                  >
                    <岗位行
                    岗={岗}
                    在谈人数={数在谈(岗.编号)}
                    末条={序 === 归档组.length - 1}
                  />
                  </滑动行>
                ))}
              </div>
            </>
          ) : null}

          <button className={`${样式.发布新岗位} 可点`} onClick={() => 跳转(路径.发布岗位)}>
            <span className={样式.添加圆}>＋</span>
            <span className={样式.添加文字}>发布新岗位</span>
          </button>

        </div>
      </滚动区>

      {/* 停止招聘二次确认：只在还有在谈候选时弹。停岗对我方可逆（随时重开），
          但对那几位候选是一次真实的终止通知，必须让用户知道自己在做什么 */}
      {待停 ? (
        <弹层框架 标签={`停止招聘${待停.名称}`} 遮罩类名={样式.遮罩} 面板类名={样式.确认框} 关闭={() => 设待停(null)}>
            <div className={样式.确认标题}>停止招聘「{待停.名称}」？</div>
            <div className={样式.确认正文}>
              这个岗位还有 {数在谈(待停.编号)} 位在谈候选，他们会收到代理的礼貌终止通知，
              不会被晾在半路。接洽记录全部保留，随时可以重新开放。
            </div>
            <div className={样式.确认键行}>
              <button className={`${样式.确认取消} 可点`} onClick={() => 设待停(null)}>
                取消
              </button>
              <button
                className={`${样式.确认执行绿} 可点`}
                onClick={() => {
                  执行停止(待停);
                  设待停(null);
                }}
              >
                停止招聘
              </button>
            </div>
        </弹层框架>
      ) : null}

      {/* 删除二次确认：删除不可逆，必须显式点掉 */}
      {待删 ? (
        <弹层框架 标签={`删除岗位${待删.名称}`} 遮罩类名={样式.遮罩} 面板类名={样式.确认框} 关闭={() => 设待删(null)}>
            <div className={样式.确认标题}>删除「{待删.名称}」？</div>
            <div className={样式.确认正文}>
              删除后这个岗位和它的全部记录都不再保留，且不可撤销。
              如果只是暂时不招，用「停止招聘」归档更合适 —— 档案留着，随时能重新开放。
            </div>
            <div className={样式.确认键行}>
              <button className={`${样式.确认取消} 可点`} onClick={() => 设待删(null)}>
                取消
              </button>
              <button
                className={`${样式.确认执行} 可点`}
                onClick={() => {
                  派发({ 型: '删除岗位', 编号: 待删.编号 });
                  设提示(`「${待删.名称}」已删除`);
                  设待删(null);
                }}
              >
                删除
              </button>
            </div>
        </弹层框架>
      ) : null}

      {提示 ? <div className={样式.浮层提示}>{提示}</div> : null}
    </次级页外壳>
  );
}

// ── 单个岗位行：左侧「名称（+ 当前徽）+ 薪资带 · 在谈人数」，右侧状态徽标 ──
function 岗位行({
  岗,
  在谈人数,
  当前 = false,
  末条,
}: {
  岗: 在招岗位;
  /** 由外层用 数在谈() 实时算好传进来 —— 与删除守卫、停止招聘确认框同一个数。
      原来这里读的是静态字段 岗.在谈数：行上写「在谈 4 人」、点停止招聘弹「还有 2 位在谈候选」，
      同一屏两个数字打架；刚发布的岗位更糟，顶着一个硬编码的假 2（拦路 11）。
      静态字段 在招岗位.在谈数 至此没有任何屏再读它 */
  在谈人数: number;
  当前?: boolean;
  末条: boolean;
}) {
  const 在招中 = 岗.状态 === '在招';
  // 点击交给外层 滑动行 统一处理（打开态下点击应收起而不是进下一屏）
  return (
    <div className={`${样式.岗位行} ${末条 ? 样式.末条 : ''} 可点`}>
      <span className={样式.岗位主体}>
        <span className={样式.名称行}>
          <span className={`${样式.岗位名称} ${在招中 ? '' : 样式.已归档名} 单行`}>
            {岗.名称}
          </span>
          {当前 ? <span className={样式.当前徽}>当前</span> : null}
        </span>
        <span className={`${样式.条件行} 等宽数字`}>
          {在招中 ? `${岗.薪资带} · 在谈 ${在谈人数} 人` : 岗.薪资带}
        </span>
      </span>
      <span className={`${样式.状态徽} ${在招中 ? '' : 样式.归档徽}`}>{岗.状态}</span>
    </div>
  );
}
