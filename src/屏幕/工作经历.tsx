// A2 添加工作经历 —— 引导流程里「让 AI 代理认识你」的第一步。
//
// 屏幕结构（对齐设计稿 A2）：
//   返回栏（右侧「保存」→ 引导问答）→ 页面大标题 → 绿色虚线上传条
//   → 滚动区：第 1 段解析结果逐项可改 → 在职时间 → 对这家公司隐藏我的信息
//   → 其余经历段（折叠行）→ 添加一段工作经历
//
// 两条产品语义决定了这屏的交互写法：
//   · 顶部文案写的是「以下为解析结果，可修改」—— 所以每一行都要真能改，
//     点一行就地变成输入框，而不是只做静态展示。
//   · 虚线框（而不是实线卡）是「这块还能一键导入、不是最终态」的视觉暗示，
//     所以 border-style 必须是 dashed，不能图省事换成实线。

import { useRef, useState } from 'react';
import type { ChangeEvent } from 'react';
import 样式 from './工作经历.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 表单条目, 滚动区, 开关 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 工作经历 as 工作经历数据 } from '../数据/模拟数据';

/** 第 1 段里可逐项修改的文本字段。键直接就是屏幕上的标签文字，省掉一层标签映射表 */
type 可改字段名 = '公司名称' | '所在行业' | '职位名称' | '工作内容';

/** 折叠展示的一段历史经历（第 2 段及以后）*/
type 折叠经历段 = { 摘要: string; 说明: string };

export default function 工作经历() {
  const { 跳转, 返回 } = use导航();
  const 第一段 = 工作经历数据.第一段;

  // 解析结果全部放本地 state：这屏语义是「简历解析出来的草稿」，
  // 用户改完点「保存」才算数，还没到进全局状态那一步。
  const [字段值, 设字段值] = useState<Record<可改字段名, string>>({
    公司名称: 第一段.公司名称,
    所在行业: 第一段.所在行业,
    职位名称: 第一段.职位名称,
    工作内容: 第一段.工作内容,
  });
  // 当前正在内联编辑的字段；null 表示所有行都是只读版式
  const [编辑中字段, 设编辑中字段] = useState<可改字段名 | null>(null);
  const [入职时间, 设入职时间] = useState(第一段.在职时间.起);
  const [离职时间, 设离职时间] = useState(第一段.在职时间.止);
  const [屏蔽现雇主, 设屏蔽现雇主] = useState(true);
  const [解析提示, 设解析提示] = useState(工作经历数据.解析文件);
  // 其余经历段：初始只有简历里解析出的第 2 段，点「添加一段工作经历」往后追加
  const [其余经历, 设其余经历] = useState<折叠经历段[]>([工作经历数据.第二段]);

  // 隐藏的原生文件选择框：上传条本身是自定义样式的按钮，
  // 点它再去 click() 这个 input，这样既保住设计稿版式又能真的选到文件。
  const 文件选择框 = useRef<HTMLInputElement>(null);

  /** 选中简历文件后，把提示文案换成新文件名，模拟「重新解析完成」 */
  function 选中简历文件(事件: ChangeEvent<HTMLInputElement>) {
    const 文件 = 事件.target.files?.[0];
    if (!文件) return;
    设解析提示(`${文件.name} ✓ 已解析 · 以下为解析结果，可修改`);
  }

  /** 改某个字段的值（内联输入框每敲一个字都会走这里）*/
  function 改字段(字段: 可改字段名, 新值: string) {
    设字段值((旧) => ({ ...旧, [字段]: 新值 }));
  }

  /** 追加一段待填写的经历。序号从 2 起算：第 1 段是当前在职那段 */
  function 添加一段经历() {
    设其余经历((旧) => [
      ...旧,
      { 摘要: `第 ${旧.length + 2} 段 · 待填写`, 说明: '点开填公司、职位与在职时间' },
    ]);
  }

  return (
    <次级页外壳>
      <返回栏
        返回={返回}
        右侧={
          <button className={`${样式.保存} 可点`} onClick={() => 跳转(路径.引导问答)}>
            保存
          </button>
        }
      />

      <页面大标题
        标题="工作经历"
        说明="可添加多段经历；也可以上传简历，自动解析填入在线简历。"
      />

      {/* 一键上传简历：绿色虚线框 + 深绿上传图标 */}
      <button className={`${样式.上传条} 可点`} onClick={() => 文件选择框.current?.click()}>
        <span className={样式.上传图标}>⬆</span>
        <span className={样式.上传文案}>
          <span className={样式.上传标题}>一键上传简历 · 自动填好下面每一项</span>
          <span className={`${样式.上传说明} 单行`}>{解析提示}</span>
        </span>
      </button>
      <input
        ref={文件选择框}
        type="file"
        accept=".pdf,.doc,.docx"
        className={样式.隐藏文件框}
        onChange={选中简历文件}
      />

      {/* 表单区是这屏唯一的滚动容器；左右 22 与大标题对齐，底部 40 留白给虚拟键盘 */}
      <滚动区 样式覆盖={{ padding: '0 22px 40px' }}>
        <div className={样式.分组标}>第 1 段 · 当前在职</div>

        {(['公司名称', '所在行业'] as const).map((字段) => (
          <可改条目
            key={字段}
            标签={字段}
            值={字段值[字段]}
            编辑中={编辑中字段 === 字段}
            开始编辑={() => 设编辑中字段(字段)}
            结束编辑={() => 设编辑中字段(null)}
            改变={(新值) => 改字段(字段, 新值)}
          />
        ))}

        {/* 在职时间：起止两个值都常驻输入框，因为它俩太短，
            再套一层「点了才能编辑」反而多一次点击。 */}
        <div className={样式.时间条目}>
          <div className={样式.条目标签}>在职时间</div>
          <div className={样式.时间行}>
            <input
              className={`${样式.时间输入} 等宽数字`}
              value={入职时间}
              aria-label="入职时间"
              onChange={(事件) => 设入职时间(事件.target.value)}
            />
            <span className={样式.时间连字}>—</span>
            <input
              className={`${样式.时间输入} 等宽数字`}
              value={离职时间}
              aria-label="离职时间"
              onChange={(事件) => 设离职时间(事件.target.value)}
            />
          </div>
        </div>

        {(['职位名称', '工作内容'] as const).map((字段) => (
          <可改条目
            key={字段}
            标签={字段}
            值={字段值[字段]}
            编辑中={编辑中字段 === 字段}
            开始编辑={() => 设编辑中字段(字段)}
            结束编辑={() => 设编辑中字段(null)}
            改变={(新值) => 改字段(字段, 新值)}
          />
        ))}

        {/* 对现雇主隐身：说明文案跟着开关走，
            公司名读的是上面可改的字段值，用户改了公司名这里同步跟着变。 */}
        <div className={样式.屏蔽条目}>
          <div className={样式.屏蔽头}>
            <span className={样式.屏蔽标题}>对这家公司隐藏我的信息</span>
            <开关 开={屏蔽现雇主} 切换={() => 设屏蔽现雇主((旧) => !旧)} />
          </div>
          <div className={样式.屏蔽说明}>
            {屏蔽现雇主
              ? `已自动屏蔽${字段值.公司名称}及关联公司 · 互不推荐`
              : '关闭后现雇主可能看到你的匿名档案'}
          </div>
        </div>

        {/* 其余经历段折叠成一行；点开去在线简历里编辑那一段 */}
        {其余经历.map((段, 序) => (
          <button
            key={`${段.摘要}-${序}`}
            className={`${样式.经历段行} 可点`}
            onClick={() => 跳转(路径.我的简历)}
          >
            <span className={样式.段文案}>
              <span className={`${样式.段摘要} 单行`}>{段.摘要}</span>
              <span className={`${样式.段说明} 单行`}>{段.说明}</span>
            </span>
            <span className={样式.尖括号}>›</span>
          </button>
        ))}

        <button className={`${样式.添加行} 可点`} onClick={添加一段经历}>
          <span className={样式.添加加号}>＋</span>
          <span className={样式.添加文字}>添加一段工作经历</span>
        </button>
      </滚动区>
    </次级页外壳>
  );
}

/** 一行可内联编辑的表单条目。
 *  只读态直接复用地基的 <表单条目>（保证和其它表单屏版式完全一致），
 *  点一下换成同版式的输入框：标签位置、字号、行高都对齐，切换时不跳动。 */
function 可改条目({
  标签,
  值,
  编辑中,
  开始编辑,
  结束编辑,
  改变,
}: {
  标签: string;
  值: string;
  编辑中: boolean;
  开始编辑: () => void;
  结束编辑: () => void;
  改变: (新值: string) => void;
}) {
  if (!编辑中) {
    return <表单条目 标签={标签} 值={值} 按下={开始编辑} />;
  }

  return (
    <div className={样式.编辑条目}>
      <div className={样式.条目标签}>{标签}</div>
      <input
        className={样式.条目输入}
        value={值}
        aria-label={标签}
        autoFocus
        onChange={(事件) => 改变(事件.target.value)}
        onBlur={结束编辑}
        onKeyDown={(事件) => {
          // 回车收起键盘并退出编辑态，和 iOS 表单的「完成」一致
          if (事件.key === 'Enter') 结束编辑();
        }}
      />
    </div>
  );
}
