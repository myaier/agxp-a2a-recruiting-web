// 职位正文展示契约（P1 Task 2，Task 3 职位页面契约将扩展本目录）。
//
// 两条准备函数（Mock / Backend P4）把各自来源收拢成同一份 职位正文数据，
// 职位正文展示 只按数据/能力渲染：无 Context、无运行模式、无路由、无请求、无匹配计算。
// 数据文本已全部格式化（含 §3.2 的未知占位文案），未知文案只用于展示、不写回任何模型。

import type { 公司区块资料 } from '../../组件/公司区块';
import type { 对齐行 } from '../../数据/匹配对齐';
import type { 基本信息, 简历教育段, 简历经历段 } from '../../数据/类型';

/**
 * 图位：已知字标（Mock 现有形态）、真实图片（Spec §6.1：显式 BFF 媒体 URL 填原节点，
 * 加载失败回中性占位、换 URL 清失败态 —— 复用 Task 3 的图位输入模式）或中性未知占位
 *（带可访问名，不拿派生首字充当真实图片）。兜底字/可访问名只服务失败回退，不是宣称的照片。
 */
export type 图位 =
  | { 种类: '字标'; 字: string }
  | { 种类: '图片'; URL: string; 兜底字: string; 可访问名: string }
  | { 种类: '未知'; 可访问名: string };

/**
 * 匹配度分析两态：
 *   核对 —— 有依据（Mock 分从行来 / Backend 推荐卡 basis 已确认），44px 分析环 + 核对行 + 分析段；
 *   说明 —— 无依据（Backend basis 未确认 / 详情直取无推荐批次），交代现状；分 null = 无推荐分，
 *   展示用本页 44×44 中性分数位（不绘制进度、不伪造 0）。
 */
export type 匹配展示 =
  | { 种类: '核对'; 分: number; 行们: 对齐行[]; 分析: { 墨句: string; 灰句: string } | null }
  | { 种类: '说明'; 分: number | null; 说明: string[] };

export interface 职位正文数据 {
  职位: string;
  薪资: string;
  匹配: 匹配展示;
  职位详情标题: string;
  /** Backend（P4）岗位硬事实行（「标签：值」）；Mock 恒空 */
  职位事实行: string[];
  /** JD 正文行（合法空正文已由准备函数换成未知占位文案） */
  职位详情行: string[];
  职位要求标题: string;
  职位要求行: string[];
  公司: { 名称: string; 图: 图位; 简介: string; 资料: 公司区块资料 };
  /** 发布人卡原位置始终渲染；缺失字段已由准备函数换成对应未知文案 */
  发布人: { 图: 图位; 姓名: string; 公司: string; 职务: string; 备注: string };
}

/** 匹配核对输入的简历侧事实：连接层从应用状态收拢，准备函数不读状态 */
export interface 职位核对简历 {
  经历: 简历经历段[];
  教育: 简历教育段[];
  技能: string[];
  开始工作年: 基本信息['开始工作年'];
}

export interface 职位正文展示属性 {
  数据: 职位正文数据;
  /** 公司槽落点由连接层给（organization ref / 原 Mock slug）；无 ref 则不传，渲染非交互块 */
  打开公司?: () => void;
  /** 直聊能力由连接层按现有规则给（Mock 且非嵌入隐藏）；不给则不渲染按钮 */
  直接聊?: () => void;
}

/**
 * 职位页面契约（P1 Task 3）：Mock 与 Backend(P4) 两条正常页共用的页面外壳属性。
 * 返回栏 / 正文 / 浮动条 / 更多菜单只有一份；错误 / 加载页与附件选择、确认、举报层
 * 仍由连接层挂载。动作与弹层事务全部归属连接层回调 —— 抽屉的收层 / toast / 返回
 * 顺序由 菜单按下/举报 承载，展示不改更多打开 来收层。
 */
export interface 职位页面展示属性 extends 职位正文展示属性 {
  返回: () => void;
  /** 「⋯」拉起的更多操作抽屉是否展开（受控：开关状态在连接层） */
  更多打开: boolean;
  改更多打开: (值: boolean) => void;
  /** 主键文案 / 已委托淡绿态 / 禁用（含无推荐坐标与写中）与按下 */
  主按钮: { 文案: string; 已委托样式: boolean; 禁用: boolean; 按下: () => void };
  /**
   * 不感兴趣：禁用（无推荐坐标 / 写中）、浮动圆钮按下；菜单可见=false 时抽屉里
   * 不出这一项（详情直取路径），菜单按下 独立承载原收层 / toast / 返回顺序
   */
  不感兴趣: { 禁用: boolean; 按下: () => void; 菜单可见: boolean; 菜单按下: () => void };
  /** 抽屉「举报这个职位」：收层 + 挂举报层都由连接层回调完成 */
  举报: () => void;
}