// 职位正文展示（P1 Task 2；匹配区 Task 5 模型化）—— Mock 与 Backend(P4) 共用的唯一正文 JSX。
//
// 原 职位详情.tsx 的 正文 JSX 原样迁移（2026-08-24 从本屏抽出、直聊会话「看职位」层
// 同铺一份的那个组件）：内容顺序 职位名+薪资 → 匹配度分析 → JD → 公司(加厚) → 发布人。
// 数据文本已由 准备职位正文 格式化（含 §3.2 未知文案），本组件只按 数据/能力 渲染：
// 无 Context、无运行模式、无路由、无请求、无匹配计算。匹配区只吃 C3 匹配分析模型
// （匹配分析块 渲染），旧「求职核对块」三态核对版式自 Task 5 起不再由本组件消费。
// 未知占位（.公司图位 / 发布人图位）只作用于缺失节点；完整状态沿用原声明值。

import { useEffect, useState, type ReactElement } from 'react';
import 样式 from '../职位详情.module.css';
import { 公司区块 } from '../../组件/公司区块';
import { 匹配分析块 } from '../../组件/匹配分析块';
import type { 图位, 职位正文展示属性 } from './类型';

/**
 * 公司图位：字标/真实图片沿用 公司区块 缺省标志（与原 Mock 渲染逐像素一致；真实 URL 走
 * 公司字标 的显式图片分支，失败回中性首字块）；未知给中性空白占位。
 */
function 公司标志(图: 图位): ReactElement | undefined {
  if (图.种类 !== '未知') return undefined;
  return <span className={样式.公司图位} role="img" aria-label={图.可访问名} />;
}

/** 公司头行 首字：字标给字；真实图片只作加载失败的回退字；未知不给（不充当真实图片） */
function 公司兜底字(图: 图位): string {
  if (图.种类 === '字标') return 图.字;
  return 图.种类 === '图片' ? 图.兜底字 : '';
}

export function 职位正文展示({ 数据, 打开公司, 直接聊 }: 职位正文展示属性): ReactElement {
  const { 发布人 } = 数据;
  // 发布人头像（Spec §6.1）：显式真实 URL 渲染进原头像槽，失败回既有中性未知图位
  //（与无图源同一形态，不拿姓名首字充当照片），换 URL 清失败状态 —— 与 看市场
  // 发布人头像的既有接线同一套图片事件实践
  const 发布人图片URL = 发布人.图.种类 === '图片' ? 发布人.图.URL : null;
  const [发布人图片失败, 设发布人图片失败] = useState(false);
  useEffect(() => {
    设发布人图片失败(false);
  }, [发布人图片URL]);
  const 显示发布人图片 = 发布人图片URL !== null && !发布人图片失败;
  const 发布人图位未知 = 发布人.图.种类 === '未知' || (发布人.图.种类 === '图片' && 发布人图片失败);
  return (
    <div className={样式.内容}>
      {/* 职位名 + 薪资：baseline 对齐，让 21px 的职位名和 16px 的薪资底线齐平。
          标签行(本科及以上/今天新发)已删(用户 2026-08-31「所有的都不要加这种标签」) */}
      <div>
        <div className={样式.标题行}>
          <div className={样式.职位名}>{数据.职位}</div>
          <div className={`${样式.薪资} 薪资体`}>{数据.薪资}</div>
        </div>
      </div>

      {/* 匹配度分析（Task 5 模型化，Spec §3.4）：C3 匹配分析块直接展开 —— 六维解释在
          本页唯一总分环（44px）之下；解释合法缺失给「暂无该次匹配的详细分析」+ 有限依据
          或上下文文案。旧「JD 学历/经验核对行」与独立「推荐依据」小区已随路径删除：
          学历不属于六维评分，已知原因并入 模型.有限依据。 */}
      <div className={样式.卡}>
        <匹配分析块 模型={数据.匹配} />
      </div>

      {/* JD：职位详情 + 职位要求两段合在一张卡里，中间用小标题分隔。
          Backend(P4)：标题与小标题是如实口径 —— 事实行混在 JD 正文里，标题说明「岗位信息」；
          职位要求只是补充说明、不自动解析进匹配卡 */}
      <div className={样式.卡}>
        <div className={样式.卡标题}>{数据.职位详情标题}</div>
        {[...数据.职位事实行, ...数据.职位详情行].map((行, index) => (
          <div key={`${index}:${行}`} className={样式.卡正文}>
            {行}
          </div>
        ))}
        <div className={样式.卡小标题}>{数据.职位要求标题}</div>
        {数据.职位要求行.map((行) => (
          <div key={行} className={样式.卡正文}>
            {行}
          </div>
        ))}
      </div>

      {/* 公司(加厚,2026-08-26 用户指定「所有页面都要改」)：共用 公司区块，介绍段 + 元信息表。
          资料/标志 显式传入（绝不漏传 资料 触发静态兜底）；按下 缺省渲染同 class 非交互块 */}
      <div className={样式.卡}>
        <公司区块
          名称={数据.公司.名称}
          首字={公司兜底字(数据.公司.图)}
          公司图片URL={数据.公司.图.种类 === '图片' ? 数据.公司.图.URL : undefined}
          一行简介={数据.公司.简介}
          资料={数据.公司.资料}
          标志={公司标志(数据.公司.图)}
          按下={打开公司}
        />
      </div>

      {/* 发布人：是企业招聘负责人还是猎头,决定了用户愿不愿意直接聊。
          2026-08-26 用户指定:挪到公司区块之下——先认识公司,再认识对接的人。
          卡位始终保留；图位/文字缺什么补什么未知占位（§3.2） */}
      <div className={`${样式.卡} ${样式.发布人卡}`}>
        <span
          className={发布人图位未知
            ? `${样式.发布人头像} ${样式.发布人图位}`
            : 样式.发布人头像}
          role={发布人图位未知 ? 'img' : undefined}
          aria-label={发布人图位未知 && '可访问名' in 发布人.图 ? 发布人.图.可访问名 : undefined}
        >
          {显示发布人图片 ? (
            <img
              src={发布人图片URL ?? undefined}
              alt=""
              onError={() => 设发布人图片失败(true)}
              style={{
                width: '100%', height: '100%', objectFit: 'cover',
                display: 'block', borderRadius: 'inherit',
              }}
            />
          ) : 发布人.图.种类 === '字标' ? 发布人.图.字 : null}
        </span>
        <div className={样式.发布人文字区}>
          <div className={样式.发布人名}>
            {发布人.姓名} · {发布人.公司}{' '}
            {发布人.职务 ? (
              <span className={样式.发布人职务}>{发布人.职务}</span>
            ) : null}
          </div>
          {发布人.备注 ? (
            <div className={样式.发布人备注}>{发布人.备注}</div>
          ) : null}
        </div>
        {/* 直接聊入口收进发布人卡:聊的对象就是这个人,按钮贴着人放。
            能力由连接层按现有规则给（直聊层里藏掉;Backend 无直聊坐标不给） */}
        {直接聊 ? (
          <button
            className={`${样式.发布人聊} 可点`}
            onClick={直接聊}
          >
            直接聊
          </button>
        ) : null}
      </div>

    </div>
  );
}