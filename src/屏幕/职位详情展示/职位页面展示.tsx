// 职位页面展示（P1 Task 3）—— Mock 与 Backend(P4) 两条正常页共用的唯一页面外壳 JSX。
//
// 原 职位详情.tsx 两份正常页的 返回栏（⋯ 入口）/ 浮动胶囊条 / 「⋯」更多操作抽屉
// 原样迁移到这里（标签 / class / 菜单结构逐字保留，避免 span→button 或嵌套 button），
// 正文复用 职位正文展示。本组件不渲染 次级页外壳 —— 附件选择 / 确认 / 举报层仍由
// 连接层挂在外壳内（遮罩与抽屉都以 次级页外壳 为定位基准）；错误 / 加载页也留在连接层。
// 无 Context、无运行模式、无路由、无请求、无业务派发：动作与弹层事务全部经回调归属连接层，
// 抽屉的收层 / toast / 返回顺序由 菜单按下/举报 承载，本组件不改更多打开 来收层。

import type { ReactElement } from 'react';
import 样式 from '../职位详情.module.css';
import { 返回栏, 滚动区 } from '../../组件/通用';
import { 谈判图标, 禁止图标 } from '../../组件/图标';
import 弹层框架 from '../../组件/弹层框架';
import { 职位正文展示 } from './职位正文展示';
import type { 职位页面展示属性 } from './类型';

export function 职位页面展示({
  数据,
  打开公司,
  直接聊,
  返回,
  更多打开,
  改更多打开,
  主按钮,
  不感兴趣,
  举报,
}: 职位页面展示属性): ReactElement {
  return (
    <>
      <返回栏
        返回={返回}
        右侧={
          // 正常页的更多入口恒可见（加载 / 失败页在连接层，本来就没有 ⋯）
          <div className={样式.工具组}>
            <button
              className={`${样式.工具符} 可点`}
              onClick={() => 改更多打开(true)}
              aria-label="更多操作"
            >
              ⋯
            </button>
          </div>
        }
      />

      <滚动区>
        <职位正文展示 数据={数据} 打开公司={打开公司} 直接聊={直接聊} />
      </滚动区>

      {/* 底部浮动胶囊条：悬浮在滚动内容之上，🚫（不感兴趣）+ 主键（让AI代理去谈 / 已接手状态标）。
          禁用 = 无推荐坐标 / 写中（连接层算好）；一切委托态都保持 disabled 主键形态（Spec §7.1） */}
      <div className={样式.浮动条}>
        <button
          className={`${样式.圆形次按钮}${不感兴趣.禁用 ? '' : ' 可点'}`}
          aria-label="不感兴趣"
          disabled={不感兴趣.禁用}
          onClick={不感兴趣.按下}
        >
          <禁止图标 尺寸={18} 色="var(--次要)" />
        </button>
        <button
          className={`${样式.主按钮} ${主按钮.已委托样式 ? 样式.已委托态 : 主按钮.禁用 ? '' : '可点'}`}
          disabled={主按钮.禁用}
          onClick={主按钮.按下}
        >
          <谈判图标 尺寸={15} 色={主按钮.已委托样式 ? 'var(--深绿)' : undefined} />
          <span className={样式.主按钮文字}>{主按钮.文案}</span>
        </button>
      </div>

      {/* 「⋯」更多操作抽屉：点遮罩或「取消」收层；不感兴趣项只在 菜单可见（有推荐坐标）时出现。
          两项动作的收层 / toast / 返回顺序都在连接层回调里，这里只负责调一次 */}
      {更多打开 ? (
        <弹层框架 标签="职位更多操作" 遮罩类名={样式.遮罩} 面板类名={样式.抽屉} 关闭={() => 改更多打开(false)}>
          {不感兴趣.菜单可见 ? (
            <button
              className={`${样式.抽屉项} 可点`}
              disabled={不感兴趣.禁用}
              onClick={不感兴趣.菜单按下}
            >
              不感兴趣，别再推给我
            </button>
          ) : null}
          <button
            className={`${样式.抽屉项} 可点`}
            onClick={举报}
          >
            举报这个职位
          </button>
          <button
            className={`${样式.抽屉项} ${样式.抽屉取消} 可点`}
            onClick={() => 改更多打开(false)}
          >
            取消
          </button>
        </弹层框架>
      ) : null}
    </>
  );
}