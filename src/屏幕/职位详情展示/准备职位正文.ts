// 不请求、不路由、不读 Context/运行状态。
//
// Task 5（Spec §3.4 / 冻结 C3）：匹配区唯一形态是 C3 匹配分析模型 ——
//   · Backend 推荐路径：分数/解释/有限依据全部来自同一张推荐卡（分数 = wire match_score，
//     解释 = 已展开批次解释，有限依据 = 本卡 match_reasons 的已知原因中文映射），
//     绝不从 JD/简历重新评分，也绝不借其他记录/批次；
//   · Backend 详情直取：无推荐分（null 不伪造 0）、无解释、无旧依据，上下文由连接层按
//     恢复状态给（'无推荐上下文' | '原推荐不可用' | 恢复中性的 '有来源'）；
//   · 旧「当前简历学历/经验核对行 + basis 说明行」路径已删除（学历不属于六维评分）；
//     简历侧输入随之移除，岗位对学历的公开要求仍在 JD 事实区展示。
//
// 缺失规则（Spec §3.2）只在 Backend（P4）路径落位：wire 没有的图源/元信息/发布人
// 用中性未知占位补齐原位置，JD 合法空正文给未知文案。Mock 路径是原 职位正文 的
// 数据准备收拢（含 公司区块 原静态档规则的必要投影）—— 匹配区在 Task 5 先落模型
// 过渡形态（分数取卡面种子分、解释合法缺失），Task 7 接 Mock 固定六维快照后替换。

