/** JD 正文行：trim 后为空视为缺失（§3.2）；全部缺失保留原标题并给未知占位 */
function 整理正文行(行们: string[], 未知文案: string): string[] {
  const 有效行们 = 行们.filter((行) => 行.trim() !== '');
  return 有效行们.length > 0 ? 有效行们 : [未知文案];
}

/**
 * Mock 公司卡显式资料：复制 公司区块 原静态档规则的必要投影（组件不改、函数不导出）。
 * 介绍段 = 档案未补全时 null（不把占位空话摆上台面）；元行 = 按内容认段、不足两段返回空，
 * 成立取 工商信息.成立日期 年份、地址取档案值，未补全两者都不出 —— 与原组件输出逐字一致。
 */
function Mock公司资料(名称: string, 一行简介: string): 公司区块资料 {
  const 档案 = 取公司档案(公司路由键(名称));
  const 档案未补全 = 档案.规模行 === '规模与融资信息待补充';
  // 规模行/一行简介按段识别,不按位置硬套:含「轮/上市」= 融资阶段,含「人」= 规模,
  // 其余 = 行业。在谈单的公司简介只有「融资 · 规模」两段,按内容认才不会整体降级
  const 简介段们 = (档案未补全 ? 一行简介 : 档案.规模行).split(' · ');
  const 认段 = (段: string) =>
    /轮|上市/.test(段) ? '融资阶段' : /人/.test(段) ? '规模' : '行业';
  const 成立年 = 档案.工商信息.find((条) => 条.项 === '成立日期')?.值.slice(0, 4);
  const 元行组: readonly [string, string][] = 简介段们.length >= 2
    ? ([
        ...简介段们.map((段) => [认段(段), 段] as [string, string]),
        成立年 && !档案未补全 ? (['成立', `${成立年} 年`] as [string, string]) : null,
        档案未补全 ? null : (['地址', 档案.地址] as [string, string]),
      ].filter(Boolean) as [string, string][])
    : [];
  return {
    介绍段: 档案未补全 ? null : 档案.简介[0] ?? null,
    元行组: 元行组.map(([标签, 值]) => ({ 标签, 值 })),
  };
}

/** Mock 原型路径：静态市场表 + 演示口径。匹配 = 模型过渡形态（Task 7 接固定快照） */
export function 准备Mock职位正文(岗: 市场职位): 职位正文数据 {
  const 详 = 取市场岗位详情(岗);
  return {
    职位: 岗.职位,
    薪资: 岗.薪资,
    匹配: {
      // 过渡形态：分数沿用卡面种子分（与列表环同源演示数据）；解释合法缺失，
      // 上下文给 '有来源'（不携带上下文缺失文案）—— Task 7 换成记录级固定快照
      分数: 岗.适配分,
      解释: null,
      有限依据: [],
      上下文: '有来源',
    },
    职位详情标题: '职位详情',
    职位事实行: [],
    职位详情行: 详.职位详情,
    职位要求标题: '职位要求',
    职位要求行: 详.职位要求,
    公司: {
      名称: 详.公司.名称,
      图: { 种类: '字标', 字: 详.公司.首字 },
      简介: 详.公司.简介,
      资料: Mock公司资料(详.公司.名称, 详.公司.简介),
    },
    // Mock 发布人字段来自详情表/卡面合成，职务/备注空值原样保留（既有渲染行为）
    发布人: {
      图: { 种类: '字标', 字: 详.发布人.首字 },
      姓名: 详.发布人.姓名,
      公司: 详.发布人.公司,
      职务: 详.发布人.职务,
      备注: 详.发布人.备注,
    },
  };
}

/**
 * Backend（P4）路径：只吃映射后的权威视图，绝不读 Mock 详情表与静态公司档。
 * 公开企业（Spec §6.1）是明确可选输入：独立职位详情在真实 organization_id 在场时补读
 * 公开组织 GET，把已提供的 company_intro/office_address/logo 补进公司原槽 —— 缺省 null
 * （Mock 分支 / 读取未回来）不受影响，未提供的成员保持未知，绝不补默认值。
 * 推荐上下文（C3）由连接层按四坐标恢复状态传入：有卡恒 '有来源'；无卡时
 * '无推荐上下文'（通用直达）/ '原推荐不可用'（穷尽未找到/批次不符）/
 * '有来源'（恢复中或临时失败——中性缺失，不冒充永久不可用）。
 */
export function 准备Backend职位正文(
  视图: P4候选岗位页面,
  公开企业: BFF公开企业 | null = null,
  推荐上下文: 匹配分析上下文 = '有来源',
): 职位正文数据 {
  // 岗位硬事实以「标签：值」文本行前置进既有 JD 卡正文槽：只渲染已投影的非空事实
  //（办公地点 blank → null 不出空标签，年薪月数 null 不出 X 薪，绝不补 12 薪默认）
  const 职位事实行 = [
    `城市：${视图.岗位事实.城市}`,
    `办公方式：${视图.岗位事实.办公方式}`,
    ...(视图.岗位事实.办公地点 === null ? [] : [`办公地点：${视图.岗位事实.办公地点}`]),
    ...(视图.岗位事实.年薪月数 === null ? [] : [`年薪月数：${视图.岗位事实.年薪月数} 薪`]),
    ...(视图.岗位事实.经验要求 === null ? [] : [`结构化经验要求：${视图.岗位事实.经验要求}`]),
    ...(视图.岗位事实.学历要求 === null ? [] : [`结构化学历要求：${视图.岗位事实.学历要求}`]),
  ];
  // ── 公司槽（Spec §6.1）：摘要先展示，公开读取成功后补已提供事实 ──
  // 元行沿用原五槽骨架（融资阶段/规模/行业/成立/地址）：摘要（organization 六键）已知的
  // 段立即成行，公开档案补仍缺失的段；两边都未提供的保持未知。成立日期本轮无源恒未知
  //（Spec §9 延后项）；地址只认公开档案 office_address（与岗位办公地点分开）。
  const 摘要元行 = 公司已知元行组(视图.公司.organization);
  const 档案元行 = 公开企业 === null ? [] : 公司已知元行组(公开企业.profile);
  const 元值 = (标签: string): string =>
    摘要元行.find((行) => 行.标签 === 标签)?.值
    ?? 档案元行.find((行) => 行.标签 === 标签)?.值
    ?? '未知';
  // 图位只认显式真实 URL：摘要 Logo 优先，公开档案 Logo 补摘要缺席的岗；空白 URL 按缺图
  const 公司图片URL = 视图.卡.公司图片URL
    ?? (公开企业 === null ? null : 公开企业.profile.logo?.url ?? null);
  const 介绍段 = 公开企业 === null ? '' : 公开企业.profile.company_intro.trim();
  const 地址 = 公开企业 === null ? '' : 公开企业.profile.office_address.trim();
  // 发布人头像同接显式真实 URL；发布人缺席 / 无头像仍是中性图位，不拿姓名首字充当照片
  const 发布人图片URL = 视图.卡.发布人图片URL ?? null;

  // 匹配模型（Spec §3.4）：只认同一张推荐卡的 wire 事实 —— 分数 = match_score，
  // 解释 = 已展开批次解释（缺席/显式 null 都按缺失显示），有限依据 = 本卡已知原因
  // （新解释在场时组件不渲染它）。无推荐批次（详情直取）恒 null/null/[]，不伪造 0 分。
  const 匹配: 匹配展示 = 视图.recommendationId !== null
    ? {
      分数: 视图.卡.适配分,
      解释: 视图.匹配解释 ?? null,
      有限依据: 映射推荐依据(视图.卡.对得上 ?? []),
      上下文: 推荐上下文,
    }
    : { 分数: null, 解释: null, 有限依据: [], 上下文: 推荐上下文 };

  return {
    职位: 视图.卡.职位,
    薪资: 视图.卡.薪资,
    匹配,
    职位详情标题: '岗位信息与职位详情',
    职位事实行,
    职位详情行: 整理正文行(视图.职位详情, '职位详情未知'),
    职位要求标题: '职位要求（补充说明，不自动解析）',
    职位要求行: 整理正文行(视图.职位要求, '职位要求未知'),
    公司: {
      名称: 视图.公司.名称,
      // 真实图源只在显式 URL 在场时给（失败回退字 兜底字）；否则中性占位，
      // 不拿 claim 派生首字充当公司图片（§3.2）
      图: 公司图片URL !== null && 公司图片URL.trim() !== ''
        ? { 种类: '图片', URL: 公司图片URL, 兜底字: 视图.公司.首字, 可访问名: '公司图片未知' }
        : { 种类: '未知', 可访问名: '公司图片未知' },
      简介: 视图.公司.简介,
      资料: {
        介绍段: 介绍段 !== ''
          ? 介绍段
          : 视图.公司.简介.trim() === '' ? '公司简介未知' : 视图.公司.简介,
        元行组: [
          { 标签: '融资阶段', 值: 元值('融资阶段') },
          { 标签: '规模', 值: 元值('规模') },
          { 标签: '行业', 值: 元值('行业') },
          { 标签: '成立', 值: '未知' },
          { 标签: '地址', 值: 地址 === '' ? '未知' : 地址 },
        ],
      },
    },
    // 发布人卡原位置始终保留：缺席给占位对象，绝不拿公司声明合成「某某 · 企业直招」；
    // 在场时已知姓名/公司/职务照常展示，头像无真实图源给中性图位，wire 无备注给未知；
    // blank 姓名/公司按 §3.2 缺失换未知，不渲染空白槽（部分字段已知就展示已知部分）
    发布人: 视图.发布人 === null
      ? {
        图: { 种类: '未知', 可访问名: '发布人图片未知' },
        姓名: '发布人姓名未知',
        公司: '企业信息未知',
        职务: '职务未知',
        备注: '发布人备注未知',
      }
      : {
        // 发布人加载失败回中性未知占位（不用姓名首字充当照片），兜底字恒空
        图: 发布人图片URL !== null && 发布人图片URL.trim() !== ''
          ? { 种类: '图片', URL: 发布人图片URL, 兜底字: '', 可访问名: '发布人图片未知' }
          : { 种类: '未知', 可访问名: '发布人图片未知' },
        姓名: 视图.发布人.姓名.trim() === '' ? '发布人姓名未知' : 视图.发布人.姓名,
        公司: 视图.公司.名称.trim() === '' ? '企业信息未知' : 视图.公司.名称,
        职务: 视图.发布人.职务.trim() === '' ? '职务未知' : 视图.发布人.职务,
        备注: '发布人备注未知',
      },
  };
}
