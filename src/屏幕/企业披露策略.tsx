// 企业披露策略 —— 企业「我的 › 其他功能 › 披露策略」。求职端「披露偏好」的镜像。
//
// 版式与 披露偏好.tsx 一比一（同一套 我的功能页.module.css），差别只在业务口径：
//   · 不对称双盲：招聘方本来就实名，所以这里管的不是「要不要露脸」，
//     而是「岗位与团队的细节在哪个阶段交出去」；
//   · 对称的只有薪资：岗位薪资带数字锁死在「不披露」，代理只回答
//     「候选人的期望是否落在带内」这类是否题。这把锁在归约层也挡了一次，不是 UI 上灰一下。

import 样式 from './我的功能页.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import type { 披露档 } from '../数据/类型';

const 全部档: 披露档[] = ['不披露', '意向确认后', '一直允许'];

export default function 企业披露策略() {
  const { 返回 } = use导航();
  const { 状态, 派发 } = use应用状态();

  return (
    <次级页外壳>
      <返回栏 返回={返回} 标题="披露策略" 副标题="代理按这里的设定决定何时交出信息" />

      <滚动区 样式覆盖={{ padding: '14px 18px 24px' }}>
        <div className={样式.说明条}>
          公司名与对接人从第一轮起就对候选人可见，这是不对称双盲的设定。
          <span className={样式.说明强调}>AI 不会自动披露双方的薪资数字</span>
          —— 初筛时只判断「区间是否匹配」；意向确认后，由招聘方和候选人自行决定是否沟通具体金额。
        </div>

        {状态.企业披露策略.map((项) => {
          const 锁了 = 项.锁定 !== null;
          return (
            <div key={项.编号} className={样式.披露卡}>
              <div className={样式.披露头}>
                <span className={样式.披露名}>{项.名称}</span>
                {锁了 ? <span className={样式.锁标}>🔒 机制锁定</span> : null}
              </div>
              <div className={样式.披露说明}>{项.说明}</div>

              <div className={样式.分段}>
                {全部档.map((档) => {
                  const 可选 = 项.可选档.includes(档);
                  const 选中 = 项.档 === 档;
                  return (
                    <button
                      key={档}
                      className={`${样式.分段项} ${选中 ? 样式.分段项选中 : ''} ${
                        可选 ? '可点' : 样式.分段项禁用
                      }`}
                      onClick={() =>
                        可选 && !锁了 && 派发({ 型: '设企业披露档', 编号: 项.编号, 档 })
                      }
                      disabled={!可选 || 锁了}
                    >
                      {档}
                    </button>
                  );
                })}
              </div>

              {锁了 ? <div className={样式.锁条}>{项.锁定}</div> : null}
            </div>
          );
        })}

        <div className={样式.版本}>
          改动即时生效，对正在进行的匹配和代谈同样适用。
          <br />
          已经披露出去的信息无法收回。
        </div>
      </滚动区>
    </次级页外壳>
  );
}
