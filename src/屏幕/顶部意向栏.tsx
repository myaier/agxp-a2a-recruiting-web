// 顶部意向切换栏：在谈首页（A6·L）与看市场（A14）共用。
//
// 放大镜 = 自己去市场里搜岗，筛选 ▾ = 收窄市场职位流。这两件事都只对「看市场」
// 的职位流成立（在谈单是已经在谈的，不该再被筛掉），所以两个按钮的真实 UI
// 都长在 看市场.tsx 里，本栏只负责把它们打开：
//   · 已经在看市场 → 走 打开搜索 / 打开筛选 回调（看市场把自己的 setState 传进来）；
//   · 还在「在谈」→ 本页此刻没挂载，先置模块级信号再切子视图，
//     看市场挂载时取走信号打开对应的工具（见下方 请求打开市场工具）。

import 样式 from './顶部意向栏.module.css';
import { 放大镜图标 } from '../组件/图标';
import { use应用状态, 取意向名 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

/** 待打开的市场工具。搜索/筛选是「看市场」的 UI 态、不是跨端业务状态，
 *  所以不进全局 store；跨子视图这一下用模块级信号传话就够。 */
let 市场待打开: '搜索' | '筛选' | null = null;

export function 请求打开市场工具(工具: '搜索' | '筛选') {
  市场待打开 = 工具;
}

/** 取走并复位（只生效一次，避免下次进看市场又自己弹开）*/
export function 取走市场工具请求(): '搜索' | '筛选' | null {
  const 值 = 市场待打开;
  市场待打开 = null;
  return 值;
}

interface 属性 {
  /** 在谈传入：拉起它页内的「看哪几单」面板 + 已生效档（用户 2026-08-21：两个子视图筛选入口要一致）*/
  打开在谈筛选?: () => void;
  在谈生效?: boolean;
  /** 在谈列表正处在「全部意向」档：此时不高亮任何一个意向胶囊，
   *  否则顶栏说的是「你在看这条意向」而列表里躺着别条意向的单，屏上两处自相矛盾。
   *  点任一胶囊会把范围收回当前意向（归约 切意向 里做的），顶栏因此仍是可用的出口。
   *  看市场不传：那一屏永远按当前意向过滤，高亮本来就是对的。 */
  跨意向?: boolean;
  /** 看市场传入：直接展开它页内的搜索行。不传 = 当前不在看市场 */
  打开搜索?: () => void;
  /** 看市场传入：直接拉起它页内的筛选抽屉 */
  打开筛选?: () => void;
  /** 已生效的筛选维度个数，>0 时在「筛选」上标出来，否则用户不知道列表被收窄过 */
  筛选生效数?: number;
}

export default function 顶部意向栏({ 打开搜索, 打开筛选, 筛选生效数 = 0, 打开在谈筛选, 在谈生效 = false, 跨意向 = false }: 属性) {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  /** 打开市场工具：在看市场就直接开，不在就先记下再切过去 */
  const 开市场工具 = (工具: '搜索' | '筛选', 直接开?: () => void) => {
    if (直接开) {
      直接开();
      return;
    }
    请求打开市场工具(工具);
    派发({ 型: '切子视图', 子视图: '看市场' });
  };

  return (
    <div className={样式.顶栏}>
      {/* 胶囊直接由 状态.求职意向表 渲染：「一份简历挂多个意向、各自独立谈」是产品主线，
          写死的常量会让「在意向管理页新增/删除」这件事在首页上不存在。
          意向表为空时这里一个胶囊都不出，整行只剩右侧的 ＋ 和放大镜 ——
          ＋ 本身就是此刻唯一该做的事（去建第一条意向），不另配解释文案。 */}
      <div className={样式.意向行}>
        {/* 胶囊条要能横向滚：意向条数由用户定（配额上限 5 条），不再永远是 2 条。
            布局与「不截断」的取舍都在 .胶囊条 / .胶囊 里（原来那段行内样式已挪进 CSS），
            企业端顶栏 composes 的就是这两个类 —— 两端同一套，改一处两边一起动。 */}
        <div className={样式.胶囊条}>
          {状态.求职意向表.map((条) => {
            // 胶囊上显示的是意向名（标题里的职位部分），它同时是在谈/看市场列表过滤的键
            const 意向名 = 取意向名(条.标题);
            const 选中 = !跨意向 && 意向名 === 状态.当前意向;
            return (
              <button
                key={条.编号}
                className={`${选中 ? 样式.意向选中 : 样式.意向未选} 可点`}
                onClick={() => 派发({ 型: '切意向', 意向: 意向名 })}
              >
                {意向名}
              </button>
            );
          })}
        </div>
        <span className={样式.意向行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.求职意向管理)}
            aria-label="添加求职意向"
          >
            ＋
          </button>
          <button
            className="可点"
            onClick={() => 开市场工具('搜索', 打开搜索)}
            aria-label="搜索职位"
            style={{ display: 'flex', alignItems: 'center' }}
          >
            <放大镜图标 />
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '看市场'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        {/* 两个子视图共用同一个筛选入口（用户 2026-08-21）：
            看市场 → 代理硬性要求（规则，长期生效）；在谈 → 看哪几单（纯视图） */}
        <button
          className={`${样式.筛选} ${
            (状态.子视图 === '看市场' ? 筛选生效数 > 0 : 在谈生效) ? 样式.筛选生效 : ''
          } 可点`}
          onClick={() =>
            状态.子视图 === '看市场'
              ? 开市场工具('筛选', 打开筛选)
              : 打开在谈筛选?.()
          }
        >
          {状态.子视图 === '看市场' && 筛选生效数 > 0 ? `筛选 · ${筛选生效数}` : '筛选'} ▾
        </button>
      </div>
    </div>
  );
}
