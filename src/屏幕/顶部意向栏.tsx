/** 待打开的市场工具。搜索是「看市场」的 UI 态、不是跨端业务状态，
 *  所以不进全局 store；跨子视图这一下用模块级信号传话就够。
 *  （'筛选' 分支已随删筛选一起删除，2026-09-09 产品负责人定稿）*/
let 市场待打开: '搜索' | null = null;

export function 请求打开市场工具(工具: '搜索') {
  市场待打开 = 工具;
}

/** 取走并复位（只生效一次，避免下次进看市场又自己弹开）*/
export function 取走市场工具请求(): '搜索' | null {
  const 值 = 市场待打开;
  市场待打开 = null;
  return 值;
}

/** 标题 `[城市] 职位` 里的城市段；无中括号或纯空白 → ''（缺城市就不加这一节） */
function 取城市(标题: string): string {
  return /^\[([^\]]*)\]/.exec(标题)?.[1]?.trim() ?? '';
}

/** 说明 `薪资｜行业` 的薪资段；纯空白 → ''（不猜、不补） */
function 取薪资说明(说明: string): string {
  return 说明.split('｜')[0]?.trim() ?? '';
}

/** 只给仍然重名的那一组加后缀；后缀为空的条目保持原文字 */
function 消歧一轮(标签们: string[], 取后缀: (序: number) => string): string[] {
  const 计数 = new Map<string, number>();
  for (const 文字 of 标签们) 计数.set(文字, (计数.get(文字) ?? 0) + 1);
  return 标签们.map((文字, 序) => {
    if ((计数.get(文字) ?? 0) < 2) return 文字;
    const 后缀 = 取后缀(序);
    return 后缀 === '' ? 文字 : `${文字} · ${后缀}`;
  });
}

/**
 * Backend 胶囊的区分文字（Spec §4.2）：职位名不重复就只用职位名；重名依次加标题里
 * 已有的城市、说明里已有的薪资；最终仍相同的加同组序号。序号只是列表位置提示，
 * 不是业务坐标、不持久化。绝不展示 int_ 内部编号，也不猜城市／薪资。
 */
export function 造意向胶囊文字(表: 求职意向[]): string[] {
  const 带城市 = 消歧一轮(表.map((条) => 取意向名(条.标题)), (序) => 取城市(表[序].标题));
  const 带薪资 = 消歧一轮(带城市, (序) => 取薪资说明(表[序].说明));
  const 终计数 = new Map<string, number>();
  for (const 文字 of 带薪资) 终计数.set(文字, (终计数.get(文字) ?? 0) + 1);
  const 组内序 = new Map<string, number>();
  return 带薪资.map((文字) => {
    if ((终计数.get(文字) ?? 0) < 2) return 文字;
    const 序 = (组内序.get(文字) ?? 0) + 1;
    组内序.set(文字, 序);
    return `${文字}（${序}）`;
  });
}

interface 属性 {
  /** 在谈列表正处在「全部意向」档：此时不高亮任何一个意向胶囊，
   *  否则顶栏说的是「你在看这条意向」而列表里躺着别条意向的单，屏上两处自相矛盾。
   *  点任一胶囊会把范围收回当前意向（归约 切意向 里做的），顶栏因此仍是可用的出口。
   *  看市场不传：那一屏永远按当前意向过滤，高亮本来就是对的。 */
  跨意向?: boolean;
  /** 看市场传入：直接展开它页内的搜索行。不传 = 当前不在看市场 */
  打开搜索?: () => void;
}

export default function 顶部意向栏({ 打开搜索, 跨意向 = false }: 属性) {
  const { 状态, 派发, 数据源模式 } = use应用状态();
  const { 跳转 } = use导航();

  // 区分文字只在 Backend 生成（同名意向是 Backend 才有的真实情况）；Mock 保持意向名。
  const 胶囊文字们 = 数据源模式 === 'backend' ? 造意向胶囊文字(状态.求职意向表) : null;

  /** 打开市场工具（现只剩搜索）：在看市场就直接开，不在就先记下再切过去 */
  const 开市场工具 = (工具: '搜索', 直接开?: () => void) => {
    if (直接开) {
      直接开();
      return;
    }
    请求打开市场工具(工具);
    派发({ 型: '切子视图', 子视图: '看市场' });
  };

  return (
    <div className={样式.顶栏}>
      {/* 胶囊直接由 状态.求职意向表 渲染：「一份简历挂多个意向、各自独立谈」是产品主线，
          写死的常量会让「在意向管理页新增/删除」这件事在首页上不存在。
          意向表为空时这里一个胶囊都不出，整行只剩右侧的 ＋ 和放大镜 ——
          ＋ 本身就是此刻唯一该做的事（去建第一条意向），不另配解释文案。 */}
      <div className={样式.意向行}>
        {/* 胶囊条要能横向滚：意向条数由用户定（配额上限 5 条），不再永远是 2 条。
            布局与「不截断」的取舍都在 .胶囊条 / .胶囊 里（原来那段行内样式已挪进 CSS），
            企业端顶栏 composes 的就是这两个类 —— 两端同一套，改一处两边一起动。 */}
        <div className={样式.胶囊条}>
          {状态.求职意向表.map((条, 序) => {
            // 胶囊上显示的是意向名（标题里的职位部分），它同时是在谈/看市场列表过滤的键
            const 意向名 = 取意向名(条.标题);
            // Backend 的选中判断只认 ID（意向名不唯一，同名两条会一起点亮）；
            // Mock 没有真实编号，仍按名称比较，行为原样。
            const 选中 = !跨意向 && (
              数据源模式 === 'backend' ? 条.编号 === 状态.当前意向编号 : 意向名 === 状态.当前意向
            );
            return (
              <button
                key={条.编号}
                className={`${选中 ? 样式.意向选中 : 样式.意向未选} 可点`}
                onClick={() =>
                  派发(
                    // Backend：胶囊的 求职意向表.编号 就是 intention_id（水合映射落的），
                    // 随 action 带上给 P4 发现域当 scope 坐标 —— 意向名不唯一，不能反查。
                    // Mock：不带编号，编号载体保持 null，Mock 行为原样。
                    数据源模式 === 'backend'
                      ? { 型: '切意向', 意向: 意向名, 编号: 条.编号 }
                      : { 型: '切意向', 意向: 意向名 },
                  )
                }
              >
                {胶囊文字们 === null ? 意向名 : 胶囊文字们[序]}
              </button>
            );
          })}
        </div>
        <span className={样式.意向行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.求职意向管理)}
            aria-label="添加求职意向"
          >
            ＋
          </button>
          <button
            className="可点"
            onClick={() => 开市场工具('搜索', 打开搜索)}
            aria-label="搜索职位"
            style={{ display: 'flex', alignItems: 'center' }}
          >
            <放大镜图标 />
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '看市场'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '切子视图', 子视图: 视图 })}
          >
            {/* 标注 2026-08-24：「看市场」对外显示改成「市场」。
                状态值不动（'看市场' 是全局 reducer 的枚举），只换渲染名 */}
            {视图 === '看市场' ? '市场' : 视图}
          </button>
        ))}
        {/* 原本这一行右端还有两个子视图共用的「筛选 ▾」入口（用户 2026-08-21），
            2026-09-09 产品负责人定稿整体删除：子视图行只剩 在谈 / 市场 两个键 */}
      </div>
    </div>
  );
}
