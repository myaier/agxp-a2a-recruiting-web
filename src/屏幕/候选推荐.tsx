/** 与 企业在谈候选 同款截短：顶栏只取「 · 」前的主名，两屏切换顶栏不跳变 */
function 岗位名截短(名称: string): string {
  return 名称.split(' · ')[0];
}

/** 「不合适」的四个原因。这是给代理的负反馈样本，所以要具体到可训练，而不是一个笼统的 ✕ */
const 不合适原因表 = ['年限不足', '方向不符', '主栈不符', '其他'];

export default function 候选推荐() {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();
  const [抽屉开, 设抽屉开] = useState(false);
  // 同一时刻只允许一张卡滑开，存的是那张卡的候选编号
  const [滑开的, 设滑开的] = useState<string | null>(null);
  // 待选原因的候选；非 null 时弹「不合适」原因层
  const [待标记, 设待标记] = useState<推荐候选 | null>(null);
  // 本次进屏内点过「让AI代理去聊」的人：卡先留在原位显示「AI代理已接触」，
  // 让用户看到反馈；离开这一屏再回来就不再出现（他已经在「在谈」里了）
  const 本次已接触 = useRef<Set<string>>(new Set());

  const { 当前岗位编号, 不合适候选, 收藏候选, 已接触推荐 } = 状态;

  const 过滤后 = useMemo(() => {
    return 状态.推荐列表.filter((人) => {
      // ① 推荐流必须随顶栏岗位走：切岗位换的是「这个岗位的候选池」，不是同一批人换个标题
      if (人.岗位编号 !== 当前岗位编号) return false;
      // ② 已标记「不合适」的不再出现（可在「已筛掉的候选」里撤销）
      if (不合适候选[人.编号]) return false;
      // ②b 已让代理去聊的：人已经进「在谈」，推荐流里不再重复出现（标注 11:52）。
      //     本次会话里刚点的那张卡先留着显示「AI代理已接触」，下次进来才消失
      if (已接触推荐.includes(人.编号) && !本次已接触.current.has(人.编号)) return false;
      // 到这里就没有本地档位过滤了：筛选层已改成规则清单，按规则筛人是代理的活
      return true;
    });
  }, [状态.推荐列表, 当前岗位编号, 不合适候选, 已接触推荐]);

  // 本岗位一共有多少推荐（不含已标不合适的）—— 空态文案要靠它区分「本来就没有」和「都处理过了」
  const 本岗总数 = 状态.推荐列表.filter(
    (人) => 人.岗位编号 === 当前岗位编号 && !不合适候选[人.编号]
  ).length;

  // 顶栏「筛选 ▾」右上角的数字 = 代理正在生效的企业规则条数
  const 生效规则数 = 状态.企业规则.filter((条) => 条.生效).length;
  const 当前岗位薪资带 = 状态.岗位列表.find((岗) => 岗.编号 === 当前岗位编号)?.薪资带;

  return (
    <主页外壳>
      <企业顶栏 筛选数={生效规则数} 开筛选={() => 设抽屉开(true)} />

      {/* 问AI代理横幅：与「在谈」子视图同款同位（标注 2026-08-19 18:03）*/}
      <代理横幅
        前文="按这个岗位的硬性条件筛出"
        强调={`${本岗总数} 个推荐候选`}
        按下={() => 跳转(路径.企业问AI代理)}
      />

      {/* 横幅与列表之间的固定留白（镜像看市场横幅下方的占位） */}
      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {过滤后.length === 0 ? (
            <div className={样式.空态}>
              {本岗总数 === 0
                ? '这个岗位还没有推荐候选，让代理再找一批试试。'
                : '这个岗位的推荐候选都处理过了，让代理再找一批试试。'}
            </div>
          ) : (
            过滤后.map((人) => (
              <div key={人.编号} className={样式.滑动包}>
                <滑动行
                  操作={[{ 文字: '不合适', 按下: () => 设待标记(人) }]}
                  打开={滑开的 === 人.编号}
                  请求打开={(开) => 设滑开的(开 ? 人.编号 : null)}
                >
                  <推荐卡
                    人={人}
                    岗位薪资带={当前岗位薪资带}
                    滑开={滑开的 === 人.编号}
                    已收藏={收藏候选.includes(人.编号)}
                    切收藏={() => 派发({ 型: '切收藏候选', 编号: 人.编号 })}
                    已接触={状态.已接触推荐.includes(人.编号)}
                    接触={() => {
                      本次已接触.current.add(人.编号);
                      派发({ 型: '接触推荐候选', 编号: 人.编号 });
                    }}
                    按下={() => 跳转(路径.匿名在线简历(人.编号))}
                  />
                </滑动行>
              </div>
            ))
          )}

          {/* 补给入口：推荐流是有限的，翻到底要有「再来一批」而不是一堵墙 */}
          <button
            className={`${样式.补给键} 可点`}
            onClick={() => {
              派发({ 型: '补给推荐' });
              // 诚实反馈：再扫一轮只会新增人选，绝不召回你已经否决过的
              // （回归发现原文案「此前标记不合适的候选重新进入推荐流」与
              //  「已筛掉的候选」页的承诺自相矛盾）
              轻提示('代理已再扫一轮，暂时没有新的人选 · 有新的会直接进推荐流');
            }}
          >
            让代理再找一批
          </button>
        </div>
      </滚动区>
      </下拉刷新>

      {抽屉开 ? (
        <候选筛选抽屉 关闭={() => 设抽屉开(false)} />
      ) : null}

      {待标记 ? (
        <不合适原因层
          人={待标记}
          关闭={() => 设待标记(null)}
          选定={(原因) => {
            派发({ 型: '标记不合适', 编号: 待标记.编号, 原因 });
            设待标记(null);
            轻提示(`已标记「${原因}」· 可在「已筛掉的候选」里撤销`);
          }}
        />
      ) : null}
    </主页外壳>
  );
}

/** 企业顶栏：在招岗位切换（左右平铺）+ ＋发岗 → 在谈/推荐子视图 + 筛选。
 *  与「企业在谈候选」同款（版式镜像求职端 顶部意向栏），两屏切换时顶部不动。 */
function 企业顶栏({ 筛选数, 开筛选 }: { 筛选数: number; 开筛选: () => void }) {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  // 顶栏只平铺在招中的岗位；已归档的收在 D17 岗位管理里
  const 在招们 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');

  return (
    <div className={样式.顶栏}>
      <div className={样式.岗位行}>
        {/* 在招岗位放进横向滚动条里，＋ 留在外面固定住 —— 与求职端意向胶囊条同一套类
            （.岗位滚动条 / .岗位选中 / .岗位未选 都 composes 自 顶部意向栏.module.css）。
            原来是把 N 个岗位直接平铺在 .岗位行 上、靠 max-width 截断，8–15 个岗时整个顶栏失效。
            这里也不再挂全局 .单行：横着滚就是为了整名可读，再打省略号等于白滚。 */}
        <div className={样式.岗位滚动条}>
          {在招们.map((岗) => {
            const 选中 = 岗.编号 === 状态.当前岗位编号;
            return (
              <button
                key={岗.编号}
                className={`${选中 ? 样式.岗位选中 : 样式.岗位未选} 可点`}
                onClick={() => 派发({ 型: '切当前岗位', 编号: 岗.编号 })}
              >
                {岗位名截短(岗.名称)}
              </button>
            );
          })}
        </div>
        <span className={样式.岗位行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.发布岗位)}
            aria-label="发布新岗位"
          >
            ＋
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '推荐'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.企业子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '企业切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        <button
          className={`${样式.筛选} ${筛选数 > 0 ? 样式.筛选生效 : ''} 可点`}
          onClick={开筛选}
        >
          筛选 ▾
        </button>
      </div>
    </div>
  );
}

/** 单张推荐候选卡。
 *  同市场卡：卡内还有自己的按钮（★ / › / 去聊键），HTML 里 button 不能嵌套 button，
 *  所以外层用不可点的白卡，卡主体单独做一个按钮。
 *  滑开 = 这张卡正露着「不合适」，此时卡内所有点击都让位给「收起」，避免误入下一屏。 */
function 推荐卡({
  人,
  岗位薪资带,
  滑开,
  已收藏,
  切收藏,
  已接触,
  接触,
  按下,
}: {
  人: 推荐候选;
  岗位薪资带?: string;
  滑开: boolean;
  已收藏: boolean;
  切收藏: () => void;
  已接触: boolean;
  接触: () => void;
  按下: () => void;
}) {
  // 版式直接抄 BOSS 牛人卡（用户 2026-08-18 定），皮肤是我们的；
  // 卡上只放数据本身，不加任何自创小文案。
  // 画像 = 「年限 · 方向 · 现职类型」三段
  const [, 方向, 现职类型] = 人.画像.split(' · ');

  const 候选期望 = (匿名简历表[人.编号] ?? 匿名简历表[人.编号.split('@')[0]])?.期望.薪资;
  const 薪资结论 = 薪资初筛文案(薪资初筛(候选期望, 岗位薪资带));

  return (
    <白卡 类名={样式.卡}>
      {/* 卡主体整块可点 → D11·A 匿名在线简历（独立屏，版式按 mockup）*/}
      <button className={`${样式.卡主体} 可点`} onClick={() => !滑开 && 按下()}>
        {/* 行1：头像 + 代号 + 活跃度（双盲：头像只用 头像字，不用真人照片） */}
        <div className={样式.头行}>
          <div style={{ flex: 1, minWidth: 0 }}>
            <div className={样式.名行}>
              <span className={`${样式.代号} 单行`}>{人.代号}</span>
            </div>
            {/* 只展示本地结构化筛选结论，不展示候选期望数字。 */}
            <div className={`${样式.基本行} 单行`}>
              {人.经验年} 年<span className={样式.竖分}>｜</span>
              {人.学历}
              <span className={样式.竖分}>｜</span>{薪资结论}
            </div>
          </div>
          <div className={样式.右列}>
            <适配环 分={人.匹配分} 标={null} />
          </div>
        </div>

        {/* 行3/4/5：现职 · 求职状态 · 教育（BOSS 的三条图标行） */}
        <div className={样式.信息行}>
          <公文包图标 尺寸={14} 色="var(--次要浅)" />
          <span className={`${样式.信息文} 单行`}>
            {现职类型} · {方向}
          </span>
        </div>
        <div className={样式.信息行}>
          <学帽图标 尺寸={14} 色="var(--次要浅)" />
          <span className={`${样式.信息文} 单行`}>
            {人.学校} · {人.专业}
          </span>
        </div>

        {/* 标签行：亮点（BOSS 的标签位） */}
        <div className={样式.标签行}>
          {人.亮点.map((亮点) => (
            <span key={亮点} className={样式.标签}>
              {亮点}
            </span>
          ))}
        </div>

      </button>

      {/* 底行：AI代理来源标 + ★收藏 + 「让AI代理去聊」（镜像市场卡的发布人行 + 去谈键） */}
      <div className={样式.底行}>
        <span className={样式.代理小圆}>
          <代理标 尺寸={12} 带点={false} />
        </span>
        <span className={`${样式.来源} 单行`}>你的AI代理从人才库筛出</span>

        <button
          className={`${样式.收藏键} ${已收藏 ? 样式.已收藏 : ''} 可点`}
          onClick={() => !滑开 && 切收藏()}
          aria-label={已收藏 ? '取消收藏' : '收藏'}
          aria-pressed={已收藏}
        >
          {已收藏 ? '★' : '☆'}
        </button>

        <button
          className={`${样式.尖括号} 可点`}
          onClick={() => !滑开 && 按下()}
          aria-label="查看候选画像"
        >
          ›
        </button>

        {已接触 ? (
          // 已接触态：换成不可点的状态标（代理已接手，不需要再点第二次）
          <span className={样式.已接触}>
            <span className={样式.已接触文字}>AI代理已接触</span>
          </span>
        ) : (
          <button className={`${样式.去聊键} 可点`} onClick={() => !滑开 && 接触()}>
            <谈判图标 />
            <span className={样式.去聊文字}>让AI代理去聊</span>
          </button>
        )}
      </div>
    </白卡>
  );
}

/** 「不合适」原因层：负反馈必须带原因，否则代理学不到东西，只是把人藏起来 */
function 不合适原因层({
  人,
  选定,
  关闭,
}: {
  人: 推荐候选;
  选定: (原因: string) => void;
  关闭: () => void;
}) {
  return (
    <弹层框架 标签="标记候选不合适" 遮罩类名={样式.遮罩} 面板类名={样式.原因层} 关闭={关闭}>
        <div className={样式.抓手} />
        <div className={样式.原因标题}>{人.代号} 哪里不合适？</div>
        <div className={样式.原因说明}>
          代理会按这条反馈调整后续寻访，也可以随时在「已筛掉的候选」里撤销。
        </div>
        {不合适原因表.map((原因) => (
          <button key={原因} className={`${样式.原因项} 可点`} onClick={() => 选定(原因)}>
            {原因}
            <span className={样式.原因尖括号}>›</span>
          </button>
        ))}
        <button className={`${样式.原因取消} 可点`} onClick={关闭}>
          取消
        </button>
    </弹层框架>
  );
}
