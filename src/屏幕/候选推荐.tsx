// D11 人才Tab·推荐 + D11·D 搜人才 —— 企业端与求职端同构：本屏镜像求职端「看市场」（A14）。
//
// 与「在谈」共用顶栏（在招岗位左右平铺切换 + 在谈/推荐子视图），两屏切换时顶部不动、
// 只有列表在换 —— 与求职端 A6/A14 的同构硬要求一致；顶栏版式镜像求职端「顶部意向栏」。
//
// 卡片结构（镜像市场卡）：双盲头像 + 代号 + 画像 + 右侧匹配分 → 亮点标签行
//          → 求职状态 · 活跃度 小字信号行 → 代理评语（小结托盘风格）
//          → 分隔线 → 底行「★ 收藏 / 让AI代理去聊」。左滑露出「不合适」。
// 双盲语义：意向确认前只见代号与画像，头像用 头像字 + 灰绿底，绝不出现真名；不谈薪。

import { useMemo, useRef, useState } from 'react';
import 样式 from './候选推荐.module.css';
import 下拉刷新 from '../组件/下拉刷新';
import { 主页外壳, 白卡, 滚动区, 代理横幅 } from '../组件/通用';
import 适配环 from '../组件/适配环';
import 人像头 from '../组件/人像头';
import { 公文包图标, 学帽图标, 放大镜图标, 谈判图标 } from '../组件/图标';
import { 轻提示 } from '../组件/轻提示';
import { use应用状态 } from '../状态/应用状态';
import 代理标 from '../组件/代理标';
import 滑动行 from '../组件/滑动行';
import 候选筛选抽屉, {
  命中筛选,
  生效维度数,
  空筛选条件,
  type 候选筛选条件,
} from '../组件/候选筛选抽屉';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { 匿名简历表, 推荐列表 } from '../数据/企业端模拟数据';
import type { 推荐候选 } from '../数据/类型';

/** 与 企业在谈候选 同款截短：顶栏只取「 · 」前的主名，两屏切换顶栏不跳变 */
function 岗位名截短(名称: string): string {
  return 名称.split(' · ')[0];
}

/** 「不合适」的四个原因。这是给代理的负反馈样本，所以要具体到可训练，而不是一个笼统的 ✕ */
const 不合适原因表 = ['年限不足', '方向不符', '主栈不符', '其他'];

export default function 候选推荐() {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();
  const [搜索词, 设搜索词] = useState('');
  const [筛选条件, 设筛选条件] = useState<候选筛选条件>(空筛选条件);
  const [抽屉开, 设抽屉开] = useState(false);
  // 同一时刻只允许一张卡滑开，存的是那张卡的候选编号
  const [滑开的, 设滑开的] = useState<string | null>(null);
  // 待选原因的候选；非 null 时弹「不合适」原因层
  const [待标记, 设待标记] = useState<推荐候选 | null>(null);
  // 顶栏放大镜把焦点送进搜索条 —— D11·D「搜人才」的入口就是它
  const 搜索框引用 = useRef<HTMLInputElement>(null);
  // 本次进屏内点过「让AI代理去聊」的人：卡先留在原位显示「AI代理已接触」，
  // 让用户看到反馈；离开这一屏再回来就不再出现（他已经在「在谈」里了）
  const 本次已接触 = useRef<Set<string>>(new Set());

  const { 当前岗位编号, 不合适候选, 收藏候选, 已接触推荐 } = 状态;

  const 过滤后 = useMemo(() => {
    const 关键词 = 搜索词.trim();
    return 推荐列表.filter((人) => {
      // ① 推荐流必须随顶栏岗位走：切岗位换的是「这个岗位的候选池」，不是同一批人换个标题
      if (人.岗位编号 !== 当前岗位编号) return false;
      // ② 已标记「不合适」的不再出现（可在「已筛掉的候选」里撤销）
      if (不合适候选[人.编号]) return false;
      // ②b 已让代理去聊的：人已经进「在谈」，推荐流里不再重复出现（标注 11:52）。
      //     本次会话里刚点的那张卡先留着显示「AI代理已接触」，下次进来才消失
      if (已接触推荐.includes(人.编号) && !本次已接触.current.has(人.编号)) return false;
      // ③ 搜索覆盖 代号 / 画像 / 亮点 / 技能：只搜代号等于搜不到人
      if (关键词) {
        const 技能 = 匿名简历表[人.编号]?.技能.join(' ') ?? '';
        const 全文 = `${人.代号} ${人.画像} ${人.亮点.join(' ')} ${技能}`;
        if (!全文.includes(关键词)) return false;
      }
      // ④ 筛选抽屉的条件（无薪资维度，见 候选筛选抽屉 顶部说明）
      return 命中筛选(
        { 经验年: 人.经验年, 学历: 人.学历, 求职状态: 人.求职状态 },
        筛选条件,
        收藏候选.includes(人.编号)
      );
    });
  }, [搜索词, 当前岗位编号, 不合适候选, 收藏候选, 已接触推荐, 筛选条件]);

  // 本岗位一共有多少推荐（不含筛选/搜索）—— 空态文案要靠它区分「本来就没有」和「被筛没了」
  const 本岗总数 = 推荐列表.filter(
    (人) => 人.岗位编号 === 当前岗位编号 && !不合适候选[人.编号]
  ).length;

  return (
    <主页外壳>
      <企业顶栏
        聚焦搜索={() => 搜索框引用.current?.focus()}
        筛选数={生效维度数(筛选条件)}
        开筛选={() => 设抽屉开(true)}
      />

      {/* 问AI代理横幅：与「在谈」子视图同款同位（标注 2026-08-19 18:03）*/}
      <代理横幅
        前文="按这个岗位的硬性条件筛出"
        强调={`${本岗总数} 个推荐候选`}
        按下={() => 跳转(路径.企业问AI代理)}
      />

      {/* 搜索条（D11·D 搜人才）：固定不随列表滚动 */}
      <div className={样式.搜索条}>
        <放大镜图标 尺寸={15} 色="var(--灰白)" 线宽={2} />
        <input
          ref={搜索框引用}
          className={样式.搜索输入}
          placeholder="搜人才：画像 / 亮点 / 技能"
          value={搜索词}
          onChange={(事件) => 设搜索词(事件.target.value)}
        />
      </div>

      {/* 搜索条与列表之间的固定留白（镜像看市场横幅下方的占位） */}
      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {过滤后.length === 0 ? (
            <div className={样式.空态}>
              {本岗总数 === 0
                ? '这个岗位还没有推荐候选，让代理再找一批试试。'
                : '没有符合条件的候选，放宽筛选或换个关键词。'}
            </div>
          ) : (
            过滤后.map((人) => (
              <div key={人.编号} className={样式.滑动包}>
                <滑动行
                  操作={[{ 文字: '不合适', 按下: () => 设待标记(人) }]}
                  打开={滑开的 === 人.编号}
                  请求打开={(开) => 设滑开的(开 ? 人.编号 : null)}
                >
                  <推荐卡
                    人={人}
                    滑开={滑开的 === 人.编号}
                    已收藏={收藏候选.includes(人.编号)}
                    切收藏={() => 派发({ 型: '切收藏候选', 编号: 人.编号 })}
                    已接触={状态.已接触推荐.includes(人.编号)}
                    接触={() => {
                      本次已接触.current.add(人.编号);
                      派发({ 型: '接触推荐候选', 编号: 人.编号 });
                    }}
                    按下={() => 跳转(路径.匿名在线简历(人.编号))}
                  />
                </滑动行>
              </div>
            ))
          )}

          {/* 补给入口：推荐流是有限的，翻到底要有「再来一批」而不是一堵墙 */}
          <button
            className={`${样式.补给键} 可点`}
            onClick={() => {
              派发({ 型: '补给推荐' });
              // 诚实反馈：再扫一轮只会新增人选，绝不召回你已经否决过的
              // （回归发现原文案「此前标记不合适的候选重新进入推荐流」与
              //  「已筛掉的候选」页的承诺自相矛盾）
              轻提示('代理已再扫一轮，暂时没有新的人选 · 有新的会直接进推荐流');
            }}
          >
            让代理再找一批
          </button>
        </div>
      </滚动区>
      </下拉刷新>

      {抽屉开 ? (
        <候选筛选抽屉
          条件={筛选条件}
          设条件={设筛选条件}
          命中数={过滤后.length}
          关闭={() => 设抽屉开(false)}
        />
      ) : null}

      {待标记 ? (
        <不合适原因层
          人={待标记}
          关闭={() => 设待标记(null)}
          选定={(原因) => {
            派发({ 型: '标记不合适', 编号: 待标记.编号, 原因 });
            设待标记(null);
            轻提示(`已标记「${原因}」· 可在「已筛掉的候选」里撤销`);
          }}
        />
      ) : null}
    </主页外壳>
  );
}

/** 企业顶栏：在招岗位切换（左右平铺）+ ＋发岗 + 放大镜 → 在谈/推荐子视图 + 筛选。
 *  与「企业在谈候选」同款（版式镜像求职端 顶部意向栏），两屏切换时顶部不动。 */
function 企业顶栏({
  聚焦搜索,
  筛选数,
  开筛选,
}: {
  聚焦搜索: () => void;
  筛选数: number;
  开筛选: () => void;
}) {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  // 顶栏只平铺在招中的岗位；已归档的收在 D17 岗位管理里
  const 在招们 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');

  return (
    <div className={样式.顶栏}>
      <div className={样式.岗位行}>
        {在招们.map((岗) => {
          const 选中 = 岗.编号 === 状态.当前岗位编号;
          return (
            <button
              key={岗.编号}
              className={`${选中 ? 样式.岗位选中 : 样式.岗位未选} 单行 可点`}
              onClick={() => 派发({ 型: '切当前岗位', 编号: 岗.编号 })}
            >
              {岗位名截短(岗.名称)}
            </button>
          );
        })}
        <span className={样式.岗位行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.发布岗位)}
            aria-label="发布新岗位"
          >
            ＋
          </button>
          <button
            className="可点"
            onClick={聚焦搜索}
            aria-label="搜人才"
            style={{ display: 'flex', alignItems: 'center' }}
          >
            <放大镜图标 />
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '推荐'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.企业子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '企业切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        <button
          className={`${样式.筛选} ${筛选数 > 0 ? 样式.筛选生效 : ''} 可点`}
          onClick={开筛选}
        >
          筛选{筛选数 > 0 ? ` · ${筛选数}` : ''} ▾
        </button>
      </div>
    </div>
  );
}

/** 单张推荐候选卡。
 *  同市场卡：卡内还有自己的按钮（★ / › / 去聊键），HTML 里 button 不能嵌套 button，
 *  所以外层用不可点的白卡，卡主体单独做一个按钮。
 *  滑开 = 这张卡正露着「不合适」，此时卡内所有点击都让位给「收起」，避免误入下一屏。 */
function 推荐卡({
  人,
  滑开,
  已收藏,
  切收藏,
  已接触,
  接触,
  按下,
}: {
  人: 推荐候选;
  滑开: boolean;
  已收藏: boolean;
  切收藏: () => void;
  已接触: boolean;
  接触: () => void;
  按下: () => void;
}) {
  // 版式直接抄 BOSS 牛人卡（用户 2026-08-18 定），皮肤是我们的；
  // 卡上只放数据本身，不加任何自创小文案。
  // 画像 = 「年限 · 方向 · 现职类型」三段
  const [, 方向, 现职类型] = 人.画像.split(' · ');

  return (
    <白卡 类名={样式.卡}>
      {/* 卡主体整块可点 → D11·A 匿名在线简历（独立屏，版式按 mockup）*/}
      <button className={`${样式.卡主体} 可点`} onClick={() => !滑开 && 按下()}>
        {/* 行1：头像 + 代号 + 活跃度（双盲：头像只用 头像字，不用真人照片） */}
        <div className={样式.头行}>
          <人像头 键={人.编号} 首字={人.头像字} 尺寸={34} />
          <div style={{ flex: 1, minWidth: 0 }}>
            <div className={样式.名行}>
              <span className={`${样式.代号} 单行`}>{人.代号}</span>
            </div>
            {/* 行2：年限 ｜ 学历 ｜ 到岗（BOSS 基本行的面议位放到岗档） */}
            <div className={`${样式.基本行} 单行`}>
              {人.经验年} 年<span className={样式.竖分}>｜</span>
              {人.学历}
              {人.到岗 ? (
                <>
                  <span className={样式.竖分}>｜</span>
                  {人.到岗}
                </>
              ) : null}
            </div>
          </div>
          <div className={样式.右列}>
            <适配环 分={人.匹配分} 标={null} />
          </div>
        </div>

        {/* 行3/4/5：现职 · 求职状态 · 教育（BOSS 的三条图标行） */}
        <div className={样式.信息行}>
          <公文包图标 尺寸={14} 色="var(--次要浅)" />
          <span className={`${样式.信息文} 单行`}>
            {现职类型} · {方向}
          </span>
        </div>
        <div className={样式.信息行}>
          <学帽图标 尺寸={14} 色="var(--次要浅)" />
          <span className={`${样式.信息文} 单行`}>
            {人.学校} · {人.专业}
          </span>
        </div>

        {/* 标签行：亮点（BOSS 的标签位） */}
        <div className={样式.标签行}>
          {人.亮点.map((亮点) => (
            <span key={亮点} className={样式.标签}>
              {亮点}
            </span>
          ))}
        </div>

      </button>

      {/* 底行：AI代理来源标 + ★收藏 + 「让AI代理去聊」（镜像市场卡的发布人行 + 去谈键） */}
      <div className={样式.底行}>
        <span className={样式.代理小圆}>
          <代理标 尺寸={12} 带点={false} />
        </span>
        <span className={`${样式.来源} 单行`}>你的AI代理从人才库筛出</span>

        <button
          className={`${样式.收藏键} ${已收藏 ? 样式.已收藏 : ''} 可点`}
          onClick={() => !滑开 && 切收藏()}
          aria-label={已收藏 ? '取消收藏' : '收藏'}
          aria-pressed={已收藏}
        >
          {已收藏 ? '★' : '☆'}
        </button>

        <button
          className={`${样式.尖括号} 可点`}
          onClick={() => !滑开 && 按下()}
          aria-label="查看候选画像"
        >
          ›
        </button>

        {已接触 ? (
          // 已接触态：换成不可点的状态标（代理已接手，不需要再点第二次）
          <span className={样式.已接触}>
            <span className={样式.已接触文字}>AI代理已接触</span>
          </span>
        ) : (
          <button className={`${样式.去聊键} 可点`} onClick={() => !滑开 && 接触()}>
            <谈判图标 />
            <span className={样式.去聊文字}>让AI代理去聊</span>
          </button>
        )}
      </div>
    </白卡>
  );
}

/** 「不合适」原因层：负反馈必须带原因，否则代理学不到东西，只是把人藏起来 */
function 不合适原因层({
  人,
  选定,
  关闭,
}: {
  人: 推荐候选;
  选定: (原因: string) => void;
  关闭: () => void;
}) {
  return (
    <>
      <div className={样式.遮罩} onClick={关闭} />
      <div className={样式.原因层} role="dialog" aria-label="标记不合适">
        <div className={样式.抓手} />
        <div className={样式.原因标题}>{人.代号} 哪里不合适？</div>
        <div className={样式.原因说明}>
          代理会按这条反馈调整后续寻访，也可以随时在「已筛掉的候选」里撤销。
        </div>
        {不合适原因表.map((原因) => (
          <button key={原因} className={`${样式.原因项} 可点`} onClick={() => 选定(原因)}>
            {原因}
            <span className={样式.原因尖括号}>›</span>
          </button>
        ))}
        <button className={`${样式.原因取消} 可点`} onClick={关闭}>
          取消
        </button>
      </div>
    </>
  );
}
