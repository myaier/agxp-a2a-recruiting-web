// 用户还没答过期望薪资时，「底线」那句话里的兜底数字（单位 K，与原文案的 52K 一致）。
// 有兜底才不会渲染出 undefined，也不用给这句话另写一套「你还没设底线」的说法。
const 默认薪资底线K = 52;

// 空历史时给的能力说明：只承诺真实可查的（岗位推荐 / 在谈进展 / 卡片进原生详情），
// 不声称自由筛选、规则修改或日报（Spec §7 非目标）。
const 空会话说明 =
  '你可以直接问我岗位推荐和在谈进展，结果里的项目可以点开原生详情。自由筛选、修改规则和日报暂不支持，请用下方的市场、在谈与规则库入口。';

// 新回复只在接近底部时跟随滚动的阈值（Spec §3：不打断阅读旧消息）。
const 接近底部阈值像素 = 80;

// 关键词 → mock 回复。原型不接后端，用规则表模拟代理应答；
// 顺序即优先级：先命中的先返回，最后一条是兜底。
// 薪资底线K 由调用方算好传进来：这句话里的数字必须跟用户真填的薪资对得上，写死会穿帮。
function 生成回复(问题: string, 薪资底线K: number): string {
  if (问题.includes('远程')) return '搜到 7 个全远程、薪资带覆盖你底线的。要我直接去谈前 3 个吗？';
  if (问题.includes('在谈') || 问题.includes('进展'))
    return '这周 5 个在谈：抖音等你确认意向、小红书差 2K、腾讯到岗差 15 天，另外两个我在核，不用你管。';
  if (问题.includes('薪资') || 问题.includes('底线'))
    return `匿名初筛时，你的底线 ${薪资底线K}K 只有我知道。我只回答「区间是否匹配」，不会自动披露数值；意向确认后由你自行决定是否谈薪。`;
  if (问题.includes('去谈')) return '好，已按匿名口径接触前 3 家，进展我在往来记录里逐条留痕。';
  return '收到。我按这个口径继续谈，拿不准的地方会先来问你，不会替你破例。';
}

export default function 问AI代理() {
  const { 数据源模式 } = use应用状态();
  return 数据源模式 === 'backend' ? <Backend问AI代理 /> : <Mock问AI代理 />;
}

// ── Backend：真实聊天页。复用既有外壳 / 返回栏 / 气泡 / 快捷槽 / 滚动容器，状态机在
//    use助手会话，本组件只做展示接线与滚动编排，不新造会话存储 ──
function Backend问AI代理() {
  const { 返回, 跳转, 替换跳转 } = use导航();
  const { 派发, 状态, 助手会话 } = use应用状态();
  // 仅 Backend 分支挂助手 hook；访问为 null（Mock / 未登录 / 非 candidate）时钩子输出
  // 空底座并锁输入，零请求。Mock 容器不挂这个 hook。
  const {
    消息, 草稿, 设草稿, 首读中, 加载更早中, 有更早, 输入禁用,
    错误, 提交待确认, 发送, 加载更早, 重读, 重试提交, 重试轮次,
  } = use助手会话(助手会话);
  const 我首字 = 状态.基本信息.真名.charAt(0);

  // 两个主壳快捷键共用：先摆好目标 Tab + 子视图状态，再原地替换进主壳 ——
  // 与 职位详情 安全返回 同一套动作，用户落进主壳看到的就是选好的那个视图。
  const 去主壳 = (子视图: '看市场' | '在谈') => {
    派发({ 型: '切Tab', Tab: '职位' });
    派发({ 型: '切子视图', 子视图 });
    替换跳转(路径.主壳);
  };

  // 当前访问的镜像 ref：解读恢复草稿前核对身份范围没有变过
  const 访问引用 = useRef(助手会话);
  访问引用.current = 助手会话;

  // ── 滚动编排：对话流是屏幕内唯一滚动区 ──
  // · 首读落地定位到底部；· 加载更早按前后 scrollHeight 差值回补 scrollTop 保阅读位置；
  // · 其余新内容只在距底 ≤80px 时跟随，用户在读旧消息时不抢滚动。
  const 滚动引用 = useRef<HTMLDivElement>(null);
  const 首屏未定位 = useRef(true);
  const 更早前高度 = useRef<number | null>(null);

  useEffect(() => {
    const 容器 = 滚动引用.current;
    if (!容器 || 消息.length === 0) return;
    if (首屏未定位.current) {
      首屏未定位.current = false;
      容器.scrollTo({ top: 容器.scrollHeight });
      return;
    }
    if (更早前高度.current !== null) {
      容器.scrollTop += 容器.scrollHeight - 更早前高度.current;
      更早前高度.current = null;
      return;
    }
    const 距底 = 容器.scrollHeight - 容器.scrollTop - 容器.clientHeight;
    if (距底 <= 接近底部阈值像素) 容器.scrollTo({ top: 容器.scrollHeight });
  }, [消息]);

  // 卡片导航（Spec §5）：岗位项带 candidate-assistant 来源 + 导航钩子的窄内存证据；
  // 在谈项直接用可信 record_id 进现有在谈详情，不要求 case_id（pre-Case 可达）。
  const 打开岗位 = (岗位编号: string) => {
    标记助手来路();
    跳转(路径.职位详情(岗位编号), { 来源: 'candidate-assistant' });
  };
  const 打开在谈 = (记录编号: string) => {
    跳转(路径.在谈详情(记录编号));
  };

  // 「让 AI 解读」的草稿暂存（fix：待确认分支不吞草稿）。解读发送可能落入「提交待确认」
  // （网络错 / 5xx / 坏体）—— promise 仍正常 resolve，下方 .then 的恢复是等值 no-op，而
  // 待确认解除的两条路径（重试提交成功 / 重读结算权威轮次）都会无条件清草稿。所以暂存
  // 挂 ref，在 提交待确认 true→false 时统一恢复；普通输入发送先清 ref（发出去的就是草稿
  // 本身，清稿是正常契约，不得复活旧暂存）。恢复前核对身份范围，已换范围一律丢弃。
  // 暂存还带新鲜度校验（fix 2）：用户已改稿甩开的旧暂存（直接受理后残留的那份）在进入
  // 待确认时作废，不被无关的待确认解除复活 —— 见下方 effect 的 false→true 沿。
  const 解读暂存 = useRef<{ 草稿: string; 范围键: string | null } | null>(null);
  const 曾提交待确认 = useRef(false);

  useEffect(() => {
    if (提交待确认 && !曾提交待确认.current) {
      // 进入待确认时校验暂存新鲜度（fix 2）：暂存只有「从创建到此刻草稿原封未动」才仍是
      // 本条解读发送的暂存（解读在飞期间输入锁死，草稿不可能被动）。直接受理后残留、又被
      // 用户改稿甩开的旧暂存一律作废，防止之后无关的待确认解除把它复活进输入框、覆盖
      // 用户当前草稿。不在发送的 .then 里按「是否进待确认」清 ref：设待确认(true) 的
      // React 提交晚于该微任务回调，彼时读状态必是旧值，会把待确认路径正需要的暂存误清。
      const 暂存 = 解读暂存.current;
      if (暂存 !== null && 草稿 !== 暂存.草稿) 解读暂存.current = null;
    }
    if (曾提交待确认.current && !提交待确认) {
      const 暂存 = 解读暂存.current;
      解读暂存.current = null;
      if (暂存 !== null && 访问引用.current?.范围键 === 暂存.范围键) 设草稿(暂存.草稿);
    }
    曾提交待确认.current = 提交待确认;
    // 内部只读 refs 与 hook 的稳定行为 设草稿；草稿只在待确认翻转的当帧读取（其余渲染的
    // 旧值无副作用）；仅待确认翻转才需要跑
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [提交待确认]);

  // 「让 AI 解读」次级动作（Spec §5）：按普通发送锁发送可见模板文本，ID 取自已解码结果，
  // 不混入占位事实、不注入隐藏 prompt，也不触发页面导航。use助手会话 的 发送(显式文本)
  // 受理后会无条件清草稿 —— 解读不该吞掉用户正在输入的内容：发送前暂存、受理后原样
  // 恢复（身份范围已换则丢弃，不把旧草稿带进新会话）。
  const 解读在谈 = (项: AssistantNegotiationItem) => {
    const 暂存草稿 = 草稿;
    const 捕获范围键 = 助手会话?.范围键 ?? null;
    解读暂存.current = 暂存草稿 !== '' ? { 草稿: 暂存草稿, 范围键: 捕获范围键 } : null;
    const 职位名 = 项.job.title !== null && 项.job.title.trim() !== '' ? 项.job.title : '职位未知';
    void 发送(`请查看在谈记录 ${项.record_id}（${职位名}）的详细进展。`).then(() => {
      // 直接受理（未进待确认）时 hook 已清稿，这里原样恢复；进待确认/明确拒绝时为等值
      // no-op，待确认解除的恢复交给上面的 effect
      if (暂存草稿 !== '' && 访问引用.current?.范围键 === 捕获范围键) 设草稿(暂存草稿);
    });
  };

  const 加载更早并保持位置 = () => {
    更早前高度.current = 滚动引用.current?.scrollHeight ?? 0;
    void 加载更早();
  };

  return (
    <次级页外壳 对话底 白底>
      <返回栏
        返回={返回}
        标题="我的求职AI代理"
        右侧={<button className={`${样式.更多} 可点`} onClick={() => 跳转(路径.代理详情)}>⋯</button>}
      />

      <div ref={滚动引用} className={`${样式.对话流} 滚动区`}>
        <div className={样式.对话内容}>
          {首读中 ? <div className={样式.状态行}>正在读取历史消息…</div> : null}
          {/* 加载更早按钮随内容滚动、置顶在流内：不遮底部输入条 */}
          {有更早 ? (
            <button
              className={`${样式.加载更早} 可点`}
              disabled={加载更早中}
              onClick={加载更早并保持位置}
            >
              {加载更早中 ? '正在加载更早消息…' : '查看更早消息'}
            </button>
          ) : null}
          {消息.map((条) => (
            <div key={条.message_id} className={样式.一轮}>
              {/* 用户时间位于气泡外下方；与 Agent 侧共用同条 created_at（Spec §10.4） */}
              <我方气泡 外观="求职" 内容={条.text} 头像URL={null} 首字={我首字} 时间={条.created_at} />
              {条.status === 'processing' ? (
                <div className={样式.状态行}>正在处理…</div>
              ) : 条.status === 'succeeded' && 条.reply !== null ? (
                <查询结果展示
                  回复={条.reply}
                  时间={条.created_at}
                  打开岗位={打开岗位}
                  打开在谈={打开在谈}
                  解读在谈={解读在谈}
                  解读禁用={输入禁用}
                />
              ) : 条.status === 'failed' ? (
                <div className={样式.状态行}>
                  这条消息处理失败
                  {/* 只有 failed && retryable 给显式重试（Spec §3）：新幂等键、原位替换 */}
                  {条.retryable ? (
                    <button
                      className={`${样式.文本键} 可点`}
                      onClick={() => void 重试轮次(条.message_id)}
                    >
                      重试
                    </button>
                  ) : null}
                </div>
              ) : 条.status === 'uncertain' ? (
                <div className={样式.状态行}>结果暂无法确认</div>
              ) : null}
            </div>
          ))}
          {/* 空会话说明只在首读成功后出现：首读失败不当空历史（错误行与说明不得同屏） */}
          {!首读中 && 错误 === null && 消息.length === 0 ? <代理气泡 外观="求职" 内容={空会话说明} /> : null}
          {/* 错误 / 提交待确认：现有文本按钮语义。待确认给重试确认入口（同 key 重放）；
              其余错误给重读入口（首读失败重试、轮询失败恢复都走它）。 */}
          {提交待确认 || 错误 !== null ? (
            <div className={样式.状态行}>
              {错误 ?? '上一条消息的提交结果待确认'}
              {提交待确认 ? (
                <button className={`${样式.文本键} 可点`} onClick={() => void 重试提交()}>
                  重试提交
                </button>
              ) : (
                <button className={`${样式.文本键} 可点`} onClick={() => void 重读()}>
                  重试
                </button>
              )}
            </div>
          ) : null}
        </div>
      </div>

      <快捷操作行
        外观="求职"
        项们={[
          { 键: '去市场', 文案: '去市场', 按下: () => 去主壳('看市场') },
          { 键: '看在谈', 文案: '看在谈', 按下: () => 去主壳('在谈') },
          { 键: '规则库', 文案: '规则库', 按下: () => 跳转(路径.规则库) },
        ]}
      />

      <真输入条
        占位="问问岗位推荐或在谈进展…"
        值={草稿}
        改变={设草稿}
        发送={() => {
          // 用户从输入框发起的发送：清掉任何解读暂存 —— 发出去的就是草稿本身，
          // 其待确认解除后的清稿是正常契约，不得把旧暂存复活进输入框
          解读暂存.current = null;
          void 发送();
        }}
        禁用={输入禁用}
      />
    </次级页外壳>
  );
}

// ── Mock：原型对话体，只在 mock 模式挂载 ──
function Mock问AI代理() {
  const { 返回, 跳转 } = use导航();
  // 我方头像首字：读全局基本信息（改了名字这里跟着变）
  const { 状态, 派发 } = use应用状态();
  const 我首字 = 状态.基本信息.真名.charAt(0);

  // 代理回复里那句「你的底线 xxK」的数字来源。
  // 「底线」这个独立字段已从 UI 移除，现在由期望薪资区间的下限承担底线的作用，所以从这里取。
  // 两种情况取不到可用的 K 值，都回落到 默认薪资底线K：
  //   · 还没走过向导薪资题（引导预填.薪资 为空）
  //   · 实习生走的是「元/天」日薪档，那个数字塞进「xxK」的句式里会变成假话
  // 另外挡一道 Number.isFinite —— 引导预填 来自 localStorage，缓存被改坏时不能渲染出 NaNK。
  const 薪资档 = 状态.引导预填?.薪资;
  const 薪资底线K =
    薪资档 && 薪资档.单位 !== '元/天' && Number.isFinite(薪资档.下限) && 薪资档.下限 > 0
      ? 薪资档.下限
      : 默认薪资底线K;

  // 「改成可谈」= 把这条红线放宽写成一条真规则，再让用户当场看到结果。
  // 这套动作原本长在已删除的 未通过说明 屏上，逻辑一行未改，只是换了触发它的地方。
  // 本体只在 mock 模式挂载（模式门在 state/effect 之前分流），Backend 结构上碰不到这里；
  // 写规则归 规则库（canonical），落规则后留在本页、轻提示告知。
  const 改成可谈 = () => {
    派发({
      型: '新增规则',
      内容: 今日简报.松一档.规则内容,
      来源: 今日简报.松一档.规则来源,
    });
    // 用户 2026-08-31:「点记成规则不应该跳到规则库」—— 落规则后留在本页,轻提示告知
    轻提示('已记成规则');
  };

  // 「维持红线」不改任何规则，只把这条建议标记为已处理，避免点了没反应。
  // 处理状态在 Mock 容器（展示件不自持）：父级把确认文案经 建议.处理文案 送进卡片，
  // 没送之前组件不得自行换成「已维持」。
  const [已维持红线, 设已维持红线] = useState(false);

  const [对话, 设对话] = useState<代理对话条[]>(代理对话初始);
  const [草稿, 设草稿] = useState('');
  // 对话流容器：需要拿原生 DOM 节点手动滚到底，所以用 div.滚动区 而不是 <滚动区> 组件
  const 滚动引用 = useRef<HTMLDivElement>(null);
  // 550ms 假回复的定时器句柄集合：卸载（含切到 Backend 分支）时统一取消，
  // 不让一条排队的模拟回复在别的模式 / 别的页面上凭空冒出来。
  const 回复定时器 = useRef<Set<number>>(new Set());

  useEffect(() => () => {
    回复定时器.current.forEach((handle) => window.clearTimeout(handle));
    回复定时器.current.clear();
  }, []);

  // 对话每变一次就滚到底部（含代理 550ms 后追加的那条），保证新消息始终可见
  useEffect(() => {
    const 容器 = 滚动引用.current;
    if (!容器) return;
    容器.scrollTo({ top: 容器.scrollHeight, behavior: 'smooth' });
  }, [对话]);

  // 发送：不带参数发草稿（输入框），带参数发快捷问句
  const 发送 = (文本?: string) => {
    const 内容 = (文本 ?? 草稿).trim();
    if (!内容) return;
    // 用时刻做编号：我方那条用 时刻，代理回复用 时刻+1，保证两条 key 不撞
    const 时刻 = Date.now();
    设对话((旧) => [...旧, { 编号: 时刻, 角色: '我', 内容 }]);
    设草稿('');
    const handle = window.setTimeout(() => {
      回复定时器.current.delete(handle);
      设对话((旧) => [...旧, { 编号: 时刻 + 1, 角色: '代理', 内容: 生成回复(内容, 薪资底线K) }]);
    }, 550);
    回复定时器.current.add(handle);
  };

  return (
    <次级页外壳 对话底 白底> {/* 2026-08-24 全站去框（产品负责人批）：页底转纯白，与私聊三屏一致 */}
      <返回栏 返回={返回} 标题="我的求职AI代理" 右侧={<button className={`${样式.更多} 可点`} onClick={() => 跳转(路径.代理详情)}>⋯</button>} />

      {/* 对话流：屏幕内唯一滚动区 */}
      <div ref={滚动引用} className={`${样式.对话流} 滚动区`}>
        <div className={样式.对话内容}>
          {对话.map((条) => {
            if (条.角色 === '简报')
              return (
                <简报展示
                  key={条.编号}
                  外观="求职"
                  标题="今日简报"
                  更新时间="09:00 更新"
                  统计={今日简报.统计}
                  正文前={今日简报.正文前}
                  正文强调={今日简报.正文强调}
                  正文后={今日简报.正文后}
                  脚注={今日简报.脚注}
                  漏斗={null}
                  建议={{
                    标题: 今日简报.松一档.标题,
                    正文前: 今日简报.松一档.正文前,
                    数值1: 今日简报.松一档.数值1,
                    正文中: 今日简报.松一档.正文中,
                    数值2: 今日简报.松一档.数值2,
                    正文后: 今日简报.松一档.正文后,
                    维持文案: '维持红线',
                    放宽文案: '改成可谈',
                    处理文案: 已维持红线
                      ? '已维持红线 · 规则不变，我会继续替你挡掉这类岗位。'
                      : null,
                    维持: () => 设已维持红线(true),
                    放宽: 改成可谈,
                  }}
                />
              );
            if (条.角色 === '我')
              return (
                <我方气泡
                  key={条.编号}
                  外观="求职"
                  内容={条.内容 ?? ''}
                  头像URL={null}
                  首字={我首字}
                />
              );
            return <代理气泡 key={条.编号} 外观="求职" 内容={条.内容 ?? ''} />;
          })}
        </div>
      </div>

      {/* 快捷问句：点一下等于直接把这句话发出去 */}
      <快捷操作行
        外观="求职"
        项们={快捷问句.map((句) => ({ 键: 句, 文案: 句, 按下: () => 发送(句) }))}
      />

      <真输入条
        占位="让AI代理搜岗、去谈，或问进展…"
        值={草稿}
        改变={设草稿}
        发送={() => 发送()}
      />
    </次级页外壳>
  );
}
