// A27 与AI代理对话 · 从在谈首页的「问AI代理」横幅进入。
//
// 屏幕结构（自上而下）：
//   返回栏（标题 + 右侧 ⋯）→ 对话流（第一条是今日简报卡）→ 快捷问句胶囊行 → 真输入条
//
// 三条要点：
//   · 第一条消息不是普通气泡，而是代理气泡里嵌的「今日简报」卡（统计横条 + 正文 + 松一档 + 脚注）
//   · 输入框真的能发：本地 useState 追加消息，代理回复由关键词规则表生成，延迟 550ms 追加
//   · 每次对话变化后自动滚到底，跟原生 IM 一致

import { useEffect, useRef, useState } from 'react';
import 样式 from './问AI代理.module.css';
import { 次级页外壳, 返回栏, 真输入条 } from '../组件/通用';
import 代理标 from '../组件/代理标';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';
import { 今日简报, 代理对话初始, 快捷问句 } from '../数据/模拟数据';
import type { 代理对话条 } from '../数据/类型';

// 用户还没答过期望薪资时，「底线」那句话里的兜底数字（单位 K，与原文案的 52K 一致）。
// 有兜底才不会渲染出 undefined，也不用给这句话另写一套「你还没设底线」的说法。
const 默认薪资底线K = 52;

// 关键词 → mock 回复。原型不接后端，用规则表模拟代理应答；
// 顺序即优先级：先命中的先返回，最后一条是兜底。
// 薪资底线K 由调用方算好传进来：这句话里的数字必须跟用户真填的薪资对得上，写死会穿帮。
function 生成回复(问题: string, 薪资底线K: number): string {
  if (问题.includes('远程')) return '搜到 7 个全远程、薪资带覆盖你底线的。要我直接去谈前 3 个吗？';
  if (问题.includes('在谈') || 问题.includes('进展'))
    return '这周 5 个在谈：抖音等你确认意向、小红书差 2K、腾讯到岗差 15 天，另外两个我在核，不用你管。';
  if (问题.includes('薪资') || 问题.includes('底线'))
    return `匿名初筛时，你的底线 ${薪资底线K}K 只有我知道。我只回答「区间是否匹配」，不会自动披露数值；意向确认后由你自行决定是否谈薪。`;
  if (问题.includes('去谈')) return '好，已按匿名口径接触前 3 家，进展我在往来记录里逐条留痕。';
  return '收到。我按这个口径继续谈，拿不准的地方会先来问你，不会替你破例。';
}

export default function 问AI代理() {
  const { 返回, 跳转 } = use导航();
  // 我方头像首字：读全局基本信息（改了名字这里跟着变）
  const { 状态, 派发 } = use应用状态();
  const 我首字 = 状态.基本信息.真名.charAt(0);

  // 代理回复里那句「你的底线 xxK」的数字来源。
  // 「底线」这个独立字段已从 UI 移除，现在由期望薪资区间的下限承担底线的作用，所以从这里取。
  // 两种情况取不到可用的 K 值，都回落到 默认薪资底线K：
  //   · 还没走过向导薪资题（引导预填.薪资 为空）
  //   · 实习生走的是「元/天」日薪档，那个数字塞进「xxK」的句式里会变成假话
  // 另外挡一道 Number.isFinite —— 引导预填 来自 localStorage，缓存被改坏时不能渲染出 NaNK。
  const 薪资档 = 状态.引导预填?.薪资;
  const 薪资底线K =
    薪资档 && 薪资档.单位 !== '元/天' && Number.isFinite(薪资档.下限) && 薪资档.下限 > 0
      ? 薪资档.下限
      : 默认薪资底线K;

  // 「改成可谈」= 把这条红线放宽写成一条真规则，再跳规则库让用户当场看到结果。
  // 这套动作原本长在已删除的 未通过说明 屏上，逻辑一行未改，只是换了触发它的地方。
  const 改成可谈 = () => {
    派发({
      型: '新增规则',
      内容: 今日简报.松一档.规则内容,
      来源: 今日简报.松一档.规则来源,
    });
    跳转(路径.规则库);
  };

  const [对话, 设对话] = useState<代理对话条[]>(代理对话初始);
  const [草稿, 设草稿] = useState('');
  // 对话流容器：需要拿原生 DOM 节点手动滚到底，所以用 div.滚动区 而不是 <滚动区> 组件
  const 滚动引用 = useRef<HTMLDivElement>(null);

  // 对话每变一次就滚到底部（含代理 550ms 后追加的那条），保证新消息始终可见
  useEffect(() => {
    const 容器 = 滚动引用.current;
    if (!容器) return;
    容器.scrollTo({ top: 容器.scrollHeight, behavior: 'smooth' });
  }, [对话]);

  // 发送：不带参数发草稿（输入框），带参数发快捷问句
  const 发送 = (文本?: string) => {
    const 内容 = (文本 ?? 草稿).trim();
    if (!内容) return;
    // 用时刻做编号：我方那条用 时刻，代理回复用 时刻+1，保证两条 key 不撞
    const 时刻 = Date.now();
    设对话((旧) => [...旧, { 编号: 时刻, 角色: '我', 内容 }]);
    设草稿('');
    setTimeout(() => {
      设对话((旧) => [...旧, { 编号: 时刻 + 1, 角色: '代理', 内容: 生成回复(内容, 薪资底线K) }]);
    }, 550);
  };

  return (
    <次级页外壳 对话底 白底> {/* 2026-08-24 全站去框（产品负责人批）：页底转纯白，与私聊三屏一致 */}
      <返回栏 返回={返回} 标题="我的求职AI代理" 右侧={<button className={`${样式.更多} 可点`} onClick={() => 跳转(路径.代理详情)}>⋯</button>} />

      {/* 对话流：屏幕内唯一滚动区 */}
      <div ref={滚动引用} className={`${样式.对话流} 滚动区`}>
        <div className={样式.对话内容}>
          {对话.map((条) => {
            if (条.角色 === '简报') return <简报气泡 key={条.编号} 改成可谈={改成可谈} />;
            if (条.角色 === '我')
              return (
                <div key={条.编号} className={样式.我行}>
                  <div className={`${样式.我气泡} ${样式.气泡文字}`}>{条.内容}</div>
                  {/* 我方头像（标注 23:52）：与左侧代理头像对称 */}
                  <span className={样式.我头像}>{我首字}</span>
                </div>
              );
            return <代理气泡 key={条.编号} 内容={条.内容 ?? ''} />;
          })}
        </div>
      </div>

      {/* 快捷问句：点一下等于直接把这句话发出去 */}
      <div className={样式.快捷行}>
        {快捷问句.map((句) => (
          <button key={句} className={`${样式.快捷键} 可点`} onClick={() => 发送(句)}>
            {句}
          </button>
        ))}
      </div>

      <真输入条
        占位="让AI代理搜岗、去谈，或问进展…"
        值={草稿}
        改变={设草稿}
        发送={() => 发送()}
      />
    </次级页外壳>
  );
}

// ── 代理气泡：左侧代理标头像（与主页横幅同款，无圆底）+ 左上角切平的白气泡 ──
function 代理气泡({ 内容 }: { 内容: string }) {
  return (
    <div className={样式.代理行}>
      <span className={样式.小盾牌}>
        <代理标 尺寸={30} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
      </span>
      <div className={`${样式.代理气泡} ${样式.气泡文字}`}>{内容}</div>
    </div>
  );
}

// ── 今日简报：每天 09:00 / 18:00 各更新一次，套在代理气泡里当第一条消息 ──
// 「需要你」那个统计数用 --意向（红）标出来，让待决策项在一屏内最先被看到。
//
// 「要不要松一档？」放在简报卡**内部**（正文与脚注之间），而不是紧随其后另起一张卡，
// 三个理由：
//   1. 它和统计条同源 —— 都是代理这一周替你盘出来的数，同一份汇报拆成两张卡会让人以为
//      是两次不同的汇报；
//   2. 对话流里另起一张卡就得给 代理对话条 加一个新角色，等于在 IM 流里插一条不是消息的
//      东西，简报本来就是这条流里唯一的「卡片附件」，不该有第二个；
//   3. 招聘端的简报卡里已经有可点的漏斗行（硬性匹配 → 初筛记录），卡内放可操作元素是这屏
//      定好的做法，两端保持一致。
// 位置选在正文之后、脚注之前：脚注讲的是整张简报的更新节奏，是收尾行，
// 动作卡压在它后面会让人误以为「每天 09:00 更新」说的是这条建议。
function 简报气泡({ 改成可谈 }: { 改成可谈: () => void }) {
  // 「维持红线」不改任何规则，只把这条建议标记为已处理，避免点了没反应
  const [已维持红线, 设已维持红线] = useState(false);

  return (
    <div className={样式.代理行}>
      <span className={样式.小盾牌}>
        <代理标 尺寸={30} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
      </span>
      <div className={`${样式.代理气泡} ${样式.简报气泡}`}>
        <div className={样式.简报头}>
          <span className={样式.简报标题}>今日简报</span>
          <span className={样式.简报时间}>09:00 更新</span>
        </div>

        {/* 四个统计数横条 */}
        <div className={样式.统计条}>
          {今日简报.统计.map((项) => (
            <div key={项.名称} className={样式.统计项}>
              <div
                className={`${样式.统计数} ${项.强调 ? 样式.统计数强调 : ''} 等宽数字`}
              >
                {项.数值}
              </div>
              <div className={样式.统计名}>{项.名称}</div>
            </div>
          ))}
        </div>

        <div className={样式.简报正文}>
          {今日简报.正文前}
          <b className={样式.简报强调}>{今日简报.正文强调}</b>
          {今日简报.正文后}
        </div>

        {/* 绿色建议卡：把「这条红线卡掉了多少岗」量化出来，再给两个动作 */}
        <div className={样式.松一档卡}>
          <div className={样式.松一档标题}>{今日简报.松一档.标题}</div>
          <div className={样式.松一档正文}>
            {今日简报.松一档.正文前}
            <b className={样式.松一档强调}>{今日简报.松一档.数值1}</b>
            {今日简报.松一档.正文中}
            <b className={样式.松一档强调}>{今日简报.松一档.数值2}</b>
            {今日简报.松一档.正文后}
          </div>

          {已维持红线 ? (
            <div className={样式.已维持}>已维持红线 · 规则不变，我会继续替你挡掉这类岗位。</div>
          ) : (
            <div className={样式.按钮行}>
              <button className={`${样式.次按钮} 可点`} onClick={() => 设已维持红线(true)}>
                维持红线
              </button>
              <button className={`${样式.主按钮} 可点`} onClick={改成可谈}>
                改成可谈
              </button>
            </div>
          )}
        </div>

        <div className={样式.简报脚注}>{今日简报.脚注}</div>
      </div>
    </div>
  );
}
