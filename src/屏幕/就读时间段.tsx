// 入学年 / 毕业年（2000–2030，可空），副行回显学校名。
// 答案落 简历教育[0].开始 / 结束（'YYYY-09' / 'YYYY-06'，按学年惯例取 9 月入学 6 月毕业）。
// 下一步：无条件进 工作经历 —— 学生也要在那页补实习经历 / 技能 / 证书，
// 由 工作经历 再按身份分流（学生 → 求职状态，非学生 → 引导问答偏好段）。
// 旧注释写的「学生 → 引导问答续答」是上一版残留，与代码和流程合同都对不上。
//
// 候选 onboarding 简历预填（Spec §8 /onboard/eduyears）：首挂载同步用 取就读年份预填
// 预选 —— 仅 2000..2030 界内年份才预选，缺席保留空值；学生 end month 缺失可回退
// graduation_year；确认 education_period 分区只在既有保存成功后、跳转之前。
//
// Task 4（2026-09-14）：年份可空、单一值真相 —— 页面不持有 `?? 2021 / ?? 2025`
// 伪默认（2021/2025 演示预填迁到数据层种子 就读年份演示预填）。未填显示「请选择」；
// 未填就不拼日期，点下一步标记对应字段持续错误、修改该项清除；清空写回草稿空字符串。
//
// bottom-drawer 统一 Task 4（2026-09-15）：页内双滚轮改年份区间抽屉入口 ——
// 页面只显示两侧值/空占位，点开共用 年份区间层（内嵌双滚轮 + 弹层框架）；
// 抽屉临时值自持，确定才一次回填并把开始/结束原子写入建档草稿（同一次
// 更新候选建档草稿，不分两次持久化成半状态）；取消不改值、不清错误、不写盘。
// 旧「每次滚动即时写草稿」就此移除；返回/刷新恢复继续使用原建档草稿能力。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import 年份区间层 from '../组件/年份区间层';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import { 取就读年份预填 } from '../流程/候选Onboarding简历预填';
import { 创建空候选预填状态 } from '../状态/后端/类型';
import { 并入建档草稿, 校验起止年月 } from '../流程/onboarding配置';
import { 路径 } from '../路由/路径表';

/** 从 'YYYY-MM' 里抠年份；抠不出或超界返回 null（R：缺失就是缺失，不补兜底值） */
function 取年(值: string | undefined): number | null {
  const 年 = Number((值 ?? '').slice(0, 4));
  return 年 >= 2000 && 年 <= 2030 ? 年 : null;
}

export default function 就读时间段() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 操作, 数据源模式, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  // J-PILOT-02 Task 4：起止补齐前这条教育段仍是不完整的，BFF 跳过它 ——
  // 前三屏的学历/学校/专业只在建档草稿里，这一屏在同一条草稿段上收口。
  // 旅程标记见 基本信息.tsx（日常编辑不写草稿）
  const 旅程中 = 是后端 && 全局.引导预填 !== null;
  const 建档 = 旅程中 ? 全局.引导预填?.建档 : undefined;
  const 草稿基本 = 建档?.资料?.基本信息;
  const 教育基底 = 建档?.资料?.教育 ?? 全局.简历教育;
  const 首段 = 教育基底[0];
  const 在校中 = (草稿基本?.身份 ?? 全局.基本信息.身份) === '在校';

  // 候选 onboarding 预填：首挂载同步预选（无建议/超界/缺席时返回传入的当前值）
  const 年份初始 = 取就读年份预填(
    后端状态.候选预填状态 ?? 创建空候选预填状态(),
    取年(首段?.开始),
    取年(首段?.结束),
    在校中,
  );
  // R：年份可空 —— 未填的侧入口就显示「请选择」，看到的空就是保存的空；
  // 没有「显示占位值 + 隐藏确认标志」的第二真相。
  const [入学年, 设入学年] = useState<number | null>(年份初始.start);
  const [毕业年, 设毕业年] = useState<number | null>(年份初始.end);
  // 点下一步时未填那一侧的持续字段错误；抽屉确认修改该项即清除
  const [入学年错误, 设入学年错误] = useState(false);
  const [毕业年错误, 设毕业年错误] = useState(false);
  // 抽屉打开判别：临时值由 年份区间层 自持，确定才回填（同 基本信息 生日抽屉约定）
  const [抽屉打开, 设抽屉打开] = useState(false);

  /** 抽屉确定：一次设置两个本地值，只对发生变化的侧清除字段错误；
   *  同一次 更新候选建档草稿 原子写入教育首段的开始与结束
   *  （null 映射空字符串，非空映射 'YYYY-09' / 'YYYY-06'）。 */
  const 确认年份 = (新入学: number | null, 新毕业: number | null) => {
    设抽屉打开(false);
    设入学年(新入学);
    设毕业年(新毕业);
    if (新入学 !== 入学年) 设入学年错误(false);
    if (新毕业 !== 毕业年) 设毕业年错误(false);
    if (旅程中 && 首段 !== undefined) {
      操作.更新候选建档草稿(并入建档草稿(建档, {
        资料: {
          教育: 教育基底.map((条, 序) => (序 === 0
            ? {
              ...条,
              开始: 新入学 === null ? '' : `${新入学}-09`,
              结束: 新毕业 === null ? '' : `${新毕业}-06`,
            }
            : 条)),
        },
      }));
    }
  };

  const 下一步 = async () => {
    // R：空值真相检查在前 —— 任一侧未填就不拼日期不保存，标对应字段持续错误
    if (入学年 === null || 毕业年 === null) {
      设入学年错误(入学年 === null);
      设毕业年错误(毕业年 === null);
      轻提示('请选择入学时间和毕业时间');
      return;
    }
    // 两列各自独立、都是 2000–2030，谁也不管谁 —— 抽屉允许倒置确认，
    // 起止合法性在这里拦（校验用与三处编辑页同一个函数，口径不会分叉）。
    const 时间错误 = 校验起止年月(`${入学年}-09`, `${毕业年}-06`, '入学时间', '毕业时间');
    if (时间错误) {
      轻提示(时间错误);
      return;
    }
    const 新教育 = 教育基底.map((条, 序) =>
      序 === 0 ? { ...条, 开始: `${入学年}-09`, 结束: `${毕业年}-06` } : 条
    );
    if (旅程中) {
      操作.更新候选建档草稿(并入建档草稿(建档, {
        资料: {
          教育: 新教育,
          ...(在校中 ? { 基本信息: { ...草稿基本, 毕业年: String(毕业年) } } : {}),
        },
      }));
    }
    try {
      await 操作.保存简历({
        // 学生的毕业年份记入基本信息（学生这里填的是**预计毕业**，可以在未来）
        基本信息: 在校中
          ? { ...全局.基本信息, ...草稿基本, 毕业年: String(毕业年) }
          : { ...全局.基本信息, ...草稿基本 },
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 新教育,
        证书: 全局.简历证书,
      });
      // 预填确认只在既有保存成功后（拒绝时分区不确认），且先于跳转
      操作.确认候选Onboarding预填分区('education_period');
      // 分叉：学生 → 求职状态（在校四档）→ 向导；非学生 → 工作经历（保存后回向导）
      // 学生也必须经过这页补实习经历、技能、证书；此前有页面却被路由静默跳过。
      跳转(路径.工作经历);
    } catch (错误) {
      轻提示(取后端错误文案(错误));
    }
  };

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      {/* 副行回显学校名：确认「填的是这所学校的就读时间」 */}
      <页面大标题 标题="就读时间段" 说明={首段?.学校 || undefined} />

      <滚动区 样式覆盖={{ padding: '14px 18px 12px' }}>
        {/* 年份区间入口（沿原滚轮卡/滚轮头样式）：点开共用抽屉；未填侧显示「请选择」 */}
        <button
          type="button"
          className={`${样式.滚轮卡} ${样式.年份入口} 可点`}
          aria-label="入学年和毕业年"
          onClick={() => 设抽屉打开(true)}
        >
          <span className={样式.滚轮头}>
            <span className={`${样式.滚轮头文字} ${入学年错误 ? 样式.滚轮头文字错误 : ''}`}>入学年</span>
            <span className={`${样式.滚轮头文字} ${毕业年错误 ? 样式.滚轮头文字错误 : ''}`}>毕业年</span>
          </span>
          <span className={样式.年份值行}>
            <span className={`${样式.年份值} 等宽数字`}>{入学年 === null ? '请选择' : 入学年}</span>
            <span className={`${样式.年份值} 等宽数字`}>{毕业年 === null ? '请选择' : 毕业年}</span>
          </span>
        </button>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />

      {抽屉打开 ? (
        <年份区间层
          入学年={入学年}
          毕业年={毕业年}
          确认={确认年份}
          取消={() => 设抽屉打开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}