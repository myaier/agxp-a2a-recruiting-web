// 就读时间段（/onboard/eduyears）—— 2026-08-20 按 BOSS 截图顺序重排：
// 入学年 / 毕业年双滚轮（2000–2030），副行回显学校名。
// 答案落 简历教育[0].开始 / 结束（'YYYY-09' / 'YYYY-06'，按学年惯例取 9 月入学 6 月毕业）。
// 下一步：无条件进 工作经历 —— 学生也要在那页补实习经历 / 技能 / 证书，
// 由 工作经历 再按身份分流（学生 → 求职状态，非学生 → 引导问答偏好段）。
// 旧注释写的「学生 → 引导问答续答」是上一版残留，与代码和流程合同都对不上。
//
// 候选 onboarding 简历预填（Spec §8 /onboard/eduyears）：首挂载同步用 取就读年份预填
// 预选双滚轮 —— 仅 2000..2030 界内年份才预选，超界/缺席保留页面既有默认；
// 学生 end month 缺失可回退 graduation_year；确认 education_period 分区只在既有
// 保存成功后、跳转之前。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import 内嵌双滚轮 from '../组件/内嵌双滚轮';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import { 取就读年份预填 } from '../流程/候选Onboarding简历预填';
import { 创建空候选预填状态 } from '../状态/后端/类型';
import { 校验起止年月 } from '../流程/onboarding配置';
import { 路径 } from '../路由/路径表';

/** 年份档位：2000–2030 */
const 年档 = Array.from({ length: 31 }, (_, 序) => 2000 + 序);

/** 从 'YYYY-MM' 里抠年份；抠不出或超界返回 null（R：缺失就是缺失，不补兜底值） */
function 取年(值: string | undefined): number | null {
  const 年 = Number((值 ?? '').slice(0, 4));
  return 年档.includes(年) ? 年 : null;
}

export default function 就读时间段() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 操作, 数据源模式, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  const 首段 = 全局.简历教育[0];
  const 在校中 = 全局.基本信息.身份 === '在校';

  // 候选 onboarding 预填：首挂载同步预选（无建议/超界/缺席时返回传入的当前值）
  const 年份初始 = 取就读年份预填(
    后端状态.候选预填状态 ?? 创建空候选预填状态(),
    取年(首段?.开始),
    取年(首段?.结束),
    在校中,
  );
  // R：滚轮没有空态总显示一个落点 —— 显示值（缺失时用演示默认 2021/2025 占位）
  // 与确认态分离；只有已有值、真实建议或用户滚动过的那一侧才随保存写盘。
  const [入学年, 设入学年] = useState(年份初始.start ?? 2021);
  const [毕业年, 设毕业年] = useState(年份初始.end ?? 2025);
  const [入学年已确认, 设入学年已确认] = useState(!是后端 || 年份初始.start !== null);
  const [毕业年已确认, 设毕业年已确认] = useState(!是后端 || 年份初始.end !== null);
  const 设入学年并确认 = (值: number) => { 设入学年(值); 设入学年已确认(true); };
  const 设毕业年并确认 = (值: number) => { 设毕业年(值); 设毕业年已确认(true); };

  // 两个年份轮各自独立、都是 2000–2030，谁也不管谁 —— 这里正是截图里
  // 「2020.09 — 2018.06」的来源：毕业年滚到入学年前面，一路静默存进简历教育段。
  // 校验用与三处编辑页同一个函数，口径不会分叉。
  const 时间错误 = 校验起止年月(`${入学年}-09`, `${毕业年}-06`, '入学时间', '毕业时间');

  const 下一步 = async () => {
    // R：确认态检查在前 —— 任一侧未确认（无已有值/建议/用户滚动）不拼接不保存
    if (!入学年已确认 || !毕业年已确认) {
      轻提示('请选择入学时间和毕业时间');
      return;
    }
    if (时间错误) {
      轻提示(时间错误);
      return;
    }
    try {
      await 操作.保存简历({
        // 学生的毕业年份记入基本信息（意向卡与初筛按它折算应届口径）
        基本信息: 在校中 ? { ...全局.基本信息, 毕业年: String(毕业年) } : 全局.基本信息,
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 全局.简历教育.map((条, 序) =>
          序 === 0 ? { ...条, 开始: `${入学年}-09`, 结束: `${毕业年}-06` } : 条
        ),
        证书: 全局.简历证书,
      });
      // 预填确认只在既有保存成功后（拒绝时分区不确认），且先于跳转
      操作.确认候选Onboarding预填分区('education_period');
      // 分叉：学生 → 求职状态（在校四档）→ 向导；非学生 → 工作经历（保存后回向导）
      // 学生也必须经过这页补实习经历、技能、证书；此前有页面却被路由静默跳过。
      跳转(路径.工作经历);
    } catch (错误) {
      轻提示(取后端错误文案(错误));
    }
  };

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      {/* 副行回显学校名：确认「填的是这所学校的就读时间」 */}
      <页面大标题 标题="就读时间段" 说明={首段?.学校 || undefined} />

      <滚动区 样式覆盖={{ padding: '14px 18px 12px' }}>
        <div className={样式.滚轮卡}>
          <div className={样式.滚轮头}>
            <span className={样式.滚轮头文字}>入学年</span>
            <span className={样式.滚轮头文字}>毕业年</span>
          </div>
          <内嵌双滚轮
            左档={年档}
            右档={年档}
            左值={入学年}
            右值={毕业年}
            设左值={设入学年并确认}
            设右值={设毕业年并确认}
            左名="入学年"
            右名="毕业年"
            左单位="年"
            右单位="年"
          />
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
