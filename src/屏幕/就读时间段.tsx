// 就读时间段（/onboard/eduyears）—— 2026-08-20 按 BOSS 截图顺序重排：
// 入学年 / 毕业年双滚轮（2000–2030），副行回显学校名。
// 答案落 简历教育[0].开始 / 结束（'YYYY-09' / 'YYYY-06'，按学年惯例取 9 月入学 6 月毕业）。
// 下一步：无条件进 工作经历 —— 学生也要在那页补实习经历 / 技能 / 证书，
// 由 工作经历 再按身份分流（学生 → 求职状态，非学生 → 引导问答偏好段）。
// 旧注释写的「学生 → 引导问答续答」是上一版残留，与代码和流程合同都对不上。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import 内嵌双滚轮 from '../组件/内嵌双滚轮';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 校验起止年月 } from '../流程/onboarding配置';
import { 路径 } from '../路由/路径表';

/** 年份档位：2000–2030 */
const 年档 = Array.from({ length: 31 }, (_, 序) => 2000 + 序);

/** 从 'YYYY-MM' 里抠年份；抠不出用兜底值 */
function 取年(值: string | undefined, 兜底: number): number {
  const 年 = Number((值 ?? '').slice(0, 4));
  return 年档.includes(年) ? 年 : 兜底;
}

export default function 就读时间段() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  const 首段 = 全局.简历教育[0];
  const 在校中 = 全局.基本信息.身份 === '在校';

  const [入学年, 设入学年] = useState(取年(首段?.开始, 2021));
  const [毕业年, 设毕业年] = useState(取年(首段?.结束, 2025));

  // 两个年份轮各自独立、都是 2000–2030，谁也不管谁 —— 这里正是截图里
  // 「2020.09 — 2018.06」的来源：毕业年滚到入学年前面，一路静默存进简历教育段。
  // 校验用与三处编辑页同一个函数，口径不会分叉。
  const 时间错误 = 校验起止年月(`${入学年}-09`, `${毕业年}-06`, '入学时间', '毕业时间');

  const 下一步 = () => {
    if (时间错误) {
      轻提示(时间错误);
      return;
    }
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育.map((条, 序) =>
        序 === 0 ? { ...条, 开始: `${入学年}-09`, 结束: `${毕业年}-06` } : 条
      ),
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      // 学生的毕业年份记入基本信息（意向卡与初筛按它折算应届口径）
      基本信息: 在校中 ? { ...全局.基本信息, 毕业年: String(毕业年) } : 全局.基本信息,
    });
    // 分叉：学生 → 求职状态（在校四档）→ 向导；非学生 → 工作经历（保存后回向导）
    // 学生也必须经过这页补实习经历、技能、证书；此前有页面却被路由静默跳过。
    跳转(路径.工作经历);
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      {/* 副行回显学校名：确认「填的是这所学校的就读时间」 */}
      <页面大标题 标题="就读时间段" 说明={首段?.学校 || undefined} />

      <滚动区 样式覆盖={{ padding: '14px 18px 12px' }}>
        <div className={样式.滚轮卡}>
          <div className={样式.滚轮头}>
            <span className={样式.滚轮头文字}>入学年</span>
            <span className={样式.滚轮头文字}>毕业年</span>
          </div>
          <内嵌双滚轮
            左档={年档}
            右档={年档}
            左值={入学年}
            右值={毕业年}
            设左值={设入学年}
            设右值={设毕业年}
            左名="入学年"
            右名="毕业年"
            左单位="年"
            右单位="年"
          />
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
