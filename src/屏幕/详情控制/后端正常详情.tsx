// 后端正常详情 —— 只在正常联合成立时挂载的正常详情子组件（契约 C，Task 9 自
// 屏幕/P5/MatchCase详情 的 详情主体/阶段动作区 原样搬入）。父路由实例
// （MatchCase详情，持有 use后端详情控制）按 role/case/主体 key 重挂载本组件；本组件
// 自己持 Tab 与滚动定位，内部无条件调用 use后端详情动作 与 useCasePDF预览（禁止条件
// 调用 hooks），把两者的结果组装为 A/B 纯展示 props、动作卡与弹层 —— raw 动作输入
// 绝不进展示层。
//
// 生命周期（plan 固定）：换 Case/角色/账号由 key 重挂载整体重置（Tab 回进度、弹层销毁、
// 动作/PDF 局部草稿与租约回收）；Tab 切换只互斥挂载两个内容槽，不卸载本组件 —— 动作
// 草稿、S1 单选/披露层与 PDF 租约不因切 Tab 丢失或无人回收。回答在飞表经 动作输入
// 由父控制持有，本组件卸载不丢锁。
//
// 模式边界：动作卡只从 视图.actions（映射交集）渲染，本组件绝不加卡；PDF 入口只由
// 阶段投影的 typed 附件授权（点附件 只走 Case 专属 role 路径）；终局摘要/移交/底栏
// 只读展示（契约 A）；错误不当缺失（刷新错误单独一行 + 重试）。

import { useEffect, useState, type CSSProperties, type ReactNode } from 'react';
import 确认层 from '../../组件/确认层';
// 原始 PDF 弹层只借既有 module 的壳，文案由本文件给：Plan 1 的 简历原件层 渲染的是
// Mock 仿真纸身（无 blob/url 通道）—— 评审 R1 裁定 P5 自建最小 UI，不硬套错口径的层。
import 原始PDF层 from '../../组件/原始PDF层';
import 阶段对话流 from '../../组件/阶段对话流';
import { 详情外壳 } from '../../组件/在谈详情/详情外壳';
import { 详情状态区 } from '../../组件/在谈详情/详情状态区';
import { 详情动作卡 } from '../../组件/在谈详情/详情动作卡';
import { 事实问题卡 } from '../../组件/在谈详情/事实问题卡';
import { 终局区 } from '../../组件/在谈详情/终局区';
import { 详情底栏 } from '../../组件/在谈详情/详情底栏';
import { 职位资料 } from '../../组件/在谈详情/职位资料';
import { 在线简历正文 } from '../../组件/在谈详情/在线简历正文';
import { 简历选择层 } from '../../组件/在谈详情/简历选择层';
import type { 详情Tab, 事实问题属性, 详情动作卡信息 } from '../../组件/在谈详情/类型';
import 样式 from '../../组件/在谈详情/详情外壳.module.css';
import { use导航 } from '../../路由/导航钩子';
import { use后端详情动作 } from './use后端详情动作';
import { useCasePDF预览 } from './useCasePDF预览';
import type { 后端正常资源 } from './use后端详情控制';

/** 动作区的行间排布（卡片本体/按钮的样式归 组件/在谈详情/详情动作卡.module.css） */
const 动作区样式: CSSProperties = { display: 'flex', flexDirection: 'column', gap: 10 };

export function 后端正常详情({ 资源 }: { 资源: 后端正常资源 }) {
  const { 返回 } = use导航();

  // Tab 由本组件持有（切 Tab 不改 URL）：换 Case/角色/账号由父层 key 重挂载整体重置，
  // 不沿用上一单的视图。
  const [当前Tab, 设当前Tab] = useState<详情Tab>('进度');

  // 进入页面（以及换 Case 重挂载、从资料 Tab 切回进度）自动定位到当前阶段段（与两端
  // Mock 详情屏同构），不用手动划过整条流。两个 Tab 的内容互斥挂载，切走即卸载 ——
  // 依赖里带上当前 Tab 才能在切回进度时重新定位当前段，不因条件挂载丢失节点定位。
  const 当前段引用 = 资源.当前段引用;
  useEffect(() => {
    const 定时 = window.setTimeout(() => {
      当前段引用.current?.scrollIntoView({ block: 'start', behavior: 'smooth' });
    }, 120);
    return () => window.clearTimeout(定时);
  }, [当前Tab, 当前段引用]);

  // S0–S3 动作控制（Task 5/6/8 迁入的 hook，Task 9 起由本组件无条件调用）：卡片、
  // 回答区、单选/披露/终结确认的 props 全由 hook 交付；回答在飞表仍由父控制持有
  // （本组件卸载不丢锁）。
  const { 卡片们, 事实问题, 简历选择, 披露确认, 终结确认 } = use后端详情动作(资源.动作输入);

  // 授权原始 PDF（两端，Task 7 迁入的 hook）：租约只活在弹层生命周期（关闭/换 Case/
  // 换角色/卸载即 revoke，绝不缓存），在飞单发防连点，迟到成败过代际栅栏。
  const { 预览: PDF预览, 打开: 开PDF, 关闭: 关PDF } = useCasePDF预览(资源.PDF输入);

  // 分段投影（纯 mapper 交付）+ 控制端只把动作卡挂到「有动作的合法当前段」
  // （mapper 已把该段标 默认展开 —— S0 passed 行钉住展开，卡不随分节条折没）。
  const 分段们 = 资源.分段们.map((段) =>
    段.默认展开 === true
      ? { ...段, 尾部: <阶段动作区 卡片们={卡片们} 事实问题={事实问题} /> }
      : 段,
  );

  return (
    <详情外壳
      信息={资源.顶栏}
      返回={返回}
      当前Tab={当前Tab}
      切Tab={设当前Tab}
      进度={
        <>
          {/* 刷新/轮询失败：旧详情原样保留只读，错误单独一行交代 + 重试（§10.3） */}
          {资源.刷新错误 !== null ? (
            <div className={样式.错误行}>
              {资源.刷新错误}
              <button className={`${样式.重试键} 可点`} onClick={资源.重试}>
                重试
              </button>
            </div>
          ) : null}

          {/* 状态区：viewer 待办徽标 + 闭词状态文案 + 步骤说明 + 轮次 + 注意说明，
              全部由 从P5到详情状态 投影（权威 state.*）；终局只读态徽标退场 */}
          <详情状态区 信息={资源.状态} />

          {/* 终局摘要 + completed 移交（契约 A 纯展示；pending 恒禁用零导航） */}
          <终局区 信息={资源.终局} />

          {/* 四阶段对话流：类型化分段的渲染器（时间线/回执只是展示文本）。动作卡在
              分段项.尾部、两端 PDF 入口在 附件 槽（点附件 只走 Case 专属 role 路径）。 */}
          <阶段对话流
            分段们={分段们}
            当前段引用={当前段引用}
            点附件={(文件名) => void 开PDF(文件名)}
          />
        </>
      }
      资料={
        // 第二 Tab：求职端 = 职位资料（spec §3.3 全部区块），招聘端 = 在线简历正文
        // （spec §3.4 九个信息区）。Backend 两端都只吃 Case 冻结详情，不用公司/岗位/
        // 推荐查询补值，也不发任何新请求。招聘端 P5 detail 不提供结构化在线简历 ——
        // 档 恒 null，不构造空假简历；求职端无合法公司导航坐标：入口位置保留、真实
        // 禁用并就地解释，不从公司文本推 opaque ID。
        资源.动作输入.role === 'recruiter' ? (
          <在线简历正文 档={null} 完整布局 缺失说明="当前在谈详情数据未提供" />
        ) : (
          <职位资料
            信息={资源.职位资料}
            公司详情={{
              键: '公司详情',
              文案: '公司详情',
              外观: '次要',
              禁用说明: '公司详情暂不可用',
              执行: null,
            }}
          />
        )
      }
      底栏={<详情底栏 信息={资源.底栏} />}
      弹层={
        <>
          {/* S1 多份附件的当场单选（use后端详情动作 交付的 简历选择属性）；取消/遮罩/
              Esc 只走 取消（零请求），确认进披露确认 */}
          {简历选择 !== null ? <简历选择层 {...简历选择} /> : null}

          {/* S1 Case 专属披露确认（hook 交付的 确认属性，逐字段透传）：正文点名冻结
              职位与这次递交哪份 PDF；确认/取消都即刻清层，上一次的授权绝不复用 */}
          {披露确认 !== null ? <确认层 {...披露确认} /> : null}

          {/* 终结类二次确认（结束初筛/婉拒邀请/判不合适，hook 交付，逐字段透传） */}
          {终结确认 !== null ? <确认层 {...终结确认} /> : null}

          {/* 原始 PDF 弹层：顶栏只有 PDF 徽标 + 文件名 + 关闭（无解释文字）；正文以
              租约地址呈现真实字节；关闭（hook 交付）即回收租约 */}
          {PDF预览 !== null ? (
            <原始PDF层 文件名={PDF预览.文件名} 地址={PDF预览.地址} 关闭={关PDF} />
          ) : null}
        </>
      }
    />
  );
}

// ── 阶段动作区：只渲染映射交集里的卡（S0–S3 的控制与投影全在 use后端详情动作，
//    这里只剩排版；respond_fact 的提交控件归 事实问题卡，嵌在卡正文槽，不双挂载）──

function 阶段动作区({
  卡片们,
  事实问题,
}: {
  卡片们: readonly 详情动作卡信息[];
  事实问题: 事实问题属性 | null;
}): ReactNode {
  if (卡片们.length === 0) return null; // 无动作（映射交集为空）不渲染动作区
  return (
    <div style={动作区样式}>
      {卡片们.map((卡) => (
        <详情动作卡
          key={卡.键}
          信息={卡.键 === 'respond_fact' && 事实问题 !== null
            ? { ...卡, 正文: <事实问题卡 {...事实问题} /> }
            : 卡}
        />
      ))}
    </div>
  );
}
