/** 动作区的行间排布（卡片本体/按钮的样式归 组件/在谈详情/详情动作卡.module.css） */
const 动作区样式: CSSProperties = { display: 'flex', flexDirection: 'column', gap: 10 };

/**
 * 后端详情渲染（J-PILOT-01 Task 5）：按 role/case/主体 key 重挂载的详情主体 —— 持 Tab，
 * 正常联合（Case）交 后端正常详情（P5 展示与动作），连续联合（pre-Case/retention）交
 * 后端连续详情（纯展示 + 失败动作卡）。同一张卡 pre-Case→Case 只是联合切换：Tab 不
 * 重置、不追加导航历史（Spec §6「正常轮询避免丢 Tab」）。
 */
export function 后端详情渲染({ 资源 }: { 资源: 后端正常资源 | 后端连续资源 }) {
  const [当前Tab, 设当前Tab] = useState<详情Tab>('进度');
  return 资源.kind === '正常' ? (
    <后端正常详情 资源={资源} 当前Tab={当前Tab} 切Tab={设当前Tab} />
  ) : (
    <后端连续详情 资源={资源} 当前Tab={当前Tab} 切Tab={设当前Tab} />
  );
}

/** 公开信息初评托盘（Spec §6）：现有总结组件 + 来源标签；决定/内容/证据以源数据呈现。 */
function 公开初评托盘({ 视图 }: { 视图: 公开初评托盘视图 }) {
  return (
    <小结托盘 标签="公开信息初评">
      <div>{`结论：${视图.决定}`}</div>
      <div>{视图.内容}</div>
      {视图.证据行们.map((行, 序) => (
        <div key={序}>{行}</div>
      ))}
    </小结托盘>
  );
}

export function 后端正常详情({
  资源,
  当前Tab: 外部Tab,
  切Tab: 外部切Tab,
}: {
  资源: 后端正常资源;
  /** J-PILOT-01 Task 5：Tab 由 后端详情渲染 持有（联合切换不重置）；缺省组件自持（旧调用方）。 */
  当前Tab?: 详情Tab;
  切Tab?: (tab: 详情Tab) => void;
}) {
  const { 返回 } = use导航();

  // Tab 兜底自持（缺省 = 旧行为完全不变）：换 Case/角色/账号由父层 key 重挂载整体重置，
  // 不沿用上一单的视图。
  const [内部Tab, 设内部Tab] = useState<详情Tab>('进度');
  const 当前Tab = 外部Tab ?? 内部Tab;
  const 设当前Tab = 外部切Tab ?? 设内部Tab;

  // 进入页面（以及换 Case 重挂载、从资料 Tab 切回进度）自动定位到当前阶段段（与两端
  // Mock 详情屏同构），不用手动划过整条流。两个 Tab 的内容互斥挂载，切走即卸载 ——
  // 依赖里带上当前 Tab 才能在切回进度时重新定位当前段，不因条件挂载丢失节点定位。
  const 当前段引用 = 资源.当前段引用;
  useEffect(() => {
    const 定时 = window.setTimeout(() => {
      当前段引用.current?.scrollIntoView({ block: 'start', behavior: 'smooth' });
    }, 120);
    return () => window.clearTimeout(定时);
  }, [当前Tab, 当前段引用]);

  // S0–S3 动作控制（Task 5/6/8 迁入的 hook，Task 9 起由本组件无条件调用）：卡片、
  // 单选/披露/终结确认的 props 全由 hook 交付（J-PILOT-01：S0 无 respond_fact 回答区，
  // 双端零人工补事实输入）。
  const { 卡片们, 简历选择, 披露确认, 终结确认 } = use后端详情动作(资源.动作输入);

  // 授权原始 PDF（两端，Task 7 迁入的 hook）：租约只活在弹层生命周期（关闭/换 Case/
  // 换角色/卸载即 revoke，绝不缓存），在飞单发防连点，迟到成败过代际栅栏。
  const { 预览: PDF预览, 打开: 开PDF, 关闭: 关PDF } = useCasePDF预览(资源.PDF输入);

  // 分段投影（纯 mapper 交付）+ 控制端只把动作卡挂到「有动作的合法当前段」
  // （mapper 已把该段标 默认展开 —— S0 passed 行钉住展开，卡不随分节条折没）。
  const 分段们 = 资源.分段们.map((段) =>
    段.默认展开 === true
      ? { ...段, 尾部: <阶段动作区 卡片们={卡片们} /> }
      : 段,
  );

  return (
    <详情外壳
      信息={资源.顶栏}
      返回={返回}
      当前Tab={当前Tab}
      切Tab={设当前Tab}
      进度={
        <>
          {/* 刷新/轮询失败：旧详情原样保留只读，错误单独一行交代 + 重试（§10.3） */}
          {资源.刷新错误 !== null ? (
            <div className={样式.错误行}>
              {资源.刷新错误}
              <button className={`${样式.重试键} 可点`} onClick={资源.重试}>
                重试
              </button>
            </div>
          ) : null}

          {/* 状态区：viewer 待办徽标 + 闭词状态文案 + 步骤说明 + 轮次 + 注意说明，
              全部由 从P5到详情状态 投影（权威 state.*）；终局只读态徽标退场 */}
          <详情状态区 信息={资源.状态} />

          {/* 公开信息初评（J-PILOT-01 Task 5，Spec §6）：独立于 S0 总结的现有托盘槽，
              来源标签「公开信息初评」；有 Case 时候选可同时回看两份来源 */}
          {资源.公开初评 !== null ? <公开初评托盘 视图={资源.公开初评} /> : null}

          {/* 终局摘要 + completed 移交（契约 A 纯展示；pending 恒禁用零导航） */}
          <终局区 信息={资源.终局} />

          {/* 四阶段对话流：类型化分段的渲染器（时间线/回执只是展示文本）。动作卡在
              分段项.尾部、两端 PDF 入口在 附件 槽（点附件 只走 Case 专属 role 路径）。 */}
          <阶段对话流
            分段们={分段们}
            当前段引用={当前段引用}
            点附件={(文件名) => void 开PDF(文件名)}
          />
        </>
      }
      资料={
        // 第二 Tab：求职端 = 职位资料（spec §3.3 全部区块），招聘端 = 在线简历正文
        // （spec §3.4 九个信息区）。Backend 两端都只吃 Case 冻结详情，不用公司/岗位/
        // 推荐查询补值，也不发任何新请求。招聘端 P5 detail 不提供结构化在线简历 ——
        // 档 恒 null，不构造空假简历；求职端无合法公司导航坐标：入口位置保留、真实
        // 禁用并就地解释，不从公司文本推 opaque ID。
        资源.动作输入.role === 'recruiter' ? (
          <在线简历正文 档={null} 完整布局 缺失说明="当前在谈详情数据未提供" />
        ) : (
          <职位资料
            信息={资源.职位资料}
            公司详情={{
              键: '公司详情',
              文案: '公司详情',
              外观: '次要',
              禁用说明: '公司详情暂不可用',
              执行: null,
            }}
          />
        )
      }
      底栏={<详情底栏 信息={资源.底栏} />}
      弹层={
        <>
          {/* S1 多份附件的当场单选（use后端详情动作 交付的 简历选择属性）；取消/遮罩/
              Esc 只走 取消（零请求），确认进披露确认 */}
          {简历选择 !== null ? <简历选择层 {...简历选择} /> : null}

          {/* S1 Case 专属披露确认（hook 交付的 确认属性，逐字段透传）：正文点名冻结
              职位与这次递交哪份 PDF；确认/取消都即刻清层，上一次的授权绝不复用 */}
          {披露确认 !== null ? <确认层 {...披露确认} /> : null}

          {/* 终结类二次确认（结束初筛/婉拒邀请/判不合适，hook 交付，逐字段透传） */}
          {终结确认 !== null ? <确认层 {...终结确认} /> : null}

          {/* 原始 PDF 弹层：顶栏只有 PDF 徽标 + 文件名 + 关闭（无解释文字）；正文以
              租约地址呈现真实字节；关闭（hook 交付）即回收租约 */}
          {PDF预览 !== null ? (
            <原始PDF层 文件名={PDF预览.文件名} 地址={PDF预览.地址} 关闭={关PDF} />
          ) : null}
        </>
      }
    />
  );
}

// ── 阶段动作区：只渲染映射交集里的卡（S0–S3 的控制与投影全在 use后端详情动作，
//    这里只剩排版；J-PILOT-01：S0 respond_fact 白名单已摘除，无回答卡/问题卡槽）──

function 阶段动作区({
  卡片们,
}: {
  卡片们: readonly 详情动作卡信息[];
}): ReactNode {
  if (卡片们.length === 0) return null; // 无动作（映射交集为空）不渲染动作区
  return (
    <div style={动作区样式}>
      {卡片们.map((卡) => (
        <详情动作卡 key={卡.键} 信息={卡} />
      ))}
    </div>
  );
}

// ── 后端连续详情（J-PILOT-01 Task 5，Spec §6/§8）：pre-Case / retention 封闭的组合 ──
// 复用详情外壳顶栏、两个 Tab、状态区、四阶段流和底栏；pre-Case 状态与四个未到达阶段
// 只作展示（不提交为业务 state），失败动作复用 详情动作卡 与原按钮样式，归档走现有
// 确认层。无 Case 动作/PDF hooks 可挂（retry/archive 的控制归父控制 hook）。

export function 后端连续详情({
  资源,
  当前Tab,
  切Tab,
}: {
  资源: 后端连续资源;
  当前Tab: 详情Tab;
  切Tab: (tab: 详情Tab) => void;
}) {
  const { 返回 } = use导航();
  return (
    <详情外壳
      信息={资源.顶栏}
      返回={返回}
      当前Tab={当前Tab}
      切Tab={切Tab}
      进度={
        <>
          {/* 刷新失败：旧记录状态原样保留只读，错误单独一行交代 + 重试（§10.3） */}
          {资源.刷新错误 !== null ? (
            <div className={样式.错误行}>
              {资源.刷新错误}
              <button className={`${样式.重试键} 可点`} onClick={资源.重试}>
                重试
              </button>
            </div>
          ) : null}

          {/* 状态区：phase/失败/拒绝权威投影；轮次缺失（无轮次不造 0/3） */}
          <详情状态区 信息={资源.状态} />

          {/* 公开信息初评：pre-Case 也放现有总结托盘（与 Case 分支同槽） */}
          {资源.公开初评 !== null ? <公开初评托盘 视图={资源.公开初评} /> : null}

          {/* 失败初评的恢复动作（Spec §8）：重试/归档仅权威允许时在场，复用原动作卡 */}
          {资源.失败动作卡 !== null ? <详情动作卡 信息={资源.失败动作卡} /> : null}

          {/* 四阶段流：均未到达（灰分节条），无对话/附件/PDF 入口 */}
          <阶段对话流 分段们={资源.分段们} />
        </>
      }
      资料={
        // 第二 Tab 延续现有字段缺失与权限说明：negotiation.job 只给实际字段，不补
        // 完整 JD/公司/在线简历（Spec §6）
        <职位资料
          信息={资源.职位资料}
          公司详情={{
            键: '公司详情',
            文案: '公司详情',
            外观: '次要',
            禁用说明: '公司详情暂不可用',
            执行: null,
          }}
        />
      }
      底栏={<详情底栏 信息={资源.底栏} />}
      弹层={
        // 归档二次确认（现有确认层）：「移入历史，不是取消」；取消/遮罩/Esc 零请求
        资源.归档确认 !== null ? <确认层 {...资源.归档确认} /> : null
      }
    />
  );
}
