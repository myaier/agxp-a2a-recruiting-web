// D14 企业问AI代理 · 从企业主壳的「问AI代理」横幅进入。
// 同构镜像求职端 A27 问AI代理：结构与像素值一致，只换数据源与文案视角。
//
// 屏幕结构（自上而下）：
//   返回栏（标题 + 右侧 ⋯）→ 对话流（第一条是今日简报卡）→ 快捷问句胶囊行 → 真输入条
//
// 与求职端的差异只有两处：
//   · 简报卡在统计条下方多一块「人才漏斗」：五档横条（宽度=数据宽度%，橄榄渐变到淡绿）
//   · 关键词回复规则表换成招聘方口径（漏斗 / 触达 / 带宽 / A-01 到岗）
// 简报卡里的「要不要放宽薪资带？」与求职端的「要不要松一档？」同构，落点理由见 简报气泡 上方注释。

import { useEffect, useRef, useState } from 'react';
import 样式 from './企业问AI代理.module.css';
import { 次级页外壳, 返回栏, 真输入条 } from '../组件/通用';
import 代理标 from '../组件/代理标';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { use应用状态 } from '../状态/应用状态';
import { 轻提示 } from '../组件/轻提示';
import { 人才漏斗, 企业日报, 企业代理对话初始, 企业快捷问句 } from '../数据/企业端模拟数据';
import type { 代理对话条, 漏斗档 } from '../数据/类型';

// 漏斗里唯一可点的一档：点「硬性匹配」进本周初筛记录，看代理这一周按哪几条硬性筛的、
// 挡掉的是谁。其余四档本轮还没有对应的落地屏，保持不可点（不做假入口）。
const 可点漏斗档 = '硬性匹配';

// 关键词 → mock 回复（招聘方口径）。原型不接后端，用规则表模拟代理应答；
// 顺序即优先级：先命中的先返回，最后一条是兜底。
// 双盲约束：回复里只出现匿名昵称（陈屿 / 江叙白），绝不出现真名；薪资只答「有无交集」，不给数值。
function 生成回复(问题: string): string {
  if (问题.includes('漏斗') || 问题.includes('进展'))
    return '本周漏斗：触达 23 → 硬性匹配 12 → 在谈 5 → 深谈 2 → 意向达成 1。转化卡在硬性匹配这档，主栈放宽半档能多进 4 人，要不要试两周？';
  if (问题.includes('触达') || 问题.includes('再找'))
    return '好，按现有硬性五项再去触达 10 个对口的，两天内给你首批画像。硬性不符的我直接挡掉，不拿来烦你。';
  if (问题.includes('带宽') || 问题.includes('薪资'))
    return '带宽内有交集的还有 3 位：江叙白 / 周砚秋 / 许临风。按双盲规矩我只核「有无交集」，拿不到对方数值，也不会把咱们的带外余量透出去。';
  if (问题.includes('陈屿') || 问题.includes('到岗'))
    return '对方代理明确 45 天到岗是硬线（现职交接），其余条件全部一致。匹配分 94 半年内只出现过 2 次，我的建议是接受，等你拍板。';
  return '收到。我按这个口径继续筛、继续谈；碰到规则之外的卡点会先来问你，不会替你拍板。';
}

export default function 企业问AI代理() {
  const { 返回, 跳转 } = use导航();
  const { 状态, 派发, 数据源模式 } = use应用状态();

  // 「放宽薪资带」= 把这条放宽写成一条真规则，再跳AI代理设置让招聘方当场看到结果。
  // 这套动作原本长在已删除的 候选未通过 屏上，逻辑一行未改，只是换了触发它的地方。
  // P6 模式边界：写规则归 企业代理设置（canonical）。Mock 保留原型动作；Backend 不在本屏
  // 落规则、也不跳设置页冒充已生效，只给一条中性提示，规则的确认与添加一律回AI代理设置做。
  const 放宽薪资带 = () => {
    if (数据源模式 === 'mock') {
      派发({
        型: '企业新增规则',
        内容: 企业日报.松一档.规则内容,
        来源: 企业日报.松一档.规则来源,
      });
      跳转(路径.企业代理设置);
    } else {
      轻提示('请到AI代理设置确认并添加长期规则');
    }
  };

  const [对话, 设对话] = useState<代理对话条[]>(企业代理对话初始);
  const [草稿, 设草稿] = useState('');
  // 对话流容器：需要拿原生 DOM 节点手动滚到底，所以用 div.滚动区 而不是 <滚动区> 组件
  const 滚动引用 = useRef<HTMLDivElement>(null);

  // 对话每变一次就滚到底部（含代理 550ms 后追加的那条），保证新消息始终可见
  useEffect(() => {
    const 容器 = 滚动引用.current;
    if (!容器) return;
    容器.scrollTo({ top: 容器.scrollHeight, behavior: 'smooth' });
  }, [对话]);

  // 发送：不带参数发草稿（输入框），带参数发快捷问句
  const 发送 = (文本?: string) => {
    const 内容 = (文本 ?? 草稿).trim();
    if (!内容) return;
    // 用时刻做编号：我方那条用 时刻，代理回复用 时刻+1，保证两条 key 不撞
    const 时刻 = Date.now();
    设对话((旧) => [...旧, { 编号: 时刻, 角色: '我', 内容 }]);
    设草稿('');
    setTimeout(() => {
      设对话((旧) => [...旧, { 编号: 时刻 + 1, 角色: '代理', 内容: 生成回复(内容) }]);
    }, 550);
  };

  return (
    <次级页外壳 对话底 白底> {/* 2026-08-24 全站去框（产品负责人批）：页底转纯白，与私聊三屏一致 */}
      <返回栏 返回={返回} 标题="我的招聘AI代理" 右侧={<button className={`${样式.更多} 可点`} onClick={() => 跳转(路径.企业代理详情)}>⋯</button>} />

      {/* 对话流：屏幕内唯一滚动区 */}
      <div ref={滚动引用} className={`${样式.对话流} 滚动区`}>
        <div className={样式.对话内容}>
          {对话.map((条) => {
            if (条.角色 === '简报')
              return (
                <简报气泡
                  key={条.编号}
                  打开初筛记录={() => 跳转(路径.初筛记录)}
                  放宽薪资带={放宽薪资带}
                />
              );
            if (条.角色 === '我')
              return (
                <div key={条.编号} className={样式.我行}>
                  <div className={`${样式.我气泡} ${样式.气泡文字}`}>{条.内容}</div>
                  {/* 我方头像（标注 23:52）：与左侧代理头像对称 */}
                  <span className={样式.我头像}>
                    {状态.招聘头像 ? (
                      <img
                        src={状态.招聘头像}
                        alt=""
                        style={{ width: '100%', height: '100%', objectFit: 'cover' }}
                      />
                    ) : (
                      状态.企业认证.姓名.charAt(0)
                    )}
                  </span>
                </div>
              );
            return <代理气泡 key={条.编号} 内容={条.内容 ?? ''} />;
          })}
        </div>
      </div>

      {/* 快捷问句：点一下等于直接把这句话发出去 */}
      <div className={样式.快捷行}>
        {企业快捷问句.map((句) => (
          <button key={句} className={`${样式.快捷键} 可点`} onClick={() => 发送(句)}>
            {句}
          </button>
        ))}
      </div>

      <真输入条
        占位="让AI代理找人、触达，或问漏斗…"
        值={草稿}
        改变={设草稿}
        发送={() => 发送()}
      />
    </次级页外壳>
  );
}

// ── 代理气泡：左侧代理标头像（与主页横幅同款，无圆底）+ 左上角切平的白气泡 ──
function 代理气泡({ 内容 }: { 内容: string }) {
  return (
    <div className={样式.代理行}>
      <span className={样式.小盾牌}>
        <代理标 尺寸={30} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
      </span>
      <div className={`${样式.代理气泡} ${样式.气泡文字}`}>{内容}</div>
    </div>
  );
}

// ── 今日简报：每天 09:00 / 18:00 各更新一次，套在代理气泡里当第一条消息 ──
// 「需要你」那个统计数用 --意向（红）标出来，让待决策项在一屏内最先被看到。
// 企业侧比求职端多一块人才漏斗：统计条下方五档横条，一眼看清转化卡在哪一档。
//
// 「要不要放宽薪资带？」放在简报卡**内部**（正文与脚注之间），而不是紧随其后另起一张卡，
// 三个理由：
//   1. 它和统计条、漏斗同源 —— 都是代理这一周替你盘出来的数，同一份汇报拆成两张卡会让人
//      以为是两次不同的汇报；
//   2. 对话流里另起一张卡就得给 代理对话条 加一个新角色，等于在 IM 流里插一条不是消息的
//      东西，简报本来就是这条流里唯一的「卡片附件」，不该有第二个；
//   3. 这张卡里本来就有可点的漏斗行（硬性匹配 → 初筛记录），卡内放可操作元素是这屏定好的
//      做法，与求职端保持一致。
// 位置选在正文之后、脚注之前：脚注讲的是整张简报的更新节奏，是收尾行，
// 动作卡压在它后面会让人误以为「每天 09:00 更新」说的是这条建议。
function 简报气泡({
  打开初筛记录,
  放宽薪资带,
}: {
  打开初筛记录: () => void;
  放宽薪资带: () => void;
}) {
  // 「维持红线」不改任何规则，只把这条建议标记为已处理，避免点了没反应
  const [已维持红线, 设已维持红线] = useState(false);

  return (
    <div className={样式.代理行}>
      <span className={样式.小盾牌}>
        <代理标 尺寸={30} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
      </span>
      <div className={样式.代理气泡}>
        <div className={样式.简报头}>
          <span className={样式.简报标题}>今日简报</span>
          <span className={样式.简报时间}>09:00 更新</span>
        </div>

        {/* 四个统计数横条 */}
        <div className={样式.统计条}>
          {企业日报.统计.map((项) => (
            <div key={项.名称} className={样式.统计项}>
              <div
                className={`${样式.统计数} ${项.强调 ? 样式.统计数强调 : ''} 等宽数字`}
              >
                {项.数值}
              </div>
              <div className={样式.统计名}>{项.名称}</div>
            </div>
          ))}
        </div>

        {/* 人才漏斗：五档，横条宽度直接取数据里的 宽度%，人数右对齐等宽。
            只有「硬性匹配」那一档整行可点（落到本周初筛记录），所以它渲染成 <button>，
            其余四档没有落地屏、保持 <div> 不可点 —— 元素类型本身就是「能不能点」的语义，
            不额外加「查看详情 ›」这类提示文案。 */}
        <div className={样式.漏斗块}>
          {人才漏斗.map((档) =>
            档.名称 === 可点漏斗档 ? (
              <button
                key={档.名称}
                type="button"
                className={`${样式.漏斗行} ${样式.漏斗行可点} 可点`}
                // 行内可见的只有「硬性匹配」和人数，读屏得自己补上落到哪一屏，
                // 否则听到的是一个不知道通向何处的按钮
                aria-label={`${档.名称} ${档.人数}，打开本周初筛记录`}
                onClick={打开初筛记录}
              >
                <漏斗行内容 档={档} />
              </button>
            ) : (
              <div key={档.名称} className={样式.漏斗行}>
                <漏斗行内容 档={档} />
              </div>
            ),
          )}
        </div>

        <div className={样式.简报正文}>
          {企业日报.正文前}
          <b className={样式.简报强调}>{企业日报.正文强调}</b>
          {企业日报.正文后}
        </div>

        {/* 绿色建议卡：把「这条红线卡掉了多少候选」量化出来，再给两个动作 */}
        <div className={样式.松一档卡}>
          <div className={样式.松一档标题}>{企业日报.松一档.标题}</div>
          <div className={样式.松一档正文}>
            {企业日报.松一档.正文前}
            <b className={样式.松一档强调}>{企业日报.松一档.数值1}</b>
            {企业日报.松一档.正文中}
            <b className={样式.松一档强调}>{企业日报.松一档.数值2}</b>
            {企业日报.松一档.正文后}
          </div>

          {已维持红线 ? (
            <div className={样式.已维持}>已维持红线 · 规则不变，我会继续替你挡掉这类候选。</div>
          ) : (
            <div className={样式.按钮行}>
              <button className={`${样式.次按钮} 可点`} onClick={() => 设已维持红线(true)}>
                维持红线
              </button>
              <button className={`${样式.主按钮} 可点`} onClick={放宽薪资带}>
                放宽薪资带
              </button>
            </div>
          )}
        </div>

        <div className={样式.简报脚注}>{企业日报.脚注}</div>
      </div>
    </div>
  );
}

// 一行漏斗的内容：档名 + 横条 + 人数。可点那行与不可点那四行共用同一份，
// 保证两种外层元素下版式一模一样。
// 全部用 <span>：可点那行的外层是 <button>，而 button 的内容模型只允许短语内容，
// <div> 嵌在里面是不合法的 HTML。槽与条在 CSS 里显式 display:block 补回块级尺寸。
function 漏斗行内容({ 档 }: { 档: 漏斗档 }) {
  return (
    <>
      <span className={`${样式.漏斗名} 单行`}>{档.名称}</span>
      <span className={样式.漏斗槽}>
        <span className={样式.漏斗条} style={{ width: `${档.宽度}%` }} />
      </span>
      <span className={`${样式.漏斗数} 等宽数字`}>{档.人数}</span>
    </>
  );
}
