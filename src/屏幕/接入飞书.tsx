// 接入工作台 —— 注册流最后一屏（用户 2026-08-20：注册最后能绑飞书也能跳过；
// 之后还会支持其他渠道；有代理的用户也可以扫我的码把我的代理加进去，所以要能切换）。
//
// 两个维度：
//   · 渠道 —— 飞书先上线，企业微信 / 钉钉 / Slack 占位（点了给轻提示，不做死按钮）；
//   · 方式 —— 用户按自己的需求二选一（用户 2026-08-20）：
//       「绑定我的代理」= 我的代理码，用飞书扫它，代理就进飞书；
//       「扫码接入代理」= 反方向，扫飞书里已有 agent 的码，把它接进来。
// 两端共用：求职端走完添加头像到这里，企业端发完第一个岗位到这里。

import { useState } from 'react';
import 样式 from './接入飞书.module.css';
import { 次级页外壳, 主按钮 } from '../组件/通用';
import 接入二维码 from '../组件/接入二维码';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';

type 渠道键 = '飞书' | '企业微信' | '钉钉' | 'Slack';

/** 渠道清单：可用的排前面，未上线的灰着但仍可见 —— 让用户知道后面还会有 */
const 渠道们: { 键: 渠道键; 名: string; 色: string; 可用: boolean }[] = [
  { 键: '飞书', 名: '飞书', 色: '#2f7de1', 可用: true },
  { 键: '企业微信', 名: '企业微信', 色: '#2ba471', 可用: false },
  { 键: '钉钉', 名: '钉钉', 色: '#2b7de0', 可用: false },
  { 键: 'Slack', 名: 'Slack', 色: '#7b4fc0', 可用: false },
];

type 方式键 = '绑定' | '扫码';

export default function 接入飞书({ 企业端 = false }: { 企业端?: boolean }) {
  const { 进主壳, 进企业主壳 } = use导航();
  const { 状态, 派发 } = use应用状态();
  const [渠道, 设渠道] = useState<渠道键>('飞书');
  const [方式, 设方式] = useState<方式键>('绑定');

  const 已接入 = 企业端 ? 状态.企业飞书已接入 : 状态.飞书已接入;
  const 我的名 = 企业端 ? 状态.企业认证.姓名 : 状态.基本信息.真名;
  const 完成 = () => (企业端 ? 进企业主壳() : 进主壳());

  const 绑定 = () => {
    派发(企业端 ? { 型: '设企业飞书接入', 接入: true } : { 型: '设飞书接入', 接入: true });
    轻提示(`已接入${渠道}`);
    完成();
  };

  return (
    <次级页外壳>
      <div className={样式.页}>
        <h1 className={样式.标题}>把AI代理接到你的工作台</h1>
        <p className={样式.副题}>接入后不用打开 App，在工作台里就能收提醒、下指令</p>

        {/* 渠道选择：一行圆角图标，未上线的降透明度 */}
        <div className={样式.渠道行}>
          {渠道们.map((条) => {
            const 选中 = 渠道 === 条.键;
            return (
              <button
                key={条.键}
                className={`${样式.渠道} ${选中 ? 样式.渠道选中 : ''} ${条.可用 ? '' : 样式.渠道未开} 可点`}
                onClick={() =>
                  条.可用 ? 设渠道(条.键) : 轻提示(`${条.名}接入即将上线`)
                }
              >
                <span className={样式.渠道标} style={{ background: 条.色 }}>
                  {条.名.charAt(0)}
                </span>
                <span className={样式.渠道名}>{条.名}</span>
              </button>
            );
          })}
        </div>

        {/* 方式切换：接入我的工作台 / 分享我的代理 */}
        <div className={样式.分段}>
          {(['绑定', '扫码'] as 方式键[]).map((键) => (
            <button
              key={键}
              className={`${样式.分段项} ${方式 === 键 ? 样式.分段项选中 : ''} 可点`}
              onClick={() => 设方式(键)}
            >
              {键 === '绑定' ? '绑定我的代理' : '扫码接入代理'}
            </button>
          ))}
        </div>

        {/* 绑定 = 出示我的代理码；扫码 = 反方向，去扫对方 agent 的码 */}
        {方式 === '绑定' ? (
          <div className={样式.码卡}>
            <div className={样式.码框}>
              <接入二维码 边长={150} />
            </div>
            <div className={样式.码说明}>
              用{渠道}扫这张码，{我的名}的AI代理就出现在你的{渠道}里
            </div>
          </div>
        ) : (
          <div className={样式.码卡}>
            <button
              className={`${样式.取景框} 可点`}
              onClick={() => 轻提示('原型演示：已识别到一个代理')}
              aria-label="打开相机扫码"
            >
              <span className={`${样式.取景角} ${样式.角左上}`} />
              <span className={`${样式.取景角} ${样式.角右上}`} />
              <span className={`${样式.取景角} ${样式.角左下}`} />
              <span className={`${样式.取景角} ${样式.角右下}`} />
              <span className={样式.取景线} />
            </button>
            <div className={样式.码说明}>
              扫{渠道}里那个 agent 的二维码，把它接到这边一起谈
            </div>
          </div>
        )}

        <div className={样式.撑开} />

        <主按钮
          文字={已接入 ? `已接入${渠道} · 继续` : '完成绑定'}
          按下={已接入 ? 完成 : 绑定}
        />

        <button className={`${样式.跳过} 可点`} onClick={完成}>
          暂时跳过
        </button>
      </div>
    </次级页外壳>
  );
}
