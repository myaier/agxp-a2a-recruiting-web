// 接入飞书 —— 注册流的最后一屏（用户 2026-08-20：注册最后应该能绑飞书，也能跳过，
// 让用户知道飞书里也能收到消息、直接和 AI 代理说话）。
//
// 两端共用：求职端走完「添加头像」到这里，企业端发完第一个岗位到这里。
// 绑定态各自独立（飞书已接入 / 企业飞书已接入），与「我的 AI 代理」详情页读同一份状态。

import 样式 from './接入飞书.module.css';
import { 次级页外壳, 页面大标题, 主按钮 } from '../组件/通用';
import 接入二维码 from '../组件/接入二维码';
import 代理标 from '../组件/代理标';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';

/** 接入后能做的三件事：都是「不用打开 App」的场景，这才是绑定的理由 */
const 接入后能做 = [
  '需要你拍板时，直接在飞书里收到提醒',
  '在飞书里对代理说话，给它新的要求',
  '随时问一句进展，它把当前所有单的状态报给你',
];

export default function 接入飞书({ 企业端 = false }: { 企业端?: boolean }) {
  const { 进主壳, 进企业主壳 } = use导航();
  const { 状态, 派发 } = use应用状态();

  const 已接入 = 企业端 ? 状态.企业飞书已接入 : 状态.飞书已接入;
  const 完成 = () => (企业端 ? 进企业主壳() : 进主壳());

  const 绑定 = () => {
    派发(企业端 ? { 型: '设企业飞书接入', 接入: true } : { 型: '设飞书接入', 接入: true });
    轻提示('已接入飞书');
    完成();
  };

  return (
    <次级页外壳>
      <div className={样式.页}>
        <页面大标题 标题="在飞书里也能指挥你的AI代理" />

        <div className={样式.码卡}>
          <div className={样式.码框}>
            <接入二维码 边长={168} />
          </div>
          <div className={样式.码注}>用飞书扫一扫 · 有效期 5 分钟</div>
        </div>

        <div className={样式.能做卡}>
          {接入后能做.map((条) => (
            <div key={条} className={样式.能做行}>
              <span className={样式.能做标}>
                <代理标 尺寸={15} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} 带点={false} />
              </span>
              <span className={样式.能做文}>{条}</span>
            </div>
          ))}
        </div>

        <div className={样式.撑开} />

        <主按钮 文字={已接入 ? '已接入 · 继续' : '我已扫码'} 按下={已接入 ? 完成 : 绑定} />

        <button className={`${样式.跳过} 可点`} onClick={完成}>
          暂时跳过
        </button>
      </div>
    </次级页外壳>
  );
}
