// A21 添加求职意向（表单）
//
// 结构：返回栏 → 大标题 + 说明 → 求职类型单选行 → 六个表单条目 → 尾注 → 主按钮。
//
// 关键口径：「本意向底线」永远挂「仅AI代理可见 · 触线即拒」徽标 ——
// 底线只有 AI 代理知道，对企业方永不披露，徽标是这条边界在 UI 上的唯一提示。
//
// 交互：六个条目点开会从底部升起一个编辑抽屉（RN 的 Modal → DOM 固定定位覆盖层），
// 输入后回填到表单本地状态，让原型能被真的当表单来点。

import { useState } from 'react';
import 样式 from './添加意向.module.css';
import {
  次级页外壳,
  返回栏,
  页面大标题,
  滚动区,
  表单条目,
  单选点,
  主按钮,
  通用样式,
} from '../组件/通用';
import { use导航 } from '../路由/导航钩子';

/** 表单里可编辑的六个字段 */
type 表单键 = '工作城市' | '期望职位' | '其他感兴趣城市' | '期望薪资' | '本意向底线' | '期望行业';

/** 字段表：标签文案与徽标都在这里，渲染时直接 map，避免六段重复 JSX */
const 表单字段表: { 键: 表单键; 标签: string; 徽标?: string }[] = [
  { 键: '工作城市', 标签: '工作城市' },
  { 键: '期望职位', 标签: '期望职位' },
  { 键: '其他感兴趣城市', 标签: '其他感兴趣城市（1/9）' },
  { 键: '期望薪资', 标签: '期望薪资' },
  { 键: '本意向底线', 标签: '本意向底线', 徽标: '仅AI代理可见 · 触线即拒' },
  { 键: '期望行业', 标签: '期望行业' },
];

/** 表单初值（设计稿 A21 里填的示例值） */
const 表单初值: Record<表单键, string> = {
  工作城市: '杭州',
  期望职位: '平台架构 · 基础平台',
  其他感兴趣城市: '上海',
  期望薪资: '55K · 15 薪',
  本意向底线: '52K · 15 薪',
  期望行业: '金融科技 · 基础软件',
};

export default function 添加意向() {
  const { 返回 } = use导航();

  // 求职类型：全职 / 顾问·兼职 二选一
  const [全职, 设全职] = useState(true);
  const [表单值, 设表单值] = useState<Record<表单键, string>>(表单初值);
  // 正在编辑哪个字段（null = 抽屉关着）
  const [编辑中, 设编辑中] = useState<表单键 | null>(null);
  // 抽屉里的草稿值，确认前不写回表单，取消就丢掉
  const [草稿, 设草稿] = useState('');

  const 编辑中字段 = 表单字段表.find((字段) => 字段.键 === 编辑中);

  // 打开抽屉时把现值灌进草稿，用户看到的是「改」而不是「重填」
  function 打开编辑(键: 表单键) {
    设编辑中(键);
    设草稿(表单值[键]);
  }

  // 确认：空白视作没改（不允许把字段清空成空串，否则表单条目会塌成空行）
  function 确认编辑() {
    if (编辑中 === null) return;
    const 新值 = 草稿.trim();
    if (新值) 设表单值((旧) => ({ ...旧, [编辑中]: 新值 }));
    设编辑中(null);
  }

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题
        标题="添加求职意向"
        说明="意向不同，AI代理的初筛口径与谈判授权也不同。"
      />

      <滚动区 样式覆盖={{ padding: '6px 22px 0' }}>
        {/* ── 求职类型：两个单选点 ── */}
        <div className={样式.类型行}>
          <span className={样式.类型标}>求职类型</span>
          <div className={样式.类型组}>
            <button className={`${样式.类型选项} 可点`} onClick={() => 设全职(true)}>
              <单选点 选中={全职} 尺寸={18} />
              <span className={全职 ? 样式.类型文字选中 : 样式.类型文字}>全职</span>
            </button>
            <button className={`${样式.类型选项} 可点`} onClick={() => 设全职(false)}>
              <单选点 选中={!全职} 尺寸={18} />
              <span className={!全职 ? 样式.类型文字选中 : 样式.类型文字}>顾问 / 兼职</span>
            </button>
          </div>
        </div>

        {/* ── 六个表单条目 ── */}
        {表单字段表.map((字段) => (
          <表单条目
            key={字段.键}
            标签={字段.标签}
            徽标={字段.徽标}
            值={表单值[字段.键]}
            按下={() => 打开编辑(字段.键)}
          />
        ))}
      </滚动区>

      <主按钮 文字="保存 · AI代理开始初筛" 按下={返回} />

      {/* ── 编辑抽屉：点遮罩或确认都关掉 ── */}
      {编辑中字段 ? (
        <>
          <div className={样式.遮罩} onClick={() => 设编辑中(null)} />
          <div className={样式.抽屉}>
            <div className={样式.抽屉头}>
              <span className={样式.抽屉标题}>{编辑中字段.标签}</span>
              {编辑中字段.徽标 ? (
                <span className={通用样式.小徽标}>{编辑中字段.徽标}</span>
              ) : null}
            </div>
            <input
              className={样式.抽屉输入}
              value={草稿}
              autoFocus
              onChange={(事件) => 设草稿(事件.target.value)}
              onKeyDown={(事件) => {
                if (事件.key === 'Enter') 确认编辑();
              }}
              enterKeyHint="done"
            />
            <主按钮 文字="确定" 按下={确认编辑} />
          </div>
        </>
      ) : null}
    </次级页外壳>
  );
}
