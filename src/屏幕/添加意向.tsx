// A21 添加求职意向（表单）
//
// 结构：返回栏 → 大标题 + 说明 → 求职类型单选行 → 六个表单条目 → 尾注 → 主按钮。
//
// 关键口径：「本意向底线」永远挂「仅AI代理可见 · 触线即拒」徽标 ——
// 底线只有 AI 代理知道，对企业方永不披露，徽标是这条边界在 UI 上的唯一提示。
//
// 交互：六个条目点开会从底部升起一个编辑抽屉（RN 的 Modal → DOM 固定定位覆盖层），
// 输入后回填到表单本地状态，让原型能被真的当表单来点。

import { useState } from 'react';
import { useParams } from 'react-router-dom';
import 样式 from './添加意向.module.css';
import {
  次级页外壳,
  返回栏,
  页面大标题,
  滚动区,
  主按钮,
  通用样式,
} from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import 弹层框架 from '../组件/弹层框架';
import { use应用状态 } from '../状态/应用状态';

/** 表单里可编辑的六个字段 */
type 表单键 = '工作城市' | '期望职位' | '其他感兴趣城市' | '期望薪资' | '本意向底线' | '期望行业';

/** 字段表：标签文案与徽标都在这里，渲染时直接 map，避免六段重复 JSX */
const 表单字段表: { 键: 表单键; 标签: string; 徽标?: string }[] = [
  { 键: '工作城市', 标签: '工作城市' },
  { 键: '期望职位', 标签: '期望职位' },
  { 键: '其他感兴趣城市', 标签: '其他感兴趣城市（1/9）' },
  { 键: '期望薪资', 标签: '期望薪资' },
  { 键: '本意向底线', 标签: '本意向底线', 徽标: '仅AI代理可见 · 触线即拒' },
  { 键: '期望行业', 标签: '期望行业' },
];

/** 表单初值（设计稿 A21 里填的示例值） */
const 表单初值: Record<表单键, string> = {
  工作城市: '杭州',
  期望职位: '平台架构 · 基础平台',
  其他感兴趣城市: '上海',
  期望薪资: '55K · 15 薪',
  本意向底线: '52K · 15 薪',
  期望行业: '金融科技 · 基础软件',
};

/** 句子里可点的填空词元：有值显示值，空值显示浅色占位；主词元用于期望职位 */
function 词元({
  值,
  按下,
  主 = false,
  小 = false,
}: {
  值: string;
  按下: () => void;
  主?: boolean;
  小?: boolean;
}) {
  return (
    <button
      className={`${样式.词元} ${主 ? 样式.词元主 : ''} ${小 ? 样式.词元小 : ''} 可点`}
      onClick={按下}
    >
      {值 || '未填'}
    </button>
  );
}

export default function 添加意向() {
  const { id: 路由编号 } = useParams<{ id: string }>();
  const { 返回 } = use导航();
  const { 状态, 派发 } = use应用状态();

  // 编辑态：URL 带编号且能在意向表里找到（标注 11:08：原来点行直接跳走，没法改也没法删）
  const 编辑目标 = 路由编号
    ? 状态.求职意向表.find((条) => 条.编号 === 路由编号) ?? null
    : null;
  const 编辑态 = 编辑目标 !== null;

  // 求职类型：全职 / 顾问·兼职 二选一
  const [全职, 设全职] = useState(true);
  // 编辑态用已存的意向拆回表单：标题「[上海] 后端工程师」→ 城市 + 职位；
  // 说明「58K · 15 薪｜金融基建优先｜在谈 5」→ 薪资 + 行业
  const [表单值, 设表单值] = useState<Record<表单键, string>>(() => {
    if (!编辑目标) return 表单初值;
    const 命中 = /^\[([^\]]+)\]\s*(.+)$/.exec(编辑目标.标题);
    const 段 = 编辑目标.说明.split('｜');
    return {
      ...表单初值,
      工作城市: 命中?.[1] ?? 表单初值.工作城市,
      期望职位: 命中?.[2] ?? 编辑目标.标题,
      期望薪资: 段[0]?.trim() || 表单初值.期望薪资,
      期望行业: 段[1]?.trim() || 表单初值.期望行业,
    };
  });
  // 正在编辑哪个字段（null = 抽屉关着）
  const [编辑中, 设编辑中] = useState<表单键 | null>(null);
  // 抽屉里的草稿值，确认前不写回表单，取消就丢掉
  const [草稿, 设草稿] = useState('');

  const 编辑中字段 = 表单字段表.find((字段) => 字段.键 === 编辑中);

  // 打开抽屉时把现值灌进草稿，用户看到的是「改」而不是「重填」
  function 打开编辑(键: 表单键) {
    设编辑中(键);
    设草稿(表单值[键]);
  }

  // 保存：表单拼回意向表的「标题 + 说明」两个字段
  function 提交() {
    const 标题 = `[${表单值.工作城市}] ${表单值.期望职位}`;
    const 说明 = `${表单值.期望薪资}｜${表单值.期望行业}`;
    if (编辑目标) 派发({ 型: '改意向', 编号: 编辑目标.编号, 标题, 说明 });
    else 派发({ 型: '新增意向', 标题, 说明 });
    返回();
  }

  // 确认：空白视作没改（不允许把字段清空成空串，否则表单条目会塌成空行）
  function 确认编辑() {
    if (编辑中 === null) return;
    const 新值 = 草稿.trim();
    if (新值) 设表单值((旧) => ({ ...旧, [编辑中]: 新值 }));
    设编辑中(null);
  }

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题 标题={编辑态 ? '编辑求职意向' : '添加求职意向'} />

      <滚动区 样式覆盖={{ padding: '2px 22px 0' }}>
        {/* ── 极简重构（2026-08-19 用户定）：不再是七行 label + value 的清单，
               整份意向写成一句话，可填的部分是词元（点开编辑抽屉改）。
               用户读一遍就知道自己配置了什么；也贴合「把要求讲给代理听」这个心智。 ── */}
        <div className={样式.句块}>
          <span className={样式.连接词}>我在</span>
          <词元 值={表单值.工作城市} 按下={() => 打开编辑('工作城市')} />
          <span className={样式.连接词}>找</span>
          <br />
          <词元 主 值={表单值.期望职位} 按下={() => 打开编辑('期望职位')} />
        </div>

        {/* 次级三项：同一行内联，不各占一行 */}
        <div className={样式.次句块}>
          <span className={样式.连接词小}>期望</span>
          <词元 小 值={表单值.期望薪资} 按下={() => 打开编辑('期望薪资')} />
          <span className={样式.连接词小}>行业</span>
          <词元 小 值={表单值.期望行业} 按下={() => 打开编辑('期望行业')} />
          <span className={样式.连接词小}>也看</span>
          <词元 小 值={表单值.其他感兴趣城市} 按下={() => 打开编辑('其他感兴趣城市')} />
        </div>

        {/* 底线单独成卡：这是全表唯一「只有代理知道」的字段，
            排进清单里会被当成第五行普通条目，拎出来才对得上它的分量 */}
        <button className={`${样式.底线卡} 可点`} onClick={() => 打开编辑('本意向底线')}>
          <div className={样式.底线头}>
            <span className={样式.底线标}>本意向底线</span>
            <span className={通用样式.小徽标}>仅AI代理可见 · 触线即拒</span>
          </div>
          <div className={样式.底线值}>{表单值.本意向底线}</div>
        </button>

        {/* 求职类型：分段切换收到最后，它最少被改 */}
        <div className={样式.类型段}>
          {[true, false].map((是全职) => (
            <button
              key={String(是全职)}
              className={`${样式.类型片} ${全职 === 是全职 ? 样式.类型片选中 : ''} 可点`}
              onClick={() => 设全职(是全职)}
            >
              {是全职 ? '全职' : '顾问 / 兼职'}
            </button>
          ))}
        </div>
      </滚动区>

      {/* 编辑态底部是「删除 + 保存」两键（对照截图）；新建态只有保存 */}
      {编辑态 ? (
        <div className={样式.底键行}>
          <button
            className={`${样式.删除键} 可点`}
            onClick={() => {
              派发({ 型: '删意向', 编号: 编辑目标!.编号 });
              返回();
            }}
          >
            删除
          </button>
          <button className={`${样式.保存键} 可点`} onClick={提交}>
            保存
          </button>
        </div>
      ) : (
        <主按钮 文字="保存 · AI代理开始初筛" 按下={提交} />
      )}

      {/* ── 编辑抽屉：点遮罩或确认都关掉 ── */}
      {编辑中字段 ? (
        <弹层框架 标签={`编辑${编辑中字段.标签}`} 遮罩类名={样式.遮罩} 面板类名={样式.抽屉} 关闭={() => 设编辑中(null)}>
            <div className={样式.抽屉头}>
              <span className={样式.抽屉标题}>{编辑中字段.标签}</span>
              {编辑中字段.徽标 ? (
                <span className={通用样式.小徽标}>{编辑中字段.徽标}</span>
              ) : null}
            </div>
            <input
              className={样式.抽屉输入}
              value={草稿}
              autoFocus
              onChange={(事件) => 设草稿(事件.target.value)}
              onKeyDown={(事件) => {
                if (事件.key === 'Enter') 确认编辑();
              }}
              enterKeyHint="done"
            />
            <主按钮 文字="确定" 按下={确认编辑} />
        </弹层框架>
      ) : null}
    </次级页外壳>
  );
}
