// 添加 / 编辑求职期望（/intentions/new，编辑态 /intentions/:id）——
// 2026-08-21 按用户截图重写：推翻 08-19 的「一句话填空词元」版，回到朴素的 label + 值 清单表单。
//
// 版式（见 docs/design/添加求职期望规格.md「主屏」一节）自上而下：
//   返回栏 ‹（无标题、无右键）→ 大标题 + 副标题 → 六行条目 → 底部固定按钮。
//   每行 = 小字灰 label + 大字值行（未填时灰占位）+ 右侧 ›，行间一条细分隔线；
//   第 1 行「求职类型」例外：行内两个单选圆点右对齐，没有值行也没有 ›。
//
// 数据来源只有一处 —— 全局 意向草稿，不在本页留 useState 副本。
//   工作城市 / 期望职位 / 感兴趣城市 / 期望行业 四项要跳次级页，跳走再回来本页会重新挂载，
//   本地 state 那一份必然被清空；薪资走弹层虽然不跳页，为了不出现两份真相也一样写草稿。
//
// 2026-08-22 产品负责人「本意向底线删掉吧，感觉没啥用」：连同「仅AI代理可见 · 触线即拒」
//   徽标与底线滚轮弹层一起摘掉，表单从七行回到六行。
//   删的只是「期望区间」之外那条更硬的底线字段 —— 薪资区间的下限仍然承担底线作用，
//   代理之间依旧只交换「有没有交集」、不交换数字，双盲机制没有因为这次删除而改变。

import { useEffect, useRef, useState } from 'react';
import { useNavigationType, useParams } from 'react-router-dom';
import 样式 from './添加意向.module.css';
// 2026-08-24 全站选择风格统一（C1 定稿）：求职类型改选钮片后不再用 单选点
import { 次级页外壳, 返回栏, 页面大标题, 滚动区, 主按钮 } from '../组件/通用';
import 薪资区间层 from '../组件/薪资区间层';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import { use应用状态, type 意向草稿型 } from '../状态/应用状态';
import { 轻提示 } from '../组件/轻提示';
import { 取后端错误文案 } from '../数据/HTTP客户端';

/** 感兴趣城市上限（规格：其他感兴趣城市（N/9））。这里只用于渲染 label 里的计数，
 *  真正的选择上限由次级页 选择城市 把关 —— 上限判断放在能拦住点击的那一层才有意义。 */
const 感兴趣城市上限 = 9;

/**
 * 一行表单条目：小字灰 label + 大字值行 + 右侧 ›。
 * 「有值 / 未填」在版式上唯一的区别就是值行的颜色：未填走 .值占位 的灰，
 * 位置、字号、行高都不变，这样六行的基线不会因为填没填而参差。
 */
function 期望行({
  标签,
  值,
  占位,
  按下,
}: {
  标签: string;
  /** 已填的值；空串 = 未填，此时显示 占位 */
  值: string;
  占位: string;
  按下: () => void;
}) {
  const 有值 = 值 !== '';
  return (
    <button type="button" className={`${样式.条目} 可点`} onClick={按下}>
      {/* 标签外面这层 flex 行是版式的一部分：它把小字标签的行高锁在自己的行盒里，
          去掉之后标签会退回按钮那档更大的行高，六行的基线整体往下掉 */}
      <span className={样式.条目标签行}>
        <span className={样式.条目标签}>{标签}</span>
      </span>
      <span className={样式.条目值行}>
        <span className={`${样式.条目值} ${有值 ? '' : 样式.值占位} 单行`}>
          {有值 ? 值 : 占位}
        </span>
        <span className={样式.尖括号}>›</span>
      </span>
    </button>
  );
}

export default function 添加意向() {
  const { id: 路由编号 } = useParams<{ id: string }>();
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发, 操作 } = use应用状态();
  const 导航类型 = useNavigationType();

  const 草稿 = 全局.意向草稿;
  // 编辑态只看 URL 有没有带编号：底部按钮是一键还是两键由它决定，
  // 不依赖草稿里的 编辑编号（草稿要等下面那个 effect 跑完才有值）
  const 编辑态 = 路由编号 !== undefined;

  // 底线弹层删掉之后，本页只剩薪资一个底部弹层，开关用一个布尔就够，不再需要「弹层名」联合类型
  const [薪资层开, 设薪资层开] = useState(false);

  // 办公方式必填校验的可见状态：只在点保存且没选时点亮（aria-invalid + aria-description），
  // 用户点任一办公方式选钮立即熄灭 —— 错误跟着「最后一次校验」走，不常驻。
  // 校验错误不是草稿的一部分，所以不放全局状态，本页局部 state 足够。
  const [办公方式错误, 设办公方式错误] = useState(false);
  const 办公方式组引用 = useRef<HTMLDivElement>(null);

  // 换一条意向（新建 ↔ 编辑互跳）时上一次的错误不该带到新表单上
  useEffect(() => {
    设办公方式错误(false);
  }, [路由编号]);

  // 挂载这一刻草稿装的是哪一条。用 useState 的初值锁住，之后草稿被本页和次级页改也不跟着变 ——
  // 下面那个 effect 要的正是「进来时」的快照，不是「此刻」的值。
  const [挂载时草稿编号] = useState(草稿.编辑编号);

  // 进页面开一份草稿：新建 → 空表；编辑 → 从 求职意向表 里那一条拆回来预填。
  //
  // 坑在这里：本屏跳去次级页（选城市 / 选职位 / 选行业）再 返回() 时会**重新挂载**，
  // 而那一次挂载草稿里正装着用户刚选好的东西，无脑再开一次就全清了（实测：选完城市返回，
  // 工作城市又变回「请选择工作城市」）。所以按导航类型分流：
  //   PUSH / REPLACE = 从意向管理页新进来的一次编辑会话 → 开新草稿；
  //   POP            = 从次级页返回或浏览器后退 → 草稿是自己的，原样留着。
  // 唯一要给 POP 破例的是「直接刷新 /intentions/:id」：那也是 POP，但草稿是空的、
  // 装的不是这一条，不开就永远是空表 —— 所以再加一道「草稿不是本条」的判断。
  useEffect(() => {
    const 草稿不是本条 = 挂载时草稿编号 !== (路由编号 ?? null);
    if (导航类型 !== 'POP' || 草稿不是本条) {
      派发({ 型: '开意向草稿', 编号: 路由编号 ?? null });
    }
  }, [派发, 导航类型, 路由编号, 挂载时草稿编号]);

  /** 本页所有字段改动的单点出口 */
  const 改草稿 = (补丁: Partial<意向草稿型>) => 派发({ 型: '改意向草稿', 补丁 });

  // 薪资回填格式（规格弹层 C）：下限 === 上限 → 「10K」；否则 「10-11K」
  const 薪资文本 =
    草稿.薪资下限 === null || 草稿.薪资上限 === null
      ? ''
      : 草稿.薪资下限 === 草稿.薪资上限
        ? `${草稿.薪资下限}K`
        : `${草稿.薪资下限}-${草稿.薪资上限}K`;
  const 感兴趣城市文本 = 草稿.感兴趣城市们.join('、');
  const 期望行业文本 = 草稿.期望行业们.join('、');

  // 保存键不再因缺字段置灰（置灰让「为什么不让我存」变成哑谜），改成点保存时按序校验：
  //   工作城市 → 期望职位 → 办公方式，缺哪条轻提示哪条，一条没过就停。
  // 城市和职位是标题「[城市] 职位」的两个组成部分，缺一条就会存出「[] 」这种空壳标题，
  // 意向管理页那一行会变成一片空白且再也点不明白 —— 所以这三项都必须有。
  // 办公方式没选时还要把那一组滚进视口、聚焦第一个选钮，并挂 aria-invalid 提示屏幕阅读器。
  const 校验必填 = (): boolean => {
    if (草稿.工作城市 === '') {
      轻提示('请选择工作城市');
      return false;
    }
    if (草稿.期望职位 === '') {
      轻提示('请选择期望职位');
      return false;
    }
    if (草稿.办公方式.length === 0) {
      设办公方式错误(true);
      轻提示('请选择办公方式');
      const 组 = 办公方式组引用.current;
      组?.scrollIntoView({ block: 'center' });
      组?.querySelector<HTMLButtonElement>('button')?.focus();
      return false;
    }
    return true;
  };

  const 提交 = async () => {
    if (!校验必填()) return;
    try {
      await 操作.保存意向(草稿);
      派发({ 型: '清意向草稿' });
      返回();
    } catch (error) {
      轻提示(取后端错误文案(error));
    }
  };

  const 删除 = async () => {
    if (草稿.编辑编号) {
      try {
        await 操作.删除意向(草稿.编辑编号);
        派发({ 型: '清意向草稿' });
        返回();
      } catch (error) {
        轻提示(取后端错误文案(error));
      }
    }
  };

  // ‹ 退出：不保存就走，草稿要归零。这样「保存 / 删除 / 返回」三条出口一致，
  // 下次新建进来必然是干净的空表，不会看见上一轮没存的残留。
  const 退出 = () => {
    派发({ 型: '清意向草稿' });
    返回();
  };

  return (
    /* 2026-08-24 全站选择风格统一（C1 定稿）：页底加白底 */
    <次级页外壳 白底>
      <返回栏 返回={退出} />

      <页面大标题
        标题={编辑态 ? '编辑求职期望' : '添加求职期望'}
        说明="求职期望的不同，推荐的职位也会不同"
      />

      <滚动区 样式覆盖={{ padding: '6px 22px 10px' }}>
        {/* 第 1 行：求职类型 —— 两个选钮片行内右对齐，没有值行也没有 › */}
        {/* 2026-08-24 全站选择风格统一（C1 定稿）：单选圆点改定稿选钮片，选中对勾由 CSS ::before 画 */}
        <div className={样式.类型行}>
          <span className={样式.类型标}>求职类型</span>
          <div className={样式.类型组}>
            {(['全职', '兼职'] as const).map((类型) => {
              const 选中 = 草稿.求职类型 === 类型;
              return (
                <button
                  key={类型}
                  type="button"
                  className={`${样式.类型选项} ${选中 ? 样式.类型选项选中 : ''} 可点`}
                  onClick={() => 改草稿({ 求职类型: 类型 })}
                  aria-pressed={选中}
                >
                  {类型}
                </button>
              );
            })}
          </div>
        </div>

        {/* 办公方式：复用 求职类型 的选钮片行样式，多选（现场/混合/远程）。
            Task 6 新增必填草稿字段：保存时映射为 BFF wire code，空数组时 映射办公方式 抛错，
            这里在 校验必填 里提前挡住，给 轻提示 而不是让映射层抛。
            语义只挂在这一组上：role=group + aria-label 让读屏软件把它念成一个可命名分组，
            校验没过时 aria-invalid / aria-description 指到组上（不建新元素、不动版式）。 */}
        <div className={样式.类型行}>
          <span className={样式.类型标}>办公方式</span>
          <div
            ref={办公方式组引用}
            className={样式.类型组}
            role="group"
            aria-label="办公方式"
            aria-invalid={办公方式错误 || undefined}
            aria-description={办公方式错误 ? '请选择办公方式' : undefined}
          >
            {(['现场', '混合', '远程'] as const).map((方式) => {
              const 选中 = 草稿.办公方式.includes(方式);
              return (
                <button
                  key={方式}
                  type="button"
                  className={`${样式.类型选项} ${选中 ? 样式.类型选项选中 : ''} 可点`}
                  onClick={() => {
                    // 用户已经开始处理这一组了，校验错误立刻熄灭，再派发原有的选择
                    设办公方式错误(false);
                    改草稿({
                      办公方式: 选中
                        ? 草稿.办公方式.filter((项) => 项 !== 方式)
                        : [...草稿.办公方式, 方式],
                    });
                  }}
                  aria-pressed={选中}
                >
                  {方式}
                </button>
              );
            })}
          </div>
        </div>

        {/* 第 2、3 行跳注册引导里那两屏，带 ?来源=意向 让它们写草稿而不是写 引导预填 */}
        <期望行
          标签="工作城市"
          值={草稿.工作城市}
          占位="请选择工作城市"
          按下={() => 跳转(`${路径.选工作城市}?来源=意向`)}
        />
        <期望行
          标签="期望职位"
          值={草稿.期望职位}
          占位="请选择期望职位"
          按下={() => 跳转(`${路径.选期望职位}?来源=意向`)}
        />

        {/* 第 4 行的 label 自带 N/9 计数（规格表原样），值是顿号连接的城市们 */}
        <期望行
          标签={`其他感兴趣城市（${草稿.感兴趣城市们.length}/${感兴趣城市上限}）`}
          值={感兴趣城市文本}
          占位="请选择更多感兴趣城市"
          按下={() => 跳转(路径.选择城市)}
        />

        {/* 第 5 行开底部弹层，不跳页：薪资是滚轮选数，跳一整屏太重 */}
        <期望行
          标签="薪资要求"
          值={薪资文本}
          占位="请选择薪资要求"
          按下={() => 设薪资层开(true)}
        />

        <期望行
          标签="期望行业"
          值={期望行业文本}
          占位="不限"
          按下={() => 跳转(路径.选期望行业)}
        />
      </滚动区>

      {/* 编辑态底部是「删除 + 保存」两键，新建态只有一个「保存」。
          保存键不再置灰：缺什么点保存时轻提示什么（见 校验必填） */}
      {编辑态 ? (
        <div className={样式.底键行}>
          <button type="button" className={`${样式.删除键} 可点`} onClick={删除}>
            删除
          </button>
          <button type="button" className={`${样式.保存键} 可点`} onClick={提交}>
            保存
          </button>
        </div>
      ) : (
        <主按钮 文字="保存" 按下={提交} 禁用={false} />
      )}

      {薪资层开 ? (
        <薪资区间层
          下限={草稿.薪资下限}
          上限={草稿.薪资上限}
          确认={(下, 上) => {
            改草稿({ 薪资下限: 下, 薪资上限: 上 });
            设薪资层开(false);
          }}
          取消={() => 设薪资层开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}
