  // source=手动添加 屏蔽；一键屏蔽按真实组织 ID 顺序写（见 一键屏蔽后端）。
  const 权威屏蔽: 屏蔽项[] = 是后端 ? 全局.屏蔽名单 : [];
  const [一键屏蔽简历公司, 设一键屏蔽简历公司] = useState(是后端 ? false : !在校生);
  const [屏蔽公司, 设屏蔽公司] = useState<string[]>(是后端 || 在校生 ? [] : 简历里的公司);
