// A1b 基本信息 —— 插在「引导说明」与「工作经历」之间的第一张表单。
//
// 为什么必须有这一屏（2026-08-18 补）：匿名初筛阶段代理要逐条核对岗位的硬性条件，
// 其中「工作年限 ≥ N 年」是最高频的一条，可整个 onboarding 从来没问过用户
// 什么时候开始工作 —— 核对的输入是悬空的。这屏把它补上，并且当场把折算结果
// 显示出来，让用户看得见「我填的这个数会被拿去干什么」。
//
// 双盲口径：真名在这里采集，但意向确认前不会交给任何企业，代理对外一律用代号。
// 所以输入框下面那行灰字不是客套话，是这屏存在的前提，不要删。

import { useState } from 'react';
import 样式 from './基本信息.module.css';
import 数字滚轮层 from '../组件/数字滚轮层';
import { 主按钮, 次级页外壳, 滚动区, 页面大标题, 返回栏 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use应用状态 } from '../状态/应用状态';
import type { 基本信息 as 基本信息类型 } from '../数据/类型';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

/** 身份三档。在校 = 应届 / 实习语境，会改变到岗节奏那题的默认档 */
const 身份选项: 基本信息类型['身份'][] = ['在校', '在职', '离职'];

/** 开始工作年份的下界。再往前推没有实际意义，滚轮也会长得离谱 */
const 最早工作年 = 1990;

export default function 基本信息() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  const 基本 = 全局.基本信息;
  const [年份轮打开, 设年份轮打开] = useState(false);

  const 当前年 = new Date().getFullYear();

  /** 写回全局：简历快照是整体存的，改一项也要把其余几块原样带上，否则会被清空 */
  const 存基本信息 = (改: Partial<基本信息类型>) =>
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: { ...基本, ...改 },
    });

  // 折算年限：代理在匿名初筛里核对「年限 ≥ 要求」用的就是这个数
  const 起始年 = Number(基本.开始工作年) || 当前年;
  const 折算年限 = Math.max(0, 当前年 - 起始年);
  const 在校中 = 基本.身份 === '在校';

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题
        标题="先认识一下你"
      />

      <滚动区 样式覆盖={{ padding: '2px 22px 24px' }}>
        {/* 真名：双盲机制里最敏感的一项。原有一行灰字说明按标注（2026-08-18 21:07）删除 */}
        <div className={样式.条目}>
          <div className={样式.条目标签}>真名</div>
          <input
            className={样式.条目输入}
            value={基本.真名}
            placeholder="身份证上的名字"
            onChange={(事件) => 存基本信息({ 真名: 事件.target.value })}
          />
        </div>

        {/* 开始工作年份：走数字滚轮，避免手输出现「二〇一七」「17」这类脏数据。
            在校生填的是预计年份，标签跟着身份改，免得「应届」和一个过去的年份并排显示 */}
        <button className={`${样式.选择条目} 可点`} onClick={() => 设年份轮打开(true)}>
          <span className={样式.条目标签}>
            {在校中 ? '预计开始工作年份' : '开始工作年份'}
          </span>
          <span className={样式.选择值行}>
            <span className={`${样式.条目值} 等宽数字`}>{基本.开始工作年 || 当前年} 年</span>
            <span className={样式.尖括号}>›</span>
          </span>
        </button>

        {/* 身份：快捷片，一眼看完三档，不做下拉 */}
        <div className={样式.条目}>
          <div className={样式.条目标签}>现在的身份</div>
          <div className={样式.片行}>
            {身份选项.map((项) => (
              <button
                key={项}
                className={`${样式.片} ${基本.身份 === 项 ? 样式.片选中 : ''} 可点`}
                onClick={() => 存基本信息({ 身份: 项 })}
              >
                {项}
              </button>
            ))}
          </div>
        </div>

        {/* 折算回显：让「我填的数字会被拿去干什么」当场可见，
            而不是等到某一单被刷掉了才知道年限没对上 */}
        <div className={样式.折算区}>
          {在校中 ? (
            <div className={样式.折算数}>应届</div>
          ) : (
            <div className={样式.折算数}>
              {折算年限}
              <span className={样式.折算单位}>年经验</span>
            </div>
          )}
          <div className={样式.折算注}>
            {在校中
              ? '按此折算：在校 · 匿名初筛按在校身份核对，不卡年限要求'
              : '按此折算：匿名初筛用它核对岗位的年限要求'}
          </div>
        </div>
      </滚动区>

      <主按钮
        文字="下一步"
        按下={() => {
          if (基本.真名.trim() === '') {
            轻提示('填一下真名，代理只在双方确认意向后才交出去');
            return;
          }
          跳转(路径.工作经历);
        }}
      />

      {年份轮打开 ? (
        <数字滚轮层
          标题="开始工作年份"
          初值={起始年}
          最小={最早工作年}
          // 在校生填的是「预计」，得能选到还没到的年份；社会人只能选到今年
          最大={在校中 ? 当前年 + 2 : 当前年}
          单位="年"
          确认={(值) => {
            存基本信息({ 开始工作年: String(值) });
            设年份轮打开(false);
          }}
          取消={() => 设年份轮打开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}
