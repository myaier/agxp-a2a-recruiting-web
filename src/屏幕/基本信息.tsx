/** 预填产物里只取需要种入根草稿的键（真名/性别/开始工作年，非空才带）；
 *  出生抽屉值是页本地态，status（身份）永不映射，在这里一并挡掉。 */
function 仅取根基本字段(预填: 候选基本信息预填): Partial<基本信息类型> {
  const 根: Partial<基本信息类型> = {};
  if (预填.真名) 根.真名 = 预填.真名;
  if (预填.性别 !== undefined) 根.性别 = 预填.性别;
  if (预填.开始工作年) 根.开始工作年 = 预填.开始工作年;
  return 根;
}

/** 本页拥有的 profile 输入。身份归求职状态屏、在读学历归学历屏，不在这里回写草稿；
 *  出生年月未确认时两个键都缺席（缺席 = 不写入，见下面的落盘分支）。 */
function 本页草稿字段(源: 基本信息类型): Partial<基本信息类型> {
  const 字段: Partial<基本信息类型> = { 真名: 源.真名 };
  if (源.性别 !== undefined) 字段.性别 = 源.性别;
  if (源.开始工作年 !== '') 字段.开始工作年 = 源.开始工作年;
  if (源.出生年 !== undefined && 源.出生月 !== undefined) {
    字段.出生年 = 源.出生年;
    字段.出生月 = 源.出生月;
  }
  return 字段;
}

export default function 基本信息() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发, 操作, 数据源模式, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  // 日常编辑来源（合同 A，Task 1）：/basic 只接受 from=resume —— 我的简历 的入口带它，
  // 是「这次编辑只服务简历域」的唯一判据（不能用 引导预填 非空反推）。日常模式输入只进
  // 局部草稿，保存只回我的简历：零建档草稿、零分区确认、零预填种入（URL 在，刷新后
  // 同样不恢复建议）。白名单外的来源值（含 intentions 这种状态页专用来源）一律不当日常。
  const [查询参数] = useSearchParams();
  const 来源 = 读候选编辑来源(查询参数.toString());
  const 日常 = 来源 === 'resume';
  // 日常编辑的统一出口：有来路证明退一格回我的简历，否则安全替换回去（不盲退）
  const 退出编辑 = use候选编辑退出('resume');
  // J-PILOT-02 Task 4：建档草稿优先。刷新后 Context 只剩服务端权威（空身份那一步
  // 根本没发 profile），用户输入只在草稿里 —— 页面读写都以草稿为准，Mock 不涉及。
  //
  // 旅程标记：这一屏同时是日常编辑的入口（我的简历 → 基本信息）。只有注册旅程里才
  // 碰草稿 —— 引导预填 由 学生分流 的 启程引导 在进本屏之前派发（两条候选合同共用
  // 那一个出口），清后端草稿 把它置回 null。日常编辑进来时它是 null，一行草稿也不写，
  // 否则 简历域保存 会从「非 onboarding 原路径」切到单槽/缺项保护那条，改掉日常业务。
  // /basic 只认 from=resume 这一个合法日常来源：其余来源值（含状态页专用的 intentions）
  // 等同无来源 —— 与 候选Onboarding预填边界 的路径限定同一口径（那里错配来源也不算
  // 日常位置），同一 URL 不在两层得到互相矛盾的语义。
  const 旅程中 = 是后端 && 全局.引导预填 !== null && !日常;
  const 建档 = 旅程中 ? 全局.引导预填?.建档 : undefined;
  const 草稿基本 = 建档?.资料?.基本信息;
  // 日常编辑的局部草稿：初值取已水合权威快照（刷新丢未保存输入、读权威值）；输入只改
  // 这份草稿，取消/失败零写。背景权威刷新不覆盖这里（快照对象在 reducer 里整体换新，
  // 草稿引用不跟着走）。
  const [日常草稿, 设日常草稿] = useState<基本信息类型>(全局.基本信息);
  // 同一挂载页的状态收口子视图（Task 1 Step 4）：空身份日常保存时切过来，不 push 新页
  const [收口中, 设收口中] = useState(false);
  const [保存中, 设保存中] = useState(false);
  const 基本 = 日常 ? 日常草稿 : (草稿基本 ? { ...全局.基本信息, ...草稿基本 } : 全局.基本信息);
  const [年份轮打开, 设年份轮打开] = useState(false);
  // 候选 onboarding 预填：首挂载同步算一次（manual/inactive/已确认/不可预填轮为空对象）。
  // 日常编辑传 pristine 空轮：建议只在注册旅程种入，日常路径零建议写入。
  const [基本预填] = useState(() =>
    日常 ? {} : 取基本信息预填(后端状态.候选预填状态 ?? 创建空候选预填状态(), 基本));
  // 出生年月：抽屉临时值由 年月滚轮层 自己持有，确定才回填这对页本地数值
  // （建议的数字初值只在界内给出；超界/缺席由映射层落 undefined，保留既有默认）
  const [出生年, 设出生年] = useState<number>(() => 基本预填.出生年 ?? (Number(基本.出生年) || 1998));
  const [出生月, 设出生月] = useState<number>(() => 基本预填.出生月 ?? (Number(基本.出生月) || 6));
  // L：抽屉没有「空态」总显示一个落点 —— 显示值与确认态分离（picker 统一 Task 3：
  // 父行只有确认了才显示年月）。Backend 只有已有完整年月、完整真实建议或用户在抽屉
  // 里点过 确定，才算确认（保存双值）；未确认保存 null 语义（不写入出生年月）。
  // Mock 保持原型默认（1998/6 演示数据直接确认）；日常编辑一律只认权威已有值 ——
  // 把演示默认当用户生日写进已保存态不是编辑该有的行为。
  const 有已有生日 = 基本.出生年 !== undefined && 基本.出生月 !== undefined;
  const 有建议生日 = 基本预填.出生年 !== undefined && 基本预填.出生月 !== undefined;
  const [出生年月已确认, 设出生年月已确认] = useState(
    日常 ? 有已有生日 : (!是后端 || 有已有生日 || 有建议生日));
  // 出生年月抽屉：父页只持有是否打开（同 开始工作年份 / 学生分流 毕业抽屉的约定）
  const [生日轮打开, 设生日轮打开] = useState(false);

  const 当前年 = new Date().getFullYear();

  /** 写回全局：简历快照是整体存的，改一项也要把其余几块原样带上，否则会被清空 */
  const 写全局基本 = (下一基本: 基本信息类型) =>
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: 下一基本,
    });

  /** 用户明确编辑：注册旅程同时进 Context（本次会话）与建档草稿（刷新后仍在）；
   *  日常编辑只改局部草稿 —— 明确的「保存」才提交，取消/失败零写。 */
  const 存基本信息 = (改: Partial<基本信息类型>) => {
    if (日常) {
      设日常草稿((旧) => ({ ...旧, ...改 }));
      return;
    }
    写全局基本({ ...基本, ...改 });
    if (旅程中) {
      操作.更新候选建档草稿(并入建档草稿(建档, { 资料: { 基本信息: { ...草稿基本, ...改 } } }));
    }
  };

  /**
   * 出生年月在这里统一落盘（滚轮值是页本地态）。
   * L：先移除可能存在的半边旧值，再按确认态成对加入 —— 未确认就不写入。
   */
  const 合并生日 = (源: 基本信息类型): 基本信息类型 => {
    const 结果: 基本信息类型 = { ...源 };
    delete 结果.出生年;
    delete 结果.出生月;
    if (出生年月已确认) {
      结果.出生年 = String(出生年);
      结果.出生月 = String(出生月);
    }
    return 结果;
  };

  /** 日常保存：把本次 next 快照作为显式参数交给既有保存链（不经过 setState 再读旧闭包），
   *  成功才退出一格回原列表；失败留页保留草稿、锁随之释放。 */
  const 日常保存 = async (身份: 基本信息类型['身份']) => {
    if (保存中) return;
    if (身份 === '') {
      轻提示('请选择当前求职状态');
      return;
    }
    设保存中(true);
    try {
      await 操作.保存简历({
        基本信息: { ...合并生日(日常草稿), 身份 },
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 全局.简历教育,
        证书: 全局.简历证书,
      }, '日常编辑');
    } catch (错误) {
      轻提示(取后端错误文案(错误));
      设保存中(false);
      return;
    }
    设保存中(false);
    退出编辑();
  };

  // 一次性把建议里的空白根字段种入根草稿。种入是挂载域的：basic 未确认前清空建议
  // 字段、离开再回来会再次建议（非空编辑总是赢，manual 轮完全不再种）—— 接受的
  // 边界，不做持久 touched 框架。只在此处写根，出生抽屉值仍走「下一步统一落盘」。
  const 已种基本预填 = useRef(false);
  useLayoutEffect(() => {
    if (已种基本预填.current) return;
    已种基本预填.current = true;
    const 根字段 = 仅取根基本字段(基本预填);
    // 只种 Context：建议不是「用户明确编辑的输入」，不占建档草稿（manual 轮/清空
    // 建议的既有语义保持不变，草稿里只留用户自己敲进去的值）
    if (Object.keys(根字段).length > 0) 写全局基本({ ...基本, ...根字段 });
    // ref 守卫保证只跑首次：依赖表按 brief 固定，写全局基本 每渲染换标不影响语义
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [基本预填, 写全局基本]);

  // 开始工作年（非学生路径的年份轮初值）
  const 起始年 = Number(基本.开始工作年) || 当前年;
  const 在校中 = 基本.身份 === '在校';

  // ── 日常编辑的空身份收口子视图：同一挂载页复用状态三态正文 ──
  // 保留局部基本草稿（姓名/生日都不写全局），选合法状态后点保存才用合并后的基本信息
  // 一次进入保存链；返回/取消退出整链不写。刷新（重新挂载）丢未保存输入读权威值。
  if (日常 && 收口中) {
    return (
      <次级页外壳 白底>
        <返回栏 返回={退出编辑} />
        <页面大标题 标题="现在是什么状态？" />
        <滚动区 样式覆盖={{ padding: '48px 18px 12px' }}>
          <求职状态编辑正文
            值={日常草稿.身份}
            修改={(值) => 设日常草稿((旧) => ({ ...旧, 身份: 值 }))}
          />
        </滚动区>
        <主按钮 文字="保存" 按下={() => { void 日常保存(日常草稿.身份); }} />
      </次级页外壳>
    );
  }

  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：页底加白底
    <次级页外壳 白底>
      {/* 日常编辑的返回 = 取消：退出整链不写，不提交未保存内容 */}
      <返回栏 返回={日常 ? 退出编辑 : 返回} />

      <页面大标题 标题={日常 ? '编辑基本信息' : '创建在线简历'} />

      <滚动区 样式覆盖={{ padding: '2px 22px 24px' }}>
        {/* 真名：双盲机制里最敏感的一项。原有一行灰字说明按标注（2026-08-18 21:07）删除 */}
        <div className={样式.条目}>
          <div className={样式.条目标签}>姓名</div>
          <input
            className={样式.条目输入}
            value={基本.真名}
            placeholder="身份证上的名字"
            onChange={(事件) => 存基本信息({ 真名: 事件.target.value })}
          />
        </div>

        {/* 性别：并排双选钮（同 学生分流 的选钮样式）*/}
        <div className={样式.条目}>
          <div className={样式.条目标签}>性别</div>
          <div className={样式.双选行}>
            {性别选项.map((项) => (
              <button
                key={项}
                className={`${样式.选钮} ${基本.性别 === 项 ? 样式.选钮当前 : ''} 可点`}
                onClick={() => 存基本信息({ 性别: 项 })}
                aria-pressed={基本.性别 === 项}
              >
                {项}
              </button>
            ))}
          </div>
        </div>

        {/* 出生年月（picker 统一 Task 3）：常驻双滚轮改选择行 + 共用 年月抽屉，
            版式同 开始工作年份 行。未确认显示 未填写 —— 显示值与确认态分离 */}
        <button
          type="button"
          className={`${样式.选择条目} 可点`}
          onClick={() => 设生日轮打开(true)}
        >
          <span className={样式.条目标签}>出生年月</span>
          <span className={样式.选择值行}>
            {出生年月已确认 ? (
              <span className={`${样式.条目值} 等宽数字`}>
                {出生年} 年 {String(出生月).padStart(2, '0')} 月
              </span>
            ) : (
              <span className={样式.条目值}>未填写</span>
            )}
            <span className={样式.尖括号}>›</span>
          </span>
        </button>

        {/* 非学生分支：开始工作年份（学历相关块已挪去 /onboard 新页）*/}
        {在校中 ? null : (
          <>
            {/* 开始工作年份：走数字滚轮，避免手输出现「二〇一七」「17」这类脏数据 */}
            <button className={`${样式.选择条目} 可点`} onClick={() => 设年份轮打开(true)}>
              <span className={样式.条目标签}>开始工作年份</span>
              <span className={样式.选择值行}>
                <span className={`${样式.条目值} 等宽数字`}>{基本.开始工作年 || 当前年} 年</span>
                <span className={样式.尖括号}>›</span>
              </span>
            </button>

          </>
        )}
      </滚动区>

      <主按钮
        文字={日常 ? '保存' : '下一步'}
        按下={async () => {
          if (基本.真名.trim() === '') {
            轻提示('填一下真名，递交简历（S1）原件时即向招聘方显示');
            return;
          }
          // ── 日常编辑：不提前写任何状态。空身份先在同页切到状态收口子视图；
          //    有身份就用本次快照一次进入保存链（成功退出一格回原列表）──
          if (日常) {
            if (基本.身份 === '') {
              设收口中(true);
              return;
            }
            await 日常保存(基本.身份);
            return;
          }
          // 出生年月在这里统一落盘（滚轮值是本地态），再进求职状态屏
          const 待存基本: 基本信息类型 = 合并生日(基本);
          // 出生年月只在这一步成对落盘：同一份值同时进草稿（空身份那一步不发写入，
          // 刷新后全靠草稿；求职状态屏收口时再读回来）
          if (旅程中) {
            操作.更新候选建档草稿(并入建档草稿(建档, {
              资料: { 基本信息: { ...草稿基本, ...本页草稿字段(待存基本) } },
            }));
          }
          const 待存简历 = {
            基本信息: 待存基本,
            个人优势: 全局.个人优势,
            技能: 全局.简历技能,
            经历: 全局.简历经历,
            教育: 全局.简历教育,
            证书: 全局.简历证书,
          };
          // M：Backend 空身份延迟 profile —— 姓名/生日先落页面草稿（存简历 派发），
          // 不发 mutation、不确认 basic，去求职状态屏收口；身份选完由状态页一次性保存
          if (是后端 && 基本.身份 === '') {
            派发({ 型: '存简历', ...待存简历 });
            跳转(路径.求职状态);
            return;
          }
          try {
            // 注册旅程不传保存来源（缺省 = 现行 onboarding 跟踪行为）
            await 操作.保存简历(待存简历);
            // 分区确认仅注册旅程执行，且先于跳转
            操作.确认候选Onboarding预填分区('basic');
            // Task 3（合同 C）：两身份同一主序 —— 求职状态紧跟基本信息收口，
            // 学历四页与简历资料都在它之后（学生不再绕到资料之后再回来收口）
            跳转(路径.求职状态);
          } catch (错误) {
            轻提示(取后端错误文案(错误));
          }
        }}
      />

      {年份轮打开 ? (
        <数字滚轮层
          标题="开始工作年份"
          初值={起始年}
          最小={最早工作年}
          最大={当前年}
          单位="年"
          确认={(值) => {
            存基本信息({ 开始工作年: String(值) });
            设年份轮打开(false);
          }}
          取消={() => 设年份轮打开(false)}
        />
      ) : null}

      {/* 出生年月抽屉（picker 统一 Task 3）：滚动只改抽屉内临时值，确定才成对
          回填页本地数值并置确认标志；取消 / 遮罩 / Escape 只关层，零写入 */}
      {生日轮打开 ? (
        <年月滚轮层
          标题="出生年月"
          初值={`${出生年}-${String(出生月).padStart(2, '0')}`}
          最小={最早出生年月}
          最大={最晚出生年月}
          年名称="出生年"
          月名称="出生月"
          确认={(值) => {
            设出生年(Number(值.slice(0, 4)));
            设出生月(Number(值.slice(5, 7)));
            设出生年月已确认(true);
            设生日轮打开(false);
          }}
          取消={() => 设生日轮打开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}
