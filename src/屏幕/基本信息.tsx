// A1b 创建在线简历（/basic）—— 2026-08-20 按 BOSS 截图顺序重排。
//
// 期望月薪（引导问答首题）答完跳到这屏：姓名 → 性别（男/女 双选钮）→
// 出生年月（年 1970–2010 / 月 1–12 双滚轮，scroll-snap 中间高亮行）。
// 学历 / 毕业年相关块已挪去 /onboard/degree…/onboard/eduyears 新页；
// 非学生保留「开始工作年份」行（匿名初筛核对「年限 ≥ 要求」的输入）与折算回显。
//
// 双盲口径：真名在这里采集，但意向确认前不会交给任何企业，代理对外一律用代号。
//
// 候选 onboarding 简历预填（Spec §8 /basic）：首挂载同步用 取基本信息预填 算一次建议，
// 出生滚轮吃数字初值，空白根字段（真名/性别/开始工作年）经一次性 useLayoutEffect 种入
// 根草稿 —— 根 Resume 对象是本页的客户端草稿，逐键 存简历 派发保持不变。

import { useLayoutEffect, useRef, useState } from 'react';
import 样式 from './基本信息.module.css';
import 数字滚轮层 from '../组件/数字滚轮层';
import 内嵌双滚轮 from '../组件/内嵌双滚轮';
import { 主按钮, 次级页外壳, 滚动区, 页面大标题, 返回栏 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use应用状态 } from '../状态/应用状态';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import { 取基本信息预填, type 候选基本信息预填 } from '../流程/候选Onboarding简历预填';
import { 创建空候选预填状态 } from '../状态/后端/类型';
import type { 基本信息 as 基本信息类型 } from '../数据/类型';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

/** 性别两档：并排双选钮（同 学生分流 的选钮样式）*/
const 性别选项: NonNullable<基本信息类型['性别']>[] = ['男', '女'];

/** 开始工作年份的下界。再往前推没有实际意义，滚轮也会长得离谱 */
const 最早工作年 = 1990;

/** 出生年滚轮范围（截图档位）*/
const 出生年档 = Array.from({ length: 2010 - 1970 + 1 }, (_, 序) => 1970 + 序);
const 出生月档 = Array.from({ length: 12 }, (_, 序) => 序 + 1);

/** 预填产物里只取需要种入根草稿的键（真名/性别/开始工作年，非空才带）；
 *  出生滚轮值是页本地态，status（身份）永不映射，在这里一并挡掉。 */
function 仅取根基本字段(预填: 候选基本信息预填): Partial<基本信息类型> {
  const 根: Partial<基本信息类型> = {};
  if (预填.真名) 根.真名 = 预填.真名;
  if (预填.性别 !== undefined) 根.性别 = 预填.性别;
  if (预填.开始工作年) 根.开始工作年 = 预填.开始工作年;
  return 根;
}

export default function 基本信息() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发, 操作, 数据源模式, 后端状态 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  const 基本 = 全局.基本信息;
  const [年份轮打开, 设年份轮打开] = useState(false);
  // 候选 onboarding 预填：首挂载同步算一次（manual/inactive/已确认/不可预填轮为空对象）
  const [基本预填] = useState(() => 取基本信息预填(后端状态.候选预填状态 ?? 创建空候选预填状态(), 基本));
  // 出生年月：滚轮本地持值，下一步统一落 基本信息（滚动过程不必每档写盘）；
  // 建议的数字初值只在界内给出（超界/缺席由映射层落 undefined，保留既有默认）
  const [出生年, 设出生年] = useState<number>(() => 基本预填.出生年 ?? (Number(基本.出生年) || 1998));
  const [出生月, 设出生月] = useState<number>(() => 基本预填.出生月 ?? (Number(基本.出生月) || 6));

  const 当前年 = new Date().getFullYear();

  /** 写回全局：简历快照是整体存的，改一项也要把其余几块原样带上，否则会被清空 */
  const 存基本信息 = (改: Partial<基本信息类型>) =>
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: { ...基本, ...改 },
    });

  // 一次性把建议里的空白根字段种入根草稿。种入是挂载域的：basic 未确认前清空建议
  // 字段、离开再回来会再次建议（非空编辑总是赢，manual 轮完全不再种）—— 接受的
  // 边界，不做持久 touched 框架。只在此处写根，出生滚轮值仍走「下一步统一落盘」。
  const 已种基本预填 = useRef(false);
  useLayoutEffect(() => {
    if (已种基本预填.current) return;
    已种基本预填.current = true;
    const 根字段 = 仅取根基本字段(基本预填);
    if (Object.keys(根字段).length > 0) 存基本信息(根字段);
    // ref 守卫保证只跑首次：依赖表按 brief 固定，存基本信息 每渲染换标不影响语义
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [基本预填, 存基本信息]);

  // 开始工作年（非学生路径的年份轮初值）
  const 起始年 = Number(基本.开始工作年) || 当前年;
  const 在校中 = 基本.身份 === '在校';

  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：页底加白底
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      <页面大标题 标题="创建在线简历" />

      <滚动区 样式覆盖={{ padding: '2px 22px 24px' }}>
        {/* 真名：双盲机制里最敏感的一项。原有一行灰字说明按标注（2026-08-18 21:07）删除 */}
        <div className={样式.条目}>
          <div className={样式.条目标签}>姓名</div>
          <input
            className={样式.条目输入}
            value={基本.真名}
            placeholder="身份证上的名字"
            onChange={(事件) => 存基本信息({ 真名: 事件.target.value })}
          />
        </div>

        {/* 性别：并排双选钮（同 学生分流 的选钮样式）*/}
        <div className={样式.条目}>
          <div className={样式.条目标签}>性别</div>
          <div className={样式.双选行}>
            {性别选项.map((项) => (
              <button
                key={项}
                className={`${样式.选钮} ${基本.性别 === 项 ? 样式.选钮当前 : ''} 可点`}
                onClick={() => 存基本信息({ 性别: 项 })}
                aria-pressed={基本.性别 === 项}
              >
                {项}
              </button>
            ))}
          </div>
        </div>

        {/* 出生年月：年 / 月双滚轮，scroll-snap 吸附 + 中间高亮行 */}
        <div className={样式.条目}>
          <div className={样式.条目标签}>出生年月</div>
          <div className={样式.滚轮卡}>
            <内嵌双滚轮
              左档={出生年档}
              右档={出生月档}
              左值={出生年}
              右值={出生月}
              设左值={设出生年}
              设右值={设出生月}
              左名="出生年"
              右名="出生月"
              左单位="年"
              右单位="月"
            />
          </div>
        </div>

        {/* 非学生分支：开始工作年份（学历相关块已挪去 /onboard 新页）*/}
        {在校中 ? null : (
          <>
            {/* 开始工作年份：走数字滚轮，避免手输出现「二〇一七」「17」这类脏数据 */}
            <button className={`${样式.选择条目} 可点`} onClick={() => 设年份轮打开(true)}>
              <span className={样式.条目标签}>开始工作年份</span>
              <span className={样式.选择值行}>
                <span className={`${样式.条目值} 等宽数字`}>{基本.开始工作年 || 当前年} 年</span>
                <span className={样式.尖括号}>›</span>
              </span>
            </button>

          </>
        )}
      </滚动区>

      <主按钮
        文字="下一步"
        按下={async () => {
          if (基本.真名.trim() === '') {
            轻提示('填一下真名，递交简历（S1）原件时即向招聘方显示');
            return;
          }
          // 出生年月在这里统一落盘（滚轮值是本地态），再进求职状态屏
          const 待存简历 = {
            基本信息: { ...基本, 出生年: String(出生年), 出生月: String(出生月) },
            个人优势: 全局.个人优势,
            技能: 全局.简历技能,
            经历: 全局.简历经历,
            教育: 全局.简历教育,
            证书: 全局.简历证书,
          };
          // M：Backend 空身份延迟 profile —— 姓名/生日先落页面草稿（存简历 派发），
          // 不发 mutation、不确认 basic，去求职状态屏收口；身份选完由状态页一次性保存
          if (是后端 && 基本.身份 === '') {
            派发({ 型: '存简历', ...待存简历 });
            跳转(路径.求职状态);
            return;
          }
          try {
            await 操作.保存简历(待存简历);
            // 预填确认只在既有保存成功后（拒绝时分区不确认），且先于跳转
            操作.确认候选Onboarding预填分区('basic');
            // 学生路径先补学业档案，求职状态挪到时间段之后
            跳转(全局.基本信息.身份 === '在校' ? 路径.最高学历 : 路径.求职状态);
          } catch (错误) {
            轻提示(取后端错误文案(错误));
          }
        }}
      />

      {年份轮打开 ? (
        <数字滚轮层
          标题="开始工作年份"
          初值={起始年}
          最小={最早工作年}
          最大={当前年}
          单位="年"
          确认={(值) => {
            存基本信息({ 开始工作年: String(值) });
            设年份轮打开(false);
          }}
          取消={() => 设年份轮打开(false)}
        />
      ) : null}
    </次级页外壳>
  );
}
