import { 附件错误文案, 校验附件PDF } from '../流程/附件简历交互';
import { BFF错误 } from '../数据/HTTP客户端';
import { use附件简历刷新 } from '../流程/附件简历刷新';
import { 创建空候选预填状态 } from '../状态/后端/类型';
import {
  默认求职初筛偏好,
  空求职初筛偏好,
  求职初筛缺失项,
  今天日期,
  校验预计毕业时间,
  type 办公偏好,
  type 求职初筛偏好,
  type 求职类型,
} from '../流程/onboarding配置';


export default function 学生分流() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发, 数据源模式, 后端状态, 操作 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  const 文件选择框 = useRef<HTMLInputElement>(null);

  // P2 Task 5：附件简历（Backend）—— 权威快照只读 items[0] 一行；空库创建、非空替换。
  // 待确认文件是「授权层背后的那一份」：选中只预检不发送，同意后才真正上传。
  const 附件库 = 是后端 ? 后端状态.附件简历库 : null;
  const 最近附件 = 附件库?.items[0] ?? null;
  const [待确认文件, 设待确认文件] = useState<File | null>(null);
  const [附件提交中, 设附件提交中] = useState(false);
  // Backend 页面可见期轮询附件解析状态（钩子内部自判 Mock / 未登录 / 角色，静默）
  use附件简历刷新(是后端);

  // ── 候选 onboarding 简历预填（设计 §7 上传页接线）──
  // 页面只做四件事：挂载恢复（等候选/附件水合，恰好一次）、权威上传成功后激活、
  // 盯权威附件解析坐标交操作层推进、离页决策门（再等等 / 继续手填）。
  // 建议读取、单飞、栅栏、恢复分支全在操作层；本页零直接 BFF/预填请求。
  const 预填 = 后端状态.候选预填状态 ?? 创建空候选预填状态();
  const [离页确认, 设离页确认] = useState(false);
  const 已恢复引用 = useRef(false);
  const 上一预填阶段 = useRef(预填.phase);
  const 候选会话就绪 = 是后端 && 后端状态.主体?.last_used_role === 'candidate';
  const 附件已水合 = 附件库 !== null;
  // 解析真相源只有权威附件 items[0]：file/version/parse 状态（与 parse_id）四元组坐标
  const 最近解析 = 最近附件?.current_version.parse ?? null;
  const 解析坐标 = 最近附件 === null || 最近解析 === null
    ? ''
    : `${最近附件.file_id}|${最近附件.current_version.version_id}|${最近解析.status}|${'parse_id' in 最近解析 ? 最近解析.parse_id : ''}`;

  // 挂载恢复：等候选与附件水合完成后恰好调一次；是否真恢复（元数据匹配、waiting
  // 还是 manual）由操作层裁决，页面不重复那份判定
  useEffect(() => {
    if (已恢复引用.current || !候选会话就绪 || !附件已水合) return;
    已恢复引用.current = true;
    void 操作.恢复候选Onboarding预填({ 允许等待解析: true });
  }, [候选会话就绪, 附件已水合, 操作]);

  // 权威解析坐标 → 操作层推进。只在活轮在场时转交（inactive 轮零触碰：带旧附件
  // 直接进来不激活也不读取）；「轮从无到有」（激活/恢复落地）也触发一次推进，
  // 关掉「上传先落库、激活后到」的竞态窗口。重复调用由操作层单飞收敛。
  const 预填轮在场 = 预填.phase !== 'inactive';
  useEffect(() => {
    if (!是后端 || !预填轮在场 || 解析坐标 === '') return;
    void 操作.同步候选Onboarding解析();
  }, [是后端, 预填轮在场, 解析坐标, 操作]);

  // failed 落位反馈（设计 §7）：复用 轻提示；parse 失败（error:null）用固定文案，
  // 读取失败用操作层已落好的闭合文案。只在观察到「非 failed → failed」转移时提示。
  useEffect(() => {
    if (是后端 && 上一预填阶段.current !== 'failed' && 预填.phase === 'failed') {
      轻提示(预填.error ?? '简历识别失败，可重新上传或继续手填');
    }
    上一预填阶段.current = 预填.phase;
  }, [预填.phase, 预填.error, 是后端]);

  // 是否学生：三态 —— 草稿显式选择 在校选择 优先；缺席时从身份推导（在校→true、
  // 空→null 未选择、其余→false）。城市 / 职位选择改成跳页后本屏会被卸载重挂，
  // 选择落 引导预填.在校选择（随 存求职筛选偏好 派发），不留在本地 useState
  const 在校选择 = 全局.引导预填?.在校选择
    ?? (全局.基本信息.身份 === '在校' ? true
      : 全局.基本信息.身份 === '' ? null : false);
  const 是学生 = 在校选择 === true;
  // 简历文件名读全局，不留本地副本 —— 同上一条注释的道理：点城市 / 职位跳全屏选择页
  // 再返回，本屏重新挂载，本地 useState 那份文件名会归零，行内退回占位文案，
  // 用户会以为简历没传上去（全局其实已经存着）
  const 已选简历名 = 全局.简历文件名;

  // 城市 / 职位由全屏选择页写进 引导预填，本屏只读回显
  // review-r2 R2-I-1：Backend 引导预填=null 时不回落到 ['上海']——那是一个无引用的默认串，
  // 直接提交会让首轮意向丢 refs。Backend 显示空占位，等用户去选择页选（选择页才写 城市引用们）。
  // Mock 保留 ['上海'] 默认（演示数据不进 Backend 会话）。
  const 城市们 = 全局.引导预填?.城市们 ?? (是后端 ? [] : ['上海']);
  const 已选职位 = 全局.引导预填?.职位 ?? [];
  const 城市引用们 = 全局.引导预填?.城市引用们 ?? [];
  const 职位引用们 = 全局.引导预填?.职位引用们 ?? [];
  // 首屏默认（Task 5B）：Backend 初次进入的偏好是空的 —— 类型/办公方式等用户明确
  // 选择后才进草稿；Mock 保留演示默认
  const 筛选偏好 = 全局.引导预填?.筛选偏好
    ?? (是后端 ? 空求职初筛偏好() : 默认求职初筛偏好(是学生));
  // 在校状态只决定后续资料流程，不替用户限制机会类型。
  // 这里采集一个主要方向，避免校招月薪与实习日薪共用一个期望区间。
  const 求职类型选项: 求职类型[] = ['社招全职', '校园招聘', '实习生', '兼职'];
  const 办公方式选项: 办公偏好[] = ['现场', '混合', '全远程'];
  const 今天 = 今天日期();
  const 毕业时间错误 = 筛选偏好.毕业时间
    ? 校验预计毕业时间(筛选偏好.毕业时间, 今天)
    : null;

  // 毕业时间滚轮档位：今年起往后 8 年；当前值缺省取今天的下一年 6 月（毕业季）
  const 今年 = Number(今天.slice(0, 4));
  const 毕业年档 = Array.from({ length: 8 }, (_, i) => 今年 + i);
  const 毕业月档 = Array.from({ length: 12 }, (_, i) => i + 1);
  const [毕业年, 毕业月] = 筛选偏好.毕业时间
    ? [Number(筛选偏好.毕业时间.slice(0, 4)), Number(筛选偏好.毕业时间.slice(5, 7))]
    : [今年 + 1, 6];

  // 毕业时间弹层：临时值在层里滑，点「完成」才落盘（与 数字滚轮层 同约定）。
  // 首屏默认（Task 5B）：删掉「选了校园招聘就自动落默认毕业月」的 mount effect ——
  // 显示落点与确认态分离，只有弹层「完成」才写值
  const [毕业轮开, 设毕业轮开] = useState(false);
  const [临毕业年, 设临毕业年] = useState(毕业年);
  const [临毕业月, 设临毕业月] = useState(毕业月);

  /** 落筛选偏好：携带页面当前四项草稿基底与显式 在校选择（Task 5B：
   *  reducer 不再兜底默认城市，未选择就是空数组） */
  const 存筛选偏好 = (改: Partial<求职初筛偏好>) =>
    派发({
      型: '存求职筛选偏好',
      偏好: { ...筛选偏好, ...改 },
      在校选择: 在校选择 ?? undefined,
      城市们,
      职位: 已选职位,
      城市引用们,
      职位引用们,
    });

  const 切多选 = <T,>(当前: T[], 项: T): T[] =>
    当前.includes(项) ? 当前.filter((值) => 值 !== 项) : [...当前, 项];


  /** 上传简历（一键读取入口）：Mock 文件名落全局，行内占位换成文件名；
      Backend 只预检 + 挂起待授权，同意后才真正上传（见 同意处理附件） */
  function 选中简历文件(事件: ChangeEvent<HTMLInputElement>) {
    const 文件 = 事件.target.files?.[0];
    事件.target.value = ''; // 允许再次选同一个文件
    if (!文件) return;
    if (是后端) {
      // 先本地预检（扩展名 / media type / 快照大小上限），有错只提示、零副作用；
      // 快照未到（limits 未知）不硬编码本地限制，大小交服务端裁决
      const 错误 = 校验附件PDF(文件, 附件库?.limits ?? null);
      if (错误) {
        轻提示(错误);
        return;
      }
      设待确认文件(文件);
      return;
    }
    派发({ 型: '存简历文件名', 文件名: 文件.name });
    轻提示('已选择简历，可识别的信息将用于预填');
  }

  /** 授权层「同意并继续」：空库创建 / 非空替换 items[0]，consent 字面量 true。
      已换代（会话已转移）静默；失败用 附件错误文案 的闭合表，行上保留权威展示名。
      附件提交中 + aria-busy 防重复提交，上传不阻塞「下一步」。 */
  async function 同意处理附件() {
    if (!待确认文件 || 附件提交中) return;
    const file = 待确认文件;
    const target = 最近附件;
    设附件提交中(true);
    try {
      const result = target
        ? await 操作.替换附件简历(target.file_id, file, true)
        : await 操作.创建附件简历(file, true);
      设待确认文件(null);
      if (result === '已换代') return;
      轻提示('简历已上传，正在识别');
      // 上传页显式新一轮：权威上传/替换 resolves '已提交' 之后才激活（严格晚于
      // 上传调用）；source 绑定与解析推进交给 同步候选Onboarding解析 按权威附件完成
      操作.激活候选Onboarding预填();
    } catch (error) {
      // 401 时操作层已清账号状态（Spec §10.1：snapshot、timer 与待处理文件一起失效），
      // 保留授权层只会对着死会话重发注定失败的 mutation —— 关层，仍按闭合表提示
      if (error instanceof BFF错误 && error.status === 401) 设待确认文件(null);
      轻提示(附件错误文案(error, 附件库?.limits ?? null));
    } finally {
      设附件提交中(false);
    }
  }

  /** 点「是 / 不是」当场落全局身份（跳页选城市 / 职位回来后选择不能丢）：
      选「是」→ 身份=在校，并清掉演示种子残留的 开始工作年（学生没有工龄，
      防止后面按「有工龄=社招」误判）；选「不是」→ 若此前是在校则落回空身份
      （是否学生重新待选，身份由求职状态屏收口），已是在职/离职的保持不动
      （离职是求职状态屏才细分的档，这里不覆盖） */
  const 选身份 = (选了是: boolean) => {
    // 已选中的身份再次被点击时不做任何事。此前每次点击都会重建默认筛选偏好，
    // 用户只是确认当前选择，也会丢掉已经填写的实习日期和办公方式。
    if (在校选择 === 选了是) return;

    const 旧 = 全局.基本信息;
    const 改: Partial<基本信息类型> = 选了是
      ? { 身份: '在校', 开始工作年: '' }
      : { 身份: 旧.身份 === '在校' ? '' : 旧.身份 };
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: { ...旧, ...改 },
    });
    // 身份切换时重置角色专属偏好，避免学生的「实习生」或社招的「兼职」串到另一条流程。
    // Backend 重置为空偏好（Task 5B：不虚构选择），Mock 保留原默认。
    派发({
      型: '存求职筛选偏好',
      偏好: 是后端 ? 空求职初筛偏好() : 默认求职初筛偏好(选了是),
      在校选择: 选了是,
      城市们,
      职位: 已选职位,
      城市引用们,
      职位引用们,
    });
  };

  /** 启程引导 + 既有路由分叉（下一步 直行与「继续手填」共用同一条出口） */
  const 启程并跳转 = () => {
    // review-r2 R2-I-2：启程引导 携带选择器写入的 目录引用们，首轮意向提交才带得上 refs
    派发({
      型: '启程引导',
      城市们,
      职位: 已选职位,
      筛选偏好,
      城市引用们,
      职位引用们,
    });
    // 分叉口（用户 2026-08-20：两条配置路径不能一样）——
    // 学生：先学业档案（在线简历 → 在读学历 → 学校 → 专业 → 时间段 → 求职状态），薪资在向导里最后问；
    // 非学生：先期望薪资，按 BOSS 截图序走。进的是向导的**薪资段**（地址带 ?stage=salary）——
    // 社招要进两次向导，不写明段，向导就分不清自己是第一次还是第二次（见 onboarding配置.向导题序）
    跳转(是学生 ? 路径.基本信息 : 路径.引导问答薪资段);
  };

  const 下一步 = () => {
    // 首屏默认（Task 5B）：主按钮不再置灰，缺失按序给可见提示 ——
    // 身份 → 偏好 → 城市/职位，任一失败都不派发 启程引导
    if (在校选择 === null) {
      轻提示('请选择是否在校');
      return;
    }
    const 缺失 = 求职初筛缺失项(筛选偏好);
    if (缺失.length > 0) {
      轻提示(`请补充：${缺失.join('、')}`);
      return;
    }
    // review-r2 R2-I-1：Backend 必须有城市/职位引用才能提交——没进选择页就没有 refs，
    // 不能把无引用的默认串派发出去（首轮意向会丢 refs）。Mock 保留旧行为：默认城市落下去，
    // 引导问答按 引导预填 非空跳过城市题（Mock 以已选职位非空为同一道门）。
    if (是后端
      ? (城市引用们.length === 0 || 职位引用们.length === 0)
      : 已选职位.length === 0) {
      轻提示('请先选择工作城市与期望职位');
      return;
    }
    // 离页决策门（设计 §7）：解析/建议还在途（含激活初期的 arming）先问「再等等 /
    // 继续手填」；failed 的反馈已在落位时 轻提示，本次点击视为继续手填（横幅上的
    // 重新上传入口保留）；无轮 / ready / manual 直接走既有路由。
    if (是后端) {
      if (预填.phase === 'arming' || 预填.phase === 'waiting_parse' || 预填.phase === 'loading') {
        设离页确认(true);
        return;
      }
      if (预填.phase === 'failed') {
        操作.继续手填候选Onboarding();
        启程并跳转();
        return;
      }
    }
    启程并跳转();
  };

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      <页面大标题 标题="完善资料" />

      <滚动区 样式覆盖={{ padding: '4px 18px 10px' }}>
        {/* ── 上传简历：一键读取入口（观感同 工作经历 顶部上传行）──
            Backend：空库占位「确认后开始识别」，非空回显权威行 items[0] 的展示名；
            Mock：沿用原 已选简历名 回显与原文案（逐字保留，防视觉漂移）。
            提交中外层 aria-busy + .附件忙碌（pointer-events:none），不新增 spinner */}
        {/* 上传简历入口改成主页同款代理横幅(用户 2026-09-02:与发岗端「上传 JD」同构)。
            Backend:空库文案保留「确认后开始识别」语义,非空回显权威行展示名;
            Mock:未选时「把简历给我,这张表我来填」,选中后回显文件名。
            提交中外层 aria-busy + .附件忙碌(pointer-events:none),不新增 spinner */}
        <div
          className={附件提交中 ? `${样式.上传横幅区} ${样式.附件忙碌}` : 样式.上传横幅区}
          aria-busy={附件提交中 || undefined}
        >
          {(() => {
            const 已选名 = 是后端 ? 最近附件?.display_name ?? '' : 已选简历名;
            const 动作文 = 已选名 !== '' ? '重新上传 ›' : '上传简历 ›';
            const 按下 = () => 文件选择框.current?.click();
            // 预填承诺文案（设计 §7 状态表）：pending/processing「正在识别简历」、
            // loading「正在准备可填写内容」、ready「已识别，将填写空白项」——只换
            // 既有 前文/强调 props，上传/重新上传动作与节点位置不动；failed/manual/
            // inactive 落回既有行（failed 的反馈走 轻提示，横幅保留重新上传动作）
            const 承诺 = !是后端 ? null
              : 预填.phase === 'arming' || 预填.phase === 'waiting_parse'
                ? { 前文: '', 强调: '正在识别简历' }
                : 预填.phase === 'loading'
                  ? { 前文: '', 强调: '正在准备可填写内容' }
                  : 预填.phase === 'ready'
                    ? { 前文: '已识别，', 强调: '将填写空白项' }
                    : null;
            if (承诺 !== null) {
              return <代理横幅 前文={承诺.前文} 强调={承诺.强调} 动作文={动作文} 按下={按下} />;
            }
            if (已选名 !== '') {
              return <代理横幅 前文="已收到 " 强调={已选名} 动作文={动作文} 按下={按下} />;
            }
            return 是后端 ? (
              <代理横幅 前文="上传 PDF 简历，" 强调="确认后开始识别" 动作文={动作文} 按下={按下} />
            ) : (
              <代理横幅 前文="把简历给我，" 强调="这张表我来填" 动作文={动作文} 按下={按下} />
            );
          })()}
        </div>
        <input
          ref={文件选择框}
          type="file"
          accept=".pdf,application/pdf"
          className={样式.隐藏文件框}
          onChange={选中简历文件}
        />

        {/* 在校状态只用来安排资料填写顺序，不限制求职类型。三态：未选择时两钮都不亮 */}
        <div className={`${样式.节问} ${样式.节问间距}`}>你目前是否在校？</div>
        <div className={样式.双选行}>
          {([true, false] as const).map((值) => (
            <button
              key={String(值)}
              className={`${样式.选钮} ${在校选择 === 值 ? 样式.选钮当前 : ''} 可点`}
              onClick={() => 选身份(值)}
              aria-pressed={在校选择 === 值}
            >
              {值 ? '在校' : '已毕业'}
            </button>
          ))}
        </div>
        <div className={样式.选钮副行}>
          仅用于安排后续资料填写，不会限制你可选的机会类型
        </div>

        {/* 求职类型与办公方式必须结构化采集，才能与招聘端字段做确定性筛选。 */}
        <div className={`${样式.节问} ${样式.节问间距}`}>主要想找哪类机会？</div>
        <div className={样式.猜片行}>
          {求职类型选项.map((项) => {
            const 选中 = 筛选偏好.求职类型.includes(项);
            return (
              <button
                key={项}
                className={`${样式.猜片} ${选中 ? 样式.猜片选中 : ''} 可点`}
                onClick={() => 存筛选偏好({ 求职类型: [项] })}
                aria-pressed={选中}
              >
                {项}
              </button>
            );
          })}
        </div>
        <div className={样式.选钮副行}>先选一个主要方向，进入后可继续添加其他求职意向</div>

        {筛选偏好.求职类型.includes('校园招聘') ? (
          <>
            <div className={`${样式.节问} ${样式.节问间距}`}>预计毕业时间</div>
            {/* 标注 2026-08-24 二改：「这个地方还是要填写的，点开时候可以滑动」——
                不常驻摊开；平时是一行字段（值 ›），点开才弹滚轮层滑动选，
                与 开始工作年份 的数字滚轮层同一交互 */}
            <button
              type="button"
              className={`${样式.选择行} 可点`}
              onClick={() => {
                设临毕业年(毕业年);
                设临毕业月(毕业月);
                设毕业轮开(true);
              }}
            >
              {/* 值字挂 选择值：与城市行同款 15/600（上一版没挂类掉回按钮默认字） */}
              <span className={样式.选择值}>{毕业年} 年 {String(毕业月).padStart(2, '0')} 月</span>
              <span className={样式.选择尖括号}>›</span>
            </button>
            {毕业时间错误 ? <div className={样式.字段错误}>{毕业时间错误}</div> : null}
          </>
        ) : null}

        {筛选偏好.求职类型.includes('实习生') ? (
          <>
            <div className={`${样式.节问} ${样式.节问间距}`}>实习可用时间</div>
            <div className={样式.猜片行}>
              {[1, 3, 6].map((月数) => (
                <button
                  key={月数}
                  className={`${样式.猜片} ${筛选偏好.实习月数 === 月数 ? 样式.猜片选中 : ''} 可点`}
                  onClick={() => 存筛选偏好({ 实习月数: 月数 })}
                  aria-pressed={筛选偏好.实习月数 === 月数}
                >
                  至少 {月数} 个月
                </button>
              ))}
            </div>
            <div className={样式.猜片行}>
              {[2, 3, 4, 5].map((天数) => (
                <button
                  key={天数}
                  className={`${样式.猜片} ${筛选偏好.每周到岗天数 === 天数 ? 样式.猜片选中 : ''} 可点`}
                  onClick={() => 存筛选偏好({ 每周到岗天数: 天数 })}
                  aria-pressed={筛选偏好.每周到岗天数 === 天数}
                >
                  每周 {天数} 天
                </button>
              ))}
            </div>
            {/* 「最早可开始实习日期」删于 2026-08-22：它比对的招聘端「最晚可接受实习开始日期」
                已按产品负责人标注（「这个删了吧，没啥用」）删除，这一头随之成为孤儿字段。
                实习月数 / 每周到岗天数 保留 —— 它们有一半是产品负责人自己加的 */}
          </>
        ) : null}

        {/* 作品集链接不在这一屏了 —— 它是简历内容（一个人一个作品集），
            2026-08-22 起长在 工作经历 屏，与专业技能、证书与语言并列 */}
        <div className={`${样式.节问} ${样式.节问间距}`}>可接受的办公方式</div>
        <div className={样式.猜片行}>
          {办公方式选项.map((项) => {
            const 选中 = 筛选偏好.办公方式.includes(项);
            return (
              <button
                key={项}
                className={`${样式.猜片} ${选中 ? 样式.猜片选中 : ''} 可点`}
                onClick={() => 存筛选偏好({ 办公方式: 切多选(筛选偏好.办公方式, 项) })}
                aria-pressed={选中}
              >
                {项}
              </button>
            );
          })}
        </div>

        {/* ── 希望在哪里工作：多选（上限 10），点行进全屏选择页 ── */}
        <div className={`${样式.节问} ${样式.节问间距}`}>希望在哪里工作</div>
        <button className={`${样式.选择行} 可点`} onClick={() => 跳转(路径.选工作城市)}>
          {城市们.length === 0 ? (
            <span className={`${样式.选择占位} 单行`}>选择工作城市</span>
          ) : (
            <span className={样式.选择值}>{城市们.join('、')}</span>
          )}
          <span className={样式.选择尖}>›</span>
        </button>

        {/* ── 期望的职位：多选（上限 10），点行进全屏选择页 ── */}
        <div className={`${样式.节问} ${样式.节问间距}`}>期望的职位是（可多选）</div>
        <button className={`${样式.选择行} 可点`} onClick={() => 跳转(路径.选期望职位)}>
          {已选职位.length === 0 ? (
            <span className={样式.选择占位}>选择期望职位</span>
          ) : (
            <span className={样式.选择值}>{已选职位.join('、')}</span>
          )}
          <span className={样式.选择尖}>›</span>
        </button>
      </滚动区>

      {/* 首屏默认（Task 5B）：不再置灰 —— 缺什么点下一步时按序轻提示（见 下一步） */}
      <主按钮
        文字="下一步"
        按下={下一步}
      />

      {毕业轮开 ? (
        <弹层框架
          标签="预计毕业时间"
          遮罩类名={轮层样式.遮罩}
          面板类名={轮层样式.层}
          关闭={() => 设毕业轮开(false)}
          层级={71}
        >
          <div className={轮层样式.顶栏}>
            <button className={`${轮层样式.取消键} 可点`} onClick={() => 设毕业轮开(false)}>
              取消
            </button>
            <span className={轮层样式.标题}>预计毕业时间</span>
            <button
              className={`${轮层样式.确认键} 可点`}
              onClick={() => {
                存筛选偏好({ 毕业时间: `${临毕业年}-${String(临毕业月).padStart(2, '0')}` });
                设毕业轮开(false);
              }}
            >
              完成
            </button>
          </div>
          <div className={样式.毕业轮区}>
            <内嵌双滚轮
              左档={毕业年档}
              右档={毕业月档}
              左值={临毕业年}
              右值={临毕业月}
              设左值={设临毕业年}
              设右值={设临毕业月}
              左名="毕业年"
              右名="毕业月"
              左单位="年"
              右单位="月"
            />
          </div>
        </弹层框架>
      ) : null}

      {/* P2 Task 5：附件上传授权确认层（文案冻结，Task 6 的 consent 复用同一组字）——
          选中只预检，用户同意后才发送；取消 / 遮罩 / Escape 都只清 待确认文件，零 mutation。
          失败时 待确认文件 保留，确认层不关，可直接重试。 */}
      {待确认文件 ? (
        <确认层
          标题="允许 AI 识别这份简历？"
          正文="这份 PDF 将发送给受控模型服务进行简历识别，可能包含个人信息。确认后才会上传并开始处理。"
          执行文="同意并继续"
          执行={() => {
            void 同意处理附件();
          }}
          取消={() => 设待确认文件(null)}
        />
      ) : null}

      {/* 离页决策门（设计 §7）：解析/建议还在途时点「下一步」——再等等留在本页由
          已挂载的 poller 推进；继续手填 = 本轮明确 opt-out（操作层置 manual，迟到
          建议不再应用）后走既有路由 */}
      {离页确认 ? (
        <确认层
          标题="简历还在识别中"
          正文="AI 正在读取这份简历，识别完成后会自动填写空白项。可以再等等，也可以继续手动填写。"
          执行文="继续手填"
          取消文="再等等"
          执行={() => {
            设离页确认(false);
            操作.继续手填候选Onboarding();
            启程并跳转();
          }}
          取消={() => 设离页确认(false)}
        />
      ) : null}

    </次级页外壳>
  );
}
