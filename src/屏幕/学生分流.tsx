// 学生分流（完善资料）—— 引导说明之后的资料第一屏（标注 10:49 调整顺序）。
//
// 2026-08-20 按 BOSS 截图顺序重排：
//   · 新增「上传简历」行 —— 一键读取入口，选中 .pdf 后文件名落全局.简历文件名，
//     行内占位换成文件名（观感同 工作经历 顶部的一键上传行）；
//   · 城市 / 职位不再用底部弹层，点行跳全屏选择页（/onboard/city、/onboard/job）；
//   · 城市升级为多选（上限 10），与职位一起存在 全局.引导预填（选择页直接派发），
//     本屏只读取回显 —— 跳页选完回来值还在。
//
// 学生答案仍落 全局.基本信息.身份（在校 / 在职），后续各屏都读它分支 —— 链路不变。

import { useRef, useState } from 'react';
import type { ChangeEvent } from 'react';
import type { 基本信息 as 基本信息类型 } from '../数据/类型';
import 样式 from './学生分流.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';
import {
  默认求职初筛偏好,
  求职初筛缺失项,
  type 办公偏好,
  type 求职初筛偏好,
  type 求职类型,
} from '../流程/onboarding配置';


export default function 学生分流() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  const 文件选择框 = useRef<HTMLInputElement>(null);

  // 是否学生：直接读全局身份 —— 城市 / 职位选择改成跳页后，本屏会被卸载重挂，
  // 本地 useState 会把「是」的选择丢掉，所以点选钮时就落全局（见 选身份）
  const 是学生 = 全局.基本信息.身份 === '在校';
  // 本次会话里选过的简历文件名：null = 还没选，行内显示占位
  const [已选简历名, 设已选简历名] = useState<string | null>(null);

  // 城市 / 职位由全屏选择页写进 引导预填，本屏只读回显
  const 城市们 = 全局.引导预填?.城市们 ?? ['上海'];
  const 已选职位 = 全局.引导预填?.职位 ?? [];
  const 筛选偏好 = 全局.引导预填?.筛选偏好 ?? 默认求职初筛偏好(是学生);
  // 在校状态只决定后续资料流程，不替用户限制机会类型。
  // 这里采集一个主要方向，避免校招月薪与实习日薪共用一个期望区间。
  const 求职类型选项: 求职类型[] = ['社招全职', '校园招聘', '实习生', '兼职'];
  const 办公方式选项: 办公偏好[] = ['现场', '混合', '全远程'];

  const 存筛选偏好 = (改: Partial<求职初筛偏好>) =>
    派发({ 型: '存求职筛选偏好', 偏好: { ...筛选偏好, ...改 } });

  const 切多选 = <T,>(当前: T[], 项: T): T[] =>
    当前.includes(项) ? 当前.filter((值) => 值 !== 项) : [...当前, 项];


  /** 上传简历（一键读取入口）：文件名落全局，行内占位换成文件名 */
  function 选中简历文件(事件: ChangeEvent<HTMLInputElement>) {
    const 文件 = 事件.target.files?.[0];
    事件.target.value = ''; // 允许再次选同一个文件
    if (!文件) return;
    派发({ 型: '存简历文件名', 文件名: 文件.name });
    设已选简历名(文件.name);
    轻提示('已选择简历，可识别的信息将用于预填');
  }

  /** 点「是 / 不是」当场落全局身份（跳页选城市 / 职位回来后选择不能丢）：
      选「是」→ 身份=在校，并清掉演示种子残留的 开始工作年（学生没有工龄，
      防止后面按「有工龄=社招」误判）；选「不是」→ 若此前是在校则落回在职，
      已是在职/离职的保持不动（离职是求职状态屏才细分的档，这里不覆盖） */
  const 选身份 = (选了是: boolean) => {
    const 旧 = 全局.基本信息;
    const 改: Partial<基本信息类型> = 选了是
      ? { 身份: '在校', 开始工作年: '' }
      : { 身份: 旧.身份 === '在校' ? '在职' : 旧.身份 };
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: { ...旧, ...改 },
    });
    // 身份切换时重置角色专属偏好，避免学生的「实习生」或社招的「兼职」串到另一条流程。
    派发({ 型: '存求职筛选偏好', 偏好: 默认求职初筛偏好(选了是) });
  };

  const 下一步 = () => {
    const 缺失 = 求职初筛缺失项(筛选偏好);
    if (缺失.length > 0) {
      轻提示(`请补充：${缺失.join('、')}`);
      return;
    }
    // 没进过选择页也要把默认城市落下去，引导问答按 引导预填 非空跳过城市题
    派发({ 型: '启程引导', 城市们, 职位: 已选职位, 筛选偏好 });
    // 分叉口（用户 2026-08-20：两条配置路径不能一样）——
    // 学生：先学业档案（在线简历 → 在读学历 → 学校 → 专业 → 时间段 → 求职状态），薪资在向导里最后问；
    // 非学生：先期望薪资，按 BOSS 截图序走
    跳转(是学生 ? 路径.基本信息 : 路径.引导问答);
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题 标题="完善资料" />

      <滚动区 样式覆盖={{ padding: '4px 18px 10px' }}>
        {/* ── 上传简历：一键读取入口（观感同 工作经历 顶部上传行）── */}
        <div className={样式.节问}>上传简历</div>
        <button className={`${样式.上传行} 可点`} onClick={() => 文件选择框.current?.click()}>
          <span className={样式.上传图标}>⬆</span>
          {已选简历名 === null ? (
            <span className={`${样式.选择占位} 单行`}>上传简历，自动预填可识别的信息</span>
          ) : (
            <span className={`${样式.选择值} 单行`}>{已选简历名}</span>
          )}
          <span className={样式.选择尖}>›</span>
        </button>
        <input
          ref={文件选择框}
          type="file"
          accept=".pdf"
          className={样式.隐藏文件框}
          onChange={选中简历文件}
        />

        {/* 在校状态只用来安排资料填写顺序，不限制求职类型。 */}
        <div className={`${样式.节问} ${样式.节问间距}`}>你目前是否在校？</div>
        <div className={样式.双选行}>
          {([true, false] as const).map((值) => (
            <button
              key={String(值)}
              className={`${样式.选钮} ${是学生 === 值 ? 样式.选钮当前 : ''} 可点`}
              onClick={() => 选身份(值)}
              aria-pressed={是学生 === 值}
            >
              {值 ? '在校' : '已毕业'}
            </button>
          ))}
        </div>
        <div className={样式.选钮副行}>
          仅用于安排后续资料填写，不会限制你可选的机会类型
        </div>

        {/* 求职类型与办公方式必须结构化采集，才能与招聘端字段做确定性筛选。 */}
        <div className={`${样式.节问} ${样式.节问间距}`}>主要想找哪类机会？</div>
        <div className={样式.猜片行}>
          {求职类型选项.map((项) => {
            const 选中 = 筛选偏好.求职类型.includes(项);
            return (
              <button
                key={项}
                className={`${样式.猜片} ${选中 ? 样式.猜片选中 : ''} 可点`}
                onClick={() => 存筛选偏好({ 求职类型: [项] })}
                aria-pressed={选中}
              >
                {项}
              </button>
            );
          })}
        </div>
        <div className={样式.选钮副行}>先选一个主要方向，进入后可继续添加其他求职意向</div>

        {筛选偏好.求职类型.includes('校园招聘') ? (
          <>
            <div className={`${样式.节问} ${样式.节问间距}`}>预计毕业时间</div>
            <input
              className={样式.资料输入}
              type="month"
              value={筛选偏好.毕业时间 ?? ''}
              aria-label="预计毕业时间"
              onChange={(事件) => 存筛选偏好({ 毕业时间: 事件.target.value })}
            />
          </>
        ) : null}

        {筛选偏好.求职类型.includes('实习生') ? (
          <>
            <div className={`${样式.节问} ${样式.节问间距}`}>实习可用时间</div>
            <div className={样式.猜片行}>
              {[1, 3, 6].map((月数) => (
                <button
                  key={月数}
                  className={`${样式.猜片} ${筛选偏好.实习月数 === 月数 ? 样式.猜片选中 : ''} 可点`}
                  onClick={() => 存筛选偏好({ 实习月数: 月数 })}
                  aria-pressed={筛选偏好.实习月数 === 月数}
                >
                  至少 {月数} 个月
                </button>
              ))}
            </div>
            <div className={样式.猜片行}>
              {[2, 3, 4, 5].map((天数) => (
                <button
                  key={天数}
                  className={`${样式.猜片} ${筛选偏好.每周到岗天数 === 天数 ? 样式.猜片选中 : ''} 可点`}
                  onClick={() => 存筛选偏好({ 每周到岗天数: 天数 })}
                  aria-pressed={筛选偏好.每周到岗天数 === 天数}
                >
                  每周 {天数} 天
                </button>
              ))}
            </div>
            <div className={`${样式.节问} ${样式.节问间距}`}>最早可开始实习日期</div>
            <input
              className={样式.资料输入}
              type="date"
              value={筛选偏好.实习开始日期 ?? ''}
              aria-label="最早可开始实习日期"
              onChange={(事件) => 存筛选偏好({ 实习开始日期: 事件.target.value })}
            />
          </>
        ) : null}

        <div className={`${样式.节问} ${样式.节问间距}`}>作品集或项目链接（可选）</div>
        <input
          className={样式.资料输入}
          type="url"
          inputMode="url"
          value={筛选偏好.作品集链接 ?? ''}
          placeholder="https://"
          aria-label="作品集或项目链接"
          onChange={(事件) => 存筛选偏好({ 作品集链接: 事件.target.value })}
        />

        <div className={`${样式.节问} ${样式.节问间距}`}>可接受的办公方式</div>
        <div className={样式.猜片行}>
          {办公方式选项.map((项) => {
            const 选中 = 筛选偏好.办公方式.includes(项);
            return (
              <button
                key={项}
                className={`${样式.猜片} ${选中 ? 样式.猜片选中 : ''} 可点`}
                onClick={() => 存筛选偏好({ 办公方式: 切多选(筛选偏好.办公方式, 项) })}
                aria-pressed={选中}
              >
                {项}
              </button>
            );
          })}
        </div>

        {/* ── 希望在哪里工作：多选（上限 10），点行进全屏选择页 ── */}
        <div className={`${样式.节问} ${样式.节问间距}`}>希望在哪里工作</div>
        <button className={`${样式.选择行} 可点`} onClick={() => 跳转(路径.选工作城市)}>
          <span className={样式.选择值}>{城市们.join('、')}</span>
          <span className={样式.选择尖}>›</span>
        </button>

        {/* ── 期望的职位：多选（上限 10），点行进全屏选择页 ── */}
        <div className={`${样式.节问} ${样式.节问间距}`}>期望的职位是（可多选）</div>
        <button className={`${样式.选择行} 可点`} onClick={() => 跳转(路径.选期望职位)}>
          {已选职位.length === 0 ? (
            <span className={样式.选择占位}>选择期望职位</span>
          ) : (
            <span className={样式.选择值}>{已选职位.join('、')}</span>
          )}
          <span className={样式.选择尖}>›</span>
        </button>
      </滚动区>

      <主按钮
        文字="下一步"
        按下={下一步}
        禁用={已选职位.length === 0 || 求职初筛缺失项(筛选偏好).length > 0}
      />
    </次级页外壳>
  );
}
