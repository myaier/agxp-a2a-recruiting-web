  // 权威解析坐标 → 操作层推进。只在活轮在场时转交（inactive 轮零触碰：带旧附件
  // 直接进来不激活也不读取）；「轮从无到有」（激活/恢复落地）也触发一次推进，
  // 关掉「上传先落库、激活后到」的竞态窗口。重复调用由操作层单飞收敛。
  const 预填轮在场 = 预填.phase !== 'inactive';
  useEffect(() => {
    if (!是后端 || !预填轮在场 || 解析坐标 === '') return;
    void 操作.同步候选Onboarding解析();
  }, [是后端, 预填轮在场, 解析坐标, 操作]);

