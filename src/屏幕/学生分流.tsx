// 学生分流 —— 选完「求职者」后的第一问：还在读书吗？
//
// 为什么放在最前面：学生和有经验的人后续要填的东西完全不同
// （在读学历/毕业年 vs 开始工作年，实习经历 vs 工作经历，到岗档也不同），
// 越早分流，后面每一屏越干净。答案落 全局.基本信息.身份（在校 / 在职），
// 基本信息、工作经历、引导问答三屏都读它分支。
//
// 视觉沿用「选身份」注册页那套叠卡手法：选中的浮起、未选的压平退淡。
// 卡内容自己画：在校学生 = 荧光绿底，已有工作经验 = 墨底，各配一行事实副行。

import { useState } from 'react';
import 样式 from './学生分流.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';

/** 两条路径的键：在校 → 学生路径；有经验 → 社招路径 */
type 路径键 = '在校' | '有经验';

const 选项列表: { 键: 路径键; 标题: string; 副行: string }[] = [
  { 键: '在校', 标题: '在校学生', 副行: '校招与实习岗位 · 不卡年限' },
  { 键: '有经验', 标题: '已有工作经验', 副行: '社招岗位 · 按工作年限核对' },
];

export default function 学生分流() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  // 默认选中跟着全局身份走：退回本屏重选时，之前的选择还在
  const [选中, 设选中] = useState<路径键>(全局.基本信息.身份 === '在校' ? '在校' : '有经验');

  const 继续 = () => {
    const 旧 = 全局.基本信息;
    // 选「在校」→ 身份=在校；选「有经验」→ 若此前是在校则落回在职，
    // 已是在职/离职的保持不动（离职是基本信息屏才细分的档，这里不覆盖）
    const 新身份 = 选中 === '在校' ? '在校' : 旧.身份 === '在校' ? '在职' : 旧.身份;
    // 学生没有工龄：清掉演示种子残留的 开始工作年，防止后面按「有工龄=社招」误判
    const 新开始工作年 = 选中 === '在校' ? '' : 旧.开始工作年;
    // 走已有的整快照存简历动作，不造平行存储
    派发({
      型: '存简历',
      经历: 全局.简历经历,
      教育: 全局.简历教育,
      技能: 全局.简历技能,
      证书: 全局.简历证书,
      基本信息: { ...旧, 身份: 新身份, 开始工作年: 新开始工作年 },
    });
    跳转(路径.引导说明);
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题 标题="还在读书吗？" />

      <div className={样式.选面区}>
        {选项列表.map((项) => {
          const 当前 = 选中 === 项.键;
          return (
            <button
              key={项.键}
              className={`${样式.选面壳} ${当前 ? 样式.选面当前 : 样式.选面退后} 可点`}
              onClick={() => 设选中(项.键)}
              aria-pressed={当前}
            >
              <span
                className={`${样式.分流面} ${项.键 === '在校' ? 样式.面在校 : 样式.面有经验}`}
              >
                <span className={样式.面主标}>{项.标题}</span>
                <span className={样式.面副行}>{项.副行}</span>
              </span>
            </button>
          );
        })}
      </div>

      <主按钮 文字="继续" 按下={继续} />
    </次级页外壳>
  );
}
