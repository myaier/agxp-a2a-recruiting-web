  //    {下限:0,上限:0} = 明确面议、其余 = 区间；单位跟随主要求职类型（实习生按日薪）。
  //    抽屉只改临时值（薪资区间层 自己持有），确定才 存薪资预填（携带当前城市/职位
  //    基底），取消 / 遮罩 / Escape 零回填。──
  const 薪资单位 = 判断求职薪资单位(筛选偏好);
