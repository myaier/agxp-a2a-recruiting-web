/**
 * 「全部意向」档下按意向分组。
 * 一屏里混着几条意向的在谈单，不分组就看不出哪张卡属于哪条意向 ——
 * 而「一份简历挂多个意向、各自独立谈」正是要在这一屏里看得见的东西。
 * 组序跟 求职意向表（= 顶栏胶囊的顺序）；意向已被删掉的孤儿单排在最后各成一组，
 * 不静默藏起来 —— 它们本来就是「统计里有、列表里找不到」的那部分。
 */
function 按意向分组(列表: 在谈单[], 意向表: 求职意向[]): { 名: string; 单们: 在谈单[] }[] {
  const 表内序 = 意向表.map((条) => 取意向名(条.标题));
  const 出现过 = [...new Set(列表.map((单) => 单.意向))];
  const 组序 = [
    ...表内序.filter((名) => 出现过.includes(名)),
    ...出现过.filter((名) => !表内序.includes(名)),
  ];
  return 组序.map((名) => ({ 名, 单们: 列表.filter((单) => 单.意向 === 名) }));
}

export default function 在谈首页() {
  const { 数据源模式 } = use应用状态();
  return 数据源模式 === 'backend' ? <Backend在谈首页 /> : <Mock在谈首页 />;
}

/** Backend 分支（P5）：open 工作区快照 + MatchCase列表；Mock 的在谈单对象一概不读。 */
function Backend在谈首页() {
  const { 状态, 后端状态, 操作 } = use应用状态();
  const { 跳转 } = use导航();

  // 范围档只读：看全部在谈 置「全部」、切意向 收回「当前」（切换面板已删，2026-09-09）
  const 范围 = 状态.在谈范围;

  // 当前档的过滤坐标 = 当前意向编号 载体本身（顶栏胶囊、市场 P4 同一来源）。
  // 绝不按意向名反查 —— 名字不唯一，同名两条会反查到第一条。
  // 护栏：当前编号无效（不在表内 / 服务端不是 active）时这一档整片空掉，
  // 绝不拿别的坐标顶上、也不偷偷放宽成全部。
  const 当前编号 = 取有效当前意向编号(状态.当前意向编号, 状态.求职意向表, 状态.后端意向服务端);
  const filterRef = 范围 === '全部' ? null : 当前编号;
  const 当前意向仍在表内 = 当前编号 !== null;

  const 有scope = 当前意向仍在表内 || 范围 === '全部';
  const 快照 = 有scope
    ? 后端状态.P5工作区?.[P5范围键.open('candidate', filterRef)]
    : undefined;
  // 横幅四态投影复用共享纯 selector（与「看市场」同一在谈范围同一口径）：
  // owner 不匹配（同角色换主体的过渡帧）按未载入处理，绝不显示旧主体的待办数
  const 当前SubjectId = 后端状态.主体?.last_used_role === 'candidate'
    ? 后端状态.主体.subject_id
    : null;
  const 横幅状态 = 取P5候选横幅状态(快照, 当前SubjectId, 有scope);
  const 横幅强调 = 横幅状态.强调;

  // 下拉只重读当前 scope（GET）；错误文案由快照 error 承载，列表上方错误行呈现
  const 重读当前范围 = () =>
    有scope
      ? 操作.刷新工作区('candidate', filterRef).catch(() => undefined)
      : undefined;

  return (
    <主页外壳>
      <顶部意向栏 跨意向={范围 === '全部'} />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={横幅强调}
        // 交付 G：Backend 的代理页是导航说明而非自由对话，入口文案不许承诺「问AI代理」
        动作文="查看代理功能 ›"
        按下={() => 跳转(路径.问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新 刷新={重读当前范围}>
      <滚动区>
        {范围 === '当前' && !当前意向仍在表内 ? (
          <div className={样式.空态}>这个意向下暂时没有在谈职位。</div>
        ) : (
          // eslint-disable-next-line jsx-a11y/aria-role -- role 是 P5 域 prop，非 ARIA role
          <MatchCase列表 role="candidate" filterRef={filterRef} />
        )}
      </滚动区>
      </下拉刷新>
    </主页外壳>
  );
}

/** Mock 原型分支：静态在谈表 + 全局归约，行为与接线前逐字一致。 */
function Mock在谈首页() {
  const { 状态 } = use应用状态();
  // 进入首页先给一小段加载体感（标注意见：用户进来应该有加载过程）
  const 数据就绪 = use模拟加载();
  const { 跳转 } = use导航();

  // 范围档在全局（应用状态.在谈范围）：「我的」的「待你拍」点着直接落到「全部意向」档上
  // （看全部在谈 归约），切意向 再收回「当前」；本屏没有切换 UI（2026-09-09 删筛选）。
  const 范围 = 状态.在谈范围;

  // 等你行动的卡置顶，其余保持原顺序
  // 标注意见 #9：切意向后列表跟着变 —— 当前档只显示归属当前意向的在谈单。
  // 过滤键锚在 求职意向表 上（顶栏胶囊也是由它渲染的），不直接信 当前意向 这个裸字符串：
  // 意向被删光时 当前意向 是空串，这里必须整片空掉，不能把上一个意向的在谈单继续挂着。
  const 当前意向仍在表内 = 状态.求职意向表.some((条) => 取意向名(条.标题) === 状态.当前意向);
  // 全部意向档刻意不做上面那道过滤：跨意向看全就是这一档存在的理由，
  // 连意向已被删掉的孤儿单也一并露出来（它们在当前档下永远看不见）
  const 范围内列表 =
    范围 === '全部'
      ? 状态.在谈列表
      : 当前意向仍在表内
        ? 状态.在谈列表.filter((单) => 单.意向 === 状态.当前意向)
        : [];
  const 待协调数 = 范围内列表.filter((单) => 单.需要你).length;

  // 2026-09-09 产品负责人定稿删筛选：「看哪几单」（全部 / 待我拍板 / 进行中）不再过滤列表，
  // 列表固定显示范围内全部单 —— 在谈看什么 字段保留但本屏不读；「待你拍」落地后
  // 等你行动的卡本来就置顶（8/25 产品负责人认可的排序），不用再单独筛出来。
  const 排序后 = [...范围内列表].sort((甲, 乙) => Number(乙.需要你) - Number(甲.需要你));
  const 分组后 = 按意向分组(排序后, 状态.求职意向表);

  return (
    <主页外壳>
      <顶部意向栏 跨意向={范围 === '全部'} />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={待协调数 > 0 ? `${待协调数} 个职位需要你协调` : '暂时没有需要你介入的'}
        按下={() => 跳转(路径.问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {!数据就绪 ? (
            <骨架卡组 张数={3} />
          ) : 排序后.length === 0 ? (
            <div className={样式.空态}>
              {范围 === '全部' ? '全部意向下' : '这个意向下'}暂时没有在谈职位。
              <br />
              去「看市场」挑几个，让AI代理替你去谈。
            </div>
          ) : 范围 === '全部' ? (
            // 全部意向档：按意向分组，每组一条组名 —— 卡片本身一个像素都不改
            分组后.map((组) => (
              <div key={组.名} className={样式.分组}>
                <div className={样式.分组标}>{组.名}</div>
                {组.单们.map((单) => (
                  <在谈卡 key={单.编号} 单={单} 按下={() => 跳转(路径.在谈详情(单.编号))} />
                ))}
              </div>
            ))
          ) : (
            排序后.map((单) => (
              <在谈卡 key={单.编号} 单={单} 按下={() => 跳转(路径.在谈详情(单.编号))} />
            ))
          )}
        </div>
      </滚动区>
      </下拉刷新>
    </主页外壳>
  );
}

function 在谈卡({ 单, 按下 }: { 单: 在谈单; 按下: () => void }) {
  // 分从行来(2026-08-31):卡上的环与详情页同一份计算分
  const 计算适配分 = use适配分(单);
  return (
    <白卡 按下={按下} 类名={样式.卡}>
      {/* 公司头行：右侧列 = 适配环，薪资挂在环正下方（标注 2026-08-18：卡太高，
          金额挪到适配下面）—— 右列吃掉一行，卡整体矮一截 */}
      <div className={样式.公司头行}>
        <公司字标 首字={单.公司首字} 公司名={单.公司} 尺寸={34} 圆角={10} 字号={14} />
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className={`${样式.公司名} 单行`}>{单.公司}</div>
          <div className={`${样式.公司简介} 单行`}>{单.公司简介}</div>
        </div>
        <div className={样式.右列}>
          <适配环 分={计算适配分} 标={null} />
          <span className={`${样式.薪资} 薪资体`}>{单.薪资.replace('-', '–')}</span>
        </div>
      </div>

      {/* 职位名（薪资已上移到右列） */}
      <div className={`${样式.职位名} 单行`}>{单.职位}</div>

      {/* 标签行 */}
      <div className={样式.标签行}>
        {单.标签.map((标签) => (
          <span key={标签} className={样式.标签}>
            {标签}
          </span>
        ))}
      </div>

      {/* 阶段区 */}
      <div className={样式.阶段区}>
        {/* 标注 11:07：下一步文字并到阶段标签同一行 */}
        <div className={样式.阶段头}>
          <阶段标签 阶段={单.阶段} 待你={单.需要你} />
          <div className={`${样式.下一步} 单行`}>{单.下一步}</div>
          <span style={{ color: 'var(--最弱)', fontSize: 16, fontWeight: 300 }}>›</span>
        </div>

        {/* 标注 18:00：卡上小字全部去掉（轮次 / 分歧轴 / 辅助文案），
            靠「下一步」大字表达；数字对比进详情页看 */}
      </div>
    </白卡>
  );
}
