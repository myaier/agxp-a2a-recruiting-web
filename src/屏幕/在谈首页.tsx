// A6·L 在谈·档案卡版 —— 求职端定稿首页。
//
// 卡片结构（视觉规范 v2，2026-08-18）：公司头行（字标 + 公司名/简介 +
// 右列[适配环 + 薪资]）→ 职位名 → 标签行 → 发丝线 → 阶段标签 + 轮次 → 下一步 + ›
// → 辅助文案 或 分歧对比轴。与看市场卡同一骨架，在谈/看市场切换时卡形不跳。
//
// 两条交互硬规矩（来自设计稿）：
//   · 等你行动的卡置顶；紧急感只由红色阶段标 + 「需要你」胶囊表达（用户否了卡级红标记）
//   · 卡上不放决策按钮，决策一律进详情页做

import { useState } from 'react';
import 样式 from './在谈首页.module.css';
import 下拉刷新 from '../组件/下拉刷新';
import 顶部意向栏 from './顶部意向栏';
import { 主页外壳, 代理横幅, 阶段标签, 滚动区, 白卡, 公司字标, use模拟加载, 骨架卡组 } from '../组件/通用';
import 适配环 from '../组件/适配环';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import type { 在谈单 } from '../数据/类型';

export default function 在谈首页() {
  const { 状态 } = use应用状态();
  // 进入首页先给一小段加载体感（标注意见：用户进来应该有加载过程）
  const 数据就绪 = use模拟加载();
  const { 跳转 } = use导航();

  // 等你行动的卡置顶，其余保持原顺序
  // 标注意见 #9：切意向后列表跟着变 —— 只显示归属当前意向的在谈单
  const 本意向列表 = 状态.在谈列表.filter((单) => 单.意向 === 状态.当前意向);
  const 待协调数 = 本意向列表.filter((单) => 单.需要你).length;

  // 状态胶囊（用户 2026-08-21 定：在谈筛的是「现在先看哪几单」，纯视图态，不写成代理规则）
  const [看什么, 设看什么] = useState<'全部' | '待我拍板' | '进行中'>('全部');
  const 过滤后 = 本意向列表.filter((单) =>
    看什么 === '全部' ? true : 看什么 === '待我拍板' ? 单.需要你 : !单.需要你
  );
  const 排序后 = [...过滤后].sort((甲, 乙) => Number(乙.需要你) - Number(甲.需要你));

  return (
    <主页外壳>
      <顶部意向栏 />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={待协调数 > 0 ? `${待协调数} 个职位需要你协调` : '暂时没有需要你介入的'}
        按下={() => 跳转(路径.问AI代理)}
      />

      {/* 状态胶囊：一步可达「待我拍板」，比藏进筛选面板快 */}
      <div className={样式.状态行}>
        {(['全部', '待我拍板', '进行中'] as const).map((项) => (
          <button
            key={项}
            className={`${样式.状态片} ${看什么 === 项 ? 样式.状态片选中 : ''} 可点`}
            onClick={() => 设看什么(项)}
          >
            {项}
            {项 === '待我拍板' && 待协调数 > 0 ? (
              <span className={`${样式.状态数} 等宽数字`}>{待协调数}</span>
            ) : null}
          </button>
        ))}
      </div>

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {!数据就绪 ? (
            <骨架卡组 张数={3} />
          ) : 排序后.length === 0 ? (
            <div className={样式.空态}>
              {看什么 === '全部' ? (
                <>
                  这个意向下暂时没有在谈职位。
                  <br />
                  去「看市场」挑几个，让AI代理替你去谈。
                </>
              ) : (
                `没有${看什么}的职位`
              )}
            </div>
          ) : (
            排序后.map((单) => (
              <在谈卡 key={单.编号} 单={单} 按下={() => 跳转(路径.在谈详情(单.编号))} />
            ))
          )}
        </div>
      </滚动区>
      </下拉刷新>
    </主页外壳>
  );
}

function 在谈卡({ 单, 按下 }: { 单: 在谈单; 按下: () => void }) {
  return (
    <白卡 按下={按下} 类名={样式.卡}>
      {/* 公司头行：右侧列 = 适配环，薪资挂在环正下方（标注 2026-08-18：卡太高，
          金额挪到适配下面）—— 右列吃掉一行，卡整体矮一截 */}
      <div className={样式.公司头行}>
        <公司字标 首字={单.公司首字} 公司名={单.公司} 尺寸={34} 圆角={10} 字号={14} />
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className={`${样式.公司名} 单行`}>{单.公司}</div>
          <div className={`${样式.公司简介} 单行`}>{单.公司简介}</div>
        </div>
        <div className={样式.右列}>
          <适配环 分={单.适配分} 标={null} />
          <span className={`${样式.薪资} 薪资体`}>{单.薪资.replace('-', '–')}</span>
        </div>
      </div>

      {/* 职位名（薪资已上移到右列） */}
      <div className={`${样式.职位名} 单行`}>{单.职位}</div>

      {/* 标签行 */}
      <div className={样式.标签行}>
        {单.标签.map((标签) => (
          <span key={标签} className={样式.标签}>
            {标签}
          </span>
        ))}
      </div>

      {/* 阶段区 */}
      <div className={样式.阶段区}>
        {/* 标注 11:07：下一步文字并到阶段标签同一行 */}
        <div className={样式.阶段头}>
          <阶段标签 阶段={单.阶段} 待你={单.需要你} />
          <div className={`${样式.下一步} 单行`}>{单.下一步}</div>
          <span style={{ color: 'var(--最弱)', fontSize: 16, fontWeight: 300 }}>›</span>
        </div>

        {/* 标注 18:00：卡上小字全部去掉（轮次 / 分歧轴 / 辅助文案），
            靠「下一步」大字表达；数字对比进详情页看 */}
      </div>
    </白卡>
  );
}
