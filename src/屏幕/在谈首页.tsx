// 卡片结构（视觉规范 v2，2026-08-18）：公司头行（字标 + 公司名/简介 +
// 右列[适配环 + 薪资]）→ 职位名 → 标签行 → 发丝线 → 阶段标签 + 轮次 → 下一步 + ›
// → 辅助文案 或 分歧对比轴。与看市场卡同一骨架，在谈/看市场切换时卡形不跳。
//
// 两条交互硬规矩（来自设计稿）：
//   · 等你行动的卡置顶；紧急感只由红色阶段标 + 「需要你」胶囊表达（用户否了卡级红标记）
//   · 卡上不放决策按钮，决策一律进详情页做

