// 求职状态（/onboard/status）—— 2026-08-20 按 BOSS 截图顺序重排：
// 原引导问答的「到岗节奏」题挪成独立屏，2×2 方块单选。
//
// 档位常量自 引导问答.tsx 原样挪来：学生 4 档全程「在校 ·」措辞，
// 社会人 4 档不混出「在校」。答案落 全局.引导预填.到岗（引导问答已删该题）；
// 社会人档位自带 在职/离职 前缀，顺手同步 基本信息.身份 —— 这是该字段
// 在新流程里的唯一采集口（原 基本信息 屏的身份快捷片已删）。
//
// 日常编辑（Task 1 / Spec §6，URL ?from=resume / ?from=intentions）：这一屏同时是
// 「我的简历 → 当前状态」与「求职意向管理 → 求职状态」的落点。带合法日常来源时只读
// 权威 profile 三态（在校/在职/离职，空值不假选），保存走既有简历写入并传 日常编辑，
// 成功后按来源退一格回原列表（我的简历 / 求职意向管理），不派发到岗、不确认 basic；
// 无来源时保持注册旅程的到岗档位采集，逐字不变。

import { useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import 样式 from './入职引导.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import 求职状态编辑正文 from '../组件/求职状态编辑正文';
import { 轻提示 } from '../组件/轻提示';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 取后端错误文案 } from '../数据/HTTP客户端';
import { 读候选编辑来源, use候选编辑退出 } from '../流程/候选日常编辑';
import { 并入建档草稿 } from '../流程/onboarding配置';
import { 路径 } from '../路由/路径表';

interface 到岗项 {
  键: string;
  徽标?: string;
}

// 到岗档按学生分流分两组（2026-08-19）：学生全程「在校 ·」措辞，社会人不再混出「在校」档。
// 此前混排一列时应届生只能在「离职 · 随时到岗」和「在职」之间硬选，代理据此谈到岗时间会谈错。
const 学生到岗选项: 到岗项[] = [
  { 键: '在校 · 离校随时到岗', 徽标: '应届优先' },
  { 键: '在校 · 月内到岗' },
  { 键: '在校 · 考虑机会' },
  { 键: '在校 · 暂不考虑' },
];

const 社会人到岗选项: 到岗项[] = [
  { 键: '离职 · 随时到岗', 徽标: '优先推荐' },
  { 键: '在职 · 月内到岗', 徽标: '优先推荐' },
  { 键: '在职 · 考虑机会' },
  { 键: '在职 · 暂不考虑' },
];

export default function 求职状态() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发, 操作, 数据源模式 } = use应用状态();
  const 是后端 = 数据源模式 === 'backend';
  // 日常编辑来源（合同 A，Task 1）：resume = 我的简历，intentions = 求职意向管理，
  // 二者共用同一份三态编辑（Spec §6）；白名单外的来源值不当日常，走注册旅程的档位采集。
  const [查询参数] = useSearchParams();
  const 来源 = 读候选编辑来源(查询参数.toString());
  const 日常 = 来源 !== null;
  // 日常出口：有来路证明退一格回原列表，否则安全替换回来源固定路径（我的简历/意向管理）
  const 退出编辑 = use候选编辑退出(来源 ?? 'resume');
  // 日常编辑的局部选择：初值取已水合权威 profile 身份（空值不假选，刷新读权威）
  const [日常选择, 设日常选择] = useState(全局.基本信息.身份);
  const [保存中, 设保存中] = useState(false);
  // J-PILOT-02 Task 4：/basic 的姓名/生日在空身份那一步没有发过 profile —— 刷新后
  // 它们只在建档草稿里。身份在这一屏收口，profile 写入必须带上草稿里的那几项。
  // 旅程标记见 基本信息.tsx：带合法日常来源的完整位置绝不算注册旅程，判据同一套
  const 旅程中 = 是后端 && 全局.引导预填 !== null && 来源 === null;
  const 建档 = 旅程中 ? 全局.引导预填?.建档 : undefined;
  const 草稿基本 = 建档?.资料?.基本信息;
  const 在校中 = (草稿基本?.身份 ?? 全局.基本信息.身份) === '在校';
  const 选项 = 在校中 ? 学生到岗选项 : 社会人到岗选项;
  // M：身份选择是 profile 的收口页 —— 进入页面时身份为空意味着 /basic 的姓名/生日
  // 还在 Context 草稿里，保存成功后要先确认 basic 分区再继续（用初值锁定，不被
  // 保存后的水合重渲染改写）
  const [进入时空身份] = useState((草稿基本?.身份 ?? 全局.基本信息.身份) === '');

  // M：不设默认档 —— 未选择就是 null，点下一步给出可见提示，不替用户做决定
  const [当前, 设当前] = useState<string | null>(全局.引导预填?.到岗 ?? null);

  /** 日常保存（Spec §6）：只读 profile 三态、single-flight、传 日常编辑；不派发到岗、
   *  不确认 basic、零建档草稿；成功才按来源退出，失败留页保留选择。 */
  const 日常保存 = async () => {
    if (保存中) return;
    if (日常选择 === '') {
      轻提示('请选择当前求职状态');
      return;
    }
    设保存中(true);
    try {
      await 操作.保存简历({
        基本信息: { ...全局.基本信息, 身份: 日常选择 },
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 全局.简历教育,
        证书: 全局.简历证书,
      }, '日常编辑');
    } catch (错误) {
      轻提示(取后端错误文案(错误));
      设保存中(false);
      return;
    }
    设保存中(false);
    退出编辑();
  };

  const 下一步 = async () => {
    if (当前 === null) {
      轻提示('请选择当前求职状态');
      return;
    }
    // 社会人档位自带 在职/离职 前缀：据此落非空身份（学生保持 在校 不动）；
    // 把此前累积的 Context 草稿（/basic 姓名/生日等）随本次 profile 写入一并收口
    const 新身份 = 在校中 ? ('在校' as const) : 当前.startsWith('离职') ? ('离职' as const) : ('在职' as const);
    // 先把本次身份并进草稿：保存失败（或刷新）时这一步的选择与前面几屏的输入都还在
    if (旅程中) {
      操作.更新候选建档草稿(并入建档草稿(建档, { 资料: { 基本信息: { ...草稿基本, 身份: 新身份 } } }));
    }
    try {
      // 注册旅程不传保存来源（缺省 = 现行 onboarding 跟踪行为）
      await 操作.保存简历({
        基本信息: { ...全局.基本信息, ...草稿基本, 身份: 新身份 },
        个人优势: 全局.个人优势,
        技能: 全局.简历技能,
        经历: 全局.简历经历,
        教育: 全局.简历教育,
        证书: 全局.简历证书,
      });
    } catch (错误) {
      轻提示(取后端错误文案(错误));
      return;
    }
    if (进入时空身份) 操作.确认候选Onboarding预填分区('basic');
    // Task 5B：草稿动作自带基底 —— 求职状态传全局草稿值（缺席则各用空数组）
    派发({
      型: '存到岗预填',
      到岗: 当前,
      城市们: 全局.引导预填?.城市们 ?? [],
      职位: 全局.引导预填?.职位 ?? [],
      城市引用们: 全局.引导预填?.城市引用们 ?? [],
      职位引用们: 全局.引导预填?.职位引用们 ?? [],
    });
    // Task 3（合同 C）：两身份同一主序 —— 状态收口之后都进学历四页（最高学历 → 毕业院校
    // → 专业 → 就读时间段），简历资料与补充偏好都排在教育之后。原来学生在这里直接跳向
    // 向导（状态排在资料之后），是主顺序的唯一分叉点，本次取消。
    跳转(路径.最高学历);
  };

  // 日常编辑（三态正文，保存/取消由本页承担）：返回=取消，退出整链不写
  if (日常) {
    return (
      <次级页外壳 白底>
        <返回栏 返回={退出编辑} />

        <页面大标题 标题="现在是什么状态？" />

        <滚动区 样式覆盖={{ padding: '48px 18px 12px' }}>
          <求职状态编辑正文 值={日常选择} 修改={设日常选择} />
        </滚动区>

        <主按钮 文字="保存" 按下={() => { void 日常保存(); }} />
      </次级页外壳>
    );
  }

  return (
    <次级页外壳 白底>
      <返回栏 返回={返回} />

      {/* 说明句按标注 2026-08-24 删除（「把这个中间的小文案删掉，保持原来的
          位置不变」）—— 滚动区上内边距 18→48 补回删句的高度，方块网格不上移 */}
      <页面大标题 标题="现在是什么状态？" />

      <滚动区 样式覆盖={{ padding: '48px 18px 12px' }}>
        <div className={样式.方块网格}>
          {选项.map((项) => {
            const 选中 = 当前 === 项.键;
            return (
              <button
                key={项.键}
                className={`${样式.方块} ${选中 ? 样式.方块选中 : ''} 可点`}
                onClick={() => 设当前(项.键)}
                aria-pressed={选中}
              >
                <span className={样式.方块题}>{项.键}</span>
                {项.徽标 ? <span className={样式.徽标}>{项.徽标}</span> : null}
              </button>
            );
          })}
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
