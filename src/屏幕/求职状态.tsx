// 求职状态（/onboard/status）—— 2026-08-20 按 BOSS 截图顺序重排：
// 原引导问答的「到岗节奏」题挪成独立屏，2×2 方块单选。
//
// 档位常量自 引导问答.tsx 原样挪来：学生 4 档全程「在校 ·」措辞，
// 社会人 4 档不混出「在校」。答案落 全局.引导预填.到岗（引导问答已删该题）；
// 社会人档位自带 在职/离职 前缀，顺手同步 基本信息.身份 —— 这是该字段
// 在新流程里的唯一采集口（原 基本信息 屏的身份快捷片已删）。

import { useState } from 'react';
import 样式 from './入职引导.module.css';
import { 次级页外壳, 返回栏, 页面大标题, 主按钮, 滚动区 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { use应用状态 } from '../状态/应用状态';
import { 路径 } from '../路由/路径表';

interface 到岗项 {
  键: string;
  徽标?: string;
}

// 到岗档按学生分流分两组（2026-08-19）：学生全程「在校 ·」措辞，社会人不再混出「在校」档。
// 此前混排一列时应届生只能在「离职 · 随时到岗」和「在职」之间硬选，代理据此谈到岗时间会谈错。
const 学生到岗选项: 到岗项[] = [
  { 键: '在校 · 离校随时到岗', 徽标: '应届优先' },
  { 键: '在校 · 月内到岗' },
  { 键: '在校 · 考虑机会' },
  { 键: '在校 · 暂不考虑' },
];

const 社会人到岗选项: 到岗项[] = [
  { 键: '离职 · 随时到岗', 徽标: '优先推荐' },
  { 键: '在职 · 月内到岗', 徽标: '优先推荐' },
  { 键: '在职 · 考虑机会' },
  { 键: '在职 · 暂不考虑' },
];

export default function 求职状态() {
  const { 跳转, 返回 } = use导航();
  const { 状态: 全局, 派发 } = use应用状态();
  const 在校中 = 全局.基本信息.身份 === '在校';
  const 选项 = 在校中 ? 学生到岗选项 : 社会人到岗选项;

  // 默认档跟着身份走（沿用原到岗题的推法）；退回本屏时已选的档还在
  const [当前, 设当前] = useState(
    全局.引导预填?.到岗 ??
      (在校中
        ? '在校 · 离校随时到岗'
        : 全局.基本信息.身份 === '离职'
          ? '离职 · 随时到岗'
          : '在职 · 考虑机会')
  );

  const 下一步 = () => {
    派发({ 型: '存到岗预填', 到岗: 当前 });
    // 社会人档位自带 在职/离职 前缀：同步 基本信息.身份（学生保持 在校 不动）
    if (!在校中) {
      const 新身份 = 当前.startsWith('离职') ? ('离职' as const) : ('在职' as const);
      if (新身份 !== 全局.基本信息.身份) {
        派发({
          型: '存简历',
          经历: 全局.简历经历,
          教育: 全局.简历教育,
          技能: 全局.简历技能,
          证书: 全局.简历证书,
          基本信息: { ...全局.基本信息, 身份: 新身份 },
        });
      }
    }
    // 分叉：学生的学业档案已在前面填完，这里直接进向导；非学生继续学历四连页。
    // 判据用上面算好的 在校中，不再读 全局.基本信息.身份 —— 那是本次 render 闭包里的旧值，
    // 上面刚派发的 存简历 还没生效，一旦跳转条件细化到区分 在职/离职 就会跳错
    跳转(在校中 ? 路径.引导问答 : 路径.最高学历);
  };

  return (
    <次级页外壳>
      <返回栏 返回={返回} />

      <页面大标题
        标题="现在是什么状态？"
        说明="状态影响你被推荐的频率，以及AI代理的催问节奏。"
      />

      <滚动区 样式覆盖={{ padding: '18px 18px 12px' }}>
        <div className={样式.方块网格}>
          {选项.map((项) => {
            const 选中 = 当前 === 项.键;
            return (
              <button
                key={项.键}
                className={`${样式.方块} ${选中 ? 样式.方块选中 : ''} 可点`}
                onClick={() => 设当前(项.键)}
                aria-pressed={选中}
              >
                <span className={样式.方块题}>{项.键}</span>
                {项.徽标 ? <span className={样式.徽标}>{项.徽标}</span> : null}
              </button>
            );
          })}
        </div>
      </滚动区>

      <主按钮 文字="下一步" 按下={下一步} />
    </次级页外壳>
  );
}
