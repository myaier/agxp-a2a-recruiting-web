// D5·B 在谈候选 —— 企业端定稿首页（求职端 在谈首页 A6·L + 顶部意向栏 的同构镜像）。
//
// 镜像关系：意向切换 → 在招岗位切换；在谈卡 → 候选卡。
// 卡片结构：代号头行（头像 + 代号/真名 + 画像 + 匹配分）
// → 分隔线 → 阶段标签 + 轮次 → 下一步文案 + › → 辅助文案 或 分歧对比轴。
//
// 两条交互硬规矩（与求职端相同）：
//   · 需要你拍板的卡红描边并置顶
//   · 卡上不放决策按钮，决策一律进候选详情页做
//
// 双盲语义（业务硬约束）：意向确认前只显示代号（候选 A-01）与画像；
// 「候选确认意向」后 真名 才有值，头像换成真名首字 + 深绿底。

import 样式 from './企业在谈候选.module.css';
import { 主页外壳, 代理横幅, 阶段标签, 分歧轴, 滚动区, 白卡, 公司字标, use模拟加载, 骨架卡组 } from '../组件/通用';
import { 放大镜图标 } from '../组件/图标';
import { 轻提示 } from '../组件/轻提示';
import { use应用状态 } from '../状态/应用状态';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';
import type { 候选 } from '../数据/类型';

export default function 企业在谈候选() {
  const 数据就绪 = use模拟加载();
  const { 状态 } = use应用状态();
  const { 跳转 } = use导航();

  // 只看当前选中岗位的候选：顶栏切岗位原来不生效，切了还是整锅端出来
  const 本岗候选 = 状态.企业候选列表.filter((单) => 单.岗位编号 === 状态.当前岗位编号);
  // 需要你拍板的卡置顶（红描边），其余保持原顺序
  const 排序后 = [...本岗候选].sort((甲, 乙) => Number(乙.需要你) - Number(甲.需要你));
  const 待拍板数 = 本岗候选.filter((单) => 单.需要你).length;

  return (
    <主页外壳>
      <岗位切换栏 />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={待拍板数 > 0 ? `${待拍板数} 个候选需要你拍板` : '暂时没有需要你拍板的'}
        按下={() => 跳转(路径.企业问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <滚动区>
        <div className={样式.列表}>
          {!数据就绪 ? (
            <骨架卡组 张数={3} />
          ) : 排序后.length === 0 ? (
            <div className={样式.空态}>
              这个岗位暂无在谈候选，
              <br />
              去推荐里让AI代理接触几个
            </div>
          ) : (
            排序后.map((单) => (
              <候选卡 key={单.编号} 单={单} 按下={() => 跳转(路径.候选详情(单.编号))} />
            ))
          )}
        </div>
      </滚动区>
    </主页外壳>
  );
}

// ── 顶部岗位切换栏：求职端 顶部意向栏 的镜像 ──
// 意向切换 → 在招岗位切换；＋ = 发布新岗位；放大镜 = 自己去推荐里找人。
function 岗位切换栏() {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  // 顶栏只放在招岗位；已归档的去岗位管理页看
  const 在招岗位 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');

  return (
    <div className={样式.顶栏}>
      <div className={样式.岗位行}>
        {在招岗位.map((岗) => {
          const 选中 = 岗.编号 === 状态.当前岗位编号;
          return (
            <button
              key={岗.编号}
              className={`${选中 ? 样式.岗位选中 : 样式.岗位未选} 单行 可点`}
              onClick={() => 派发({ 型: '切当前岗位', 编号: 岗.编号 })}
            >
              {岗位名截短(岗.名称)}
            </button>
          );
        })}
        <span className={样式.岗位行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.发布岗位)}
            aria-label="发布新岗位"
          >
            ＋
          </button>
          <button
            className="可点"
            onClick={() => 派发({ 型: '企业切子视图', 子视图: '推荐' })}
            aria-label="搜索候选人"
            style={{ display: 'flex', alignItems: 'center' }}
          >
            <放大镜图标 />
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '推荐'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.企业子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '企业切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        <button className={`${样式.筛选} 可点`} onClick={() => 轻提示('筛选功能待接后端条件项')}>
          筛选 ▾
        </button>
      </div>
    </div>
  );
}

/** 岗位名截短：顶栏空间有限，只取「 · 」前的主名（资深后端工程师 · 交易网关 → 资深后端工程师） */
function 岗位名截短(名称: string): string {
  return 名称.split(' · ')[0];
}

// ── 候选卡：求职端 在谈卡 的镜像 ──
function 候选卡({ 单, 按下 }: { 单: 候选; 按下: () => void }) {
  // 双盲：意向确认且真名已互换，头像才换真名首字 + 深绿底；否则代号头像 + 灰绿底
  const 显示真名 = 单.阶段 === '意向确认' && 单.真名 ? 单.真名 : null;

  return (
    <白卡 按下={按下} 红描边={单.需要你} 类名={样式.卡}>
      {/* 代号头行（镜像求职端公司头行；匹配分替代薪资位） */}
      <div className={样式.头行}>
        <公司字标
          首字={显示真名 ? 显示真名.charAt(0) : 单.头像字}
          底色={显示真名 ? 'var(--深绿)' : 'var(--初筛底)'}
          字色={显示真名 ? 'var(--白)' : 'var(--初筛)'}
          描边={!显示真名}
          字号={显示真名 ? 15 : 13}
        />
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className={`${样式.代号名} 单行`}>{显示真名 ?? 单.代号}</div>
          <div className={`${样式.画像行} 单行`}>{单.画像}</div>
        </div>
        <span className={`${样式.匹配分} 等宽数字`}>匹配 {单.匹配分}</span>
      </div>

      {/* 阶段区：与求职端一比一 */}
      <div className={样式.阶段区}>
        <div className={样式.阶段头}>
          <阶段标签 阶段={单.阶段} />
          {单.需要你 ? <span className={样式.需要你胶囊}>需要你</span> : null}
          <span className={样式.轮次}>{单.轮次}</span>
        </div>

        <div className={样式.下一步行}>
          <div className={`${样式.下一步} 单行`}>{单.下一步}</div>
          <span style={{ color: 'var(--最弱)', fontSize: 16, fontWeight: 300 }}>›</span>
        </div>

        {单.分歧 ? (
          <分歧轴 我方={单.分歧.我方} 差值={单.分歧.差值} 对方={单.分歧.对方} />
        ) : 单.辅助文案 ? (
          <div className={`${样式.辅助文案} 单行`}>{单.辅助文案}</div>
        ) : null}
      </div>
    </白卡>
  );
}
