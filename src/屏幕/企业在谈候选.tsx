/**
 * 「全部岗位」档下按岗位分组 —— 镜像求职端 在谈首页 的按意向分组。
 * 跨岗位的待拍板列表里，「这个人是哪个岗的」是拍板前必须知道的第一件事，
 * 所以组名就是岗位名。组序跟岗位列表（= 顶栏胶囊的顺序）；
 * 岗位已被删掉的孤儿候选排在最后各成一组，不静默藏起来。
 */
function 按岗位分组(
  列表: 候选[],
  岗位列表: 在招岗位[]
): { 名: string; 单们: 候选[] }[] {
  const 出现过 = [...new Set(列表.map((单) => 单.岗位编号))];
  const 表内序 = 岗位列表.map((岗) => 岗.编号).filter((编号) => 出现过.includes(编号));
  const 组序 = [...表内序, ...出现过.filter((编号) => !表内序.includes(编号))];
  return 组序.map((编号) => ({
    // 岗位查不到就退回岗位编号，组名不至于空一行（同 应用状态 里归档条的口径）
    名: 岗位列表.find((岗) => 岗.编号 === 编号)?.名称 ?? 编号,
    单们: 列表.filter((单) => 单.岗位编号 === 编号),
  }));
}

export default function 企业在谈候选() {
  const 数据就绪 = use模拟加载();
  const { 状态, 派发, 数据源模式, 后端状态 } = use应用状态();
  const { 跳转 } = use导航();
  const [抽屉开, 设抽屉开] = useState(false);
  // 状态档与范围档都在全局（应用状态.企业在谈看什么 / 企业在谈范围）：
  // 企业「我的」的「待拍板」数字要能点着直接落到「全部岗位 · 待我拍板」这一档上
  const 看什么 = 状态.企业在谈看什么;
  const 范围 = 状态.企业在谈范围;
  const [在谈层开, 设在谈层开] = useState(false);

  // 当前档只看顶栏选中岗位的候选；全部岗位档跨岗位一次看全（拦路 5）。
  // 这里不做本地条件过滤 —— 筛选层里的规则清单是代理筛人的活，这两个档只决定「先看哪几单」。
  const 范围内候选 =
    范围 === '全部'
      ? 状态.企业候选列表
      : 状态.企业候选列表.filter((单) => 单.岗位编号 === 状态.当前岗位编号);
  const 待拍板数 = 范围内候选.filter((单) => 单.需要你).length;
  // 跨岗位待拍板总数：与企业「我的」那个统计数同源，标在筛选面板「全部岗位」档右侧
  const 全岗待拍板数 = 状态.企业候选列表.filter((单) => 单.需要你).length;
  const 看后 = 范围内候选.filter((单) =>
    看什么 === '全部' ? true : 看什么 === '待我拍板' ? 单.需要你 : !单.需要你
  );
  // 需要你拍板的卡置顶，其余保持原顺序
  const 排序后 = [...看后].sort((甲, 乙) => Number(乙.需要你) - Number(甲.需要你));
  const 分组后 = 按岗位分组(排序后, 状态.岗位列表);
  const 当前岗位薪资带 = 状态.岗位列表.find((岗) => 岗.编号 === 状态.当前岗位编号)?.薪资带;
  /** 卡上的薪资交集结论按各自岗位的薪资带算 —— 跨岗位时不能全用当前岗位那一条带 */
  const 取岗位薪资带 = (岗位编号: string) =>
    范围 === '全部'
      ? 状态.岗位列表.find((岗) => 岗.编号 === 岗位编号)?.薪资带
      : 当前岗位薪资带;

  // 顶栏「筛选 ▾」右上角的数字 = 代理正在生效的企业规则条数。
  // P6：高亮只认已水合的权威规则 —— Backend 未水合时不高亮（顶栏不显数、只显 筛选 ▾），
  // 不把 Mock 种子数当真（与 企业代理设置 门控同一口径）。
  const 可显示招聘规则数 = 数据源模式 === 'mock' || 后端状态.Agent规则水合.recruiter.rules === '成功';
  const 生效规则数 = 可显示招聘规则数
    ? 状态.企业规则.filter((条) => 条.生效).length
    : 0;

  return (
    <主页外壳>
      <岗位切换栏
        跨岗位={范围 === '全部'}
        筛选生效={
          状态.企业子视图 === '推荐' ? 生效规则数 > 0 : 看什么 !== '全部' || 范围 === '全部'
        }
        开筛选={() =>
          状态.企业子视图 === '推荐' ? 设抽屉开(true) : 设在谈层开(true)
        }
      />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={待拍板数 > 0 ? `${待拍板数} 个候选需要你拍板` : '暂时没有需要你拍板的'}
        按下={() => 跳转(路径.企业问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {!数据就绪 ? (
            <骨架卡组 张数={3} />
          ) : 排序后.length === 0 ? (
            <div className={样式.空态}>
              {看什么 === '全部' ? (
                <>
                  {范围 === '全部' ? '全部岗位' : '这个岗位'}暂无在谈候选，
                  <br />
                  去推荐里让AI代理接触几个
                </>
              ) : (
                `没有${看什么}的候选`
              )}
            </div>
          ) : 范围 === '全部' ? (
            // 全部岗位档：按岗位分组，每组一条组名 —— 卡片本身一个像素都不改
            分组后.map((组) => (
              <div key={组.名} className={样式.分组}>
                <div className={样式.分组标}>{组.名}</div>
                {组.单们.map((单) => (
                  <候选卡
                    key={单.编号}
                    单={单}
                    岗位薪资带={取岗位薪资带(单.岗位编号)}
                    按下={() => 跳转(路径.候选详情(单.编号))}
                  />
                ))}
              </div>
            ))
          ) : (
            排序后.map((单) => (
              <候选卡
                key={单.编号}
                单={单}
                岗位薪资带={当前岗位薪资带}
                按下={() => 跳转(路径.候选详情(单.编号))}
              />
            ))
          )}
        </div>
      </滚动区>
      </下拉刷新>

      {抽屉开 ? (
        <候选筛选抽屉 关闭={() => 设抽屉开(false)} />
      ) : null}
      {在谈层开 ? (
        <在谈筛选层
          当前={看什么}
          设当前={(档) => 派发({ 型: '企业设在谈看什么', 档 })}
          待办数={待拍板数}
          范围组={{
            标题: '看哪些岗位',
            当前档名: '当前岗位',
            全部档名: '全部岗位',
            当前: 范围,
            设当前: (档) => 派发({ 型: '企业设在谈范围', 档 }),
            全部待办数: 全岗待拍板数,
          }}
          关闭={() => 设在谈层开(false)}
        />
      ) : null}
    </主页外壳>
  );
}

// ── 顶部岗位切换栏：求职端 顶部意向栏 的镜像 ──
// 意向切换 → 在招岗位切换；＋ = 发布新岗位。
function 岗位切换栏({
  跨岗位,
  筛选生效,
  开筛选,
}: {
  /** 列表正处在「全部岗位」档：此时不高亮任何一个岗位胶囊，
      否则顶栏说的是「你在看这个岗」而列表里躺着别的岗的人，屏上两处自相矛盾。
      点任一胶囊会把范围收回当前岗（归约 切当前岗位 里做的），顶栏因此仍是可用的出口 */
  跨岗位: boolean;
  筛选生效: boolean;
  开筛选: () => void;
}) {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  // 顶栏只放在招岗位；已归档的去岗位管理页看
  const 在招岗位 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');

  return (
    <div className={样式.顶栏}>
      <div className={样式.岗位行}>
        {/* 胶囊装在可横向滚动的 .岗位滚动条 里，＋ 留在滚动区外面固定住
            （.岗位滚动条 / .岗位选中 / .岗位未选 都 composes 自 顶部意向栏.module.css，
            与「推荐」子视图同一份样式源）。原来是把 N 个岗位平铺在 .岗位行 上、靠
            max-width 截断，当前 3 个在招岗位就已经个个被切成「资深后…」。
            这里也不再挂全局 .单行：横着滚就是为了整名可读，再打省略号等于白滚。 */}
        <div className={样式.岗位滚动条}>
          {在招岗位.map((岗) => {
            const 选中 = !跨岗位 && 岗.编号 === 状态.当前岗位编号;
            return (
              <button
                key={岗.编号}
                className={`${选中 ? 样式.岗位选中 : 样式.岗位未选} 可点`}
                onClick={() => 派发({ 型: '切当前岗位', 编号: 岗.编号 })}
              >
                {岗位名截短(岗.名称)}
              </button>
            );
          })}
        </div>
        <span className={样式.岗位行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.发布岗位)}
            aria-label="发布新岗位"
          >
            ＋
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '推荐'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.企业子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '企业切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        {/* 两个子视图共用同一个筛选入口（用户 2026-08-21）：
            推荐 → 代理硬性要求（规则）；在谈 → 看哪几单（纯视图） */}
        <button
          className={`${样式.筛选} ${筛选生效 ? 样式.筛选生效 : ''} 可点`}
          onClick={开筛选}
        >
          筛选 ▾
        </button>
      </div>
    </div>
  );
}

/** 岗位名截短：顶栏空间有限，只取「 · 」前的主名（资深后端工程师 · 交易网关 → 资深后端工程师） */
function 岗位名截短(名称: string): string {
  return 名称.split(' · ')[0];
}

// ── 候选卡：求职端 在谈卡 的镜像 ──
function 候选卡({ 单, 岗位薪资带, 按下 }: { 单: 候选; 岗位薪资带?: string; 按下: () => void }) {
  // 身份可见性消费投影事实：S1 原件递交后真名非空即显示真名，S0 候选真名为空仍显示代号
  const 显示真名 = 单.真名;
  // 画像 = 「年限 · 方向 · 现职类型」
  const [年限, 方向, 现职类型] = 单.画像.split(' · ');
  const 推 = 推荐列表.find((条) => 条.编号 === 单.编号);
  const 标签组 = 推 ? [...推.亮点, 推.学历] : [];
  const 候选期望 = (匿名简历表[单.编号] ?? 匿名简历表[单.编号.split('@')[0]])?.期望.薪资;
  const 薪资结论 = 薪资初筛文案(薪资初筛(候选期望, 岗位薪资带));

  return (
    <白卡 按下={按下} 类名={样式.卡}>
      {/* 行1：头像 + 化名/真名 + 活跃度；右列 匹配环 + 硬性核对数 */}
      <div className={样式.头行}>
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className={样式.名行}>
            <span className={`${样式.代号名} 单行`}>{显示真名 ?? 单.代号}</span>
          </div>
          {/* 薪资数字不进入卡面；结构化筛选只暴露交集结论。 */}
          <div className={`${样式.基本行} 单行`}>
            {年限}
            {单.学历 ? <><span className={样式.竖分}>｜</span>{单.学历}</> : null}
            <span className={样式.竖分}>｜</span>{薪资结论}
          </div>
        </div>
        <div className={样式.右列}>
          <适配环 分={单.匹配分} 标={null} />
        </div>
      </div>

      {/* 行3/4/5：现职 · 方向 / 在找 / 学校 · 专业 */}
      <div className={样式.信息行}>
        <公文包图标 尺寸={14} 色="var(--次要浅)" />
        <span className={`${样式.信息文} 单行`}>
          {现职类型 ?? 单.画像} · {方向}
        </span>
      </div>
      {单.学校 ? (
        <div className={样式.信息行}>
          <学帽图标 尺寸={14} 色="var(--次要浅)" />
          <span className={`${样式.信息文} 单行`}>
            {单.学校} · {单.专业}
          </span>
        </div>
      ) : null}

      {/* 标签行：结构化亮点（回查推荐库；查不到不摆空行） */}
      {标签组.length > 0 ? (
        <div className={样式.标签行}>
          {标签组.map((标签) => (
            <span key={标签} className={样式.标签}>
              {标签}
            </span>
          ))}
        </div>
      ) : null}

            {/* 阶段区：与求职端一比一 */}
      <div className={样式.阶段区}>
        {/* 标注 11:07：下一步文字并到阶段标签同一行 */}
        <div className={样式.阶段头}>
          <阶段标签 阶段={单.阶段} 待你={单.需要你} />
          <div className={`${样式.下一步} 单行`}>{单.下一步}</div>
          <span style={{ color: 'var(--最弱)', fontSize: 16, fontWeight: 300 }}>›</span>
        </div>

        {/* 与求职端在谈卡同步（标注 18:00）：小字全部去掉，靠下一步大字表达 */}
      </div>
    </白卡>
  );
}
