/** Backend 分支（P5）：open 工作区快照 + MatchCase列表；Mock 候选对象一概不读。 */
function Backend企业在谈候选() {
  const { 状态, 后端状态, 操作 } = use应用状态();
  const { 跳转 } = use导航();

  // 范围档只读：企业看全部在谈 置「全部」、切当前岗位 收回「当前」（切换面板已删，2026-09-09）
  const 范围 = 状态.企业在谈范围;

  // 招聘 scope 只能是自己名下「在招」岗位的 job_id（与 候选推荐 的 P4 口径同一条
  // 规则）：选新当前岗 在没有在招岗时会保留上一个（可能已归档）的编号，拿它当
  // scope 就是拿归档岗去要列表 —— 核不实就不发任何 P5 请求（宁空勿错）。
  const 活跃岗位 = 状态.岗位列表.find((岗) => 岗.编号 === 状态.当前岗位编号)?.状态 === '在招'
    ? 状态.当前岗位编号
    : null;
  const filterRef = 范围 === '全部' ? null : 活跃岗位;
  const 有scope = filterRef !== null || 范围 === '全部';

  const 快照 = 有scope ? 后端状态.P5工作区?.[P5范围键.open('recruiter', filterRef)] : undefined;
  const 已载待拍板数 = 快照?.items.filter((条) => 条.needsAction).length ?? 0;
  // 「读尽」只在成功快照上成立：操作层的起步/失败构造会把还没读成的东西置
  // 阶段 进行中/失败 且 nextCursor 兜底成 null —— 只看游标会把在飞/失败误读成读尽。
  const 读尽 = 快照 !== undefined && 快照.阶段 === '成功' && 快照.nextCursor === null;

  // 横幅：0 也可能是「还没读完」（§10.1 未读尽不声称全量）—— 成功读尽前一律非定论
  // 文案；首帧与首次读取在飞（未开始/进行中）只说正在读入；首载失败由列表的错误卡
  // 交代，横幅只给非定论兜底。护栏空态（无在招岗位，本屏刻意零请求）没有未读
  // 数据，定论与 Mock 同口径。
  const 横幅强调 = !有scope
    ? '暂时没有需要你拍板的'
    : 快照 === undefined || 快照.阶段 === '未开始' || 快照.阶段 === '进行中'
      ? '正在读入在谈候选…'
      : 已载待拍板数 > 0
        ? (读尽 ? `${已载待拍板数} 个候选需要你拍板` : '有候选需要你拍板')
        : (读尽 ? '暂时没有需要你拍板的' : '已读入的里暂时没有需要你拍板的');

  // 本屏只在「在谈」子视图挂载（企业主壳按 企业子视图 切换）。

  // 下拉只重读当前 scope（GET）；错误文案由快照 error 承载，列表上方错误行呈现
  const 重读当前范围 = () =>
    有scope ? 操作.刷新工作区('recruiter', filterRef).catch(() => undefined) : undefined;

  return (
    <主页外壳>
      <岗位切换栏 跨岗位={范围 === '全部'} />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={横幅强调}
        // 交付 G：Backend 的代理页是导航说明而非自由对话，入口文案不许承诺「问AI代理」
        动作文="查看代理功能 ›"
        按下={() => 跳转(路径.企业问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新 刷新={重读当前范围}>
      <滚动区>
        {!有scope ? (
          <div className={样式.空态}>
            <div>还没有在招的岗位</div>
            <div>在谈的 Case 都挂在岗位上，先去发布或重开一个岗位吧。</div>
          </div>
        ) : (
          // eslint-disable-next-line jsx-a11y/aria-role -- role 是 P5 域 prop，非 ARIA role
          <MatchCase列表 role="recruiter" filterRef={filterRef} />
        )}
      </滚动区>
      </下拉刷新>
    </主页外壳>
  );
}

/** Mock 原型分支：静态候选表 + 全局归约，行为与接线前逐字一致。 */
function Mock企业在谈候选() {
  const 数据就绪 = use模拟加载();
  const { 状态 } = use应用状态();
  const { 跳转 } = use导航();
  // 范围档在全局（应用状态.企业在谈范围）：企业「我的」的「待拍板」数字点着直接落到
  // 「全部岗位」档上（企业看全部在谈 归约），切当前岗位 再收回「当前」；本屏没有切换 UI。
  const 范围 = 状态.企业在谈范围;

  // 当前档只看顶栏选中岗位的候选；全部岗位档跨岗位一次看全（拦路 5）。
  // 这里不做本地条件过滤 —— 规则清单是代理筛人的活，范围档只决定「先看哪几单」。
  const 范围内候选 =
    范围 === '全部'
      ? 状态.企业候选列表
      : 状态.企业候选列表.filter((单) => 单.岗位编号 === 状态.当前岗位编号);
  const 待拍板数 = 范围内候选.filter((单) => 单.需要你).length;
  // 2026-09-09 产品负责人定稿删筛选：「看哪几单」（全部 / 待我拍板 / 进行中）不再过滤列表，
  // 列表固定显示范围内全部单 —— 企业在谈看什么 字段保留但本屏不读；「待拍板」落地后
  // 需要你拍板的卡本来就置顶（8/25 产品负责人认可的排序），不用再单独筛出来。
  // 需要你拍板的卡置顶，其余保持原顺序
  const 排序后 = [...范围内候选].sort((甲, 乙) => Number(乙.需要你) - Number(甲.需要你));
  const 分组后 = 按岗位分组(排序后, 状态.岗位列表);
  // 「薪资带有交集」结论及其岗位薪资带取值链已整体删除（2026-09-08 产品负责人定稿）：
  // 卡面不再放薪资相关结论，候选卡也不再接 岗位薪资带 prop。

  return (
    <主页外壳>
      <岗位切换栏 跨岗位={范围 === '全部'} />

      <代理横幅
        前文="初筛与前几轮我已谈完，"
        强调={待拍板数 > 0 ? `${待拍板数} 个候选需要你拍板` : '暂时没有需要你拍板的'}
        按下={() => 跳转(路径.企业问AI代理)}
      />

      <div style={{ height: 10, flex: 'none' }} />

      <下拉刷新>
      <滚动区>
        <div className={样式.列表}>
          {!数据就绪 ? (
            <骨架卡组 张数={3} />
          ) : 排序后.length === 0 ? (
            <div className={样式.空态}>
              {范围 === '全部' ? '全部岗位' : '这个岗位'}暂无在谈候选，
              <br />
              去推荐里让AI代理接触几个
            </div>
          ) : 范围 === '全部' ? (
            // 全部岗位档：按岗位分组，每组一条组名 —— 卡片本身一个像素都不改
            分组后.map((组) => (
              <div key={组.名} className={样式.分组}>
                <div className={样式.分组标}>{组.名}</div>
                {组.单们.map((单) => (
                  <招聘在谈卡
                    key={单.编号}
                    信息={从Mock候选到卡信息(单, 推荐标签(单.编号))}
                    匹配分={单.匹配分}
                    阶段={从Mock在谈到阶段(单)}
                    打开={() => 跳转(路径.候选详情(单.编号))}
                  />
                ))}
              </div>
            ))
          ) : (
            排序后.map((单) => (
              <招聘在谈卡
                key={单.编号}
                信息={从Mock候选到卡信息(单, 推荐标签(单.编号))}
                匹配分={单.匹配分}
                阶段={从Mock在谈到阶段(单)}
                打开={() => 跳转(路径.候选详情(单.编号))}
              />
            ))
          )}
        </div>
      </滚动区>
      </下拉刷新>
    </主页外壳>
  );
}

// ── 顶部岗位切换栏：求职端 顶部意向栏 的镜像 ──
// 意向切换 → 在招岗位切换；＋ = 发布新岗位。
// 原子视图行右端的「筛选 ▾」及 筛选生效 / 开筛选 两个 props 已删（2026-09-09 产品负责人定稿）。
function 岗位切换栏({
  跨岗位,
}: {
  /** 列表正处在「全部岗位」档：此时不高亮任何一个岗位胶囊，
      否则顶栏说的是「你在看这个岗」而列表里躺着别的岗的人，屏上两处自相矛盾。
      点任一胶囊会把范围收回当前岗（归约 切当前岗位 里做的），顶栏因此仍是可用的出口 */
  跨岗位: boolean;
}) {
  const { 状态, 派发 } = use应用状态();
  const { 跳转 } = use导航();

  // 顶栏只放在招岗位；已归档的去岗位管理页看
  const 在招岗位 = 状态.岗位列表.filter((岗) => 岗.状态 === '在招');

  return (
    <div className={样式.顶栏}>
      <div className={样式.岗位行}>
        {/* 胶囊装在可横向滚动的 .岗位滚动条 里，＋ 留在滚动区外面固定住
            （.岗位滚动条 / .岗位选中 / .岗位未选 都 composes 自 顶部意向栏.module.css，
            与「推荐」子视图同一份样式源）。原来是把 N 个岗位平铺在 .岗位行 上、靠
            max-width 截断，当前 3 个在招岗位就已经个个被切成「资深后…」。
            这里也不再挂全局 .单行：横着滚就是为了整名可读，再打省略号等于白滚。 */}
        <div className={样式.岗位滚动条}>
          {在招岗位.map((岗) => {
            const 选中 = !跨岗位 && 岗.编号 === 状态.当前岗位编号;
            return (
              <button
                key={岗.编号}
                className={`${选中 ? 样式.岗位选中 : 样式.岗位未选} 可点`}
                onClick={() => 派发({ 型: '切当前岗位', 编号: 岗.编号 })}
              >
                {岗位名截短(岗.名称)}
              </button>
            );
          })}
        </div>
        <span className={样式.岗位行右}>
          <button
            className={`${样式.加号} 可点`}
            onClick={() => 跳转(路径.发布岗位)}
            aria-label="发布新岗位"
          >
            ＋
          </button>
        </span>
      </div>

      <div className={样式.子视图行}>
        {(['在谈', '推荐'] as const).map((视图) => (
          <button
            key={视图}
            className={`${状态.企业子视图 === 视图 ? 样式.子视图选中 : 样式.子视图未选} 可点`}
            onClick={() => 派发({ 型: '企业切子视图', 子视图: 视图 })}
          >
            {视图}
          </button>
        ))}
        {/* 原本这里还有两个子视图共用的「筛选 ▾」入口（用户 2026-08-21），
            2026-09-09 产品负责人定稿整体删除：子视图行只剩 在谈 / 推荐 两个键 */}
      </div>
    </div>
  );
}

/** 岗位名截短：顶栏空间有限，只取「 · 」前的主名（资深后端工程师 · 交易网关 → 资深后端工程师） */
function 岗位名截短(名称: string): string {
  return 名称.split(' · ')[0];
}

/** 在谈卡的亮点标签回查（原 候选卡 行为，2026-09-10 随卡面共用留在连接层）：
 *  推荐库同编号条目的 亮点 + 学历；查不到就没有可展示标签（占位交给共享卡面）。 */
function 推荐标签(编号: string): string[] {
  const 推 = 推荐列表.find((条) => 条.编号 === 编号);
  return 推 ? [...推.亮点, 推.学历] : [];
}
