// A1 欢迎与AI代理说明 —— 「条件对上了，再开始聊。」
//
// 注册流第一屏，只做一件事：在用户开始填资料之前，先把「AI 代理替你匿名核对条件」
// 这套机制讲清楚。所以这屏没有任何表单，通篇是文案 + 三步说明卡 + 一个前进按钮。
// 内容高度固定（不滚动），底部按钮靠空白撑开件压到屏底 —— 与 RN 源一致。

import 样式 from './引导说明.module.css';
import { 次级页外壳, 主按钮 } from '../组件/通用';
import { use导航 } from '../路由/导航钩子';
import { 路径 } from '../路由/路径表';

/** 三步说明文案。只有这一屏用，所以留在屏内，不进模拟数据层。 */
const 三步 = [
  { 序: '01', 标题: '填好你的条件', 说明: '期望城市、薪资范围、排除项，只有你的 AI 代理知道' },
  { 序: '02', 标题: 'AI 代理匿名核对', 说明: '和岗位方互查条件，有交集才互递简历' },
  { 序: '03', 标题: '你确认，才见面', 说明: '双方点头后互换联系方式，面试和薪资你们直接谈' },
];

export default function 引导说明() {
  const { 跳转 } = use导航();

  return (
    <次级页外壳>
      {/* hero：27px/800 两行。断行位置写死成 <br>，不交给自动折行，
          否则窄屏会折成三行、把「再开始聊。」的节奏感打散。 */}
      <div className={样式.头部}>
        <h1 className={样式.主标题}>
          条件对上了，
          <br />
          再开始聊。
        </h1>
        <p className={样式.副说明}>把期望告诉你的 AI 代理，它替你和岗位方逐项核对。</p>
      </div>

      {/* 三步说明卡：01 / 02 / 03 序号列 + 标题 + 说明；序号走等宽数字避免字宽跳动 */}
      <div className={样式.卡}>
        {三步.map((步) => (
          <div key={步.序} className={样式.步骤行}>
            <span className={`${样式.步骤序} 等宽数字`}>{步.序}</span>
            <div className={样式.步骤文字组}>
              <div className={样式.步骤标题}>{步.标题}</div>
              <div className={样式.步骤说明}>{步.说明}</div>
            </div>
          </div>
        ))}
      </div>

      <div className={样式.占位撑开} />

      {/* 前进到 A1b 基本信息（2026-08-18 插入的一屏：真名 / 开始工作年份 / 身份，
          匿名初筛核对「年限 ≥ 要求」的数据源）。这里用普通跳转（保留后退），
          因为用户从下一屏退回来重看这段说明是合理动作。 */}
      <主按钮 文字="开始资料" 按下={() => 跳转(路径.基本信息)} />
    </次级页外壳>
  );
}
