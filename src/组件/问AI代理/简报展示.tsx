// 问AI代理 两端（求职 A27 / 招聘 D14）共用的今日简报卡：代理气泡框里的「卡片附件」。
//
// 只做受控展示：标题、更新时间、统计、正文、脚注、建议全部文案与漏斗数据都来自内存
// props，这里不认识 fixture、Context、路由、API、存储或业务操作；收到新 props 直接更新，
// 没有任何 state —— 「已维持」与否完全由父级送来的 处理文案 决定，点击只调回调。
//
// 结构沿用原两端实现：气泡内自上而下 统计条 → 人才漏斗（招聘端）→ 正文 → 建议卡 → 脚注。
// 「要不要松一档 / 放宽薪资带」放在卡片内部（正文与脚注之间）而不是另起一张卡：
// 它与统计/漏斗同源（都是这份日报盘出来的数），且卡内可点元素是这屏定好的做法
// （漏斗的「硬性匹配」行本来就整行可点）；脚注讲整张卡的更新节奏，动作压在它后面
// 会让人误以为「每天 09:00 更新」说的是这条建议。
//
// 外观（'求职' | '招聘'）只选择 CSS，不参与业务处理：两端完全一致的声明直接共用，
// 各自的档位差异由内容容器上的外观类（本模块的 .求职 / .招聘）按原值保留 ——
// CSS module 类名跨文件不通，对话展示 挂在行根的外观类本模块看不见，所以这层
// 无声明的纯 block 容器只承担本模块端差后代选择器的挂点，不影响 flex / 布局。

import { 代理气泡框 } from './对话展示';
import type { 代理外观 } from './对话展示';
import 样式 from './简报展示.module.css';

export type 规则建议属性 = {
  标题: string;
  正文前: string;
  数值1: string;
  正文中: string;
  数值2: string;
  正文后: string;
  维持文案: string;
  放宽文案: string;
  /** null = 还没处理，出维持/放宽双按钮；非 null = 显示这段确认文案，双按钮退场 */
  处理文案: string | null;
  维持: () => void;
  放宽: () => void;
};

export type 简报统计 = { 名称: string; 数值: string; 强调: boolean };

export type 漏斗展示档 = {
  名称: string;
  人数: number;
  宽度: number;
  /** 非 null 的档渲染成 button（说明=读屏整句）；null 保持 div 不可点，不做假入口 */
  动作: { 说明: string; 按下: () => void } | null;
};

export type 简报展示属性 = {
  外观: 代理外观;
  标题: string;
  更新时间: string;
  统计: readonly 简报统计[];
  正文前: string;
  正文强调: string;
  正文后: string;
  脚注: string;
  建议: 规则建议属性;
  /** 招聘端的人才漏斗；求职端传 null（不渲染漏斗块） */
  漏斗: readonly 漏斗展示档[] | null;
};

// 外观容器类：挂在气泡内的内容容器上，专供本模块后代选择器取端差
const 外观类 = (外观: 代理外观) => (外观 === '求职' ? 样式.求职 : 样式.招聘);

// ── 绿色建议卡（要不要松一档 / 放宽薪资带）：把这条红线卡掉多少量化出来，再给两个动作。
// 处理文案 === null 出双按钮；点击只调对应回调，换不换成确认文案由父级送 处理文案 决定 ──
export function 规则建议({
  标题,
  正文前,
  数值1,
  正文中,
  数值2,
  正文后,
  维持文案,
  放宽文案,
  处理文案,
  维持,
  放宽,
}: 规则建议属性) {
  return (
    <div className={样式.松一档卡}>
      <div className={样式.松一档标题}>{标题}</div>
      <div className={样式.松一档正文}>
        {正文前}
        <b className={样式.松一档强调}>{数值1}</b>
        {正文中}
        <b className={样式.松一档强调}>{数值2}</b>
        {正文后}
      </div>

      {处理文案 === null ? (
        <div className={样式.按钮行}>
          <button className={`${样式.次按钮} 可点`} onClick={维持}>
            {维持文案}
          </button>
          <button className={`${样式.主按钮} 可点`} onClick={放宽}>
            {放宽文案}
          </button>
        </div>
      ) : (
        <div className={样式.已维持}>{处理文案}</div>
      )}
    </div>
  );
}

// ── 今日简报卡：套在代理气泡框里当第一条消息。标题/更新时间/脚注/全部建议文案由容器提供 ──
export function 简报展示({
  外观,
  标题,
  更新时间,
  统计,
  正文前,
  正文强调,
  正文后,
  脚注,
  建议,
  漏斗,
}: 简报展示属性) {
  return (
    <代理气泡框 外观={外观} 简报>
      <div className={外观类(外观)}>
        <div className={样式.简报头}>
          <span className={样式.简报标题}>{标题}</span>
          <span className={样式.简报时间}>{更新时间}</span>
        </div>

        {/* 统计数横条：「需要你」那列用 --意向（红）标出，待决策项最先被看到 */}
        <div className={样式.统计条}>
          {统计.map((项) => (
            <div key={项.名称} className={样式.统计项}>
              <div className={`${样式.统计数} ${项.强调 ? 样式.统计数强调 : ''} 等宽数字`}>
                {项.数值}
              </div>
              <div className={样式.统计名}>{项.名称}</div>
            </div>
          ))}
        </div>

        {漏斗 && <漏斗块 漏斗={漏斗} />}

        <div className={样式.简报正文}>
          {正文前}
          <b className={样式.简报强调}>{正文强调}</b>
          {正文后}
        </div>

        <规则建议 {...建议} />

        <div className={样式.简报脚注}>{脚注}</div>
      </div>
    </代理气泡框>
  );
}

// ── 人才漏斗（招聘端）：五档横条，宽度直接取数据里的 宽度%。
// 动作非 null 的档整行是 <button>（元素类型本身就是「能不能点」的语义，不另加提示文案），
// 其余档保持 <div> 不可点。哪个档可点、落到哪一屏、读屏说明都由容器决定 ──
function 漏斗块({ 漏斗 }: { 漏斗: readonly 漏斗展示档[] }) {
  return (
    <div className={样式.漏斗块}>
      {漏斗.map((档) =>
        档.动作 ? (
          <button
            key={档.名称}
            type="button"
            className={`${样式.漏斗行} ${样式.漏斗行可点} 可点`}
            aria-label={档.动作.说明}
            onClick={档.动作.按下}
          >
            <漏斗行内容 档={档} />
          </button>
        ) : (
          <div key={档.名称} className={样式.漏斗行}>
            <漏斗行内容 档={档} />
          </div>
        ),
      )}
    </div>
  );
}

// 一行漏斗的内容：档名 + 横条 + 人数。可点行与不可点四行共用同一份，保证两种外层元素
// 下版式一模一样。全部用 <span>：可点行外层是 <button>，button 的内容模型只允许短语内容，
// <div> 嵌在里面是不合法的 HTML；槽与条在 CSS 里显式 display:block 补回块级尺寸。
function 漏斗行内容({ 档 }: { 档: 漏斗展示档 }) {
  return (
    <>
      <span className={`${样式.漏斗名} 单行`}>{档.名称}</span>
      <span className={样式.漏斗槽}>
        <span className={样式.漏斗条} style={{ width: `${档.宽度}%` }} />
      </span>
      <span className={`${样式.漏斗数} 等宽数字`}>{档.人数}</span>
    </>
  );
}
