// 问AI代理 两端（求职 A27 / 招聘 D14）共用的对话展示件：
// 代理气泡框 / 代理气泡 / 我方气泡 / 快捷操作行。
//
// 只做受控展示：数据与动作全部来自内存 props，这里不认识 fixture、Context、
// 路由、API、存储或业务操作；收到新 props 直接更新，不把初值复制成 state。
//
// 行向/头像槽/气泡列/时间与正文渲染复用公共 聊天气泡 / 聊天正文；本文件只保留
// 两端差异（外观类选择 CSS）与既有类名挂点。外观（'求职' | '招聘'）差异按原声明保留：
//   · 求职代理气泡镜像净空（列内再让 39px，右缘距行尾 ≥ 头像列宽）；招聘代理气泡伸展（上限 86%）
//   · 求气泡文字 13.5px/1.45；招聘 14px/1.7
//   · 求职快捷行单行横滑；招聘换行堆叠
// 简报=true 时只有求职端放宽到整列（简报类 + 宽内容），招聘端保持基础气泡宽度。

import type { ReactNode } from 'react';
import { 聊天正文, 聊天气泡 } from '../聊天气泡';
import 样式 from './对话展示.module.css';
import 代理标 from '../代理标';

export type 代理外观 = '求职' | '招聘';
export type 快捷操作项 = { 键: string; 文案: string; 按下: () => void };

export type 代理气泡框属性 = {
  外观: 代理外观;
  简报?: boolean;
  时间?: string | null;
  children: ReactNode;
};

export type 代理气泡属性 = {
  外观: 代理外观;
  内容: string;
  时间?: string | null;
  正文格式?: 'text' | 'markdown'; // 默认 text：Mock 与招聘端原行为不变
};

export type 我方气泡属性 = {
  外观: 代理外观;
  内容: string;
  头像URL: string | null;
  首字: string;
  时间?: string | null;
};

export type 快捷操作行属性 = { 外观: 代理外观; 项们: readonly 快捷操作项[] };

// 外观类挂在行根元素上，后代选择器按端取差异 —— 不新增任何影响 flex 的 DOM 层
const 外观类 = (外观: 代理外观) => (外观 === '求职' ? 样式.求职 : 样式.招聘);

// ── 代理侧一行：裸代理标头像（与主页横幅同款，无圆底）+ 左上角切平的气泡外壳。
// 文字排版由调用方内容负责；普通文本走 代理气泡 里的 聊天正文。 ──
export function 代理气泡框({ 外观, 简报 = false, 时间, children }: 代理气泡框属性) {
  const 宽 = 简报 && 外观 === '求职';
  return (
    <聊天气泡
      方="对方"
      头像={
        <span className={样式.小盾牌}>
          <代理标 尺寸={30} 脸色="var(--荧光绿)" 眼色="var(--墨)" 描边色="var(--墨)" 描边宽={2.6} />
        </span>
      }
      时间={时间}
      宽内容={宽}
      类名={外观类(外观)}
      气泡类名={[样式.代理气泡, 宽 ? 样式.简报气泡 : ''].filter(Boolean).join(' ')}
    >
      {children}
    </聊天气泡>
  );
}

// ── 普通代理文本气泡：框 + 正文（text/markdown 由调用方显式选择，默认纯文本）。 ──
export function 代理气泡({ 外观, 内容, 时间, 正文格式 = 'text' }: 代理气泡属性) {
  return (
    <代理气泡框 外观={外观} 时间={时间}>
      <聊天正文 内容={内容} 格式={正文格式} 类名={样式.气泡文字} />
    </代理气泡框>
  );
}

// ── 我方（右）：荧光绿浅底气泡、右下角切角，头像列与左侧代理头像对称。
// 有头像图用图，否则落首字；换 props 立即跟着换。AI 用户输入按纯文本显示。 ──
export function 我方气泡({ 外观, 内容, 头像URL, 首字, 时间 }: 我方气泡属性) {
  return (
    <聊天气泡
      方="我方"
      头像={
        <span className={样式.我头像}>
          {头像URL ? (
            <img
              src={头像URL}
              alt=""
              style={{ width: '100%', height: '100%', objectFit: 'cover' }}
            />
          ) : (
            首字
          )}
        </span>
      }
      时间={时间}
      类名={外观类(外观)}
      气泡类名={样式.我气泡}
    >
      <聊天正文 内容={内容} 格式="text" 类名={样式.气泡文字} />
    </聊天气泡>
  );
}

// ── 快捷问句 / 快捷导航胶囊行：求职单行横滑、招聘换行。点击只触发被点那一项的回调 ──
export function 快捷操作行({ 外观, 项们 }: 快捷操作行属性) {
  return (
    <div className={`${样式.快捷行} ${外观类(外观)}`}>
      {项们.map((项) => (
        <button key={项.键} className={`${样式.快捷键} 可点`} onClick={项.按下}>
          {项.文案}
        </button>
      ))}
    </div>
  );
}
