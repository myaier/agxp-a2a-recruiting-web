// 候选人头像（2026-08-19 标注 11:33：不要只有姓氏字，放"人"的形象）。
//
// 不用真人照片：双盲机制下意向确认前不该出现可辨识的真脸，用真人照也会
// 把演示数据变成"像是真人信息"。改为按编号生成的几何人像 —— 每个人一副
// 稳定的配色 + 发型，看着是一个人、又不指向任何具体的人。

/** 六套配色：底色 + 人形色，取自品牌绿系与中性色，避免花哨 */
const 配色表 = [
  { 底: '#e8efd8', 人: '#4a6741' },
  { 底: '#dfe7ee', 人: '#3f5668' },
  { 底: '#f0e6da', 人: '#6b5340' },
  { 底: '#e4e9e2', 人: '#4d5a4a' },
  { 底: '#ece2ee', 人: '#5b4a63' },
  { 底: '#e2ecec', 人: '#3f5f5c' },
];

/** 三种发型：短发 / 长发 / 圆寸，按编号取，保证同一个人每次都一样 */
const 发型数 = 3;

/** 把任意编号打散成稳定的正整数（同一编号永远同一头像） */
function 散列(键: string): number {
  let 值 = 0;
  for (let i = 0; i < 键.length; i += 1) 值 = (值 * 31 + 键.charCodeAt(i)) >>> 0;
  return 值;
}

export default function 人像头({
  键,
  尺寸 = 34,
}: {
  /** 稳定标识（用候选编号）。同一个键永远得到同一副头像 */
  键: string;
  尺寸?: number;
}) {
  const 种 = 散列(键);
  const 配 = 配色表[种 % 配色表.length];
  const 发型 = Math.floor(种 / 7) % 发型数;

  return (
    <svg
      width={尺寸}
      height={尺寸}
      viewBox="0 0 40 40"
      fill="none"
      style={{ flex: 'none', borderRadius: '50%', display: 'block' }}
      aria-hidden
    >
      <circle cx="20" cy="20" r="20" fill={配.底} />
      {/* 肩 */}
      <path d="M6.5 40c1.6-7 6.9-11 13.5-11s11.9 4 13.5 11z" fill={配.人} />
      {/* 头 */}
      <circle cx="20" cy="16.5" r="7.4" fill={配.人} />
      {/* 发型：0 短发 / 1 长发（两侧垂下）/ 2 圆寸（只压一层刘海） */}
      {发型 === 0 ? (
        <path d="M12.6 15.4c0-4.3 3.3-7.2 7.4-7.2s7.4 2.9 7.4 7.2c-2-1.6-4.4-2.3-7.4-2.3s-5.4.7-7.4 2.3z" fill={配.人} />
      ) : null}
      {发型 === 1 ? (
        <path d="M11.4 15c0-5 3.8-8.2 8.6-8.2s8.6 3.2 8.6 8.2v7.6c-1 0-1.9-.8-1.9-1.8v-4.6c-2-1.4-4.2-2-6.7-2s-4.7.6-6.7 2v4.6c0 1-.9 1.8-1.9 1.8z" fill={配.人} />
      ) : null}
      {发型 === 2 ? (
        <path d="M13 14.2c1.7-2.6 4.1-3.9 7-3.9s5.3 1.3 7 3.9c-1.9-1-4.2-1.5-7-1.5s-5.1.5-7 1.5z" fill={配.人} />
      ) : null}
    </svg>
  );
}
