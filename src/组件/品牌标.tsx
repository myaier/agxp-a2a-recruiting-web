// 产品图标「对席」。
//
// 概念直接来自产品名：对席 = 双方对坐，隔一张谈判桌。
// 所以图形就是**两个相向的圆角块**，中间留一道缝（那道缝就是双盲边界 ——
// 意向确认前双方谁都过不去，只有两边的代理在缝上核对条件）：
//   · 左块荧光绿 = 求职者一席
//   · 右块深绿   = 招聘方一席
//   · 中缝里一枚小圆点 = 两个代理在中间对话
//
// 风格与选身份页的彩绘图标同一套（填充色块 + 圆润几何 + 双色分层，Robinhood 风），
// 不用线性描边 —— 这样它在 24px 的返回栏里和 96px 的登录页都立得住。

interface 品牌标属性 {
  尺寸?: number;
  /** 深色底：整个标反白，用于深色场景（暂未用到，先留口） */
  反白?: boolean;
}

export default function 品牌标({ 尺寸 = 56, 反白 = false }: 品牌标属性) {
  const 左色 = 反白 ? 'rgba(255,255,255,0.92)' : 'var(--荧光绿)';
  const 右色 = 反白 ? 'rgba(255,255,255,0.55)' : 'var(--深绿)';
  const 底色 = 反白 ? 'transparent' : 'var(--墨)';

  return (
    <svg width={尺寸} height={尺寸} viewBox="0 0 64 64" aria-label="对席" role="img">
      {/* 墨色 squircle 底：App 图标的形，放在浅色页面上也自带存在感 */}
      <rect x="0" y="0" width="64" height="64" rx="17" fill={底色} />

      {/* 左席：荧光绿，内侧收窄的圆角块 */}
      <rect x="12" y="18" width="16" height="28" rx="8" fill={左色} />
      {/* 右席：深绿 */}
      <rect x="36" y="18" width="16" height="28" rx="8" fill={右色} />

      {/* 中缝里的对话点：两个代理在双盲边界上核对条件 */}
      <circle cx="32" cy="32" r="3.2" fill={左色} />
    </svg>
  );
}
