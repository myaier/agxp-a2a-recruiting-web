// 分析弹层（承接义务 1/2，Spec §3.2）：列表「匹配度分析」弹层的唯一共享组装 ——
// 四个消费者（求职看市场 / 招聘候选推荐 / 求职在谈卡 / 招聘在谈卡）共用：既有 弹层框架
// （遮罩 / 圆角抓手 / Escape / 焦点圈与恢复全是现成机制，本组件不建第二套弹层基础设施）
// + 弹层头部可见关闭按钮（与遮罩、Escape 并列的第三条关闭通道）+ 当前记录的简短岗位
// 上下文行 + 匹配分析块（藏环：弹层总分用紧凑文本，不再画环）。
//
// 模型与上下文全部由调用方从该行已返回数据构建 —— 本组件零网络请求、不补读、不缓存；
// 关闭（关闭键/遮罩/Escape）只调 关闭 回调，调用方清 page-local 选中 ID 即可。
// 岗位上下文 null（该行没有已知公司/职位）时不造占位，仅省略该行。

import 弹层框架 from './弹层框架';
import { 匹配分析块 } from './匹配分析块';
import 样式 from './分析弹层.module.css';
import type { 匹配分析模型 } from '../数据/匹配解释展示映射';

export default function 分析弹层({
  模型,
  岗位上下文,
  关闭,
}: {
  /** 该行已返回的解释与分数（匹配解释展示映射 的展示模型） */
  模型: 匹配分析模型;
  /** 当前记录的简短岗位上下文（如「职位名 · 公司」）；null = 该行无已知上下文，不造占位 */
  岗位上下文: string | null;
  /** 关闭回调（关闭键 / 遮罩 / Escape 三通道同源）；调用方清选中记录 ID */
  关闭: () => void;
}) {
  return (
    <弹层框架 标签="匹配度分析" 遮罩类名={样式.遮罩} 面板类名={样式.层} 关闭={关闭}>
      <div className={样式.抓手} />
      <div className={样式.头行}>
        {岗位上下文 !== null ? <p className={样式.上下文}>{岗位上下文}</p> : null}
        <button type="button" className={`${样式.关闭键} 可点`} aria-label="关闭" onClick={关闭}>
          ✕
        </button>
      </div>
      <匹配分析块 模型={模型} 藏环 />
    </弹层框架>
  );
}
