// 求职状态三态受控正文（合同 B，Spec §6）：日常状态编辑的唯一绘制 —— 我的简历 →
// 求职状态页、求职意向管理 → 求职状态页、基本信息空身份的同页收口子视图三处共用。
//
// 只画三个真实身份选项（在校/在职/离职），保存/取消/路由与提示全由调用页承担；
// 不引入到岗节奏（在校 · 月内到岗 / 离职 · 随时到岗 …）等 onboarding 语义 —— 那是注册
// 旅程的另一种采集，不映射成 profile 的三个合法状态值，也不在这里包装成新字段。
//
// 版式复用 入职引导.module.css 的方块网格（状态屏与最高学历页共用同一套）：三处绘制
// 同一份状态时视觉与 DOM 结构一致，且不新增样式文件。

import 样式 from '../屏幕/入职引导.module.css';

/** 三态顺序与 profile 的三个合法值一致（空串是未选择，不是第四档）*/
const 三态 = ['在校', '在职', '离职'] as const;

type 求职状态编辑正文Props = {
  值: '' | '在校' | '在职' | '离职';
  修改: (值: '在校' | '在职' | '离职') => void;
};

export default function 求职状态编辑正文({ 值, 修改 }: 求职状态编辑正文Props) {
  return (
    <div className={样式.方块网格}>
      {三态.map((档) => {
        const 选中 = 值 === 档;
        return (
          <button
            key={档}
            type="button"
            className={`${样式.方块} ${选中 ? 样式.方块选中 : ''} 可点`}
            onClick={() => 修改(档)}
            aria-pressed={选中}
          >
            <span className={样式.方块题}>{档}</span>
          </button>
        );
      })}
    </div>
  );
}
