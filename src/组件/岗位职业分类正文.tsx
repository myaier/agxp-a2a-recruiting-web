// 岗位职业分类正文（Task 4）：发布岗位 职位类别 两级两栏选择层的两模式共用正文。
//
// 版式照原页两套分类层（Mock 本地表 / Backend catalog）共用的一套 JSX 自上而下：
//   抓手 → 标题「职位类别」→ 左栏根项 → 右栏子项，各栏列表尾沿用现有「加载更多」控件。
// 样式直接沿用原页面 CSS（发布岗位.module.css 的 分类/大类/小类 各类名），不另建样式。
//
// 本组件是纯展示正文：只收展示值、稳定键、状态与回调，不依赖数据源模式、BFF DTO、
// Context、API、路由或存储，也不读目录 API。真实目录引用、分页游标、迟到响应与
// 版本守卫都在页面外层（src/屏幕/发布岗位.tsx 保留的 Backend hooks / Mock 本地控制）。
//
// 点击沿两栏的现有行为：
//   · 左栏恒为导航 —— 点击交给 展开（下钻），不因可选直选；
//   · 右栏可选单击选定（可选+有子项同真也按现有单击选定，不设第二点击区）；
//     不可选仅在有子项时展开下钻；无子项的不可选项不提交也不展开。
// `可选` 源自 selectable、`有子项` 源自 has_children，由页面原样映射，本组件不推导。

import 样式 from '../屏幕/发布岗位.module.css';
import 弹层框架 from './弹层框架';

/** 一枚栏项的展示值：页面把两模式的目录项映射成这个形状 */
export type 职业栏项 = { 键: string; 名称: string; 选中: boolean; 可选: boolean; 有子项: boolean };

/** 一栏（左根/右子）的展示输入；「加载中 / 还有 / 加载更多」指本栏当前可见列表 */
export type 职业栏 = { 项们: 职业栏项[]; 加载中: boolean; 还有: boolean; 加载更多: () => void };

/** 正文 props（页面局部契约，不是公共领域模型） */
export type 岗位职业分类正文Props = {
  根栏: 职业栏;
  子栏: 职业栏;
  展开: (键: string) => void;
  选定: (键: string) => void;
  关闭: () => void;
};

export function 岗位职业分类正文({ 根栏, 子栏, 展开, 选定, 关闭 }: 岗位职业分类正文Props): React.JSX.Element {
  /** 左栏根项：选中态照旧高亮（浅灰底 → 白底 + 荧光绿左条由 CSS 呈现） */
  const 根项键 = (项: 职业栏项) => (
    <button
      key={项.键}
      className={`${样式.大类项} ${项.选中 ? 样式.大类项选中 : ''} 可点`}
      onClick={() => 展开(项.键)}
    >
      {项.名称}
    </button>
  );

  /** 右栏子项：可选单击选定；不可选仅有子项才下钻；勾沿用原 小类勾 结构 */
  const 子项键 = (项: 职业栏项) => (
    <button
      key={项.键}
      className={`${样式.小类项} ${项.选中 ? 样式.小类项选中 : ''} 可点`}
      onClick={() => {
        if (项.可选) {
          选定(项.键);
          return;
        }
        if (项.有子项) 展开(项.键);
      }}
      aria-disabled={!项.可选 ? true : undefined}
    >
      {项.名称}
      {项.选中 ? <span className={样式.小类勾}>✓</span> : null}
    </button>
  );

  /** 列表尾分页按钮（沿用原页现有控件）：还有才渲染，忙时文案换「加载中…」并禁用 */
  const 分页键 = (栏: 职业栏) =>
    栏.还有 ? (
      <button
        className="可点"
        onClick={栏.加载更多}
        disabled={栏.加载中}
        style={{ width: '100%', padding: '10px', color: 'var(--最弱)' }}
      >
        {栏.加载中 ? '加载中…' : '加载更多'}
      </button>
    ) : null;

  return (
    <弹层框架 标签="选择职位类别" 遮罩类名={样式.分类遮罩} 面板类名={样式.分类层} 关闭={关闭}>
      <span className={样式.分类抓手} />
      <div className={样式.分类标题}>职位类别</div>
      <div className={样式.分类体}>
        {/* 左栏：根项 */}
        <div className={`${样式.大类栏} 滚动区`}>
          {根栏.项们.map(根项键)}
          {分页键(根栏)}
        </div>
        {/* 右栏：当前根的子项；可选叶子原子选定，不可选父项继续下钻 */}
        <div className={`${样式.小类栏} 滚动区`}>
          {子栏.项们.map(子项键)}
          {分页键(子栏)}
        </div>
      </div>
    </弹层框架>
  );
}
