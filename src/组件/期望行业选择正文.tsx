// 期望行业选择正文（Task 7，core editors §5.2）：选期望行业页（/intentions/industries）
// 两模式共用正文。版式照原页 JSX 自上而下：次级页外壳(白底) → 返回栏 ‹ + 右上「保存」→
// 大标题「已选行业」+ 右上 N/3 计数 → 副标题 →「推荐」一行 chips → 手风琴清单
// （组行点开展开该组细分 chips 多选）→ 根列表尾「加载更多」。
// 样式直接沿用原页面 CSS（选期望行业.module.css），不另建样式、不改基础组件外观。
//
// 本组件是纯展示正文：只收展示值、稳定键、状态与回调，不依赖数据源模式、BFF DTO、
// Context、API、路由或存储。真实目录引用、分页游标、迟到响应、3 项上限的写入守卫与
// 保存归属都在页面外层（选期望行业页沿原业务：选择即写意向草稿，保存只负责返回）。
// 组件按 键 回报点击，不按显示名反查真实 ID。
//
// 计数与上限态来自 已选项们（不扫当前可见分组）——已选不依赖当前可见项；上限沿规格
// 固定 3（与原页 行业上限 一致）：未选片禁用变灰、已选片仍可点移除、组行展开不受限，
// 与原页逐位一致。
//
// 片点击沿现有优先级：可选则 切换（含取消已选），否则可展开才 展开；两者均假单击不动
//（页面侧契约：不发目录请求、不提交）。`可选` 源自 selectable、`可展开` 由页面按
// 目录形态映射，本组件不推导。
//
// 分组们按列表顺序渲染，是展示批次不是新树存储：层级 0 组 = 手风琴行 + 展开细分片组
//（含组尾「加载更多」）；层级 ≥1 组 = 嵌套细分片组（沿用原孙项盒 paddingLeft 12，
// 无自己的行标题，自带分页尾），承载「非 selectable 子项展开后的孙项」，渲染时按
// 稳定键插回同键子片之后 —— 照原稿「子片 wrapper + 孙盒 + 其余兄弟子片 + 组分页尾」
// 的交错位置逐位还原。

import 样式 from '../屏幕/选期望行业.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from './通用';

/** 期望行业多选上限（规格：最多 3 个）—— 计数分母与上限态都由此推导 */
const 行业上限 = 3;

/** 一枚行业片的展示值：键是稳定键（Backend = 目录 ID，Mock = 局部模拟键），与名称分离 */
export type 期望行业项 = { 键: string; 名称: string; 选中: boolean; 可选: boolean; 可展开: boolean };

/** 一组（层级 0 手风琴组 / 层级 ≥1 嵌套片组）的展示输入；「加载中 / 还有 / 加载更多」指本组当前可见列表 */
export type 期望行业组 = {
  键: string; 标题: string; 层级: 0 | 1 | 2; 已展开: boolean;
  项们: 期望行业项[]; 加载中: boolean; 还有: boolean; 加载更多: () => void;
};

/** 正文 props（页面局部契约，不是公共领域模型） */
export type 期望行业选择正文Props = {
  已选项们: 期望行业项[]; 推荐项们: 期望行业项[]; 分组们: 期望行业组[];
  根加载中: boolean; 根还有: boolean; 根加载更多: () => void;
  展开: (键: string) => void; 切换: (键: string) => void; 返回: () => void; 保存: () => void;
};

export function 期望行业选择正文({
  已选项们,
  推荐项们,
  分组们,
  根加载中,
  根还有,
  根加载更多,
  展开,
  切换,
  返回,
  保存,
}: 期望行业选择正文Props): React.JSX.Element {
  const 已满 = 已选项们.length >= 行业上限;

  /** 一枚行业片：推荐区与手风琴展开区（含孙项盒）共用同一枚。
   *  三态：未选 / 选中（✓ 由 CSS ::before 前置渲染）/ 上限态未选禁用变灰 */
  const 片键 = (项: 期望行业项) => {
    const 不可点 = !项.选中 && 已满;
    return (
      <button
        key={项.键}
        className={[样式.行业片, 项.选中 ? 样式.行业片选中 : '', 不可点 ? 样式.行业片禁用 : '可点'].join(' ')}
        onClick={() => {
          if (项.可选) {
            切换(项.键);
            return;
          }
          if (项.可展开) 展开(项.键);
        }}
        disabled={不可点}
        aria-pressed={项.选中}
      >
        {项.名称}
      </button>
    );
  };

  /** 组尾分页沿用原页控件：还有才渲染，忙时文案换「加载中…」并禁用 */
  const 分页键 = (组: 期望行业组) =>
    组.还有 ? (
      <button className={`${样式.加载更多键} 可点`} onClick={组.加载更多} disabled={组.加载中}>
        {组.加载中 ? '加载中…' : '加载更多'}
      </button>
    ) : null;

  // 层级 ≥1 的嵌套片组折进最近前面的 层级 0 组（页面按「父组之后紧跟孙盒」给出顺序）
  const 折叠组们: { 组: 期望行业组; 嵌套们: 期望行业组[] }[] = [];
  分组们.forEach((组) => {
    if (组.层级 === 0 || 折叠组们.length === 0) 折叠组们.push({ 组, 嵌套们: [] });
    else 折叠组们[折叠组们.length - 1]!.嵌套们.push(组);
  });

  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：页底改白底
    <次级页外壳 白底>
      <返回栏
        返回={返回}
        右侧={
          <button className={`${样式.保存键} 可点`} onClick={保存}>
            保存
          </button>
        }
      />

      {/* 大标题 + 右上 N/3 计数（版式同 选工作城市 的标题行）*/}
      <div className={样式.标题行}>
        <h1 className={样式.大标题}>已选行业</h1>
        <span className={`${样式.计数} 等宽数字`}>
          {已选项们.length}/{行业上限}
        </span>
      </div>
      <p className={样式.副标题}>请选择行业，最多3个</p>

      <滚动区>
        <div className={样式.内容区}>
          <div className={样式.组标}>推荐</div>
          <div className={样式.推荐片组}>{推荐项们.map((项) => 片键(项))}</div>

          <div className={样式.手风琴}>
            {折叠组们.map(({ 组, 嵌套们 }) => (
              <div key={组.键} className={样式.手风琴组}>
                <button className={`${样式.手风琴行} 可点`} onClick={() => 展开(组.键)} aria-expanded={组.已展开}>
                  <span className={样式.手风琴行名}>{组.标题}</span>
                  <span className={样式.展开箭头}>{组.已展开 ? '⌃' : '⌄'}</span>
                </button>
                {组.已展开 ? (
                  <div className={样式.细分片组}>
                    {组.加载中 && 组.项们.length === 0 ? <div className={样式.无结果}>加载中…</div> : null}
                    {/* 照原稿：每枚片一个 wrapper，同键孙项盒紧跟其后（多级展开沿原实现的位置） */}
                    {组.项们.map((项) => (
                      <div key={项.键}>
                        {片键(项)}
                        {嵌套们.map((嵌套) =>
                          嵌套.已展开 && 嵌套.键 === 项.键 ? (
                            <div key={嵌套.键} className={样式.细分片组} style={{ paddingLeft: 12 }}>
                              {嵌套.项们.map((嵌套片) => 片键(嵌套片))}
                              {分页键(嵌套)}
                            </div>
                          ) : null,
                        )}
                      </div>
                    ))}
                    {分页键(组)}
                  </div>
                ) : null}
              </div>
            ))}
            {/* 根列表尾分页（沿原页位置：挂在全部手风琴组之后） */}
            {根还有 ? (
              <button className={`${样式.加载更多键} 可点`} onClick={根加载更多} disabled={根加载中}>
                {根加载中 ? '加载中…' : '加载更多'}
              </button>
            ) : null}
          </div>
        </div>
      </滚动区>
    </次级页外壳>
  );
}
