// 期望行业选择正文（picker 统一 Task 1）：选期望行业页（/intentions/industries）
// 两模式共用正文。版式照原页自上而下：次级页外壳(白底) → 返回栏 ‹ + 右上「保存」→
// 大标题「已选行业」+ 右上 N/3 计数 → 副标题 → 行业折叠目录列表（共用 行业分类列表）。
// 原页的「推荐」区按 Plan 删除（伪推荐不再保留），目录展开/缓存/分页/重试机制由
// 屏幕/行业目录钩子 提供，页面注入查询适配；选择归属（多选上限、按稳定 ID 写意向草稿）
// 仍在本页外层，正文不读数据源模式、Context、BFF DTO 或路由。
//
// 计数与上限来自 已选键 与 上限（不扫当前可见行）——已选不依赖当前可见项；
// 满额时未选可选行由 行业分类列表 禁用变灰、已选行仍可点移除、展开行不受限。

import 样式 from '../屏幕/选期望行业.module.css';
import { 次级页外壳, 返回栏, 滚动区 } from './通用';
import { 行业分类列表, type 行业项, type 行业目录状态 } from './行业分类列表';

/** 正文 props（页面局部契约，不是公共领域模型） */
export type 期望行业选择正文Props = {
  已选键: readonly string[];
  上限: number;
  目录: 行业目录状态;
  选择: (项: 行业项) => void;
  返回: () => void;
  保存: () => void;
};

export function 期望行业选择正文({
  已选键,
  上限,
  目录,
  选择,
  返回,
  保存,
}: 期望行业选择正文Props): React.JSX.Element {
  return (
    // 2026-08-24 全站选择风格统一（C1 定稿）：页底改白底
    <次级页外壳 白底>
      <返回栏
        返回={返回}
        右侧={
          <button className={`${样式.保存键} 可点`} onClick={保存}>
            保存
          </button>
        }
      />

      {/* 大标题 + 右上 N/3 计数（版式同 选工作城市 的标题行）*/}
      <div className={样式.标题行}>
        <h1 className={样式.大标题}>已选行业</h1>
        <span className={`${样式.计数} 等宽数字`}>
          {已选键.length}/{上限}
        </span>
      </div>
      <p className={样式.副标题}>请选择行业，最多3个</p>

      <滚动区>
        <div className={样式.内容区}>
          {/* 共用折叠目录列表：全页滚动区里容器自然增高、由外层滚动区滚动 */}
          <div className={样式.手风琴}>
            <行业分类列表 {...目录} 已选键={已选键} 上限={上限} 选择={选择} />
          </div>
        </div>
      </滚动区>
    </次级页外壳>
  );
}
