// 详情底栏 —— 底部 Case 叮嘱输入/只读状态的纯展示（契约 A，详情统一 Task 9）。
//   · 输入 可用（发送!==null 且 禁用说明===null）直接复用全站 真输入条（现有 props 足够，
//     不为本页改它的默认行为）：占位/值/改变/发送原样接线；
//   · 其余（只读 态，或 输入 态缺发送/带禁用说明）一律本组件自己的只读条 —— 终局
//     「保留底部区域且无可执行发送」（spec §5），说明可见；
//   · 已发送的在飞锁归控制层（发送回调内部栅栏），不靠 disabled DOM 冒充。
// 本组件不读 Context/fixture、不发请求、不推导终局 —— 只读还是输入由控制层定。

import { 真输入条 } from '../通用';
import 样式 from './详情外壳.module.css';
import type { 详情底栏信息 } from './类型';

export function 详情底栏({ 信息 }: { 信息: 详情底栏信息 }) {
  // 可用输入 = 输入 态且按钮铁律成立（发送在场、无禁用说明）
  if (信息.kind === '只读' || 信息.发送 === null || 信息.禁用说明 !== null) {
    const 说明 = 信息.kind === '只读' ? 信息.说明 : (信息.禁用说明 ?? '当前不可输入');
    return <div className={样式.只读底栏}>{说明}</div>;
  }
  return (
    <真输入条 占位={信息.占位} 值={信息.值} 改变={信息.改变} 发送={信息.发送} />
  );
}
