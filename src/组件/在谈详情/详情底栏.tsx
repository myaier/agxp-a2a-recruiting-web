// 详情底栏 —— 底部 Case 叮嘱输入/禁用/只读状态的纯展示（契约 A，详情统一 Task 9；
// J-PILOT-01 Task 6 按 Spec §7 调整禁用分支）。
//   · 输入 可用（发送!==null 且 禁用说明===null）直接复用全站 真输入条（现有 props 足够，
//     不为本页改它的默认行为）：占位/值/改变/发送原样接线；
//   · 输入 不可用（发送 null 或 禁用说明非空，双端 S0）仍是原 真输入条 控件 —— textarea
//     与发送键保留在 DOM（尺寸/位置不变）但真实 disabled + 键盘先挡 + 改变不接线（输入值
//     清空），绝不换成只读 div，也不仅靠颜色灰化；占位文案即禁用说明（映射层成对产出）；
//   · 只读 态维持本组件自己的只读条 —— 终局（非 S0）「保留底部区域且无可执行发送」，
//     说明可见；
//   · 已发送的在飞锁归控制层（发送回调内部栅栏），不靠 disabled DOM 冒充。
// 本组件不读 Context/fixture、不发请求、不推导终局 —— 禁用还是输入由控制层定。

import { 真输入条 } from '../通用';
import 样式 from './详情外壳.module.css';
import type { 详情底栏信息 } from './类型';

export function 详情底栏({ 信息 }: { 信息: 详情底栏信息 }) {
  if (信息.kind === '只读') {
    return <div className={样式.只读底栏}>{信息.说明}</div>;
  }
  // 输入不可用（双端 S0）：原控件保留但真实禁用；改变不接线（值恒清空，草稿写不进控制层）
  if (信息.发送 === null || 信息.禁用说明 !== null) {
    return (
      <真输入条
        占位={信息.占位}
        值={信息.值}
        改变={() => undefined}
        发送={信息.发送 ?? (() => undefined)}
        禁用
      />
    );
  }
  return (
    <真输入条 占位={信息.占位} 值={信息.值} 改变={信息.改变} 发送={信息.发送} />
  );
}
