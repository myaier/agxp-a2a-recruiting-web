// 详情顶栏 —— 共用外壳的第一行：返回键 + 标题位 + 副标题 + 右侧分数/薪资 + 岗位上下文。
//
// 全部内容由 顶栏信息 给定，本组件不做任何业务推导：
//   · 标题位给了 画像 就渲染画像行（招聘端去名裁定：真名/代号/candidateAlias 都不上顶栏，
//     传入的 标题 直接忽略），画像缺段显示缺失占位、性别位给中性未知标记（不猜性别）；
//     没有画像就渲染 标题 文本（求职端 职位 · 公司 / 冻结职位名），null 时留空标题位。
//   · 右侧分数：真实值原样（0 也是合法值），缺失显示「—」并带「匹配分缺失」可访问说明，
//     不画假分数或低分警示；低于 80 沿用 Mock 既有的协调橙警示。
//   · 岗位上下文是独立一行（招聘端顶栏让位给画像后，冻结职位 · 城市 · 薪资带仍要可读）。

import 候选头行 from '../候选头行';
import { 返回栏 } from '../通用';
import 样式 from './详情外壳.module.css';
import type { 顶栏信息 } from './类型';

/** 招聘端画像三段的缺失占位：位置保留、缺失说缺失，不编值。 */
const 画像缺失占位 = {
  年限: '经验缺失',
  学历: '学历缺失',
  求职状态: '求职状态缺失',
} as const;

/** 性别未知时的中性占位归共享 候选头行（Spec §9 合入收敛）：显式传 未知性别占位，
 *  16px 灰色 ?、读屏与 title 均为「性别未知」，不猜性别，也不在详情留第三份标记。 */
function 画像行(画像: NonNullable<顶栏信息['画像']>) {
  return (
    <div className={样式.画像行}>
      <候选头行
        性别={画像.性别 ?? undefined}
        未知性别占位={画像.性别 === null}
        年限={画像.年限 ?? 画像缺失占位.年限}
        学历={画像.学历 ?? 画像缺失占位.学历}
        求职状态={画像.求职状态 ?? 画像缺失占位.求职状态}
      />
    </div>
  );
}

export function 详情顶栏({ 信息, 返回 }: { 信息: 顶栏信息; 返回: () => void }) {
  const { 端, 标题, 副标题, 画像, 右侧, 岗位上下文 } = 信息;
  // NaN 不是合法分数：按缺失处理，绝不把 NaN 印到屏上（spec 验收：无 NaN）
  const 分数 = 右侧.kind === '分数' && 右侧.值 !== null && !Number.isNaN(右侧.值) ? 右侧.值 : null;
  return (
    <>
      <返回栏
        返回={返回}
        标题={画像 === null ? (标题 ?? undefined) : undefined}
        标题节点={画像 === null ? undefined : 画像行(画像)}
        副标题={副标题 ?? undefined}
        右侧={
          右侧.kind === '分数' ? (
            <span className={样式.分数组}>
              <span className={样式.分数标}>{端 === '招聘' ? '匹配' : '适配'}</span>
              <span
                className={`${样式.分数值} ${分数 !== null && 分数 < 80 ? 样式.分数警示 : ''} 等宽数字`}
                title={分数 === null ? '匹配分缺失' : undefined}
              >
                {分数 === null ? '—' : 分数}
              </span>
            </span>
          ) : (
            <span className={`${样式.薪资} 薪资体`} title={右侧.值 === null ? '薪资缺失' : undefined}>
              {右侧.值 ?? '—'}
            </span>
          )
        }
      />
      {岗位上下文 !== null ? <div className={样式.岗位上下文}>{岗位上下文}</div> : null}
    </>
  );
}
