// 详情状态区 —— 「代谈进度」顶部的状态行（P5 待办徽标 / 闭词状态 / 步骤说明 / 轮次 /
// 注意说明）。内容全部由 状态区信息 给定，本组件不做任何业务推导：不读 Context/fixture、
// 不推导动作权限、不请求数据。
//   · 徽标 null = 终局只读态，徽标位退场（「处理中」是进行中的语义）；其余三值各用
//     既有样式位，需注意与待办同色阶（都是「要看一眼」），代理处理中走中性灰。
//   · 轮次 null = 该来源没有轮次字段（Mock 等），显示「轮次 —」并带可访问缺失说明，
//     绝不编造数字；轮次 0 是合法数值，照常显示。
//   · 注意说明只在有值时出现（不人为制造注意提示）；阶段标题归下方分节条（spec §3.2），
//     状态区只承载闭词状态，避免与当前阶段的标题重复。

import 样式 from './详情外壳.module.css';
import type { 状态区信息 } from './类型';

export function 详情状态区({ 信息 }: { 信息: 状态区信息 }) {
  return (
    <div className={样式.状态区}>
      {信息.徽标 !== null ? (
        <span
          className={`${样式.徽标} ${信息.徽标 === '代理处理中' ? 样式.徽标代理 : 样式.徽标待办}`}
        >
          {信息.徽标}
        </span>
      ) : null}
      <span className={样式.状态标}>{信息.状态}</span>
      {信息.步骤 !== null ? <span className={样式.步骤说明}>{信息.步骤}</span> : null}
      {信息.轮次 !== null ? (
        <span className={`${样式.轮次} 等宽数字`}>
          轮次 {信息.轮次.当前}/{信息.轮次.预算}
        </span>
      ) : (
        <span className={`${样式.轮次} 等宽数字`} title="轮次缺失">
          轮次 —
        </span>
      )}
      {信息.注意说明 !== null ? <div className={样式.注意说明}>{信息.注意说明}</div> : null}
    </div>
  );
}
