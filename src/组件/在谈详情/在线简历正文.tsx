// 在线简历正文 —— 招聘端在谈详情第二 Tab（资料）与独立匿名简历页共用的唯一正文
// （详情统一 Task 4 自 屏幕/匿名在线简历 的 简历正文 提取；旧导出变成兼容包装。
// S0–S3 展示统一 Task 6：正文只吃一个输入 内容（数据/在线简历正文映射 的归一产出），
// 不再识别数据源 —— 两来源在连接器/包装处归一成同一模型，这里没有任何双源分支，
// 也不 import Mock 简历档或任何 raw DTO）。信息顺序即 spec §3.4/§7.1：
// 匿名画像/职位行 → 匹配依据 → 个人优势 → 求职期望 → 工作经历 → 项目经历 → 教育经历 →
// 专业技能 → 页尾说明。
//
// 纯展示：不读 Context/fixture/localStorage/环境变量，不请求数据、不推导动作权限、
// 不拼路由。实名/授权决定都在适配层完成：经历段的公司名已是已授权显示的公司，
// 页尾的披露/核验说明也由 内容.页尾说明 显式带来（安全来源不携带 → 回退生成声明）。
//
// 缺失口径（spec §3.4/§7.2）：内容 = null 表示数据源未提供结构化在线简历 —— 各信息区在
// 同一组 JSX 里原位显示缺失，绝不顶层换成另一整页；区级 null 给「XX缺失」、合法 [] 给
// 「暂无…」，二者不互换。缺失走既有次要文字色，不用错误红/通过绿。期望薪资槽只吃
// 归一后的 薪资结论（安全来源 unknown → null 不出），「薪资带已进入初筛/一致」这类
// 无依据承诺不由本组件生成。
// 完整布局（详情显式传 true）给缺失/空区保留标题与空状态；独立简历页兼容包装默认
// false —— 空项目整区不出、匹配依据缺行整区不渲染。资料各区真实为空是页面要表达的
// 事实，缺失/空状态照常出。
// 页尾由显式展示事实输入（spec §7.3）：内容 null → 缺失；已确认（双方确认完成事实，
// 不能 stage===S3）→ 确认文案；否则 内容.页尾说明（Mock 适配层按演示事实提供），
// 无页尾说明时回退「由候选人的AI代理生成 · 内容不可转发」—— 没有证据不宣称双向核验。

import { 匹配对齐卡 } from '../匹配对齐卡';
import 候选头行 from '../候选头行';
// 沿用原 CSS（契约 B）：旧 module 仍被 兼容包装 与独立简历页消费，这里只加
// 「仅本页显式完整布局样式」，不为第二份正文另建样式。
import 样式 from '../../屏幕/匿名在线简历.module.css';
import type { 在线简历正文属性 } from './类型';

/** 安全来源无匹配分数证据：匹配区标题与缺失提示照常保留（spec R1，不整区消失） */
const 匹配分析缺失块 = (
  <>
    <div className={样式.节标行}>
      <span className={样式.节标}>匹配度分析</span>
    </div>
    <p className={样式.区块缺失}>匹配分析缺失</p>
  </>
);

export function 在线简历正文({
  内容,
  对齐行们 = null,
  推荐依据 = undefined,
  已确认 = false,
  完整布局 = false,
  缺失说明 = null,
}: 在线简历正文属性) {
  // 缺失/空区「保留标题与空状态」的开关：详情显式传 完整布局；内容缺失（整份缺源档）
  // 时同样按缺失布局兜底 —— 同一组 JSX，不另起一页。
  const 缺区保留标题 = 完整布局 || 内容 === null;

  return (
    <div className={样式.页体}>
      {/* 区块级缺口说明（详情由连接层给，如「当前在谈详情数据未提供」）；旧版式不渲染 */}
      {缺区保留标题 && 缺失说明 !== null ? <p className={样式.缺口说明}>{缺失说明}</p> : null}

      {/* ── 头区：与列表卡同一套头行（性别图标 + 年限｜学历｜状态）+ 职位行。
          2026-09-09 产品负责人（第二批）：大代号（真名/代号）与灰人像占位整体删除 ——
          「卡面不显示真名」，头区同理；真名事实只剩适配层的公司实名恢复与页尾说明。
          年限由适配层给「N 年」（Mock 去「经验」后缀 / 安全摘要「不满 1 年」口径）。 ── */}
      <div className={样式.头区}>
        {内容 !== null && 内容.头区 !== null ? (
          <>
            <候选头行
              性别={内容.头区.性别 ?? undefined}
              年限={内容.头区.年限}
              学历={内容.头区.学历}
              求职状态={内容.头区.求职状态}
            />
            {内容.头区.职位行 !== null
              ? <div className={样式.职位行}>{内容.头区.职位行}</div>
              : <p className={样式.区块缺失}>职位信息缺失</p>}
          </>
        ) : (
          <>
            <p className={样式.区块缺失}>匿名画像缺失</p>
            <p className={样式.区块缺失}>职位信息缺失</p>
          </>
        )}
      </div>

      {/* 概览条(经验/学历/年龄)已删(用户 2026-09-01):经验与学历在匹配度分析里有证据行,不重复 */}

      {/* ── 匹配度分析(2026-08-26 定稿对齐表,两端同构):岗位硬性条件原文 ×
          候选简历原文,与求职端职位详情同一个共用卡。
          藏环:返回栏已带「匹配 N」,同屏不出现两个分数(2026-08-24 既定口径)
          完整布局:缺分或缺行时标题与位置保留,显示缺失 —— 不伪造 0 分/空行喂给卡；
          分数槽只有归一内容带来时才画卡，安全来源（适配分 null）按布局出缺失块 ── */}
      {内容 !== null && 内容.适配分 !== null && 对齐行们 !== null && 对齐行们.length > 0 ? (
        <div className={样式.对齐卡容器}>
          <匹配对齐卡 分={内容.适配分} 行们={对齐行们} 藏环 />
        </div>
      ) : 缺区保留标题 ? (
        推荐依据 !== undefined ? (
          // DF-011：独立详情启用推荐依据时，缺失文案换成批准的可读状态（标题仍只一个）；
          // 不传 prop 的 Case/旧消费者保持原「匹配分析缺失」，文案不被全局更换
          <>
            <div className={样式.节标行}>
              <span className={样式.节标}>匹配度分析</span>
            </div>
            <p className={样式.区块缺失}>暂无逐条匹配证据</p>
          </>
        ) : (
          匹配分析缺失块
        )
      ) : null}

      {/* ── DF-011 推荐依据（画像之后、个人优势之前）：当前推荐批次返回的已知原因，
          映射/去重由调用方经 映射推荐依据 完成。顶栏已带唯一分数位：这里只出说明文字，
          不画分数环、不以已有原因合成对齐行；[] 给「暂无推荐依据」不猜词义。 ── */}
      {推荐依据 !== undefined ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>推荐依据</span>
          </div>
          {推荐依据.length > 0
            ? 推荐依据.map((依据) => (
              <p key={依据} className={样式.自述}>{依据}</p>
            ))
            : <p className={样式.区块缺失}>暂无推荐依据</p>}
        </>
      ) : null}

      {/* ── 个人优势段（2026-08-21：与注册采集页「分享一下自己的个人优势」统一命名）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>个人优势</span>
      </div>
      {内容 !== null && 内容.自述 !== null ? (
        <p className={样式.自述}>{内容.自述}</p>
      ) : (
        <p className={样式.区块缺失}>个人优势缺失</p>
      )}

      {/* ── 求职期望：薪资槽只吃归一后的结论文案（安全来源 unknown/缺源 → null 不出），
          一致性条只有 Mock 演示事实带 —— 不拿岗位薪资代填候选期望，也不给「已进入初筛/
          一致」这类无依据承诺（spec §3.4 / §7.2：unknown 不作结论）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>求职期望</span>
      </div>
      {内容 !== null && 内容.期望 !== null ? (
        <>
          <div className={样式.期望标题行}>
            {内容.期望.标题 !== null ? <span className={样式.期望标题}>{内容.期望.标题}</span> : null}
            {内容.期望.薪资结论 !== null ? <span className={样式.期望薪资}>{内容.期望.薪资结论}</span> : null}
          </div>
          {内容.期望.带宽行 !== null || 内容.期望.偏好 !== null ? (
            <div className={样式.期望副行}>
              {内容.期望.带宽行}
              {内容.期望.偏好 ? <span className={样式.期望偏好}>{内容.期望.偏好}</span> : null}
            </div>
          ) : null}
          {内容.期望.一致性 !== null ? (
            <div className={样式.一致条}>
              <span className={样式.一致符} aria-hidden>✓</span>
              <span>{内容.期望.一致性}</span>
            </div>
          ) : null}
        </>
      ) : (
        <p className={样式.区块缺失}>求职期望缺失</p>
      )}

      {/* ── 工作经历：每段可带 AI 逐段批注绿条（Mock 演示事实）。公司名已由适配层定为
          已授权显示的公司 —— 真名→实名的恢复不在这里做 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>工作经历</span>
      </div>
      {内容 === null || 内容.经历 === null ? (
        <p className={样式.区块缺失}>工作经历缺失</p>
      ) : 内容.经历.length > 0 ? (
        内容.经历.map((段, 序) => (
          <div key={`${序}-${段.起止}-${段.公司 ?? ''}`} className={样式.经历段}>
            <div className={样式.经历头}>
              <span className={`${样式.经历公司} 单行`}>{段.公司}</span>
              {段.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{段.起止}</span> : null}
            </div>
            {段.职位 !== null ? <div className={样式.经历职位}>{段.职位}</div> : null}
            {段.说明 !== null ? (
              <div className={样式.经历说明}>
                {段.说明.split('\n').map((行) => (
                  <div key={行} className={样式.说明行}>
                    {行}
                  </div>
                ))}
              </div>
            ) : null}
            {段.批注 ? (
              <div className={样式.一致条}>
                <span className={样式.一致符} aria-hidden>✓</span>
                <span>{段.批注}</span>
              </div>
            ) : null}
          </div>
        ))
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无工作经历</p>
      ) : null}

      {/* ── 项目经历：空也保留标题与空状态 —— 但只由完整布局开关控制（独立页旧版式
          整区不出；详情缺失/空状态照常出）。起止由适配层给（安全来源恒 null）── */}
      {内容 === null || 内容.项目 === null || 缺区保留标题 || 内容.项目.length > 0 ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>项目经历</span>
          </div>
          {内容 === null || 内容.项目 === null ? (
            <p className={样式.区块缺失}>项目经历缺失</p>
          ) : 内容.项目.length > 0 ? (
            内容.项目.map((项, 序) => (
              <div key={`${序}-${项.名称 ?? ''}`} className={样式.经历段}>
                <div className={样式.经历头}>
                  <span className={`${样式.经历公司} 单行`}>{项.名称}</span>
                  {项.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{项.起止}</span> : null}
                </div>
                {项.角色 !== null ? <div className={样式.经历职位}>{项.角色}</div> : null}
                {项.说明 !== null ? <div className={样式.经历说明}>{项.说明}</div> : null}
                {项.批注 ? (
                  <div className={样式.一致条}>
                    <span className={样式.一致符} aria-hidden>✓</span>
                    <span>{项.批注}</span>
                  </div>
                ) : null}
              </div>
            ))
          ) : (
            <p className={样式.区块缺失}>暂无项目经历</p>
          )}
        </>
      ) : null}

      {/* ── 教育经历：直接显示具体学校（用户定：学校不脱敏，onboarding 配置）；
          多条保持源序，逐条复用既有教育条目样式 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>教育经历</span>
      </div>
      {内容 === null || 内容.教育 === null ? (
        <p className={样式.区块缺失}>教育经历缺失</p>
      ) : 内容.教育.length > 0 ? (
        内容.教育.map((条, 序) => (
          // key 用源位置组合：同校同起止的多条不因值重复而丢条
          <div key={`${序}-${条.行}`} className={样式.教育行}>
            <span className={样式.教育文}>{条.行}</span>
            {条.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{条.起止}</span> : null}
          </div>
        ))
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无教育经历</p>
      ) : null}

      {/* ── 专业技能 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>专业技能</span>
      </div>
      {内容 === null || 内容.技能 === null ? (
        <p className={样式.区块缺失}>专业技能缺失</p>
      ) : 内容.技能.length > 0 ? (
        <div className={样式.技能行}>
          {内容.技能.map((技, 序) => (
            <span key={`${序}-${技}`} className={样式.技能片}>
              {技}
            </span>
          ))}
        </div>
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无专业技能</p>
      ) : null}

      {/* ── 披露/沟通状态说明：只消费显式展示事实（spec §7.3）—— 内容缺失时不沿用
          「内容真实性经双向核验」（没有正文就核验不了）；已确认只来自双方确认完成
          事实；其余按 内容.页尾说明（适配层按演示事实提供），无说明不宣称核验/披露。 ── */}
      <div className={样式.页尾注}>
        {内容 === null
          ? '在线简历缺失 · 内容不可转发'
          : 已确认
            ? '双方已确认意向，可进入真人沟通 · 内容不可转发'
            : 内容.页尾说明 != null && 内容.页尾说明 !== ''
              ? 内容.页尾说明
              : '这份简历由候选人的AI代理生成 · 内容不可转发'}
      </div>
    </div>
  );
}
