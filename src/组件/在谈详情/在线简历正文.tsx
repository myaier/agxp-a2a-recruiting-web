// 在线简历正文 —— 招聘端在谈详情第二 Tab（资料）与独立匿名简历页共用的唯一正文
// （详情统一 Task 4，自 屏幕/匿名在线简历 的 简历正文 提取；旧导出变成兼容包装，
// 这里是正文 JSX 的唯一出处）。信息顺序即 spec §3.4：匿名画像/职位行 → 匹配依据 →
// 个人优势 → 求职期望 → 工作经历 → 项目经历 → 教育经历 → 专业技能 → 披露/沟通状态说明。
//
// 纯展示：不读 Context/fixture/localStorage/环境变量/raw DTO，不请求数据、不推导动作
// 权限、不拼路由。匿名简历档 只 type import（契约 B：不导入 Mock 简历表或任何值）。
//
// 缺失口径（spec §3.4/§4）：档 = null 表示数据源未提供结构化在线简历 —— 各信息区在
// 同一组 JSX 里原位显示缺失，绝不顶层换成另一整页，也不以一句「简历尚未同步」替代
// 整页；缺失走既有次要文字色，不用错误红/通过绿。求职期望未知时不渲染 薪资结论 与
// 一致性条 —— 岗位薪资不是候选求职期望，「薪资带已进入初筛/一致」这类无依据承诺不出。
// 完整布局（详情显式传 true）才给缺失/空区保留标题与空状态；独立简历页不传（默认
// false），保持旧版式 —— 空项目整区不出、匹配依据缺行整区不渲染。
// 披露边界（spec §4）：档缺失 ≠ 权威状态未授权/未披露，缺失不自动改写成「尚未披露」。

import { 匹配对齐卡 } from '../匹配对齐卡';
import 候选头行 from '../候选头行';
// 沿用原 CSS（契约 B）：旧 module 仍被 兼容包装 与独立简历页消费，这里只加
// 「仅本页显式完整布局样式」，不为第二份正文另建样式。
import 样式 from '../../屏幕/匿名在线简历.module.css';
import type { 在线简历正文属性 } from './类型';

export function 在线简历正文({
  档,
  真名 = null,
  已确认 = false,
  薪资结论 = '薪资带已进入初筛',
  对齐行们 = null,
  求职状态 = null,
  完整布局 = false,
  缺失说明 = null,
}: 在线简历正文属性) {
  const 已披露 = 真名 !== null && 真名 !== undefined && 真名 !== '';
  // 缺失/空区「保留标题与空状态」的开关：详情显式传 完整布局；档缺失时没有旧版式可走
  // （独立页恒传档），同样按缺失布局兜底 —— 同一组 JSX，不另起一页。
  const 缺区保留标题 = 完整布局 || 档 === null;

  return (
    <div className={样式.页体}>
      {/* 区块级缺口说明（详情由连接层给，如「当前在谈详情数据未提供」）；旧版式不渲染 */}
      {缺区保留标题 && 缺失说明 !== null ? <p className={样式.缺口说明}>{缺失说明}</p> : null}

      {/* ── 头区：与列表卡同一套头行（性别图标 + 年限｜学历｜状态）+ 职位行。
          2026-09-09 产品负责人（第二批）：原 大代号（已披露 ? 真名 : 代号）与灰人像占位整体删除 ——
          9/8 定稿「卡面不显示真名」，头区同理；真名事实只剩下面的公司实名还原与页尾注在用。
          年限取简历档 经验（「9 年经验」→「9 年」），与列表卡画像首段同一写法。 ── */}
      <div className={样式.头区}>
        {档 !== null ? (
          <>
            <候选头行
              性别={档.性别}
              年限={档.经验.replace(/经验$/, '')}
              学历={档.学历}
              求职状态={求职状态}
            />
            <div className={样式.职位行}>{档.职位行}</div>
          </>
        ) : (
          <>
            <p className={样式.区块缺失}>匿名画像缺失</p>
            <p className={样式.区块缺失}>职位信息缺失</p>
          </>
        )}
      </div>

      {/* 概览条(经验/学历/年龄)已删(用户 2026-09-01):经验与学历在匹配度分析里有证据行,不重复 */}

      {/* ── 匹配度分析(2026-08-26 定稿对齐表,两端同构):岗位硬性条件原文 ×
          候选简历原文,与求职端职位详情同一个共用卡。原「AI代理读完简历后的判断」
          散文卡随之退役——判断类小文案整类淘汰,证据自己说话。
          藏环:返回栏已带「匹配 N」,同屏不出现两个分数(2026-08-24 既定口径)
          完整布局:缺分或缺行时标题与位置保留,显示缺失 —— 不伪造 0 分/空行喂给卡 ── */}
      {档 !== null && 对齐行们 !== null && 对齐行们.length > 0 ? (
        <div className={样式.对齐卡容器}>
          <匹配对齐卡 分={档.适配分} 行们={对齐行们} 藏环 />
        </div>
      ) : 缺区保留标题 ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>匹配度分析</span>
          </div>
          <p className={样式.区块缺失}>匹配分析缺失</p>
        </>
      ) : null}

      {/* ── 个人优势段（2026-08-21：与注册采集页「分享一下自己的个人优势」统一命名）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>个人优势</span>
      </div>
      {档 !== null ? (
        <p className={样式.自述}>{档.自述}</p>
      ) : (
        <p className={样式.区块缺失}>个人优势缺失</p>
      )}

      {/* ── 求职期望：档缺失时不渲染 薪资结论/带宽行/一致性条 —— 不拿岗位薪资代填候选期望，
          也不给「已进入初筛/一致」这类无依据承诺（spec §3.4）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>求职期望</span>
      </div>
      {档 !== null ? (
        <>
          <div className={样式.期望标题行}>
            <span className={样式.期望标题}>{档.期望.标题}</span>
            <span className={样式.期望薪资}>{薪资结论}</span>
          </div>
          <div className={样式.期望副行}>
            {档.期望.带宽行}
            {档.期望.偏好 ? <span className={样式.期望偏好}>{档.期望.偏好}</span> : null}
          </div>
          <div className={样式.一致条}>
            <span className={样式.一致符} aria-hidden>✓</span>
            <span>{档.期望.一致性}</span>
          </div>
        </>
      ) : (
        <p className={样式.区块缺失}>求职期望缺失</p>
      )}

      {/* ── 工作经历：每段可带 AI 逐段批注绿条；真名非空（S1）时还原公司实名 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>工作经历</span>
      </div>
      {档 === null ? (
        <p className={样式.区块缺失}>工作经历缺失</p>
      ) : 档.经历.length > 0 ? (
        档.经历.map((段) => (
          <div key={段.起止} className={样式.经历段}>
            <div className={样式.经历头}>
              <span className={`${样式.经历公司} 单行`}>
                {已披露 && 段.公司实名 ? 段.公司实名 : 段.公司}
              </span>
              <span className={`${样式.经历起止} 等宽数字`}>{段.起止}</span>
            </div>
            <div className={样式.经历职位}>{段.职位}</div>
            <div className={样式.经历说明}>
              {段.说明.split('\n').map((行) => (
                <div key={行} className={样式.说明行}>
                  {行}
                </div>
              ))}
            </div>
            {段.批注 ? (
              <div className={样式.一致条}>
                <span className={样式.一致符} aria-hidden>✓</span>
                <span>{段.批注}</span>
              </div>
            ) : null}
          </div>
        ))
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无工作经历</p>
      ) : null}

      {/* ── 项目经历：空也保留标题与空状态 —— 但只由完整布局开关控制（旧版式整区不出）── */}
      {档 === null || 缺区保留标题 || 档.项目.length > 0 ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>项目经历</span>
          </div>
          {档 === null ? (
            <p className={样式.区块缺失}>项目经历缺失</p>
          ) : 档.项目.length > 0 ? (
            档.项目.map((项) => (
              <div key={项.名称} className={样式.经历段}>
                <div className={样式.经历头}>
                  <span className={`${样式.经历公司} 单行`}>{项.名称}</span>
                  <span className={`${样式.经历起止} 等宽数字`}>{项.起止}</span>
                </div>
                <div className={样式.经历职位}>{项.角色}</div>
                <div className={样式.经历说明}>{项.说明}</div>
                {项.批注 ? (
                  <div className={样式.一致条}>
                    <span className={样式.一致符} aria-hidden>✓</span>
                    <span>{项.批注}</span>
                  </div>
                ) : null}
              </div>
            ))
          ) : (
            <p className={样式.区块缺失}>暂无项目经历</p>
          )}
        </>
      ) : null}

      {/* ── 教育经历：直接显示具体学校（用户定：学校不脱敏，onboarding 配置）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>教育经历</span>
      </div>
      {档 !== null ? (
        <div className={样式.教育行}>
          <span className={样式.教育文}>{档.教育行}</span>
          <span className={`${样式.经历起止} 等宽数字`}>{档.教育起止}</span>
        </div>
      ) : (
        <p className={样式.区块缺失}>教育经历缺失</p>
      )}

      {/* ── 专业技能 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>专业技能</span>
      </div>
      {档 === null ? (
        <p className={样式.区块缺失}>专业技能缺失</p>
      ) : 档.技能.length > 0 ? (
        <div className={样式.技能行}>
          {档.技能.map((技) => (
            <span key={技} className={样式.技能片}>
              {技}
            </span>
          ))}
        </div>
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无专业技能</p>
      ) : null}

      {/* ── 披露/沟通状态说明：只消费 已确认/已披露 事实；档缺失时不沿用「内容真实性经
          双向核验」—— 没有正文就核验不了，只保留真实成立的不可转发政策 ── */}
      <div className={样式.页尾注}>
        {档 === null
          ? '在线简历缺失 · 内容不可转发'
          : 已确认
            ? '双方已确认意向，可进入真人沟通 · 内容不可转发'
            : 已披露
              ? '候选人身份已随 S1 原件披露 · 意向确认后进入真人沟通 · 内容不可转发'
              : '这份简历由候选人的AI代理生成 · 内容真实性经双向核验 · 不可转发'}
      </div>
    </div>
  );
}
