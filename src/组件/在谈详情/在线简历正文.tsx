// 资料。两种输入在组件顶部归一化成同一个内部形状再进 JSX —— 不另造 Backend 视觉分支，
// 也不把 nullable 强转成 匿名简历档。
//
// 缺失口径（spec §3.4/§4）：档 / 资料 = null 表示数据源未提供结构化在线简历 —— 各信息区在
// 同一组 JSX 里原位显示缺失，绝不顶层换成另一整页，也不以一句「简历尚未同步」替代
// 整页；区级 null 给「XX缺失」、合法 [] 给「暂无…」，二者不互换。缺失走既有次要文字色，
// 不用错误红/通过绿。求职期望未知时不渲染 薪资结论 与 一致性条 —— 岗位薪资不是候选
