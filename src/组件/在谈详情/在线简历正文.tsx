/** 头区内容（内部归一化形状，不导出）：性别/年限/学历/求职状态 + 最近工作组合职位行 */
interface 头区内容 {
  性别: '男' | '女' | null;
  年限: string | null;
  学历: string | null;
  求职状态: string | null;
  职位行: string | null;
}

/** 工作段（内部归一化形状）：Mock 档带 公司实名 与 批注，资料槽恒 null */
interface 经历段内容 {
  公司: string | null;
  公司实名: string | null;
  起止: string | null;
  职位: string | null;
  说明: string | null;
  批注: string | null;
}

/** 项目段（内部归一化形状）：资料项目无独立日期，起止恒 null */
interface 项目段内容 {
  名称: string | null;
  起止: string | null;
  角色: string | null;
  说明: string | null;
  批注: string | null;
}

/** 期望槽（内部归一化形状）：薪资结论 Mock 取调用方传入，资料取薪资关系文案
 *  （unknown → null 不出）；一致性条只有 Mock 旧档有，资料无证据恒 null */
interface 期望内容 {
  标题: string | null;
  薪资结论: string | null;
  带宽行: string | null;
  偏好: string | null;
  一致性: string | null;
}

/** 两种输入归一化后的正文内容；null = 整份缺源档（各区原位显示缺失） */
interface 正文内容 {
  头区: 头区内容 | null;
  /** 匹配对齐卡的分数槽：只有 Mock 档有；资料模式无分数证据，不画卡也不画缺失占位 */
  适配分: number | null;
  自述: string | null;
  期望: 期望内容 | null;
  经历: 经历段内容[] | null;
  项目: 项目段内容[] | null;
  教育: { 行: string; 起止: string | null }[] | null;
  技能: string[] | null;
}

/** Mock 档 → 正文内容：字段名与非空分支与重构前逐字一致（视觉红线） */
function 从匿名档归一(
  档: 匿名简历档 | null,
  求职状态: string | null,
  薪资结论: string,
): 正文内容 | null {
  if (档 === null) return null;
  return {
    头区: {
      性别: 档.性别 ?? null,
      年限: 档.经验.replace(/经验$/, ''),
      学历: 档.学历,
      求职状态,
      职位行: 档.职位行,
    },
    适配分: 档.适配分,
    自述: 档.自述,
    期望: {
      标题: 档.期望.标题,
      薪资结论,
      带宽行: 档.期望.带宽行 === '' ? null : 档.期望.带宽行,
      偏好: 档.期望.偏好 === '' ? null : 档.期望.偏好,
      一致性: 档.期望.一致性 === '' ? null : 档.期望.一致性,
    },
    经历: 档.经历.map((段) => ({
      公司: 段.公司, 公司实名: 段.公司实名 ?? null, 起止: 段.起止,
      职位: 段.职位, 说明: 段.说明, 批注: 段.批注,
    })),
    项目: 档.项目.map((项) => ({
      名称: 项.名称, 起止: 项.起止, 角色: 项.角色, 说明: 项.说明, 批注: 项.批注,
    })),
    教育: [{ 行: 档.教育行, 起止: 档.教育起止 }],
    技能: [...档.技能],
  };
}

/** Backend 资料 → 正文内容：真名恢复 / 公司实名 / 批注 / 一致性条在资料槽恒不存在；
 *  头行求职状态按约束取 resume.summary 的事实（闭表更全），仅摘要缺失时回退调用方
 *  显式传入的文案，绝不让占位文本覆盖真实事实。 */
function 从展示资料归一(
  资料: 在线简历展示资料 | null,
  求职状态: string | null,
): 正文内容 | null {
  if (资料 === null) return null;
  return {
    头区: 资料.画像 === null ? null : { ...资料.画像, 求职状态: 资料.画像.求职状态 ?? 求职状态 },
    适配分: null,
    自述: 资料.个人优势,
    期望: 资料.期望 === null
      ? null
      : {
          标题: 资料.期望.标题,
          薪资结论: 资料.期望.薪资关系,
          带宽行: 资料.期望.副行,
          偏好: null,
          一致性: null,
        },
    经历: 资料.工作 === null
      ? null
      : 资料.工作.map((段) => ({
          公司: 段.公司, 公司实名: null, 起止: 段.起止, 职位: 段.职位, 说明: 段.说明, 批注: null,
        })),
    项目: 资料.项目 === null
      ? null
      : 资料.项目.map((项) => ({ 名称: 项.名称, 起止: null, 角色: 项.角色, 说明: 项.结果, 批注: null })),
    教育: 资料.教育 === null ? null : 资料.教育.map((条) => ({ 行: 条.行, 起止: 条.起止 })),
    技能: 资料.技能 === null ? null : [...资料.技能],
  };
}

export function 在线简历正文({
  档,
  资料,
  真名 = null,
  已确认 = false,
  薪资结论 = '薪资带已进入初筛',
  对齐行们 = null,
  求职状态 = null,
  完整布局 = false,
  缺失说明 = null,
}: 在线简历正文属性) {
  // 资料模式只由「显式传了 资料」判定（含 资料=null 的整份缺源档）；undefined = Mock 档
  const 资料模式 = 资料 !== undefined;
  // 真名恢复只属于 Mock 档（S1 原件披露的既有口径）；资料模式不传 真名，误传也不生效
  const 已披露 = !资料模式 && 真名 !== null && 真名 !== undefined && 真名 !== '';
  // 缺失/空区「保留标题与空状态」的开关：详情显式传 完整布局；档缺失时没有旧版式可走
  // （独立页恒传档），同样按缺失布局兜底 —— 同一组 JSX，不另起一页。资料模式各区
  // 真实为空就是要表达的事实，缺失/空状态照常出。
  const 缺区保留标题 = 完整布局 || 档 === null || 资料模式;
  const 内容 = 资料模式 ? 从展示资料归一(资料 ?? null, 求职状态) : 从匿名档归一(档, 求职状态, 薪资结论);

  return (
    <div className={样式.页体}>
      {/* 区块级缺口说明（详情由连接层给，如「当前在谈详情数据未提供」）；旧版式不渲染 */}
      {缺区保留标题 && 缺失说明 !== null ? <p className={样式.缺口说明}>{缺失说明}</p> : null}

      {/* ── 头区：与列表卡同一套头行（性别图标 + 年限｜学历｜状态）+ 职位行。
          2026-09-09 产品负责人（第二批）：原 大代号（已披露 ? 真名 : 代号）与灰人像占位整体删除 ——
          9/8 定稿「卡面不显示真名」，头区同理；真名事实只剩下面的公司实名还原与页尾注在用。
          Mock 年限取简历档 经验（「9 年经验」→「9 年」）；资料模式由映射按摘要年限给「N 年」。 ── */}
      <div className={样式.头区}>
        {内容 !== null && 内容.头区 !== null ? (
          <>
            <候选头行
              性别={内容.头区.性别 ?? undefined}
              年限={内容.头区.年限}
              学历={内容.头区.学历}
              求职状态={内容.头区.求职状态}
            />
            {内容.头区.职位行 !== null
              ? <div className={样式.职位行}>{内容.头区.职位行}</div>
              : <p className={样式.区块缺失}>职位信息缺失</p>}
          </>
        ) : (
          <>
            <p className={样式.区块缺失}>匿名画像缺失</p>
            <p className={样式.区块缺失}>职位信息缺失</p>
          </>
        )}
      </div>

      {/* 概览条(经验/学历/年龄)已删(用户 2026-09-01):经验与学历在匹配度分析里有证据行,不重复 */}

      {/* ── 匹配度分析(2026-08-26 定稿对齐表,两端同构):岗位硬性条件原文 ×
          候选简历原文,与求职端职位详情同一个共用卡。原「AI代理读完简历后的判断」
          散文卡随之退役——判断类小文案整类淘汰,证据自己说话。
          藏环:返回栏已带「匹配 N」,同屏不出现两个分数(2026-08-24 既定口径)
          完整布局:缺分或缺行时标题与位置保留,显示缺失 —— 不伪造 0 分/空行喂给卡；
          资料模式没有可依据的适配分，整区不生成（无证据不生成行）── */}
      {内容 !== null && 内容.适配分 !== null && 对齐行们 !== null && 对齐行们.length > 0 ? (
        <div className={样式.对齐卡容器}>
          <匹配对齐卡 分={内容.适配分} 行们={对齐行们} 藏环 />
        </div>
      ) : 缺区保留标题 && (内容 === null || 内容.适配分 !== null) ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>匹配度分析</span>
          </div>
          <p className={样式.区块缺失}>匹配分析缺失</p>
        </>
      ) : null}

      {/* ── 个人优势段（2026-08-21：与注册采集页「分享一下自己的个人优势」统一命名）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>个人优势</span>
      </div>
      {内容 !== null && 内容.自述 !== null ? (
        <p className={样式.自述}>{内容.自述}</p>
      ) : (
        <p className={样式.区块缺失}>个人优势缺失</p>
      )}

      {/* ── 求职期望：无薪资结论（资料 unknown / 缺源）时不渲染 薪资槽，一致性条只在
          Mock 旧档有 —— 不拿岗位薪资代填候选期望，也不给「已进入初筛/一致」这类
          无依据承诺（spec §3.4 / Task 5：unknown 不作结论）── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>求职期望</span>
      </div>
      {内容 !== null && 内容.期望 !== null ? (
        <>
          <div className={样式.期望标题行}>
            {内容.期望.标题 !== null ? <span className={样式.期望标题}>{内容.期望.标题}</span> : null}
            {内容.期望.薪资结论 !== null ? <span className={样式.期望薪资}>{内容.期望.薪资结论}</span> : null}
          </div>
          {内容.期望.带宽行 !== null || 内容.期望.偏好 !== null ? (
            <div className={样式.期望副行}>
              {内容.期望.带宽行}
              {内容.期望.偏好 ? <span className={样式.期望偏好}>{内容.期望.偏好}</span> : null}
            </div>
          ) : null}
          {内容.期望.一致性 !== null ? (
            <div className={样式.一致条}>
              <span className={样式.一致符} aria-hidden>✓</span>
              <span>{内容.期望.一致性}</span>
            </div>
          ) : null}
        </>
      ) : (
        <p className={样式.区块缺失}>求职期望缺失</p>
      )}

      {/* ── 工作经历：每段可带 AI 逐段批注绿条；真名非空（S1）时还原公司实名 ——
          只对 Mock 档生效，资料槽不承载实名恢复字段 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>工作经历</span>
      </div>
      {内容 === null || 内容.经历 === null ? (
        <p className={样式.区块缺失}>工作经历缺失</p>
      ) : 内容.经历.length > 0 ? (
        内容.经历.map((段, 序) => (
          <div key={`${序}-${段.起止}-${段.公司 ?? ''}`} className={样式.经历段}>
            <div className={样式.经历头}>
              <span className={`${样式.经历公司} 单行`}>
                {已披露 && 段.公司实名 ? 段.公司实名 : 段.公司}
              </span>
              {段.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{段.起止}</span> : null}
            </div>
            {段.职位 !== null ? <div className={样式.经历职位}>{段.职位}</div> : null}
            {段.说明 !== null ? (
              <div className={样式.经历说明}>
                {段.说明.split('\n').map((行) => (
                  <div key={行} className={样式.说明行}>
                    {行}
                  </div>
                ))}
              </div>
            ) : null}
            {段.批注 ? (
              <div className={样式.一致条}>
                <span className={样式.一致符} aria-hidden>✓</span>
                <span>{段.批注}</span>
              </div>
            ) : null}
          </div>
        ))
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无工作经历</p>
      ) : null}

      {/* ── 项目经历：空也保留标题与空状态 —— 但只由完整布局开关控制（Mock 旧版式整区不出；
          资料模式缺失/空状态照常出）── */}
      {内容 === null || 内容.项目 === null || 缺区保留标题 || 内容.项目.length > 0 ? (
        <>
          <div className={样式.节标行}>
            <span className={样式.节标}>项目经历</span>
          </div>
          {内容 === null || 内容.项目 === null ? (
            <p className={样式.区块缺失}>项目经历缺失</p>
          ) : 内容.项目.length > 0 ? (
            内容.项目.map((项, 序) => (
              <div key={`${序}-${项.名称 ?? ''}`} className={样式.经历段}>
                <div className={样式.经历头}>
                  <span className={`${样式.经历公司} 单行`}>{项.名称}</span>
                  {项.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{项.起止}</span> : null}
                </div>
                {项.角色 !== null ? <div className={样式.经历职位}>{项.角色}</div> : null}
                {项.说明 !== null ? <div className={样式.经历说明}>{项.说明}</div> : null}
                {项.批注 ? (
                  <div className={样式.一致条}>
                    <span className={样式.一致符} aria-hidden>✓</span>
                    <span>{项.批注}</span>
                  </div>
                ) : null}
              </div>
            ))
          ) : (
            <p className={样式.区块缺失}>暂无项目经历</p>
          )}
        </>
      ) : null}

      {/* ── 教育经历：直接显示具体学校（用户定：学校不脱敏，onboarding 配置）；
          Task 5 起适配为多条，逐条复用既有教育条目样式 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>教育经历</span>
      </div>
      {内容 === null || 内容.教育 === null ? (
        <p className={样式.区块缺失}>教育经历缺失</p>
      ) : 内容.教育.length > 0 ? (
        内容.教育.map((条, 序) => (
          // key 用源位置组合：同校同起止的多条不因值重复而丢条
          <div key={`${序}-${条.行}`} className={样式.教育行}>
            <span className={样式.教育文}>{条.行}</span>
            {条.起止 !== null ? <span className={`${样式.经历起止} 等宽数字`}>{条.起止}</span> : null}
          </div>
        ))
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无教育经历</p>
      ) : null}

      {/* ── 专业技能 ── */}
      <div className={样式.节标行}>
        <span className={样式.节标}>专业技能</span>
      </div>
      {内容 === null || 内容.技能 === null ? (
        <p className={样式.区块缺失}>专业技能缺失</p>
      ) : 内容.技能.length > 0 ? (
        <div className={样式.技能行}>
          {内容.技能.map((技, 序) => (
            <span key={`${序}-${技}`} className={样式.技能片}>
              {技}
            </span>
          ))}
        </div>
      ) : 缺区保留标题 ? (
        <p className={样式.区块缺失}>暂无专业技能</p>
      ) : null}

      {/* ── 披露/沟通状态说明：只消费 已确认/已披露 事实；档缺失时不沿用「内容真实性经
          双向核验」—— 没有正文就核验不了，只保留真实成立的不可转发政策。资料模式
          也没有后端核验证据：页尾注只说来源与不可转发，不宣称已核验，
          更不把资料缺失说成「未披露」。 ── */}
      <div className={样式.页尾注}>
        {内容 === null
          ? '在线简历缺失 · 内容不可转发'
          : 已确认
            ? '双方已确认意向，可进入真人沟通 · 内容不可转发'
            : 已披露
              ? '候选人身份已随 S1 原件披露 · 意向确认后进入真人沟通 · 内容不可转发'
              : 资料模式
                ? '这份简历由候选人的AI代理生成 · 内容不可转发'
                : '这份简历由候选人的AI代理生成 · 内容真实性经双向核验 · 不可转发'}
      </div>
    </div>
  );
}