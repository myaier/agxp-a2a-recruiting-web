// 不可逆动作的二次确认层。
//
// 这不是一种新弹层：结构、类名、动画与 屏蔽名单（解除屏蔽）、岗位详情（关闭职位）、
// 发布岗位（删除岗位）那三处手写的确认框逐条一致，样式规则从 我的功能页.module.css
// 的确认框那一段原样搬到本组件的 .module.css。
//
// 抽成组件的理由：候选详情 / 在谈详情 也要同一套确认，而这两屏的 module.css 里没有
// 这组类；就地再抄一遍会变成第四、第五份各自漂移的确认框。
//
// 正文由调用方给：这一层不生成任何解释文案，只负责摆放。

import 样式 from './确认层.module.css';
import 弹层框架 from './弹层框架';

export default function 确认层({
  标题,
  正文,
  执行文,
  执行,
  取消,
  取消文 = '取消',
}: {
  /** 「动词「主体名」？」——与既有三处确认框同一口径 */
  标题: string;
  /** 后果说明。调用方传项目里已有的口径，不在这里编 */
  正文: string;
  /** 右侧执行键的文字，用触发它的那个动作本身的词 */
  执行文: string;
  执行: () => void;
  取消: () => void;
  取消文?: string;
}) {
  return (
    <弹层框架
      标签={标题}
      遮罩类名={样式.遮罩}
      面板类名={样式.确认框}
      位置="居中"
      关闭={取消}
    >
      <div className={样式.确认标题}>{标题}</div>
      <div className={样式.确认正文}>{正文}</div>
      <div className={样式.确认键行}>
        <button type="button" className={`${样式.确认取消} 可点`} onClick={取消}>
          {取消文}
        </button>
        <button type="button" className={`${样式.确认执行} 可点`} onClick={执行}>
          {执行文}
        </button>
      </div>
    </弹层框架>
  );
}
