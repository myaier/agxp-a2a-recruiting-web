// 候选头行 —— 招聘端「去名改版」的统一头行：性别裸符号 + 年限｜学历｜求职状态。
//
// 2026-09-08 产品负责人定稿：招聘端卡面全匿名，名字 / 代号对招聘方决策价值为零，
// 列表卡（企业在谈候选 / 候选推荐）的头行就是这一套。
// 2026-09-09 产品负责人（第二批）：候选详情顶栏与匿名在线简历头区也换成同一套头行，
// 「招聘端的用户都已经是匿名了，左上角的名字也应该删掉」—— 本组件把这套头行收成一个出处，
// 详情页 / 简历页跟列表卡说同一种话；列表卡自身的写法不动（那里的类名被既有测试锚定）。
//
// 三段都是可缺省的：BFF 合同没给性别就不出图标、缺哪段就不渲染哪段（不猜、不补）。

import { 性别图标 } from './图标';
import 样式 from './候选头行.module.css';

/** 头行三段名：列表卡用 未知段们 点名哪段是占位（Spec §6 次要色） */
export type 头行段名 = '年限' | '学历' | '求职状态';

interface 候选头行属性 {
  性别?: '男' | '女';
  /** 年限，如「9 年」（画像首段 / 简历档 经验 去掉「经验」后缀） */
  年限?: string | null;
  学历?: string | null;
  /** 求职状态只取 在找「·」后半段这类文案，如「在职看机会」 */
  求职状态?: string | null;
  /** 调用方附加的类名（如返回栏标题位需要更紧的字号时） */
  类名?: string;
  /** 列表卡未知占位（Spec §4.3）：数据没给性别时在原图标位出 16px 灰色 ?，
   *  可访问名与 title 均为「性别未知」。默认 false —— 详情/匿名简历等既有消费者仍是
   *  「没给性别就不渲染」，默认行为一字不变。 */
  未知性别占位?: boolean;
  /** 列表卡未知段（Spec §6）：点名哪些段的文案是占位，渲染时给现有次要文字色，不与真实
   *  数据同色。默认不传 —— 详情/匿名简历零差异；占位文案仍由调用方预格式化传入，
   *  本组件只管上色，不猜哪段是占位。 */
  未知段们?: readonly 头行段名[];
}

/** 画像「年限 · 方向 · 现职」拆成 首段年限 与 其余（详情页副标题 = 画像去掉年限段） */
export function 拆画像(画像: string): { 年限: string; 其余: string } {
  const [年限 = '', ...其余] = 画像.split(' · ');
  return { 年限, 其余: 其余.join(' · ') };
}

export default function 候选头行({
  性别, 年限, 学历, 求职状态, 类名, 未知性别占位 = false, 未知段们,
}: 候选头行属性) {
  // 三段带段名进头行：缺哪段就不渲染哪段（不猜、不补），分隔竖线只出现在两段之间；
  // 段名留给 未知段们 对号上色，渲染出来的文本与结构不变
  const 候选段们: { 名: 头行段名; 文: string | null | undefined }[] = [
    { 名: '年限', 文: 年限 },
    { 名: '学历', 文: 学历 },
    { 名: '求职状态', 文: 求职状态 },
  ];
  const 段们 = 候选段们.filter((段): 段 is { 名: 头行段名; 文: string } => !!段.文 && 段.文.trim() !== '');
  return (
    <div className={`${样式.头行}${类名 ? ` ${类名}` : ''}`}>
      {性别 ? (
        <span className={样式.性别符}>
          <性别图标 性别={性别} />
        </span>
      ) : 未知性别占位 ? (
        // 未知占位：不造男女图标，16×16 灰色 ?，读屏与 title 都说「性别未知」
        <span className={样式.性别符} role="img" aria-label="性别未知" title="性别未知">
          <span className={样式.未知性别}>?</span>
        </span>
      ) : null}
      {段们.map(({ 名, 文 }, 序) => (
        <span key={`${序}-${文}`} className={未知段们?.includes(名) ? 样式.未知段 : undefined}>
          {序 > 0 ? <span className={样式.竖分}>｜</span> : null}
          {文}
        </span>
      ))}
    </div>
  );
}
