// 简历预览层 —— 简历内容的三种呈现（标注意见 2026-08-18 23:51；P0 契约校准 2026-08-25）：
//
//   · 简历纸身（具名导出，可复用）：简历正文本体，三个分支 ——
//       脱敏（默认）：代号替真名、联系方式打码、公司写「同赛道公司」—— S0 匿名初筛版；
//       原件（原件 prop，无候选原件）：真名、真实联系方式、公司实名 —— 求职者自己的原件，
//                    继续读取求职端全局简历切片（用户在工作经历页改完这里跟着变）；
//       候选原件（候选原件 prop）：招聘方打开 S1 附件看到的该候选人自己的 PDF 原件投影，
//                    抬头姓名 / 手机 / 邮箱 / 经验 / 履历 / 教育都取自候选专属投影，
//                    不再跟随求职端全局简历编辑，也不能把所有候选都渲染成沈亦舟。
//   · 简历原件层（默认导出）：点阶段节点里的 PDF 附件行打开的弹层，
//       观感是一份 PDF 文档：顶部文件名 + PDF 徽标，正文一张白纸。
//       传候选原件 = 招聘方看候选原件；传匿名代号 = S0 候选打码版；都不传 = 求职者自己的原件。
//
// 硬规则（用户 2026-08-18 反复强调）：界面上不加任何解释性小文案 ——
// 弹层只有文件名和简历数据本身，折叠卡只有「在线简历」四个字。

import 样式 from './简历预览层.module.css';
import 弹层框架 from './弹层框架';
import { 简历联系方式 } from '../数据/模拟数据';
import type { 候选简历原件投影 } from '../数据/企业端模拟数据';
import { use应用状态 } from '../状态/应用状态';

/**
 * 简历纸身 —— 简历正文本体，不带滚动容器：
 * 弹层把它包进 PDF 白纸，在谈详情把它内联铺进「在线简历」折叠卡。
 */
export function 简历纸身({
  原件 = false,
  代号 = '',
  候选原件,
}: {
  /** true = 简历原件：真名、真实联系方式、公司实名（求职者自己的原件或候选原件投影） */
  原件?: boolean;
  /** 脱敏视图下的对外化名，如 陈屿 */
  代号?: string;
  /** 招聘方视角的候选专属原件投影；存在时抬头与履历取投影，不再读求职端全局简历 */
  候选原件?: 候选简历原件投影;
}) {
  // 读全局：用户在注册最后一题写的那段（2026-08-21 修断链）
  // 经历/教育读全局简历切片：用户在工作经历页改完，这里立刻跟着变；真名读基本信息。
  // 候选原件分支不消费这些全局字段（投影自带姓名 / 联系方式 / 履历）。
  const { 状态: 全局 } = use应用状态();
  const 优势条目 = (候选原件 ? 候选原件.个人优势 : 全局.个人优势)
    .split('\n')
    .filter((行) => 行.trim() !== '');
  const 经历列表 = 全局.简历经历;
  const 教育列表 = 全局.简历教育;
  const 显示年月 = (值: string | null) => (值 ? 值.replace('-', '.') : '至今');

  // 抬头姓名 / 联系方式 / 首段职位 / 经验：候选原件分支取投影，其余分支沿用既有规则
  const 抬头姓名 = 候选原件 ? 候选原件.真名 : 原件 ? 全局.基本信息.真名 : 代号;
  const 首段职位 = 候选原件
    ? (候选原件.经历[0]?.职位 ?? '')
    : (经历列表[0]?.职位 ?? '');
  const 经验文 = 候选原件 ? 候选原件.经验 : '9 年经验';
  const 手机 = 候选原件 ? 候选原件.手机 : 简历联系方式.手机;
  const 邮箱 = 候选原件 ? 候选原件.邮箱 : 简历联系方式.邮箱;

  return (
    <>
      {/* 抬头：原件/候选原件给真名与真实联系方式；脱敏版代号替真名、联系方式只露首尾 */}
      <div className={样式.抬头}>
        <div className={样式.姓名}>{抬头姓名}</div>
        <div className={样式.抬头职位}>
          {首段职位.split(' · ')[0]} · {经验文}
        </div>
        <div className={样式.联系行}>
          {原件 || 候选原件 ? (
            <>
              <span className={样式.联系项}>手机：{手机}</span>
              <span className={样式.联系项}>邮箱：{邮箱}</span>
            </>
          ) : (
            <>
              <span className={样式.联系项}>手机：138****6021</span>
              <span className={样式.联系项}>邮箱：s***@***.com</span>
            </>
          )}
        </div>
      </div>

      {/* 工作经历：候选原件取投影经历（公司实名、起止整串、无行业行）；脱敏版写「同赛道公司」 */}
      <div className={样式.节标}>工作经历</div>
      {候选原件
        ? 候选原件.经历.map((段, 序) => (
            <div key={序} className={样式.经历段}>
              <div className={样式.经历头}>
                <span className={样式.经历公司}>{段.公司}</span>
                <span className={样式.经历时间}>{段.起止}</span>
              </div>
              <div className={样式.经历职位}>{段.职位}</div>
              {段.说明 ? (
                <div className={样式.经历内容}>
                  {段.说明.split('\n').map((行) => (
                    <div key={行} className={样式.内容行}>
                      {行}
                    </div>
                  ))}
                </div>
              ) : null}
            </div>
          ))
        : 经历列表.map((条) => (
            <div key={条.编号} className={样式.经历段}>
              <div className={样式.经历头}>
                <span className={样式.经历公司}>{原件 ? 条.公司 : '同赛道公司'}</span>
                <span className={样式.经历时间}>
                  {显示年月(条.开始)} — {显示年月(条.结束)}
                </span>
              </div>
              <div className={样式.经历职位}>{条.职位}</div>
              {条.行业 ? <div className={样式.经历行业}>{条.行业}</div> : null}
              {条.内容 ? (
                <div className={样式.经历内容}>
                  {条.内容.split('\n').map((行) => (
                    <div key={行} className={样式.内容行}>
                      {行}
                    </div>
                  ))}
                </div>
              ) : null}
            </div>
          ))}

      {/* 教育经历：候选原件把教育行第一个「 · 」前放学校槽、剩余放学历/专业槽；学校两版都实名 */}
      <div className={样式.节标}>教育经历</div>
      {候选原件 ? (
        (() => {
          const 分点 = 候选原件.教育行.indexOf(' · ');
          const 学校 = 分点 >= 0 ? 候选原件.教育行.slice(0, 分点) : 候选原件.教育行;
          const 学历专业 = 分点 >= 0 ? 候选原件.教育行.slice(分点 + 3) : '';
          return (
            <div key={0} className={样式.经历段}>
              <div className={样式.经历头}>
                <span className={样式.经历公司}>{学校}</span>
                <span className={样式.经历时间}>{候选原件.教育起止}</span>
              </div>
              <div className={样式.经历职位}>{学历专业}</div>
            </div>
          );
        })()
      ) : (
        教育列表.map((条) => (
          <div key={条.编号} className={样式.经历段}>
            <div className={样式.经历头}>
              <span className={样式.经历公司}>{条.学校}</span>
              <span className={样式.经历时间}>
                {显示年月(条.开始)} — {显示年月(条.结束)}
              </span>
            </div>
            <div className={样式.经历职位}>
              {条.学历} · {条.专业}
            </div>
          </div>
        ))
      )}

      {/* 个人优势 */}
      <div className={样式.节标}>个人优势</div>
      <ul className={样式.优势列}>
        {优势条目.map((行) => (
          <li key={行} className={样式.优势项}>
            {行.replace(/；$/, '')}
          </li>
        ))}
      </ul>

      {/* 薪资位置：双盲机制的产物，只存在于脱敏版；原件 / 候选原件是正式文档，没有这一节 */}
      {原件 || 候选原件 ? null : (
        <>
          <div className={样式.节标}>薪资与到岗</div>
          <div className={样式.薪资框}>
            <div className={样式.薪资行}>
              <span className={样式.薪资标}>现金期望</span>
              <span className={样式.薪资值}>落在贵方区间内 ✓</span>
            </div>
            <div className={样式.薪资行}>
              <span className={样式.薪资标}>到岗时间</span>
              <span className={样式.薪资值}>45 天内</span>
            </div>
          </div>
        </>
      )}
    </>
  );
}

/** 简历原件弹层：PDF 文档观感 —— 顶栏文件名 + PDF 徽标，正文一张白纸 */
export default function 简历原件层({
  文件名,
  匿名代号,
  候选原件,
  关闭,
}: {
  文件名: string;
  /** 传了 = S0 对方视角（未递交原件）：化名 + 打码，不是原件 */
  匿名代号?: string;
  /** 招聘方视角的候选专属原件投影；存在时铺候选原件，不再读求职端全局简历 */
  候选原件?: 候选简历原件投影;
  关闭: () => void;
}) {
  return (
    <弹层框架 标签="简历原件" 遮罩类名={样式.遮罩} 面板类名={样式.层} 关闭={关闭}>
        {/* 顶栏：只有 PDF 徽标 + 文件名 + 关闭，没有任何说明文字（用户硬规则）*/}
        <div className={样式.顶栏}>
          <span className={样式.抓手} />
          <div className={样式.顶栏行}>
            <span className={样式.PDF徽标}>
              <span className={样式.PDF徽标字}>PDF</span>
            </span>
            <span className={`${样式.文件名} 单行`}>{文件名}</span>
            <button className={`${样式.关闭键} 可点`} onClick={关闭} aria-label="关闭">
              ✕
            </button>
          </div>
        </div>

        {/* 灰底上浮一张白纸，模拟 PDF 阅读器里的一页 */}
        <div className={`${样式.纸底} 滚动区`}>
          {/* .文档 = 真实 PDF 文档排版（标注 2026-08-19 17:58）：宋体黑字、节标横线、两端对齐 */}
          <div className={`${样式.白纸} ${样式.文档}`}>
            {候选原件 ? (
              <简历纸身 候选原件={候选原件} 原件 代号={匿名代号 ?? ''} />
            ) : 匿名代号 ? (
              <简历纸身 代号={匿名代号} />
            ) : (
              <简历纸身 原件 />
            )}
          </div>
        </div>
    </弹层框架>
  );
}
