// 在谈筛选层（用户 2026-08-21：筛选入口两个子视图要一致，过滤项收进面板里）。
//
// 与「看市场 / 推荐」的筛选面板是两回事：那边改的是代理的硬性要求（写成规则、长期生效），
// 这边只决定「现在先看哪几单」——纯视图态，关掉面板就只影响这一屏的列表。
// 两端共用：求职端在谈、企业端在谈候选。
//
// 面板现在有两组档位（2026-08-22 拦路 5 / 6）：
//   · 看哪几单 —— 全部 / 待我拍板 / 进行中（老的那组，没动）
//   · 范围组   —— 当前意向 or 当前岗位 / 全部。可选，调用方不传就只显示上面那组。
// 跨意向、跨岗位总览没有另起一套筛选，就是给这套档位加一组，两端仍然只有一个筛选入口。

import 样式 from './在谈筛选层.module.css';
import 弹层框架 from './弹层框架';
import type { 看什么档, 在谈范围档 } from '../状态/应用状态';

export type { 看什么档, 在谈范围档 };

/** 范围组的配置：档名两端不同（意向 / 岗位），所以由调用方给名字，面板只管排版 */
export interface 范围组配置 {
  /** 组标题，与「看哪几单」同级，如「看哪些意向」/「看哪些岗位」 */
  标题: string;
  /** 「当前」档的档名，如「当前意向」/「当前岗位」 */
  当前档名: string;
  /** 「全部」档的档名，如「全部意向」/「全部岗位」 */
  全部档名: string;
  当前: 在谈范围档;
  设当前: (档: 在谈范围档) => void;
  /** 全部范围下待你拍板的条数，标在「全部」档右侧 —— 与「待我拍板」档右侧的数字同一口径，
      不点开也知道别的意向 / 别的岗位下还压着几件事 */
  全部待办数: number;
}

export default function 在谈筛选层({
  当前,
  设当前,
  待办数,
  范围组,
  关闭,
}: {
  当前: 看什么档;
  设当前: (档: 看什么档) => void;
  /** 待你拍板的条数，标在对应档右侧 */
  待办数: number;
  范围组?: 范围组配置;
  关闭: () => void;
}) {
  return (
    <弹层框架 标签="筛选在谈项目" 遮罩类名={样式.遮罩} 面板类名={样式.层} 关闭={关闭}>
      <span className={样式.抓手} aria-hidden="true" />
      <div className={样式.标题}>看哪几单</div>

      <div className={样式.选项组}>
        {(['全部', '待我拍板', '进行中'] as 看什么档[]).map((档) => (
          <button
            key={档}
            className={`${样式.选项} ${当前 === 档 ? 样式.选项选中 : ''} 可点`}
            onClick={() => 设当前(档)}
          >
            <span className={样式.选项名}>{档}</span>
            {档 === '待我拍板' && 待办数 > 0 ? (
              <span className={`${样式.选项数} 等宽数字`}>{待办数}</span>
            ) : null}
            {当前 === 档 ? <span className={样式.选项勾}>✓</span> : null}
          </button>
        ))}
      </div>

      {范围组 ? (
        <>
          <div className={样式.标题}>{范围组.标题}</div>
          <div className={样式.选项组}>
            {(['当前', '全部'] as 在谈范围档[]).map((档) => (
              <button
                key={档}
                className={`${样式.选项} ${范围组.当前 === 档 ? 样式.选项选中 : ''} 可点`}
                onClick={() => 范围组.设当前(档)}
              >
                <span className={样式.选项名}>
                  {档 === '当前' ? 范围组.当前档名 : 范围组.全部档名}
                </span>
                {档 === '全部' && 范围组.全部待办数 > 0 ? (
                  <span className={`${样式.选项数} 等宽数字`}>{范围组.全部待办数}</span>
                ) : null}
                {范围组.当前 === 档 ? <span className={样式.选项勾}>✓</span> : null}
              </button>
            ))}
          </div>
        </>
      ) : null}

      <button className={`${样式.完成} 可点`} onClick={关闭}>
        完成
      </button>
    </弹层框架>
  );
}
