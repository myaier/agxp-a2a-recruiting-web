/**
 * 生成一个不与现有规则撞号的编号。
 * 不能直接用「条数 + 偏移」：筛选层里可以删规则，删一条再加一条就会撞上还活着的号，
 * 撞号会让 React 列表里出现两个相同 key、编辑其中一条时另一条跟着变。
 */
function 造规则编号(已有: 规则[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`R-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `R-${String(序).padStart(2, '0')}`;
}

/**
 * 未读表播种：把模拟数据里静态写死的 未读数 / 红点 收进全局状态，之后只认这张表。
 * 值 = 未读条数；只标了红点、没给条数的那种存 0（渲染成红点，不是数字徽标）。
 * 模拟数据里的 未读数 / 红点 从此只当种子用，屏上一律不再直接读它们 ——
 * 两个数据源同时存在，就会出现「表里已清、卡上还红」的对不上。
 */
function 播种未读表(消息表: 消息条目[]): Record<string, number> {
  const 表: Record<string, number> = {};
  for (const 条 of 消息表) {
    if (条.未读数 !== undefined && 条.未读数 > 0) 表[条.编号] = 条.未读数;
    else if (条.红点) 表[条.编号] = 0;
  }
  return 表;
}

/**
 * 未读总数 —— 底部导航角标用。
 * 只画红点、不计条数的会话按 1 条计入：它在表里的值是 0，直接求和会让它在角标上等于不存在，
 * 而它恰恰就是「有新消息」这件事本身。
 */
export function 数未读(表: Record<string, number>): number {
  return Object.values(表).reduce((和, 数) => 和 + (数 > 0 ? 数 : 1), 0);
}

