      if (!该岗) return 旧;
      if (旧.企业候选列表.some((候) => 候.岗位编号 === 动作.编号)) return 旧;
      const 新列表 = 旧.岗位列表.filter((岗) => 岗.编号 !== 动作.编号);
      return { ...旧, 岗位列表: 新列表, 当前岗位编号: 选新当前岗(新列表, 旧.当前岗位编号) };
