// 全局业务状态（方案第 3 节：业务状态归 Web 层）。
// 原型里跨屏联动都走这里，所以「在详情页接受方案」会让首页那张卡跟着变，
// 「记成规则」会真的出现在规则库里 —— 这是原型能被当真评审的前提。

import { createContext, useContext, useMemo, useReducer, type ReactNode } from 'react';
import { 在谈列表 as 初始在谈, 全局规则, 意向级规则, 意向切换 } from '../数据/模拟数据';
import { 在谈候选列表 as 初始候选, 企业规则列表, 在招岗位列表 } from '../数据/企业端模拟数据';
import type { 分歧, 在谈单, 候选, 在招岗位, 规则 } from '../数据/类型';

type 子视图 = '在谈' | '看市场';
type 底部Tab = '职位' | '消息' | '我的';

interface 状态 {
  当前意向: string;
  子视图: 子视图;
  当前Tab: 底部Tab;
  在谈列表: 在谈单[];
  /** 已作出的决策：编号 → 接受 / 退出 */
  决策: Record<string, '接受' | '退出'>;
  /** 决策时的分歧快照：接受方案会清掉 单.分歧（首页卡片不再显示分歧轴），
      但详情页回看时仍要展示当时的数字对比，所以在这里留档 */
  决策快照: Record<string, 分歧>;
  全局规则: 规则[];
  意向级规则: 规则[];
  /** 在看市场里已委托代理去谈的岗位编号 */
  已委托: string[];

  // ── 企业端（招人方）切片：与求职端同构 ──
  企业候选列表: 候选[];
  候选决策: Record<string, '接受' | '终止'>;
  候选决策快照: Record<string, 分歧>;
  企业规则: 规则[];
  岗位列表: 在招岗位[];
  当前岗位编号: string;
  企业子视图: '在谈' | '推荐';
  企业Tab: '人才' | '消息' | '我的';
  /** 已委托代理去聊的推荐候选编号 */
  已接触推荐: string[];
}

type 动作 =
  | { 型: '切意向'; 意向: string }
  | { 型: '切子视图'; 子视图: 子视图 }
  | { 型: '切Tab'; Tab: 底部Tab }
  | { 型: '接受方案'; 编号: string }
  | { 型: '退出谈判'; 编号: string }
  | { 型: '确认意向'; 编号: string }
  | { 型: '新增规则'; 内容: string; 来源: string }
  | { 型: '切规则开关'; 编号: string }
  | { 型: '委托代理'; 编号: string }
  // ── 企业端动作 ──
  | { 型: '企业切Tab'; Tab: '人才' | '消息' | '我的' }
  | { 型: '企业切子视图'; 子视图: '在谈' | '推荐' }
  | { 型: '切当前岗位'; 编号: string }
  | { 型: '候选接受方案'; 编号: string }
  | { 型: '候选终止'; 编号: string }
  | { 型: '候选确认意向'; 编号: string }
  | { 型: '企业新增规则'; 内容: string; 来源: string }
  | { 型: '企业切规则开关'; 编号: string }
  | { 型: '接触推荐候选'; 编号: string };

const 初始状态: 状态 = {
  当前意向: 意向切换[0],
  子视图: '在谈',
  当前Tab: '职位',
  在谈列表: 初始在谈,
  决策: {},
  决策快照: {},
  全局规则,
  意向级规则,
  已委托: [],
  企业候选列表: 初始候选,
  候选决策: {},
  候选决策快照: {},
  企业规则: 企业规则列表,
  岗位列表: 在招岗位列表,
  当前岗位编号: 在招岗位列表[0].编号,
  企业子视图: '在谈',
  企业Tab: '人才',
  已接触推荐: [],
};

function 归约(旧: 状态, 动作: 动作): 状态 {
  switch (动作.型) {
    case '切意向':
      return { ...旧, 当前意向: 动作.意向 };
    case '切子视图':
      return { ...旧, 子视图: 动作.子视图 };
    case '切Tab':
      return { ...旧, 当前Tab: 动作.Tab };

    // 接受协调方案 → 该单推进到「意向确认」，不再需要你
    case '接受方案': {
      const 该单 = 旧.在谈列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '接受' },
        // 分歧数据留档：详情页回看时还能展示当时的数字对比
        决策快照: 该单?.分歧 ? { ...旧.决策快照, [动作.编号]: 该单.分歧 } : 旧.决策快照,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                需要你: true,
                下一步: '条件已放宽并回报对方，等双方确认意向',
                辅助文案: '确认后转真人沟通',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 退出 → 该单从在谈列表移除（归档）
    case '退出谈判':
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '退出' },
        在谈列表: 旧.在谈列表.filter((条) => 条.编号 !== 动作.编号),
      };

    // 确认意向 → 转真人沟通，卡片不再等你
    case '确认意向':
      return {
        ...旧,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                下一步: '已确认意向，联系方式已互换',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    // 叮嘱沉淀成规则
    case '新增规则': {
      const 新编号 = `R-${String(旧.全局规则.length + 旧.意向级规则.length + 8).padStart(2, '0')}`;
      return {
        ...旧,
        全局规则: [...旧.全局规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }

    case '切规则开关':
      return {
        ...旧,
        全局规则: 旧.全局规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
        意向级规则: 旧.意向级规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };

    case '委托代理':
      return 旧.已委托.includes(动作.编号)
        ? 旧
        : { ...旧, 已委托: [...旧.已委托, 动作.编号] };

    // ── 企业端动作：与求职端同构的镜像逻辑 ──
    case '企业切Tab':
      return { ...旧, 企业Tab: 动作.Tab };
    case '企业切子视图':
      return { ...旧, 企业子视图: 动作.子视图 };
    case '切当前岗位':
      return { ...旧, 当前岗位编号: 动作.编号 };

    // 接受代理方案 → 该候选推进到「意向确认」（等对方点头）
    case '候选接受方案': {
      const 该候选 = 旧.企业候选列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '接受' },
        候选决策快照: 该候选?.分歧
          ? { ...旧.候选决策快照, [动作.编号]: 该候选.分歧 }
          : 旧.候选决策快照,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                // 镜像求职端语义：接受方案后进入意向确认，先等你（企业）正式确认，
                // 所以卡片保持红描边置顶；「候选确认意向」时才置 false
                需要你: true,
                下一步: '条件已一致，等你确认意向',
                辅助文案: '确认后等候选人点头，双方齐了互换联系方式',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 终止 → 从在谈候选里移除（归档）
    case '候选终止':
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '终止' },
        企业候选列表: 旧.企业候选列表.filter((条) => 条.编号 !== 动作.编号),
      };

    // 双方意向确认 → 互换姓名（A-01 即求职端主角沈亦舟，剧情闭环）
    case '候选确认意向':
      return {
        ...旧,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                真名: 条.编号 === 'A-01' ? '沈亦舟' : 条.真名,
                下一步: '双方已确认，联系方式已互换',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    case '企业新增规则': {
      const 新编号 = `R-${String(旧.企业规则.length + 6).padStart(2, '0')}`;
      return {
        ...旧,
        企业规则: [...旧.企业规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }

    case '企业切规则开关':
      return {
        ...旧,
        企业规则: 旧.企业规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };

    case '接触推荐候选':
      return 旧.已接触推荐.includes(动作.编号)
        ? 旧
        : { ...旧, 已接触推荐: [...旧.已接触推荐, 动作.编号] };

    default:
      return 旧;
  }
}

const 上下文 = createContext<{ 状态: 状态; 派发: (动作: 动作) => void } | null>(null);

export function 应用状态提供者({ children }: { children: ReactNode }) {
  const [状态, 派发] = useReducer(归约, 初始状态);
  const 值 = useMemo(() => ({ 状态, 派发 }), [状态]);
  return <上下文.Provider value={值}>{children}</上下文.Provider>;
}

export function use应用状态() {
  const 值 = useContext(上下文);
  if (!值) throw new Error('use应用状态 必须在 应用状态提供者 内部使用');
  return 值;
}
