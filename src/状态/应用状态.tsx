/**
 * 生成一个不与现有规则撞号的编号。
 * 不能直接用「条数 + 偏移」：筛选层里可以删规则，删一条再加一条就会撞上还活着的号，
 * 撞号会让 React 列表里出现两个相同 key、编辑其中一条时另一条跟着变。
 */
function 造规则编号(已有: 规则[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`R-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `R-${String(序).padStart(2, '0')}`;
}

/**
 * 生成一个不与现有求职意向撞号的编号 —— 与 造规则编号 同一套口径。
 * 原来直接用「条数 + 1」：删掉 I-01 之后表长回到 1，再新增算出来还是 I-02，
 * 与幸存的那条 I-02 撞号。顶栏意向胶囊和意向管理列表都用 编号 当 React key，
 * 撞号会报「two children with the same key」，且编辑其中一条时另一条可能跟着变。
 */
function 造意向编号(已有: 求职意向[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`I-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `I-${String(序).padStart(2, '0')}`;
}

