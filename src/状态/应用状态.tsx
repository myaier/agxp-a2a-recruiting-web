/** 初始推荐池：静态种子 + 给每个在招岗位补足到至少 2 个（用起步推荐模板克隆，
    编号带 @岗位编号 后缀，匿名简历档按 @ 前缀回落）*/
function 推荐列表初始(): 推荐候选[] {
  const 池 = [...推荐列表种子];
  for (const 岗 of 在招岗位列表) {
    if (岗.状态 !== '在招') continue;
    const 已有 = 池.filter((人) => 人.岗位编号 === 岗.编号).length;
    for (let 序 = 0; 序 < Math.max(0, 2 - 已有); 序++) {
      const 模 = 起步推荐模板[序 % 起步推荐模板.length];
      池.push({ ...模, 编号: `${模.编号}@${岗.编号}`, 岗位编号: 岗.编号 });
    }
  }
  return 池;
}

/**
 * 生成一个不与现有规则撞号的编号。
 * 不能直接用「条数 + 偏移」：筛选层里可以删规则，删一条再加一条就会撞上还活着的号，
 * 撞号会让 React 列表里出现两个相同 key、编辑其中一条时另一条跟着变。
 */
function 造规则编号(已有: 规则[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`R-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `R-${String(序).padStart(2, '0')}`;
}

