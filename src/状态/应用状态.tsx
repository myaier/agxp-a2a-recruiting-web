/**
 * 在谈列表的「看哪几单」档位 —— 两端共用（求职端在谈 / 企业端在谈候选）。
 * 定义放状态层而不是 组件/在谈筛选层：这三个档现在是全局状态的取值，
 * 面板只是它的一个编辑入口；类型跟着状态走，两处各写一份迟早会漂。
 */
export type 看什么档 = '全部' | '待我拍板' | '进行中';

/**
 * 在谈列表的范围档：
 *   当前 = 只看顶栏此刻选中的那一个（求职端 = 一条求职意向，企业端 = 一个在招岗位）；
 *   全部 = 跨范围一次看全。
 *
 * 为什么必须有「全部」这一档（拦路 5 / 6）：
 *   · 求职端「我的」四个统计读的是全量在谈（8），职位 Tab 按当前意向过滤只剩 5，
 *     少的 3 个挂在别的意向下，而用户没有任何视图能一次看全 ——
 *     「一份简历挂多个意向、各自独立谈」是产品主线，把统计缩到单意向等于把主线砍了，
 *     所以选择给列表补一个跨意向档，而不是把统计缩到当前意向。
 *   · 企业端同理：「等我拍板」是跨岗位算的，落地的列表也必须能跨岗位，
 *     否则招聘方要逐个岗位切顶栏才能看全，岗位越多漏得越多。
 */
export type 在谈范围档 = '当前' | '全部';

/**
 * 意向草稿：添加/编辑求职期望页与它的次级页（选城市 / 选行业 / 薪资弹层）共用的一份表单态。
 * 跳去次级页再回来不能丢已填内容，所以它必须在全局状态里，不能只放在页面组件的 useState。
 * 与 引导预填 严格分开：那是 onboarding 的持久答案，这是一次编辑会话的临时稿，互不污染。
 *
 * 类型定义已迁入 数据/招聘数据源类型.ts（数据层不反向 import React Context）；
 * 此处 import 供本地归约使用，并以 `export type` 再导出，保持现有屏幕
 * `import { type 意向草稿型 } from '../状态/应用状态'` 不变。
 */
import type { 意向草稿型 } from '../数据/招聘数据源类型';
