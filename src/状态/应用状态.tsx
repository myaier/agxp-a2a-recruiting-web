/**
 * 把已存的求职意向拆回草稿字段，供编辑态预填。
 * 现有格式：标题 `[上海] 后端工程师`，说明 `58K · 15 薪｜金融基建优先｜在谈 5`。
 * 说明是给人看的展示串、不是结构化数据，格式随时可能对不上 ——
 * 所以每个字段各自宽容匹配，匹配不上就退回空值，绝不抛错、也绝不因为一段没对上就整条放弃。
 */
function 拆意向为草稿(条: 求职意向): 意向草稿型 {
  const 标题命中 = /^\[([^\]]+)\]\s*(.+)$/.exec(条.标题);
  const 段 = 条.说明.split('｜');
  const 薪资段 = 段[0]?.trim() ?? '';
  // 先试区间「10-11K」，再试单值「58K」；单值时下限=上限，滚轮打开就停在这个档位上
  const 区间命中 = /(\d+)\s*-\s*(\d+)\s*[Kk]/.exec(薪资段);
  const 单值命中 = /(\d+)\s*[Kk]/.exec(薪资段);
  const 薪资下限 = 区间命中 ? Number(区间命中[1]) : 单值命中 ? Number(单值命中[1]) : null;
  const 薪资上限 = 区间命中 ? Number(区间命中[2]) : 单值命中 ? Number(单值命中[1]) : null;
  // 行业段按顿号拆；说明串里根本没有这一段时留空数组
  const 期望行业们 = (段[1] ?? '')
    .split('、')
    .map((名) => 名.trim())
    .filter((名) => 名 !== '');
  return {
    ...空意向草稿,
    编辑编号: 条.编号,
    // 标题拆不出「[城市] 职位」时，把整个标题当职位用，城市留空等用户补
    工作城市: 标题命中?.[1] ?? '',
    期望职位: 标题命中?.[2] ?? 条.标题,
    薪资下限,
    薪资上限,
    期望行业们,
    // 求职类型 / 感兴趣城市们：意向表的标题说明里本来就不带这些信息，
    // 保持空意向草稿的默认值
  };
}

/**
 * 未读表播种：把模拟数据里静态写死的 未读数 / 红点 收进全局状态，之后只认这张表。
 * 值 = 未读条数；只标了红点、没给条数的那种存 0（渲染成红点，不是数字徽标）。
 * 模拟数据里的 未读数 / 红点 从此只当种子用，屏上一律不再直接读它们 ——
 * 两个数据源同时存在，就会出现「表里已清、卡上还红」的对不上。
 */
function 播种未读表(消息表: 消息条目[]): Record<string, number> {
  const 表: Record<string, number> = {};
  for (const 条 of 消息表) {
    if (条.未读数 !== undefined && 条.未读数 > 0) 表[条.编号] = 条.未读数;
    else if (条.红点) 表[条.编号] = 0;
  }
  return 表;
}

/**
 * 未读总数 —— 底部导航角标用。
 * 只画红点、不计条数的会话按 1 条计入：它在表里的值是 0，直接求和会让它在角标上等于不存在，
 * 而它恰恰就是「有新消息」这件事本身。
 */
export function 数未读(表: Record<string, number>): number {
  return Object.values(表).reduce((和, 数) => 和 + (数 > 0 ? 数 : 1), 0);
}

