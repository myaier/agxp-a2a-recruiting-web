function 归约(旧: 状态, 动作: 动作): 状态 {
  switch (动作.型) {
    case '切意向':
      return { ...旧, 当前意向: 动作.意向 };
    case '切子视图':
      return { ...旧, 子视图: 动作.子视图 };
    case '切Tab':
      return { ...旧, 当前Tab: 动作.Tab };

    // 接受协调方案 → 该单推进到「意向确认」，不再需要你
    case '接受方案': {
      const 该单 = 旧.在谈列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '接受' },
        // 分歧数据留档：详情页回看时还能展示当时的数字对比
        决策快照: 该单?.分歧 ? { ...旧.决策快照, [动作.编号]: 该单.分歧 } : 旧.决策快照,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                需要你: true,
                下一步: '条件已放宽并回报对方，等双方确认意向',
                辅助文案: '确认后转真人沟通',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 退出 → 从在谈列表移除，同时落一条到归档列表（归档页要能看到它）
    case '退出谈判': {
      const 该单 = 旧.在谈列表.find((条) => 条.编号 === 动作.编号);
      const 新归档: 归档条[] = 该单
        ? [
            {
              编号: 该单.编号,
              公司: 该单.公司,
              公司首字: 该单.公司首字,
              职位: 该单.职位,
              止步阶段: 该单.阶段,
              结果: '我方退出',
              // 分歧只有「我方 / 差值 / 对方」三项，卡点项名要从下一步文案里抠
              原因: 该单.分歧
                ? `双方在「${/卡在(.{1,6}?)[，,]/.exec(该单.下一步)?.[1] ?? '关键条件'}」上${该单.分歧.差值}，你选择退出。`
                : '你在本轮选择退出这一单。',
              时间: '刚刚',
            },
            ...旧.归档列表,
          ]
        : 旧.归档列表;
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '退出' },
        在谈列表: 旧.在谈列表.filter((条) => 条.编号 !== 动作.编号),
        归档列表: 新归档,
      };
    }

    // 确认意向 → 转真人沟通，卡片不再等你
    case '确认意向':
      return {
        ...旧,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                下一步: '已确认意向，联系方式已互换',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    // 叮嘱沉淀成规则
    case '新增规则': {
      const 新编号 = `R-${String(旧.全局规则.length + 旧.意向级规则.length + 8).padStart(2, '0')}`;
      return {
        ...旧,
        全局规则: [...旧.全局规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }

    case '切规则开关':
      return {
        ...旧,
        全局规则: 旧.全局规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
        意向级规则: 旧.意向级规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };

    case '委托代理':
      return 旧.已委托.includes(动作.编号)
        ? 旧
        : { ...旧, 已委托: [...旧.已委托, 动作.编号] };

    // 标注意见 #8：「让AI代理去谈」把市场岗位真的变成一个在谈单 ——
    // 代理立刻主动打招呼（打招呼内容在详情/往来记录里可见），阶段从匿名初筛起步
    case '委托入谈': {
      if (旧.在谈列表.some((条) => 条.编号 === 动作.岗.编号)) return 旧; // 幂等
      const 公司名 = 动作.岗.公司行.split(' · ')[0];
      const 新单: 在谈单 = {
        编号: 动作.岗.编号,
        意向: 动作.岗.意向,
        公司: 公司名,
        公司首字: 公司名.charAt(0),
        公司简介: 动作.岗.公司行.slice(公司名.length + 3) || 动作.岗.标签.join(' · '),
        薪资: 动作.岗.薪资,
        职位: 动作.岗.职位,
        标签: 动作.岗.标签,
        阶段: '匿名初筛',
        轮次: '第 1 轮',
        下一步: 'AI代理已主动发起接触，等待对方响应',
        辅助文案: '硬性条件核对中，无需你介入',
        需要你: false,
        分歧: null,
        适配分: 动作.岗.适配分,
        顶部横幅: null,
        横幅时长: null,
      };
      return {
        ...旧,
        已委托: 旧.已委托.includes(动作.岗.编号) ? 旧.已委托 : [...旧.已委托, 动作.岗.编号],
        在谈列表: [...旧.在谈列表, 新单],
      };
    }

    // ── 企业端动作：与求职端同构的镜像逻辑 ──
    case '企业切Tab':
      return { ...旧, 企业Tab: 动作.Tab };
    case '企业切子视图':
      return { ...旧, 企业子视图: 动作.子视图 };
    case '切当前岗位':
      return { ...旧, 当前岗位编号: 动作.编号 };

    // 接受代理方案 → 该候选推进到「意向确认」（等对方点头）
    case '候选接受方案': {
      const 该候选 = 旧.企业候选列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '接受' },
        候选决策快照: 该候选?.分歧
          ? { ...旧.候选决策快照, [动作.编号]: 该候选.分歧 }
          : 旧.候选决策快照,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                // 镜像求职端语义：接受方案后进入意向确认，先等你（企业）正式确认，
                // 所以卡片保持红描边置顶；「候选确认意向」时才置 false
                需要你: true,
                下一步: '条件已一致，等你确认意向',
                辅助文案: '确认后等候选人点头，双方齐了互换联系方式',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 终止 → 从在谈候选里移除（归档）
    case '候选终止':
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '终止' },
        企业候选列表: 旧.企业候选列表.filter((条) => 条.编号 !== 动作.编号),
      };

    // 双方意向确认 → 互换姓名（A-01 即求职端主角沈亦舟，剧情闭环）
    case '候选确认意向':
      return {
        ...旧,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                真名: 条.编号 === 'A-01' ? '沈亦舟' : 条.真名,
                下一步: '双方已确认，联系方式已互换',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    case '企业新增规则': {
      const 新编号 = `R-${String(旧.企业规则.length + 6).padStart(2, '0')}`;
      return {
        ...旧,
        企业规则: [...旧.企业规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }

    case '企业切规则开关':
      return {
        ...旧,
        企业规则: 旧.企业规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };

    case '接触推荐候选':
      return 旧.已接触推荐.includes(动作.编号)
        ? 旧
        : { ...旧, 已接触推荐: [...旧.已接触推荐, 动作.编号] };

    // 新发布的岗位插到列表最前并自动选中（标注意见 2026-08-18）——
    // 用户刚填完就想看见它，排在第 3 个还要自己找
    case '发布岗位': {
      const 新编号 = `P-${String(旧.岗位列表.length + 1).padStart(2, '0')}`;
      const 新岗: 在招岗位 = {
        编号: 新编号,
        名称: 动作.名称,
        薪资带: 动作.薪资带,
        状态: '在招',
        在谈数: 0,
      };
      return {
        ...旧,
        岗位列表: [新岗, ...旧.岗位列表],
        当前岗位编号: 新编号,
        企业子视图: '在谈',
        企业Tab: '人才',
      };
    }

    // ── 「我的」下属功能页 ──
    case '读通知':
      return {
        ...旧,
        通知列表: 旧.通知列表.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 已读: true } : 条
        ),
      };

    case '通知全读':
      return { ...旧, 通知列表: 旧.通知列表.map((条) => ({ ...条, 已读: true })) };

    // 拉黑是双向的（业务约束 6）：加进来之后对方也看不到你
    case '拉黑': {
      const 名称 = 动作.名称.trim();
      if (名称 === '' || 旧.屏蔽名单.some((条) => 条.名称 === 名称)) return 旧;
      const 新项: 屏蔽项 = {
        编号: `B-${String(旧.屏蔽名单.length + 1).padStart(2, '0')}`,
        名称,
        首字: 名称.charAt(0),
        理由: '你手动加入 · 双向不可见',
        时间: '刚刚',
      };
      return { ...旧, 屏蔽名单: [新项, ...旧.屏蔽名单] };
    }

    case '解除屏蔽':
      return { ...旧, 屏蔽名单: 旧.屏蔽名单.filter((条) => 条.编号 !== 动作.编号) };

    // 锁定项（薪资数字 / 并行数量）在归约层再挡一次，UI 之外也改不动
    case '设披露档':
      return {
        ...旧,
        披露偏好: 旧.披露偏好.map((条) =>
          条.编号 === 动作.编号 && 条.锁定 === null && 条.可选档.includes(动作.档)
            ? { ...条, 档: 动作.档 }
            : 条
        ),
      };

    case '切设置开关':
      return {
        ...旧,
        设置开关: { ...旧.设置开关, [动作.键]: !旧.设置开关[动作.键] },
      };

    default:
      return 旧;
  }
}

const 上下文 = createContext<{ 状态: 状态; 派发: (动作: 动作) => void } | null>(null);

export function 应用状态提供者({ children }: { children: ReactNode }) {
  const [状态, 派发] = useReducer(归约, 初始状态);
  const 值 = useMemo(() => ({ 状态, 派发 }), [状态]);
  return <上下文.Provider value={值}>{children}</上下文.Provider>;
}

export function use应用状态() {
  const 值 = useContext(上下文);
  if (!值) throw new Error('use应用状态 必须在 应用状态提供者 内部使用');
  return 值;
}
