type 子视图 = '在谈' | '看市场';
type 底部Tab = '职位' | '消息' | '我的';

interface 状态 {
  当前意向: string;
  子视图: 子视图;
  当前Tab: 底部Tab;
  在谈列表: 在谈单[];
  /** 已作出的决策：编号 → 接受 / 退出 */
  决策: Record<string, '接受' | '退出'>;
  /** 决策时的分歧快照：接受方案会清掉 单.分歧（首页卡片不再显示分歧轴），
      但详情页回看时仍要展示当时的数字对比，所以在这里留档 */
  决策快照: Record<string, 分歧>;
  全局规则: 规则[];
  意向级规则: 规则[];
  /** 在看市场里已委托代理去谈的岗位编号 */
  已委托: string[];

  // ── 企业端（招人方）切片：与求职端同构 ──
  企业候选列表: 候选[];
  候选决策: Record<string, '接受' | '终止'>;
  候选决策快照: Record<string, 分歧>;
  企业规则: 规则[];
  岗位列表: 在招岗位[];
  当前岗位编号: string;
  企业子视图: '在谈' | '推荐';
  企业Tab: '人才' | '消息' | '我的';
  /** 已委托代理去聊的推荐候选编号 */
  已接触推荐: string[];

  // ── 「我的」下属功能页切片 ──
  通知列表: 通知条[];
  屏蔽名单: 屏蔽项[];
  披露偏好: 披露项[];
  归档列表: 归档条[];
  /** 设置页的开关：键 → 开。键用中文语义名，直接当标题用 */
  设置开关: Record<string, boolean>;
}

type 动作 =
  | { 型: '切意向'; 意向: string }
  | { 型: '切子视图'; 子视图: 子视图 }
  | { 型: '切Tab'; Tab: 底部Tab }
  | { 型: '接受方案'; 编号: string }
  | { 型: '退出谈判'; 编号: string }
  | { 型: '确认意向'; 编号: string }
  | { 型: '新增规则'; 内容: string; 来源: string }
  | { 型: '切规则开关'; 编号: string }
  | { 型: '委托代理'; 编号: string }
  | { 型: '委托入谈'; 岗: 市场职位 }
  // ── 企业端动作 ──
  | { 型: '企业切Tab'; Tab: '人才' | '消息' | '我的' }
  | { 型: '企业切子视图'; 子视图: '在谈' | '推荐' }
  | { 型: '切当前岗位'; 编号: string }
  | { 型: '候选接受方案'; 编号: string }
  | { 型: '候选终止'; 编号: string }
  | { 型: '候选确认意向'; 编号: string }
  | { 型: '企业新增规则'; 内容: string; 来源: string }
  | { 型: '企业切规则开关'; 编号: string }
  | { 型: '接触推荐候选'; 编号: string }
  | { 型: '发布岗位'; 名称: string; 薪资带: string }
  // ── 「我的」下属功能页动作 ──
  | { 型: '读通知'; 编号: string }
  | { 型: '通知全读' }
  | { 型: '拉黑'; 名称: string }
  | { 型: '解除屏蔽'; 编号: string }
  | { 型: '设披露档'; 编号: string; 档: 披露档 }
  | { 型: '切设置开关'; 键: string };

