// ── Backend 水合 / 会话 / 操作 ───────────────────────────────────

// 后端状态与操作组合类型已按 owner 拆到 ./后端/类型；此处保留公开导入路径。
export type { 应用操作, 后端状态 } from './后端/类型';

interface 应用状态值 {
  状态: 状态;
  派发: (动作: 动作) => void;
  数据源模式: 'mock' | 'backend';
  后端状态: 后端状态;
  操作: 应用操作;
  /** 目录查询方法（Task 3 R8）：Backend 模式暴露 查询Location/Taxonomy/Institution，Mock 为 null */
  目录查询: Pick<HTTP招聘数据源, '查询Location' | '查询Taxonomy' | '查询Institution'> | null;
}

const 上下文 = createContext<应用状态值 | null>(null);

export function 应用状态提供者({ children, 数据源 }: { children?: ReactNode; 数据源?: 招聘数据源选择 }) {
  const 源 = 数据源 ?? 招聘数据;
  const 是后端 = 源.模式 === 'backend';
  const 后端 = 是后端 ? 源.后端 : null;
  const 环境 = 源.后端环境 ?? 'stg';
  const [状态, 派发] = useReducer(归约, 源, 创建初始状态);
  const [后端状态, 设后端状态] = useState<后端状态>(() => ({
    初始化: 是后端 ? '进行中' : '跳过',
    已登录: false,
    主体: null,
    简历快照: null,
    意向快照: {},
    岗位快照: {},
    隐私快照: null,
    // P6：Agent 规则域种子全空，双端水合阶段都从 未开始 起跑
    候选规则快照: {},
    招聘规则快照: {},
    候选规则提案: {},
    招聘规则提案: {},
    Agent规则水合: {
      candidate: { rules: '未开始', proposals: '未开始' },
      recruiter: { rules: '未开始', proposals: '未开始' },
    },
  }));

  // 让异步操作读到最新的 后端状态 / 状态（useMemo 闭包只捕获首次值）
  const 后端状态引用 = useRef(后端状态);
  后端状态引用.current = 后端状态;
  const 状态引用 = useRef(状态);
  状态引用.current = 状态;
  // 手机登录尝试号：开始登录写入，完成登录读出
  const 尝试引用 = useRef<string | null>(null);
  // StrictMode 下 effect 会跑两次，用 ref 阻止恢复会话重复请求
  const 已初始化 = useRef(false);
  // 并发写锁：简历保存 / 意向:${id|new} 同一操作进行中时拒绝重复提交
  const 锁 = useRef<Set<string>>(new Set());
  // review-r2 R2-I-4：当前主体 subject_id。新主体到达时若 subject_id 变了，
  // 先清上个账号的草稿/快照/缓存，再接受新主体（同 Provider 实例跨账号泄漏）。
  const 主体标识引用 = useRef<string | null>(null);
  // review-r2 R2-M-4：会话代际。登录/退出/401 清理时递增；目录请求捕获起始代际，
  // 401 到达时若代际已变（新会话），stale 401 被忽略，不清新会话。
  const 会话代际 = useRef(0);
  const 当前主体标识 = 后端状态.主体?.subject_id ?? null;
  use资料持久化({ 状态, 派发, 是后端, 环境, 当前主体标识 });

  // P1C：从 subject-scoped sessionStorage 读取恢复的 current relation 候选值。
  // 只作为 选择当前企业关系(affiliations, restoredId) 的输入；读取本身不派发选择 action，
  // revoked ID 只会在最新 Affiliations 校验后被丢弃。
  const 读取恢复企业关系编号 = (subjectId: string): string | null => {
    const 快照 = 读资料缓存(安全取存储('session'), { 模式: 'backend', 环境, 账号: subjectId });
    const 值 = 快照.当前企业关系编号;
    return typeof 值 === 'string' ? 值 : null;
  };

  // ── Backend 初始化：mount 时恢复会话一次；401 视为未登录，其他错误轻提示；均不回退 Mock ──
  // 已知边缘：资源写入的 in-flight 代际守卫未实现（R3-I-1 延后）——但登录水合链（P1C 起）带
  // subject fence + 会话代际：mount/切角色 先写 ref 再水合，组织水合内部逐响应丢弃过时结果。
  useEffect(() => {
    if (!是后端 || !后端) return;
    if (已初始化.current) return;
    已初始化.current = true;
    let 已取消 = false;
    (async () => {
      try {
        await 后端.恢复会话();
      } catch (错误) {
        if (已取消) return;
        if (错误 instanceof BFF错误 && 错误.status === 401) {
          // 401 只清后端状态，不载入 Mock 支持域
          设后端状态((旧) => ({ ...旧, 初始化: '完成', 已登录: false }));
          // Task 2：401 清空目录缓存，避免下个会话复用上个会话的目录页缓存。
          后端?.清空目录缓存();
        } else {
          轻提示(取后端错误文案(错误));
          设后端状态((旧) => ({ ...旧, 初始化: '完成', 已登录: false }));
        }
        return;
      }
      if (已取消) return;
      let 主体: BFF主体;
      try {
        主体 = await 后端.读取主体();
      } catch (错误) {
        if (已取消) return;
        轻提示(取后端错误文案(错误));
        设后端状态((旧) => ({ ...旧, 初始化: '完成', 已登录: false }));
        return;
      }
      if (已取消) return;
      // P1C：读取主体后先建立 subject fence 再开始任何角色水合 —— mount 恢复出一个新会话，
      // 先递增 generation 再把捕获值传入水合；不能在水合完成后才写 ref（否则同一次恢复会话
      // 会被无意义地再次换代，且水合途中无 fence 可拦 stale 响应）。
      主体标识引用.current = 主体.subject_id;
      会话代际.current += 1;
      const 本次代际 = 会话代际.current;
      // review-r2 R2-I-3：水合 401 时 水合角色数据 内部已走登出清理并返回 会话失效=true，
      // 不再落 已登录=true（旧实现会把上个会话的快照/草稿留给已失效的登录态）。
      const 会话失效 = await 水合角色数据({
        后端, 派发, 设后端状态, 主体标识引用, 会话代际, 读取恢复企业关系编号,
      }, 主体, false, 本次代际);
      if (已取消) return;
      if (会话失效) {
        // review-r3 R3-I-2：清账号状态 已在 水合角色数据 内部清完（含主体标识 + 会话代际），
        // 这里只早退，不再重复清理。
        return;
      }
      设后端状态((旧) => ({ ...旧, 初始化: '完成', 已登录: true, 主体 }));
    })();
    return () => {
      已取消 = true;
      // StrictMode 下 dev 会 setup→cleanup→setup：第一次的异步已被 已取消=true 取消，
      // 但 已初始化.current 仍为 true，第二次 setup 会早退 → 初始化永远停在 '进行中'。
      // 这里一并复位 ref，让第二次 setup 重新跑初始化；第一次的异步已被 已取消 守住不会再 set state。
      // 生产环境（无 StrictMode）cleanup 只在 unmount 时跑，复位不影响。
      已初始化.current = false;
    };
    // 是后端 / 后端 在同一 Provider 实例下不变；派发 / 设后端状态 由 React 保证稳定
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [是后端, 后端]);

  const 操作 = useMemo<应用操作>(
    () => {
      const deps: 后端操作依赖 = {
        是后端,
        后端,
        派发,
        设后端状态,
        后端状态引用,
        状态引用,
        锁,
        尝试引用,
        主体标识引用,
        会话代际,
        读取恢复企业关系编号,
      };
      return {
        ...创建会话操作(deps),
        ...创建候选操作(deps),
        ...创建岗位操作(deps),
        ...创建组织操作(deps),
        ...创建隐私操作(deps),
        // P6：Agent 规则/提案操作与其它域共用同一把 deps（锁 / 主体标识 / 会话代际）
        ...创建Agent规则操作(deps),
      };
    },
    // 是后端 / 后端 在同一 Provider 实例下不变；派发 / 设后端状态 由 React 保证稳定
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [是后端, 后端],
  );

  // ── P6 页面数组派生：raw 快照（或权威意向字典）任一变化都重算分组 ──
  // Rule 请求与 Intention 请求谁先完成都不影响最终归属：这里只吃 raw 输入，
  // orphan 意向 scope 在权威意向到达前整条省略，到达后同一 raw Rule 自动归组。
  // 意向侧读 状态.后端意向服务端（水合后端意向 落的权威字典，操作与会话层双写），
  // 与 候选分组 的其余消费者同源，避免再养第二份意向真相。
  useEffect(() => {
    if (!是后端 || 后端状态.Agent规则水合.candidate.rules !== '成功') return;
    const mapped = 映射候选Agent规则(
      Object.values(后端状态.候选规则快照),
      状态.后端意向服务端,
    );
    派发({ 型: '水合后端候选规则', 全局: mapped.全局, 意向级: mapped.意向级 });
  }, [是后端, 后端状态.Agent规则水合.candidate.rules, 后端状态.候选规则快照, 状态.后端意向服务端]);

  useEffect(() => {
    if (!是后端 || 后端状态.Agent规则水合.recruiter.rules !== '成功') return;
    派发({
      型: '水合后端招聘规则',
      规则: 映射招聘Agent规则(Object.values(后端状态.招聘规则快照)),
    });
  }, [是后端, 后端状态.Agent规则水合.recruiter.rules, 后端状态.招聘规则快照]);

  // 目录查询 seam 已按 owner 拆到 ./后端/目录查询：Backend 模式暴露 查询Location/Taxonomy/Institution，
  // Mock 为 null；401 会话代际守卫与统一清理都在 创建目录查询 内部。
  // useMemo 键 是后端/后端（同 Provider 实例下不变），使 目录查询 引用稳定。
  const 目录查询 = useMemo(
    () => 创建目录查询({ 是后端, 后端, 派发, 设后端状态, 主体标识引用, 会话代际 }),
    // 是后端 / 后端 在同一 Provider 实例下不变；派发 / 设后端状态 由 React 保证稳定
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [是后端, 后端],
  );

  const 值 = useMemo<应用状态值>(
    () => ({ 状态, 派发, 数据源模式: 源.模式, 后端状态, 操作, 目录查询 }),
    [状态, 派发, 源.模式, 后端状态, 操作, 目录查询],
  );
  return <上下文.Provider value={值}>{children}</上下文.Provider>;
}

export function use应用状态() {
  const 值 = useContext(上下文);
  if (!值) throw new Error('use应用状态 必须在 应用状态提供者 内部使用');
  return 值;
}
