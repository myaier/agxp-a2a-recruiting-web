// 都从这里拿同一份「由对齐行算出」的分,与详情页的环、分析段永不打架。
//
// Backend 模式直接回落 wire 上的分:求职侧对齐行 的 Mock 分支用演示简历口径
// (9 年 / 硕士)断言命中,绝不能拿它替真实用户算分(P4 纪律);
// 权威路径的逐行核对只在 职位详情 里做(那里有 核对 事实可用)。

import { use应用状态 } from './应用状态';
import { 市场列表 } from '../数据/模拟数据';
import { 求职侧对齐行, 算适配分 } from '../数据/匹配对齐';

export function use适配分(源: {
  编号?: string;
  适配分: number;
  经验要求?: string;
  学历要求?: string;
  技能要求?: string[];
}): number {
  const { 状态, 数据源模式 } = use应用状态();
  if (数据源模式 === 'backend') return 源.适配分;
  // 委托进来的 M- 单借市场岗位上的证据,剧本 J- 单/市场岗用自己的同名字段
  const 证据源 = 市场列表.find((岗) => 岗.编号 === 源.编号) ?? 源;
  return 算适配分(
    求职侧对齐行(证据源, {
      经历: 状态.简历经历,
      教育: 状态.简历教育,
      技能: 状态.简历技能,
    }),
    源.适配分,
  );
}
