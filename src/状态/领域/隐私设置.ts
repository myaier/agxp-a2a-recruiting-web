// 隐私与设置域 reducer：屏蔽、披露档、隐私/设置开关、飞书接入。
// 从根 归约 按业务 owner 拆出，case body 逐字搬移。对根 状态 只使用 type-only import。

import type { 披露档, 披露项, 屏蔽项 } from '../../数据/类型';
import type { 状态 } from '../应用状态';

export interface 隐私设置状态 {
  屏蔽名单: 屏蔽项[];
  披露偏好: 披露项[];
  企业披露策略: 披露项[];
  设置开关: Record<string, boolean>;
  企业设置开关: Record<string, boolean>;
  飞书已接入: boolean;
  企业飞书已接入: boolean;
}

export type 隐私设置动作 =
  | { 型: '拉黑'; 名称: string }
  | { 型: '解除屏蔽'; 编号: string }
  | { 型: '设披露档'; 编号: string; 档: 披露档 }
  | { 型: '设企业披露档'; 编号: string; 档: 披露档 }
  | { 型: '切设置开关'; 键: string }
  | { 型: '企业切设置开关'; 键: string }
  | { 型: '设飞书接入'; 接入: boolean }
  | { 型: '设企业飞书接入'; 接入: boolean };

export type 隐私设置归约 = (旧: 状态, 动作: 隐私设置动作) => 状态;

export const 归约隐私设置: 隐私设置归约 = (旧, 动作) => {
  switch (动作.型) {
    case '拉黑': {
      const 名称 = 动作.名称.trim();
      if (名称 === '' || 旧.屏蔽名单.some((条) => 条.名称 === 名称)) return 旧;
      const 新项: 屏蔽项 = {
        编号: `B-${String(旧.屏蔽名单.length + 1).padStart(2, '0')}`,
        名称,
        首字: 名称.charAt(0),
        理由: '你手动加入 · 双向不可见',
        时间: '刚刚',
      };
      return { ...旧, 屏蔽名单: [新项, ...旧.屏蔽名单] };
    }
    case '解除屏蔽':
      return { ...旧, 屏蔽名单: 旧.屏蔽名单.filter((条) => 条.编号 !== 动作.编号) };
    case '设披露档':
      return {
        ...旧,
        披露偏好: 旧.披露偏好.map((条) =>
          条.编号 === 动作.编号 && 条.锁定 === null && 条.可选档.includes(动作.档)
            ? { ...条, 档: 动作.档 }
            : 条
        ),
      };
    case '设企业披露档':
      return {
        ...旧,
        企业披露策略: 旧.企业披露策略.map((条) =>
          条.编号 === 动作.编号 && 条.锁定 === null && 条.可选档.includes(动作.档)
            ? { ...条, 档: 动作.档 }
            : 条
        ),
      };
    case '切设置开关':
      return {
        ...旧,
        设置开关: { ...旧.设置开关, [动作.键]: !旧.设置开关[动作.键] },
      };
    case '企业切设置开关':
      return {
        ...旧,
        企业设置开关: { ...旧.企业设置开关, [动作.键]: !旧.企业设置开关[动作.键] },
      };
    case '设飞书接入':
      return { ...旧, 飞书已接入: 动作.接入 };
    case '设企业飞书接入':
      return { ...旧, 企业飞书已接入: 动作.接入 };
    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};