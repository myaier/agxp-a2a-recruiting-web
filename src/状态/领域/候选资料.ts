/**
 * 把已存的求职意向拆回草稿字段，供编辑态预填。
 */
function 拆意向为草稿(条: 求职意向): 意向草稿型 {
  const 标题命中 = /^\[([^\]]+)\]\s*(.+)$/.exec(条.标题);
  const 段 = 条.说明.split('｜');
  const 薪资段 = 段[0]?.trim() ?? '';
  const 区间命中 = /(\d+)\s*-\s*(\d+)\s*[Kk]/.exec(薪资段);
  const 单值命中 = /(\d+)\s*[Kk]/.exec(薪资段);
  const 薪资下限 = 区间命中 ? Number(区间命中[1]) : 单值命中 ? Number(单值命中[1]) : null;
  const 薪资上限 = 区间命中 ? Number(区间命中[2]) : 单值命中 ? Number(单值命中[1]) : null;
  const 期望行业们 = (段[1] ?? '')
    .split('、')
    .map((名) => 名.trim())
    .filter((名) => 名 !== '');
  return {
    ...空意向草稿,
    编辑编号: 条.编号,
    工作城市: 标题命中?.[1] ?? '',
    期望职位: 标题命中?.[2] ?? 条.标题,
    薪资下限,
    薪资上限,
    期望行业们,
  };
}

/**
 * 意向名 = 求职意向.标题 `[城市] 职位` 里的职位部分。
 */
export function 取意向名(标题: string): string {
  return /^\[[^\]]*\]\s*(.+)$/.exec(标题)?.[1] ?? 标题;
}

/**
 * 算「当前意向」的落点。选中的那条还在表里就原样不动；不在了就落到表里第一条。
 */
export function 选新当前意向(表: 求职意向[], 当前: string): string {
  if (表.some((条) => 取意向名(条.标题) === 当前)) return 当前;
  return 表.length > 0 ? 取意向名(表[0].标题) : '';
}

export const 归约候选资料: 候选资料归约 = (旧, 动作) => {
  switch (动作.型) {
    case '改意向': {
      const 旧条 = 旧.求职意向表.find((条) => 条.编号 === 动作.编号);
      const 新表 = 旧.求职意向表.map((条) =>
        条.编号 === 动作.编号 ? { ...条, 标题: 动作.标题, 说明: 动作.说明 } : 条
      );
      const 跟随改名 =
        旧条 !== undefined && 取意向名(旧条.标题) === 旧.当前意向
          ? 取意向名(动作.标题)
          : 旧.当前意向;
      return { ...旧, 求职意向表: 新表, 当前意向: 选新当前意向(新表, 跟随改名) };
    }
    case '删意向': {
      const 新表 = 旧.求职意向表.filter((条) => 条.编号 !== 动作.编号);
      return { ...旧, 求职意向表: 新表, 当前意向: 选新当前意向(新表, 旧.当前意向) };
    }
    case '新增意向': {
      const 新编号 = 造意向编号(旧.求职意向表);
      const 新表 = [...旧.求职意向表, { 编号: 新编号, 标题: 动作.标题, 说明: 动作.说明 }];
      return { ...旧, 求职意向表: 新表, 当前意向: 选新当前意向(新表, 旧.当前意向) };
    }
    case '开意向草稿': {
      if (动作.编号 === null) return { ...旧, 意向草稿: 空意向草稿 };
      const 服务端dto = 旧.后端意向服务端[动作.编号];
      if (服务端dto) return { ...旧, 意向草稿: 从BFF意向草稿(服务端dto) };
      const 目标 = 旧.求职意向表.find((条) => 条.编号 === 动作.编号);
      return { ...旧, 意向草稿: 目标 ? 拆意向为草稿(目标) : 空意向草稿 };
    }
    case '改意向草稿': {
      const 新草稿: 意向草稿型 = { ...旧.意向草稿, ...动作.补丁 };
      if (动作.补丁.求职类型 !== undefined) 新草稿.求职类型已改 = true;
      return { ...旧, 意向草稿: 新草稿 };
    }
    case '清意向草稿':
      return { ...旧, 意向草稿: 空意向草稿 };
    case '存简历':
      return {
        ...旧,
        简历经历: 动作.经历,
        简历教育: 动作.教育,
        简历技能: 动作.技能,
        简历证书: 动作.证书,
        基本信息: 动作.基本信息,
      };
    case '存个人优势':
      return { ...旧, 个人优势: 动作.文本 };
    case '存作品集链接':
      return { ...旧, 简历作品集链接: 动作.链接 };
    case '存简历文件名':
      return { ...旧, 简历文件名: 动作.文件名 };
    case '存求职头像':
      return { ...旧, 求职头像: 动作.图 };
    case '存联系方式':
      return { ...旧, 联系方式: { ...旧.联系方式, ...动作.补丁 } };
    case '存引导预填':
      return {
        ...旧,
        引导预填: {
          ...(旧.引导预填 ?? {}),
          城市们: 动作.城市们,
          职位: 动作.职位,
          城市引用们: 动作.城市引用们,
          职位引用们: 动作.职位引用们,
        },
      };
    case '启程引导':
      return {
        ...旧,
        引导预填: {
          ...(旧.引导预填 ?? {}),
          城市们: 动作.城市们,
          职位: 动作.职位,
          筛选偏好: 动作.筛选偏好,
          城市引用们: 动作.城市引用们 ?? [],
          职位引用们: 动作.职位引用们 ?? [],
        },
      };
    case '存求职筛选偏好':
      return {
        ...旧,
        引导预填: {
          ...(旧.引导预填 ?? { 城市们: ['上海'], 职位: [] }),
          筛选偏好: 动作.偏好,
        },
      };
    case '存薪资预填':
      return {
        ...旧,
        引导预填: {
          ...(旧.引导预填 ?? { 城市们: ['上海'], 职位: [] }),
          薪资: { 下限: 动作.下限, 上限: 动作.上限, 单位: 动作.单位 },
        },
      };
    case '存到岗预填':
      return {
        ...旧,
        引导预填: {
          ...(旧.引导预填 ?? { 城市们: ['上海'], 职位: [] }),
          到岗: 动作.到岗,
        },
      };
    case '水合后端简历':
      return {
        ...旧,
        基本信息: 动作.快照.基本信息,
        个人优势: 动作.快照.个人优势,
        简历技能: 动作.快照.技能,
        简历经历: 动作.快照.经历,
        简历教育: 动作.快照.教育,
        简历证书: 动作.快照.证书,
      };
    case '水合后端意向': {
      const 新表 = 动作.快照.列表;
      // 编号载体跟着权威快照走：用户已选且仍 active 的原值优先，
      // 否则落水合列表里第一条 active —— 绝不凭意向名反查（名字不保证唯一）。
      const 仍活跃 = 旧.当前意向编号 !== null &&
        动作.快照.服务端[旧.当前意向编号]?.status === 'active'
        ? 旧.当前意向编号
        : 新表.find((条) => 动作.快照.服务端[条.编号]?.status === 'active')?.编号 ?? null;
      // 意向名与编号载体必须同源：服务端改名后按名字反查会落到别条的名字（表头一条、
      // P4 scope 另一条）。载体在表里就取它自己的标题，取不到才回落既有兜底。
      const 活跃条 = 仍活跃 === null ? undefined : 新表.find((条) => 条.编号 === 仍活跃);
      return {
        ...旧,
        求职意向表: 新表,
        当前意向: 活跃条 ? 取意向名(活跃条.标题) : 选新当前意向(新表, 旧.当前意向),
        当前意向编号: 仍活跃,
        后端意向服务端: 动作.快照.服务端,
      };
    }
    case '水合候选引导草稿':
      return { ...旧, 引导预填: 动作.草稿 };
    case '清后端草稿':
      return { ...旧, 引导预填: null, 意向草稿: 空意向草稿 };
    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};