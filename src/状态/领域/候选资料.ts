/**
 * 生成一个不与现有求职意向撞号的编号 —— 与 造规则编号 同一套口径。
 */
function 造意向编号(已有: 求职意向[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`I-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `I-${String(序).padStart(2, '0')}`;
}

/** 空草稿：新建求职期望的起点，也是 清意向草稿 的归零值。 */
