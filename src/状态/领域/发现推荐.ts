// 发现与推荐域 reducer：市场委托、不感兴趣、候选收藏/淘汰/补给推荐。
// 从根 归约 按业务 owner 拆出，case body 逐字搬移。委托入谈 与 接触推荐候选 同时写本域与
// MatchCase 域，保留在根 reducer 跨域编排，不进入本域动作。对根 状态 只使用 type-only import。

import type { 推荐候选 } from '../../数据/类型';
import type { 状态 } from '../应用状态';

export interface 发现推荐状态 {
  /** 在看市场里已委托代理去谈的岗位编号 */
  已委托: string[];
  /** 已委托代理去聊的推荐候选编号 */
  已接触推荐: string[];
  /** 推荐池（标注 2026-08-20 11:42 起入全局）：发岗即播种起步推荐，进推荐页不空盘 */
  推荐列表: 推荐候选[];
  /** 「不感兴趣」的岗位：从看市场流里过滤掉 */
  不感兴趣岗位: string[];
  收藏候选: string[];
  /** 编号 → 不合适原因 */
  不合适候选: Record<string, string>;
}

export type 发现推荐动作 =
  | { 型: '委托代理'; 编号: string }
  | { 型: '不感兴趣'; 编号: string }
  | { 型: '切收藏候选'; 编号: string }
  | { 型: '标记不合适'; 编号: string; 原因: string }
  | { 型: '撤销不合适'; 编号: string }
  | { 型: '补给推荐' };

export type 发现推荐归约 = (旧: 状态, 动作: 发现推荐动作) => 状态;

export const 归约发现推荐: 发现推荐归约 = (旧, 动作) => {
  switch (动作.型) {
    case '委托代理':
      return 旧.已委托.includes(动作.编号)
        ? 旧
        : { ...旧, 已委托: [...旧.已委托, 动作.编号] };

    // 「不感兴趣」：从市场流过滤掉，同时是代理的负反馈样本
    case '不感兴趣':
      return 旧.不感兴趣岗位.includes(动作.编号)
        ? 旧
        : { ...旧, 不感兴趣岗位: [...旧.不感兴趣岗位, 动作.编号] };

    case '切收藏候选':
      return {
        ...旧,
        收藏候选: 旧.收藏候选.includes(动作.编号)
          ? 旧.收藏候选.filter((条) => 条 !== 动作.编号)
          : [...旧.收藏候选, 动作.编号],
      };

    // 标记不合适：从推荐流移出，进「已筛掉」列表留档（可撤销，审计面）
    case '标记不合适':
      return { ...旧, 不合适候选: { ...旧.不合适候选, [动作.编号]: 动作.原因 } };

    case '撤销不合适': {
      const 余 = { ...旧.不合适候选 };
      delete 余[动作.编号];
      return { ...旧, 不合适候选: 余 };
    }

    // 补给推荐（回归修：原实现把 不合适候选 全清空 —— 等于把用户的负反馈静默抹掉，
    // 且与「已筛掉的候选」页「代理不会再推荐这些人」「原因会成为负反馈样本」自相矛盾）。
    // 正确语义：再扫一轮只可能新增候选，绝不召回已被否决的人。原型没有真数据源，
    // 所以这里不改任何状态，由调用方给「暂时没有新的人选」的诚实反馈。
    case '补给推荐':
      return 旧;

    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};