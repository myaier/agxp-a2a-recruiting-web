// Agent 规则域 reducer：双端规则 CRUD、开关和规则草案。
// 从根 归约 按业务 owner 拆出，case body 逐字搬移。造规则编号 随规则 case 移入本文件，
// 它没有其他消费者，不建立共享 utils 文件。对根 状态 只使用 type-only import。

import type { 规则 } from '../../数据/类型';
import type { 状态 } from '../应用状态';

export interface Agent规则状态 {
  全局规则: 规则[];
  意向级规则: 规则[];
  企业规则: 规则[];
}

export type Agent规则动作 =
  | { 型: '新增规则'; 内容: string; 来源: string }
  | { 型: '改规则'; 编号: string; 内容: string }
  | { 型: '删规则'; 编号: string }
  | { 型: '切规则开关'; 编号: string }
  | { 型: '企业新增规则'; 内容: string; 来源: string }
  | { 型: '企业改规则'; 编号: string; 内容: string }
  | { 型: '企业删规则'; 编号: string }
  | { 型: '企业切规则开关'; 编号: string };

export type Agent规则归约 = (旧: 状态, 动作: Agent规则动作) => 状态;

/**
 * 生成一个不与现有规则撞号的编号。
 * 不能直接用「条数 + 偏移」：筛选层里可以删规则，删一条再加一条就会撞上还活着的号，
 * 撞号会让 React 列表里出现两个相同 key、编辑其中一条时另一条跟着变。
 */
function 造规则编号(已有: 规则[]): string {
  const 占用 = new Set(已有.map((条) => 条.编号));
  let 序 = 已有.length + 1;
  while (占用.has(`R-${String(序).padStart(2, '0')}`)) 序 += 1;
  return `R-${String(序).padStart(2, '0')}`;
}

export const 归约Agent规则: Agent规则归约 = (旧, 动作) => {
  switch (动作.型) {
    case '新增规则': {
      const 新编号 = 造规则编号([...旧.全局规则, ...旧.意向级规则]);
      return {
        ...旧,
        全局规则: [...旧.全局规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }
    // 规则可编辑可删除（标注 10:16：不是开关制，是编辑保存制）
    case '改规则': {
      const 改 = (列: 规则[]) =>
        列.map((条) => (条.编号 === 动作.编号 ? { ...条, 内容: 动作.内容 } : 条));
      return { ...旧, 全局规则: 改(旧.全局规则), 意向级规则: 改(旧.意向级规则) };
    }
    case '删规则': {
      const 删 = (列: 规则[]) => 列.filter((条) => 条.编号 !== 动作.编号);
      return { ...旧, 全局规则: 删(旧.全局规则), 意向级规则: 删(旧.意向级规则) };
    }
    case '切规则开关':
      return {
        ...旧,
        全局规则: 旧.全局规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
        意向级规则: 旧.意向级规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };

    case '企业新增规则': {
      const 新编号 = 造规则编号(旧.企业规则);
      return {
        ...旧,
        企业规则: [...旧.企业规则, { 编号: 新编号, 内容: 动作.内容, 来源: 动作.来源, 生效: true }],
      };
    }
    // 企业规则跟求职端规则一样是编辑保存制：筛选层里一排一条，改完失焦即落库
    case '企业改规则':
      return {
        ...旧,
        企业规则: 旧.企业规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 内容: 动作.内容 } : 条
        ),
      };
    case '企业删规则':
      return { ...旧, 企业规则: 旧.企业规则.filter((条) => 条.编号 !== 动作.编号) };
    case '企业切规则开关':
      return {
        ...旧,
        企业规则: 旧.企业规则.map((条) =>
          条.编号 === 动作.编号 ? { ...条, 生效: !条.生效 } : 条
        ),
      };
    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};