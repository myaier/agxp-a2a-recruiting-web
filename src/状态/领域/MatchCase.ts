// MatchCase 域 reducer：双端在谈、阶段决策、归档、叮嘱归属。
// 从根 归约 按业务 owner 拆出，case body 逐字搬移。发布岗位 / 委托入谈 / 接触推荐候选 同时写
// 本域与别的域，保留在根 reducer 跨域编排。候选终止 只读 旧.岗位列表（跨域只读，不写）。对根
// 状态 只使用 type-only import。

import type { 分歧, 在谈单, 候选, 归档条, 阶段 } from '../../数据/类型';
import type { 看什么档, 在谈范围档 } from '../应用状态';
import type { 企业归档条 } from '../应用状态';
import type { 状态 } from '../应用状态';

export interface MatchCase状态 {
  在谈列表: 在谈单[];
  /** 在谈列表的「看哪几单」档 */
  在谈看什么: 看什么档;
  /** 在谈列表的范围档（当前意向 / 全部意向）*/
  在谈范围: 在谈范围档;
  /** 已作出的决策：编号 → 接受 / 退出 */
  决策: Record<string, '接受' | '退出'>;
  /** 决策时的分歧快照 */
  决策快照: Record<string, 分歧>;
  企业候选列表: 候选[];
  候选决策: Record<string, '接受' | '终止'>;
  候选决策快照: Record<string, 分歧>;
  /** 企业端在谈候选的「看哪几单」档（镜像 在谈看什么）*/
  企业在谈看什么: 看什么档;
  /** 企业端在谈候选的范围档（当前岗位 / 全部岗位）*/
  企业在谈范围: 在谈范围档;
  /** 叮嘱表：键=单/候选编号，值=按时间排的叮嘱与代理回执 */
  叮嘱表: Record<string, { 编号: number; 我: string; 回执: string; 写于阶段: 阶段 }[]>;
  归档列表: 归档条[];
  /** 被终止的候选落这里（镜像求职端 归档列表）*/
  企业归档列表: 企业归档条[];
}

export type MatchCase动作 =
  | { 型: '设在谈看什么'; 档: 看什么档 }
  | { 型: '设在谈范围'; 档: 在谈范围档 }
  | { 型: '企业设在谈看什么'; 档: 看什么档 }
  | { 型: '企业设在谈范围'; 档: 在谈范围档 }
  | { 型: '接受方案'; 编号: string }
  | { 型: '退出谈判'; 编号: string }
  | { 型: '确认意向'; 编号: string }
  | { 型: '候选接受方案'; 编号: string }
  | { 型: '候选终止'; 编号: string }
  | { 型: '候选确认意向'; 编号: string }
  | { 型: '加叮嘱'; 归属: string; 文本: string; 序号: number; 写于阶段: 阶段 };

export type MatchCase归约 = (旧: 状态, 动作: MatchCase动作) => 状态;

export const 归约MatchCase: MatchCase归约 = (旧, 动作) => {
  switch (动作.型) {
    case '设在谈看什么':
      return { ...旧, 在谈看什么: 动作.档 };
    case '设在谈范围':
      return { ...旧, 在谈范围: 动作.档 };
    case '企业设在谈看什么':
      return { ...旧, 企业在谈看什么: 动作.档 };
    case '企业设在谈范围':
      return { ...旧, 企业在谈范围: 动作.档 };

    // 接受协调方案 → 该单推进到「意向确认」，不再需要你
    case '接受方案': {
      const 该单 = 旧.在谈列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '接受' },
        // 分歧数据留档：详情页回看时还能展示当时的数字对比
        决策快照: 该单?.分歧 ? { ...旧.决策快照, [动作.编号]: 该单.分歧 } : 旧.决策快照,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                需要你: true,
                下一步: '条件已放宽并回报对方，等双方确认意向',
                辅助文案: '确认后转真人沟通',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 退出 → 从在谈列表移除，同时落一条到归档列表（归档页要能看到它）
    case '退出谈判': {
      const 该单 = 旧.在谈列表.find((条) => 条.编号 === 动作.编号);
      const 新归档: 归档条[] = 该单
        ? [
            {
              编号: 该单.编号,
              公司: 该单.公司,
              公司首字: 该单.公司首字,
              职位: 该单.职位,
              止步阶段: 该单.阶段,
              结果: '我方退出',
              // 分歧只有「我方 / 差值 / 对方」三项，卡点项名要从下一步文案里抠
              原因: 该单.分歧
                ? `双方在「${/卡在(.{1,6}?)[，,]/.exec(该单.下一步)?.[1] ?? '关键条件'}」上${该单.分歧.差值}，你选择退出。`
                : '你在本轮选择退出这一单。',
              时间: '刚刚',
            },
            ...旧.归档列表,
          ]
        : 旧.归档列表;
      return {
        ...旧,
        决策: { ...旧.决策, [动作.编号]: '退出' },
        在谈列表: 旧.在谈列表.filter((条) => 条.编号 !== 动作.编号),
        归档列表: 新归档,
      };
    }

    // 确认意向 → 转真人沟通，卡片不再等你
    case '确认意向':
      return {
        ...旧,
        在谈列表: 旧.在谈列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                下一步: '已确认意向，可进入真人沟通',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    // 接受代理方案 → 该候选推进到「意向确认」（等对方点头）
    case '候选接受方案': {
      const 该候选 = 旧.企业候选列表.find((条) => 条.编号 === 动作.编号);
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '接受' },
        候选决策快照: 该候选?.分歧
          ? { ...旧.候选决策快照, [动作.编号]: 该候选.分歧 }
          : 旧.候选决策快照,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                阶段: '意向确认',
                // 镜像求职端语义：接受方案后进入意向确认，先等你（企业）正式确认，
                // 所以卡片保持置顶；「候选确认意向」时才置 false
                需要你: true,
                下一步: '条件已一致，等你确认意向',
                辅助文案: '确认后等候选人点头，双方齐了进入真人沟通',
                分歧: null,
              }
            : 条
        ),
      };
    }

    // 终止 → 从在谈候选里移除，同时落一条到企业归档列表（企业归档屏要能看到他）。
    // 只 filter 不落表的旧写法等于永久删除：这一单的阶段、卡在哪一条、往来记录
    // 全部失去入口，而屏上还写着「已归档」。镜像求职端的「退出谈判」补上归档这一半
    case '候选终止': {
      const 该候选 = 旧.企业候选列表.find((条) => 条.编号 === 动作.编号);
      const 新归档: 企业归档条[] = 该候选
        ? [
            {
              编号: 该候选.编号,
              代号: 该候选.代号,
              头像字: 该候选.头像字,
              画像: 该候选.画像,
              岗位编号: 该候选.岗位编号,
              // 岗位可能已被删除/改名，查不到就退回岗位编号，归档卡不至于空一行
              职位:
                旧.岗位列表.find((岗) => 岗.编号 === 该候选.岗位编号)?.名称 ?? 该候选.岗位编号,
              止步阶段: 该候选.阶段,
              结果: '我方终止',
              // 分歧三项本身就说清了卡在哪：我方条件 / 对方条件 / 差值，不另写解释
              原因: 该候选.分歧
                ? `${该候选.分歧.我方}，${该候选.分歧.对方}，${该候选.分歧.差值}，你选择终止。`
                : '你在本轮选择终止这一单。',
              时间: '刚刚',
            },
            ...旧.企业归档列表,
          ]
        : 旧.企业归档列表;
      return {
        ...旧,
        候选决策: { ...旧.候选决策, [动作.编号]: '终止' },
        企业候选列表: 旧.企业候选列表.filter((条) => 条.编号 !== 动作.编号),
        企业归档列表: 新归档,
      };
    }

    // 双方意向确认 → 进入真人沟通，卡片不再等你。
    // 候选人真名与画像在 S1 原件递交时已写入初始 Mock，意向确认不再承担首次披露身份，
    // 这里只更新 S3 结果文案（产品契约 2026-08-25：S3 不再负责首次交换身份）。
    case '候选确认意向':
      return {
        ...旧,
        企业候选列表: 旧.企业候选列表.map((条) =>
          条.编号 === 动作.编号
            ? {
                ...条,
                需要你: false,
                下一步: '已确认意向，可进入真人沟通',
                辅助文案: '去消息页私聊',
              }
            : 条
        ),
      };

    // 叮嘱即时生效：写下自己的话，代理紧跟一条执行回执（原型按内容给定式回执）
    case '加叮嘱': {
      const 内容 = 动作.文本.trim();
      if (内容 === '') return 旧;
      const 回执 = 内容.includes('？') || 内容.includes('?')
        ? '收到，我这就去问对方代理，有结果第一时间回你。'
        : '收到，我按你的口径回复对方，谈拢就推进到下一阶段。';
      const 旧条 = 旧.叮嘱表[动作.归属] ?? [];
      return {
        ...旧,
        叮嘱表: {
          ...旧.叮嘱表,
          // 写于阶段 与内容一起冻结：之后阶段推进，这条话仍留在它当时所在的那一段里
          [动作.归属]: [...旧条, { 编号: 动作.序号, 我: 内容, 回执, 写于阶段: 动作.写于阶段 }],
        },
      };
    }

    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};