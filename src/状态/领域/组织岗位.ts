// 组织与岗位域 reducer：公司资料、招聘方身份资料、岗位本地状态。
// 从根 归约 按业务 owner 拆出，case body 逐字搬移。发布岗位 与 切当前岗位 跨越多个域，
// 保留在根 reducer，不进入本域动作。对根 状态 只使用 type-only import。

import type { 在招岗位, 公司自述覆盖 } from '../../数据/类型';
import type { 页面岗位快照 } from '../../数据/招聘数据源类型';
import type { 状态 } from '../应用状态';

export interface 组织岗位状态 {
  岗位列表: 在招岗位[];
  当前岗位编号: string;
  公司自述: 公司自述覆盖 | null;
  企业认证: { 姓名: string; 公司: string; 职务?: string };
  招聘头像: string | null;
  公司LOGO: string | null;
}

export type 组织岗位动作 =
  | { 型: '更新岗位'; 岗: 在招岗位 }
  | { 型: '停止招聘'; 编号: string }
  | { 型: '重开岗位'; 编号: string }
  | { 型: '删除岗位'; 编号: string }
  | { 型: '水合后端岗位'; 快照: 页面岗位快照 }
  | { 型: '存公司自述'; 值: 公司自述覆盖 }
  | { 型: '存企业认证'; 姓名: string; 公司: string; 职务?: string }
  | { 型: '存招聘头像'; 图: string | null }
  | { 型: '存公司LOGO'; 图: string | null };

export type 组织岗位归约 = (旧: 状态, 动作: 组织岗位动作) => 状态;

/** 当前岗位若已被归档/删除，改指向第一个在招岗；一个都没有就保持原值（列表页会显示空态）*/
export function 选新当前岗(列表: 在招岗位[], 当前: string): string {
  if (列表.some((岗) => 岗.编号 === 当前 && 岗.状态 === '在招')) return 当前;
  return 列表.find((岗) => 岗.状态 === '在招')?.编号 ?? 当前;
}

export const 归约组织岗位: 组织岗位归约 = (旧, 动作) => {
  switch (动作.型) {
    case '更新岗位':
      return {
        ...旧,
        岗位列表: 旧.岗位列表.map((岗) => (岗.编号 === 动作.岗.编号 ? 动作.岗 : 岗)),
      };
    case '停止招聘': {
      const 新列表 = 旧.岗位列表.map((岗) =>
        岗.编号 === 动作.编号 ? { ...岗, 状态: '已归档' as const } : 岗
      );
      return { ...旧, 岗位列表: 新列表, 当前岗位编号: 选新当前岗(新列表, 旧.当前岗位编号) };
    }
    case '重开岗位': {
      const 新列表 = 旧.岗位列表.map((岗) =>
        岗.编号 === 动作.编号 ? { ...岗, 状态: '在招' as const } : 岗
      );
      return { ...旧, 岗位列表: 新列表, 当前岗位编号: 动作.编号 };
    }
    case '删除岗位': {
      const 该岗 = 旧.岗位列表.find((岗) => 岗.编号 === 动作.编号);
      if (!该岗) return 旧;
      if (旧.企业候选列表.some((候) => 候.岗位编号 === 动作.编号)) return 旧;
      const 新列表 = 旧.岗位列表.filter((岗) => 岗.编号 !== 动作.编号);
      return { ...旧, 岗位列表: 新列表, 当前岗位编号: 选新当前岗(新列表, 旧.当前岗位编号) };
    }
    case '水合后端岗位': {
      const 新列表 = 动作.快照.列表;
      return { ...旧, 岗位列表: 新列表, 当前岗位编号: 选新当前岗(新列表, 旧.当前岗位编号) };
    }
    case '存公司自述':
      return { ...旧, 公司自述: 动作.值 };
    case '存企业认证': {
      const 值 = { 姓名: 动作.姓名, 公司: 动作.公司, 职务: 动作.职务 ?? 旧.企业认证.职务 };
      return { ...旧, 企业认证: 值 };
    }
    case '存招聘头像':
      return { ...旧, 招聘头像: 动作.图 };
    case '存公司LOGO':
      return { ...旧, 公司LOGO: 动作.图 };
    default: {
      const 不可能: never = 动作;
      return 不可能;
    }
  }
};