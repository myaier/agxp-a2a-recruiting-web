// Provider 的浏览器存储副作用。
// 快照如何验证/命名归数据层，这里只把 React 状态与当前账号仓同步。

import { useEffect, useMemo, type Dispatch } from 'react';
import type { 后端环境 } from '../配置/运行配置';
import {
  账号存储键,
  写资料缓存,
  读资料缓存,
  资料缓存键,
  type 资料缓存快照,
  type 资料缓存范围,
} from '../数据/资料缓存';
import { 安全取存储, 演示范围, 空账号资料, type 简历快照 } from './初始状态';
import type { 动作, 状态 } from './应用状态';

interface 资料持久化参数 {
  状态: 状态;
  派发: Dispatch<动作>;
  是后端: boolean;
  环境: 后端环境;
  当前主体标识: string | null;
}

export function use资料持久化({ 状态, 派发, 是后端, 环境, 当前主体标识 }: 资料持久化参数): void {
  const 本地存储 = 安全取存储('local');
  const 会话存储 = 安全取存储('session');
  const Mock范围 = useMemo(() => 演示范围(环境), [环境]);
  const Mock简历键 = 账号存储键('简历v3', Mock范围);
  const Mock筛选键 = 账号存储键('求职筛选v2', Mock范围);

  // 简历/引导只在 Mock 持久化；Backend 已接域只认服务端权威。
  useEffect(() => {
    if (是后端) return;
    const 快照: 简历快照 = {
      经历: 状态.简历经历,
      教育: 状态.简历教育,
      技能: 状态.简历技能,
      证书: 状态.简历证书,
      基本信息: 状态.基本信息,
      文件名: 状态.简历文件名,
      个人优势: 状态.个人优势,
      作品集链接: 状态.简历作品集链接,
      联系方式: 状态.联系方式,
    };
    try {
      本地存储?.setItem(Mock简历键, JSON.stringify(快照));
    } catch {
      // 隐私模式或空间不足时只保留内存状态。
    }
  }, [
    是后端,
    状态.简历经历,
    状态.简历教育,
    状态.简历技能,
    状态.简历证书,
    状态.基本信息,
    状态.简历文件名,
    状态.个人优势,
    状态.简历作品集链接,
    状态.联系方式,
    Mock简历键,
    本地存储,
  ]);

  useEffect(() => {
    if (是后端) return;
    try {
      if (状态.引导预填) 本地存储?.setItem(Mock筛选键, JSON.stringify(状态.引导预填));
      else 本地存储?.removeItem(Mock筛选键);
    } catch {
      // 同上。
    }
  }, [是后端, 状态.引导预填, Mock筛选键, 本地存储]);

  // 账号切换的中间 render 不得把 A 的状态写到 B 的键下。
  useEffect(() => {
    if (!是后端) return;
    if (!当前主体标识) {
      派发({ 型: '清账号资料' });
      return;
    }
    const 范围: 资料缓存范围 = { 模式: 'backend', 环境, 账号: 当前主体标识 };
    const 快照 = { ...空账号资料, ...读资料缓存(会话存储, 范围) };
    派发({ 型: '水合账号资料', 范围键: 资料缓存键(范围), 快照 });
  }, [是后端, 环境, 当前主体标识, 会话存储, 派发]);

  useEffect(() => {
    const 范围: 资料缓存范围 | null = 是后端
      ? (当前主体标识 ? { 模式: 'backend', 环境, 账号: 当前主体标识 } : null)
      : Mock范围;
    if (!范围 || 状态.资料缓存范围键 !== 资料缓存键(范围)) return;
    const 快照: 资料缓存快照 = {
      公司自述: 状态.公司自述,
      企业认证: 状态.企业认证,
      招聘头像: 状态.招聘头像,
      公司LOGO: 状态.公司LOGO,
      求职头像: 状态.求职头像,
      飞书已接入: 状态.飞书已接入,
      企业飞书已接入: 状态.企业飞书已接入,
    };
    写资料缓存(是后端 ? 会话存储 : 本地存储, 范围, 快照);
  }, [
    是后端,
    环境,
    当前主体标识,
    会话存储,
    本地存储,
    Mock范围,
    状态.资料缓存范围键,
    状态.公司自述,
    状态.企业认证,
    状态.招聘头像,
    状态.公司LOGO,
    状态.求职头像,
    状态.飞书已接入,
    状态.企业飞书已接入,
  ]);
}
