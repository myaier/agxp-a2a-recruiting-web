function 推荐列表初始(): 推荐候选[] {
  const 池 = [...推荐列表种子];
  for (const 岗 of 在招岗位列表) {
    if (岗.状态 !== '在招') continue;
    const 已有 = 池.filter((人) => 人.岗位编号 === 岗.编号).length;
    for (let 序 = 0; 序 < Math.max(0, 2 - 已有); 序++) {
      const 模 = 起步推荐模板[序 % 起步推荐模板.length];
      池.push({ ...模, 编号: `${模.编号}@${岗.编号}`, 岗位编号: 岗.编号 });
    }
  }
  return 池;
}

function 播种未读表(消息表: 消息条目[]): Record<string, number> {
  const 表: Record<string, number> = {};
  for (const 条 of 消息表) {
    if (条.未读数 !== undefined && 条.未读数 > 0) 表[条.编号] = 条.未读数;
    else if (条.红点) 表[条.编号] = 0;
  }
  return 表;
}

