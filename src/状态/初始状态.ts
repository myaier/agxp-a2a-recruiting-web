function 读简历缓存(存储: 资料缓存存储 | null, 存储键: string): 简历快照 | null {
  if (!存储) return null;
  try {
    const 原文 = 存储.getItem(存储键);
    if (!原文) return null;
    const 值 = JSON.parse(原文);
    if (!Array.isArray(值?.经历) || !Array.isArray(值?.教育)) return null;
    const 加厚文本: Record<string, string> = {
      e1: '主导交易网关重建：单元化部署 + 多活容灾，发布事故率降 82%\n大促峰值 32 万 QPS 全链路治理，全年可用性 99.99%\n带 8 人小组，建立值班、容量规划与故障演练体系',
      e2: '交易履约链路开发，负责订单状态机与超时补偿模块\n参与订单中心从单体到微服务拆分，发布周期从双周缩短到每日\n搭建链路压测平台，支撑三次大促容量评估',
    };
    for (const 段 of 值.经历) {
      if (!加厚文本[段.编号]) continue;
      if (段.内容 === '主导交易网关重建与峰值稳定性治理，大促峰值 32 万 QPS。' || 段.内容 === '')
        段.内容 = 加厚文本[段.编号];
    }
    return 值;
  } catch {
    return null;
  }
}

function 读旧作品集链接(存储: 资料缓存存储 | null, 存储键: string): string {
  if (!存储) return '';
  try {
    const 原文 = 存储.getItem(存储键);
    if (!原文) return '';
    const 值 = JSON.parse(原文);
    return typeof 值?.筛选偏好?.作品集链接 === 'string' ? 值.筛选偏好.作品集链接 : '';
  } catch {
    return '';
  }
}

function 读求职筛选缓存(存储: 资料缓存存储 | null, 存储键: string): 状态['引导预填'] {
  if (!存储) return null;
  try {
    const 原文 = 存储.getItem(存储键);
    if (!原文) return null;
    const 值 = JSON.parse(原文);
    if (!Array.isArray(值?.城市们) || !Array.isArray(值?.职位)) return null;
    if (值.筛选偏好) delete 值.筛选偏好.作品集链接;
    if (值.筛选偏好 && Array.isArray(值.筛选偏好.求职类型)) {
      值.筛选偏好 = 迁移主要求职类型(值.筛选偏好, 值.薪资?.单位);
      const 应使用日薪 = 值.筛选偏好.求职类型[0] === '实习生';
      if (值.薪资?.单位 && (应使用日薪 ? 值.薪资.单位 !== '元/天' : 值.薪资.单位 !== '月薪K')) delete 值.薪资;
    }
    return 值;
  } catch {
    return null;
  }
}

